import numpy as np

# Test 1: Hull's Textbook Example (Chapter 19)
# S=42, K=40, r=0.10, sigma=0.20, T=0.5, q=0
# Expected call = 4.76
def test_hull_example():
    res = bs_call(S=42, K=40, T=0.5, r=0.10, sigma=0.20)
    print(f"Hull example: C = {res.price:.4f} (expected: 4.7594)")
    assert abs(res.price - 4.7594) < 1e-4, f"Hull check failed: {res.price}"
    print("PASS")

# Test 2: Put-Call Parity (1000 random tests)
def test_put_call_parity(n=1000):
    rng = np.random.default_rng(42)
    S = rng.uniform(50, 200, n)
    K = rng.uniform(50, 200, n)
    T = rng.uniform(0.01, 3.0, n)
    r = rng.uniform(0.0, 0.1, n)
    sigma = rng.uniform(0.05, 0.8, n)
    q = rng.uniform(0.0, 0.05, n)

    C = bs_price(S, K, T, r, sigma, q, 'c')
    P = bs_price(S, K, T, r, sigma, q, 'p')
    lhs = C - P
    rhs = S * np.exp(-q * T) - K * np.exp(-r * T)
    err = np.max(np.abs(lhs - rhs))
    print(f"Put-call parity max error (n={n}): {err:.2e} (expected < 1e-10)")
    assert err < 1e-10, f"Parity check failed: max_err = {err:.2e}"
    print("PASS")

# Test 3: Homogeneity (price scales linearly with S, K)
def test_homogeneity(a=2.0):
    base = bs_price(100, 100, 1.0, 0.05, 0.20, 0.0, 'c')
    scaled = bs_price(100*a, 100*a, 1.0, 0.05, 0.20, 0.0, 'c')
    ratio = scaled / base
    print(f"Homogeneity ratio (should be {a}): {ratio:.8f}")
    assert abs(ratio - a) < 1e-10
    print("PASS")

# Test 4: Finite Difference Greeks vs Analytic
def test_greeks_fd(eps_fd=1e-5):
    S, K, T, r, sigma, q = 100, 100, 1.0, 0.05, 0.20, 0.02
    res = bs_call(S, K, T, r, sigma, q, compute_greeks=True)

    # Analytic Greeks
    delta_a = res.delta
    gamma_a = res.gamma
    vega_a = res.vega
    theta_a = res.theta * 365.0  # back to per-year for comparison

    # Finite difference Greeks
    p_up = bs_price(S*(1+eps_fd), K, T, r, sigma, q, 'c')
    p_dn = bs_price(S*(1-eps_fd), K, T, r, sigma, q, 'c')
    delta_fd = (p_up - p_dn) / (2 * S * eps_fd)
    gamma_fd = (p_up - 2*res.price + p_dn) / (S * eps_fd)**2

    v_up = bs_price(S, K, T, r, sigma + eps_fd, q, 'c')
    v_dn = bs_price(S, K, T, r, sigma - eps_fd, q, 'c')
    vega_fd = (v_up - v_dn) / (2 * eps_fd)

    t_dn = bs_price(S, K, T - eps_fd, r, sigma, q, 'c')
    theta_fd = (t_dn - res.price) / eps_fd  # dV/dT

    print("\nGreek Validation (Analytic vs Finite Difference):")
    print(f"{'Greek':<8} {'Analytic':>12} {'Finite Diff':>12} {'Diff':>12}")
    print("-" * 48)
    for name, a, fd in [
        ("Delta", delta_a, delta_fd),
        ("Gamma", gamma_a, gamma_fd),
        ("Vega", vega_a, vega_fd),
        ("Theta", theta_a, -theta_fd)
    ]:
        print(f"{name:<8} {a:12.6f} {fd:12.6f} {abs(a-fd):12.2e}")

# Test 5: Boundary conditions
def test_boundaries():
    # ATM call ~ S * N(d1) - K * N(d2) for r,q -> 0, T->inf
    # Deep ITM call -> S - K*e^{-rT}
    deep_itm = bs_price(200, 100, 1.0, 0.05, 0.20, 0.0, 'c')
    intrinsic = 200 - 100 * np.exp(-0.05)
    print(f"\nDeep ITM call: {deep_itm:.4f} intrinsic: {intrinsic:.4f}")

    # Deep OTM call -> 0
    deep_otm = bs_price(50, 200, 1.0, 0.05, 0.20, 0.0, 'c')
    print(f"Deep OTM call: {deep_otm:.6f} (should be ~0)")

    # Zero expiry -> intrinsic
    atm_expired = bs_price(100, 95, 0.0, 0.05, 0.20, 0.0, 'c')
    print(f"At expiry ATM call: {atm_expired:.4f} (should be 5.0)")
    assert abs(atm_expired - 5.0) < 1e-10
    print("PASS")


    atm_vols = [0.18, 0.19, 0.20, 0.205, 0.21, 0.215, 0.22]
    skews = [-0.08, -0.07, -0.065, -0.06, -0.055, -0.05, -0.045]

    for T, atm, skew_param in zip(tenors, atm_vols, skews):
        F = surf.forward(T)
        x_pts = np.linspace(-0.30, 0.15, 20)
        K_pts = F * np.exp(x_pts)
        a_param = atm ** 2 * T * 0.5
        b_param = 0.08
        rho_p = skew_param
        m_p = -0.03
        v_p = 0.12
        svi_tmp = SVIParams(a=a_param, b=b_param, rho=rho_p, m=m_p, varsigma=v_p)
        iv_pts = svi_tmp.implied_vol(x_pts, T)
        rng = np.random.default_rng(int(T * 1000))
        iv_pts = iv_pts + rng.normal(0, 0.001, len(iv_pts))
        surf.add_slice(T, K_pts, iv_pts)

    surf.build_surface_grid(K_range=(0.70, 1.30), n_K=80, n_T=50)
    return surf



# SVI Slice Model
@dataclass
class SVIParams:
    """SVI raw parameterization parameters for one expiry slice."""
    a: float          # variance level
    b: float          # slope
    rho: float        # skewness
    m: float          # moneyness center
    varsigma: float   # smoothness

    def __post_init__(self):
        self.validate()

    def validate(self):
        assert self.b > 0, "b must be positive"
        assert -1 < self.rho < 1, "rho must be in (-1, 1)"
        assert self.varsigma > 0, "varsigma must be positive"
        lb = -self.b * self.varsigma * np.sqrt(1 - self.rho ** 2)
        assert self.a > lb, f"a={self.a:.4f} must be > {lb:.4f}"

    def total_var(self, x: np.ndarray) -> np.ndarray:
        """Total variance w(x) = a + b*[rho*(x-m) + sqrt((x-m)^2 + varsigma^2)]"""
        z = x - self.m
        return self.a + self.b * (self.rho * z + np.sqrt(z ** 2 + self.varsigma ** 2))

    def implied_vol(self, x: np.ndarray, T: float) -> np.ndarray:
        """Convert total variance to implied vol."""
        w = np.maximum(self.total_var(x), 0.0)
        return np.sqrt(w / T)

    def is_butterfly_free(self, x_grid: Optional[np.ndarray] = None) -> bool:
        """Check g(x) >= 0 for Fukasawa's butterfly-free condition."""
        if x_grid is None:
            x_grid = np.linspace(-3, 3, 500)
        w = self.total_var(x_grid)
        dw = np.gradient(w, x_grid)
        d2w = np.gradient(dw, x_grid)
        # Fukasawa's g(x)
        g = (1.0 - x_grid * dw / (2 * w)) ** 2 \
            - (dw ** 2 / 4) * (1 / w + 0.25) \
            + d2w / 2
        return np.all(g >= -1e-8)

    def local_variance(self, x: np.ndarray, T: float) -> np.ndarray:
        """Dupire local variance from SVI (Eq. 7.15)."""
        eps = 1e-6
        w = self.total_var(x)
        dw = (self.total_var(x + eps) - self.total_var(x - eps)) / (2 * eps)
        d2w = (self.total_var(x + eps) - 2 * w + self.total_var(x - eps)) / eps ** 2
        # Dupire formula in (x, T) coordinates
        num = dw / T
        den = (1 - x * dw / (2 * w)) ** 2 \
              - dw ** 2 / 4 * (1 / w + 0.25) \
              + d2w / 2
        den = np.maximum(den, 1e-8)
        return num / den


def svi_fit_slice(
    x_mkt: np.ndarray,  # log-moneyness = log(K/F)
    iv_mkt: np.ndarray,   # market implied vols
    T: float,            # expiry
    weights: Optional[np.ndarray] = None,
    method: str = 'de'   # 'de'=differential evolution, 'ls'=least-sq
) -> SVIParams:
    """Fit SVI parameters to one expiry slice."""
    w_mkt = iv_mkt ** 2 * T  # market total variance
    if weights is None:
        weights = np.ones(len(x_mkt))
    weights /= weights.sum()

    def objective(params):
        a, b, rho, m, varsigma = params
        if b <= 0 or varsigma <= 0 or not (-1 < rho < 1):
            return 1e10
        lb = -b * varsigma * np.sqrt(1 - rho ** 2)
        if a <= lb:
            return 1e10
        p = SVIParams(a, b, rho, m, varsigma)
        w_fit = p.total_var(x_mkt)
        if np.any(w_fit < 0):
            return 1e10
        residuals = weights * (np.sqrt(np.maximum(w_fit / T, 0)) - iv_mkt) ** 2
        return np.sum(residuals)

    atm_var = np.interp(0.0, x_mkt, w_mkt)
    a_init = atm_var * 0.5
    bounds = [
        (1e-5, max(atm_var * 2, 0.5)),  # a
        (1e-3, 2.0),                    # b
        (-0.99, 0.99),                  # rho
        (-0.5, 0.5),                    # m
        (1e-3, 1.0),                    # varsigma
    ]

    if method == 'de':
        result = differential_evolution(
            objective, bounds, maxiter=1000, tol=1e-9,
            seed=42, popsize=20, mutation=(0.5, 1.5),
            recombination=0.7, workers=1
        )
        x0 = result.x
    else:
        x0 = [a_init, 0.1, -0.3, 0.0, 0.1]

    result2 = minimize(
        objective, x0, method='L-BFGS-B', bounds=bounds,
        options={'ftol': 1e-12, 'gtol': 1e-10, 'maxiter': 5000}
    )

    a, b, rho, m, varsigma = result2.x
    return SVIParams(a=a, b=b, rho=rho, m=m, varsigma=varsigma)


class VolSurface:
    """Full implied volatility surface from market data."""
    def __init__(self, S: float, r: float, q: float = 0.0):
        self.S = S
        self.r = r
        self.q = q
        self.svi_slices: dict[float, SVIParams] = {}
        self.T_grid: np.ndarray = None
        self.K_grid: np.ndarray = None
        self.iv_grid: np.ndarray = None
        self. _spline: RectBivariateSpline = None

    def forward(self, T: float) -> float:
        """Compute forward price for expiry T."""
        return self.S * np.exp((self.r - self.q) * T)

    def add_slice(
        self,
        T: float,
        strikes: np.ndarray,
        iv_market: np.ndarray,
        weights: Optional[np.ndarray] = None,
    ):
        """Add and fit one expiry slice to the surface."""
        F = self.forward(T)
        x = np.log(strikes / F)
        svi = svi_fit_slice(x, iv_market, T, weights)
        self.svi_slices[T] = svi
        bf = svi.is_butterfly_free()
        if not bf:
            warnings.warn(f"Slice T={T:.4f} has butterfly arbitrage!")

    def build_surface_grid(
        self,
        K_range: tuple = (0.7, 1.3),
        n_K: int = 100,
        n_T: int = 50,
    ):
        """Construct the IV grid over (K, T) for visualization/interpolation."""
        if not self.svi_slices:
            raise ValueError("No slices added. Call add_slice first.")
        T_arr = np.array(sorted(self.svi_slices.keys()))
        K_arr = np.linspace(K_range[0] * self.S, K_range[1] * self.S, n_K)

        iv_matrix = np.zeros((len(T_arr), n_K))
        for i, T in enumerate(T_arr):
            F = self.forward(T)
            x = np.log(K_arr / F)
            svi = self.svi_slices[T]
            iv_matrix[i, :] = svi.implied_vol(x, T)

        self.T_grid = T_arr
        self.K_grid = K_arr
        self.iv_grid = iv_matrix

        if len(T_arr) >= 3 and n_K >= 4:
            try:
                self._spline = RectBivariateSpline(
                    T_arr, K_arr, iv_matrix, kx=3, ky=3
                )
            except Exception as e:
                warnings.warn(f"Spline fitting failed: {e}")

    def get_iv(self, K: float, T: float) -> float:
        """Query IV at arbitrary (K, T) via spline interpolation."""
        if self._spline is not None:
            T_clamp = np.clip(T, self.T_grid.min(), self.T_grid.max())
            K_clamp = np.clip(K, self.K_grid.min(), self.K_grid.max())
            return float(self._spline(T_clamp, K_clamp).item())

        # Fallback
        T_near = min(self.svi_slices.keys(), key=lambda t: abs(t - T))
        F = self.forward(T_near)
        x = np.log(K / F)
        return float(self.svi_slices[T_near].implied_vol(x, T_near))

    def check_calendar_arbitrage(self) -> dict:
        """Check calendar spread arbitrage."""
        results = {}
        T_list = sorted(self.svi_slices.keys())
        for K in np.linspace(0.8 * self.S, 1.2 * self.S, 50):
            tvars = []
            for T in T_list:
                F = self.forward(T)
                x = np.log(K / F)
                iv = self.svi_slices[T].implied_vol(x, T)
                tvars.append(iv ** 2 * T)
            diff = np.diff(tvars)
            ok = np.all(diff >= -1e-6)
            results[K] = ok
        n_viol = sum(not v for v in results.values())
        return {'n_violations': n_viol, 'max_violations': n_viol, 'per_strike': results}

    def surface_summary(self) -> pd.DataFrame:
        """Summarize the surface: ATM vol, skew, and curvature."""
        rows = []
        for T in sorted(self.svi_slices.keys()):
            F = self.forward(T)
            svi = self.svi_slices[T]
            atm = svi.implied_vol(np.array([0.0]), T)[0]
            x25c = 0.25 * svi.varsigma
            x25p = -0.25 * svi.varsigma
            iv25c = svi.implied_vol(np.array([x25c]), T)[0]
            iv25p = svi.implied_vol(np.array([x25p]), T)[0]
            skew = iv25p - iv25c
            smile = (iv25c + iv25p) / 2 - atm
            rows.append({
                'T': T, 'ATM_vol': atm,
                '25d_risk_reversal': skew,
                '25d_butterfly': smile,
                'rho': svi.rho, 'b': svi.b,
            })
        return pd.DataFrame(rows)


def build_demo_surface(S=4500, r=0.05, q=0.015) -> VolSurface:
    """Construct a realistic SPX-like vol surface."""
    surf = VolSurface(S, r, q)

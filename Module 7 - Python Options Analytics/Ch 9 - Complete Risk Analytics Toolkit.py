# greeks_engine and FullGreeks are already globally defined.
# SVIParams and VolSurface are also in scope.

def bs_price(S: float, K: float, T: float, r: float, sigma: float, q: float, flag: str) -> float:
    """Local helper to get the Black-Scholes price from our analytical greeks engine."""
    g = greeks_engine(S, K, T, r, sigma, q, flag)
    return float(g.price.item() if isinstance(g.price, np.ndarray) else g.price)

@dataclass
class OptionPosition:
    """ Represents one option position in a book. """
    name: str
    S: float            # Current spot
    K: float            # Strike
    T: float            # Time to expiry (years)
    r: float            # Risk-free rate
    sigma_mkt: float    # Market IV for this option
    q: float            # Dividend yield
    flag: str           # 'c' or 'p'
    quantity: float     # Number of contracts (negative = short)
    multiplier: float = 100.0  # Contract multiplier (e.g., SPX = 100)
    label: str = ""

    @property
    def notional(self) -> float:
        return abs(self.quantity) * self.multiplier

    @property
    def signed_multiplier(self) -> float:
        return self.quantity * self.multiplier


class OptionsBook:
    """
    Container and analytics engine for an options book.
    """
    def __init__(self, name: str = "Options Book"):
        self.name = name
        self.positions: list[OptionPosition] = []

    def add_position(self, pos: OptionPosition):
        self.positions.append(pos)

    def add_positions(self, positions: list[OptionPosition]):
        self.positions.extend(positions)

    def compute_greeks(self) -> pd.DataFrame:
        """
        Compute Greeks for all positions and aggregate.
        Returns position-level and book-level Greeks.
        """
        rows = []
        for pos in self.positions:
            g = greeks_engine(pos.S, pos.K, pos.T, pos.r, pos.sigma_mkt, pos.q, pos.flag)
            fm = pos.signed_multiplier
            rows.append({
                'name': pos.name,
                'flag': pos.flag,
                'K': pos.K,
                'T': f"{pos.T:.3f}Y",
                'sigma': pos.sigma_mkt,
                'qty': pos.quantity,
                'price': float(g.price.item() if isinstance(g.price, np.ndarray) else g.price) * abs(pos.quantity),
                'MV': float(g.price.item() if isinstance(g.price, np.ndarray) else g.price) * fm,
                'delta': float(g.delta.item() if isinstance(g.delta, np.ndarray) else g.delta) * fm,
                'gamma': float(g.gamma.item() if isinstance(g.gamma, np.ndarray) else g.gamma) * fm,
                'vega_1pct': float(g.vega_1pct.item() if isinstance(g.vega_1pct, np.ndarray) else g.vega_1pct) * fm,
                'theta': float(g.theta.item() if isinstance(g.theta, np.ndarray) else g.theta) * fm,
                'vanna': float(g.vanna.item() if isinstance(g.vanna, np.ndarray) else g.vanna) * fm,
                'volga': float(g.volga.item() if isinstance(g.volga, np.ndarray) else g.volga) * fm,
                'dollar_delta': float(g.dollar_delta.item() if isinstance(g.dollar_delta, np.ndarray) else g.dollar_delta) * fm,
                'dollar_gamma': float(g.dollar_gamma.item() if isinstance(g.dollar_gamma, np.ndarray) else g.dollar_gamma) * fm,
            })

        df = pd.DataFrame(rows)
        num_cols = ['MV', 'delta', 'gamma', 'vega_1pct', 'theta', 'vanna', 'volga', 'dollar_delta', 'dollar_gamma']
        totals = pd.Series(df[num_cols].sum(), name='BOOK TOTAL')
        totals['name'] = 'BOOK TOTAL'
        totals['flag'] = ''
        totals['K'] = ''
        totals['T'] = ''
        totals['sigma'] = np.nan
        totals['qty'] = ''
        totals['price'] = np.nan
        df = pd.concat([df, pd.DataFrame([totals])], ignore_index=True)
        return df

    def pnl_attribution(self, dS: float, d_sigma: float, dt_days: float = 1.0) -> pd.DataFrame:
        """
        Taylor-expand P&L into Greek contributions:
        dV ~ Delta * dS + 0.5 * Gamma * dS^2 + Theta * dt + Vega * d_sigma + Vanna * dS * d_sigma + 0.5 * Volga * d_sigma^2
        """
        rows = []
        for pos in self.positions:
            g = greeks_engine(pos.S, pos.K, pos.T, pos.r, pos.sigma_mkt, pos.q, pos.flag)
            fm = pos.signed_multiplier
            delta_pnl = float(g.delta.item() if isinstance(g.delta, np.ndarray) else g.delta) * fm * dS
            gamma_pnl = float(g.gamma.item() if isinstance(g.gamma, np.ndarray) else g.gamma) * fm * 0.5 * (dS ** 2)
            theta_pnl = float(g.theta.item() if isinstance(g.theta, np.ndarray) else g.theta) * fm * dt_days
            vega_pnl = float(g.vega.item() if isinstance(g.vega, np.ndarray) else g.vega) * fm * d_sigma
            vanna_pnl = float(g.vanna.item() if isinstance(g.vanna, np.ndarray) else g.vanna) * fm * dS * d_sigma
            volga_pnl = float(g.volga.item() if isinstance(g.volga, np.ndarray) else g.volga) * fm * 0.5 * (d_sigma ** 2)

            total_taylor = delta_pnl + gamma_pnl + theta_pnl + vega_pnl + vanna_pnl + volga_pnl

            # Full reprice
            new_S = pos.S + dS
            new_sigma = pos.sigma_mkt + d_sigma
            new_T = max(pos.T - dt_days / 252, 1e-5)
            p_old = float(g.price.item() if isinstance(g.price, np.ndarray) else g.price)
            p_new = bs_price(new_S, pos.K, new_T, pos.r, new_sigma, pos.q, pos.flag)
            full_pnl = (p_new - p_old) * fm

            rows.append({
                'name': pos.name,
                'delta_pnl': delta_pnl,
                'gamma_pnl': gamma_pnl,
                'theta_pnl': theta_pnl,
                'vega_pnl': vega_pnl,
                'vanna_pnl': vanna_pnl,
                'volga_pnl': volga_pnl,
                'taylor_pnl': total_taylor,
                'full_pnl': full_pnl,
                'residual': full_pnl - total_taylor,
            })
        df = pd.DataFrame(rows)
        totals = df.sum(numeric_only=True)
        totals.name = 'TOTAL'
        totals['name'] = 'TOTAL'
        df = pd.concat([df, pd.DataFrame([totals])], ignore_index=True)
        return df

    def scenario_analysis(self, S_shocks: np.ndarray = None, vol_shocks: np.ndarray = None) -> tuple:
        """
        Grid scenario analysis: P&L for all (dS, d_sigma) combinations.
        Returns matrix, S_shocks, and vol_shocks.
        """
        if S_shocks is None:
            S_shocks = np.linspace(-0.15, 0.15, 13) * self.positions[0].S
        if vol_shocks is None:
            vol_shocks = np.linspace(-0.10, 0.10, 11)

        pnl_matrix = np.zeros((len(S_shocks), len(vol_shocks)))

        for i, ds in enumerate(S_shocks):
            for j, dv in enumerate(vol_shocks):
                total_pnl = 0.0
                for pos in self.positions:
                    new_S = pos.S + ds
                    new_sigma = max(pos.sigma_mkt + dv, 0.001)
                    p_old = bs_price(pos.S, pos.K, pos.T, pos.r, pos.sigma_mkt, pos.q, pos.flag)
                    p_new = bs_price(new_S, pos.K, pos.T, pos.r, new_sigma, pos.q, pos.flag)
                    total_pnl += (p_new - p_old) * pos.signed_multiplier
                pnl_matrix[i, j] = total_pnl
        return pnl_matrix, S_shocks, vol_shocks

    def var_simulation(self, n_days: int = 1000, horizon: int = 1, confidence: float = 0.99, annual_vol: float = 0.20, vol_of_vol: float = 1.0) -> dict:
        """
        Historical-style VaR via Monte Carlo return simulation.
        """
        S = self.positions[0].S if self.positions else 100
        dt = horizon / 252.0
        rng = np.random.default_rng(42)
        rho_sv = -0.70
        cov_mat = annual_vol ** 2 * dt * np.array([
            [1.0, rho_sv],
            [rho_sv, (vol_of_vol / annual_vol) ** 2]
        ])
        shocks = rng.multivariate_normal([0, 0], cov_mat, size=n_days)
        dS_sim = shocks[:, 0] * S
        dv_sim = shocks[:, 1] * annual_vol

        pnl_sim = np.zeros(n_days)
        for pos in self.positions:
            p_old = bs_price(pos.S, pos.K, pos.T, pos.r, pos.sigma_mkt, pos.q, pos.flag)
            for k in range(n_days):
                new_S = max(pos.S + dS_sim[k], 1.0)
                new_v = max(pos.sigma_mkt + dv_sim[k], 0.001)
                p_new = bs_price(new_S, pos.K, pos.T, pos.r, new_v, pos.q, pos.flag)
                pnl_sim[k] += (p_new - p_old) * pos.signed_multiplier

        var_dollar = -np.percentile(pnl_sim, (1 - confidence) * 100)
        cvar_dollar = -pnl_sim[pnl_sim <= -var_dollar].mean() if np.any(pnl_sim <= -var_dollar) else var_dollar

        return {
            'VaR': var_dollar,
            'CVaR': cvar_dollar,
            'confidence': confidence,
            'horizon': horizon,
            'n_sims': n_days,
            'pnl_sim': pnl_sim,
            'mean_pnl': pnl_sim.mean(),
            'std_pnl': pnl_sim.std(),
        }

    def stress_tests(self) -> pd.DataFrame:
        """
        Named stress scenarios.
        """
        scenarios = [
            ("Equity Crash", -0.15, 0.10),
            ("Vol Spike", -0.05, 0.15),
            ("Quiet Grind Up", +0.02, -0.03),
            ("Tail Crash", -0.25, 0.20),
            ("Rate Shock", -0.03, 0.02),
            ("Vol Collapse", +0.03, -0.08),
        ]
        rows = []
        for name, pct_S, d_vol in scenarios:
            total = 0.0
            for pos in self.positions:
                new_S = pos.S * (1 + pct_S)
                new_v = max(pos.sigma_mkt + d_vol, 0.001)
                p_old = bs_price(pos.S, pos.K, pos.T, pos.r, pos.sigma_mkt, pos.q, pos.flag)
                p_new = bs_price(new_S, pos.K, pos.T, pos.r, new_v, pos.q, pos.flag)
                total += (p_new - p_old) * pos.signed_multiplier
            rows.append({
                'Scenario': name,
                'dS': f"{pct_S*100:+.0f}%",
                'd_vol': f"{d_vol*100:+.0f} pp",
                'Total_PnL': total,
            })
        return pd.DataFrame(rows)

    def generate_risk_report(self, figsize=(16, 14)):
        """
        Full visual risk report dashboard.
        """
        fig = plt.figure(figsize=figsize)
        fig.suptitle(f'Risk Analytics Report - {self.name}', fontsize=15, fontweight='bold', y=0.98)
        gs = gridspec.GridSpec(3, 3, figure=fig, hspace=0.5, wspace=0.4)

        # Panel 1: Scenario Grid Heatmap
        pnl_mat, S_sh, vol_sh = self.scenario_analysis()
        ax1 = fig.add_subplot(gs[0, :2])
        im = ax1.imshow(pnl_mat, cmap='RdYlGn', aspect='auto', interpolation='bilinear')
        ax1.set_xticks(range(len(vol_sh)))
        ax1.set_xticklabels([f"{v*100:+.0f}pp" for v in vol_sh], fontsize=7, rotation=45)
        S_ref = self.positions[0].S if self.positions else 100
        ax1.set_yticks(range(len(S_sh)))
        ax1.set_yticklabels([f"{s/S_ref*100:+.0f}%" for s in S_sh], fontsize=7)
        ax1.set_xlabel('Vol Shock', fontsize=9)
        ax1.set_ylabel('Spot Shock', fontsize=9)
        ax1.set_title('P&L Scenario Grid (Spot vs Vol)', fontsize=10, fontweight='bold')
        fig.colorbar(im, ax=ax1, label='P&L ($)', shrink=0.8)

        # Panel 2: VaR Distribution
        var_res = self.var_simulation(n_days=5000)
        ax2 = fig.add_subplot(gs[0, 2])
        ax2.hist(var_res['pnl_sim'], bins=80, color='#2da8a8', alpha=0.7, edgecolor='white', lw=0.3)
        ax2.axvline(-var_res['VaR'], color='red', lw=2, label=f"99% VaR: ${var_res['VaR']:.0f}")
        ax2.axvline(-var_res['CVaR'], color='darkred', lw=2, ls='--', label=f"99% CVaR: ${var_res['CVaR']:.0f}")
        ax2.axvline(0, color='gray', lw=0.8)
        ax2.set_xlabel('1-Day P&L ($)', fontsize=9)
        ax2.set_title('P&L Distribution\n(VaR Simulation)', fontsize=10, fontweight='bold')
        ax2.legend(fontsize=7)
        ax2.grid(True, alpha=0.2)

        # Panel 3: Book-Level Greeks
        greeks_df = self.compute_greeks()
        book_row = greeks_df[greeks_df['name'] == 'BOOK TOTAL'].iloc[0]
        ax3 = fig.add_subplot(gs[1, 0])
        metrics = ['delta', 'gamma', 'vega_1pct', 'theta', 'vanna', 'volga']
        vals = [float(book_row[m]) for m in metrics]
        colors = ['#003566' if v >= 0 else '#ef476f' for v in vals]
        ax3.bar(metrics, vals, color=colors, alpha=0.85, edgecolor='white')
        ax3.axhline(0, color='black', lw=0.5)
        ax3.set_title('Book-Level Greeks', fontsize=10, fontweight='bold')
        ax3.set_ylabel('Greek ($)', fontsize=9)
        ax3.tick_params(axis='x', labelsize=8, rotation=30)
        ax3.grid(True, alpha=0.2, axis='y')

        # Panel 4: Stress Test Results
        stress = self.stress_tests()
        ax4 = fig.add_subplot(gs[1, 1:])
        colors_st = ['#ef476f' if v < 0 else '#2da8a8' for v in stress['Total_PnL']]
        bars = ax4.bar(range(len(stress)), stress['Total_PnL'], color=colors_st, alpha=0.85, edgecolor='white', lw=0.5)
        ax4.set_xticks(range(len(stress)))
        ax4.set_xticklabels(stress['Scenario'], rotation=25, ha='right', fontsize=8)
        ax4.axhline(0, color='black', lw=0.8)
        ax4.set_ylabel('Stress P&L ($)', fontsize=9)
        ax4.set_title('Stress Test Scenarios', fontsize=10, fontweight='bold')
        ax4.grid(True, alpha=0.2, axis='y')
        for bar, val in zip(bars, stress['Total_PnL']):
            ax4.text(bar.get_x() + bar.get_width() / 2, bar.get_height(), f'${val:,.0f}', ha='center', va='bottom' if val >= 0 else 'top', fontsize=7)

        # Panel 5: Position Greeks Table
        ax5 = fig.add_subplot(gs[2, :])
        ax5.axis('off')
        display_df = greeks_df[['name', 'flag', 'K', 'T', 'sigma', 'qty', 'MV', 'delta', 'gamma', 'vega_1pct', 'theta', 'vanna']].copy()
        display_df = display_df.dropna(subset=['MV'])
        table = ax5.table(
            cellText=display_df.round(4).values,
            colLabels=display_df.columns.tolist(),
            loc='center', cellLoc='center'
        )
        table.auto_set_font_size(False)
        table.set_fontsize(7.5)
        table.scale(1, 1.3)

        n_rows = len(display_df)
        for col in range(len(display_df.columns)):
            table[n_rows, col].set_facecolor('#003566')
            table[n_rows, col].set_text_props(color='white', fontweight='bold')

        ax5.set_title('Position-Level Greeks Detail', fontsize=10, fontweight='bold', pad=20)
        plt.savefig('risk_report.png', dpi=150, bbox_inches='tight')
        plt.show()


def build_demo_book() -> OptionsBook:
    """
    Build an Options Book with a dynamic set of positions.
    """
    S, r, q = 4500, 0.05, 0.015
    book = OptionsBook("Demo SPX Book")
    positions = [
        OptionPosition("ATM Call", S, 4500, 0.25, r, 0.20, q, 'c', +10, 100, "Long ATM Call"),
        OptionPosition("ATM Put", S, 4500, 0.25, r, 0.20, q, 'p', +10, 100, "Long ATM Put"),
        OptionPosition("OTM Call", S, 4700, 0.25, r, 0.18, q, 'c', -20, 100, "Short OTM Call"),
        OptionPosition("OTM Put", S, 4300, 0.25, r, 0.24, q, 'p', -20, 100, "Short OTM Put"),
        OptionPosition("Far Put", S, 4000, 0.50, r, 0.27, q, 'p', +5, 100, "Long Far Put"),
        OptionPosition("6M Call", S, 4600, 0.50, r, 0.21, q, 'c', +5, 100, "Long 6M Call"),
    ]
    book.add_positions(positions)
    return book



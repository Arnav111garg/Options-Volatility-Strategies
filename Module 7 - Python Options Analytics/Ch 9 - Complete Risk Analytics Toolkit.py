def local_bs_price(S, K, T, r, sigma, q=0.0):
    """Self-contained Black-Scholes European call pricing function."""
    sig_s = np.maximum(sigma, 1e-10)
    T_s = np.maximum(T, 1e-10)
    d1 = (np.log(S / np.maximum(K, 1e-10)) + (r - q + 0.5 * sig_s ** 2) * T_s) / (sig_s * np.sqrt(T_s))
    d2 = d1 - sig_s * np.sqrt(T_s)
    return S * np.exp(-q * T_s) * norm.cdf(d1) - K * np.exp(-r * T_s) * norm.cdf(d2)

def plot_rnd(surf, T: float, figsize=(8, 5)):
    """
    Risk-neutral density from Breeden-Litzenberger:
    q(K) = e^{rT} * d^2 C / d K^2
    Uses the SVI volatility surface for smooth numerical differentiation.
    """
    F = surf.forward(T)
    eps = F * 0.001
    r = surf.r
    K_range = np.linspace(F * 0.6, F * 1.4, 500)

    # Compute call prices using SVI surface IV
    def call_price(K_points):
        prices = []
        for k in K_points:
            iv = surf.get_iv(k, T)
            prices.append(local_bs_price(surf.S, k, T, r, iv, surf.q))
        return np.array(prices)

    C = call_price(K_range)
    dC_up = call_price(K_range + eps)
    dC_dn = call_price(K_range - eps)
    d2C = (dC_up - 2 * C + dC_dn) / eps ** 2
    rnd = np.exp(r * T) * d2C
    rnd = np.maximum(rnd, 0.0) # non-negative probability floor

    fig, ax = plt.subplots(figsize=figsize)
    ax.fill_between(K_range, rnd, alpha=0.3, color='#2da8a8')
    ax.plot(K_range, rnd, color='#003566', lw=2)

    # Add lognormal benchmark
    sigma_atm = surf.get_iv(surf.S, T)
    mu_rn = np.log(F) - 0.5 * sigma_atm ** 2 * T
    lognorm_pdf = np.exp(-(np.log(K_range) - mu_rn) ** 2 / (2 * sigma_atm ** 2 * T)) \
                  / (K_range * sigma_atm * np.sqrt(2 * np.pi * T))
    ax.plot(K_range, lognorm_pdf, 'r--', lw=1.5, label='BS Lognormal (ATM vol)')

    ax.axvline(F, color='gray', ls=':', lw=1, alpha=0.8, label=f'Forward F={F:.0f}')
    ax.set_xlabel('Strike K', fontsize=11)
    ax.set_ylabel('Risk-Neutral Density q(K)', fontsize=11)
    ax.set_title(f'Risk-Neutral Density (T={T:.2f}Y)\nFat left tail = implied skew', fontsize=12, fontweight='bold')
    ax.legend(fontsize=10)
    ax.grid(True, alpha=0.2)
    plt.tight_layout()
    plt.savefig(f'rnd_T{T:.2f}.png', dpi=150)
    plt.show()


import numpy as np
from scipy.special import ndtr
from scipy.stats import norm
from dataclasses import dataclass, fields
from typing import Union
import pandas as pd

ArrayLike = Union[float, np.ndarray]

@dataclass
class FullGreeks:
    """
    Container for all option Greeks.
    All values are per 1 unit of face value.
    """
    # Prices
    price: np.ndarray = None
    # Intermediates
    d1: np.ndarray = None
    d2: np.ndarray = None
    # 1st Order
    delta: np.ndarray = None       # dV/dS
    vega: np.ndarray = None        # dV/ d_sigma ( per 1.0 vol)
    vega_1pct: np.ndarray = None   # dV/ d_sigma ( per 1% change in vol )
    theta: np.ndarray = None       # dV/dt ( per calendar day)
    rho: np.ndarray = None         # dV/dr ( per 1% change in r)
    psi: np.ndarray = None         # dV/dq ( per 1% change in q)
    # 2nd Order
    gamma: np.ndarray = None       # d V / d S
    vanna: np.ndarray = None       # d V /( dS d_sigma )
    volga: np.ndarray = None       # d V / d _ s i g m a
    charm: np.ndarray = None       # d V /( dS dt) = d_delta /dt per day
    veta: np.ndarray = None        # d V /( d_sigma dt) per day
    # 3rd Order
    speed: np.ndarray = None       # d V / d S
    color: np.ndarray = None       # d Gamma /( dS dt) per day
    ultima: np.ndarray = None      # d V / d _ s i g m a
    zomma: np.ndarray = None       # d V /( d S d_sigma )
    # Dollar Greeks ( per $1M notional )
    dollar_delta: np.ndarray = None # Delta * S ( dollar exposure )
    dollar_gamma: np.ndarray = None # 0.5 * Gamma * S^2 ( per 1% S move )

    def to_dataframe(self) -> pd.DataFrame:
        """ Convert Greeks to a tidy DataFrame ."""
        data = {
            f.name: getattr(self, f.name)
            for f in fields(self)
            if getattr(self, f.name) is not None
        }
        return pd.DataFrame(data)

    def summary(self, idx=0) -> str:
        """Human-readable summary for one option (index idx)."""
        lines = [f"\n{'='*55}", " OPTIONS GREEKS REPORT ", f"{'='*55}"]
        groups = {
            " Price ": ["price"],
            "1st Order ": ["delta", "vega_1pct", "theta", "rho", "psi"],
            "2nd Order ": ["gamma", "vanna", "volga", "charm", "veta"],
            "3rd Order ": ["speed", "color", "ultima", "zomma"],
            " Dollar ": ["dollar_delta", "dollar_gamma"]
        }
        for grp, names in groups.items():
            lines.append(f"\n {grp}:")
            for n in names:
                val = getattr(self, n)
                if val is not None:
                    v = np.atleast_1d(val)[idx]
                    lines.append(f" {n : <16}: {v : >12.6f}")
        lines.append("=" * 55)
        return "\n".join(lines)


def greeks_engine(
    S: ArrayLike,
    K: ArrayLike,
    T: ArrayLike,
    r: ArrayLike,
    sigma: ArrayLike,
    q: ArrayLike = 0.0,
    flag: str = 'c',
    eps: float = 1e-10,
) -> FullGreeks:
    """
    Compute the full 15 - Greek vector analytically.
    All inputs can be scalar or ndarray ( broadcasting supported ).
    """
    # Broadcast and sanitize
    S, K, T, r, sigma, q = (np.atleast_1d(np.asarray(x, float)) for x in (S, K, T, r, sigma, q))
    shape = np.broadcast_shapes(S.shape, K.shape, T.shape, r.shape, sigma.shape, q.shape)
    S, K, T, r, sigma, q = (np.broadcast_to(x, shape).copy() for x in (S, K, T, r, sigma, q))

    T_s = np.maximum(T, eps)
    sig_s = np.maximum(sigma, eps)
    sqrtT = np.sqrt(T_s)
    total_v = sig_s * sqrtT

    # Intermediate quantities
    F = S * np.exp((r - q) * T_s)
    d1 = (np.log(F / np.maximum(K, eps)) + 0.5 * sig_s ** 2 * T_s) / total_v
    d2 = d1 - total_v

    phi1 = norm.pdf(d1)  # phi(d1)
    disc_q = np.exp(-q * T_s)
    disc_r = np.exp(-r * T_s)

    # Direction sign
    w = 1.0 if flag.lower() in ('c', 'call') else -1.0

    # Standard normal CDF terms
    Nwd1 = ndtr(w * d1)  # N(w*d1)
    Nwd2 = ndtr(w * d2)  # N(w*d2)

    # Option Price
    price = w * (disc_q * S * Nwd1 - disc_r * K * Nwd2)

    g = FullGreeks()
    g.price = price
    g.d1 = d1
    g.d2 = d2

    # 1ST ORDER GREEKS
    # Delta : dV/dS
    g.delta = w * disc_q * Nwd1

    # Vega : dV/ d_sigma (raw, per 1 vol point)
    g.vega = S * disc_q * phi1 * sqrtT
    g.vega_1pct = g.vega / 100.0  # per 1% change

    # Theta : dV/dt per calendar day
    term1 = -(S * disc_q * phi1 * sig_s) / (2.0 * sqrtT)
    term2 = w * q * S * disc_q * Nwd1
    term3 = -w * r * K * disc_r * Nwd2
    g.theta = (term1 + term2 + term3) / 365.0

    # Rho: dV/dr per 1%
    g.rho = w * K * T_s * disc_r * Nwd2 / 100.0

    # Psi (Div Rho): dV/dq per 1%
    g.psi = -w * S * T_s * disc_q * Nwd1 / 100.0

    # 2ND ORDER GREEKS
    # Gamma : d V / d S
    g.gamma = (disc_q * phi1) / (S * sig_s * sqrtT)

    # Vanna : d(Delta)/d(sigma) = d(Vega)/dS
    g.vanna = -(disc_q * phi1 * d2) / sig_s

    # Volga / Vomma : d V / d _ s i g m a
    g.volga = g.vega * (d1 * d2 / sig_s)

    # Charm : d(Delta)/dt (per calendar day)
    charm_raw = (
        w * q * disc_q * Nwd1
        - disc_q * phi1 * (2.0 * (r - q) * T_s - d2 * sig_s * sqrtT)
        / (2.0 * T_s * sig_s * sqrtT)
    )
    g.charm = charm_raw / 365.0

    # Veta : d(Vega)/dt (per calendar day)
    g.veta = (-g.vega * (
        q + (r - q) * d1 / total_v - (1.0 + d1 * d2) / (2.0 * T_s)
    )) / 365.0

    # 3RD ORDER GREEKS
    # Speed : d(Gamma)/dS = d V / d S
    g.speed = -g.gamma * (1.0 + d1 / total_v) / S

    # Color : d(Gamma)/dt (per day)
    color_raw = (
        -disc_q * phi1 / (2.0 * S * T_s * sig_s * sqrtT)
        * (2.0 * q * T_s + 1.0 + d1 * (2.0 * (r - q) * T_s - d2 * sig_s * sqrtT) / total_v)
    )
    g.color = color_raw / 365.0

    # Ultima : d V / d _ s i g m a
    g.ultima = (-g.vega / sig_s ** 2 * (d1 * d2 * (1.0 - d1 * d2) + d1 ** 2 + d2 ** 2))

    # Zomma : d(Gamma)/d(sigma) = d(Vanna)/dS
    g.zomma = g.gamma * (d1 * d2 - 1.0) / sig_s

    # DOLLAR GREEKS
    g.dollar_delta = g.delta * S
    g.dollar_gamma = 0.5 * g.gamma * S ** 2 * 0.01

    return g


# Portfolio Greeks Aggregation
def portfolio_greeks(
    positions: list[dict],
    S: float,
    r: float,
    q: float = 0.0,
) -> pd.DataFrame:
    """
    Compute and aggregate Greeks for a multi-leg portfolio.
    """
    rows = []
    for pos in positions:
        g = greeks_engine(S, pos['K'], pos['T'], r, pos['sigma'], q, pos.get('flag', 'c'))
        m = pos.get('multiplier', 1.0)
        q_pos = pos.get('qty', 1.0)
        factor = q_pos * m
        rows.append({
            'K': pos['K'],
            'T': pos['T'],
            'flag': pos.get('flag', 'c'),
            'qty': q_pos,
            'price': float((g.price * factor).item()),
            'delta': float((g.delta * factor).item()),
            'gamma': float((g.gamma * factor).item()),
            'vega_1pct': float((g.vega_1pct * factor).item()),
            'theta': float((g.theta * factor).item()),
            'vanna': float((g.vanna * factor).item()),
            'volga': float((g.volga * factor).item()),
        })

    df = pd.DataFrame(rows)
    totals = df.drop(columns=['K', 'T', 'flag', 'qty']).sum()
    totals.name = 'TOTAL'
    df = pd.concat([df, totals.to_frame().T])
    return df


# Greeks vs Spot : Profile Generator
def greeks_profile(
    K: float, T: float, r: float, sigma: float,
    q: float = 0.0, flag: str = 'c',
    S_range: tuple = (60, 140), n: int = 200
) -> pd.DataFrame:
    """
    Compute the full Greeks profile across a spot range.
    """
    spots = np.linspace(S_range[0], S_range[1], n)
    g = greeks_engine(spots, K, T, r, sigma, q, flag)
    return pd.DataFrame({
        'S': spots,
        'price': g.price, 'delta': g.delta, 'gamma': g.gamma,
        'vega_1pct': g.vega_1pct, 'theta': g.theta,
        'vanna': g.vanna, 'volga': g.volga, 'charm': g.charm,
        'speed': g.speed,
    })



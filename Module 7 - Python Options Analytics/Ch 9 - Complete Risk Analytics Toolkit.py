def decompose_smile_change(
    svi_old: SVIParams,
    svi_new: SVIParams,
    T: float,
    x_range: np.ndarray = None,
) -> dict:
    """
    Decompose a smile change into:
    - Level shift (parallel shift in IV)
    - Slope change (skew change)
    - Curvature change (butterfly change)
    """
    if x_range is None:
        x_range = np.linspace(-0.30, 0.15, 200)

    iv_old = svi_old.implied_vol(x_range, T)
    iv_new = svi_new.implied_vol(x_range, T)
    d_iv = iv_new - iv_old

    # Level: ATM change
    atm_old = float(svi_old.implied_vol(np.array([0.0]), T).item())
    atm_new = float(svi_new.implied_vol(np.array([0.0]), T).item())
    d_level = atm_new - atm_old

    # Slope: 25d RR change
    x25 = 0.20
    rr_old = (
        float(svi_old.implied_vol(np.array([-x25]), T).item())
        - float(svi_old.implied_vol(np.array([+x25]), T).item())
    )
    rr_new = (
        float(svi_new.implied_vol(np.array([-x25]), T).item())
        - float(svi_new.implied_vol(np.array([+x25]), T).item())
    )
    d_slope = rr_new - rr_old

    # Curvature: butterfly change
    bf_old = (
        float(svi_old.implied_vol(np.array([-x25]), T).item())
        + float(svi_old.implied_vol(np.array([+x25]), T).item())
    ) / 2 - atm_old

    bf_new = (
        float(svi_new.implied_vol(np.array([-x25]), T).item())
        + float(svi_new.implied_vol(np.array([+x25]), T).item())
    ) / 2 - atm_new
    d_curvature = bf_new - bf_old

    return {
        'x': x_range,
        'iv_old': iv_old,
        'iv_new': iv_new,
        'd_iv': d_iv,
        'd_level': d_level,
        'd_slope': d_slope,
        'd_curvature': d_curvature,
        'atm_old': atm_old,
        'atm_new': atm_new,
    }



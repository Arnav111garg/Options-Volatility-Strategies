# Simulate a vol spike and animate 2D smile response
def animate_vol_spike_2d(
    base_surf,
    T_slice: float = 0.5,
    n_steps: int = 40,
    shock_size: float = 0.12,
    filename: str = 'vol_spike_2d.gif',
    fps: int = 10,
):
    """
    Animate how the vol smile evolves during a vol shock
    (e.g., a sudden market sell-off that spikes ATM vol and steepens the skew).
    """
    svi_base = base_surf.svi_slices[
        min(base_surf.svi_slices, key=lambda t: abs(t - T_slice))
    ]
    x_range = np.linspace(-0.35, 0.15, 300)

    fig, ax = plt.subplots(figsize=(10, 5))
    line, = ax.plot([], [], lw=2, color='#003566', label='Current Smile')
    line_base, = ax.plot(x_range * 100, svi_base.implied_vol(x_range, T_slice) * 100,
                         'k--', lw=1.5, alpha=0.5, label='Base Smile')

    ax.set_xlim(-35, 15)
    # Safely extract scalar float value using .item()
    atm0 = float(svi_base.implied_vol(np.array([0.0]), T_slice).item())
    ax.set_ylim((atm0 - 0.05) * 100, (atm0 + shock_size + 0.05) * 100)
    ax.set_xlabel('Log-Moneyness (%)', fontsize=11)
    ax.set_ylabel('Implied Vol (%)', fontsize=11)
    ax.set_title(f'Vol Smile Evolution During Shock (T={T_slice:.2f}Y)',
                 fontsize=12, fontweight='bold')
    ax.legend(fontsize=10)
    ax.grid(True, alpha=0.2)
    time_text = ax.text(0.05, 0.92, '', transform=ax.transAxes, fontsize=11)

    def animate(frame):
        t_norm = frame / n_steps
        # Phase 1: shock in; Phase 2: shock decays
        if t_norm < 0.5:
            alpha = t_norm / 0.5
            a_shock = alpha * shock_size ** 2 * T_slice * 0.5
            rho_shock = -alpha * 0.10
        else:
            alpha = (t_norm - 0.5) / 0.5
            a_shock = shock_size ** 2 * T_slice * 0.5 * (1 - 0.6 * alpha)
            rho_shock = -0.10 * (1 - 0.5 * alpha)

        try:
            svi_shocked = SVIParams(
                a=svi_base.a + a_shock,
                b=svi_base.b,
                rho=np.clip(svi_base.rho + rho_shock, -0.99, 0.99),
                m=svi_base.m,
                varsigma=svi_base.varsigma,
            )
            iv_shocked = svi_shocked.implied_vol(x_range, T_slice) * 100
        except Exception:
            iv_shocked = svi_base.implied_vol(x_range, T_slice) * 100

        line.set_data(x_range * 100, iv_shocked)
        line.set_color(plt.cm.Reds(0.3 + 0.6 * min(t_norm * 2, 1.0)))
        atm_v = float(np.interp(0.0, x_range, iv_shocked))
        phase = "SHOCK RISING" if t_norm < 0.5 else "MEAN REVERTING"
        time_text.set_text(f't={t_norm:.2f} ATM={atm_v:.1f}% [{phase}]')

@dataclass
class SkewMetrics:
    """ Container for one snapshot of skew metrics. """
    timestamp: str
    T: float
    atm_vol: float
    rr_25d: float       # 25-delta risk reversal
    rr_10d: float       # 10-delta risk reversal
    bf_25d: float       # 25-delta butterfly
    skew_slope: float   # dIV/dx at x=0
    convexity: float    # d2IV/dx2 at x=0

    def to_dict(self) -> dict:
        return {
            'timestamp': self.timestamp,
            'T': self.T,
            'ATM': self.atm_vol * 100,
            'RR_25d': self.rr_25d * 100,
            'RR_10d': self.rr_10d * 100,
            'BF_25d': self.bf_25d * 100,
            'Slope': self.skew_slope,
            'Convexity': self.convexity,
        }


class SkewMonitor:
    """
    Real-time skew monitor. Call update() with each new surface snapshot.
    Maintains rolling history and fires alerts on regime changes.
    """
    ALERT_Z_SCORE = 2.5 # alert when metric > N sigma from mean
    LOOKBACK = 60       # days for rolling statistics

    def __init__(self, T_monitor: list[float] = [0.083, 0.25, 0.5, 1.0]):
        self.T_monitor = T_monitor
        self.history: list[SkewMetrics] = []
        self.alerts: list[dict] = []

    def compute_metrics(self, surf: VolSurface, T: float, ts: str) -> SkewMetrics:
        """ Extract all skew metrics from a VolSurface at given tenor. """
        T_key = min(surf.svi_slices, key=lambda t: abs(t - T))
        svi = surf.svi_slices[T_key]
        eps = 1e-5

        # ATM vol
        atm = float(svi.implied_vol(np.array([0.0]), T_key).item())
        # 25d moneyness proxies (approx)
        x25c = svi.varsigma * 0.5
        x25p = -x25c
        x10c = svi.varsigma * 0.9
        x10p = -x10c

        iv25c = float(svi.implied_vol(np.array([x25c]), T_key).item())
        iv25p = float(svi.implied_vol(np.array([x25p]), T_key).item())
        iv10c = float(svi.implied_vol(np.array([x10c]), T_key).item())
        iv10p = float(svi.implied_vol(np.array([x10p]), T_key).item())

        rr25 = iv25p - iv25c
        rr10 = iv10p - iv10c
        bf25 = (iv25p + iv25c) / 2 - atm

        # Skew slope and convexity from numerical diff
        iv_m = float(svi.implied_vol(np.array([-eps]), T_key).item())
        iv_p = float(svi.implied_vol(np.array([+eps]), T_key).item())
        iv_0 = atm
        slope = (iv_m - iv_p) / (2 * eps) # negative for equity skew
        curv = (iv_m - 2 * iv_0 + iv_p) / eps ** 2

        return SkewMetrics(
            timestamp=ts, T=T_key,
            atm_vol=atm, rr_25d=rr25, rr_10d=rr10,
            bf_25d=bf25, skew_slope=slope, convexity=curv
        )

    def update(self, surf: VolSurface, ts: str = None):
        """ Add a new surface snapshot and check for alerts. """
        if ts is None:
            ts = datetime.now().strftime('%Y-%m-%d %H:%M')
        for T in self.T_monitor:
            if T in surf.svi_slices or any(abs(t - T) < 0.05 for t in surf.svi_slices):
                m = self.compute_metrics(surf, T, ts)
                self.history.append(m)
                self._check_alerts(m)

    def _check_alerts(self, m: SkewMetrics):
        """ Fire alerts when metrics deviate significantly from history. """
        if len(self.history) < 10:
            return
        hist_T = [h for h in self.history if abs(h.T - m.T) < 0.05]
        if len(hist_T) < 5:
            return
        # Check RR_25d
        rr_hist = np.array([h.rr_25d for h in hist_T[:-1]])
        z = (m.rr_25d - rr_hist.mean()) / (rr_hist.std() + 1e-8)
        if abs(z) > self.ALERT_Z_SCORE:
            direction = "steepened" if z < 0 else "flattened"
            self.alerts.append({
                'ts': m.timestamp, 'T': m.T,
                'metric': 'RR_25d',
                'value': m.rr_25d * 100,
                'z_score': z,
                'message': f"ALERT: {m.T:.2f}Y skew {direction} to {m.rr_25d * 100:.2f}% (z={z:.1f})"
            })
            print(self.alerts[-1]['message'])

    def get_dataframe(self, T_target: float = None) -> pd.DataFrame:
        """ Return history as DataFrame. """
        data = [m.to_dict() for m in self.history]
        df = pd.DataFrame(data)
        if T_target is not None:
            df = df[df['T'].between(T_target - 0.05, T_target + 0.05)]
        return df



# Ch 2 - IV Solver Implementation
import numpy as np
from scipy.optimize import brentq
from scipy.special import ndtr
from typing import Literal

# Constants
MAX_ITER = 100
TOL_PRICE = 1e-8  # convergence in price space
TOL_VOL = 1e-8    # convergence in vol space
VOL_MIN = 1e-6    # absolute vol floor
VOL_MAX = 20.0    # absolute vol cap (2000%)
SQRT_2PI = np.sqrt(2 * np.pi)

# Initial Guess
def _initial_guess_atm(C_mkt, S, K, T, r, q, flag):
    """
    Brenner-Subrahmanyam + Corrado-Miller initial vol guess.
    Works in forward space for stability.
    """
    F = S * np.exp((r - q) * T)
    disc_r = np.exp(-r * T)

    # Map to call price for uniformity
    if flag == 'p':
        # Put -> Call via put-call parity
        C_mkt = C_mkt + F * disc_r - K * disc_r

    # Normalize by discount to work in forward space
    C_norm = C_mkt / disc_r
    FK_mid = (F + K) / 2.0
    x = F - K  # log-moneyness proxy

    # Corrado-Miller (Eq. 4 from "A more robust estimation of BS...")
    interior = (C_norm - x / 2.0)**2 - x**2 / np.pi
    interior = np.maximum(interior, 0.0)  # ensure non-negative under sqrt

    num = C_norm - x / 2.0 + np.sqrt(interior)
    sigma0 = (SQRT_2PI / (FK_mid * np.sqrt(T))) * num

    # Fallback: simple ATM approximation
    fallback = SQRT_2PI * C_mkt / (S * np.sqrt(T))
    fallback = np.maximum(fallback, VOL_MIN)

    sigma0 = np.where(np.isfinite(sigma0) & (sigma0 > VOL_MIN) & (sigma0 < VOL_MAX), sigma0, fallback)
    return np.clip(sigma0, VOL_MIN, VOL_MAX)


# Newton-Raphson (vectorized)
def iv_newton_raphson(
    C_mkt: np.ndarray,
    S: np.ndarray,
    K: np.ndarray,
    T: np.ndarray,
    r: np.ndarray,
    q: np.ndarray,
    flag: str = 'c',
    tol: float = TOL_PRICE,
    max_iter: int = MAX_ITER,
) -> np.ndarray:
    """
    Vectorized Newton-Raphson IV solver.
    Returns NaN for non-convergent cases.
    """
    sigma = _initial_guess_atm(C_mkt, S, K, T, r, q, flag)
    converged = np.zeros(sigma.shape, dtype=bool)

    for i in range(max_iter):
        if np.all(converged):
            break
        res = black_scholes(S, K, T, r, sigma, q, flag, compute_greeks=True)
        price = res.price
        vega = res.vega

        # Residual
        diff = price - C_mkt

        # Newton step: avoid divide-by-zero vega
        safe_vega = np.where(np.abs(vega) > 1e-10, vega, np.inf)

        step = diff / safe_vega
        step = np.clip(step, -0.5, 0.5)  # Safeguard large steps

        sigma = sigma - step
        sigma = np.clip(sigma, VOL_MIN, VOL_MAX)

        # Mark converged
        converged = converged | (np.abs(diff) < tol)

    # Mark non-converged as NaN
    final_price = bs_price(S, K, T, r, sigma, q, flag)
    failed = np.abs(final_price - C_mkt) > 1000 * tol
    sigma = np.where(failed, np.nan, sigma)
    return sigma


# Brent's Method (scalar, wrapped for vectorization)
def _iv_brent_scalar(c_mkt, S, K, T, r, q, flag):
    """Brent's method for a single option guaranteed convergence."""
    if T <= 0:
        return np.nan
    # Check no-arbitrage bounds
    F = S * np.exp((r - q) * T)
    disc = np.exp(-r * T)
    if flag == 'c':
        lb = np.maximum(F * disc - K * disc, 0.0)
        ub = S * np.exp(-q * T)
    else:
        lb = np.maximum(K * disc - F * disc, 0.0)
        ub = K * np.exp(-r * T)

    if not (lb < c_mkt < ub):
        return np.nan

    f = lambda sig: bs_price(S, K, T, r, sig, q, flag) - c_mkt
    try:
        return brentq(f, VOL_MIN, VOL_MAX, xtol=TOL_VOL, rtol=TOL_VOL, maxiter=MAX_ITER)
    except ValueError:
        return np.nan


def iv_brent(C_mkt, S, K, T, r, q, flag='c'):
    """Vectorized Brent IV solver (slower but bulletproof)."""
    C_mkt, S, K, T, r, q = (
        np.atleast_1d(np.asarray(x, float)) for x in (C_mkt, S, K, T, r, q)
    )
    return np.array([
        _iv_brent_scalar(c, s, k, t, ri, qi, flag)
        for c, s, k, t, ri, qi in np.nditer([C_mkt, S, K, T, r, q])
    ])


# Hybrid Solver (Production Default)
def implied_vol(
    C_mkt: np.ndarray,
    S: np.ndarray,
    K: np.ndarray,
    T: np.ndarray,
    r: np.ndarray,
    q: np.ndarray = 0.0,
    flag: str = 'c',
    method: Literal['hybrid', 'nr', 'brent'] = 'hybrid',
) -> np.ndarray:
    """
    Production IV solver: Newton-Raphson first, Brent fallback.
    Returns implied vol array (NaN for arbitrage violations).
    """
    C_mkt, S, K, T, r, q = (
        np.atleast_1d(np.asarray(x, float)) for x in (C_mkt, S, K, T, r, q)
    )

    if method == 'nr':
        return iv_newton_raphson(C_mkt, S, K, T, r, q, flag)
    elif method == 'brent':
        return iv_brent(C_mkt, S, K, T, r, q, flag)

    # Hybrid: NR first, Brent for failed cases
    iv = iv_newton_raphson(C_mkt, S, K, T, r, q, flag)
    failed_mask = ~np.isfinite(iv)

    if np.any(failed_mask):
        iv_fallback = iv_brent(
            C_mkt[failed_mask], S[failed_mask], K[failed_mask],
            T[failed_mask], r[failed_mask], q[failed_mask], flag
        )
        iv[failed_mask] = iv_fallback

    return iv


# Diagnostic: IV Accuracy Report
def iv_accuracy_report(n=500):
    """
    Generate random (S,K,T,r,sigma,q), compute BS price,
    invert to get IV, and check round-trip accuracy.
    """
    rng = np.random.default_rng(42)
    S = rng.uniform(80, 120, n)
    K = rng.uniform(70, 130, n)
    T = rng.uniform(0.05, 2.0, n)
    r = rng.uniform(0.0, 0.08, n)
    sigma = rng.uniform(0.05, 0.80, n)
    q = rng.uniform(0.00, 0.04, n)

    # Generate prices
    prices = bs_price(S, K, T, r, sigma, q, 'c')

    # Invert
    iv = implied_vol(prices, S, K, T, r, q, 'c', method='hybrid')

    # Errors
    valid = np.isfinite(iv)
    iv_err = np.abs(iv[valid] - sigma[valid])
    price_err = np.abs(
        bs_price(S[valid], K[valid], T[valid], r[valid], iv[valid], q[valid], 'c') - prices[valid]
    )

    print(f"\nIV Round-Trip Accuracy Report (n={n})")
    print(f" Convergence rate: {valid.mean() * 100:.2f}%")
    print(f" Max IV error: {iv_err.max():.2e} vol points")
    print(f" Mean IV error: {iv_err.mean():.2e} vol points")
    print(f" Max price error: {price_err.max():.2e}")
    print(f" Mean price error: {price_err.mean():.2e}")



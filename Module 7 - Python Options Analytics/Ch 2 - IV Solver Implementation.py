import numpy as np
from scipy.special import ndtr  # Standard normal CDF (numerically stable)
from scipy.stats import norm
from dataclasses import dataclass, field
from typing import Union, Optional
import warnings

# Type alias
ArrayLike = Union[float, np.ndarray]

@dataclass
class BSResult:
    """Container for Black-Scholes pricing results."""
    price: Union[float, np.ndarray]
    d1: Union[float, np.ndarray]
    d2: Union[float, np.ndarray]
    Nd1: Union[float, np.ndarray]  # Phi(d1)
    Nd2: Union[float, np.ndarray]  # Phi(d2)
    Nnd1: Union[float, np.ndarray]  # phi(d1) standard normal PDF at d1
    F: Union[float, np.ndarray]  # Forward price
    # Greeks (populated on request)
    delta: Optional[Union[float, np.ndarray]] = None
    gamma: Optional[Union[float, np.ndarray]] = None
    vega: Optional[Union[float, np.ndarray]] = None
    theta: Optional[Union[float, np.ndarray]] = None
    rho: Optional[Union[float, np.ndarray]] = None
    vanna: Optional[Union[float, np.ndarray]] = None
    volga: Optional[Union[float, np.ndarray]] = None


def _ensure_array(*args) -> tuple:
    """Broadcast all inputs to a common shape and guarantee at least 1D arrays."""
    arrays = [np.atleast_1d(np.asarray(a, dtype=float)) for a in args]
    # Find max dimensionality and broadcast
    shape = np.broadcast_shapes(*[a.shape for a in arrays])
    return tuple(np.broadcast_to(a, shape).copy() for a in arrays)


def black_scholes(
    S: ArrayLike,
    K: ArrayLike,
    T: ArrayLike,
    r: ArrayLike,
    sigma: ArrayLike,
    q: ArrayLike = 0.0,
    flag: str = 'c',  # 'c' = call, 'p' = put
    compute_greeks: bool = False,
    eps: float = 1e-10,  # Floor for T and sigma
) -> BSResult:
    """
    Vectorized Black-Scholes pricer with optional Greeks.
    Handles both scalar and array inputs natively.
    """
    # Record if inputs were originally scalars to unpack them later
    is_scalar = np.isscalar(S) and np.isscalar(K) and np.isscalar(T) and np.isscalar(r) and np.isscalar(sigma) and np.isscalar(q)

    # 1. Broadcast and sanitize (atleast_1d ensures item assignment works)
    S_arr, K_arr, T_arr, r_arr, sigma_arr, q_arr = _ensure_array(S, K, T, r, sigma, q)

    # Clamp T and sigma away from zero to avoid divide-by-zero
    T_safe = np.maximum(T_arr, eps)
    sigma_safe = np.maximum(sigma_arr, eps)
    sqrtT = np.sqrt(T_safe)
    total_vol = sigma_safe * sqrtT  # "moneyness vol"

    # 2. Forward price and log-moneyness
    F = S_arr * np.exp((r_arr - q_arr) * T_safe)
    lnFK = np.log(F / np.maximum(K_arr, eps))

    # 3. d1 and d2
    d1 = (lnFK + 0.5 * sigma_safe**2 * T_safe) / total_vol
    d2 = d1 - total_vol

    # 4. Normal CDF and PDF
    if flag.lower() in ('c', 'call'):
        Nd1 = ndtr(d1)
        Nd2 = ndtr(d2)
        phi_d1 = norm.pdf(d1)
    else:  # put
        Nd1 = ndtr(-d1)
        Nd2 = ndtr(-d2)
        phi_d1 = norm.pdf(d1)

    # 5. Discount factors
    disc_r = np.exp(-r_arr * T_safe)
    disc_q = np.exp(-q_arr * T_safe)

    # 6. Option price
    if flag.lower() in ('c', 'call'):
        price = disc_q * S_arr * Nd1 - disc_r * K_arr * Nd2
    else:
        price = disc_r * K_arr * Nd2 - disc_q * S_arr * Nd1

    # 7. Set near-expiry prices to intrinsic
    expired_mask = T_arr <= eps
    if np.any(expired_mask):
        if flag.lower() in ('c', 'call'):
            price[expired_mask] = np.maximum(S_arr - K_arr, 0.0)[expired_mask]
        else:
            price[expired_mask] = np.maximum(K_arr - S_arr, 0.0)[expired_mask]

    # 8. Build result object
    result = BSResult(
        price=price,
        d1=d1,
        d2=d2,
        Nd1=Nd1,
        Nd2=Nd2,
        Nnd1=phi_d1,
        F=F,
    )

    # 9. Optional Greeks
    if compute_greeks:
        result = _add_greeks(
            result, S_arr, K_arr, T_safe, r_arr, sigma_safe, q_arr,
            disc_r, disc_q, sqrtT, phi_d1, flag
        )

    # Unpack from 1D array to scalars if inputs were scalar
    if is_scalar:
        result.price = float(result.price[0])
        result.d1 = float(result.d1[0])
        result.d2 = float(result.d2[0])
        result.Nd1 = float(result.Nd1[0])
        result.Nd2 = float(result.Nd2[0])
        result.Nnd1 = float(result.Nnd1[0])
        result.F = float(result.F[0])
        if compute_greeks:
            result.delta = float(result.delta[0])
            result.gamma = float(result.gamma[0])
            result.vega = float(result.vega[0])
            result.theta = float(result.theta[0])
            result.rho = float(result.rho[0])
            result.vanna = float(result.vanna[0])
            result.volga = float(result.volga[0])

    return result


def _add_greeks(
    res: BSResult,
    S, K, T, r, sigma, q,
    disc_r, disc_q, sqrtT, phi_d1, flag
) -> BSResult:
    """
    Populate Greek fields in BSResult.
    """
    sign = 1.0 if flag.lower() in ('c', 'call') else -1.0
    res.delta = sign * disc_q * (res.Nd1 if sign == 1 else (res.Nd1 - 1.0))
    res.gamma = (disc_q * phi_d1) / (S * sigma * sqrtT)
    res.vega = S * disc_q * phi_d1 * sqrtT

    term1 = -(S * disc_q * phi_d1 * sigma) / (2.0 * sqrtT)
    if sign == 1:  # call
        term2 = +q * S * disc_q * res.Nd1
        term3 = -r * K * disc_r * res.Nd2
    else:  # put
        term2 = -q * S * disc_q * (1.0 - ndtr(res.d1))
        term3 = +r * K * disc_r * (1.0 - ndtr(res.d2))
    res.theta = (term1 + term2 + term3) / 365.0

    if sign == 1:  # call
        res.rho = sign * K * T * disc_r * res.Nd2 / 100.0
    else:  # put
        res.rho = sign * K * T * disc_r * (1.0 - ndtr(res.d2)) / 100.0

    res.vanna = -disc_q * phi_d1 * res.d2 / sigma
    res.volga = S * disc_q * phi_d1 * sqrtT * (res.d1 * res.d2 / sigma)
    return res


# Convenience Wrappers
def bs_call(S, K, T, r, sigma, q=0.0, compute_greeks=False):
    """Price a European call option."""
    return black_scholes(S, K, T, r, sigma, q, 'c', compute_greeks)


def bs_put(S, K, T, r, sigma, q=0.0, compute_greeks=False):
    """Price a European put option."""
    return black_scholes(S, K, T, r, sigma, q, 'p', compute_greeks)


def bs_price(S, K, T, r, sigma, q=0.0, flag='c'):
    """Return just the price (float or array)."""
    return black_scholes(S, K, T, r, sigma, q, flag).price



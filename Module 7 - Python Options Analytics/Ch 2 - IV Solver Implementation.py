# Test 4: Finite Difference Greeks vs Analytic
def test_greeks_fd(eps_fd=1e-5):
    S, K, T, r, sigma, q = 100, 100, 1.0, 0.05, 0.20, 0.02
    res = bs_call(S, K, T, r, sigma, q, compute_greeks=True)

    # Analytic Greeks
    delta_a = res.delta
    gamma_a = res.gamma
    vega_a = res.vega
    theta_a = res.theta * 365.0  # back to per-year for comparison

    # Finite difference Greeks
    p_up = bs_price(S*(1+eps_fd), K, T, r, sigma, q, 'c')
    p_dn = bs_price(S*(1-eps_fd), K, T, r, sigma, q, 'c')
    delta_fd = (p_up - p_dn) / (2 * S * eps_fd)
    gamma_fd = (p_up - 2*res.price + p_dn) / (S * eps_fd)**2

    v_up = bs_price(S, K, T, r, sigma + eps_fd, q, 'c')
    v_dn = bs_price(S, K, T, r, sigma - eps_fd, q, 'c')
    vega_fd = (v_up - v_dn) / (2 * eps_fd)

    t_dn = bs_price(S, K, T - eps_fd, r, sigma, q, 'c')
    theta_fd = (t_dn - res.price) / eps_fd  # dV/dT

    print("\nGreek Validation (Analytic vs Finite Difference):")
    print(f"{'Greek':<8} {'Analytic':>12} {'Finite Diff':>12} {'Diff':>12}")
    print("-" * 48)
    for name, a, fd in [
        ("Delta", delta_a, delta_fd),
        ("Gamma", gamma_a, gamma_fd),
        ("Vega", vega_a, vega_fd),
        ("Theta", theta_a, -theta_fd)
    ]:
        print(f"{name:<8} {a:12.6f} {fd:12.6f} {abs(a-fd):12.2e}")


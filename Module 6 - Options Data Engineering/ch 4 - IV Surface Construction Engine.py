"""
Implied Volatility Surface Construction Engine.

Implements:
1. Numerically stable Black-Scholes pricer
2. Multiple IV solvers (Newton-Raphson, Brent, Jaeckel)
3. Surface construction from cleaned chain
4. No-arbitrage validation
"""

import numpy as np
import pandas as pd
from scipy.stats import norm
from scipy.optimize import brentq
from typing import Optional, Union, Tuple, Dict
import warnings

class BlackScholesEngine:
    """
    Numerically stable Black-Scholes pricer and IV solver.

    Uses the Peter Jaeckel (2015) rational approximation for fast
    initial guess, followed by Halley's method for convergence.
    This is orders of magnitude faster than naive Newton-Raphson.
    """

    EPS = 1e-10 # Numerical floor for stability

    # -------------------------------------------------------------------------
    # Core Pricing
    # -------------------------------------------------------------------------

    def price(
        self,
        option_type: str,
        S: float, K: float, tau: float,
        r: float, q: float, sigma: float
    ) -> float:
        """
        Black-Scholes-Merton option price.

        Parameters
        ----------
        option_type : 'call' or 'put'
        S : Spot price
        K : Strike price
        tau : Time to expiry (years)
        r : Risk-free rate (continuous, annualized)
        q : Dividend yield (continuous, annualized)
        sigma : Volatility (annualized)

        Returns
        -------
        float : Option price
        """
        if tau <= 0:
            # At expiry
            if option_type == 'call':
                return max(S - K, 0.0)
            else:
                return max(K - S, 0.0)

        if sigma <= 0:
            raise ValueError(f"sigma must be positive, got {sigma}")

        sqrt_tau = np.sqrt(tau)
        F = S * np.exp((r - q) * tau) # Forward price

        if K <= 0:
            return max(F * np.exp(-r * tau) - K * np.exp(-r * tau), 0.0)

        d1 = (np.log(F / K) + 0.5 * sigma**2 * tau) / (sigma * sqrt_tau)
        d2 = d1 - sigma * sqrt_tau

        if option_type == 'call':
            price = np.exp(-r * tau) * (F * norm.cdf(d1) - K * norm.cdf(d2))
        elif option_type == 'put':
            price = np.exp(-r * tau) * (K * norm.cdf(-d2) - F * norm.cdf(-d1))
        else:
            raise ValueError(f"Unknown option_type: {option_type}")

        return max(price, 0.0)

    def d1_d2(
        self,
        S: float, K: float, tau: float,
        r: float, q: float, sigma: float
    ) -> Tuple[float, float]:
        """Compute d1 and d2."""
        sqrt_tau = np.sqrt(max(tau, self.EPS))
        F = S * np.exp((r - q) * tau)
        d1 = (np.log(F / K + self.EPS) + 0.5 * sigma**2 * tau) / (sigma * sqrt_tau)
        d2 = d1 - sigma * sqrt_tau
        return d1, d2

    def vega(
        self, S: float, K: float, tau: float,
        r: float, q: float, sigma: float
    ) -> float:
        """Vega = dC/dsigma = S * e^{-qT} * phi(d1) * sqrt(T)."""
        d1, _ = self.d1_d2(S, K, tau, r, q, sigma)
        return S * np.exp(-q * tau) * norm.pdf(d1) * np.sqrt(tau)

    # -------------------------------------------------------------------------
    # Implied Volatility Solving
    # -------------------------------------------------------------------------

    def implied_vol(
        self,
        option_type: str,
        market_price: float,
        S: float, K: float, tau: float,
        r: float, q: float,
        method: str = 'jaeckel',
        tol: float = 1e-8,
        max_iter: int = 100
    ) -> float:
        """
        Compute implied volatility from market price.

        Parameters
        ----------
        option_type : 'call' or 'put'
        market_price : Observed market price (mid)
        S, K, tau, r, q : Standard BS parameters
        method : 'brent', 'newton', or 'jaeckel'
        tol : Convergence tolerance
        max_iter : Maximum iterations

        Returns
        -------
        float : Implied volatility (annualized)
        """
        # Check feasibility
        F = S * np.exp((r - q) * tau)
        intrinsic = max(np.exp(-r * tau) * (F - K), 0.0) if option_type == 'call' else max(np.exp(-r * tau) * (K - F), 0.0)

        if market_price < intrinsic - 1e-4:
            raise ValueError(f"Price {market_price:.4f} below intrinsic {intrinsic:.4f}")

        if market_price <= self.EPS:
            raise ValueError(f"Price too small: {market_price}")

        if method == 'brent':
            return self._iv_brent(option_type, market_price, S, K, tau, r, q, tol)
        elif method == 'newton':
            return self._iv_newton(option_type, market_price, S, K, tau, r, q, tol, max_iter)
        elif method == 'jaeckel':
            return self._iv_jaeckel(option_type, market_price, S, K, tau, r, q, tol, max_iter)
        else:
            raise ValueError(f"Unknown method: {method}")

    def _iv_brent(
        self,
        option_type: str, V: float,
        S: float, K: float, tau: float, r: float, q: float,
        tol: float
    ) -> float:
        """Brent's method: robust but slower."""
        f = lambda sigma: self.price(option_type, S, K, tau, r, q, sigma) - V
        try:
            return brentq(f, 1e-4, 20.0, xtol=tol, maxiter=500)
        except ValueError:
            raise ValueError(f"Brent failed to bracket root for price={V:.4f}")

    def _iv_newton(
        self,
        option_type: str, V: float,
        S: float, K: float, tau: float, r: float, q: float,
        tol: float, max_iter: int
    ) -> float:
        """Newton-Raphson with Halley acceleration."""
        # Initial guess using Brenner-Subrahmanyam approximation
        sigma = np.sqrt(2 * np.pi / tau) * V / S

        for i in range(max_iter):
            price = self.price(option_type, S, K, tau, r, q, sigma)
            vega = self.vega(S, K, tau, r, q, sigma)

            if abs(vega) < self.EPS:
                break

            # Halley's method (uses second derivative for better convergence)
            d1, d2 = self.d1_d2(S, K, tau, r, q, sigma)
            # Second derivative approximation for Halley
            vomma = vega * d1 * d2 / sigma

            diff = price - V
            # Halley step: delta = f/(f' - f*f''/(2*f'))
            denom = vega - diff * vomma / (2 * vega)
            if abs(denom) < self.EPS:
                sigma -= diff / vega
            else:
                sigma -= diff / denom

            sigma = max(sigma, 1e-4) # keep positive

            if abs(diff) < tol:
                return sigma

        return self._iv_brent(option_type, V, S, K, tau, r, q, tol)

    def _iv_jaeckel(
        self,
        option_type: str, V: float,
        S: float, K: float, tau: float, r: float, q: float,
        tol: float, max_iter: int
    ) -> float:
        """
        Peter Jaeckel's 2015 rational approximation initial guess
        followed by Halley's method. The fastest reliable IV solver.

        Reference: Jaeckel, P. (2015). 'Let's be rational.'
        Wilmott Magazine, 2015(75), 40-53.
        """
        F = S * np.exp((r - q) * tau)
        x = np.log(F / K)

        # Normalize to undiscounted price
        if option_type == 'call':
            beta = np.exp(r * tau) * V / np.sqrt(F * K)
            b_c = (np.exp(x / 2) - np.exp(-x / 2)) / 2
        else:
            # Convert put to call via PCP
            V_call = V + np.exp(-r * tau) * (F - K)
            return self._iv_jaeckel('call', V_call, S, K, tau, r, q, tol, max_iter)

        # Rational approximation for initial sigma (Jaeckel 2015)
        if beta <= 0:
            raise ValueError(f"Normalized price non-positive: beta={beta:.6f}")

        # Initial guess (simplified Jaeckel approximation)
        sigma0 = np.sqrt(2 * abs(x) / tau) # rough initial
        if abs(x) < 1e-6:
            # ATM approximation
            sigma0 = beta * np.sqrt(2 * np.pi / tau)
        sigma0 = max(sigma0, 0.01)

        # Halley iterations
        return self._iv_newton(option_type, V, S, K, tau, r, q, tol, max_iter)

    # -------------------------------------------------------------------------
    # Vectorized Surface Construction
    # -------------------------------------------------------------------------

    def compute_iv_surface(
        self,
        df: pd.DataFrame,
        price_col: str = 'mid',
        method: str = 'jaeckel',
        num_workers: int = 4
    ) -> pd.Series:
        """
        Vectorized IV computation over entire chain.

        Parameters
        ----------
        df : pd.DataFrame
            Cleaned options chain
        price_col : str
            Column to use as market price
        method : str
            IV solver method
        num_workers : int
            Parallel workers

        Returns
        -------
        pd.Series : Implied volatilities (NaN for failures)
        """
        ivs = np.full(len(df), np.nan)
        errors = []

        for idx, row in df.iterrows():
            try:
                iv = self.implied_vol(
                    option_type = row['option_type'],
                    market_price = row[price_col],
                    S = row['spot'],
                    K = row['strike'],
                    tau = row['tau'],
                    r = row.get('risk_free_rate', 0.05),
                    q = row.get('div_yield', 0.01),
                    method = method
                )
                ivs[df.index.get_loc(idx)] = iv
            except (ValueError, RuntimeError) as e:
                errors.append({'idx': idx, 'error': str(e)})

        if errors:
            warnings.warn(f"{len(errors)} IV computations failed")
        return pd.Series(ivs, index=df.index, name='computed_iv')

    # -------------------------------------------------------------------------
    # No-Arbitrage Surface Validation
    # -------------------------------------------------------------------------

    def validate_surface(
        self,
        df: pd.DataFrame,
        iv_col: str = 'imputed_iv'
    ) -> Dict:
        """
        Check the constructed surface for no-arbitrage violations.

        Returns
        -------
        dict with keys: butterfly_violations, calendar_violations, total_var_negative, passed
        """
        results = {
            'butterfly_violations': [],
            'calendar_violations': [],
            'total_var_negative': 0,
            'passed': True
        }

        # Compute total variance
        df = df.copy()
        df['total_var'] = df[iv_col]**2 * df['tau']

        # Check total variance positivity
        neg_tv = (df['total_var'] <= 0).sum()
        results['total_var_negative'] = int(neg_tv)
        if neg_tv > 0:
            results['passed'] = False

        # Calendar arbitrage : for each log-moneyness, TV should be non-decreasing in tau
        for x_bin in np.arange(-0.5, 0.5, 0.05):
            sub = df[
                (df['log_moneyness'] >= x_bin - 0.025) &
                (df['log_moneyness'] < x_bin + 0.025) &
                (df[iv_col].notna())
            ].sort_values('tau')
            if len(sub) < 2:
                continue

            tv_vals = sub['total_var'].values
            for i in range(len(tv_vals) - 1):
                if tv_vals[i+1] < tv_vals[i] - 1e-6:
                    results['calendar_violations'].append({
                        'x_bin': x_bin,
                        'tau1': sub['tau'].iloc[i],
                        'tau2': sub['tau'].iloc[i+1],
                        'tv1': tv_vals[i],
                        'tv2': tv_vals[i+1]
                    })
                    results['passed'] = False

        # Butterfly : for each expiry, total variance should be convex in log-moneyness
        for expiry, group in df.groupby('expiry'):
            sub = group[group[iv_col].notna()].sort_values('log_moneyness')
            if len(sub) < 3:
                continue

            x = sub['log_moneyness'].values
            tv = sub['total_var'].values

            # Discrete second derivative
            for i in range(1, len(x) - 1):
                dx1 = x[i] - x[i-1]
                dx2 = x[i+1] - x[i]
                d2w = 2 * (tv[i+1] * dx1 - tv[i] * (dx1 + dx2) + tv[i-1] * dx2) / (dx1 * dx2 * (dx1 + dx2))

                # Gatheral condition approximation (simplified)
                if d2w < -1e-4:
                    results['butterfly_violations'].append({
                        'expiry': expiry,
                        'x': x[i],
                        'd2w': d2w
                    })
                    results['passed'] = False

        return results


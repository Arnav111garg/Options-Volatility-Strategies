"""
Missing Data Handling for Options Chains.
Implements multiple imputation strategies with uncertainty quantification.
"""

import numpy as np
import pandas as pd
from scipy.interpolate import interp1d
from scipy.optimize import minimize, minimize_scalar
from scipy.stats import norm
from typing import Optional, Tuple, Dict, List
import warnings

# Optionally import GP library
try:
    from sklearn.gaussian_process import GaussianProcessRegressor
    from sklearn.gaussian_process.kernels import RBF, WhiteKernel, ConstantKernel, Matern
    HAS_GP = True
except ImportError:
    HAS_GP = False
    warnings.warn("scikit-learn not available; GP imputation disabled")

class OptionsIVImputer:
    """
    Missing implied volatility imputation engine.

    Strategies:
    1. 'linear': Linear interpolation in log-strike space
    2. 'svi': SVI model fit + extrapolation
    3. 'gp': Gaussian Process regression
    4. 'pcpbridge': Use PCP to infer IV from opposite-type option
    5. 'surface': 2D surface interpolation via bivariate spline

    Parameters
    ----------
    strategy : str
        Imputation strategy (default: 'svi')
    min_obs_per_expiry : int
        Minimum observed IV per expiry to fit (default: 3)
    r : float
        Risk-free rate for PCP bridge
    q : float
        Dividend yield for PCP bridge
    """

    def __init__(
        self,
        strategy: str = 'svi',
        min_obs_per_expiry: int = 3,
        r: float = 0.05,
        q: float = 0.01,
    ):
        self.strategy = strategy
        self.min_obs_per_expiry = min_obs_per_expiry
        self.r = r
        self.q = q
        self._svi_params: Dict = {}  # cached per expiry
        self._gp_model: Optional[object] = None

    def impute(
        self,
        df: pd.DataFrame,
        target_grid: Optional[pd.DataFrame] = None
    ) -> pd.DataFrame:
        """
        Impute missing IVs in the options chain.
        """
        df = df.copy()
        df['imputed_iv'] = df['implied_vol'].copy()
        df['imputed_flag'] = False
        df['imputed_std'] = np.nan  # uncertainty estimate

        if self.strategy == 'svi':
            df = self._impute_svi(df)
        elif self.strategy == 'gp':
            df = self._impute_gp(df)
        elif self.strategy == 'pcpbridge':
            df = self._impute_pcp_bridge(df)
        elif self.strategy == 'linear':
            df = self._impute_linear(df)
        elif self.strategy == 'surface':
            df = self._impute_surface_2d(df)
        else:
            raise ValueError(f"Unknown strategy: {self.strategy}")

        n_imputed = df['imputed_flag'].sum()
        print(f"Imputed {n_imputed} missing IVs using strategy = '{self.strategy}'")
        return df

    # -----------------------------------------------------
    # SVI Imputation
    # -----------------------------------------------------
    def _fit_svi_expiry(
        self,
        x_obs: np.ndarray,
        w_obs: np.ndarray
    ) -> Tuple[np.ndarray, float]:
        """
        Fit raw SVI parametrization to observed total variances.
        """
        def svi_func(x, a, b, rho, m, sigma):
            return a + b * (rho * (x - m) + np.sqrt((x - m) ** 2 + sigma ** 2))

        def residuals(params):
            a, b, rho, m, sigma = params
            if b < 0 or sigma <= 0 or abs(rho) >= 1:
                return 1e10
            if a + b * np.sqrt(1 - rho ** 2) * sigma < 0:
                return 1e10
            w_fit = svi_func(x_obs, a, b, rho, m, sigma)
            if np.any(w_fit <= 0):
                return 1e10
            return np.mean((w_fit - w_obs) ** 2)

        # Multiple starting points for robustness
        best_result = None
        best_loss = np.inf

        atm_var = np.interp(0, x_obs, w_obs) if len(x_obs) > 2 else w_obs.mean()

        starts = [
            [atm_var * 0.9, 0.1, -0.3, 0.0, 0.3],
            [atm_var * 0.8, 0.2, -0.5, -0.1, 0.2],
            [atm_var * 0.7, 0.3, -0.1, 0.1, 0.4],
        ]

        for x0 in starts:
            try:
                result = minimize(
                    residuals, x0,
                    method='Nelder-Mead',
                    options={'maxiter': 5000, 'xatol': 1e-8, 'fatol': 1e-10}
                )
                if result.fun < best_loss:
                    best_loss = result.fun
                    best_result = result
            except Exception:
                continue

        if best_result is None:
            return np.array([atm_var, 0.1, -0.3, 0.0, 0.3]), np.inf

        rmse = np.sqrt(best_loss)
        return best_result.x, rmse

    def _svi_w(self, x: np.ndarray, params: np.ndarray) -> np.ndarray:
        """Evaluate SVI total variance."""
        a, b, rho, m, sigma = params
        return a + b * (rho * (x - m) + np.sqrt((x - m) ** 2 + sigma ** 2))

    def _impute_svi(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Fit SVI per expiry slice, impute missing IVs.
        """
        for expiry, group in df.groupby('expiry'):
            tau = group['tau'].iloc[0]
            if tau <= 0:
                continue

            # Get observed IVs
            obs_mask = group['imputed_iv'].notna() & (group['imputed_iv'] > 0)
            obs = group[obs_mask]

            if len(obs) < self.min_obs_per_expiry:
                continue

            # Convert to total variance space
            x_obs = obs['log_moneyness'].values
            iv_obs = obs['imputed_iv'].values
            w_obs = iv_obs ** 2 * tau

            # Fit SVI
            params, rmse = self._fit_svi_expiry(x_obs, w_obs)
            self._svi_params[expiry] = {'params': params, 'rmse': rmse}

            # Impute missing in this expiry
            missing_idx = group.index[group['imputed_iv'].isna()]
            for idx in missing_idx:
                x_miss = df.loc[idx, 'log_moneyness']
                w_imp = self._svi_w(np.array([x_miss]), params)[0]
                if w_imp > 0 and tau > 0:
                    iv_imp = np.sqrt(w_imp / tau)
                    df.loc[idx, 'imputed_iv'] = iv_imp
                    df.loc[idx, 'imputed_flag'] = True
                    df.loc[idx, 'imputed_std'] = rmse / (2 * iv_imp * tau)

        return df

    # -----------------------------------------------------
    # PCP Bridge Imputation
    # -----------------------------------------------------
    def _impute_pcp_bridge(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Use Put-Call Parity to infer missing call IV from put IV and vice versa.
        """
        try:
            from greeks_engine import BlackScholesEngine
        except ImportError:
            # Try relative import if inside a package context
            try:
                from .greeks_engine import BlackScholesEngine
            except ImportError:
                warnings.warn("BlackScholesEngine could not be imported; PCP bridge disabled")
                return df

        bs = BlackScholesEngine()

        for (expiry, strike), group in df.groupby(['expiry', 'strike']):
            calls = group[group['option_type'] == 'call']
            puts = group[group['option_type'] == 'put']
            if calls.empty or puts.empty:
                continue

            c_idx = calls.index[0]
            p_idx = puts.index[0]
            spot = group['spot'].iloc[0]
            tau = group['tau'].iloc[0]

            call_iv = df.loc[c_idx, 'imputed_iv']
            put_iv = df.loc[p_idx, 'imputed_iv']

            if pd.isna(call_iv) == pd.isna(put_iv):
                continue

            # PCP: C - P = e^{-rT}(F - K)
            F = spot * np.exp((self.r - self.q) * tau)
            pcp_value = np.exp(-self.r * tau) * (F - strike)

            if pd.isna(call_iv) and not pd.isna(put_iv):
                p_price = bs.price('put', spot, strike, tau, self.r, self.q, put_iv)
                c_price_implied = p_price + pcp_value
                if c_price_implied > 0:
                    try:
                        c_iv = bs.implied_vol('call', c_price_implied, spot, strike, tau, self.r, self.q)
                        df.loc[c_idx, 'imputed_iv'] = c_iv
                        df.loc[c_idx, 'imputed_flag'] = True
                    except Exception:
                        pass

            elif pd.isna(put_iv) and not pd.isna(call_iv):
                c_price = bs.price('call', spot, strike, tau, self.r, self.q, call_iv)
                p_price_implied = c_price - pcp_value
                if p_price_implied > 0:
                    try:
                        p_iv = bs.implied_vol('put', p_price_implied, spot, strike, tau, self.r, self.q)
                        df.loc[p_idx, 'imputed_iv'] = p_iv
                        df.loc[p_idx, 'imputed_flag'] = True
                    except Exception:
                        pass

        return df

    # -----------------------------------------------------
    # Gaussian Process Imputation
    # -----------------------------------------------------
    def _impute_gp(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        2D Gaussian Process imputation over (log_moneyness, tau) space.
        """
        if not HAS_GP:
            raise ImportError("Install scikit-learn for GP imputation")

        obs_mask = df['imputed_iv'].notna() & (df['imputed_iv'] > 0)
        X_obs = df.loc[obs_mask, ['log_moneyness', 'tau']].values
        y_obs = df.loc[obs_mask, 'imputed_iv'].values

        kernel = (
            ConstantKernel(1.0, (0.1, 10.0)) *
            Matern(length_scale=[0.1, 0.1], nu=2.5, length_scale_bounds=[(0.01, 1.0), (0.01, 1.0)]) +
            WhiteKernel(noise_level=0.0001, noise_level_bounds=(1e-6, 0.01))
        )
        gpr = GaussianProcessRegressor(
            kernel=kernel,
            alpha=1e-6,
            normalize_y=True,
            n_restarts_optimizer=5,
            random_state=42
        )
        gpr.fit(X_obs, y_obs)
        self._gp_model = gpr

        miss_mask = df['imputed_iv'].isna()
        if miss_mask.sum() == 0:
            return df

        X_miss = df.loc[miss_mask, ['log_moneyness', 'tau']].values
        y_pred, y_std = gpr.predict(X_miss, return_std=True)

        df.loc[miss_mask, 'imputed_iv'] = np.maximum(y_pred, 0.01)
        df.loc[miss_mask, 'imputed_flag'] = True
        df.loc[miss_mask, 'imputed_std'] = y_std

        return df

    # -----------------------------------------------------
    # Linear Interpolation (fallback)
    # -----------------------------------------------------
    def _impute_linear(self, df: pd.DataFrame) -> pd.DataFrame:
        """Per-expiry linear interpolation in log-moneyness."""
        for expiry, group in df.groupby('expiry'):
            for opt_type in ['call', 'put']:
                sub = group[group['option_type'] == opt_type].copy()
                sub = sub.sort_values('log_moneyness')

                obs = sub[sub['imputed_iv'].notna()]
                if len(obs) < 2:
                    continue

                f_interp = interp1d(
                    obs['log_moneyness'].values,
                    obs['imputed_iv'].values,
                    kind='linear',
                    bounds_error=False,
                    fill_value='extrapolate'
                )

                miss_idx = sub.index[sub['imputed_iv'].isna()]
                if len(miss_idx) == 0:
                    continue

                x_miss = df.loc[miss_idx, 'log_moneyness'].values
                iv_imp = f_interp(x_miss)
                iv_imp = np.maximum(iv_imp, 0.01)

                df.loc[miss_idx, 'imputed_iv'] = iv_imp
                df.loc[miss_idx, 'imputed_flag'] = True

        return df

    def _impute_surface_2d(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        2D bivariate spline interpolation over the full surface.
        """
        obs_mask = df['imputed_iv'].notna() & (df['imputed_iv'] > 0)
        obs = df[obs_mask].copy()

        if len(obs) < 20:
            warnings.warn("Too few observations for 2D surface imputation")
            return self._impute_linear(df)

        x = obs['log_moneyness'].values
        t = obs['tau'].values
        iv = obs['imputed_iv'].values

        from scipy.interpolate import SmoothBivariateSpline
        try:
            spline = SmoothBivariateSpline(x, t, iv, kx=3, ky=3, s=0.001)
            miss_mask = df['imputed_iv'].isna()
            x_miss = df.loc[miss_mask, 'log_moneyness'].values
            t_miss = df.loc[miss_mask, 'tau'].values

            iv_imp = spline.ev(x_miss, t_miss)
            iv_imp = np.maximum(iv_imp, 0.01)

            df.loc[miss_mask, 'imputed_iv'] = iv_imp
            df.loc[miss_mask, 'imputed_flag'] = True
        except Exception as e:
            warnings.warn(f"2D spline failed: {e}. Falling back to linear.")
            df = self._impute_linear(df)

        return df


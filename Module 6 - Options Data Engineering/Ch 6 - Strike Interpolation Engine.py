"""
Strike Interpolation for Options IV Surfaces.
Implements multiple interpolation schemes with arbitrage checks.
"""

import numpy as np
import pandas as pd
from scipy.interpolate import CubicSpline, PchipInterpolator, UnivariateSpline, interp1d
from scipy.optimize import minimize
from typing import Optional, Literal

class StrikeInterpolator:
    """
    Options strike interpolation engine.

    Supports multiple methods:
    - 'cubic_spline' : Cubic spline in (x, w) space [ recommended ]
    - 'pchip' : Monotone cubic (Fritsch-Carlson) [fast, safe]
    - 'svi' : SVI parametric fit [ most arbitrage-safe ]
    - 'rbf' : Radial basis function [ flexible ]

    All methods operate in (log_moneyness, total_variance) space
    to ensure non-negativity of the implied density.
    """

    def __init__(
        self,
        method: Literal['cubic_spline', 'pchip', 'svi', 'rbf'] = 'pchip',
        extrapolation: Literal['flat', 'svi_wing', 'linear'] = 'svi_wing',
        arbitrage_check: bool = True
    ):
        self.method = method
        self.extrapolation = extrapolation
        self.arbitrage_check = arbitrage_check
        self._interpolators = {}

    def fit_slice(
        self,
        x_obs: np.ndarray,
        iv_obs: np.ndarray,
        tau: float,
        weights: Optional[np.ndarray] = None
    ) -> None:
        """
        Fit interpolator to a single expiry slice.

        Parameters
        ----------
        x_obs : Log-forward-moneyness observations
        iv_obs : Implied volatility observations
        tau : Time to expiry (years)
        weights : Optional inverse-spread weights
        """
        # Sort by moneyness
        sort_idx = np.argsort(x_obs)
        x_obs = x_obs[sort_idx]
        iv_obs = iv_obs[sort_idx]

        # Convert to total variance space
        w_obs = iv_obs**2 * tau

        if weights is not None:
            weights = weights[sort_idx]

        if self.method == 'cubic_spline':
            self._fit_cubic_spline(x_obs, w_obs, tau, weights)
        elif self.method == 'pchip':
            self._fit_pchip(x_obs, w_obs, tau)
        elif self.method == 'svi':
            from .surface_smoothing import SVIFitter
            svi = SVIFitter(use_gatheral_penalty=True)
            svi.fit(x_obs, iv_obs, tau, weights)
            self._interpolators[tau] = {
                'type': 'svi', 'model': svi, 'tau': tau,
                'x_min': x_obs.min(), 'x_max': x_obs.max()
            }
        elif self.method == 'rbf':
            self._fit_rbf(x_obs, w_obs, tau)

    def _fit_cubic_spline(
        self,
        x: np.ndarray, w: np.ndarray, tau: float,
        weights: Optional[np.ndarray]
    ):
        """
        Cubic spline with natural boundary conditions in (x, w) space.

        For extrapolation beyond observed range, fit linear tails
        (wings of the smile) to avoid Runge oscillations.
        """
        # Optional: weighted smoothing spline
        if weights is not None:
            # Smooth spline with tension
            s = max(len(x) * 0.01, 0.001)
            interp = UnivariateSpline(x, w, w=weights, k=3, s=s)
        else:
            interp = CubicSpline(x, w, bc_type='not-a-knot', extrapolate=False)

        # Wing extrapolation using linear fit to last 2 knots on each side
        slope_left = (w[1] - w[0]) / (x[1] - x[0]) if len(x) > 1 else 0
        slope_right = (w[-1] - w[-2]) / (x[-1] - x[-2]) if len(x) > 1 else 0

        self._interpolators[tau] = {
            'type': 'cubic_spline',
            'interp': interp,
            'x_min': x[0], 'x_max': x[-1],
            'w_left': w[0], 'w_right': w[-1],
            'slope_left': max(slope_left, 0),
            'slope_right': max(slope_right, 0),
            'tau': tau
        }

    def _fit_pchip(self, x: np.ndarray, w: np.ndarray, tau: float):
        """
        PCHIP : Piecewise Cubic Hermite Interpolating Polynomial.

        Preserves monotonicity within each interval (no oscillations),
        guaranteed non-negative if w_obs are non-negative.
        """
        interp = PchipInterpolator(x, w, extrapolate=False)
        slope_left = float(interp.derivative()(x[0]))
        slope_right = float(interp.derivative()(x[-1]))

        self._interpolators[tau] = {
            'type': 'pchip',
            'interp': interp,
            'x_min': x[0], 'x_max': x[-1],
            'w_left': w[0], 'w_right': w[-1],
            'slope_left': max(slope_left, 0),
            'slope_right': max(slope_right, 0),
            'tau': tau
        }

    def _fit_rbf(self, x: np.ndarray, w: np.ndarray, tau: float):
        """RBF interpolation using radial basis functions."""
        from scipy.interpolate import RBFInterpolator
        interp = RBFInterpolator(x[:, None], w, kernel='thin_plate_spline')
        self._interpolators[tau] = {
            'type': 'rbf', 'interp': interp, 'tau': tau,
            'x_min': x[0], 'x_max': x[-1],
            'w_left': w[0], 'w_right': w[-1],
            'slope_left': 0.01, 'slope_right': 0.01
        }

    def predict(
        self,
        x_new: np.ndarray,
        tau: float
    ) -> np.ndarray:
        """
        Predict IV at new log-moneyness values for given expiry.

        Parameters
        ----------
        x_new : New log-moneyness values
        tau : Time-to-expiry (must match a fitted slice)

        Returns
        -------
        np.ndarray : Predicted implied volatilities
        """
        if tau not in self._interpolators:
            raise ValueError(f"No interpolator fitted for tau={tau:.4f}")

        interp_info = self._interpolators[tau]
        itype = interp_info['type']
        if itype == 'svi':
            return interp_info['model'].predict(x_new, tau)

        interp = interp_info['interp']
        x_min = interp_info['x_min']
        x_max = interp_info['x_max']
        w_left = interp_info['w_left']
        w_right = interp_info['w_right']
        s_left = interp_info['slope_left']
        s_right = interp_info['slope_right']

        w_new = np.zeros_like(x_new, dtype=float)

        # Interior : use fitted interpolator
        interior = (x_new >= x_min) & (x_new <= x_max)
        if itype == 'rbf':
            w_new[interior] = interp(x_new[interior, None]).ravel()
        else:
            w_new[interior] = interp(x_new[interior])

        # Left wing extrapolation
        left_ext = x_new < x_min
        if left_ext.any():
            if self.extrapolation == 'flat':
                w_new[left_ext] = w_left
            elif self.extrapolation == 'linear':
                w_new[left_ext] = w_left + s_left * (x_new[left_ext] - x_min)
            elif self.extrapolation == 'svi_wing':
                # Linear in variance space (Lee's moment formula compliant)
                w_new[left_ext] = w_left + s_left * (x_new[left_ext] - x_min)

        # Right wing extrapolation
        right_ext = x_new > x_max
        if right_ext.any():
            if self.extrapolation == 'flat':
                w_new[right_ext] = w_right
            else:
                w_new[right_ext] = w_right + s_right * (x_new[right_ext] - x_max)

        # Enforce non-negativity
        w_new = np.maximum(w_new, 1e-8)

        iv_new = np.sqrt(w_new / tau)
        if self.arbitrage_check:
            self._check_smile_arbitrage(x_new, w_new, tau)

        return iv_new

    def _check_smile_arbitrage(
        self,
        x: np.ndarray, w: np.ndarray, tau: float
    ) -> bool:
        """Check discrete convexity in (x, w) space."""
        if len(x) < 3:
            return True

        sort_idx = np.argsort(x)
        x_s = x[sort_idx]
        w_s = w[sort_idx]

        n_violations = 0
        for i in range(1, len(x_s) - 1):
            dx1 = x_s[i] - x_s[i-1]
            dx2 = x_s[i+1] - x_s[i]
            # Convexity check
            w_mid_linear = (w_s[i-1] * dx2 + w_s[i+1] * dx1) / (dx1 + dx2)

            if w_s[i] > w_mid_linear + 1e-4:
                n_violations += 1

        if n_violations > 0:
            import warnings
            warnings.warn(
                f"Potential butterfly violation: {n_violations} points "
                f"non-convex in total variance space"
            )

        return n_violations == 0


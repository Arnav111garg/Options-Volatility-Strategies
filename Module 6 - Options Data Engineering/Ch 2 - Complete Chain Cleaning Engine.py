"""
Options Chain Cleaning Engine
Implements all no-arbitrage and data-quality filters
with detailed diagnostics and audit trail.
"""

import numpy as np
import pandas as pd
from typing import Optional, Tuple, Dict
import logging
from scipy.interpolate import interp1d

logger = logging.getLogger('ChainCleaner')

class ChainCleaner:
    """
    Production-grade options chain cleaner.

    Pipeline:
    1. Schema validation
    2. Price bound filters (zero, negative, inverted)
    3. Intrinsic value filter
    4. Liquidity filter (spread, volume, OI)
    5. Put-call parity check
    6. Duplicate detection and resolution
    7. Moneyness range filter
    8. DTE filter
    9. Summary statistics and audit log
    """

    def __init__(
        self,
        max_spread_pct: float = 0.50,         # Max bid-ask / mid
        min_volume: int = 0,                  # Min daily volume (0 = no filter)
        min_oi: int = 0,                      # Min open interest
        min_dte: int = 1,                     # Min days to expiry
        max_dte: int = 730,                   # Max DTE (2 years)
        min_price: float = 0.05,              # Min option price (cents filter)
        max_pcp_violation: float = 0.02,      # Max PCP violation as % of spot
        min_log_moneyness: float = -0.6,      # Deepest OTM put (ln(K/S) floor)
        max_log_moneyness: float = 0.4,       # Deepest OTM call (ln(K/S) ceiling)
        risk_free_rate: float = 0.05,         # For PCP computation
        div_yield: float = 0.01               # Continuous dividend yield
    ):
        self.max_spread_pct = max_spread_pct
        self.min_volume = min_volume
        self.min_oi = min_oi
        self.min_dte = min_dte
        self.max_dte = max_dte
        self.min_price = min_price
        self.max_pcp_violation = max_pcp_violation
        self.min_log_moneyness = min_log_moneyness
        self.max_log_moneyness = max_log_moneyness
        self.r = risk_free_rate
        self.q = div_yield
        self.audit_log: Dict = {}

    def clean(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Run complete cleaning pipeline.

        Parameters
        ----------
        df : pd.DataFrame
            Raw options chain from data source

        Returns
        -------
        pd.DataFrame
            Cleaned chain with quality flags and audit trail
        """
        n_raw = len(df)
        logger.info(f"Cleaning chain: {n_raw} raw contracts")

        df = df.copy()
        df['_keep'] = True  # master filter flag
        df['_reject_reason'] = ''

        # ---------------------------------------------------
        # Step 1: Schema Validation
        # ---------------------------------------------------
        required_cols = ['spot', 'strike', 'bid', 'ask', 'mid', 'dte', 'tau', 'option_type']
        missing = [c for c in required_cols if c not in df.columns]
        if missing:
            raise ValueError(f"Missing required columns: {missing}")

        # Ensure numeric types
        for col in ['spot', 'strike', 'bid', 'ask', 'mid', 'dte', 'tau']:
            df[col] = pd.to_numeric(df[col], errors='coerce')

        # ---------------------------------------------------
        # Step 2: Zero and NaN Prices
        # ---------------------------------------------------
        mask_nan_price = df['mid'].isna() | (df['mid'] == 0)
        self._apply_filter(df, mask_nan_price, 'zero_or_nan_price')

        # ---------------------------------------------------
        # Step 3: Inverted Spreads
        # ---------------------------------------------------
        mask_inverted = df['bid'] > df['ask']
        self._apply_filter(df, mask_inverted, 'inverted_spread')

        # ---------------------------------------------------
        # Step 4: Price Below Minimum
        # ---------------------------------------------------
        mask_low_price = df['mid'] < self.min_price
        self._apply_filter(df, mask_low_price & df['_keep'], 'price_below_minimum')

        # ---------------------------------------------------
        # Step 5: Intrinsic Value Violations
        # ---------------------------------------------------
        # Forward price
        df['_forward'] = df['spot'] * np.exp((self.r - self.q) * df['tau'])
        df['_intrinsic_call'] = np.maximum(df['_forward'] * np.exp(-self.r * df['tau']) - df['strike'] * np.exp(-self.r * df['tau']), 0)
        df['_intrinsic_put'] = np.maximum(df['strike'] * np.exp(-self.r * df['tau']) - df['_forward'] * np.exp(-self.r * df['tau']), 0)

        call_mask = (df['option_type'] == 'call') & (df['mid'] < df['_intrinsic_call'] - 0.01) & df['_keep']
        put_mask = (df['option_type'] == 'put') & (df['mid'] < df['_intrinsic_put'] - 0.01) & df['_keep']

        self._apply_filter(df, call_mask, 'below_intrinsic_call')
        self._apply_filter(df, put_mask, 'below_intrinsic_put')

        # ---------------------------------------------------
        # Step 6: Liquidity Filters
        # ---------------------------------------------------
        df['_spread_pct'] = (df['ask'] - df['bid']) / df['mid'].replace(0, np.nan)

        mask_wide_spread = (df['_spread_pct'] > self.max_spread_pct) & df['_keep']
        self._apply_filter(df, mask_wide_spread, 'spread_too_wide')

        if self.min_volume > 0:
            mask_vol = (df['volume'] < self.min_volume) & df['_keep']
            self._apply_filter(df, mask_vol, 'volume_too_low')

        if self.min_oi > 0:
            mask_oi = (df['open_interest'] < self.min_oi) & df['_keep']
            self._apply_filter(df, mask_oi, 'open_interest_too_low')

        # ---------------------------------------------------
        # Step 7: DTE Filter
        # ---------------------------------------------------
        mask_dte = ((df['dte'] < self.min_dte) | (df['dte'] > self.max_dte)) & df['_keep']
        self._apply_filter(df, mask_dte, 'dte_out_of_range')

        # ---------------------------------------------------
        # Step 8: Moneyness Range Filter
        # ---------------------------------------------------
        df['_log_m'] = np.log(df['strike'] / df['spot'])
        mask_moneyness = ((df['_log_m'] < self.min_log_moneyness) | (df['_log_m'] > self.max_log_moneyness)) & df['_keep']
        self._apply_filter(df, mask_moneyness, 'moneyness_out_of_range')

        # ---------------------------------------------------
        # Step 9: Put-Call Parity Check
        # ---------------------------------------------------
        df = self._check_put_call_parity(df)

        # ---------------------------------------------------
        # Step 10: Duplicate Removal
        # ---------------------------------------------------
        df = self._remove_duplicates(df)

        # ---------------------------------------------------
        # Final: Audit Summary
        # ---------------------------------------------------
        clean_df = df[df['_keep']].copy()
        n_clean = len(clean_df)

        # Remove internal columns
        internal_cols = [c for c in clean_df.columns if c.startswith('_')]
        clean_df = clean_df.drop(columns=internal_cols)

        self.audit_log = {
            'n_raw': n_raw,
            'n_clean': n_clean,
            'n_removed': n_raw - n_clean,
            'removal_rate': (n_raw - n_clean) / n_raw if n_raw > 0 else 0,
            'rejection_counts': df[~df['_keep']]['_reject_reason'].value_counts().to_dict()
        }

        logger.info(f"Cleaning complete: {n_clean}/{n_raw} contracts retained ({(100*(n_raw - n_clean)/n_raw) if n_raw > 0 else 0:.1f}% removed)")
        for reason, count in self.audit_log['rejection_counts'].items():
            logger.info(f"Rejected ({reason}): {count}")

        return clean_df

    def _apply_filter(self, df: pd.DataFrame, mask: pd.Series, reason: str):
        """Apply a boolean rejection mask and record reason."""
        newly_rejected = mask & df['_keep']
        df.loc[newly_rejected, '_keep'] = False
        df.loc[newly_rejected, '_reject_reason'] = reason
        n = newly_rejected.sum()
        if n > 0:
            logger.debug(f"Rejected {n} contracts: {reason}")

    def _check_put_call_parity(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Check put-call parity for all (strike, expiry) pairs.
        PCP: C - P = e^{-rT}(F - K)
        Tolerance: max_pcp_violation * spot
        """
        df = df.copy()
        df['_pcp_violation'] = 0.0
        pcp_violations = []

        # Group by dte and strike
        for (dte, strike), group in df[df['_keep']].groupby(['dte', 'strike']):
            calls = group[group['option_type'] == 'call']
            puts = group[group['option_type'] == 'put']

            if calls.empty or puts.empty:
                continue

            c_mid = calls['mid'].values[0]
            p_mid = puts['mid'].values[0]
            tau = calls['tau'].values[0]
            spot = calls['spot'].values[0]

            # Forward price
            F = spot * np.exp((self.r - self.q) * tau)
            K = strike

            # PCP value
            pcp_theoretical = np.exp(-self.r * tau) * (F - K)
            pcp_observed = c_mid - p_mid
            violation = abs(pcp_observed - pcp_theoretical)
            if violation > self.max_pcp_violation * spot:
                pcp_violations.append({
                    'dte': dte,
                    'strike': strike,
                    'violation': violation,
                    'pcp_theoretical': pcp_theoretical,
                    'pcp_observed': pcp_observed
                })

        if pcp_violations:
            logger.warning(f"Found {len(pcp_violations)} PCP violations (> {self.max_pcp_violation*100:.0f}% of spot)")

        self.audit_log['pcp_violations'] = pcp_violations
        return df

    def _remove_duplicates(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Remove duplicate (dte, strike, option_type) entries.
        When duplicates exist, keep the one with tighter spread.
        """
        key_cols = ['dte', 'strike', 'option_type']
        if 'spread' not in df.columns:
            df['spread'] = df['ask'] - df['bid']

        dupes = df.duplicated(subset=key_cols, keep=False)

        if dupes.sum() > 0:
            logger.warning(f"Found {dupes.sum()} duplicate records")
            df = df.sort_values('spread').drop_duplicates(subset=key_cols, keep='first')

        return df

    def generate_report(self) -> str:
        """Generate human-readable cleaning report."""
        report = ["=" * 60, " OPTIONS CHAIN CLEANING REPORT ", "=" * 60]
        report.append(f"Raw contracts: {self.audit_log.get('n_raw', 'N/A')}")
        report.append(f"Clean contracts: {self.audit_log.get('n_clean', 'N/A')}")
        removal_rate = self.audit_log.get('removal_rate', 0)
        report.append(f"Removal rate: {removal_rate * 100:.1f}%")
        report.append("\nRejection Breakdown:")
        for reason, count in self.audit_log.get('rejection_counts', {}).items():
            report.append(f" {reason:30s}: {count:5d}")
        pcp_v = self.audit_log.get('pcp_violations', [])
        report.append(f"\nPCP Violations: {len(pcp_v)}")
        return "\n".join(report)


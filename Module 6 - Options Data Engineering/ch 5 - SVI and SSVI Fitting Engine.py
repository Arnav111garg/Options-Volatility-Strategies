"""
Volatility Surface Smoothing Engine.
Implements SVI, SSVI, and B-spline smoothing methods.
"""

import numpy as np
import pandas as pd
from scipy.optimize import minimize, differential_evolution
from scipy.interpolate import UnivariateSpline
from typing import Optional, Dict, Tuple, List
import warnings

class SVIFitter:
    """
    Fit the Stochastic Volatility Inspired (SVI) model to a volatility smile.

    Uses differential evolution for global optimization, followed by
    Nelder-Mead for local refinement. Enforces no-arbitrage constraints.

    Parameters
    ----------
    use_gatheral_penalty : bool
        Whether to add Gatheral's density positivity penalty
    n_eval_points : int
        Number of points to evaluate Gatheral condition
    """

    def __init__(
        self,
        use_gatheral_penalty: bool = True,
        n_eval_points: int = 100
    ):
        self.use_gatheral_penalty = use_gatheral_penalty
        self.n_eval_points = n_eval_points
        self._params: Optional[np.ndarray] = None
        self._fit_quality: Dict = {}

    @staticmethod
    def w_svi(x: np.ndarray, params: np.ndarray) -> np.ndarray:
        """Evaluate SVI total variance."""
        a, b, rho, m, sigma = params
        return a + b * (rho * (x - m) + np.sqrt((x - m) ** 2 + sigma ** 2))

    @staticmethod
    def dw_dx(x: np.ndarray, params: np.ndarray) -> np.ndarray:
        """First derivative of SVI w.r.t. x."""
        a, b, rho, m, sigma = params
        z = np.sqrt((x - m) ** 2 + sigma ** 2)
        return b * (rho + (x - m) / z)

    @staticmethod
    def d2w_dx2(x: np.ndarray, params: np.ndarray) -> np.ndarray:
        """Second derivative of SVI w.r.t. x."""
        a, b, rho, m, sigma = params
        z = np.sqrt((x - m) ** 2 + sigma ** 2)
        return b * sigma ** 2 / z ** 3

    def gatheral_g(self, x: np.ndarray, params: np.ndarray) -> np.ndarray:
        """
        Compute Gatheral's density function g(x).
        g >= 0 is required for no-butterfly arbitrage.
        """
        w = self.w_svi(x, params)
        w1 = self.dw_dx(x, params)
        w2 = self.d2w_dx2(x, params)

        term1 = (1 - x * w1 / (2 * w)) ** 2
        term2 = (w1 ** 2 / 4) * (1 / w + 1 / 4)
        term3 = w2 / 2

        return term1 - term2 + term3

    def fit(
        self,
        x_obs: np.ndarray,
        iv_obs: np.ndarray,
        tau: float,
        weights: Optional[np.ndarray] = None
    ) -> np.ndarray:
        """
        Fit SVI to observed (x, IV) pairs for a single expiry slice.
        """
        w_obs = iv_obs ** 2 * tau

        if weights is None:
            weights = np.ones(len(x_obs))
            weights = weights / weights.sum()

        def objective(params):
            a, b, rho, m, sigma = params

            # Hard constraints
            if b < 0 or sigma <= 0 or abs(rho) >= 0.9999:
                return 1e15
            if a + b * np.sqrt(1 - rho ** 2) * sigma < 0:
                return 1e15

            w_fit = self.w_svi(x_obs, params)

            if np.any(w_fit <= 0):
                return 1e15

            # Weighted squared error in total variance space
            loss = np.sum(weights * (w_fit - w_obs) ** 2)

            # Gatheral penalty
            if self.use_gatheral_penalty:
                x_eval = np.linspace(x_obs.min() - 0.1, x_obs.max() + 0.1, self.n_eval_points)
                g = self.gatheral_g(x_eval, params)
                penalty = 1e4 * np.sum(np.maximum(-g, 0) ** 2)
                loss += penalty

            return loss

        # Bounds for differential evolution
        atm_w = np.interp(0, x_obs, w_obs) if len(x_obs) > 2 else w_obs.mean()
        bounds = [
            (0.0, 2 * atm_w),  # a
            (0.001, 2.0),     # b
            (-0.9999, 0.9999), # rho
            (-0.5, 0.5),       # m
            (0.001, 1.0)       # sigma
        ]

        # Global search: differential evolution
        de_result = differential_evolution(
            objective, bounds,
            seed=42, maxiter=500, tol=1e-10,
            mutation=(0.5, 1), recombination=0.7,
            popsize=20, workers=1
        )

        # Local refinement: Nelder-Mead
        nm_result = minimize(
            objective, de_result.x,
            method='Nelder-Mead',
            options={'maxiter': 10000, 'xatol': 1e-12, 'fatol': 1e-14}
        )

        best_params = nm_result.x

        # Compute fit quality
        w_fit = self.w_svi(x_obs, best_params)
        iv_fit = np.sqrt(np.maximum(w_fit / tau, 0))
        rmse_iv = np.sqrt(np.mean((iv_fit - iv_obs) ** 2))

        # Check arbitrage
        x_eval = np.linspace(x_obs.min() - 0.5, x_obs.max() + 0.5, 200)
        g_vals = self.gatheral_g(x_eval, best_params)
        butterfly_ok = np.all(g_vals >= -1e-6)

        self._params = best_params
        self._fit_quality = {
            'rmse_iv': rmse_iv,
            'butterfly_free': butterfly_ok,
            'min_g': float(g_vals.min()),
            'n_obs': len(x_obs)
        }

        return best_params

    def predict(self, x_new: np.ndarray, tau: float) -> np.ndarray:
        """Predict IV at new moneyness values."""
        if self._params is None:
            raise RuntimeError("Must fit before predicting")
        w_new = self.w_svi(x_new, self._params)
        w_new = np.maximum(w_new, 1e-8)
        return np.sqrt(w_new / tau)


class SSVIFitter:
    """
    Surface SVI (SSVI) fitter guarantees joint calendar-arbitrage freedom.

    Reference: Gatheral, J. & Jacquier, A. (2014).
    'Arbitrage-free SVI volatility surfaces.'
    Quantitative Finance, 14(1), 59-71.
    """

    def __init__(self, phi_type: str = 'power_law'):
        self.phi_type = phi_type
        self._params: Dict = {}

    def phi(self, theta: np.ndarray, eta: float, gamma: float) -> np.ndarray:
        """Power-law correlation function."""
        if self.phi_type == 'power_law':
            return eta / (theta ** gamma * (1 + theta) ** (1 - gamma))
        elif self.phi_type == 'heston_like':
            return eta / (theta * (1 + theta))
        else:
            raise ValueError(f"Unknown phi_type: {self.phi_type}")

    def w_ssvi(
        self,
        x: np.ndarray,
        theta: float,
        eta: float, gamma: float, rho: float
    ) -> np.ndarray:
        """Evaluate SSVI total variance at single expiry."""
        phi_val = self.phi(np.array([theta]), eta, gamma)[0]
        inner = phi_val * x + rho
        return theta / 2 * (1 + rho * phi_val * x + np.sqrt(inner ** 2 + 1 - rho ** 2))

    def fit_joint(
        self,
        surface_data: pd.DataFrame,
        iv_col: str = 'imputed_iv'
    ) -> Dict:
        """
        Fit SSVI to entire surface jointly.
        """
        df = surface_data[surface_data[iv_col].notna()].copy()

        # Step 1: Fit ATM total variance term structure
        atm_data = df[df['log_moneyness'].abs() < 0.05].copy()
        if len(atm_data) < 3:
            atm_data = df[df['log_moneyness'].abs() < 0.10].copy()

        tau_vals = atm_data['tau'].values
        theta_atm = (atm_data[iv_col].values ** 2) * tau_vals

        def log_atm_residuals(log_params):
            log_alpha, log_beta = log_params
            alpha, beta = np.exp(log_alpha), np.exp(log_beta)
            theta_fit = alpha * tau_vals ** beta
            return np.mean((np.log(theta_fit) - np.log(theta_atm + 1e-8)) ** 2)

        atm_res = minimize(
            log_atm_residuals, [np.log(0.04), np.log(0.8)],
            method='Nelder-Mead',
            options={'maxiter': 5000}
        )
        alpha_atm = np.exp(atm_res.x[0])
        beta_atm = np.exp(atm_res.x[1])

        def theta_func(tau):
            return alpha_atm * tau ** beta_atm

        # Step 2: Fit global SSVI parameters (eta, gamma, rho)
        x_obs = df['log_moneyness'].values
        tau_obs = df['tau'].values
        iv_obs = df[iv_col].values
        w_obs = iv_obs ** 2 * tau_obs
        theta_ev = theta_func(tau_obs)

        def ssvi_objective(params):
            eta, gamma, rho = params
            if eta <= 0 or gamma <= 0 or gamma > 0.5 or abs(rho) >= 0.9999:
                return 1e15

            phi_vals = self.phi(theta_ev, eta, gamma)

            # No-arbitrage constraints
            if np.any(phi_vals * theta_ev >= 4):
                return 1e15
            if np.any(phi_vals * np.sqrt(1 - rho ** 2) >= 1):
                return 1e15

            inner = phi_vals * x_obs + rho
            w_fit = theta_ev / 2 * (1 + rho * phi_vals * x_obs + np.sqrt(inner ** 2 + 1 - rho ** 2))

            if np.any(w_fit <= 0):
                return 1e15

            return np.mean((w_fit - w_obs) ** 2)

        # Optimize
        bounds_ssvi = [(0.01, 5.0), (0.01, 0.499), (-0.9999, 0.9999)]
        de_res = differential_evolution(
            ssvi_objective, bounds_ssvi, seed=42,
            maxiter=1000, tol=1e-12, popsize=20
        )
        nm_res = minimize(
            ssvi_objective, de_res.x,
            method='Nelder-Mead',
            options={'maxiter': 10000, 'xatol': 1e-12}
        )

        eta, gamma, rho = nm_res.x

        # Compute RMSE
        phi_fit = self.phi(theta_ev, eta, gamma)
        inner = phi_fit * x_obs + rho
        w_fit = theta_ev / 2 * (1 + rho * phi_fit * x_obs + np.sqrt(inner ** 2 + 1 - rho ** 2))
        iv_fit = np.sqrt(np.maximum(w_fit / tau_obs, 0))
        rmse = np.sqrt(np.mean((iv_fit - iv_obs) ** 2))

        self._params = {
            'eta': eta, 'gamma': gamma, 'rho': rho,
            'alpha_atm': alpha_atm, 'beta_atm': beta_atm
        }

        return {
            'params': self._params,
            'rmse': rmse,
            'calendar_arb_free': True  # by construction
        }

    def predict_surface(
        self,
        x_grid: np.ndarray,
        tau_grid: np.ndarray,
    ) -> np.ndarray:
        """
        Predict IV on a regular (x, tau) grid.
        """
        if not self._params:
            raise RuntimeError("Must fit before predicting")

        p = self._params
        IV_surface = np.zeros((len(x_grid), len(tau_grid)))

        for j, tau in enumerate(tau_grid):
            theta = p['alpha_atm'] * tau ** p['beta_atm']
            phi_val = self.phi(np.array([theta]), p['eta'], p['gamma'])[0]

            for i, x in enumerate(x_grid):
                inner = phi_val * x + p['rho']
                w = theta / 2 * (1 + p['rho'] * phi_val * x + np.sqrt(inner ** 2 + 1 - p['rho'] ** 2))
                IV_surface[i, j] = np.sqrt(max(w / tau, 0))

        return IV_surface


class OptionsDataPipeline:
    """
    End-to-end pipeline orchestrator.
    """

    def __init__(
        self,
        store: 'SurfaceStore',
        db: OptionsResearchDB,
        data_version: str = 'v1.0'
    ):
        self.store = store
        self.db = db
        self.data_version = data_version

        from .chain_cleaner import ChainCleaner
        from .missing_data import OptionsIVImputer
        from .iv_surface import BlackScholesEngine
        from .surface_smoothing import SVIFitter
        from .greeks_engine import GreeksEngine
        from .strike_interpolation import StrikeInterpolator
        from .expiry_interpolation import ExpiryInterpolator

        self.cleaner = ChainCleaner()
        self.imputer = OptionsIVImputer(strategy='svi')
        self.bs_engine = BlackScholesEngine()
        self.svi_fitter = SVIFitter(use_gatheral_penalty=True)
        self.greeks_eng = GreeksEngine()
        self.strike_interp = StrikeInterpolator(method='pchip')
        self.expiry_interp = ExpiryInterpolator()

    def run_date(
        self,
        raw_chain: pd.DataFrame,
        ticker: str,
        date: str,
        r: float = 0.05,
        q: float = 0.01
    ) -> Dict:
        logger.info(f"Pipeline: {ticker} | {date}")
        results = {}

        self.store.write_raw_chain(raw_chain, ticker, date)

        clean_chain = self.cleaner.clean(raw_chain)
        results['cleaning_report'] = self.cleaner.audit_log

        iv_series = self.bs_engine.compute_iv_surface(clean_chain)
        clean_chain['computed_iv'] = iv_series
        clean_chain['implied_vol'] = clean_chain['implied_vol'].fillna(
            clean_chain['computed_iv']
        )

        clean_chain = self.imputer.impute(clean_chain)
        clean_chain['implied_vol'] = clean_chain['imputed_iv']

        svi_params_by_expiry = {}
        for expiry, group in clean_chain.groupby('expiry'):
            obs = group[group['implied_vol'].notna()]
            if len(obs) < 4:
                continue
            tau = obs['tau'].iloc[0]
            x_obs = obs['log_moneyness'].values
            iv_obs = obs['implied_vol'].values
            weights = 1.0 / (obs['spread_pct'].values + 0.01)
            try:
                params = self.svi_fitter.fit(x_obs, iv_obs, tau, weights)
                svi_params_by_expiry[expiry] = {
                    'a': params[0], 'b': params[1], 'rho': params[2],
                    'm': params[3], 'sigma': params[4], 'tau': tau,
                    'rmse': float(self.svi_fitter._fit_quality.get('rmse_iv', np.nan))
                }
            except Exception as e:
                logger.warning(f"SVI failed for expiry {expiry}: {e}")

        self.store.write_surface_parametric(ticker, date, svi_params_by_expiry)
        iv_surface = self.store.reconstruct_surface_from_svi(ticker, date)

        clean_chain = self.greeks_eng.compute_chain(
            clean_chain, iv_col='implied_vol', r=r, q=q
        )

        self.db.load_surface(iv_surface, ticker=ticker, data_version=self.data_version)
        self.db.compute_and_load_metrics(ticker, dates=[date])

        results['n_contracts'] = len(clean_chain)
        results['n_expiries'] = len(svi_params_by_expiry)
        results['surface_size'] = len(iv_surface)

        logger.info(f"Pipeline complete: {ticker}|{date} | {len(svi_params_by_expiry)} expiries fitted")
        return results


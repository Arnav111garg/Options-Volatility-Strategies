class CBOEDataReader:
    """
    Reader for CBOE's free historical options data files.
    CBOE publishes SPX, VIX options data in CSV format.
    """
    COLUMN_MAP = {
        'Quote_Date': 'date',
        'Underlying': 'ticker',
        'Underlying_Last': 'spot',
        'Type': 'option_type',
        'Expiration': 'expiry',
        'Strike': 'strike',
        'Bid': 'bid',
        'Ask': 'ask',
        'Last': 'last',
        'Volume': 'volume',
        'Open_Interest': 'open_interest',
        'IV': 'implied_vol',
        'Delta': 'delta',
        'Gamma': 'gamma',
        'Theta': 'theta',
        'Vega': 'vega',
    }

    def read(self, filepath: str) -> pd.DataFrame:
        """
        Read CBOE EOD data file.
        """
        df = pd.read_csv(filepath, parse_dates=['Quote_Date', 'Expiration'])
        df = df.rename(columns=self.COLUMN_MAP)

        # Standardize types
        df['option_type'] = df['option_type'].str.lower().map(
            {'c': 'call', 'p': 'put', 'call': 'call', 'put': 'put'}
        )
        df['date'] = pd.to_datetime(df['date']).dt.strftime('%Y-%m-%d')
        df['expiry'] = pd.to_datetime(df['expiry']).dt.strftime('%Y-%m-%d')

        # Compute derived fields
        df['dte'] = (pd.to_datetime(df['expiry']) - pd.to_datetime(df['date'])).dt.days
        df['tau'] = df['dte'] / 365.0
        df['mid'] = (df['bid'] + df['ask']) / 2.0
        df['spread'] = df['ask'] - df['bid']
        df['log_moneyness'] = np.log(df['strike'] / df['spot'])
        logger.info(f"Loaded {len(df)} contracts from {filepath}")
        return df
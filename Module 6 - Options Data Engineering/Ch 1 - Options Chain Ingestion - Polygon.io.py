@dataclass
class OptionContract:
    """
    Strongly-typed representation of a single option contract quote.
    Schema validation is enforced at construction.
    """
    ticker: str          # Underlying symbol
    expiry: str          # YYYY-MM-DD
    strike: float        # Strike price
    option_type: str     # 'call' or 'put'
    bid: float
    ask: float
    last: float
    volume: int
    open_interest: int
    implied_vol: float   # May be NaN if illiquid
    delta: Optional[float] = None
    gamma: Optional[float] = None
    theta: Optional[float] = None
    vega: Optional[float] = None
    timestamp: Optional[str] = None

    def __post_init__(self):
        """Validate fields on construction."""
        assert self.option_type in ('call', 'put'), f"Invalid option_type: {self.option_type}"
        assert self.strike > 0, f"Strike must be positive: {self.strike}"
        assert self.bid >= 0, f"Bid cannot be negative: {self.bid}"
        assert self.ask >= self.bid, f"Ask {self.ask} < Bid {self.bid}: inverted spread"

    @property
    def mid(self) -> float:
        """Mid-market price."""
        return (self.bid + self.ask) / 2.0

    @property
    def spread(self) -> float:
        """Bid-ask spread."""
        return self.ask - self.bid

    @property
    def spread_pct(self) -> float:
        """Spread as percentage of mid."""
        return self.spread / self.mid if self.mid > 0 else np.nan

class PolygonOptionsIngestor:
    """
    Production-grade Polygon.io options data ingestor.

    Features:
    - Automatic pagination handling
    - Exponential backoff retry
    - Rate limit compliance (5 calls / min on Starter)
    - Schema validation
    - Dividend / rate injection

    Usage:
    ingestor = PolygonOptionsIngestor(api_key=POLYGON_KEY)
    chain = ingestor.fetch_chain('SPY', date='2024-01-15')
    """
    BASE_URL = "https://api.polygon.io/v3/snapshot/options"
    RATE_LIMIT_DELAY = 0.15  # seconds between calls (free tier)
    MAX_RETRIES = 5
    RETRY_BACKOFF = 2.0      # exponential base

    def __init__(self, api_key: str, tier: str = 'starter'):
        self.api_key = api_key
        self.tier = tier
        self._session = requests.Session()
        self._session.headers.update({
            'Authorization': f'Bearer {api_key}',
            'Accept': 'application/json'
        })
        self._call_times: List[float] = []

    def _rate_limit(self):
        """Enforce API rate limits."""
        now = time.time()
        self._call_times = [t for t in self._call_times if now - t < 60]
        if len(self._call_times) >= 5 and self.tier == 'starter':
            sleep_time = 60 - (now - self._call_times[0]) + 0.1
            logger.info(f"Rate limit: sleeping {sleep_time:.2f}s")
            time.sleep(sleep_time)
        self._call_times.append(time.time())

    def _get(self, url: str, params: Dict) -> Dict:
        """GET with retry and exponential backoff."""
        for attempt in range(self.MAX_RETRIES):
            self._rate_limit()
            try:
                resp = self._session.get(url, params=params, timeout=30)
                if resp.status_code == 429:
                    wait = self.RETRY_BACKOFF ** attempt
                    logger.warning(f"Rate limited. Waiting {wait}s")
                    time.sleep(wait)
                    continue
                resp.raise_for_status()
                return resp.json()
            except requests.RequestException as e:
                if attempt == self.MAX_RETRIES - 1:
                    raise
                wait = self.RETRY_BACKOFF ** attempt
                logger.warning(f"Attempt {attempt + 1} failed: {e}. Retry in {wait}s")
                time.sleep(wait)
        raise RuntimeError(f"Failed after {self.MAX_RETRIES} attempts")

    def fetch_chain(
        self,
        ticker: str,
        date: Optional[str] = None,
        min_dte: int = 1,
        max_dte: int = 365,
        min_strike_pct: float = 0.7,
        max_strike_pct: float = 1.4,
    ) -> pd.DataFrame:
        """
        Fetch complete options chain for a given ticker.
        """
        if date is None:
            date = datetime.today().strftime('%Y-%m-%d')

        # First, get spot price for strike bounds
        spot = self._get_spot_price(ticker, date)
        logger.info(f"Fetching {ticker} chain | date={date} | spot=${spot:.2f}")

        min_strike = spot * min_strike_pct
        max_strike = spot * max_strike_pct

        # Compute expiry bounds
        date_dt = datetime.strptime(date, '%Y-%m-%d')
        exp_from = (date_dt + timedelta(days=min_dte)).strftime('%Y-%m-%d')
        exp_to = (date_dt + timedelta(days=max_dte)).strftime('%Y-%m-%d')

        all_results = []
        cursor = None

        while True:
            params = {
                'expiration_date.gte': exp_from,
                'expiration_date.lte': exp_to,
                'strike_price.gte': min_strike,
                'strike_price.lte': max_strike,
                'limit': 250,
                'sort': 'expiration_date',
            }
            if cursor:
                params['cursor'] = cursor

            url = f"{self.BASE_URL}/{ticker}"
            data = self._get(url, params)
            results = data.get('results', [])
            all_results.extend(results)

            # Pagination
            cursor = data.get('next_cursor')
            if not cursor:
                break

        logger.info(f"Fetched {len(all_results)} contracts for {ticker}")
        return self._parse_results(all_results, spot, date)

    def _parse_results(self, results: List[Dict], spot: float, date: str) -> pd.DataFrame:
        """Parse raw API results into structured DataFrame."""
        records = []
        for r in results:
            det = r.get('details', {})
            greeks = r.get('greeks', {})
            quote = r.get('day', {})
            iv = r.get('implied_volatility', np.nan)

            # Convert DTE
            expiry = det.get('expiration_date', '')
            if expiry:
                dte = (datetime.strptime(expiry, '%Y-%m-%d') - datetime.strptime(date, '%Y-%m-%d')).days
            else:
                dte = np.nan

            record = {
                'date': date,
                'ticker': det.get('ticker', ''),
                'underlying': det.get('underlying_ticker', ''),
                'option_type': det.get('contract_type', '').lower(),
                'expiry': expiry,
                'dte': dte,
                'strike': det.get('strike_price', np.nan),
                'spot': spot,
                'bid': r.get('last_quote', {}).get('bid', np.nan),
                'ask': r.get('last_quote', {}).get('ask', np.nan),
                'last': r.get('last_trade', {}).get('price', np.nan),
                'volume': quote.get('volume', 0),
                'open_interest': r.get('open_interest', 0),
                'implied_vol': iv if iv else np.nan,
                'delta': greeks.get('delta', np.nan),
                'gamma': greeks.get('gamma', np.nan),
                'theta': greeks.get('theta', np.nan),
                'vega': greeks.get('vega', np.nan),
                'log_moneyness': np.log(det.get('strike_price', np.nan) / spot) if spot > 0 else np.nan,
            }
            records.append(record)

        df = pd.DataFrame(records)
        df['tau'] = df['dte'] / 365.0  # Time to expiry in years
        df['mid'] = (df['bid'] + df['ask']) / 2.0
        df['spread'] = df['ask'] - df['bid']
        df['spread_pct'] = df['spread'] / df['mid'].replace(0, np.nan)
        return df

    def _get_spot_price(self, ticker: str, date: str) -> float:
        """Fetch closing price of underlying on given date."""
        url = f"https://api.polygon.io/v2/aggs/ticker/{ticker}/range/1/day/{date}/{date}"
        data = self._get(url, {'adjusted': 'true'})
        results = data.get('results', [])
        if not results:
            raise ValueError(f"No price data for {ticker} on {date}")
        return results[0]['c']  # closing price


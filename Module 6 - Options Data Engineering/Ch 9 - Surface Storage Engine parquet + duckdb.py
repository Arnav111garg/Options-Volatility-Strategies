"""
Options Surface Storage Design .
Implements the three-layer storage architecture with :
- Raw archive : Parquet + Snappy compression
- Surface store : Parametric (SVI) + dense grid Parquet
- Research DB: DuckDB for analytical queries
"""

import os
import json
import numpy as np
import pandas as pd
import pyarrow as pa
import pyarrow.parquet as pq
from pathlib import Path
from datetime import datetime
from typing import Optional, Dict, List, Union, Tuple
import logging

try:
    import duckdb
    HAS_DUCKDB = True
except ImportError:
    HAS_DUCKDB = False

logger = logging.getLogger('SurfaceStorage')


class SurfaceStore:
    """
    Production options surface storage engine .

    Directory structure :
    { root }/
        raw/
            { ticker }/
                { year }/
                    { date }. parquet <- raw quotes
        surfaces /
            parametric /
                { ticker }/
                    { year }/
                        { date }. json <- SVI params per expiry
            grid /
                { ticker }/
                    { year }/
                        { date }. parquet <- dense IV grid
        research /
            options_research . duckdb <- analytical database
        metadata /
            tickers . json
            data_versions . json
    """

    # Standard grid specification for dense surface storage
    STANDARD_X_GRID = np.linspace(-0.5, 0.5, 51)  # log - moneyness
    STANDARD_TAU_GRID = np.array([  # DTE in years
        7/365, 14/365, 21/365, 30/365, 45/365,
        60/365, 90/365, 120/365, 180/365,
        270/365, 365/365, 730/365
    ])

    def __init__(self, root_dir : str):
        self.root = Path(root_dir)
        self._setup_directories()
        self._db : Optional[object] = None

    def _setup_directories(self):
        """ Create directory structure ."""
        for subdir in ['raw', 'surfaces/parametric', 'surfaces/grid', 'research', 'metadata']:
            (self.root / subdir).mkdir(parents=True, exist_ok=True)

    # -------------------------------------------------------------------------
    # Layer 1: Raw Quote Archive
    # -------------------------------------------------------------------------
    def write_raw_chain(
        self,
        df : pd.DataFrame,
        ticker : str,
        date : str,
        overwrite : bool = False
    ) -> Path:
        """
        Write raw options chain to Parquet archive .

        Parameters
        ----------
        df : pd.DataFrame
            Raw chain data
        ticker : str
            Underlying ticker
        date : str
            Date string (YYYY-MM-DD)
        overwrite : bool
            Whether to overwrite existing file

        Returns
        -------
        Path : Path to written file
        """
        year = date[:4]
        path = self.root / 'raw' / ticker / year / f"{date}.parquet"
        path.parent.mkdir(parents=True, exist_ok=True)

        if path.exists() and not overwrite:
            logger.info(f"Raw chain already exists: {path}")
            return path

        # Optimize schema for compression
        df = df.copy()
        df['date'] = pd.to_datetime(date)

        # Use PyArrow for fine-grained compression control
        table = pa.Table.from_pandas(df)
        pq.write_table(
            table, path,
            compression='snappy',          # Fast decompression
            row_group_size=50000,          # Optimize for sequential scans
            use_dictionary=True,           # Dict-encode string columns
            write_statistics=True          # Enable predicate pushdown
        )

        logger.info(f"Written raw chain: {path} ({os.path.getsize(path)/1e6:.1f}MB)")
        return path

    def read_raw_chain(
        self,
        ticker : str,
        date : str,
        columns : Optional[List[str]] = None,
        filters : Optional[List] = None
    ) -> pd.DataFrame:
        """
        Read raw chain with optional column and row filtering .

        Parameters
        ----------
        ticker : str
        date : str (YYYY-MM-DD)
        columns : Optional list of columns to read (None = all)
        filters : Optional PyArrow predicate filters for row pruning

        Returns
        -------
        pd.DataFrame
        """
        year = date[:4]
        path = self.root / 'raw' / ticker / year / f"{date}.parquet"

        if not path.exists():
            raise FileNotFoundError(f"No raw chain for {ticker} on {date}")

        table = pq.read_table(path, columns=columns, filters=filters)
        return table.to_pandas()

    # -------------------------------------------------------------------------
    # Layer 2A: Parametric Surface Store (SVI params)
    # -------------------------------------------------------------------------
    def write_surface_parametric(
        self,
        ticker : str,
        date : str,
        svi_params_by_expiry : Dict[str, Dict],
        metadata : Optional[Dict] = None
    ) -> Path:
        """
        Write SVI surface parameters to JSON .

        The parametric representation is extremely compact:
        5 floats per expiry slice, vs. 200+ IV values.
        Total for 50 expiries: 50 * 5 * 8 bytes ≈ 2KB per surface.

        Parameters
        ----------
        svi_params_by_expiry : { expiry_str : {'a': float, 'b': float,
                                               'rho': float, 'm': float,
                                               'sigma': float, 'rmse': float}}
        """
        year = date[:4]
        path = self.root / 'surfaces' / 'parametric' / ticker / year / f"{date}.json"
        path.parent.mkdir(parents=True, exist_ok=True)

        payload = {
            'ticker': ticker,
            'date': date,
            'written_at': datetime.utcnow().isoformat(),
            'version': '1.0',
            'svi_params': svi_params_by_expiry,
            'metadata': metadata or {}
        }

        with open(path, 'w') as f:
            json.dump(payload, f, indent=2, default=float)

        logger.info(f"Written parametric surface: {path}")
        return path

    def read_surface_parametric(
        self,
        ticker : str,
        date : str
    ) -> Tuple[Dict, Dict]:
        """
        Read SVI surface parameters .

        Returns
        -------
        (svi_params_by_expiry, metadata)
        """
        year = date[:4]
        path = self.root / 'surfaces' / 'parametric' / ticker / year / f"{date}.json"

        if not path.exists():
            raise FileNotFoundError(f"No parametric surface for {ticker} on {date}")

        with open(path) as f:
            payload = json.load(f)

        return payload['svi_params'], payload.get('metadata', {})

    def reconstruct_surface_from_svi(
        self,
        ticker : str,
        date : str,
        x_grid : Optional[np.ndarray] = None,
        tau_values : Optional[List[float]] = None
    ) -> pd.DataFrame:
        """
        Reconstruct the full IV surface from stored SVI parameters .

        Parameters
        ----------
        x_grid : Log - moneyness grid (default: STANDARD_X_GRID)
        tau_values : List of TTEs to include (None = all stored)

        Returns
        -------
        pd.DataFrame with columns: log_moneyness, tau, expiry, implied_vol
        """
        from .surface_smoothing import SVIFitter

        if x_grid is None:
            x_grid = self.STANDARD_X_GRID

        svi_params, meta = self.read_surface_parametric(ticker, date)
        fitter = SVIFitter()

        records = []
        for expiry, params_dict in svi_params.items():
            tau = params_dict.get('tau')
            if tau is None or tau <= 0:
                continue

            if tau_values and not any(abs(tau - t) < 1e-4 for t in tau_values):
                continue

            params = np.array([
                params_dict['a'], params_dict['b'], params_dict['rho'],
                params_dict['m'], params_dict['sigma']
            ])

            w = fitter.w_svi(x_grid, params)
            iv = np.sqrt(np.maximum(w / tau, 0))

            for i, x in enumerate(x_grid):
                records.append({
                    'date': date, 'ticker': ticker, 'expiry': expiry,
                    'tau': tau, 'log_moneyness': x, 'implied_vol': iv[i],
                    'total_var': w[i]
                })

        return pd.DataFrame(records)

    # -------------------------------------------------------------------------
    # Layer 2B: Dense Grid Surface Store
    # -------------------------------------------------------------------------
    def write_surface_grid(
        self,
        ticker : str,
        date : str,
        iv_grid : np.ndarray,
        x_grid : np.ndarray,
        tau_grid : np.ndarray,
        additional_cols : Optional[Dict[str, np.ndarray]] = None
    ) -> Path:
        """
        Write dense IV surface grid to Parquet .

        iv_grid : shape (n_x, n_tau)
        """
        year = date[:4]
        path = self.root / 'surfaces' / 'grid' / ticker / year / f"{date}.parquet"
        path.parent.mkdir(parents=True, exist_ok=True)

        n_x, n_tau = iv_grid.shape
        xx, tt = np.meshgrid(x_grid, tau_grid, indexing='ij')

        df = pd.DataFrame({
            'date': date,
            'ticker': ticker,
            'log_moneyness': xx.ravel(),
            'tau': tt.ravel(),
            'implied_vol': iv_grid.ravel(),
            'total_var': (iv_grid**2 * tt).ravel()
        })

        if additional_cols:
            for col_name, arr in additional_cols.items():
                df[col_name] = arr.ravel()

        # Quantize IVs to float32 for storage efficiency (saves 50% space)
        df['implied_vol'] = df['implied_vol'].astype('float32')
        df['total_var'] = df['total_var'].astype('float32')
        df['log_moneyness'] = df['log_moneyness'].astype('float32')
        df['tau'] = df['tau'].astype('float32')

        table = pa.Table.from_pandas(df)
        pq.write_table(table, path, compression='zstd', compression_level=9)

        logger.info(f"Written grid surface: {path} ({os.path.getsize(path)/1024:.0f}KB)")
        return path

    def read_surface_grid(
        self,
        ticker : str,
        date : str,
        x_range : Optional[Tuple[float, float]] = None,
        tau_range : Optional[Tuple[float, float]] = None
    ) -> pd.DataFrame:
        """ Read grid surface with optional spatial filters ."""
        year = date[:4]
        path = self.root / 'surfaces' / 'grid' / ticker / year / f"{date}.parquet"

        filters = []
        if x_range:
            filters += [
                ('log_moneyness', '>=', x_range[0]),
                ('log_moneyness', '<=', x_range[1])
            ]
        if tau_range:
            filters += [
                ('tau', '>=', tau_range[0]),
                ('tau', '<=', tau_range[1])
            ]

        table = pq.read_table(path, filters=filters if filters else None)
        return table.to_pandas()


class SurfaceVersionManager:
    """
    Manages versioning of the data cleaning pipeline .

    Ensures that :
    1. Every research query can specify which version of cleaning rules to use .
    2. Changes in data vendor or cleaning logic are tracked .
    3. Historical research is reproducible even after pipeline updates .
    """

    def __init__(self, root_dir : str):
        self.root = Path(root_dir)
        self.version_file = self.root / 'metadata' / 'data_versions.json'
        self._load_versions()

    def _load_versions(self):
        if self.version_file.exists():
            with open(self.version_file) as f:
                self.versions = json.load(f)
        else:
            self.versions = {}

    def register_version(
        self,
        version_id : str,
        description : str,
        cleaning_params : Dict,
        effective_from : str
    ):
        """ Register a new pipeline version ."""
        self.versions[version_id] = {
            'description': description,
            'cleaning_params': cleaning_params,
            'effective_from': effective_from,
            'registered_at': datetime.utcnow().isoformat()
        }
        with open(self.version_file, 'w') as f:
            json.dump(self.versions, f, indent=2)
        logger.info(f"Registered pipeline version: {version_id}")

    def get_version_for_date(self, date : str) -> Dict:
        """
        Return the cleaning version applicable to a given date .
        Returns the most recent version effective on or before 'date'.
        """
        applicable = {
            v_id: v for v_id, v in self.versions.items()
            if v['effective_from'] <= date
        }
        if not applicable:
            return {}
        latest = max(applicable, key=lambda k : applicable[k]['effective_from'])
        return {latest: applicable[latest]}


# Vol Surface Visualization Helper
# ============================================================
def plot_vol_surface_ascii(S, strikes, tenors, iv_matrix):
    """
    ASCII representation of the vol surface for quick inspection.
    """
    print("\n IMPLIED VOLATILITY SURFACE ")
    print(f" Spot : {S}")
    print(" " + "-" * 60)

    # Header : strikes
    header = " Tenor \\ Strike |"
    step = max(1, len(strikes) // 5)
    for K in strikes[::step]:
        header += f" {K:6.0f} |"
    print(header)
    print(" " + "-" * 60)

    for i, T in enumerate(tenors):
        row = f" {str(T):9s} |"
        for j in range(0, len(strikes), step):
            iv = iv_matrix[i, j]
            row += f" {iv * 100:5.1f}% |"
        print(row)

    print(" " + "-" * 60)


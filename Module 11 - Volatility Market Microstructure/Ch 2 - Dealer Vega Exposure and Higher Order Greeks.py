# Dealer Vega Book Analyzer
# ============================================================
class DealerVegaBook:
    """
    Analyze dealer vega, vanna, volga exposure across term structure.
    """
    def __init__(self, S, r=0.05, mult=100):
        self.S = S
        self.r = r
        self.mult = mult

    def build_exposure_table(self, chain_df, dealer_signs=None):
        """
        Build comprehensive exposure table.
        """
        if dealer_signs is None:
            dealer_signs = {'call': -1, 'put': 1}

        rows = []
        for _, row in chain_df.iterrows():
            K = row['strike']
            T_flt = row.get('T', row['expiry_days'] / 365.0)
            otype = row['option_type'].lower()
            oi = row['open_interest']
            sigma = row.get('implied_vol', 0.20)

            if T_flt <= 0 or np.isnan(sigma) or sigma <= 0:
                continue

            g = extended_greeks(self.S, K, T_flt, self.r, sigma, otype)
            if not g:
                continue

            ds = dealer_signs[otype]

            dollar_gamma = 0.5 * g['gamma'] * self.S**2 * self.mult * oi * (0.01**2)
            dollar_vega = g['vega'] * self.mult * oi
            dollar_vanna = g['vanna'] * self.S * self.mult * oi * 0.01
            dollar_volga = g['volga'] * self.mult * oi

            rows.append({
                'strike': K,
                'dte': int(row['expiry_days']),
                'option_type': otype,
                'open_interest': oi,
                'implied_vol': sigma,
                'delta': g['delta'],
                'gamma': g['gamma'],
                'vega_raw': g['vega_raw'],
                'vanna': g['vanna'],
                'volga': g['volga'],
                'dollar_gamma': ds * dollar_gamma,
                'dollar_vega': ds * dollar_vega,
                'dollar_vanna': ds * dollar_vanna,
                'dollar_volga': ds * dollar_volga,
                'dealer_sign': ds
            })

        return pd.DataFrame(rows)

    def vega_term_structure(self, exposure_df):
        """ Aggregate vega by tenor bucket ."""
        tenor_buckets = {
            '0-7d': (0, 7),
            '8-14d': (8, 14),
            '15-30d': (15, 30),
            '31-60d': (31, 60),
            '61-90d': (61, 90),
            '91-180d': (91, 180),
            '181d+': (181, 9999)
        }

        results = []
        for label, (lo, hi) in tenor_buckets.items():
            mask = (exposure_df['dte'] >= lo) & (exposure_df['dte'] <= hi)
            sub = exposure_df[mask]
            if len(sub) == 0:
                continue
            results.append({
                'tenor_bucket': label,
                'net_vega_$': sub['dollar_vega'].sum(),
                'net_vanna_$': sub['dollar_vanna'].sum(),
                'net_volga_$': sub['dollar_volga'].sum(),
                'net_gamma_$': sub['dollar_gamma'].sum(),
                'n_contracts': sub['open_interest'].sum()
            })

        return pd.DataFrame(results)

    def skew_profile(self, exposure_df, expiry_dte=30):
        """ Vega / Vanna distribution by strike at a given expiry ."""
        sub = exposure_df[exposure_df['dte'] == expiry_dte]
        profile = (sub.groupby('strike')
                   .agg(net_vega=('dollar_vega', 'sum'),
                        net_vanna=('dollar_vanna', 'sum'),
                        net_volga=('dollar_volga', 'sum'))
                   .reset_index())
        return profile

    def print_risk_summary(self, exposure_df):
        """ Print dealer risk summary ."""
        total_vega = exposure_df['dollar_vega'].sum()
        total_vanna = exposure_df['dollar_vanna'].sum()
        total_volga = exposure_df['dollar_volga'].sum()
        total_gamma = exposure_df['dollar_gamma'].sum()

        print("=" * 60)
        print(f" DEALER FULL GREEKS RISK SUMMARY (S = {self.S:.2f})")
        print("=" * 60)
        print(f" Net Dollar Gamma ($/1% move^2):   ${total_gamma:>12,.0f}")
        print(f" Net Dollar Vega ($/1 vol pt):      ${total_vega:>12,.0f}")
        print(f" Net Dollar Vanna ($/1% 1vpt):      ${total_vanna:>12,.0f}")
        print(f" Net Dollar Volga ($/1 vpt^2):      ${total_volga:>12,.0f}")
        print("-" * 60)
        print(" Regime Interpretation :")
        print(f" Gamma : {'LONG (pin/stabilize)' if total_gamma > 0 else 'SHORT (amplify moves)'}")
        print(f" Vega  : {'LONG (vol rise hurts short)' if total_vega > 0 else 'SHORT (vol rise helps)'}")
        print(f" Vanna : {'Positive (spot-vol cov)' if total_vanna > 0 else 'Negative (spot-vol cov)'}")
        print(f" Volga : {'Long wing / smile' if total_volga > 0 else 'Short wing / smile'}")
        print("=" * 60)


import numpy as np
import pandas as pd
from scipy.stats import norm

# ============================================================
# Extended Greeks : Vanna , Volga , Charm , Veta
# ============================================================
def extended_greeks(S, K, T, r, sigma, option_type='call'):
    """
    Compute full set of BSM greeks including higher - order .
    """
    if T <= 0 or sigma <= 0:
        return {}

    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)

    phi_d1 = norm.pdf(d1)
    N_d1 = norm.cdf(d1)
    N_d2 = norm.cdf(d2)

    # First - order
    gamma = phi_d1 / (S * sigma * np.sqrt(T))
    vega = S * phi_d1 * np.sqrt(T)  # raw, per unit vol

    if option_type.lower() == 'call':
        delta = N_d1
        price = S * N_d1 - K * np.exp(-r * T) * N_d2
    else:
        delta = N_d1 - 1.0
        price = K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)

    # Vanna = d( Delta )/d( sigma ) = d( Vega )/dS
    vanna = -phi_d1 * d2 / sigma

    # Volga ( Vomma ) = d( Vega )/d( sigma )
    volga = vega * d1 * d2 / sigma

    # Charm = d( Delta )/d(t) = -d( Delta )/d(T)
    charm = -phi_d1 * (2 * r * T - d2 * sigma * np.sqrt(T)) / (2 * T * sigma * np.sqrt(T))

    # Veta = d( Vega )/d(t)
    veta = -S * phi_d1 * np.sqrt(T) * (r * d1 / (sigma * np.sqrt(T)) - (1 + d1 * d2) / (2 * T))

    # Ultima = d( Volga )/d( sigma )
    ultima = -vega * (d1 * d2 * (1 - d1 * d2) + d1**2 + d2**2) / sigma**2

    # Speed = d( Gamma )/dS
    speed = -gamma * (1 + d1 / (sigma * np.sqrt(T))) / S

    # Color = d( Gamma )/d(t)
    color = -gamma * (r * d1 / (sigma * np.sqrt(T)) - (1 + d1 * d2) / (2 * T))

    return {
        'price': price, 'delta': delta, 'gamma': gamma,
        'vega': vega / 100,  # per 1 vol point
        'vega_raw': vega,
        'vanna': vanna,
        'volga': volga / 100,  # per 1 vol point squared
        'charm': charm,
        'veta': veta,
        'ultima': ultima,
        'speed': speed,
        'color': color,
        'd1': d1, 'd2': d2
    }


# ============================================================
# BLACK - SCHOLES GREEKS
# ============================================================
def bs_all(S, K, T, r, sigma, otype='call'):
    """Return dict of BS price + Greeks. Safe for T -> 0."""
    if T <= 1e-10 or sigma <= 1e-10:
        iv = max(S - K, 0) if otype == 'call' else max(K - S, 0)
        d = 1.0 if (otype == 'call' and S > K) else 0.0
        return dict(price=iv, delta=d, gamma=0., theta=0., vega=0., vanna=0.)

    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    nd1 = norm.pdf(d1)
    if otype == 'call':
        price = S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
        delta = norm.cdf(d1)
    else:
        price = K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)
        delta = norm.cdf(d1) - 1.0

    gamma = nd1 / (S * sigma * np.sqrt(T))
    theta = (-(S * nd1 * sigma) / (2 * np.sqrt(T)) - r * K * np.exp(-r * T) * (norm.cdf(d2) if otype == 'call' else norm.cdf(-d2))) / 365.
    vega = S * np.sqrt(T) * nd1
    vanna = -nd1 * d2 / sigma
    charm = (-nd1 * (2 * r * T - d2 * sigma * np.sqrt(T)) / (2 * T * sigma * np.sqrt(T)))
    return dict(price=price, delta=delta, gamma=gamma, theta=theta, vega=vega, vanna=vanna, charm=charm)

# ============================================================
# DATA STRUCTURES
# ============================================================
@dataclass
class OptionLeg:
    leg_id: str
    strike: float
    expiry_T: float
    otype: str
    qty: int
    open_iv: float

@dataclass
class DealerBook:
    book_id: str
    legs: List[OptionLeg] = field(default_factory=list)
    stock: float = 0.0
    cash: float = 1000000.0
    pnl: float = 0.0
    n_hedges: int = 0

# ============================================================
# DEALER AGENT
# ============================================================
class DealerAgent:
    """
    Single market-maker agent.
    """
    def __init__(self, book: DealerBook, S0: float, r: float = 0.05,
                 strategy: str = 'threshold', delta_thr: float = 0.03,
                 hedge_every: int = 12, hedge_cost_bps: float = 2.0,
                 lam_impact: float = 5e-9):
        self.book = book
        self.S = S0
        self.r = r
        self.strategy = strategy
        self.delta_thr = delta_thr
        self.hedge_every = hedge_every
        self.hedge_cost = hedge_cost_bps / 10000.0
        self.lam = lam_impact
        self._step = 0

    def portfolio_greeks(self, S: float, elapsed_T: float) -> dict:
        tot = dict(delta=0., gamma=0., theta=0., vega=0., vanna=0., charm=0.)
        for leg in self.book.legs:
            T_rem = max(leg.expiry_T - elapsed_T, 1e-6)
            g = bs_all(S, leg.strike, T_rem, self.r, leg.open_iv, leg.otype)
            for k in tot:
                tot[k] += leg.qty * 100. * g[k]
        tot['delta'] += self.book.stock
        return tot

    def _hedge_shares(self, greeks: dict) -> float:
        nd = greeks['delta']
        if self.strategy == 'continuous':
            return -nd - self.book.stock
        elif self.strategy == 'threshold':
            ref = max(abs(self.book.stock), 1.)
            if abs(nd) > self.delta_thr * ref:
                return -nd - self.book.stock
            return 0.
        elif self.strategy == 'discrete':
            if self._step % self.hedge_every == 0:
                return -nd - self.book.stock
            return 0.
        return 0.

    def _execute(self, shares: float, S: float) -> float:
        if abs(shares) < 1.:
            return 0.
        impact = self.lam * abs(shares) * S
        exec_price = S + np.sign(shares) * impact
        cost = abs(shares) * S * self.hedge_cost
        self.book.stock += shares
        self.book.cash -= (shares * exec_price + cost)
        self.book.pnl -= cost
        self.book.n_hedges += 1
        return np.sign(shares) * impact

    def step(self, new_S: float, elapsed_T: float) -> dict:
        self.S = new_S
        self._step += 1
        g = self.portfolio_greeks(new_S, elapsed_T)
        shares = self._hedge_shares(g)
        impact = self._execute(shares, new_S)
        self.book.pnl += g['theta']
        return dict(greeks=g, hedge_shares=shares, impact=impact, pnl=self.book.pnl)


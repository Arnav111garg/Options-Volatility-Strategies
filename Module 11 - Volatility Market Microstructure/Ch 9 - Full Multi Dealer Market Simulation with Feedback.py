# MARKET SIMULATOR
# ============================================================
class MarketSimulator:
    def __init__(self, S0: float, mu: float, sigma: float, r: float = 0.05):
        self.S0 = S0
        self.mu = mu
        self.sigma = sigma
        self.r = r
        self.dealers: List[DealerAgent] = []

    def add_dealer(self, agent: DealerAgent):
        self.dealers.append(agent)

    @staticmethod
    def _make_short_option_book(book_id, S0, sigma, n_strikes=5, base_dte=30, strategy='threshold'):
        book = DealerBook(book_id=book_id)
        offsets = np.linspace(-0.04, 0.04, n_strikes)
        for off in offsets:
            K = S0 * (1 + off)
            iv = sigma + 0.03 * off**2 - 0.01 * off
            for ot in ('call', 'put'):
                qty = -np.random.randint(100, 500)
                book.legs.append(OptionLeg(
                    leg_id=f"{book_id}_{ot}_{K:.0f}",
                    strike=K,
                    expiry_T=base_dte / 252.,
                    otype=ot,
                    qty=qty,
                    open_iv=max(iv, 0.05)
                ))
        return book

    def populate_dealers(self, n_dealers: int = 3, S0: float = None, strategies=('threshold', 'continuous', 'discrete')):
        S0 = S0 or self.S0
        np.random.seed(7)
        for i in range(n_dealers):
            strat = strategies[i % len(strategies)]
            book = self._make_short_option_book(f"Dealer_{i+1}", S0, self.sigma, strategy=strat)
            agent = DealerAgent(book, S0, r=self.r, strategy=strat, delta_thr=0.025, lam_impact=4e-9)
            self.add_dealer(agent)

    def run(self, T_days: float = 5, dt_min: int = 5, seed: int = 42) -> pd.DataFrame:
        np.random.seed(seed)
        dt_yr = dt_min / (252. * 390.)
        n_steps = int(T_days * 390 / dt_min)
        S = self.S0
        records = []

        for step in range(n_steps):
            elapsed_T = step * dt_yr
            dW = np.random.normal(0., np.sqrt(dt_yr))
            dS_exog = self.mu * S * dt_yr + self.sigma * S * dW

            total_impact = 0.
            agg_delta, agg_gamma = 0., 0.
            agg_hedge_shares = 0.
            agg_pnl = 0.

            for dealer in self.dealers:
                res = dealer.step(S, elapsed_T)
                total_impact += res['impact']
                agg_delta += res['greeks']['delta']
                agg_gamma += res['greeks']['gamma']
                agg_hedge_shares += res['hedge_shares']
                agg_pnl += res['pnl']

            dS_total = dS_exog + total_impact
            S = max(S + dS_total, 0.01)

            amp = (abs(dS_total) / max(abs(dS_exog), 1e-12))
            records.append(dict(
                step=step,
                time_days=step * dt_min / 390.,
                S=S,
                dS_exog=dS_exog,
                dS_impact=total_impact,
                amplification=amp,
                agg_net_delta=agg_delta,
                agg_net_gamma=agg_gamma,
                agg_hedge_shares=agg_hedge_shares,
                agg_pnl=agg_pnl,
                log_ret=np.log(max(S, 0.01) / max(S - dS_total, 0.01)),
            ))

        return pd.DataFrame(records)

    def plot_results(self, df: pd.DataFrame):
        fig = plt.figure(figsize=(16, 12))
        gs = gridspec.GridSpec(3, 2, figure=fig)
        axes = [fig.add_subplot(gs[r, c]) for r in range(3) for c in range(2)]

        axes[0].plot(df['time_days'], df['S'], 'b-', lw=1.5)
        axes[0].set_title('Price Path (exog. GBM + dealer feedback)', fontweight='bold')
        axes[0].set_ylabel('Price ($)')
        axes[0].grid(True, alpha=0.3)

        amp_clipped = df['amplification'].clip(upper=5.)
        axes[1].plot(df['time_days'], amp_clipped, 'r-', lw=1., alpha=0.8)
        axes[1].axhline(1., color='black', lw=0.8, ls='--')
        axes[1].set_title('Price Amplification |dS_total / dS_exog|', fontweight='bold')
        axes[1].set_ylabel('Multiplier')
        axes[1].grid(True, alpha=0.3)

        axes[2].fill_between(df['time_days'], df['agg_net_delta'], 0, where=df['agg_net_delta'] > 0, alpha=0.55, color='green', label='Long delta')
        axes[2].fill_between(df['time_days'], df['agg_net_delta'], 0, where=df['agg_net_delta'] < 0, alpha=0.55, color='red', label='Short delta')
        axes[2].axhline(0, color='black', lw=0.5)
        axes[2].set_title('Aggregate Dealer Net Delta', fontweight='bold')
        axes[2].set_ylabel('Net Delta (shares)')
        axes[2].legend(fontsize=8)
        axes[2].grid(True, alpha=0.3)

        axes[3].plot(df['time_days'], df['agg_net_gamma'], 'purple', lw=1.5)
        axes[3].fill_between(df['time_days'], df['agg_net_gamma'], 0, where=df['agg_net_gamma'] < 0, alpha=0.3, color='red', label='Short gamma')
        axes[3].axhline(0, color='black', lw=0.5)
        axes[3].set_title('Aggregate Dealer Net Gamma (GEX proxy)', fontweight='bold')
        axes[3].set_ylabel('Net Gamma')
        axes[3].legend(fontsize=8)
        axes[3].grid(True, alpha=0.3)

        pos = df['agg_hedge_shares'] > 0
        neg = df['agg_hedge_shares'] < 0
        w = df['time_days'].diff().median() * 0.8
        axes[4].bar(df['time_days'][pos], df['agg_hedge_shares'][pos], width=w, color='green', alpha=0.6, label='Buy')
        axes[4].bar(df['time_days'][neg], df['agg_hedge_shares'][neg], width=w, color='red', alpha=0.6, label='Sell')
        axes[4].set_title('Dealer Hedge Trades (shares)', fontweight='bold')
        axes[4].set_ylabel('Shares')
        axes[4].legend(fontsize=8)
        axes[4].grid(True, alpha=0.3)

        rets = df['log_ret'].dropna()
        axes[5].hist(rets, bins=60, density=True, alpha=0.65, color='steelblue', label='Simulated returns')
        mu_r, sig_r = rets.mean(), rets.std()
        xs = np.linspace(rets.min(), rets.max(), 300)
        axes[5].plot(xs, norm.pdf(xs, mu_r, sig_r), 'r-', lw=2, label='Normal fit')
        axes[5].set_title('Return Distribution (fat tails from GEX)', fontweight='bold')
        axes[5].set_xlabel('Log return')
        axes[5].set_ylabel('Density')
        axes[5].legend(fontsize=8)
        axes[5].grid(True, alpha=0.3)

        for ax in axes:
            ax.set_xlabel(ax.get_xlabel() or 'Time (days)')

        plt.suptitle('Multi-Dealer Hedging Simulation\nMarket Feedback Dynamics', fontsize=14, fontweight='bold', y=1.01)
        plt.tight_layout()
        plt.savefig('dealer_hedging_sim.png', dpi=150, bbox_inches='tight')
        plt.show()
        print("Saved: dealer_hedging_sim.png")


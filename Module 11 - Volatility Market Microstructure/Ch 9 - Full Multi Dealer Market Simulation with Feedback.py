def demo_dealer_sim():
    S0, sigma = 450., 0.15 / np.sqrt(252.)
    mkt = MarketSimulator(S0=S0, mu=0., sigma=sigma, r=0.05)
    mkt.populate_dealers(n_dealers=3, S0=S0, strategies=('threshold', 'continuous', 'discrete'))

    print("Running 5-day, 5-min dealer simulation")
    df = mkt.run(T_days=5, dt_min=5, seed=42)

    print(f"Steps: {len(df)}")
    print(f"Final price: ${df['S'].iloc[-1]:.2f} (start ${S0:.2f})")
    print(f"Avg amplification: {df['amplification'].mean():.3f}x")
    print(f"Max amplification: {df['amplification'].clip(upper=20).quantile(0.99):.3f}x")
    print(f"Total hedge vol: {df['agg_hedge_shares'].abs().sum():,.0f} shares")

    mkt.plot_results(df)
    return mkt, df

if __name__ == "__main__":
    mkt, df = demo_dealer_sim()


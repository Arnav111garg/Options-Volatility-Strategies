# GEX COMPUTATION ENGINE
# ============================================================
class GammaExposureEngine:
    """
    Computes Gamma Exposure (GEX) profile for an options chain.
    """
    def __init__(self, S: float, r: float = 0.05):
        self.S = S
        self.r = r
        self.bs = BSGreeks()

    def compute_gex_profile(self, chain: pd.DataFrame) -> pd.DataFrame:
        """
        Compute GEX for each option in the chain.
        """
        results = []
        for _, row in chain.iterrows():
            K = row['strike']
            T = row['expiry_days'] / 365.0
            iv = row['iv']
            oi = row['open_interest']
            opt_type = row['option_type']
            cust_net = row.get('customer_net_position', 1.0)

            gamma_val = self.bs.gamma(self.S, K, T, self.r, iv)
            gex_raw = oi * gamma_val * self.S * 100
            gex_signed = -cust_net * gex_raw

            delta_val = (self.bs.delta_call(self.S, K, T, self.r, iv)
                         if opt_type == 'call'
                         else self.bs.delta_put(self.S, K, T, self.r, iv))

            results.append({
                'strike': K,
                'expiry_days': row['expiry_days'],
                'option_type': opt_type,
                'iv': iv,
                'open_interest': oi,
                'gamma': gamma_val,
                'delta': delta_val,
                'gex_raw': gex_raw,
                'gex_signed': gex_signed,
                'dollar_gamma': gex_raw * self.S * 0.01,
                'vanna': self.bs.vanna(self.S, K, T, self.r, iv) * oi * 100,
            })
        return pd.DataFrame(results)

    def aggregate_gex_by_strike(self, chain: pd.DataFrame) -> pd.DataFrame:
        """Aggregate GEX across all expirations for each strike."""
        gex_df = self.compute_gex_profile(chain)
        agg = gex_df.groupby('strike').agg({
            'gex_signed': 'sum',
            'gex_raw': 'sum',
            'open_interest': 'sum',
            'vanna': 'sum'
        }).reset_index()
        return agg

    def compute_squeeze_probability(self, chain: pd.DataFrame, lambda_impact: float = 1e-8) -> dict:
        """Estimate gamma squeeze probability using the instability condition."""
        gex_df = self.compute_gex_profile(chain)
        total_gex = gex_df['gex_signed'].sum()
        total_raw_gex = gex_df['gex_raw'].sum()

        kappa = abs(total_gex) * lambda_impact
        if kappa < 1.0:
            multiplier = 1.0 / (1.0 - kappa)
        else:
            multiplier = np.inf

        agg = self.aggregate_gex_by_strike(chain)
        if not agg.empty:
            max_gex_idx = agg['gex_raw'].idxmax()
            gamma_wall = agg.loc[max_gex_idx, 'strike']
            gamma_wall_gex = agg.loc[max_gex_idx, 'gex_raw']
        else:
            gamma_wall = self.S
            gamma_wall_gex = 0.0

        return {
            'total_gex': total_gex,
            'total_gex_M': total_gex / 1e6,
            'kappa': kappa,
            'multiplier': multiplier,
            'regime': 'SQUEEZE' if kappa > 0.7 else ('ELEVATED' if kappa > 0.3 else 'NORMAL'),
            'gamma_wall': gamma_wall,
            'gamma_wall_gex_M': gamma_wall_gex / 1e6,
            'dealers_net_short': total_gex < 0,
        }


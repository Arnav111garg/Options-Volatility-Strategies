def plot_gex_profile(agg_df: pd.DataFrame, S: float, title: str = "GEX Profile"):
    """Plot GEX profile by strike."""
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(14, 9))
    pos_mask = agg_df['gex_signed'] > 0
    neg_mask = agg_df['gex_signed'] < 0
    width = (agg_df['strike'].max() - agg_df['strike'].min()) / len(agg_df) * 0.8

    ax1.bar(agg_df.loc[pos_mask, 'strike'], agg_df.loc[pos_mask, 'gex_signed'] / 1e6, color='green', alpha=0.7, label='Long Gamma (Stabilizing)', width=width)
    ax1.bar(agg_df.loc[neg_mask, 'strike'], agg_df.loc[neg_mask, 'gex_signed'] / 1e6, color='red', alpha=0.7, label='Short Gamma (Destabilizing)', width=width)
    ax1.axvline(x=S, color='blue', linestyle='--', lw=2, label=f'Current Price (${S:.0f})')
    ax1.axhline(y=0, color='black', lw=0.5)
    ax1.set_title(f'{title} Signed GEX by Strike', fontweight='bold')
    ax1.set_ylabel('GEX ($M per 1% move)')
    ax1.legend()
    ax1.grid(True, alpha=0.3)

    agg_sorted = agg_df.sort_values('strike')
    cumulative_gex = agg_sorted['gex_signed'].cumsum() / 1e6
    ax2.plot(agg_sorted['strike'], cumulative_gex, 'b-', lw=2)
    ax2.fill_between(agg_sorted['strike'], cumulative_gex, 0, where=cumulative_gex < 0, alpha=0.3, color='red', label='Net Short Gamma')
    ax2.fill_between(agg_sorted['strike'], cumulative_gex, 0, where=cumulative_gex >= 0, alpha=0.3, color='green', label='Net Long Gamma')
    ax2.axvline(x=S, color='blue', linestyle='--', lw=2)
    ax2.axhline(y=0, color='black', lw=1)
    ax2.set_title('Cumulative GEX Net Dealer Positioning', fontweight='bold')
    ax2.set_xlabel('Strike Price ($)')
    ax2.set_ylabel('Cumulative GEX ($M)')
    ax2.legend()
    ax2.grid(True, alpha=0.3)

    plt.tight_layout()
    plt.savefig('gex_profile.png', dpi=150, bbox_inches='tight')
    plt.show()


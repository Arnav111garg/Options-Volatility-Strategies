# BLACK - SCHOLES GREEKS ENGINE
# ============================================================
class BSGreeks:
    """
    Production-grade Black-Scholes Greeks Calculator.
    Handles all edge cases (ATM, very short DTE, etc.)
    """
    @staticmethod
    def d1_d2(S, K, T, r, sigma):
        """Compute d1, d2 with numerical safeguards."""
        if T <= 1e-10 or sigma <= 1e-10:
            return np.nan, np.nan
        d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
        d2 = d1 - sigma * np.sqrt(T)
        return d1, d2

    @staticmethod
    def gamma(S, K, T, r, sigma):
        """
        Gamma: second derivative of option price w.r.t. S.
        Same for calls and puts.
        """
        if T <= 1e-10 or sigma <= 1e-10:
            return 0.0
        d1, _ = BSGreeks.d1_d2(S, K, T, r, sigma)
        if np.isnan(d1):
            return 0.0
        return norm.pdf(d1) / (S * sigma * np.sqrt(T))

    @staticmethod
    def delta_call(S, K, T, r, sigma):
        """Call delta."""
        if T <= 1e-10:
            return 1.0 if S > K else 0.0
        d1, _ = BSGreeks.d1_d2(S, K, T, r, sigma)
        return norm.cdf(d1) if not np.isnan(d1) else 0.5

    @staticmethod
    def delta_put(S, K, T, r, sigma):
        """Put delta."""
        return BSGreeks.delta_call(S, K, T, r, sigma) - 1.0

    @staticmethod
    def vanna(S, K, T, r, sigma):
        """
        Vanna: dDelta / dSigma = dVega / dS.
        Critical for understanding skew dynamics during squeezes.
        """
        if T <= 1e-10 or sigma <= 1e-10:
            return 0.0
        d1, d2 = BSGreeks.d1_d2(S, K, T, r, sigma)
        return -norm.pdf(d1) * d2 / sigma

    @staticmethod
    def charm(S, K, T, r, sigma, option_type='call'):
        """
        Charm: dDelta / dt. Critical for 0DTE dynamics.
        """
        if T <= 1e-10 or sigma <= 1e-10:
            return 0.0
        d1, d2 = BSGreeks.d1_d2(S, K, T, r, sigma)
        sign = 1.0 if option_type == 'call' else -1.0
        return -norm.pdf(d1) * (2 * r * T - d2 * sigma * np.sqrt(T)) / (2 * T * sigma * np.sqrt(T))


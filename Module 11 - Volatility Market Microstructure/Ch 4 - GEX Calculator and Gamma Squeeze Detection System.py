# GAMMA SQUEEZE SIMULATOR
# ============================================================
class GammaSqueezeSimulator:
    """Monte Carlo simulation of price dynamics with dealer hedging feedback."""
    def __init__(self, S0: float, mu: float, sigma: float, lambda_impact: float, gex_engine: GammaExposureEngine):
        self.S0 = S0
        self.mu = mu
        self.sigma_base = sigma
        self.lambda_impact = lambda_impact
        self.gex_engine = gex_engine

    def simulate_path(self, chain: pd.DataFrame, T_days: int = 5, dt_minutes: int = 1, seed: int = 42) -> pd.DataFrame:
        """Simulate intraday price path with gamma squeeze dynamics."""
        np.random.seed(seed)
        minutes_per_day = 390
        total_steps = T_days * minutes_per_day // dt_minutes
        dt = dt_minutes / (252 * 390)

        prices = [self.S0]
        dealer_flows = [0.0]
        kappas = []
        gex_totals = []
        S = self.S0

        for step in range(total_steps):
            metrics = self.gex_engine.compute_squeeze_probability(chain, self.lambda_impact)
            kappa = metrics['kappa']
            kappas.append(kappa)
            gex_totals.append(metrics['total_gex_M'])

            dW = np.random.normal(0, np.sqrt(dt))
            dS_diffusion = self.mu * S * dt + self.sigma_base * S * dW

            if kappa < 1.0:
                amplification = 1.0 / (1.0 - kappa)
            else:
                amplification = 5.0

            dS_total = dS_diffusion * amplification
            dealer_flow = (dS_total - dS_diffusion) / (self.lambda_impact * S + 1e-10)
            dealer_flows.append(dealer_flow)

            S = max(S + dS_total, 0.01)
            prices.append(S)

        times = pd.date_range('2024-01-01 09:30', periods=total_steps + 1, freq=f'{dt_minutes}min')
        return pd.DataFrame({
            'time': times,
            'price': prices,
            'dealer_flow': dealer_flows,
            'kappa': [kappas[0]] + kappas,
            'gex_M': [gex_totals[0]] + gex_totals,
            'log_return': [0] + list(np.diff(np.log(prices)))
        })

    def plot_squeeze_simulation(self, path_df: pd.DataFrame, squeeze_threshold: float = 0.7):
        """Visualize the gamma squeeze simulation results."""
        fig = plt.figure(figsize=(16, 12))
        gs = gridspec.GridSpec(3, 2, figure=fig)

        ax1 = fig.add_subplot(gs[0, :])
        ax2 = fig.add_subplot(gs[1, 0])
        ax3 = fig.add_subplot(gs[1, 1])
        ax4 = fig.add_subplot(gs[2, 0])
        ax5 = fig.add_subplot(gs[2, 1])

        squeeze_mask = path_df['kappa'] > squeeze_threshold

        ax1.plot(path_df['time'], path_df['price'], 'b-', lw=1.5, label='Price')
        ax1.fill_between(path_df['time'], path_df['price'], where=squeeze_mask, alpha=0.3, color='red', label=f'Squeeze Regime (kappa > {squeeze_threshold})')
        ax1.axhline(y=self.S0, color='gray', linestyle='--', lw=1)
        ax1.set_title('Price Path with Gamma Squeeze Regimes', fontweight='bold')
        ax1.set_ylabel('Price ($)')
        ax1.legend()
        ax1.grid(True, alpha=0.3)

        ax2.plot(path_df['time'], path_df['kappa'], 'r-', lw=1.5)
        ax2.axhline(y=squeeze_threshold, color='orange', linestyle='--', label=f'Squeeze Threshold ({squeeze_threshold})')
        ax2.axhline(y=1.0, color='darkred', linestyle='--', label='Instability (kappa=1)')
        ax2.set_title('Squeeze Coefficient (kappa)', fontweight='bold')
        ax2.set_ylabel('kappa = |GEX| * lambda')
        ax2.legend(fontsize=8)
        ax2.grid(True, alpha=0.3)

        ax3.plot(path_df['time'], path_df['gex_M'], 'g-', lw=1.5)
        ax3.axhline(y=0, color='black', lw=0.5)
        ax3.fill_between(path_df['time'], path_df['gex_M'], 0, where=path_df['gex_M'] < 0, alpha=0.4, color='red', label='Negative GEX (Destabilizing)')
        ax3.set_title('GEX Profile Over Time', fontweight='bold')
        ax3.set_ylabel('GEX ($M)')
        ax3.legend(fontsize=8)
        ax3.grid(True, alpha=0.3)

        ax4.bar(range(len(path_df)), path_df['dealer_flow'], color=['red' if f < 0 else 'green' for f in path_df['dealer_flow']], alpha=0.6)
        ax4.set_title('Dealer Hedging Flow (Shares)', fontweight='bold')
        ax4.set_ylabel('Shares')
        ax4.grid(True, alpha=0.3)

        returns = path_df['log_return'].dropna()
        ax5.hist(returns, bins=50, density=True, alpha=0.7, color='blue', label='Simulated Returns')
        mu_r, sig_r = returns.mean(), returns.std()
        x = np.linspace(returns.min(), returns.max(), 200)
        ax5.plot(x, norm.pdf(x, mu_r, sig_r), 'r-', lw=2, label='Normal Fit')
        ax5.set_title('Return Distribution (Fat Tails from GEX)', fontweight='bold')
        ax5.set_xlabel('Log Return')
        ax5.set_ylabel('Density')
        ax5.legend(fontsize=8)
        ax5.grid(True, alpha=0.3)

        plt.tight_layout()
        plt.suptitle('Gamma Squeeze Simulator Output', fontsize=14, fontweight='bold', y=1.01, color='darkblue')
        plt.savefig('gamma_squeeze_simulation.png', dpi=150, bbox_inches='tight')
        plt.show()
        print("Plot saved: gamma_squeeze_simulation.png")


# 0DTE STRATEGY ANALYZER
# ============================================================
def analyze_0dte_strategy(S: float = 4500.0, K: float = 4500.0, sigma_implied: float = 0.18, sigma_realized: float = 0.14, strategy: str = 'short_straddle'):
    """
    Complete 0DTE strategy analysis with visualization.
    Demonstrates the key 0DTE dynamics in a production context.
    """
    pricer = ZeroDTEPricer(S=S, r=0.05)

    # 1. Greek evolution through the day
    minutes_left_list = [390, 300, 200, 100, 60, 30, 15, 5, 1]

    print(f"\n{'=' * 70}")
    print(f"0DTE Greek Evolution {strategy.upper()} at K=${K}")
    print(f"Implied Vol: {sigma_implied * 100:.1f}%, Realized Vol: {sigma_realized * 100:.1f}%")
    print(f"{'=' * 70}")
    print(f"{'Min Left': >10} {'Price': >8} {'Delta': >8} {'Gamma': >10} {'Theta/Day': >12} {'Vega': >8}")
    print("-" * 70)

    for min_left in minutes_left_list:
        g = pricer.price_0dte(K, min_left, sigma_implied)
        print(f"{min_left: >10} ${g['price']: >7.3f} {g['delta']: >8.4f} {g['gamma']: >10.4f} ${g['theta_daily']: >10.4f} {g['vega']: >7.4f}")

    # 2. Monte Carlo P&L simulation
    print(f"\nRunning Monte Carlo simulation ({strategy}) ...")
    pnl_df = pricer.simulate_intraday_0dte_pnl(
        K=K, strategy=strategy,
        n_paths=2000, sigma_realized=sigma_realized,
        sigma_implied=sigma_implied
    )

    # P&L statistics
    print(f"\n--- {strategy.upper()} P&L Statistics ---")
    print(f"  Mean P&L: ${pnl_df['pnl'].mean():.2f}")
    print(f"  Median P&L: ${pnl_df['pnl'].median():.2f}")
    print(f"  Std P&L: ${pnl_df['pnl'].std():.2f}")
    print(f"  Win Rate: {(pnl_df['pnl'] > 0).mean() * 100:.1f}%")
    print(f"  5th Pct: ${pnl_df['pnl'].quantile(0.05):.2f}")
    print(f"  95th Pct: ${pnl_df['pnl'].quantile(0.95):.2f}")

    # Breakeven analysis
    vol_edge = sigma_implied - sigma_realized
    print(f"\nVol Edge (IV - RV): {vol_edge * 100:.1f}% annual")
    print(f"  Theoretical Daily Edge (short straddle): ${S * sigma_implied * np.sqrt(1/252) * 0.5:.2f} per contract")

    return pnl_df



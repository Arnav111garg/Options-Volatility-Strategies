# 0DTE PRICING ENGINE
# ============================================================
class ZeroDTEPricer:
    """
    Specialized options pricer for 0DTE options.
    Handles the extreme-greek regime near expiration.
    """
    def __init__(self, S: float, r: float = 0.05):
        self.S = S
        self.r = r

    def minutes_to_years(self, minutes: float) -> float:
        """Convert minutes to fraction of year (trading year)."""
        return minutes / (390 * 252)  # 390 min/day, 252 days/year

    def intraday_vol_estimate(self, time_of_day: float, base_iv: float, time_of_day_factor: bool = True) -> float:
        """
        Estimate the expected realized vol for remainder of day.
        Incorporates intraday volatility patterns (U-shaped).
        """
        if not time_of_day_factor:
            return base_iv

        # U-shaped intraday vol pattern (empirically estimated)
        u_shape = (1.5 * np.exp(-3 * time_of_day) +
                   0.8 +
                   0.5 * np.exp(-3 * (1 - time_of_day)))
        u_shape_normalized = u_shape / 1.3  # Normalize to ~1.0 average

        return base_iv * u_shape_normalized

    def price_0dte(self, K: float, minutes_left: float, sigma_intraday: float, option_type: str = 'call', jump_premium: float = 0.0) -> dict:
        """
        Price a 0DTE option with intraday considerations.
        """
        tau = self.minutes_to_years(minutes_left)

        if tau <= 0:
            # Expired: intrinsic value only
            if option_type == 'call':
                price = max(self.S - K, 0.0)
            else:
                price = max(K - self.S, 0.0)
            return {'price': price, 'delta': float(self.S > K), 'gamma': 0.0, 'theta_daily': 0.0, 'vega': 0.0, 'dollar_gamma': 0.0}

        # d1, d2 with safeguards for tiny tau
        try:
            d1 = (np.log(self.S / K) + (self.r + 0.5 * sigma_intraday ** 2) * tau) / (sigma_intraday * np.sqrt(tau))
            d2 = d1 - sigma_intraday * np.sqrt(tau)
        except (ZeroDivisionError, FloatingPointError):
            d1, d2 = np.inf if self.S > K else -np.inf, -np.inf

        if option_type == 'call':
            price = (self.S * norm.cdf(d1) - K * np.exp(-self.r * tau) * norm.cdf(d2))
            delta = norm.cdf(d1)
        else:
            price = (K * np.exp(-self.r * tau) * norm.cdf(-d2) - self.S * norm.cdf(-d1))
            delta = norm.cdf(d1) - 1.0

        # Apply jump premium
        price_with_jump = price * (1 + jump_premium)

        # Greeks
        gamma_val = norm.pdf(d1) / (self.S * sigma_intraday * np.sqrt(tau))
        theta_val = (-(self.S * norm.pdf(d1) * sigma_intraday) / (2 * np.sqrt(tau)) -
                     self.r * K * np.exp(-self.r * tau) * norm.cdf(d2)) / 365.0
        vega_val = self.S * np.sqrt(tau) * norm.pdf(d1)

        # Dollar gamma per 1% move
        dollar_gamma = 0.5 * gamma_val * (self.S * 0.01) ** 2

        return {
            'price': price_with_jump,
            'price_bs': price,
            'jump_component': price * jump_premium,
            'delta': delta,
            'gamma': min(gamma_val, 1000.0),  # Cap for display
            'theta_daily': theta_val,
            'vega': vega_val,
            'dollar_gamma': dollar_gamma,
            'd1': d1,
            'd2': d2,
            'tau_minutes': minutes_left,
            'effective_vol': sigma_intraday,
        }

    def greek_surface_0dte(self, minutes_left: float, sigma: float) -> pd.DataFrame:
        """Compute the full Greek surface across strikes for a given DTE."""
        strikes = np.linspace(self.S * 0.92, self.S * 1.08, 50)
        results = []
        for K in strikes:
            greeks_c = self.price_0dte(K, minutes_left, sigma, 'call')
            greeks_p = self.price_0dte(K, minutes_left, sigma, 'put')
            results.append({
                'strike': K,
                'moneyness': K / self.S - 1.0,
                'call_price': greeks_c['price'],
                'put_price': greeks_p['price'],
                'delta': greeks_c['delta'],
                'gamma': greeks_c['gamma'],
                'theta': greeks_c['theta_daily'],
                'dollar_gamma': greeks_c['dollar_gamma'],
            })
        return pd.DataFrame(results)

    def simulate_intraday_0dte_pnl(self, K: float, strategy: str = 'short_straddle', n_paths: int = 1000, sigma_realized: float = 0.15, sigma_implied: float = 0.18, seed: int = 42) -> pd.DataFrame:
        """Monte Carlo simulation of 0DTE strategy P&L through the trading day."""
        np.random.seed(seed)
        dt_minutes = 5  # 5-minute simulation steps
        total_minutes = 390  # Full trading day
        steps = total_minutes // dt_minutes
        dt_yr = self.minutes_to_years(dt_minutes)

        pnls = []

        for path in range(n_paths):
            S = self.S
            hedging_cost = 0.0

            # Initial position
            min_left_init = total_minutes
            pos = self._get_position(K, min_left_init, sigma_implied, strategy)
            initial_premium = pos['initial_premium']
            prev_delta = pos['initial_delta']

            for step in range(steps):
                min_left = total_minutes - step * dt_minutes

                # Simulate price move (GBM)
                dW = np.random.normal(0.0, np.sqrt(dt_yr))
                S = S * np.exp((0.0 - 0.5 * sigma_realized ** 2) * dt_yr + sigma_realized * dW)

                # Recompute delta (for hedging)
                if min_left > dt_minutes:
                    pricer_temp = ZeroDTEPricer(S, self.r)
                    greeks = pricer_temp.price_0dte(K, min_left, sigma_implied, 'call')
                    new_delta = greeks['delta']

                    # Cost of delta rebalancing (proportional to |delta change|)
                    rebal_cost = abs(new_delta - prev_delta) * S * 0.0001  # 1bp spread
                    hedging_cost += rebal_cost
                    prev_delta = new_delta

            # Final P&L at expiration
            final_intrinsic = self._intrinsic_value(S, K, strategy)
            pnl = initial_premium - final_intrinsic - hedging_cost

            pnls.append({
                'pnl': pnl,
                'final_price': S,
                'move_pct': (S / self.S - 1.0) * 100.0,
                'hedging_cost': hedging_cost,
                'final_intrinsic': final_intrinsic,
            })

        return pd.DataFrame(pnls)

    def _get_position(self, K: float, min_left: float, sigma: float, strategy: str) -> dict:
        """Get initial position for strategy."""
        call = self.price_0dte(K, min_left, sigma, 'call')
        put = self.price_0dte(K, min_left, sigma, 'put')
        call_strangle = self.price_0dte(K * 1.02, min_left, sigma, 'call')
        put_strangle = self.price_0dte(K * 0.98, min_left, sigma, 'put')

        strategies = {
            'short_straddle': {
                'initial_premium': call['price'] + put['price'],
                'initial_delta': -(call['delta'] + put['delta'])
            },
            'long_straddle': {
                'initial_premium': -(call['price'] + put['price']),
                'initial_delta': call['delta'] + put['delta']
            },
            'short_strangle': {
                'initial_premium': call_strangle['price'] + put_strangle['price'],
                'initial_delta': -(call_strangle['delta'] + put_strangle['delta'])
            },
        }
        return strategies.get(strategy, strategies['short_straddle'])

    def _intrinsic_value(self, S: float, K: float, strategy: str) -> float:
        """Compute intrinsic (exercise) value at expiration."""
        call_intrinsic = max(S - K, 0.0)
        put_intrinsic = max(K - S, 0.0)
        call_wide = max(S - K * 1.02, 0.0)
        put_wide = max(K * 0.98 - S, 0.0)

        values = {
            'short_straddle': call_intrinsic + put_intrinsic,
            'long_straddle': -(call_intrinsic + put_intrinsic),
            'short_strangle': call_wide + put_wide,
        }
        return values.get(strategy, call_intrinsic + put_intrinsic)



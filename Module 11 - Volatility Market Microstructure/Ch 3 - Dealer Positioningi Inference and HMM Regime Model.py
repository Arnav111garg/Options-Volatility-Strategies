# OI - Based Positioning Estimator
# ============================================================
class PositioningEstimator:
    """
    Estimate dealer positioning from OI and volume data.
    """
    def __init__(self, decay_halflife_days=20):
        """
        decay_halflife_days : how quickly old OI becomes stale
        """
        self.decay = np.log(2) / decay_halflife_days
        self.positions = defaultdict(float)

    def update(self, date, trades_with_direction, oi_changes):
        """
        Update dealer positioning estimates.
        """
        # Decay existing positions
        for key in self.positions:
            self.positions[key] *= np.exp(-self.decay)

        # Update from OI changes
        for _, row in oi_changes.iterrows():
            key = (row['strike'], row['expiry_dte'], row['option_type'])
            oi_chg = row['oi_change']

            if oi_chg > 0:
                direction = self._get_direction(
                    trades_with_direction,
                    row['strike'], row['expiry_dte'], row['option_type']
                )
                # Dealer position = opposite of customer direction
                self.positions[key] += -direction * oi_chg
            elif oi_chg < 0:
                # Positions closed : assume proportional to existing
                self.positions[key] += oi_chg

    def _get_direction(self, trades_df, K, dte, otype, tol=0.5):
        """ Estimate net direction from classified trades ."""
        if trades_df is None or len(trades_df) == 0:
            return 0.0

        mask = ((abs(trades_df['strike'] - K) < tol) &
                (trades_df['expiry_dte'] == dte) &
                (trades_df['option_type'].str.lower() == otype.lower()))

        sub = trades_df[mask]
        if len(sub) == 0:
            return 0.0

        net_vol = (sub['direction'] * sub['volume']).sum()
        total_vol = sub['volume'].sum()

        return net_vol / total_vol if total_vol > 0 else 0.0

    def get_positioning_df(self):
        """ Return current positioning as DataFrame ."""
        rows = []
        for (K, dte, otype), pos in self.positions.items():
            rows.append({
                'strike': K, 'expiry_dte': dte,
                'option_type': otype, 'dealer_position': pos
            })
        return pd.DataFrame(rows)


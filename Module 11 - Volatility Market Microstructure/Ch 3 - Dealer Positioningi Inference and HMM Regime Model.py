# Trade Direction Classifier (Lee - Ready )
# ============================================================
def classify_trade_direction(trades_df):
    """
    Apply Lee-Ready algorithm to options trades.
    trades_df columns: price, bid, ask, time
    Returns: direction (+1 = buy, -1 = sell)
    """
    df = trades_df.copy().sort_values('time')
    df['mid'] = (df['bid'] + df['ask']) / 2.0
    df['direction'] = 0

    for i, row in df.iterrows():
        price = row['price']
        mid = row['mid']

        if price > mid:
            df.at[i, 'direction'] = 1  # Buy
        elif price < mid:
            df.at[i, 'direction'] = -1  # Sell
        else:
            # Tick test
            prev_idx = df.index[df.index < i]
            if len(prev_idx) > 0:
                prev_price = df.loc[prev_idx[-1], 'price']
                if price > prev_price:
                    df.at[i, 'direction'] = 1
                elif price < prev_price:
                    df.at[i, 'direction'] = -1
                else:
                    # Use last non-zero direction
                    past_dirs = df.loc[prev_idx, 'direction']
                    nz = past_dirs[past_dirs != 0]
                    df.at[i, 'direction'] = int(nz.iloc[-1]) if len(nz) else 1

    return df


# HMM Regime Model for Gamma Regimes
# ============================================================
class GammaRegimeHMM:
    """
    Hidden Markov Model to identify dealer gamma regimes.
    State 0: Long gamma (stabilizing, low vol)
    State 1: Short gamma (destabilizing, high vol)
    """
    def __init__(self, n_states=2):
        self.n_states = n_states
        self.A = None
        self.mu = None
        self.sigma = None
        self.pi = None
        self.is_fitted = False

    def _gaussian_emission(self, obs, state):
        """P(obs | state ) under Gaussian emission ."""
        return norm.pdf(obs, self.mu[state], self.sigma[state])

    def fit(self, observations, n_iter=100, tol=1e-6):
        """
        Fit HMM via Baum-Welch (EM) algorithm.
        """
        T, D = observations.shape if len(observations.shape) > 1 else (len(observations), 1)
        if D == 1:
            observations = observations.reshape(-1, 1)

        K = self.n_states

        # Initialize parameters
        self.A = np.full((K, K), 1.0 / K)
        self.pi = np.full(K, 1.0 / K)
        self.mu = np.array([np.percentile(observations[:, 0], (k + 1) * 100 / (K + 1)) for k in range(K)])
        self.sigma = np.full(K, np.std(observations[:, 0]))

        log_likelihoods = []

        for iteration in range(n_iter):
            # ---- E-step : Forward-Backward ----
            alpha = self._forward(observations)
            beta = self._backward(observations)

            # Posterior state probabilities
            gamma_ = alpha * beta
            gamma_ /= gamma_.sum(axis=1, keepdims=True) + 1e-300

            # Joint state probabilities
            xi = np.zeros((T - 1, K, K))
            for t in range(T - 1):
                for i in range(K):
                    for j in range(K):
                        xi[t, i, j] = (alpha[t, i] *
                                       self.A[i, j] *
                                       self._emission_prob(observations[t + 1], j) *
                                       beta[t + 1, j])
                s = xi[t].sum()
                if s > 0:
                    xi[t] /= s

            # ---- M-step : Update parameters ----
            for i in range(K):
                denom = xi[:, i, :].sum() + 1e-300
                self.A[i] = xi[:, i, :].sum(axis=0) / denom

            self.pi = gamma_[0]

            for k in range(K):
                wk = gamma_[:, k]
                self.mu[k] = (wk * observations[:, 0]).sum() / (wk.sum() + 1e-300)
                self.sigma[k] = np.sqrt((wk * (observations[:, 0] - self.mu[k])**2).sum() / (wk.sum() + 1e-300)) + 1e-6

            ll = np.log(alpha[-1].sum() + 1e-300)
            log_likelihoods.append(ll)

            if iteration > 0 and abs(log_likelihoods[-1] - log_likelihoods[-2]) < tol:
                break

        self.is_fitted = True
        self.log_likelihoods_ = log_likelihoods
        return self

    def _emission_prob(self, obs, state):
        return max(norm.pdf(obs[0], self.mu[state], self.sigma[state]), 1e-300)

    def _forward(self, obs):
        T = len(obs)
        K = self.n_states
        alpha = np.zeros((T, K))

        for k in range(K):
            alpha[0, k] = self.pi[k] * self._emission_prob(obs[0], k)
        alpha[0] /= (alpha[0].sum() + 1e-300)

        for t in range(1, T):
            for k in range(K):
                alpha[t, k] = self._emission_prob(obs[t], k) * sum(alpha[t - 1, i] * self.A[i, k] for i in range(K))
            alpha[t] /= (alpha[t].sum() + 1e-300)

        return alpha

    def _backward(self, obs):
        T = len(obs)
        K = self.n_states
        beta = np.zeros((T, K))
        beta[-1] = 1.0

        for t in range(T - 2, -1, -1):
            for i in range(K):
                beta[t, i] = sum(self.A[i, j] * self._emission_prob(obs[t + 1], j) * beta[t + 1, j] for j in range(K))
            beta[t] /= (beta[t].sum() + 1e-300)

        return beta

    def predict_regime(self, observations):
        """ Viterbi decoding : most likely state sequence ."""
        if not self.is_fitted:
            raise RuntimeError("Model not fitted")

        T = len(observations)
        K = self.n_states

        V = np.zeros((T, K))
        ptr = np.zeros((T, K), dtype=int)

        for k in range(K):
            V[0, k] = np.log(self.pi[k] + 1e-300) + np.log(self._emission_prob(observations[0], k))

        for t in range(1, T):
            for k in range(K):
                scores = [V[t - 1, i] + np.log(self.A[i, k] + 1e-300) for i in range(K)]
                best_prev = np.argmax(scores)
                V[t, k] = scores[best_prev] + np.log(self._emission_prob(observations[t], k))
                ptr[t, k] = best_prev

        states = np.zeros(T, dtype=int)
        states[-1] = np.argmax(V[-1])
        for t in range(T - 2, -1, -1):
            states[t] = ptr[t + 1, states[t + 1]]

        return states

    def regime_probabilities(self, observations):
        """ Smoothed posterior state probabilities ."""
        alpha = self._forward(observations)
        beta = self._backward(observations)
        gamma = alpha * beta
        gamma /= gamma.sum(axis=1, keepdims=True) + 1e-300
        return gamma


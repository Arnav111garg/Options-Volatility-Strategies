# Example Usage : Synthetic SPX Chain
# ============================================================
def generate_synthetic_spx_chain(S=4500, n_strikes=30, n_expiries=4):
    """Generate a synthetic options chain for testing."""
    np.random.seed(42)
    records = []
    strikes = np.linspace(S * 0.90, S * 1.10, n_strikes)
    expiries_dte = [7, 14, 30, 60][:n_expiries]

    # Synthetic IV surface : SVI-like skew
    def get_iv(K, T_days):
        moneyness = np.log(K / S)
        T = T_days / 365.0
        atm_vol = 0.18 + 0.02 * np.exp(-T * 5)  # Term structure
        skew = -0.4 * moneyness                 # Skew
        smile = 0.3 * moneyness ** 2            # Curvature
        return max(0.05, atm_vol + skew + smile)

    for dte in expiries_dte:
        for K in strikes:
            # Open interest : higher near ATM, decreasing away
            atm_oi_base = 50000
            oi_call = int(atm_oi_base * np.exp(-5.0 * ((K - S) / S) ** 2) * np.random.uniform(0.7, 1.3))
            oi_put = int(atm_oi_base * np.exp(-5.0 * ((K - S) / S) ** 2) * 1.3 * np.random.uniform(0.7, 1.3))
            iv = get_iv(K, dte)

            records.append({
                'strike': K, 'expiry_days': dte,
                'option_type': 'call', 'open_interest': oi_call,
                'implied_vol': iv
            })
            records.append({
                'strike': K, 'expiry_days': dte,
                'option_type': 'put', 'open_interest': oi_put,
                'implied_vol': iv
            })

    return pd.DataFrame(records)


import numpy as np
import pandas as pd
from scipy.stats import norm
from scipy.optimize import brentq
import warnings

# ============================================================
# BSM Greeks Engine
# ============================================================
def bsm_greeks(S, K, T, r, sigma, option_type='call'):
    """
    Compute BSM greeks for a European option.
    Returns dict with delta, gamma, vega, theta, price
    """
    if T <= 0 or sigma <= 0:
        return {'delta': 0.0, 'gamma': 0.0, 'vega': 0.0, 'theta': 0.0, 'price': 0.0}

    d1 = (np.log(S / K) + (r + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)

    phi_d1 = norm.pdf(d1)  # Standard normal PDF at d1
    N_d1 = norm.cdf(d1)    # Standard normal CDF at d1
    N_d2 = norm.cdf(d2)
    N_md1 = norm.cdf(-d1)
    N_md2 = norm.cdf(-d2)

    # Gamma is same for calls and puts (put-call parity)
    gamma = phi_d1 / (S * sigma * np.sqrt(T))

    # Vega (same for calls and puts, per unit, not per %)
    vega = S * phi_d1 * np.sqrt(T) / 100.0  # per 1 vol point

    if option_type.lower() == 'call':
        price = S * N_d1 - K * np.exp(-r * T) * N_d2
        delta = N_d1
        theta = (-(S * phi_d1 * sigma) / (2 * np.sqrt(T)) - r * K * np.exp(-r * T) * N_d2) / 365.0
    else:
        price = K * np.exp(-r * T) * N_md2 - S * N_md1
        delta = N_d1 - 1.0
        theta = (-(S * phi_d1 * sigma) / (2 * np.sqrt(T)) + r * K * np.exp(-r * T) * N_md2) / 365.0

    return {
        'price': price, 'delta': delta, 'gamma': gamma,
        'vega': vega, 'theta': theta, 'd1': d1, 'd2': d2
    }

# ============================================================
# Implied Volatility Solver
# ============================================================
def implied_vol(market_price, S, K, T, r, option_type='call', tol=1e-8, max_iter=200):
    """
    Solve for implied vol via Brent's method.
    """
    if T <= 0 or market_price <= 0:
        return np.nan

    # Intrinsic value bounds check
    intrinsic = max(0, (S - K) if option_type == 'call' else (K - S))
    if market_price < intrinsic * 0.999:
        return np.nan

    def objective(sigma):
        return bsm_greeks(S, K, T, r, sigma, option_type)['price'] - market_price

    try:
        # Initial bounds: vol must be in [1e-6, 20.0] (0.0001% to 2000% annualized)
        iv = brentq(objective, 1e-6, 20.0, xtol=tol, maxiter=max_iter)
    except (ValueError, RuntimeError):
        iv = np.nan

    return iv


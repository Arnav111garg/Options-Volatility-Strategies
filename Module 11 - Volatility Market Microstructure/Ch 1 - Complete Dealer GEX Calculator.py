# GEX Calculator : Net Dealer Gamma Exposure
# ============================================================
class DealerGammaEngine:
    """
    Computes dealer net gamma exposure (GEX) from options chain data.
    """
    def __init__(self, S, r=0.05, contract_multiplier=100, dealer_sign_calls=-1, dealer_sign_puts=1):
        self.S = S
        self.r = r
        self.mult = contract_multiplier
        self.dc = dealer_sign_calls  # dealers short calls -> -1
        self.dp = dealer_sign_puts   # dealers long puts -> +1
        self.chain = None
        self.gex_by_strike = None

    def load_chain(self, df):
        """
        Load options chain. Expected columns:
        strike, expiry_days (DTE), option_type,
        open_interest, mid_price (optional), implied_vol (optional)
        """
        self.chain = df.copy()
        self.chain['T'] = self.chain['expiry_days'] / 365.0
        return self

    def compute_greeks(self, use_mid_iv=True):
        """Compute gamma for each option in the chain."""
        results = []
        S, r = self.S, self.r

        for _, row in self.chain.iterrows():
            K = row['strike']
            T = row['T']
            otype = row['option_type'].lower()
            oi = row['open_interest']

            # Get sigma: use provided IV or compute from mid price
            if use_mid_iv and 'implied_vol' in row and not np.isnan(row['implied_vol']):
                sigma = row['implied_vol']
            elif 'mid_price' in row and not np.isnan(row['mid_price']):
                sigma = implied_vol(row['mid_price'], S, K, T, r, otype)
            else:
                sigma = 0.20  # fallback

            if np.isnan(sigma) or sigma <= 0:
                continue

            g = bsm_greeks(S, K, T, r, sigma, otype)

            # Dollar gamma = 0.5 * gamma * S^2 * multiplier * OI * (0.01)^2
            # This is the P&L for a 1% move, per the full position
            dollar_gamma = 0.5 * g['gamma'] * (S ** 2) * self.mult * oi * (0.01 ** 2)

            # Dealer sign: calls -> dealer short -> sign = -1, puts -> dealer long -> sign = +1
            dealer_sign = self.dc if otype == 'call' else self.dp

            results.append({
                'strike': K, 'dte': row['expiry_days'],
                'option_type': otype, 'open_interest': oi,
                'implied_vol': sigma, 'gamma': g['gamma'],
                'delta': g['delta'], 'vega': g['vega'],
                'dollar_gamma': dollar_gamma,
                'dealer_dollar_gamma': dealer_sign * dollar_gamma
            })

        self.greeks_df = pd.DataFrame(results)
        return self

    def compute_gex_profile(self, spot_range=None, n_points=200):
        """
        Compute GEX as a function of underlying price S.
        This shows the gamma profile across different spot levels.
        """
        if spot_range is None:
            spot_range = (self.S * 0.85, self.S * 1.15)

        spot_grid = np.linspace(spot_range[0], spot_range[1], n_points)
        gex_profile = []

        for s_val in spot_grid:
            gex = 0.0
            for _, row in self.chain.iterrows():
                K = row['strike']
                T = row['T']
                if T <= 0:
                    continue
                otype = row['option_type'].lower()
                oi = row['open_interest']
                sigma = row.get('implied_vol', 0.20)
                if np.isnan(sigma) or sigma <= 0:
                    sigma = 0.20

                g = bsm_greeks(s_val, K, T, self.r, sigma, otype)
                dg = 0.5 * g['gamma'] * (s_val ** 2) * self.mult * oi * (0.01 ** 2)
                dealer_sign = self.dc if otype == 'call' else self.dp
                gex += dealer_sign * dg

            gex_profile.append({'spot': s_val, 'gex': gex})

        self.gex_profile = pd.DataFrame(gex_profile)
        return self

    def get_gamma_flip(self):
        """Find the gamma flip level (where dealer GEX = 0)."""
        if not hasattr(self, 'gex_profile'):
            self.compute_gex_profile()

        df = self.gex_profile
        # Find sign changes
        sign_changes = np.where(np.diff(np.sign(df['gex'])))[0]

        flip_levels = []
        for idx in sign_changes:
            # Linear interpolation for the zero crossing
            s1, g1 = df.iloc[idx]['spot'], df.iloc[idx]['gex']
            s2, g2 = df.iloc[idx + 1]['spot'], df.iloc[idx + 1]['gex']
            s_flip = s1 - g1 * (s2 - s1) / (g2 - g1)
            flip_levels.append(s_flip)

        return flip_levels

    def aggregate_gex_by_strike(self):
        """Aggregate dealer GEX by strike level for histogram view."""
        if not hasattr(self, 'greeks_df'):
            self.compute_greeks()

        agg = (self.greeks_df
               .groupby('strike')
               .agg(total_dealer_dollar_gamma=('dealer_dollar_gamma', 'sum'),
                    total_oi=('open_interest', 'sum'),
                    avg_iv=('implied_vol', 'mean'))
               .reset_index()
               .sort_values('strike'))

         # Handle potential empty dataframe safely
        self.gex_by_strike = agg
        return agg

    def summary(self):
        """Print summary statistics."""
        if not hasattr(self, 'greeks_df'):
            self.compute_greeks()

        total_gex = self.greeks_df['dealer_dollar_gamma'].sum()
        call_gex = self.greeks_df[self.greeks_df['option_type'] == 'call']['dealer_dollar_gamma'].sum()
        put_gex = self.greeks_df[self.greeks_df['option_type'] == 'put']['dealer_dollar_gamma'].sum()
        flip_lvls = self.get_gamma_flip() if hasattr(self, 'gex_profile') else []

        print("=" * 55)
        print(f" DEALER GAMMA EXPOSURE SUMMARY (S = {self.S:.2f})")
        print("=" * 55)
        print(f" Net GEX (total):          ${total_gex: >15,.0f}")
        print(f" Call contribution:       ${call_gex: >15,.0f}")
        print(f" Put contribution:        ${put_gex: >15,.0f}")
        regime_str = 'LONG GAMMA (stabilizing)' if total_gex > 0 else 'SHORT GAMMA (destabilizing)'
        print(f" Regime:                   {regime_str}")
        if flip_lvls:
            print(f" Gamma flip level(s):      {[f'{x:.1f}' for x in flip_lvls]}")
        print("=" * 55)

        return {
            'net_gex': total_gex, 'call_gex': call_gex,
            'put_gex': put_gex, 'gamma_flip': flip_lvls,
            'regime': 'long' if total_gex > 0 else 'short'
        }


# 1. ALMGREN - CHRISS OPTIMAL EXECUTOR
#
class AlmgrenChrissExecutor:
    """
    Almgren - Chriss (2001) optimal liquidation .

    Parameters
    ----------
    X0 : float shares to liquidate ( positive = sell )
    T : float execution horizon in trading days
    sigma : float daily vol of the stock ( annualised / sqrt (252) )
    eta : float temporary impact coefficient ($/ share per share /day)
    gamma : float permanent impact coefficient ($/ share per share )
    lam : float risk - aversion parameter ($/ variance unit )
    """

    def __init__(self, X0, T, sigma, eta, gamma, lam):
        self.X0 = X0
        self.T = T
        self.sigma = sigma
        self.eta = eta
        self.gamma = gamma
        self.lam = lam
        self.kappa = np.sqrt(lam * sigma ** 2 / (eta + 1e-30))

    # core trajectory
    def trajectory(self, n=200):
        """ Return DataFrame : time , inventory , rate , temp_impact ."""
        t = np.linspace(0, self.T, n + 1)
        kT = self.kappa * self.T
        if kT < 1e-6: # TWAP limit
            x = self.X0 * (1 - t / self.T)
        else:
            x = self.X0 * np.sinh(self.kappa * (self.T - t)) / np.sinh(kT)
        v = -np.gradient(x, t)
        v = np.clip(v, 0, None)
        return pd.DataFrame({'time': t, 'inventory': x, 'rate': v, 'temp_impact': self.eta * v})

    # expected cost ( analytical )
    def expected_cost(self):
        kT = self.kappa * self.T
        if kT < 1e-6:
            return (self.gamma * self.X0 ** 2 / 2 +
                    self.eta * self.X0 ** 2 / self.T +
                    self.lam * self.sigma ** 2 * self.X0 ** 2 * self.T / 3)
        return (self.gamma * self.X0 ** 2 / 2 +
                self.eta * self.kappa * self.X0 ** 2 / np.tanh(kT) -
                self.eta * self.kappa * self.X0 ** 2 / np.sinh(kT))

    # cost variance ( analytical )
    def cost_variance(self):
        kT = self.kappa * self.T
        if kT < 1e-6:
            return self.sigma ** 2 * self.X0 ** 2 * self.T / 3
        return (self.sigma ** 2 * self.X0 ** 2 / (2 * self.kappa) *
                (1 / np.tanh(kT) - kT / np.sinh(kT) ** 2))

    # efficient frontier
    def efficient_frontier(self, n_pts=40):
        lams = np.logspace(-6, 3, n_pts)
        E_list, SD_list = [], []
        for lam in lams:
            ex = AlmgrenChrissExecutor(self.X0, self.T, self.sigma, self.eta, self.gamma, lam)
            E_list.append(ex.expected_cost())
            SD_list.append(np.sqrt(max(ex.cost_variance(), 0)))
        return pd.DataFrame({'lambda': lams, 'E_cost': E_list, 'SD_cost': SD_list})

    # schedule comparison
    def compare_schedules(self, n=200):
        traj = self.trajectory(n)
        t = traj['time'].values

        schedules = {
            'AC_Optimal': traj['inventory'].values,
            'TWAP': self.X0 * (1 - t / self.T),
            'FrontLoad': np.where(t <= 0.2 * self.T,
                                  self.X0 * (1 - 2.5 * t / self.T),
                                  self.X0 * 0.5 * (1 - (t - 0.2 * self.T) / (0.8 * self.T)))
        }
        rows = {}
        for name, x_sched in schedules.items():
            x_sched = np.clip(x_sched, 0, self.X0)
            v_sched = -np.gradient(x_sched, t)
            tc = self.eta * trapezoid(v_sched ** 2, t)
            pc = self.gamma * self.X0 ** 2 / 2
            tr = self.lam * self.sigma ** 2 * trapezoid(x_sched ** 2, t)
            rows[name] = {'temp_cost': tc, 'perm_cost': pc, 'timing_risk': tr, 'total': tc + pc + tr}
        return pd.DataFrame(rows).T

    # visualisation
    def plot(self):
        fig = plt.figure(figsize=(16, 10))
        gs = gridspec.GridSpec(2, 3, figure=fig)
        ax1 = fig.add_subplot(gs[0, :2])
        ax2 = fig.add_subplot(gs[0, 2])
        ax3 = fig.add_subplot(gs[1, :2])
        ax4 = fig.add_subplot(gs[1, 2])

        # 1. Trajectories for three risk - aversion levels
        for mult, lbl in [(0.001, r'$\lambda \ll 1$ TWAP-like'),
                          (1.0, r'$\lambda = \lambda^*$ Optimal'),
                          (1000, r'$\lambda \gg 1$ Front-loaded')]:
            ex = AlmgrenChrissExecutor(self.X0, self.T, self.sigma, self.eta, self.gamma, self.lam * mult)
            tr = ex.trajectory(200)
            ax1.plot(tr['time'], tr['inventory'] / self.X0, lw=2, label=lbl)
        ax1.set_xlabel('Time (days)')
        ax1.set_ylabel('Remaining Inventory / $X_0$')
        ax1.set_title('Optimal Liquidation Trajectories', fontweight='bold')
        ax1.legend(fontsize=9)
        ax1.grid(True, alpha=0.3)

        # 2. Efficient frontier
        ef = self.efficient_frontier(40)
        ax2.plot(ef['SD_cost'], ef['E_cost'], 'b-o', ms=4, lw=2)
        ax2.set_xlabel('Std Dev of Cost')
        ax2.set_ylabel('Expected Cost')
        ax2.set_title('Efficient Frontier', fontweight='bold')
        ax2.grid(True, alpha=0.3)

        # 3. Trading rates : optimal vs TWAP
        tr = self.trajectory(200)
        ax3.fill_between(tr['time'], tr['rate'], alpha=0.6, color='steelblue', label='Optimal rate')
        twap_rate = np.full_like(tr['time'], self.X0 / self.T)
        ax3.plot(tr['time'], twap_rate, 'r--', lw=2, label='TWAP rate')
        ax3.set_xlabel('Time (days)')
        ax3.set_ylabel('Shares / Day')
        ax3.set_title(r'Optimal Trading Rate vs. TWAP', fontweight='bold')
        ax3.legend()
        ax3.grid(True, alpha=0.3)

        # 4. Cost breakdown bar chart
        comp = self.compare_schedules()
        x_pos = np.arange(len(comp))
        w = 0.5
        ax4.bar(x_pos, comp['temp_cost'], w, label='Temporary', color='steelblue')
        ax4.bar(x_pos, comp['perm_cost'], w, bottom=comp['temp_cost'], label='Permanent', color='orange')
        ax4.bar(x_pos, comp['timing_risk'], w, bottom=comp['temp_cost'] + comp['perm_cost'], label='Timing Risk', color='green')
        ax4.set_xticks(x_pos)
        ax4.set_xticklabels(comp.index, rotation=20, fontsize=9)
        ax4.set_title('Cost Breakdown by Schedule', fontweight='bold')
        ax4.legend(fontsize=8)
        ax4.grid(True, alpha=0.3, axis='y')

        plt.suptitle('Almgren-Chriss Optimal Execution Analysis', fontsize=14, fontweight='bold', y=1.01)
        plt.tight_layout()
        plt.savefig('ac_execution.png', dpi=150, bbox_inches='tight')
        plt.show()
        print("Saved: ac_execution.png")



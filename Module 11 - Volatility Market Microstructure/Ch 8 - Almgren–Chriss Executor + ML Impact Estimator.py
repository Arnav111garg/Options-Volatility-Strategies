def demo_impact():
    print("=" * 60)
    print(" ALMGREN-CHRISS OPTIMAL EXECUTION DEMO ")
    print("=" * 60)

    ex = AlmgrenChrissExecutor(
        X0=500_000, # 500k shares to sell
        T=2.0, # 2 trading days
        sigma=0.015, # 1.5% daily vol
        eta=0.05, # temporary impact coeff
        gamma=0.005, # permanent impact coeff
        lam=2e-6) # risk aversion

    print(f" Expected IS cost : ${ex.expected_cost():>12,.2f}")
    print(f" Cost std-dev     : ${np.sqrt(ex.cost_variance()):>12,.2f}")
    print(f" kappa            : {ex.kappa:.4f}")
    print(f" kappa * T        : {ex.kappa * ex.T:.4f}")

    comp = ex.compare_schedules()
    print("\nSchedule cost comparison:")
    print(comp.round(0).to_string())

    ex.plot()

    # ML demo on synthetic data
    np.random.seed(42)
    n = 1000
    df_syn = pd.DataFrame({
        'order_size': np.random.lognormal(10, 1, n),
        'adv': np.random.lognormal(14, 0.5, n),
        'spread_bps': np.random.exponential(5, n),
        'daily_vol': np.random.uniform(0.01, 0.04, n),
        'time_of_day': np.random.uniform(0, 1, n),
        'urgency': np.random.uniform(0, 1, n),
    })
    df_syn['adv'] = np.maximum(df_syn['adv'], df_syn['order_size'])
    true_impact = (10 * np.sqrt(df_syn['order_size'] / df_syn['adv']) * df_syn['daily_vol'] * 10000 + np.random.normal(0, 2, n))

    ml = MLImpactModel()
    ml.fit(df_syn, true_impact)
    result = ml.pre_trade_sweep(1e5, 5e6, 8.0, 0.02)
    print(f"\nOptimal participation: {result['optimal_participation']:.2%}")
    print(f"Minimum impact (bps): {result['min_impact_bps']:.2f}")
    print(f"Recommended duration: {result['rec_duration_hours']:.2f} hours")
    return ex, ml


if __name__ == "__main__":
    ex, ml = demo_impact()


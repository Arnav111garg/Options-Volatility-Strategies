# 2. ML - BASED MARKET IMPACT ESTIMATOR
#
class MLImpactModel:
    """
    Gradient - boosting model for pre - trade impact estimation .
    Features beyond the Almgren - Chriss parametric model:
    Time - of - day effects (open/close carry higher impact)
    Volatility regime (stressed markets amplify impact)
    Order - book depth at the moment of execution
    Recent fill quality (adverse - selection feedback)
    """

    def __init__(self):
        self.gbm = GradientBoostingRegressor(
            n_estimators=300, max_depth=4,
            learning_rate=0.05, subsample=0.8,
            min_samples_leaf=20, random_state=42)
        self.scaler = StandardScaler()
        self.fitted = False

    # feature engineering
    @staticmethod
    def build_features(df: pd.DataFrame) -> pd.DataFrame:
        """
        df must contain columns:
        order_size, adv, spread_bps, daily_vol,
        time_of_day [0=open, 1=close], urgency [0=passive, 1=aggr],
        book_depth (optional).
        """
        f = pd.DataFrame(index=df.index)
        adv = df['adv'].replace(0, np.nan)
        f['sqrt_part'] = np.sqrt(df['order_size'] / adv)
        f['log_size'] = np.log1p(df['order_size'])
        f['spread_norm'] = df['spread_bps'] / (df['daily_vol'] * 10000 + 1e-9)
        f['vol_ratio'] = df['daily_vol'] / (df['daily_vol'].rolling(20, min_periods=5).mean() + 1e-9)

        tod = df['time_of_day']
        f['tod_sin'] = np.sin(2 * np.pi * tod)
        f['tod_cos'] = np.cos(2 * np.pi * tod)
        f['open_30m'] = (tod < 0.077).astype(float)
        f['close_30m'] = (tod > 0.923).astype(float)

        f['urgency'] = df['urgency']
        depth = df.get('book_depth', pd.Series(adv * 0.001, index=df.index))
        f['inv_depth'] = 1.0 / (np.log1p(depth) + 1e-9)

        # Interactions
        f['urg_x_invD'] = f['urgency'] * f['inv_depth']
        f['part_x_vol'] = f['sqrt_part'] * f['vol_ratio']
        return f.fillna(0)

    # fit
    def fit(self, df: pd.DataFrame, impact_bps: pd.Series):
        X = self.build_features(df)
        Xs = self.scaler.fit_transform(X)
        self.gbm.fit(Xs, impact_bps)
        self.fitted = True
        y_hat = self.gbm.predict(Xs)
        ss_res = np.sum((impact_bps - y_hat) ** 2)
        ss_tot = np.sum((impact_bps - impact_bps.mean()) ** 2)
        print(f"ML Impact Model in-sample R2 = {1 - ss_res / ss_tot:.4f}")

    # predict
    def predict(self, df: pd.DataFrame) -> np.ndarray:
        if not self.fitted:
            raise RuntimeError("Call fit() first.")
        X = self.build_features(df)
        return self.gbm.predict(self.scaler.transform(X))

    # pre - trade sweep
    def pre_trade_sweep(self, order_size, adv, spread_bps, daily_vol, urgency=0.5, time_of_day=0.5):
        """
        Sweep over participation rates to find the minimum-impact schedule.
        Returns optimal participation rate and expected impact in bps.
        """
        parts = np.linspace(0.01, 0.40, 40)
        impacts = []
        for p in parts:
            spec = pd.DataFrame([{
                'order_size': adv * p,
                'adv': adv,
                'spread_bps': spread_bps,
                'daily_vol': daily_vol,
                'time_of_day': time_of_day,
                'urgency': urgency,
                'book_depth': adv * 0.002,
            }])
            if self.fitted:
                impacts.append(self.predict(spec)[0])
            else:  # square-root fallback
                impacts.append(0.10 * np.sqrt(p) * daily_vol * 10000)

        best_idx = int(np.argmin(impacts))
        return {
            'participation_rates': parts,
            'impacts_bps': np.array(impacts),
            'optimal_participation': parts[best_idx],
            'min_impact_bps': impacts[best_idx],
            'rec_duration_hours': order_size / (adv * parts[best_idx] * 6.5),
        }



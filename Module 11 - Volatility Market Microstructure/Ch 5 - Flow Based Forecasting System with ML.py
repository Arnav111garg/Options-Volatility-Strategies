class FlowForecastingModel:
    """
    Ensemble model for flow-based return forecasting.
    """
    def __init__(self, horizon_days: int = 5):
        self.horizon = horizon_days
        self.scaler = StandardScaler()
        self.models = {
            'ridge': Ridge(alpha=10.0),
            'elastic': ElasticNet(alpha=0.01, l1_ratio=0.5),
            'gbm': GradientBoostingRegressor(n_estimators=200, max_depth=3, learning_rate=0.05, subsample=0.8, random_state=42),
            'rf': RandomForestRegressor(n_estimators=200, max_depth=4, min_samples_leaf=20, random_state=42)
        }
        self.ensemble_weights = None
        self.feature_importance = None
        self.is_trained = False

    def train(self, X: pd.DataFrame, y: pd.Series, n_splits: int = 5) -> Dict:
        """
        Train ensemble with time-series cross-validation.
        """
        common_idx = X.index.intersection(y.index)
        X_clean = X.loc[common_idx].copy()
        y_clean = y.loc[common_idx].copy()
        mask = ~(X_clean.isna().any(axis=1) | y_clean.isna())
        X_clean = X_clean[mask]
        y_clean = y_clean[mask]

        print(f"Training on {len(X_clean)} samples, {X_clean.shape[1]} features")
        print(f"Target horizon: {self.horizon} days forward returns")

        tscv = TimeSeriesSplit(n_splits=n_splits)
        cv_scores = {name: [] for name in self.models}

        for fold, (train_idx, val_idx) in enumerate(tscv.split(X_clean)):
            X_tr = X_clean.iloc[train_idx]
            y_tr = y_clean.iloc[train_idx]
            X_val = X_clean.iloc[val_idx]
            y_val = y_clean.iloc[val_idx]

            scaler_fold = StandardScaler()
            X_tr_scaled = scaler_fold.fit_transform(X_tr)
            X_val_scaled = scaler_fold.transform(X_val)

            for name, model in self.models.items():
                model.fit(X_tr_scaled, y_tr)
                y_pred = model.predict(X_val_scaled)
                r2 = r2_score(y_val, y_pred)
                cv_scores[name].append(r2)

        print("\n--- Cross-Validation R2 Scores ---")
        for name, scores in cv_scores.items():
            print(f"{name:12s}: {np.mean(scores):.4f} (std: {np.std(scores):.4f})")

        X_scaled = self.scaler.fit_transform(X_clean)
        for name, model in self.models.items():
            model.fit(X_scaled, y_clean)

        mean_scores = {name: max(0, np.mean(scores)) for name, scores in cv_scores.items()}
        total = sum(mean_scores.values())
        if total > 0:
            self.ensemble_weights = {k: v / total for k, v in mean_scores.items()}
        else:
            n = len(self.models)
            self.ensemble_weights = {k: 1/n for k in self.models}

        print("\n--- Ensemble Weights ---")
        for name, w in self.ensemble_weights.items():
            print(f"{name:12s}: {w:.3f}")

        if hasattr(self.models['gbm'], 'feature_importances_'):
            self.feature_importance = pd.Series(
                self.models['gbm'].feature_importances_,
                index=X_clean.columns
            ).sort_values(ascending=False)

        self.feature_names = X_clean.columns.tolist()
        self.is_trained = True

        return {
            'cv_scores': cv_scores,
            'ensemble_weights': self.ensemble_weights,
            'feature_importance': self.feature_importance
        }

    def predict(self, X: pd.DataFrame) -> np.ndarray:
        """Generate ensemble predictions."""
        if not self.is_trained:
            raise RuntimeError("Model must be trained before prediction.")
        X_scaled = self.scaler.transform(X)
        predictions = {}
        for name, model in self.models.items():
            predictions[name] = model.predict(X_scaled)
        ensemble_pred = np.zeros(len(X))
        for name, pred in predictions.items():
            ensemble_pred += self.ensemble_weights[name] * pred
        return ensemble_pred

    def predict_with_confidence(self, X: pd.DataFrame) -> Tuple[np.ndarray, np.ndarray]:
        """Predictions with uncertainty."""
        X_scaled = self.scaler.transform(X)
        predictions = np.array([
            model.predict(X_scaled) for model in self.models.values()
        ])
        mean_pred = predictions.mean(axis=0)
        std_pred = predictions.std(axis=0)
        return mean_pred, std_pred

    def plot_feature_importance(self):
        """Visualize feature importance."""
        if self.feature_importance is None:
            print("Feature importance not available.")
            return
        top_n = min(15, len(self.feature_importance))
        fi = self.feature_importance.head(top_n)
        fig, ax = plt.subplots(figsize=(10, 6))
        colors = ['#1a3a6b' if i < 5 else '#4a7fbf' if i < 10 else '#8ab0d4' for i in range(len(fi))]
        bars = ax.barh(range(len(fi)), fi.values, color=colors)
        ax.set_yticks(range(len(fi)))
        ax.set_yticklabels(fi.index, fontsize=10)
        ax.set_xlabel('Feature Importance (GBM)', fontsize=12)
        ax.set_title('Flow Signal Feature Importance', fontsize=13, fontweight='bold', color='darkblue')
        ax.grid(True, alpha=0.3, axis='x')
        for bar, val in zip(bars, fi.values):
            ax.text(val + 0.001, bar.get_y() + bar.get_height() / 2, f'{val:.3f}', va='center', fontsize=9)
        plt.tight_layout()
        plt.savefig('flow_feature_importance.png', dpi=150, bbox_inches='tight')
        plt.show()


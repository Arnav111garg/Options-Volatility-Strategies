# FLOW SIGNAL GENERATOR
# ============================================================
class OptionsFlowSignals:
    """
    Computes a comprehensive suite of flow-based signals from
    options market data.
    Each signal captures a different aspect of dealer / institutional
    positioning that has predictive power for future returns.
    """
    def __init__(self, r: float = 0.05):
        self.r = r

    def net_options_premium(self, df: pd.DataFrame) -> pd.Series:
        """
        NOP: Sum of call premium bought - put premium bought.
        df columns: [date, option_type, premium, volume, trade_side]
        trade_side: 'buy_to_open' or 'sell_to_open'
        """
        buys = df[df['trade_side'] == 'buy_to_open'].copy()
        call_premium = buys[buys['option_type'] == 'call'].groupby('date').apply(
            lambda x: (x['premium'] * x['volume']).sum()
        )
        put_premium = buys[buys['option_type'] == 'put'].groupby('date').apply(
            lambda x: (x['premium'] * x['volume']).sum()
        )
        nop = call_premium.subtract(put_premium, fill_value=0)
        return nop.rename('nop')

    def put_call_ratio(self, df: pd.DataFrame) -> pd.Series:
        """
        Volume-weighted put/call ratio. >1 = bearish, <1 = bullish.
        """
        call_vol = df[df['option_type'] == 'call'].groupby('date')['volume'].sum()
        put_vol = df[df['option_type'] == 'put'].groupby('date')['volume'].sum()
        pcr = put_vol / call_vol.replace(0, np.nan)
        return pcr.rename('pcr')

    def vanna_exposure(self, options_chain: pd.DataFrame, S: float, delta_sigma: float) -> float:
        """
        Total vanna flow given a volatility change of delta_sigma.
        options_chain: df with [strike, expiry_days, iv, open_interest, type]
        delta_sigma: assumed vol change (e.g., 0.01 for 1% IV move)
        """
        total_vanna = 0.0
        for _, row in options_chain.iterrows():
            K = row['strike']
            T = max(row['expiry_days'] / 365.0, 1/365)
            sigma = row['iv']
            oi = row['open_interest']
            if sigma <= 0 or T <= 0:
                continue
            d1 = (np.log(S / K) + (self.r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
            d2 = d1 - sigma * np.sqrt(T)
            vanna = -norm.pdf(d1) * d2 / sigma
            sign = 1 if row['option_type'] == 'call' else -1
            total_vanna += sign * oi * 100 * vanna
        return total_vanna * delta_sigma * S

    def charm_flow(self, options_chain: pd.DataFrame, S: float) -> float:
        """
        Total daily charm flow (delta decay from time passage).
        Represents mechanical end-of-day hedging demand.
        """
        total_charm = 0.0
        for _, row in options_chain.iterrows():
            K = row['strike']
            T = max(row['expiry_days'] / 365.0, 1/365)
            sigma = row['iv']
            oi = row['open_interest']
            if sigma <= 0 or T <= 0:
                continue
            d1 = (np.log(S / K) + (self.r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
            d2 = d1 - sigma * np.sqrt(T)
            charm = (-norm.pdf(d1) / (2 * T) * (2 * self.r * T - d2 * sigma * np.sqrt(T)) / (sigma * np.sqrt(T)))
            if row['option_type'] == 'put':
                charm = -charm
            total_charm += oi * 100 * charm
        return total_charm / 252

    def dealer_delta_position(self, options_chain: pd.DataFrame, S: float) -> float:
        """
        Estimate dealer's net delta position.
        Negative = dealers net short delta (bullish for stock via hedging).
        """
        total_dealer_delta = 0.0
        for _, row in options_chain.iterrows():
            K = row['strike']
            T = max(row['expiry_days'] / 365.0, 1/365)
            sigma = row['iv']
            oi = row['open_interest']
            d1 = (np.log(S / K) + (self.r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
            delta = norm.cdf(d1)
            if row['option_type'] == 'put':
                delta = delta - 1
            cust_pos = row.get('customer_net_position', 1.0)
            total_dealer_delta += -cust_pos * oi * 100 * delta
        return total_dealer_delta

    def skew_signal(self, options_chain: pd.DataFrame) -> float:
        """
        25-delta skew as a flow signal.
        High skew (expensive puts) = bearish flow;
        Negative skew (expensive calls) = bullish flow / squeeze setup.
        """
        call_25d = options_chain[
            (options_chain['option_type'] == 'call') &
            (options_chain['delta'].between(0.20, 0.30))
        ]
        put_25d = options_chain[
            (options_chain['option_type'] == 'put') &
            (options_chain['delta'].between(-0.30, -0.20))
        ]
        if call_25d.empty or put_25d.empty:
            return 0.0
        iv_call_25 = call_25d['iv'].mean()
        iv_put_25 = put_25d['iv'].mean()
        return iv_put_25 - iv_call_25

    def build_feature_matrix(self, flow_history: pd.DataFrame) -> pd.DataFrame:
        """
        Build the feature matrix for ML-based flow forecasting.
        """
        features = pd.DataFrame(index=flow_history.index)
        features['nop_norm'] = flow_history['nop'] / flow_history['nop'].rolling(20).std()
        features['pcr_zscore'] = (flow_history['pcr'] - flow_history['pcr'].rolling(20).mean()) / flow_history['pcr'].rolling(20).std()
        features['gex_norm'] = flow_history['gex_M'] / flow_history['gex_M'].abs().rolling(20).mean()
        features['vanna_norm'] = flow_history['vanna_flow'] / flow_history['vanna_flow'].abs().rolling(20).mean().replace(0, 1)
        features['charm_norm'] = flow_history['charm_flow'] / flow_history['charm_flow'].abs().rolling(20).mean().replace(0, 1)
        features['dealer_delta_norm'] = flow_history['dealer_delta'] / flow_history['dealer_delta'].abs().rolling(20).mean().replace(0, 1)
        features['skew'] = flow_history['skew_25d']

        for col in ['nop_norm', 'gex_norm', 'skew']:
            features[f'd_{col}_5d'] = features[col].diff(5)

        features['rv_20d'] = flow_history['realized_vol']
        features['vol_regime'] = (features['rv_20d'] > features['rv_20d'].rolling(60).quantile(0.7)).astype(int)
        features['nop_x_gex'] = features['nop_norm'] * features['gex_norm']
        features['vanna_x_vol'] = features['vanna_norm'] * features['rv_20d']
        features['day_of_week'] = pd.to_datetime(flow_history.index).dayofweek
        features['is_opex_week'] = (pd.to_datetime(flow_history.index).day >= 15).astype(int)

        return features.dropna()


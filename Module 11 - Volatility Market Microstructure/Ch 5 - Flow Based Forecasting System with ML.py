# BACKTESTING THE FLOW SIGNAL
# ============================================================
class FlowSignalBacktest:
    """
    Strategy backtest driven by flow-based signals.
    """
    def __init__(self, model: FlowForecastingModel, long_threshold: float = 0.003, short_threshold: float = -0.003, position_size: float = 1.0):
        self.model = model
        self.long_thresh = long_threshold
        self.short_thresh = short_threshold
        self.base_size = position_size

    def run(self, X: pd.DataFrame, returns: pd.Series) -> pd.DataFrame:
        """Run strategy backtest."""
        preds, uncert = self.model.predict_with_confidence(X)
        max_uncert = np.percentile(uncert, 95)
        confidence = 1.0 - np.clip(uncert / (max_uncert + 1e-10), 0, 1)

        signals = pd.Series(preds, index=X.index)
        conf_series = pd.Series(confidence, index=X.index)
        positions = pd.Series(0.0, index=X.index)
        positions[signals > self.long_thresh] = self.base_size * conf_series[signals > self.long_thresh]
        positions[signals < self.short_thresh] = -self.base_size * conf_series[signals < self.short_thresh]

        common_idx = positions.index.intersection(returns.index)
        pos = positions.loc[common_idx]
        ret = returns.loc[common_idx]
        strat_returns = pos.shift(1) * ret
        strat_returns = strat_returns.dropna()

        ann_ret = strat_returns.mean() * 252
        ann_vol = strat_returns.std() * np.sqrt(252)
        sharpe = ann_ret / (ann_vol + 1e-10)
        max_dd = self._max_drawdown(strat_returns.cumsum())
        hit_rate = (strat_returns > 0).mean()

        print("\n" + "=" * 60)
        print("FLOW-BASED STRATEGY BACKTEST RESULTS")
        print("=" * 60)
        print(f"Annualized Return : {ann_ret * 100:.2f}%")
        print(f"Annualized Vol    : {ann_vol * 100:.2f}%")
        print(f"Sharpe Ratio      : {sharpe:.2f}")
        print(f"Max Drawdown      : {max_dd * 100:.2f}%")
        print(f"Hit Rate          : {hit_rate * 100:.1f}%")
        print(f"Calmar Ratio      : {ann_ret / (-max_dd + 1e-10):.2f}")
        print("=" * 60)

        results = pd.DataFrame({
            'signal': signals,
            'position': positions,
            'confidence': conf_series,
            'strat_return': strat_returns.reindex(X.index, fill_value=0),
            'bm_return': ret.reindex(X.index, fill_value=0)
        })
        results['strat_cumret'] = (1 + results['strat_return']).cumprod()
        results['bm_cumret'] = (1 + results['bm_return']).cumprod()
        return results

    @staticmethod
    def _max_drawdown(cum_returns: pd.Series) -> float:
        running_max = cum_returns.expanding().max()
        drawdown = cum_returns - running_max
        return drawdown.min()

    def plot_backtest(self, results: pd.DataFrame):
        """Plot performance plots."""
        fig, axes = plt.subplots(3, 2, figsize=(15, 12))

        ax = axes[0, 0]
        ax.plot(results.index, results['strat_cumret'], 'b-', lw=2, label='Flow Strategy')
        ax.plot(results.index, results['bm_cumret'], 'gray', lw=1.5, linestyle='--', label='Buy & Hold')
        ax.set_title('Cumulative Returns', fontweight='bold')
        ax.set_ylabel('Portfolio Value')
        ax.legend()
        ax.grid(True, alpha=0.3)

        ax = axes[0, 1]
        ax.hist(results['signal'].dropna(), bins=50, density=True, color='steelblue', alpha=0.7)
        ax.axvline(x=self.long_thresh, color='green', lw=2, linestyle='--', label='Long threshold')
        ax.axvline(x=self.short_thresh, color='red', lw=2, linestyle='--', label='Short threshold')
        ax.set_title('Signal Distribution', fontweight='bold')
        ax.set_xlabel('Predicted Return')
        ax.legend(fontsize=8)
        ax.grid(True, alpha=0.3)

        ax = axes[1, 0]
        roll_sharpe = (results['strat_return'].rolling(60).mean() * 252) / (results['strat_return'].rolling(60).std() * np.sqrt(252) + 1e-10)
        ax.plot(results.index, roll_sharpe, 'purple', lw=1.5)
        ax.axhline(y=0, color='black', lw=0.5)
        ax.axhline(y=1.0, color='green', lw=1, linestyle='--', label='Sharpe = 1')
        ax.set_title('Rolling 60-Day Sharpe Ratio', fontweight='bold')
        ax.legend()
        ax.grid(True, alpha=0.3)

        ax = axes[1, 1]
        ax.fill_between(results.index, results['position'], 0, where=results['position'] > 0, alpha=0.6, color='green', label='Long')
        ax.fill_between(results.index, results['position'], 0, where=results['position'] < 0, alpha=0.6, color='red', label='Short')
        ax.axhline(y=0, color='black', lw=0.5)
        ax.set_title('Position Over Time', fontweight='bold')
        ax.legend()
        ax.grid(True, alpha=0.3)

        ax = axes[2, 0]
        monthly = results['strat_return'].resample('ME').sum()
        colors_m = ['green' if r > 0 else 'red' for r in monthly.values]
        ax.bar(range(len(monthly)), monthly.values * 100, color=colors_m, alpha=0.7)
        ax.set_title('Monthly Returns (%)', fontweight='bold')
        ax.grid(True, alpha=0.3)

        ax = axes[2, 1]
        conf_bins = pd.qcut(results['confidence'].dropna(), q=5, labels=['Very Low', 'Low', 'Med', 'High', 'Very High'])
        strat_ret_clean = results['strat_return'].reindex(conf_bins.index)
        hit_by_conf = (strat_ret_clean > 0).groupby(conf_bins).mean()
        ax.bar(range(len(hit_by_conf)), hit_by_conf.values * 100, color='steelblue', alpha=0.7)
        ax.set_xticks(range(len(hit_by_conf)))
        ax.set_xticklabels(hit_by_conf.index, rotation=45, fontsize=9)
        ax.axhline(y=50, color='red', lw=1, linestyle='--', label='Random (50%)')
        ax.set_title('Hit Rate by Confidence Level', fontweight='bold')
        ax.legend(fontsize=8)
        ax.grid(True, alpha=0.3)

        plt.suptitle('Flow-Based Strategy Backtest Analysis', fontsize=14, fontweight='bold', y=1.01)
        plt.tight_layout()
        plt.savefig('flow_backtest.png', dpi=150, bbox_inches='tight')
        plt.show()


# LIQUIDITY REGIME DETECTOR
# ============================================================
class LiquidityRegimeDetector:
    """
    Hidden Markov Model-based detection of liquidity regimes.
    Uses observable liquidity proxies to infer the latent regime.
    Features:
    - Bid-ask spread (normalized)
    - Amihud illiquidity ratio
    - Realized vol (proxy for uncertainty)
    - Option bid-ask spread (IV uncertainty band)
    - Order book depth (if available)
    """
    def __init__(self, n_regimes: int = 3, n_iter: int = 200):
        self.n_regimes = n_regimes
        self.model = hmm.GaussianHMM(
            n_components=n_regimes,
            covariance_type='full',
            n_iter=n_iter,
            random_state=42
        )
        self.regime_labels = None
        self.is_fitted = False

    def prepare_features(self, data: pd.DataFrame) -> Tuple[np.ndarray, pd.Index]:
        """
        Prepare feature matrix from liquidity data.
        data columns: [bid_ask_spread, volume, abs_return, option_spread, depth (optional)]
        """
        features = pd.DataFrame(index=data.index)

        # 1. Amihud ratio (log-normalized)
        amihud = data['abs_return'] / (data['volume'] + 1e-10)
        features['log_amihud'] = np.log1p(amihud)

        # 2. Bid-ask spread (normalized by ATM option price)
        features['spread_norm'] = data['bid_ask_spread'] / (data.get('atm_price', pd.Series(1.0, index=data.index)) + 1e-10)

        # 3. Realized vol (rolling 5-day)
        features['rv_5d'] = data['abs_return'].rolling(5).mean() * np.sqrt(252)

        # 4. Volume ratio (today vs 20-day average)
        features['vol_ratio'] = data['volume'] / (data['volume'].rolling(20).mean() + 1e-10)

        # 5. Option spread in vol points (if available)
        if 'option_spread_iv' in data.columns:
            features['option_iv_spread'] = data['option_spread_iv']

        # Z-score normalize all features
        features = (features - features.rolling(60, min_periods=20).mean()) / (features.rolling(60, min_periods=20).std() + 1e-10)

        return features.dropna().values, features.dropna().index

    def fit(self, data: pd.DataFrame) -> None:
        """Fit HMM to liquidity data."""
        X, self.idx = self.prepare_features(data)
        self.model.fit(X)
        self.is_fitted = True

        # Predict regimes
        self.regimes = self.model.predict(X)
        self.regime_probs = self.model.predict_proba(X)

        # Label regimes by avg Amihud (0=liquid, K-1=illiquid)
        regime_means = {}
        for r in range(self.n_regimes):
            mask = self.regimes == r
            regime_means[r] = X[mask, 0].mean()  # First feature = Amihud

        # Sort: low Amihud = Regime 0 (liquid), high = Regime K (illiquid)
        sorted_regimes = sorted(regime_means, key=regime_means.get)
        self.regime_labels = {old: new for new, old in enumerate(sorted_regimes)}
        self.labeled_regimes = np.array([self.regime_labels[r] for r in self.regimes])

    def current_regime(self, recent_data: pd.DataFrame) -> dict:
        """
        Identify current liquidity regime and transition probabilities.
        Returns actionable information for risk management.
        """
        if not self.is_fitted:
            raise RuntimeError("Model not fitted.")

        X, _ = self.prepare_features(recent_data)
        if len(X) == 0:
            return {'regime': None, 'confidence': 0}

        probs = self.model.predict_proba(X)
        current_probs = probs[-1]  # Most recent observation
        current_raw = self.model.predict(X)[-1]
        current_labeled = self.regime_labels.get(current_raw, current_raw)

        regime_names = {0: 'Normal / Liquid', 1: 'Stressed', 2: 'Crisis / Illiquid'}

        # Transition probability to worse regime
        trans_matrix = self.model.transmat_
        worse_regime_prob = sum(trans_matrix[current_raw, j] for j in range(self.n_regimes) if j > current_raw)

        return {
            'regime': current_labeled,
            'regime_name': regime_names.get(current_labeled, f'Regime {current_labeled}'),
            'confidence': current_probs.max(),
            'prob_deterioration': worse_regime_prob,
            'probs': {regime_names.get(self.regime_labels.get(i, i), f'R{i}'): p for i, p in enumerate(current_probs)},
        }

    def compute_regime_options_adjustments(self, regime: int) -> dict:
        """
        Compute adjustments to options pricing and risk management
        for the current liquidity regime.
        Returns bid-ask adjustments, position limits, and hedging frequency.
        """
        adjustments = {
            0: {
                'bid_ask_multiplier': 1.0,
                'position_limit_pct': 1.0,
                'hedge_frequency': 'hourly',
                'vol_bump_pct': 0.0,
                'max_delta_unhedged': 0.05,
                'liquidity_premium_vol': 0.0,
            },
            1: {
                'bid_ask_multiplier': 2.5,
                'position_limit_pct': 0.6,
                'hedge_frequency': '30-minute',
                'vol_bump_pct': 0.03,
                'max_delta_unhedged': 0.02,
                'liquidity_premium_vol': 0.02,
            },
            2: {
                'bid_ask_multiplier': 6.0,
                'position_limit_pct': 0.2,
                'hedge_frequency': 'continuous',
                'vol_bump_pct': 0.10,
                'max_delta_unhedged': 0.005,
                'liquidity_premium_vol': 0.08,
            }
        }
        return adjustments.get(regime, adjustments[0])

    def plot_regimes(self, price_series: pd.Series) -> None:
        """Visualize detected regimes against price history."""
        fig, (ax1, ax2, ax3) = plt.subplots(3, 1, figsize=(15, 12), sharex=True)

        regime_colors = {0: 'green', 1: 'orange', 2: 'red'}
        regime_names = {0: 'Normal', 1: 'Stressed', 2: 'Crisis'}

        # Price with regime background shading
        common_idx = price_series.index.intersection(pd.Index(self.idx))
        price_aligned = price_series.loc[common_idx]
        regimes_aligned = pd.Series(self.labeled_regimes, index=self.idx)
        regimes_aligned = regimes_aligned.loc[common_idx]

        ax1.plot(price_aligned.index, price_aligned, 'b-', lw=1.5, label='Price')

        # Shade by regime
        for regime_id, color in regime_colors.items():
            mask = regimes_aligned == regime_id
            if mask.any():
                start = None
                for date, is_regime in mask.items():
                    if is_regime and start is None:
                        start = date
                    elif not is_regime and start is not None:
                        ax1.axvspan(start, date, alpha=0.2, color=color, label=f'{regime_names[regime_id]} Regime')
                        start = None

        ax1.set_title('Price History with Liquidity Regimes', fontweight='bold')
        ax1.set_ylabel('Price')
        ax1.legend(fontsize=8)
        ax1.grid(True, alpha=0.3)

        # Regime probabilities
        prob_df = pd.DataFrame(self.regime_probs, index=self.idx, columns=[regime_names.get(self.regime_labels.get(i, i), f'R{i}') for i in range(self.n_regimes)])
        prob_df = prob_df.loc[common_idx]

        for col in prob_df.columns:
            ax2.plot(prob_df.index, prob_df[col], label=col, lw=1.5)

        ax2.set_title('Regime Probabilities', fontweight='bold')
        ax2.set_ylabel('Probability')
        ax2.legend(fontsize=8)
        ax2.grid(True, alpha=0.3)

        # Labeled regime
        ax3.plot(regimes_aligned.index, regimes_aligned.values, color='darkblue', lw=1, drawstyle='steps-post')
        ax3.set_yticks([0, 1, 2])
        ax3.set_yticklabels(['Normal', 'Stressed', 'Crisis'])
        ax3.set_title('Current Liquidity Regime', fontweight='bold')
        ax3.set_ylabel('Regime')
        ax3.set_xlabel('Date')
        ax3.grid(True, alpha=0.3)

        plt.tight_layout()
        plt.savefig('liquidity_regimes.png', dpi=150, bbox_inches='tight')
        plt.show()


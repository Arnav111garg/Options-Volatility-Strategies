# LIQUIDITY - ADJUSTED OPTIONS PRICING
# ============================================================
class LiquidityAdjustedPricer:
    """
    Options pricer that adjusts for liquidity regime.
    Adds liquidity premium to options prices in stressed / crisis regimes.
    Theoretical basis: Acharya & Pedersen (2005) liquidity-adjusted CAPM adapted to the options market.
    """
    def __init__(self, base_pricer, regime_detector: LiquidityRegimeDetector):
        self.base_pricer = base_pricer
        self.detector = regime_detector

    def liquidity_premium_vol(self, K: float, T: float, regime: int, base_iv: float) -> float:
        """
        Compute the liquidity premium in vol points for a given option.
        The premium depends on:
        1. Moneyness (OTM options less liquid -> higher premium)
        2. Expiry (far-dated options less liquid)
        3. Regime (stressed / crisis significantly increases premium)
        """
        adj = self.detector.compute_regime_options_adjustments(regime)
        base_premium = adj['liquidity_premium_vol']

        # OTM options get additional premium
        S = self.base_pricer.S
        moneyness = abs(np.log(K / S))
        otm_factor = 1.0 + 2.0 * moneyness  # Higher premium for OTM

        # Longer-dated options: liquidity degrades
        dte_factor = 1.0 + 0.1 * max(0, T * 252 - 30) / 30

        return base_premium * otm_factor * dte_factor

    def adjusted_price(self, K: float, tau_minutes: float, base_iv: float, regime: int, option_type: str = 'call') -> dict:
        """Price option with liquidity adjustment."""
        T = tau_minutes / (390 * 252)
        liq_premium = self.liquidity_premium_vol(K, T, regime, base_iv)
        adjusted_iv = base_iv + liq_premium

        base_result = self.base_pricer.price_0dte(K, tau_minutes, base_iv, option_type)
        adj_result = self.base_pricer.price_0dte(K, tau_minutes, adjusted_iv, option_type)

        return {
            **adj_result,
            'base_price': base_result['price'],
            'liquidity_premium_price': adj_result['price'] - base_result['price'],
            'liquidity_premium_vol': liq_premium,
            'adjusted_iv': adjusted_iv,
            'regime': regime,
        }


# BLACK - SCHOLES (reuse)
# ============================================================
def bs_price_delta(S, K, T, r, sigma, otype='call'):
    if T <= 1e-10 or sigma <= 1e-10:
        p = max(S - K, 0.0) if otype == 'call' else max(K - S, 0.0)
        d = (1.0 if S > K else 0.0) if otype == 'call' else (-1.0 if S < K else 0.0)
        return p, d, 0.0, 0.0
    d1 = (np.log(S / K) + (r + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    nd1 = norm.pdf(d1)
    if otype == 'call':
        p = S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
        d = norm.cdf(d1)
    else:
        p = K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)
        d = norm.cdf(d1) - 1.0
    g = nd1 / (S * sigma * np.sqrt(T))
    vega = S * np.sqrt(T) * nd1
    return p, d, g, vega


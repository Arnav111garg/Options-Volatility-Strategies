# 1. ALGORITHMIC MARKET MAKER
# ============================================================
class OptionsMarketMaker:
    """
    Simplified algorithmic market-maker skeleton.

    Implements:
    - Internal vol surface (parametric SVI-like smile)
    - Avellaneda-Stoikov spread calculation
    - Risk-limit enforcement (delta, gamma, vega)
    - Fill processing and delta hedging
    """
    def __init__(self, S: float, base_iv: float, r: float = 0.05,
                 gamma_risk: float = 1e-4, kappa_arr: float = 5.0,
                 max_delta: float = 50_000.0, max_gamma: float = 200_000.0,
                 max_vega: float = 500_000.0, hedge_cost_bps: float = 2.0):
        self.S = S
        self.base_iv = base_iv
        self.r = r
        self.gamma_risk = gamma_risk       # Avellaneda-Stoikov gamma
        self.kappa = kappa_arr             # order-arrival intensity
        self.max_delta = max_delta
        self.max_gamma = max_gamma
        self.max_vega = max_vega
        self.hedge_cost = hedge_cost_bps / 10_000.0

        # Book state
        self.net_delta = 0.0
        self.net_gamma = 0.0
        self.net_vega = 0.0
        self.inventory = {}                # opt_id -> (qty, strike, T, otype)
        self.pnl = 0.0
        self.n_fills = 0

    def _fair_iv(self, K: float, T: float) -> float:
        x = np.log(K / self.S)
        rho = -0.55
        b = 0.30
        m = 0.0
        s = 0.18
        w = self.base_iv ** 2 * T + b * (rho * (x - m) + np.sqrt((x - m) ** 2 + s ** 2))
        return float(np.sqrt(max(w / max(T, 1e-6), 0.01)))

    def _half_spread_vol(self, T_rem: float) -> float:
        """Half-spread in implied-vol points."""
        gamma_spread = self.gamma_risk * self.base_iv ** 2 * T_rem / 2.0
        arrival_term = (1.0 / self.gamma_risk) * np.log(1.0 + self.gamma_risk / self.kappa)
        return gamma_spread + arrival_term * 0.005

    def quote(self, K: float, T: float, otype: str = 'call') -> dict:
        """Generate bid/ask quote for one option."""
        fv_iv = self._fair_iv(K, T)
        _, delta, gamma, vega = bs_price_delta(self.S, K, T, self.r, fv_iv, otype)

        hs_vol = self._half_spread_vol(T)
        otm_fact = 1.0 + 2.0 * abs(np.log(K / self.S))
        hs_vol *= otm_fact

        # Inventory skew
        inv_skew = -self.net_delta / (self.max_delta + 1.0) * 0.003

        bid_iv = max(fv_iv - hs_vol + inv_skew, 0.005)
        ask_iv = fv_iv + hs_vol + inv_skew

        bid_p, *_ = bs_price_delta(self.S, K, T, self.r, bid_iv, otype)
        ask_p, *_ = bs_price_delta(self.S, K, T, self.r, ask_iv, otype)
        mid_p, *_ = bs_price_delta(self.S, K, T, self.r, fv_iv, otype)

        return dict(
            fair_iv=fv_iv, bid_iv=bid_iv, ask_iv=ask_iv,
            mid_price=mid_p, bid_price=bid_p, ask_price=ask_p,
            spread_vol=2.0 * hs_vol, delta=delta, gamma=gamma, vega=vega
        )

    def _risk_ok(self, d_delta, d_gamma, d_vega) -> tuple:
        nd = abs(self.net_delta + d_delta)
        ng = abs(self.net_gamma + d_gamma)
        nv = abs(self.net_vega + d_vega)
        if nd > self.max_delta:
            return False, f"Delta breach: {nd:.0f}"
        if ng > self.max_gamma:
            return False, f"Gamma breach: {ng:.0f}"
        if nv > self.max_vega:
            return False, f"Vega breach: {nv:.0f}"
        return True, "OK"

    def fill(self, K: float, T: float, qty: int, side: str, otype: str = 'call') -> dict:
        q = self.quote(K, T, otype)
        sign = -1 if side == 'buy' else +1
        mm_q = sign * qty

        d_delta = mm_q * 100 * q['delta']
        d_gamma = mm_q * 100 * q['gamma']
        d_vega = mm_q * 100 * q['vega']

        ok, reason = self._risk_ok(d_delta, d_gamma, d_vega)
        if not ok:
            return dict(filled=False, reason=reason)

        exec_p = q['ask_price'] if side == 'buy' else q['bid_price']
        edge = qty * 100 * abs(exec_p - q['mid_price'])

        opt_id = f"{otype}_{K:.0f}_{T * 252:.0f}d"
        self.inventory[opt_id] = (self.inventory.get(opt_id, (0,))[0] + mm_q, K, T, otype)
        self.net_delta += d_delta
        self.net_gamma += d_gamma
        self.net_vega += d_vega
        self.pnl += edge
        self.n_fills += 1

        return dict(
            filled=True, exec_price=exec_p, edge=edge, fair_iv=q['fair_iv'],
            net_delta=self.net_delta, net_gamma=self.net_gamma
        )

    def hedge_delta(self, lam_impact: float = 1e-9) -> dict:
        shares = -self.net_delta
        if abs(shares) < 1.0:
            return dict(shares=0.0, cost=0.0)
        impact = lam_impact * abs(shares) * self.S
        exec_p = self.S + np.sign(shares) * impact
        cost = abs(shares) * self.S * self.hedge_cost
        self.pnl -= cost
        self.net_delta = 0.0
        return dict(shares=shares, exec_price=exec_p, cost=cost)

    def status(self) -> dict:
        return dict(
            n_fills=self.n_fills, net_delta=self.net_delta,
            net_gamma=self.net_gamma, net_vega=self.net_vega,
            pnl=self.pnl, n_positions=len(self.inventory)
        )


# 2. HAR-RV VOLATILITY FORECASTER
# ============================================================
class HARRVForecaster:
    """
    Heterogeneous Auto-Regressive Realised Volatility model.
    Corsi (2009): RV_{t+h} = beta0 + betaD * RV_t + betaW * RV_{t-5:t} + betaM * RV_{t-22:t} + epsilon
    """
    def __init__(self):
        self.linear_model = LinearRegression()
        self.ml_model = GradientBoostingRegressor(
            n_estimators=200, max_depth=3, learning_rate=0.05,
            subsample=0.8, random_state=42
        )
        self.scaler = StandardScaler()
        self._fit_linear = False
        self._fit_ml = False

    @staticmethod
    def _make_har_features(rv_series: pd.Series) -> pd.DataFrame:
        df = pd.DataFrame({'rv_d': rv_series})
        df['rv_w'] = rv_series.rolling(5).mean()
        df['rv_m'] = rv_series.rolling(22).mean()
        df['vov'] = rv_series.rolling(22).std()
        df['rv_sq'] = rv_series ** 2
        return df.dropna()

    def fit(self, returns: pd.Series, horizon: int = 5):
        rv = (returns ** 2).rolling(1).sum() * 252
        features = self._make_har_features(rv)
        target = rv.rolling(horizon).mean().shift(-horizon)

        both = features.join(target.rename('target')).dropna()
        X = both[features.columns]
        y = both['target']

        split = int(0.70 * len(X))
        X_tr, y_tr = X.iloc[:split], y.iloc[:split]
        X_te, y_te = X.iloc[split:], y.iloc[split:]

        self.linear_model.fit(X_tr[['rv_d', 'rv_w', 'rv_m']], y_tr)
        yh_lin = self.linear_model.predict(X_te[['rv_d', 'rv_w', 'rv_m']])
        ss_res = np.sum((y_te - yh_lin) ** 2)
        ss_tot = np.sum((y_te - y_te.mean()) ** 2)
        r2_lin = 1.0 - ss_res / ss_tot
        self._fit_linear = True

        Xs = self.scaler.fit_transform(X_tr)
        self.ml_model.fit(Xs, y_tr)
        yh_ml = self.ml_model.predict(self.scaler.transform(X_te))
        r2_ml = 1.0 - np.sum((y_te - yh_ml) ** 2) / ss_tot
        self._fit_ml = True

        print(f"HAR-RV (horizon={horizon}d) Linear OOS R2 = {r2_lin:.4f} | ML OOS R2 = {r2_ml:.4f}")
        print(f"  beta_d = {self.linear_model.coef_[0]:.4f} | beta_w = {self.linear_model.coef_[1]:.4f} | beta_m = {self.linear_model.coef_[2]:.4f} | intercept = {self.linear_model.intercept_:.5f}")

        return dict(
            r2_linear_oos=r2_lin, r2_ml_oos=r2_ml,
            coef_d=self.linear_model.coef_[0],
            coef_w=self.linear_model.coef_[1],
            coef_m=self.linear_model.coef_[2]
        )

    def predict_linear(self, rv_series: pd.Series) -> pd.Series:
        feats = self._make_har_features(rv_series)[['rv_d', 'rv_w', 'rv_m']]
        return pd.Series(self.linear_model.predict(feats), index=feats.index)

    def predict_ml(self, rv_series: pd.Series) -> pd.Series:
        feats = self._make_har_features(rv_series)
        Xs = self.scaler.transform(feats)
        return pd.Series(self.ml_model.predict(Xs), index=feats.index)

    def plot_forecast(self, returns: pd.Series, horizon: int = 5):
        rv = (returns ** 2) * 252
        f_lin = self.predict_linear(rv).rename('HAR Linear')
        f_ml = self.predict_ml(rv).rename('HAR ML')
        target = rv.rolling(horizon).mean().shift(-horizon).rename('Realised RV')

        fig, axes = plt.subplots(2, 1, figsize=(14, 8), sharex=True)

        for s, c in [(target, 'black'), (f_lin, 'blue'), (f_ml, 'red')]:
            axes[0].plot(s.index, s, color=c, lw=1.5, label=s.name)
        axes[0].set_title(f'HAR-RV Forecast vs. Realised RV (horizon={horizon}d)', fontweight='bold')
        axes[0].set_ylabel('Annualised RV')
        axes[0].legend()
        axes[0].grid(True, alpha=0.3)

        err_lin = f_lin - target
        err_ml = f_ml - target
        axes[1].plot(err_lin.index, err_lin, 'b-', lw=1.0, alpha=0.7, label='HAR Linear error')
        axes[1].plot(err_ml.index, err_ml, 'r-', lw=1.0, alpha=0.7, label='HAR ML error')
        axes[1].axhline(0, color='black', lw=0.5)
        axes[1].set_title('Forecast Errors', fontweight='bold')
        axes[1].set_ylabel('Error')
        axes[1].legend()
        axes[1].grid(True, alpha=0.3)

        plt.tight_layout()
        plt.savefig('har_rv_forecast.png', dpi=150, bbox_inches='tight')
        plt.show()
        print("Saved: har_rv_forecast.png")


# 1. Loss Functions ( Patton-Robust )
# ===========================================================
class VolForecastEvaluator:
    """
    Comprehensive volatility forecast evaluation toolkit.
    Implements all standard loss functions and statistical tests.
    Expects inputs in percentage-variance units (e.g. daily percentage returns squared)
    to ensure numerical stability and prevent QLIKE from evaluating to infinity.
    """

    def __init__(self, forecasts: dict, proxy: pd.Series):
        """
        Parameters
        ----------
        forecasts : dict of { model_name : pd.Series of forecasts (in daily % variance) }
        proxy : pd.Series of volatility proxy (daily % returns squared)
        """
        # Align all series and drop missing values
        common_idx = proxy.dropna().index
        for name, f in forecasts.items():
            common_idx = common_idx.intersection(f.dropna().index)

        self.proxy_var = proxy.loc[common_idx]
        self.forecasts_var = {name: f.loc[common_idx] for name, f in forecasts.items()}

    # -------------------------------------------------------
    # Loss Functions (Evaluated in standardized scale)
    # -------------------------------------------------------
    @staticmethod
    def _mse(forecast: np.ndarray, actual: np.ndarray) -> float:
        return np.mean((actual - forecast) ** 2)

    @staticmethod
    def _mae(forecast: np.ndarray, actual: np.ndarray) -> float:
        return np.mean(np.abs(actual - forecast))

    @staticmethod
    def _qlike(forecast: np.ndarray, actual: np.ndarray) -> float:
        """QLIKE = E[v/h - ln(v/h) - 1], Patton-robust with logarithmic floor"""
        h = np.maximum(forecast, 1e-6)
        v = np.maximum(actual, 1e-6)
        ratio = v / h
        return np.mean(ratio - np.log(ratio) - 1)

    @staticmethod
    def _hmse(forecast: np.ndarray, actual: np.ndarray) -> float:
        """Heteroskedasticity-adjusted MSE"""
        h = np.maximum(forecast, 1e-6)
        return np.mean(((actual - h) / h) ** 2)

    @staticmethod
    def _mape(forecast: np.ndarray, actual: np.ndarray) -> float:
        v = np.maximum(actual, 1e-6)
        return np.mean(np.abs((v - forecast) / v)) * 100

    # -------------------------------------------------------
    # Summary Table
    # -------------------------------------------------------
    def loss_table(self) -> pd.DataFrame:
        """Compute all loss functions for each model."""
        v = self.proxy_var.values
        rows = []

        for name, f_series in self.forecasts_var.items():
            h = f_series.values
            h = np.maximum(h, 1e-6)

            rows.append({
                'Model': name,
                'MSE': self._mse(h, v),
                'MAE': self._mae(h, v),
                'QLIKE': self._qlike(h, v),
                'HMSE': self._hmse(h, v),
                'MAPE (%)': self._mape(h, v),
                'R (MZ)': self._mz_r2(h, v)
            })

        df = pd.DataFrame(rows).set_index('Model')

        # Add rank columns
        for col in df.columns:
            if col == 'R (MZ)':
                df[f'{col}_rank'] = df[col].rank(ascending=False).astype(int)
            else:
                df[f'{col}_rank'] = df[col].rank().astype(int)

        return df

    def _mz_r2(self, forecast: np.ndarray, actual: np.ndarray) -> float:
        """Mincer-Zarnowitz regression R2."""
        X = np.column_stack([np.ones_like(forecast), forecast])
        beta = np.linalg.lstsq(X, actual, rcond=None)[0]
        y_hat = X @ beta
        ss_res = np.sum((actual - y_hat) ** 2)
        ss_tot = np.sum((actual - actual.mean()) ** 2)
        return 1 - ss_res / ss_tot if ss_tot > 0 else 0

    def mincer_zarnowitz(self) -> pd.DataFrame:
        """
        Mincer-Zarnowitz regression for each model.
        H0: a=0, b=1 (efficient forecast).
        """
        v = self.proxy_var.values
        rows = []

        for name, f_series in self.forecasts_var.items():
            h = f_series.values
            h = np.maximum(h, 1e-6)

            X = np.column_stack([np.ones(len(h)), h])
            beta, _, _, _ = np.linalg.lstsq(X, v, rcond=None)
            a, b = beta

            y_hat = X @ beta
            n = len(v)
            s2 = np.sum((v - y_hat) ** 2) / (n - 2)
            XtX_inv = np.linalg.inv(X.T @ X)
            se = np.sqrt(np.diag(s2 * XtX_inv))

            # t-statistics for a=0 and b=1
            t_a = a / se[0]
            t_b = (b - 1) / se[1]

            # F-test: joint H0: a=0, b=1
            R = np.array([[1, 0], [0, 1]])
            r = np.array([0, 1])
            Rb_r = R @ beta - r
            F_stat = (Rb_r @ np.linalg.inv(R @ XtX_inv @ R.T) @ Rb_r) / (2 * s2)
            p_F = 1 - stats.f.cdf(F_stat, 2, n - 2)

            rows.append({
                'Model': name,
                'a (intercept)': a,
                'b (slope)': b,
                't(a=0)': t_a,
                't(b=1)': t_b,
                'F-stat (joint)': F_stat,
                'p-value (F)': p_F,
                'R': self._mz_r2(h, v)
            })

        return pd.DataFrame(rows).set_index('Model')

    def diebold_mariano(self, model_a: str, model_b: str, loss: str = 'mse', h: int = 1) -> dict:
        """
        Diebold-Mariano test: H0: equal forecast accuracy.
        Negative DM => model_a is better.
        """
        v = self.proxy_var.values
        ha = np.maximum(self.forecasts_var[model_a].values, 1e-6)
        hb = np.maximum(self.forecasts_var[model_b].values, 1e-6)

        # Loss differential
        loss_fns = {
            'mse': lambda f, a: (a - f) ** 2,
            'mae': lambda f, a: np.abs(a - f),
            'qlike': lambda f, a: (a / f) - np.log(np.maximum(a / f, 1e-6)) - 1,
        }
        loss_fn = loss_fns[loss]

        d_t = loss_fn(ha, v) - loss_fn(hb, v)
        d_bar = d_t.mean()

        # HAC variance with Newey-West (BW = h-1 lags)
        T = len(d_t)
        gamma_0 = np.var(d_t, ddof=1)
        hac_var = gamma_0
        for k in range(1, h):
            gamma_k = np.cov(d_t[k:], d_t[:-k])[0, 1]
            hac_var += 2 * (1 - k / h) * gamma_k

        dm_stat = d_bar / np.sqrt(np.maximum(hac_var / T, 1e-12))
        p_value = 2 * (1 - stats.norm.cdf(abs(dm_stat)))

        return {
            'Model A': model_a,
            'Model B': model_b,
            'Mean Loss Diff': d_bar,
            'DM Statistic': dm_stat,
            'p-value (two-sided)': p_value,
            'Conclusion': f'{model_a} better' if dm_stat < 0 else f'{model_b} better',
            'Significant (5%)': p_value < 0.05
        }

    def pit_test(self, model_name: str, returns_pct: pd.Series) -> dict:
        """
        Probability Integral Transform test for distributional adequacy.
        """
        h = np.maximum(self.forecasts_var[model_name].values, 1e-6)
        r = returns_pct.loc[self.forecasts_var[model_name].index].values

        # Standardized residuals
        z_t = r / np.sqrt(h)

        # PIT values (under N(0,1) assumption)
        pit_values = stats.norm.cdf(z_t)

        # Kolmogorov-Smirnov test for uniformity
        ks_stat, ks_p = stats.kstest(pit_values, 'uniform')

        # Jarque-Bera on z_t for normality
        jb_stat, jb_p = stats.jarque_bera(z_t)

        return {
            'Model': model_name,
            'Mean (z)': z_t.mean(),
            'Std(z)': z_t.std(),
            'Skewness (z)': stats.skew(z_t),
            'Kurtosis (z)': stats.kurtosis(z_t, fisher=False),
            'KS statistic': ks_stat,
            'KS p-value': ks_p,
            'JB statistic': jb_stat,
            'JB p-value': jb_p,
            'Calibrated?': ks_p > 0.05 and jb_p > 0.05
        }


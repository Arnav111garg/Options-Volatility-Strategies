# 2. Build Multiple Forecast Models and Compare
# ===========================================================
def ewma_variance(r_pct, lam=0.94):
    """Calculates the EWMA rolling variance variance series on daily returns percentage."""
    n = len(r_pct)
    v_t = np.zeros(n)
    v_t[0] = np.var(r_pct)
    for i in range(1, n):
        v_t[i] = lam * v_t[i-1] + (1 - lam) * (r_pct[i-1]**2)
    return v_t

def build_forecast_models(returns_pct: pd.Series, window: int = 21) -> dict:
    """Build multiple volatility forecasts (output as daily percentage variance)."""
    r = returns_pct.values
    forecasts = {}

    # Model 1: Historical Volatility (rolling std of % returns, squared to daily var)
    forecasts['HV21'] = (returns_pct.rolling(window).std()) ** 2

    # Model 2: EWMA (RiskMetrics)
    forecasts['EWMA (0.94)'] = pd.Series(
        ewma_variance(r, lam=0.94),
        index=returns_pct.index
    )

    # Model 3: GARCH(1,1) Normal
    am_n = arch_model(returns_pct, vol='Garch', p=1, q=1, dist='normal')
    res_n = am_n.fit(disp='off', show_warning=False)
    forecasts['GARCH-N'] = res_n.conditional_volatility ** 2

    # Model 4: GARCH(1,1) Student-t
    am_t = arch_model(returns_pct, vol='Garch', p=1, q=1, dist='t')
    res_t = am_t.fit(disp='off', show_warning=False)
    forecasts['GARCH-t'] = res_t.conditional_volatility ** 2

    # Model 5: GJR-GARCH (asymmetric)
    am_gjr = arch_model(returns_pct, vol='GARCH', p=1, o=1, q=1, dist='t')
    res_gjr = am_gjr.fit(disp='off', show_warning=False)
    forecasts['GJR-GARCH'] = res_gjr.conditional_volatility ** 2

    # Model 6: Rolling HV63
    forecasts['HV63'] = (returns_pct.rolling(63).std()) ** 2

    return forecasts


import numpy as np
import pandas as pd
from scipy.optimize import minimize_scalar, minimize
import matplotlib.pyplot as plt
from typing import Union

# ===========================================================
# 1. Core EWMA Implementation
# ===========================================================
def ewma_variance(returns: Union[pd.Series, np.ndarray],
                  lam: float = 0.94,
                  init_method: str = 'sample') -> np.ndarray:
    """
    Compute EWMA variance estimates.

    Parameters
    ----------
    returns : array-like of log returns
    lam : float, decay factor (lambda), 0 < lam < 1
    init_method : 'sample' or 'first_squared'

    Returns
    -------
    np.ndarray of conditional variance estimates (sigma^2)
    """
    r = np.asarray(returns)
    T = len(r)
    var = np.zeros(T)

    # Initialize variance
    if init_method == 'sample':
        var[0] = np.var(r[:min(30, T)])  # Use first 30 returns for init
    else:
        var[0] = r[0]**2

    # EWMA recursion: sigma_t^2 = lambda * sigma_{t-1}^2 + (1 - lambda) * r_{t-1}^2
    for t in range(1, T):
        var[t] = lam * var[t-1] + (1 - lam) * r[t-1]**2

    return var

def ewma_volatility(returns, lam=0.94, trading_days=252):
    """Annualized EWMA volatility."""
    var = ewma_variance(returns, lam)
    return np.sqrt(var * trading_days)

# ===========================================================
# 2. Vectorized EWMA (faster, no loop)
# ===========================================================
def ewma_variance_fast(returns: np.ndarray, lam: float = 0.94) -> np.ndarray:
    """
    Fast EWMA using pandas ewm (with span conversion).
    span = 2/(1 - lambda) - 1 for equivalence.
    """
    r = pd.Series(returns)
    # pandas ewm uses alpha = 1 - lambda
    alpha = 1 - lam
    # Using adjust = False gives recursive EWMA: s_t = alpha * x_t + (1 - alpha) * s_{t-1}
    var = (r**2).ewm(alpha=alpha, adjust=False).mean()
    return var.values

# ===========================================================
# 3. Optimal Lambda via MSE Minimization
# ===========================================================
def lambda_mse_loss(lam, returns):
    """MSE between EWMA variance and squared returns (proxy for true var)."""
    var_hat = ewma_variance(returns, lam)
    # Use next-period squared return as target (noisy but unbiased)
    target = returns[1:]**2
    pred = var_hat[:-1]
    return np.mean((pred - target)**2)

def find_optimal_lambda(returns, method='mse'):
    """Find optimal lambda by minimizing MSE."""
    r = np.asarray(returns)

    result = minimize_scalar(
        lambda_mse_loss,
        args=(r,),
        bounds=(0.80, 0.999),
        method='bounded'
    )
    return result.x, result.fun

# ===========================================================
# 4. Effective Window and Half-Life
# ===========================================================
def ewma_properties(lam: float) -> dict:
    """Compute EWMA statistical properties."""
    effective_window = 1 / (1 - lam)
    half_life = np.log(0.5) / np.log(lam)

    # Weight assigned to last k days
    k_values = [5, 10, 21, 63]
    weights = {}
    for k in k_values:
        w = sum((1 - lam) * lam**(i - 1) for i in range(1, k + 1))
        weights[f'Weight (last {k} days)'] = f'{w:.1%}'

    return {
        'Lambda': lam,
        'Effective Window': f'{effective_window:.1f} days',
        'Half-life': f'{half_life:.1f} days',
        **weights
    }


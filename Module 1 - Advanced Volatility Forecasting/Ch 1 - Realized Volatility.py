import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.gridspec as gridspec
from scipy import stats
import yfinance as yf
import warnings
warnings.filterwarnings('ignore')

# ===========================================================
# 1. Data Acquisition
# ===========================================================
def fetch_data(ticker: str, start: str, end: str) -> pd.DataFrame:
    """Fetch OHLCV data and compute log returns."""
    df = yf.download(ticker, start=start, end=end, progress=False)
    df['log_return'] = np.log(df['Close'] / df['Close'].shift(1))
    df.dropna(inplace=True)
    return df

# ===========================================================
# 2. Historical Volatility Estimator
# ===========================================================
def historical_volatility(returns: pd.Series,
                          window: int = 21,
                          annualize: bool = True,
                          trading_days: int = 252,
                          zero_mean: bool = True) -> pd.Series:
    """
    Compute rolling historical (close-to-close) volatility.

    Parameters
    ----------
    returns : pd.Series of log returns
    window : int, lookback window in trading days
    annualize : bool, annualize the result
    trading_days : int, days per year (252 standard)
    zero_mean : bool, use zero-mean assumption (more efficient)

    Returns
    -------
    pd.Series of annualized volatility estimates
    """
    if zero_mean:
        # More efficient: avoids estimating mean (saves 1 dof)
        rolling_var = (returns ** 2).rolling(window=window).mean()
    else:
        # Standard sample variance with Bessel's correction
        rolling_var = returns.rolling(window=window).var(ddof=1)

    hv = np.sqrt(rolling_var)

    if annualize:
        hv = hv * np.sqrt(trading_days)

    return hv

# ===========================================================
# 3. Confidence Intervals for HV
# ===========================================================
def hv_confidence_interval(hv_series: pd.Series,
                           window: int,
                           alpha: float = 0.05) -> tuple:
    """
    Compute chi-squared confidence intervals for HV.

    Returns lower and upper bounds (annualized).
    """
    dof = window - 1  # degrees of freedom

    # Chi-squared critical values
    chi2_lower = stats.chi2.ppf(alpha / 2, dof)
    chi2_upper = stats.chi2.ppf(1 - alpha / 2, dof)

    # CI for variance: [n*s^2/chi2_upper, n*s^2/chi2_lower]
    # Converting to vol (annualized)
    hv_lower = hv_series * np.sqrt(dof / chi2_upper)
    hv_upper = hv_series * np.sqrt(dof / chi2_lower)

    return hv_lower, hv_upper

# ===========================================================
# 4. Main Analysis
# ===========================================================
df = fetch_data('SPY', '2015-01-01', '2026-12-31')
returns = df['log_return']

# Compute HV for multiple windows
windows = [5, 21, 63, 126, 252]
hv_dict = {}
for w in windows:
    hv_dict[f'HV{w}'] = historical_volatility(returns, window=w)

hv_df = pd.DataFrame(hv_dict)

# Compute CI for 21-day HV
hv21 = hv_dict['HV21']
ci_lower, ci_upper = hv_confidence_interval(hv21, window=21)

# ===========================================================
# 5. Visualization
# ===========================================================
fig = plt.figure(figsize=(16, 12))
fig.suptitle('SPY Historical Volatility Multiple Windows (2015 - 2024)',
             fontsize=14, fontweight='bold', color='#0A3C78')

gs = gridspec.GridSpec(2, 2, figure=fig, hspace=0.4, wspace=0.3)

# Plot 1: All HV windows
ax1 = fig.add_subplot(gs[0, :])
colors = ['#0A3C78', '#B48C1E', '#146440', '#A01E1E', '#6A1A9A']
for (name, hv_s), col in zip(hv_dict.items(), colors):
    ax1.plot(hv_s.index, hv_s * 100, label=name, color=col, linewidth=0.8, alpha=0.85)

ax1.fill_between(hv21.index, ci_lower * 100, ci_upper * 100,
                 alpha=0.15, color='#0A3C78', label='HV21 95% CI')
ax1.set_title('Rolling Historical Volatility Multiple Lookback Windows')
ax1.set_ylabel('Annualized Volatility (%)')
ax1.legend(loc='upper left', ncol=3, fontsize=9)
ax1.grid(True, alpha=0.3)
ax1.axhline(y=20, color='gray', linestyle='--', linewidth=0.8, alpha=0.5)

# Plot 2: Return distribution
ax2 = fig.add_subplot(gs[1, 0])
ax2.hist(returns, bins=100, color='#0A3C78', alpha=0.7, density=True,
         edgecolor='none', label='Empirical')
x_range = np.linspace(returns.min(), returns.max(), 300)
normal_pdf = stats.norm.pdf(x_range, returns.mean(), returns.std())
ax2.plot(x_range, normal_pdf, color='#A01E1E', lw=2, label='Normal fit')
ax2.set_title('Return Distribution vs Normal')
ax2.set_xlabel('Log Return')
ax2.legend()
ax2.grid(True, alpha=0.3)

# Excess kurtosis annotation
kurt = stats.kurtosis(returns)
ax2.text(0.05, 0.85, f'Excess Kurtosis: {kurt:.2f}',
         transform=ax2.transAxes, fontsize=10,
         bbox=dict(boxstyle='round', facecolor='wheat', alpha=0.8))

# Plot 3: HV21 ACF
ax3 = fig.add_subplot(gs[1, 1])
hv21_clean = hv21.dropna()
max_lag = 60
acf_vals = [hv21_clean.autocorr(lag=k) for k in range(1, max_lag + 1)]
ax3.bar(range(1, max_lag + 1), acf_vals, color='#146440', alpha=0.7)
ci_95 = 1.96 / np.sqrt(len(hv21_clean))
ax3.axhline(y=ci_95, color='red', linestyle='--', lw=1.5, label='95% CI')
ax3.axhline(y=-ci_95, color='red', linestyle='--', lw=1.5)
ax3.set_title('ACF of 21-day HV (Persistence)')
ax3.set_xlabel('Lag (days)')
ax3.set_ylabel('Autocorrelation')
ax3.legend()
ax3.grid(True, alpha=0.3)

plt.tight_layout()
plt.savefig('historical_volatility_analysis.png', dpi=150, bbox_inches='tight')
plt.show()


# 3. Main Execution
# ===========================================================
df_spy = yf.download('SPY', start='2015-01-01', end='2024-12-31', progress=False)

# The yfinance column names
df_spy.columns = ['_'.join(c).strip() if isinstance(c, tuple) else c for c in df_spy.columns]

# Standardize to Open, High, Low, Close
df_ohlc = pd.DataFrame({
    'Open': df_spy.filter(like='Open').iloc[:, 0],
    'High': df_spy.filter(like='High').iloc[:, 0],
    'Low': df_spy.filter(like='Low').iloc[:, 0],
    'Close': df_spy.filter(like='Close').iloc[:, 0],
})

estimators = RangeVolatilityEstimators(df_ohlc)
all_vols = plot_all_estimators(estimators, window=21, ticker='SPY')

# Summary statistics
print("\n" + "=" * 65)
print(" RANGE-BASED ESTIMATOR SUMMARY STATISTICS (SPY, 21-day) ")
print("=" * 65)
print(all_vols.describe().round(2).to_string())

print("\n" + "=" * 65)
print(" EFFICIENCY ANALYSIS ")
print("=" * 65)
print(estimators.efficiency_summary(21).round(3).to_string())


# ===========================================================
# 1. All Range-Based Volatility Estimators
# ===========================================================
class RangeVolatilityEstimators:
    """
    Complete suite of range-based volatility estimators.
    All methods take a DataFrame with columns: Open, High, Low, Close.
    All return annualized volatility (%) unless stated.
    """

    def __init__(self, ohlc_df: pd.DataFrame, trading_days: int = 252):
        """
        Parameters
        ----------
        ohlc_df : DataFrame with Open, High, Low, Close columns
        trading_days : int, trading days per year
        """
        self.df = ohlc_df.copy()
        self.td = trading_days
        self._precompute_log_ratios()

    def _precompute_log_ratios(self):
        """Pre-compute all needed log price ratios."""
        df = self.df

        # Standard log ratios (intraday)
        self.u = np.log(df['High'] / df['Open'])      # High-to-Open
        self.d = np.log(df['Low'] / df['Open'])       # Low-to-Open
        self.c = np.log(df['Close'] / df['Open'])     # Close-to-Open (intraday ret)

        # Overnight (Close-to-Open)
        self.o = np.log(df['Open'] / df['Close'].shift(1)) # overnight return

        # Additional ratios for GK
        self.hl = np.log(df['High'] / df['Low'])      # High-to-Low
        self.co = np.log(df['Close'] / df['Open'])     # Close-to-Open (intraday)

    def close_to_close(self, window: int = 21) -> pd.Series:
        """
        Standard close-to-close HV (benchmark).
        """
        log_ret = np.log(self.df['Close'] / self.df['Close'].shift(1))
        rv = (log_ret ** 2).rolling(window).sum()
        return (np.sqrt(rv * self.td / window) * 100).rename('CC-HV')

    def parkinson(self, window: int = 21) -> pd.Series:
        """
        Parkinson (1980) estimator.
        sigma^2 = (1/4 ln2) * (ln H/L)^2
        """
        pk_var = self.hl**2 / (4 * np.log(2))
        rv = pk_var.rolling(window).mean()
        return (np.sqrt(rv * self.td) * 100).rename('Parkinson')

    def garman_klass(self, window: int = 21) -> pd.Series:
        """
        Garman-Klass (1980) estimator.
        sigma^2 = 0.5*(ln H/L)^2 - (2*ln2 - 1)*(ln C/O)^2
        """
        gk_var = 0.5 * self.hl**2 - (2 * np.log(2) - 1) * self.co**2
        rv = gk_var.rolling(window).mean()
        return (np.sqrt(rv * self.td) * 100).rename('Garman-Klass')

    def rogers_satchell(self, window: int = 21) -> pd.Series:
        """
        Rogers-Satchell (1991) estimator.
        sigma^2 = u*(u-c) + d*(d-c)
        Drift-invariant.
        """
        rs_var = self.u * (self.u - self.c) + self.d * (self.d - self.c)
        rv = rs_var.rolling(window).mean()
        return (np.sqrt(rv * self.td) * 100).rename('Rogers-Satchell')

    def yang_zhang(self, window: int = 21) -> pd.Series:
        """
        Yang-Zhang (2000) estimator minimum variance, drift-invariant, handles overnight gaps.
        sigma^2_YZ = sigma^2_overnight + k*sigma^2_close_open + (1-k)*sigma^2_RS
        """
        n = window

        # Overnight variance (open-to-previous-close)
        o = self.o.dropna()

        # Rolling overnight variance
        o_var = (self.o - self.o.rolling(n).mean())**2
        overnight_var = o_var.rolling(n).sum() / (n - 1)

        # Close-to-open intraday variance
        c_var = (self.c - self.c.rolling(n).mean())**2
        close_var = c_var.rolling(n).sum() / (n - 1)

        # Rogers-Satchell intraday variance
        rs_var = self.u * (self.u - self.c) + self.d * (self.d - self.c)
        rs_mean = rs_var.rolling(n).mean()

        # Optimal combination weight
        k = 0.34 / (1.34 + (n + 1) / (n - 1))

        # Yang-Zhang combined estimate
        yz_var = overnight_var + k * close_var + (1 - k) * rs_mean

        return (np.sqrt(yz_var * self.td) * 100).rename('Yang-Zhang')

    def all_estimators(self, window: int = 21) -> pd.DataFrame:
        """Compute all estimators and return as DataFrame."""
        return pd.DataFrame({
            'CC-HV': self.close_to_close(window),
            'Parkinson': self.parkinson(window),
            'Garman-Klass': self.garman_klass(window),
            'Rogers-Satchell': self.rogers_satchell(window),
            'Yang-Zhang': self.yang_zhang(window),
        })

    def efficiency_summary(self, window: int = 21) -> pd.DataFrame:
        """
        Compare estimator variances to CC as efficiency measure.
        Higher relative_precision = fewer observations needed.
        """
        all_vols = self.all_estimators(window).dropna()

        # Variance of each estimator (proxy for estimation noise)
        variances = all_vols.var()
        cc_var = variances['CC-HV']

        efficiency_df = pd.DataFrame({
            'Estimator': variances.index,
            'Std of Estimates': variances.values ** 0.5,
            'Rel. Efficiency vs CC': cc_var / variances.values,
            'Theoretical Efficiency': [1.0, 4.9, 7.4, 6.2, 14.0]
        }).set_index('Estimator')

        return efficiency_df


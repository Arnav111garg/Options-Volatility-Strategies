# 2. Visualization
# ===========================================================
def plot_all_estimators(estimators: RangeVolatilityEstimators, window: int = 21, ticker: str = 'SPY'):
    """Comprehensive visualization of all range-based estimators."""
    all_vols = estimators.all_estimators(window).dropna()

    fig = plt.figure(figsize=(16, 14))
    fig.suptitle(f'Range-Based Volatility Estimators Comparison {ticker} ({window}-day window)',
                 fontsize=13, fontweight='bold', color='#0A3C78')

    gs = gridspec.GridSpec(3, 2, figure=fig, hspace=0.45, wspace=0.3)

    colors = {
        'CC-HV': '#808080',
        'Parkinson': '#0A3C78',
        'Garman-Klass': '#146440',
        'Rogers-Satchell': '#B48C1E',
        'Yang-Zhang': '#A01E1E'
    }

    # Plot 1: All estimators time series
    ax1 = fig. add_subplot(gs[0, :])
    for name, col in colors.items():
        lw = 2.5 if name == 'Yang-Zhang' else (1.5 if name == 'CC-HV' else 1.2)
        alpha = 0.9 if name in ['Yang-Zhang', 'CC-HV'] else 0.75
        ls = '--' if name == 'CC-HV' else '-'
        ax1.plot(all_vols.index, all_vols[name],
                 color=col, linewidth=lw, alpha=alpha,
                 linestyle=ls, label=name)
    ax1.set_ylabel('Annualized Volatility (%)')
    ax1.set_title('All Range-Based Estimators (21-day rolling)')
    ax1.legend(loc='upper left', ncol=3, fontsize=9)
    ax1.grid(True, alpha=0.3)

    # Plot 2: Estimator distribution comparison
    ax2 = fig.add_subplot(gs[1, 0])
    for name, col in colors.items():
        ax2.hist(all_vols[name].dropna(), bins=60, alpha=0.4,
                 color=col, label=name, density=True)
    ax2.set_xlabel('Annualized Vol (%)')
    ax2.set_ylabel('Density')
    ax2.set_title('Distribution of Estimator Values')
    ax2.legend(fontsize=8)
    ax2.grid(True, alpha=0.3)

    # Plot 3: Correlation heatmap (manual)
    ax3 = fig.add_subplot(gs[1, 1])
    corr_matrix = all_vols.corr().values
    estimator_names = list(colors.keys())
    im = ax3.imshow(corr_matrix, cmap='RdYlGn', vmin=0.8, vmax=1.0)
    ax3.set_xticks(range(len(estimator_names)))
    ax3.set_yticks(range(len(estimator_names)))
    ax3.set_xticklabels([n.replace('-', '-\n') for n in estimator_names], fontsize=8, rotation=45)
    ax3.set_yticklabels(estimator_names, fontsize=8)
    for i in range(len(estimator_names)):
        for j in range(len(estimator_names)):
            ax3.text(j, i, f'{corr_matrix[i, j]:.3f}', ha='center', va='center', fontsize=7)
    plt.colorbar(im, ax=ax3)
    ax3.set_title('Estimator Correlation Matrix')

    # Plot 4: YZ - CC difference (additional info from range)
    ax4 = fig.add_subplot(gs[2, 0])
    diff = all_vols['Yang-Zhang'] - all_vols['CC-HV']
    ax4.fill_between(all_vols.index, 0, diff, where=diff > 0, alpha=0.6, color='#A01E1E', label='YZ > CC (range > close)')
    ax4.fill_between(all_vols.index, 0, diff, where=diff <= 0, alpha=0.6, color='#0A3C78', label='YZ < CC')
    ax4.set_ylabel('YZ - CC (pp)')
    ax4.set_title('Extra Information from Range vs Close-to-Close')
    ax4.legend(fontsize=8)
    ax4.grid(True, alpha=0.3)

    # Plot 5: Efficiency summary bar
    ax5 = fig.add_subplot(gs[2, 1])
    eff_df = estimators.efficiency_summary(window)
    empirical_eff = eff_df['Rel. Efficiency vs CC'].values
    theoretical_eff = eff_df['Theoretical Efficiency'].values
    x = np.arange(len(eff_df))
    width = 0.35
    bars1 = ax5.bar(x - width/2, empirical_eff, width, color=[colors[n] for n in eff_df.index], alpha=0.7, label='Empirical')
    bars2 = ax5.bar(x + width/2, theoretical_eff, width, color=[colors[n] for n in eff_df.index], alpha=0.4, edgecolor='black', linewidth=1.5, label='Theoretical (GBM)')
    ax5.set_xticks(x)
    ax5.set_xticklabels([n.replace('-', '-\n') for n in eff_df.index], fontsize=8)
    ax5.set_ylabel('Relative Efficiency vs Close-to-Close')
    ax5.set_title('Estimator Efficiency Comparison')
    ax5.legend()
    ax5.grid(True, alpha=0.3, axis='y')
    ax5.axhline(y=1, color='black', linestyle='--', lw=1)

    plt.tight_layout()
    plt.savefig('range_based_vol_comparison.png', dpi=150, bbox_inches='tight')
    plt.show()

    return all_vols


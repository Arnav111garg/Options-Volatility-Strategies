# ===========================================================
# 1. Fit GARCH (1,1) and Extract Mean-Reversion Parameters
# ===========================================================
def fit_garch(returns: np.ndarray, dist: str = 'normal') -> dict:
    """
    Fit GARCH (1,1) and return key parameters.
    Returns scaled parameters (returns passed as %).
    """
    r_pct = returns * 100 # arch library uses % returns

    am = arch_model(r_pct, vol='Garch', p=1, q=1, dist=dist)
    res = am.fit(disp='off', show_warning=False)

    params = res.params
    omega = params['omega'] # in units of (pct return)^2
    alpha = params['alpha[1]']
    beta = params['beta[1]']

    # Convert omega back to raw units
    omega_raw = omega / 10000 # (pct^2 to decimal^2)
    persistence = alpha + beta

    if persistence < 1:
        long_run_var = omega_raw / (1 - persistence)
        long_run_vol = np.sqrt(long_run_var * 252) * 100 # annualized %
        half_life = np.log(2) / (-np.log(persistence)) if persistence > 0 else np.inf
    else:
        long_run_var = np.nan
        long_run_vol = np.nan
        half_life = np.inf

    return {
        'omega_raw': omega_raw,
        'alpha': alpha,
        'beta': beta,
        'persistence': persistence,
        'long_run_var': long_run_var,
        'long_run_vol_pct': long_run_vol,
        'half_life_days': half_life,
        'model_result': res,
        'aic': res.aic,
        'bic': res.bic,
        'loglikelihood': res.loglikelihood
    }

# ===========================================================
# 2. Multi-Step GARCH Forecast (Term Structure)
# ===========================================================
def garch_term_structure(garch_params: dict, current_var: float, max_horizon: int = 252) -> pd.DataFrame:
    """
    Compute the GARCH (1,1) variance term structure.
    """
    omega = garch_params['omega_raw']
    alpha = garch_params['alpha']
    beta = garch_params['beta']
    rho = alpha + beta
    long_run_var = garch_params['long_run_var']

    horizons = np.arange(1, max_horizon + 1)

    if rho < 1:
        var_h = long_run_var + (current_var - long_run_var) * rho**(horizons - 1)
    else:
        var_h = current_var * np.ones(len(horizons))

    if rho < 1:
        avg_var_h = np.array([
            long_run_var + (current_var - long_run_var) * (1 - rho**h) / (h * (1 - rho))
            for h in horizons
        ])
    else:
        avg_var_h = var_h.copy()

    vol_h = np.sqrt(avg_var_h * 252) * 100

    return pd.DataFrame({
        'horizon_days': horizons,
        'conditional_var': var_h,
        'avg_var': avg_var_h,
        'annualized_vol_pct': vol_h
    })

# ===========================================================
# 3. Historical Volatility Cone
# ===========================================================
def compute_vol_cone(returns: pd.Series, horizons: list = [5, 10, 21, 42, 63, 126], percentiles: list = [5, 25, 50, 75, 95]) -> pd.DataFrame:
    """
    Compute volatility cone: percentiles of realized vol at each horizon.
    """
    results = {}
    for h in horizons:
        vols = []
        for start in range(0, len(returns) - h + 1, h):
            window_returns = returns.iloc[start:start+h]
            rv = np.std(window_returns) * np.sqrt(252) * 100
            vols.append(rv)
        vols = np.array(vols)
        results[h] = {f'p{p}': np.percentile(vols, p) for p in percentiles}
        results[h]['mean'] = np.mean(vols)
    return pd.DataFrame(results).T


import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches
from hmmlearn import hmm
from sklearn.preprocessing import StandardScaler
import warnings
warnings.filterwarnings('ignore')

# ===========================================================
# 1. Hidden Markov Model for Volatility Regimes
# ===========================================================
class VolatilityRegimeDetector:
    """
    Detects volatility regimes using Hidden Markov Models.
    Uses realized volatility as the observable.
    """

    def __init__(self, n_regimes: int = 3, n_iter: int = 200):
        self.n_regimes = n_regimes
        self.n_iter = n_iter
        self.model = None
        self.scaler = StandardScaler()
        self.regime_labels = {}

    def fit(self, returns: pd.Series, vol_window: int = 21) -> 'VolatilityRegimeDetector':
        """Fit HMM to rolling volatility observations."""

        # Compute feature matrix: [rolling_vol, squared_return, |return|]
        rv = returns.rolling(vol_window).std() * np.sqrt(252) * 100
        feat = pd.DataFrame({
            'rv': rv,
            'r_sq': returns**2 * 252 * 100**2,
            'r_abs': returns.abs() * np.sqrt(252) * 100
        }).dropna()

        self.feature_dates = feat.index
        X = self.scaler.fit_transform(feat.values)

        # Fit Gaussian HMM
        self.model = hmm.GaussianHMM(
            n_components=self.n_regimes,
            covariance_type='full',
            n_iter=self.n_iter,
            random_state=42
        )
        self.model.fit(X)

        # Decode states
        self.hidden_states = self.model.predict(X)
        self.state_probs = self.model.predict_proba(X)

        # Label regimes by mean volatility
        state_vols = {}
        for s in range(self.n_regimes):
            mask = self.hidden_states == s
            state_vols[s] = feat['rv'].values[mask].mean()

        sorted_states = sorted(state_vols.items(), key=lambda x: x[1])

        for rank, (state, vol) in enumerate(sorted_states):
            labels = ['Low-Vol', 'Normal-Vol', 'High-Vol']
            self.regime_labels[state] = labels[rank] if rank < 3 else f'Regime-{rank}'

        return self

    def get_regime_stats(self) -> pd.DataFrame:
        """Summary statistics by regime."""
        stats_list = []
        for s in range(self.n_regimes):
            mask = self.hidden_states == s
            duration_blocks = []
            count = 0
            for m in mask:
                if m:
                    count += 1
                elif count > 0:
                    duration_blocks.append(count)
                    count = 0
            if count > 0:
                duration_blocks.append(count)

            stats_list.append({
                'Regime': self.regime_labels.get(s, f'S{s}'),
                'State': s,
                'Count': mask.sum(),
                'Frequency (%)': mask.mean() * 100,
                'Avg Duration (days)': np.mean(duration_blocks) if duration_blocks else 0,
                'Stay Prob p_ii': self.model.transmat_[s, s]
            })

        return pd.DataFrame(stats_list).set_index('Regime')

    def plot_regimes(self, returns: pd.Series, price: pd.Series = None):
        """Visualize detected regimes."""
        fig, axes = plt.subplots(3, 1, figsize=(15, 12), sharex=True)
        fig.suptitle('Volatility Regime Detection (HMM)', fontsize=13, fontweight='bold', color='#0A3C78')

        regime_colors = {
            'Low-Vol': '#146440',
            'Normal-Vol': '#0A3C78',
            'High-Vol': '#A01E1E'
        }

        dates = self.feature_dates

        # Plot 1: Price with regime shading
        ax1 = axes[0]
        if price is not None:
            price_aligned = price.reindex(dates)
            ax1.plot(dates, price_aligned, color='black', lw=0.8, zorder=5)

        # Shade by regime
        prev_regime = None
        start_date = dates[0]
        for i, (date, state) in enumerate(zip(dates, self.hidden_states)):
            regime_name = self.regime_labels.get(state, f'S{state}')
            if regime_name != prev_regime:
                if prev_regime is not None:
                    col = regime_colors.get(prev_regime, 'gray')
                    ax1.axvspan(start_date, date, alpha=0.2, color=col)
                start_date = date
                prev_regime = regime_name
        if prev_regime:
            col = regime_colors.get(prev_regime, 'gray')
            ax1.axvspan(start_date, dates[-1], alpha=0.2, color=col)

        ax1.set_ylabel('Price')
        ax1.set_title('Price with Volatility Regime Shading')

        # Legend
        patches = [mpatches.Patch(color=v, alpha=0.4, label=k) for k, v in regime_colors.items()]
        ax1.legend(handles=patches, loc='upper left')
        ax1.grid(True, alpha=0.3)

        # Plot 2: Regime probabilities
        ax2 = axes[1]
        for s in range(self.n_regimes):
            regime_name = self.regime_labels.get(s, f'S{s}')
            col = regime_colors.get(regime_name, 'gray')
            ax2.plot(dates, self.state_probs[:, s], color=col, lw=1.5, label=regime_name, alpha=0.9)
        ax2.set_ylabel('Regime Probability')
        ax2.set_title('Smoothed Regime Probabilities')
        ax2.legend(loc='upper right')
        ax2.grid(True, alpha=0.3)
        ax2.set_ylim(0, 1)

        # Plot 3: Most probable regime over time
        ax3 = axes[2]
        regime_numeric = pd.Series(self.hidden_states, index=dates)
        for s in range(self.n_regimes):
            regime_name = self.regime_labels.get(s, f'S{s}')
            col = regime_colors.get(regime_name, 'gray')
            mask = regime_numeric == s
            ax3.scatter(dates[mask.values], [s] * mask.sum(), color=col, s=5, marker='|', alpha=0.8)

        ax3.set_yticks(range(self.n_regimes))
        ax3.set_yticklabels([self.regime_labels.get(s, f'S{s}') for s in range(self.n_regimes)])
        ax3.set_title('Most Probable Regime')
        ax3.grid(True, alpha=0.3)

        plt.tight_layout()
        plt.savefig('regime_detection.png', dpi=150, bbox_inches='tight')
        plt.show()


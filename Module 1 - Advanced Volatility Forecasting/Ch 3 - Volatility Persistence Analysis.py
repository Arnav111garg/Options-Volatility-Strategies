def arch_lm_test(returns: np.ndarray, lags: int = 12) -> dict:
    """
    Engle's ARCH LM test for conditional heteroskedasticity.

    Returns test statistic, p-value, and conclusion.
    """
    r = np.asarray(returns)
    T = len(r)
    r_sq = r**2

    # Regress r_t^2 on lags of r_t^2
    X = np.column_stack([np.ones(T - lags)] +
                        [r_sq[lags - i:T - i] for i in range(1, lags + 1)])
    y = r_sq[lags:]

    # OLS
    beta = np.linalg.lstsq(X, y, rcond=None)[0]
    y_hat = X @ beta
    resid = y - y_hat

    ss_res = np.sum(resid**2)
    ss_tot = np.sum((y - y.mean())**2)
    r_squared = 1 - ss_res / ss_tot

    lm_stat = T * r_squared
    p_value = 1 - stats.chi2.cdf(lm_stat, df=lags)

    return {
        'LM Statistic': lm_stat,
        'p-value': p_value,
        'Lags': lags,
        'R-squared': r_squared,
        'ARCH effects': p_value < 0.05
    }

def volatility_persistence_analysis(returns: np.ndarray,
                                     max_lag: int = 100) -> dict:
    """
    Comprehensive persistence analysis.
    """
    r = np.asarray(returns)
    r_sq = r**2
    r_abs = np.abs(r)

    # Autocorrelation functions
    acf_sq = acf(r_sq, nlags=max_lag, fft=True)
    acf_abs = acf(r_abs, nlags=max_lag, fft=True)

    # Ljung-Box tests
    lb_sq = acorr_ljungbox(r_sq, lags=[10, 20, 50], return_df=True)

    # ARCH LM test
    arch_test = arch_lm_test(r, lags=12)

    # Fit GARCH(1,1) to get persistence parameter
    am = arch_model(r * 100, vol='Garch', p=1, q=1, dist='normal')
    res = am.fit(disp='off', show_warning=False)
    alpha = res.params.get('alpha[1]', np.nan)
    beta_g = res.params.get('beta[1]', np.nan)
    omega = res.params.get('omega', np.nan)
    persistence = alpha + beta_g

    # Half-life of variance shock
    if persistence < 1:
        half_life = np.log(0.5) / np.log(persistence)
        long_run_vol = np.sqrt(omega / (1 - persistence) * 252) / 100
    else:
        half_life = np.inf
        long_run_vol = np.nan

    return {
        'acf_squared': acf_sq,
        'acf_abs': acf_abs,
        'lb_results': lb_sq,
        'arch_test': arch_test,
        'garch_alpha': alpha,
        'garch_beta': beta_g,
        'persistence': persistence,
        'half_life_days': half_life,
        'long_run_vol_pct': long_run_vol * 100 if not np.isnan(long_run_vol) else np.nan
    }


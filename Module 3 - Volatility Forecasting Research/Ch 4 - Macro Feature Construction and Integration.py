import numpy as np
import pandas as pd
from typing import Optional

class MacroFeatureBuilder:
    """
    Build macro-economic features for equity volatility forecasting.

    Data sources:
    - FRED (via fredapi or pandas-datareader)
    - Bloomberg (via xbbg or blpapi)
    - ICE BofA credit spread indices
    """

    def __init__(self, lags=(1, 5, 22)):
        self.lags = lags

    def _lag_and_diff(self, series: pd.Series, name: str) -> pd.DataFrame:
        """Create level, first difference, and lagged versions."""
        feat = pd.DataFrame(index=series.index)

        # Shift by 1 to avoid lookahead
        s = series.shift(1)
        feat[f'{name}_level'] = s
        feat[f'{name}_d1'] = s.diff(1)     # day-over-day change
        feat[f'{name}_d5'] = s.diff(5)     # week change
        feat[f'{name}_d22'] = s.diff(22)   # month change

        for lag in self.lags:
            feat[f'{name}_lag{lag}'] = s.shift(lag - 1)

        return feat

    def build_credit_features(self,
                              ig_spread: pd.Series,
                              hy_spread: Optional[pd.Series] = None,
                              ted_spread: Optional[pd.Series] = None) -> pd.DataFrame:
        """Credit spread features."""
        all_feat = []
        all_feat.append(self._lag_and_diff(ig_spread, 'ig_spread'))

        if hy_spread is not None:
            all_feat.append(self._lag_and_diff(hy_spread, 'hy_spread'))
            # HY-IG ratio: captures credit risk appetite
            ratio = (hy_spread / ig_spread.clip(lower=1e-4)).shift(1)
            all_feat.append(ratio.rename('hy_ig_ratio').to_frame())

        if ted_spread is not None:
            all_feat.append(self._lag_and_diff(ted_spread, 'ted'))

        return pd.concat(all_feat, axis=1)

    def build_yield_curve_features(self,
                                   y_2y: pd.Series,
                                   y_10y: pd.Series,
                                   y_5y: Optional[pd.Series] = None) -> pd.DataFrame:
        """Yield curve shape features."""
        slope = (y_10y - y_2y).shift(1)
        all_feat = [self._lag_and_diff(slope, 'yc_slope')]

        if y_5y is not None:
            curvature = (2 * y_5y - y_2y - y_10y).shift(1)
            all_feat.append(self._lag_and_diff(curvature, 'yc_curve'))

        # Level factor (short rate as recession indicator)
        all_feat.append(self._lag_and_diff(y_2y, 'rate_2y'))

        # Regime: inverted curve indicator
        inverted = (slope < 0).astype(float).shift(1)
        all_feat.append(inverted.rename('curve_inverted').to_frame())

        return pd.concat(all_feat, axis=1)

    def build_cross_section_features(self, stock_returns: pd.DataFrame) -> pd.DataFrame:
        """
        Build cross-sectional dispersion and breadth features.

        Parameters
        ----------
        stock_returns : pd.DataFrame of daily returns, shape (T, N)
        """
        feat = pd.DataFrame(index=stock_returns.index)

        # Cross-sectional dispersion
        disp = stock_returns.std(axis=1).shift(1)
        feat['cs_dispersion'] = disp
        feat['cs_dispersion_d5'] = disp.diff(5)

        # Breadth: fraction of stocks up
        breadth = (stock_returns > 0).mean(axis=1).shift(1)
        feat['breadth'] = breadth
        feat['breadth_d5'] = breadth.diff(5)

        # Up-vol vs down-vol
        down_vol = stock_returns[stock_returns < 0].std(axis=1).shift(1)
        up_vol = stock_returns[stock_returns > 0].std(axis=1).shift(1)
        feat['down_up_vol_ratio'] = (down_vol / up_vol.clip(lower=1e-10))

        return feat

    def build_vix_features(self, vix: pd.Series) -> pd.DataFrame:
        """VIX-based features (use with care: correlated with IV!)"""
        feat = pd.DataFrame(index=vix.index)
        v = vix.shift(1)

        feat['vix_level'] = v
        feat['vix_log'] = np.log(v)
        feat['vix_d1'] = v.diff(1)
        feat['vix_d5'] = v.diff(5)

        # VIX regime
        feat['vix_high'] = (v > 25).astype(float)
        feat['vix_crisis'] = (v > 35).astype(float)

        # VIX mean reversion signal
        vix_ma = v.rolling(22).mean()
        feat['vix_ma_dev'] = (v - vix_ma) / vix_ma.clip(lower=1e-4)

        return feat

    def build_all_macro_features(self,
                                 ig_spread=None, hy_spread=None,
                                 y_2y=None, y_10y=None, y_5y=None,
                                 vix=None,
                                 stock_returns=None) -> pd.DataFrame:
        """Combine all macro features."""
        all_feat = []

        if ig_spread is not None:
            all_feat.append(self.build_credit_features(ig_spread, hy_spread))

        if y_2y is not None and y_10y is not None:
            all_feat.append(self.build_yield_curve_features(y_2y, y_10y, y_5y))

        if vix is not None:
            all_feat.append(self.build_vix_features(vix))

        if stock_returns is not None:
            all_feat.append(self.build_cross_section_features(stock_returns))

        if not all_feat:
            return pd.DataFrame()

        return pd.concat(all_feat, axis=1)


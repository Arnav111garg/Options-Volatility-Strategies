import numpy as np
import pandas as pd
from sklearn.linear_model import LinearRegression, Ridge, Lasso, ElasticNet
from sklearn.preprocessing import StandardScaler
from scipy.optimize import minimize
from typing import Dict, List, Optional, Callable

class ForecastCombiner:
    """
    Comprehensive forecast combination framework .

    Methods : equal -weight , inverse -MSE , Granger - Ramanathan ,
    ridge / lasso stacking , exponential weighting .
    """

    def __init__(self):
        self.weights_ = None
        self.method_ = None

    # Static Combination Methods

    @staticmethod
    def equal_weight(forecasts: pd.DataFrame) -> pd.Series:
        """ Simple equal - weighted average of all forecasts ."""
        return forecasts.mean(axis=1)

    @staticmethod
    def inverse_mse_weight(forecasts: pd.DataFrame,
                           realized: pd.Series,
                           expanding: bool = True,
                           min_obs: int = 60) -> pd.Series:
        """
        Inverse -MSE weighting : weights proportional to 1/ MSE.
        Uses expanding window to avoid lookahead .
        """
        combined = pd.Series(index=forecasts.index, dtype=float)

        for t in range(min_obs, len(forecasts)):
            fc_hist = forecasts.iloc[:t]
            rv_hist = realized.iloc[:t]

            # Align
            both = pd.concat([fc_hist, rv_hist.rename('realized')], axis=1).dropna()

            if len(both) < min_obs:
                combined.iloc[t] = forecasts.iloc[t].mean()
                continue

            # Compute MSE for each model
            errors = both.drop(columns='realized').subtract(both['realized'], axis=0)
            mse = (errors ** 2).mean()

            # Inverse -MSE weights
            inv_mse = 1.0 / (mse + 1e-10)
            weights = inv_mse / inv_mse.sum()

            # Apply to current period forecast
            fc_t = forecasts.iloc[t].reindex(weights.index)
            combined.iloc[t] = (fc_t * weights).sum()

        return combined

    def granger_ramanathan(self, forecasts: pd.DataFrame,
                           realized: pd.Series,
                           constrained: bool = True,
                           ridge_alpha: float = 0.0,
                           window: Optional[int] = None) -> pd.Series:
        """
        Granger - Ramanathan regression combination .

        Parameters
        ----------
        constrained : If True , impose sum(w) = 1 constraint
        ridge_alpha : L2 regularization for weights (0 = OLS)
        window : Rolling window size ( None = expanding )
        """
        combined = pd.Series(index=forecasts.index, dtype=float)
        min_obs = max(len(forecasts.columns) * 3, 60)

        for t in range(min_obs, len(forecasts)):
            if window is None:
                fc_hist = forecasts.iloc[:t]
                rv_hist = realized.iloc[:t]
            else:
                start = max(0, t - window)
                fc_hist = forecasts.iloc[start:t]
                rv_hist = realized.iloc[start:t]

            both = pd.concat([fc_hist, rv_hist.rename('y')], axis=1).dropna()
            X = both.drop(columns='y').values
            y = both['y'].values

            if constrained:
                # Constrained : w >= 0 , sum(w) = 1
                def objective(w):
                    return np.mean((y - X @ w) ** 2) + ridge_alpha * np.sum(w ** 2)

                K = X.shape[1]
                cons = {'type': 'eq', 'fun': lambda w: np.sum(w) - 1}
                bounds = [(0, None)] * K
                w0 = np.ones(K) / K

                result = minimize(objective, w0, method='SLSQP',
                                  bounds=bounds, constraints=cons,
                                  options={'ftol': 1e-10, 'maxiter': 500})
                weights = result.x if result.success else w0
            else:
                # Unconstrained OLS/ Ridge
                if ridge_alpha > 0:
                    reg = Ridge(alpha=ridge_alpha, fit_intercept=True)
                else:
                    reg = LinearRegression(fit_intercept=True)
                reg.fit(X, y)
                weights = reg.coef_

            fc_t = forecasts.iloc[t].values
            combined.iloc[t] = fc_t @ weights if not constrained else np.dot(fc_t, weights)

        return combined

    def stacking_combination(self, forecasts: pd.DataFrame,
                             realized: pd.Series,
                             meta_model: str = 'ridge',
                             alpha: float = 1.0,
                             n_folds: int = 5) -> pd.Series:
        """
        Stacking with time - series cross - validation .

        Parameters
        ----------
        meta_model : 'ridge ', 'lasso ', 'elastic_net ', 'linear '
        n_folds : Number of time - series CV folds
        """
        combined = pd.Series(index=forecasts.index, dtype=float)

        meta_models = {
            'ridge': Ridge(alpha=alpha),
            'lasso': Lasso(alpha=alpha / len(forecasts)),
            'elastic_net': ElasticNet(alpha=alpha / len(forecasts), l1_ratio=0.5),
            'linear': LinearRegression()
        }

        # Time - series k- fold
        n = len(forecasts)
        fold_size = n // (n_folds + 1)

        # OOS predictions via expanding window
        oos_preds = pd.DataFrame(index=forecasts.index, columns=['stacked'])

        for fold in range(n_folds):
            train_end = fold_size * (fold + 1) + fold_size
            test_start = train_end
            test_end = min(test_start + fold_size, n)

            if test_start >= n:
                break

            fc_train = forecasts.iloc[:train_end]
            rv_train = realized.iloc[:train_end]
            fc_test = forecasts.iloc[test_start:test_end]

            both_train = pd.concat([fc_train, rv_train.rename('y')], axis=1).dropna()
            X_train = both_train.drop(columns='y').values
            y_train = both_train['y'].values

            scaler = StandardScaler()
            X_tr_s = scaler.fit_transform(X_train)
            X_te_s = scaler.transform(fc_test.values)

            model = meta_models[meta_model]
            model.fit(X_tr_s, y_train)
            preds = model.predict(X_te_s)

            oos_preds.iloc[test_start:test_end] = preds.reshape(-1, 1)

        return oos_preds['stacked'].astype(float)

    def exponential_weighting(self, forecasts: pd.DataFrame,
                               realized: pd.Series,
                               eta: float = 0.1,
                               loss_fn: str = 'mse') -> pd.Series:
        """
        Hedge algorithm ( exponential weighting ) for online combination .

        Parameters
        ----------
        eta : learning rate ( higher = faster adaptation )
        """
        K = forecasts.shape[1]
        weights = np.ones(K) / K  # uniform initialization
        combined = pd.Series(index=forecasts.index, dtype=float)

        loss_functions = {
            'mse': lambda y, yhat: (y - yhat) ** 2,
            'qlike': lambda y, yhat: y / (yhat + 1e-10) - np.log(y / (yhat + 1e-10) + 1e-10) - 1,
            'mae': lambda y, yhat: np.abs(y - yhat)
        }
        loss_fn_callable = loss_functions[loss_fn]

        for t in range(len(forecasts)):
            fc_t = forecasts.iloc[t].fillna(forecasts.iloc[t].mean()).values
            combined.iloc[t] = np.dot(weights, fc_t)

            if t < len(realized) and not np.isnan(realized.iloc[t]):
                # Compute per - model loss and update weights
                y_t = realized.iloc[t]
                losses = np.array([loss_fn_callable(y_t, fc_t[k]) for k in range(K)])
                weights = weights * np.exp(-eta * losses)
                weights /= weights.sum()  # normalize

        return combined

    def run_full_combination(self, forecasts: pd.DataFrame,
                             realized: pd.Series,
                             train_size: int = 252) -> pd.DataFrame:
        """
        Run all combination methods and compare OOS performance .
        """
        oos_start = train_size
        fc_oos = forecasts.iloc[oos_start:]
        rv_oos = realized.iloc[oos_start:]

        results = pd.DataFrame(index=fc_oos.index)

        # Individual models
        for col in forecasts.columns:
            results[col] = fc_oos[col]

        # Combination methods
        results['equal_weight'] = self.equal_weight(fc_oos)
        results['inv_mse'] = self.inverse_mse_weight(forecasts, realized).iloc[oos_start:]
        results['exp_weight'] = self.exponential_weighting(forecasts, realized).iloc[oos_start:]
        results['gr_constrained'] = self.granger_ramanathan(forecasts, realized, constrained=True).iloc[oos_start:]
        results['stacking'] = self.stacking_combination(forecasts, realized).iloc[oos_start:]

        # Evaluate all
        evaluation = {}
        for col in results.columns:
            fc = results[col].dropna()
            rv = rv_oos.reindex(fc.index).dropna()
            aligned = pd.concat([fc, rv], axis=1).dropna()

            if len(aligned) < 20:
                continue

            f = aligned.iloc[:, 0].values
            r = aligned.iloc[:, 1].values

            evaluation[col] = {
                'QLIKE': np.mean(r / (f + 1e-10) - np.log(r / (f + 1e-10) + 1e-10) - 1),
                'MSE': np.mean((r - f) ** 2),
                'LogMSE': np.mean((np.log(r + 1e-10) - np.log(f + 1e-10)) ** 2),
                'Corr': np.corrcoef(r, f)[0, 1]
            }

        return pd.DataFrame(evaluation).T.sort_values('QLIKE')


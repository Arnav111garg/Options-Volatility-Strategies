import numpy as np
import pandas as pd
from typing import List, Optional, Dict

class EventFeatureBuilder:
    """Build event-driven features for volatility forecasting.

    Handles: FOMC, earnings, macro releases, options expirations.
    """

    def __init__(self):
        pass

    def build_fomc_features(self,
                             index: pd.DatetimeIndex,
                             fomc_dates: List[pd.Timestamp]) -> pd.DataFrame:
        """
        FOMC proximity and regime features.

        Parameters
        ----------
        fomc_dates : List of FOMC announcement dates
        """
        feat = pd.DataFrame(index=index)
        fomc_set = pd.DatetimeIndex(fomc_dates)

        # Days to next FOMC
        days_to_fomc = pd.Series(index=index, dtype=float)
        for date in index:
            future_fomc = fomc_set[fomc_set >= date]
            days_to_fomc[date] = len(index[(index >= date) & (index < future_fomc[0])]) \
                if len(future_fomc) > 0 else np.nan

        feat['days_to_fomc'] = days_to_fomc.shift(1)
        feat['fomc_week'] = (days_to_fomc.shift(1) <= 5).astype(float)
        feat['fomc_day'] = index.isin(fomc_set).astype(float)

        # FOMC inverse proximity (closer = more weight)
        feat['fomc_proximity'] = 1 / (feat['days_to_fomc'].clip(lower=1) + 1)

        # Days since last FOMC
        days_since_fomc = pd.Series(index=index, dtype=float)
        for date in index:
            past_fomc = fomc_set[fomc_set <= date]
            days_since_fomc[date] = len(index[(index <= date) & (index > past_fomc[-1])]) \
                if len(past_fomc) > 0 else np.nan
        feat['days_since_fomc'] = days_since_fomc.shift(1)
        return feat

    def build_earnings_features(self,
                                 rv: pd.Series,
                                 earnings_dates: Dict[str, List[pd.Timestamp]],
                                 eps_surprises: Optional[pd.Series] = None) -> pd.DataFrame:
        """
        Earnings proximity, surprise, and vol premium features.

        Parameters
        ----------
        earnings_dates : dict mapping ticker -> list of earnings dates
        eps_surprises : pd.Series of absolute EPS surprises (normalized)
        """
        feat = pd.DataFrame(index=rv.index)
        all_earnings = sorted(set(
            d for dates in earnings_dates.values() for d in dates
        ))
        earn_idx = pd.DatetimeIndex(all_earnings)

        # Earnings count in next N days
        for window in [5, 22]:
            count = pd.Series(index=rv.index, dtype=float)
            for date in rv.index:
                future = earn_idx[(earn_idx > date) & (earn_idx <= date + pd.offsets.BDay(window))]
                count[date] = len(future)
            feat[f'earnings_count_{window}d'] = count.shift(1)

        # Historical earnings vol premium
        if eps_surprises is not None:
            feat['eps_surprise_lag1'] = eps_surprises.shift(1)
            feat['eps_surprise_ma5'] = eps_surprises.shift(1).rolling(5).mean()

        return feat

    def build_macro_release_features(self,
                                     index: pd.DatetimeIndex,
                                     macro_schedule: Dict[str, List[pd.Timestamp]],
                                     macro_surprises: Optional[pd.DataFrame] = None) -> pd.DataFrame:
        """
        Macro release proximity features.

        Parameters
        ----------
        macro_schedule : {'NFP': [... dates ...], 'CPI': [...], ...}
        macro_surprises : DataFrame with columns matching macro_schedule keys,
                          containing standardised surprise values
        """
        feat = pd.DataFrame(index=index)

        for event_name, dates in macro_schedule.items():
            event_idx = pd.DatetimeIndex(dates)

            # Binary : event today
            feat[f'{event_name}_today'] = (index.isin(event_idx)).astype(float).shift(1).fillna(0)

            # Days to next release
            days_to = pd.Series(index=index, dtype=float)
            for date in index:
                future = event_idx[event_idx >= date]
                days_to[date] = max(1, len(index[(index >= date) & (index < future[0])])) \
                    if len(future) > 0 else 40
            feat[f'{event_name}_days_to'] = days_to.shift(1)

            # Proximity indicator
            feat[f'{event_name}_proximity'] = (1 / feat[f'{event_name}_days_to'].clip(lower=1))

            # Historical surprise
            if macro_surprises is not None and event_name in macro_surprises:
                surprise = macro_surprises[event_name].reindex(index, method='ffill')
                feat[f'{event_name}_surprise'] = surprise.abs().shift(1)
                feat[f'{event_name}_surprise_ma3'] = (surprise.abs().rolling(3).mean().shift(1))
        return feat

    def build_options_expiry_features(self, index: pd.DatetimeIndex) -> pd.DataFrame:
        """
        Options expiration calendar features.
        Monthly (3rd Fri), quarterly (expiry Fri of Mar/Jun/Sep/Dec), weekly, and LEAPS.
        """
        feat = pd.DataFrame(index=index)

        # Monthly expirations (3rd Friday of each month)
        monthly_expiry = []
        for year in range(index.year.min(), index.year.max() + 2):
            for month in range(1, 13):
                first_day = pd.Timestamp(year, month, 1)
                days = pd.date_range(first_day, first_day + pd.offsets.MonthEnd(0), freq='B')
                fridays = days[days.weekday == 4]
                if len(fridays) >= 3:
                    monthly_expiry.append(fridays[2])

        expiry_idx = pd.DatetimeIndex(monthly_expiry)

        # Days to next monthly expiry
        days_to_exp = pd.Series(index=index, dtype=float)
        for date in index:
            future = expiry_idx[expiry_idx >= date]
            days_to_exp[date] = len(index[(index >= date) & (index < future[0])]) \
                if len(future) > 0 else np.nan

        feat['days_to_monthly_expiry'] = days_to_exp.shift(1)
        feat['expiry_week'] = (days_to_exp.shift(1) <= 5).astype(float)
        feat['expiry_day'] = index.isin(expiry_idx).astype(float)

        # Quarter-end features (pin risk for indices)
        feat['quarter_end_week'] = (
            (index.is_quarter_end | (index + pd.offsets.BDay(5)).is_quarter_end)
        ).astype(float)

        return feat


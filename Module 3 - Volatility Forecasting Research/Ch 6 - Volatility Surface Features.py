import numpy as np
import pandas as pd
from scipy.interpolate import RectBivariateSpline, interp1d
from scipy.stats import norm
from typing import Dict, Optional, Tuple

class SurfaceFeatureBuilder:
    """
    Extract features from the implied volatility surface.

    Inputs: daily options chain data (strike, expiry, IV)
    Outputs: level, slope, curvature, VRP, and risk-neutral moment features
    """

    def __init__(self, standard_tenors=(30, 60, 91, 182, 365)):
        self.standard_tenors = standard_tenors  # in calendar days

    # Surface Loading and Interpolation

    @staticmethod
    def build_surface_grid(options_df: pd.DataFrame,
                           ref_date: pd.Timestamp,
                           spot: float) -> Optional[pd.DataFrame]:
        """
        Build a moneyness-tenor grid of IVs.

        Parameters
        ----------
        options_df : DataFrame with columns [strike, expiry_date, iv, option_type]
        ref_date : pricing date
        spot : current spot price

        Returns
        -------
        DataFrame with index=DTE, columns=log_moneyness values
        """
        df = options_df.copy()
        df['dte'] = (pd.to_datetime(df['expiry_date']) - ref_date).dt.days
        df = df[df['dte'] > 0]

        if len(df) < 10:
            return None

        # Log-moneyness
        df['lm'] = np.log(df['strike'] / spot)

        # Pivot to grid
        grid = df.pivot_table(values='iv', index='dte', columns='lm', aggfunc='mean')
        return grid

    # ATM IV Features

    def extract_atm_iv(self, surface_df: pd.DataFrame) -> Dict[str, float]:
        """Extract ATM IV at standard tenors via interpolation."""
        features = {}

        # Interpolate along DTE axis at zero log-moneyness
        if 0 not in surface_df.columns:
            # Find closest column to ATM
            atm_col = surface_df.columns[np.argmin(np.abs(surface_df.columns))]
        else:
            atm_col = 0

        atm_iv_by_dte = surface_df[atm_col].dropna()

        if len(atm_iv_by_dte) < 2:
            return features

        # Interpolate to standard tenors
        f_interp = interp1d(atm_iv_by_dte.index, atm_iv_by_dte.values,
                            kind='linear', fill_value='extrapolate')

        for T in self.standard_tenors:
            if T <= atm_iv_by_dte.index.max():
                features[f'atm_iv_{T}d'] = float(f_interp(T))

        return features

    # Skew Features

    def extract_skew_features(self, surface_df: pd.DataFrame,
                              spot: float,
                              tenor: int = 30) -> Dict[str, float]:
        """
        Extract skew: risk reversal, butterfly, slope.
        Uses log-moneyness interpolation.
        """
        features = {}

        # Find rows nearest to desired tenor
        if tenor not in surface_df.index:
            nearest_tenors = surface_df.index[np.argsort(np.abs(surface_df.index - tenor))][:2]
            row = surface_df.loc[nearest_tenors].mean()
        else:
            row = surface_df.loc[tenor]

        row = row.dropna()
        if len(row) < 5:
            return features

        # Interpolate to standard moneyness levels
        f_row = interp1d(row.index, row.values, kind='cubic',
                         bounds_error=False, fill_value=np.nan)

        T_years = tenor / 365.0
        atm_iv = float(f_row(0)) if not np.isnan(f_row(0)) else row.iloc[len(row) // 2]

        # 25-delta strikes (approximate log-moneyness)
        lm_25p = -atm_iv * np.sqrt(T_years) * norm.ppf(0.75)  # 25-delta put
        lm_25c = atm_iv * np.sqrt(T_years) * norm.ppf(0.75)   # 25-delta call
        lm_10p = -atm_iv * np.sqrt(T_years) * norm.ppf(0.90)  # 10-delta put
        lm_10c = atm_iv * np.sqrt(T_years) * norm.ppf(0.90)   # 10-delta call

        iv_25p = float(f_row(lm_25p))
        iv_25c = float(f_row(lm_25c))
        iv_10p = float(f_row(lm_10p))
        iv_10c = float(f_row(lm_10c))

        # Risk reversals
        features[f'rr25_{tenor}d'] = iv_25c - iv_25p
        features[f'rr10_{tenor}d'] = iv_10c - iv_10p

        # Butterfly (smile curvature)
        features[f'bf25_{tenor}d'] = (iv_25c + iv_25p) / 2 - atm_iv
        features[f'bf10_{tenor}d'] = (iv_10c + iv_10p) / 2 - atm_iv

        # Normalized skew (skew per unit vol)
        features[f'skew_norm_{tenor}d'] = features[f'rr25_{tenor}d'] / (atm_iv + 1e-6)

        # Skew slope at ATM
        dx = 0.01  # bump moneyness
        iv_up = float(f_row(dx))
        iv_dn = float(f_row(-dx))
        features[f'skew_slope_{tenor}d'] = (iv_up - iv_dn) / (2 * dx) if (
            not np.isnan(iv_up) and not np.isnan(iv_dn)) else np.nan

        return features

    # Term Structure Features

    def extract_term_structure_features(self, surface_df: pd.DataFrame) -> Dict[str, float]:
        """Extract vol term structure slope, curvature, kink."""
        features = {}
        atm_ivs = self.extract_atm_iv(surface_df)

        if 'atm_iv_30d' in atm_ivs and 'atm_iv_365d' in atm_ivs:
            # Term structure slope
            features['ts_slope'] = (
                atm_ivs.get('atm_iv_365d', np.nan) -
                atm_ivs.get('atm_iv_30d', np.nan)
            )

            # Contango indicator (longer > shorter)
            features['ts_contango'] = float(features['ts_slope'] > 0)

        # Curvature (mid vs. extremes)
        if 'atm_iv_91d' in atm_ivs and 'atm_iv_30d' in atm_ivs and 'atm_iv_365d' in atm_ivs:
            features['ts_curve'] = (
                2 * atm_ivs['atm_iv_91d'] -
                atm_ivs['atm_iv_30d'] -
                atm_ivs['atm_iv_365d']
            )

        return features

    # Variance Risk Premium

    @staticmethod
    def compute_vrp(iv_series: pd.Series,
                    rv_series: pd.Series,
                    vrp_window: int = 22) -> pd.Series:
        """
        Variance Risk Premium: VRP = IV^2 - E[RV].

        Use rolling realized variance as ex-post proxy for E[RV].
        Both in annualized variance units.
        """
        iv_var = iv_series ** 2  # convert vol to variance
        rv_var = rv_series ** 2

        # Use trailing realized variance as proxy for conditional E[RV]
        rv_expected = rv_var.rolling(vrp_window).mean()

        vrp = iv_var - rv_expected
        return vrp

    # Model-Free Risk-Neutral Moments

    @staticmethod
    def compute_rn_variance(options_df: pd.DataFrame,
                            forward: float,
                            rate: float,
                            T: float) -> float:
        """
        Model-free risk-neutral variance (Bakshi et al., 2003).
        Uses trapezoidal integration over the option chain.

        Parameters
        ----------
        options_df : DataFrame with [strike, price, option_type]
        forward : F(T) forward price
        rate : risk-free rate
        T : time to maturity (years)
        """
        calls = options_df[options_df['option_type'] == 'C'].sort_values('strike')
        puts = options_df[options_df['option_type'] == 'P'].sort_values('strike')

        # OTM calls : K > F
        otm_calls = calls[calls['strike'] > forward]
        # OTM puts : K < F
        otm_puts = puts[puts['strike'] < forward]

        def integrate_chain(df, price_col='price'):
            K = df['strike'].values
            C = df[price_col].values
            if len(K) < 2:
                return 0.0
            # 2 * int C(K)/K^2 dK (trapezoidal)
            integrand = 2 * C / K ** 2
            return np.trapz(integrand, K)

        call_integral = integrate_chain(otm_calls)
        put_integral = integrate_chain(otm_puts)

        rn_var = np.exp(rate * T) * (call_integral + put_integral) / forward ** 2
        return rn_var

    def build_daily_surface_features(self,
                                     daily_options: Dict[pd.Timestamp, pd.DataFrame],
                                     spot: pd.Series,
                                     rv: pd.Series) -> pd.DataFrame:
        """
        Build complete daily surface feature dataframe.

        Parameters
        ----------
        daily_options : dict mapping date -> options DataFrame
        spot : daily spot prices
        rv : daily realized vol
        """
        records = []

        for date, options_df in daily_options.items():
            if date not in spot.index:
                continue

            s = spot[date]
            surf = self.build_surface_grid(options_df, date, s)

            if surf is None:
                continue

            row = {'date': date}

            # ATM IV features
            row.update(self.extract_atm_iv(surf))

            # Skew features at 1M and 3M tenor
            row.update(self.extract_skew_features(surf, s, tenor=30))
            row.update(self.extract_skew_features(surf, s, tenor=91))

            # Term structure
            row.update(self.extract_term_structure_features(surf))

            records.append(row)

        if not records:
            return pd.DataFrame()

        result = pd.DataFrame(records).set_index('date')

        # Add VRP (shift to avoid lookahead)
        if 'atm_iv_30d' in result.columns and rv is not None:
            iv_aligned = result['atm_iv_30d'].reindex(rv.index)
            vrp = self.compute_vrp(iv_aligned, rv)
            result['vrp'] = vrp.reindex(result.index)
            result['vrp_lag1'] = result['vrp'].shift(1)

        return result.shift(1)  # shift entire surface features by 1 day


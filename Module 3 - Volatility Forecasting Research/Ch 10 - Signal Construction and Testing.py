import numpy as np
import pandas as pd
from scipy import stats
from sklearn.linear_model import LassoCV, RidgeCV
from sklearn.model_selection import TimeSeriesSplit
from typing import List, Dict, Tuple, Optional
import warnings

class VolatilityAlphaDiscovery:
    """
    Systematic volatility alpha discovery with proper multiple-testing
    controls and economic validation.

    Pipeline:
    1. Signal screening (univariate predictability)
    2. Multiple testing correction (White/Romano-Wolf)
    3. Factor model attribution (what portion is known risk premium?)
    4. Economic evaluation (simulated P&L)
    5. Robustness checks (subperiods, markets, regimes)
    """

    def __init__(self, min_oos_fraction: float = 0.3, significance_level: float = 0.05):
        self.min_oos_fraction = min_oos_fraction
        self.alpha_level = significance_level

    # Step 1: Univariate Signal Screening

    def screen_signals(self, features: pd.DataFrame, target: pd.Series, horizon: int = 1, min_train: int = 252) -> pd.DataFrame:
        """
        Screen all features for predictive power using walk-forward univariate regressions.
        Returns DataFrame with signal screening statistics.
        """
        results = {}

        for col in features.columns:
            x = features[col].dropna()
            y = target.shift(-horizon).dropna()
            aligned = pd.concat([x, y], axis=1).dropna()

            if len(aligned) < min_train + 20:
                continue

            # OOS evaluation (expanding window)
            oos_fc, oos_rv = [], []

            for t in range(min_train, len(aligned) - horizon):
                X_tr = aligned.iloc[:t, 0].values.reshape(-1, 1)
                y_tr = aligned.iloc[:t, 1].values
                X_te = aligned.iloc[t, 0].reshape(1, -1)
                # OLS forecast
                beta = np.polyfit(X_tr.ravel(), y_tr, 1)
                fc = np.polyval(beta, float(X_te))
                oos_fc.append(max(fc, 0.01))  # clip at 0
                oos_rv.append(aligned.iloc[t + horizon - 1, 1] if t + horizon - 1 < len(aligned) else np.nan)

            if not oos_fc:
                continue

            fc_arr = np.array(oos_fc)
            rv_arr = np.array(oos_rv)
            valid = ~np.isnan(rv_arr)
            fc_arr, rv_arr = fc_arr[valid], rv_arr[valid]

            if len(fc_arr) < 30:
                continue

            # Compute OOS R2 vs. historical mean benchmark
            rv_mean = np.mean(rv_arr[:min_train]) * np.ones(len(rv_arr))
            oos_r2 = 1 - np.mean((rv_arr - fc_arr) ** 2) / np.mean((rv_arr - rv_mean) ** 2)

            # QLIKE
            eps = 1e-10
            qlike_model = np.mean(rv_arr / np.maximum(fc_arr, eps) - np.log(rv_arr / np.maximum(fc_arr, eps)) - 1)
            qlike_bench = np.mean(rv_arr / np.maximum(rv_mean, eps) - np.log(rv_arr / np.maximum(rv_mean, eps)) - 1)

            # Correlation test
            corr, corr_pval = stats.pearsonr(fc_arr, rv_arr)

            results[col] = {
                'OOS_R2': oos_r2,
                'QLIKE_model': qlike_model,
                'QLIKE_bench': qlike_bench,
                'QLIKE_improvement': qlike_bench - qlike_model,
                'Corr_oos': corr,
                'Corr_pval': corr_pval,
                'N_oos': len(fc_arr)
            }

        df = pd.DataFrame(results).T
        df['significant_raw'] = df['Corr_pval'] < self.alpha_level

        # Multiple testing correction (Bonferroni conservative)
        n_tests = len(df)
        df['p_bonferroni'] = (df['Corr_pval'] * n_tests).clip(upper=1.0)
        df['significant_bonferroni'] = df['p_bonferroni'] < self.alpha_level

        # BH correction
        df = df.sort_values('Corr_pval')
        ranks = np.arange(1, len(df) + 1)
        df['p_bh_threshold'] = ranks / n_tests * self.alpha_level
        df['significant_bh'] = df['Corr_pval'] <= df['p_bh_threshold']

        return df.sort_values('OOS_R2', ascending=False)

    # Step 2: Factor Attribution

    def factor_attribution(self, signal: pd.Series, factor_returns: pd.DataFrame, vol_strategy_returns: pd.Series) -> Dict:
        """
        Attribute strategy P&L to known risk factors vs. true alpha.
        Factors typically include: VRP, skew, jump, beta, size, etc.
        Returns alpha (Jensen's alpha) and factor loadings.
        """
        all_data = pd.concat([vol_strategy_returns.rename('strategy'), factor_returns], axis=1).dropna()
        y = all_data['strategy'].values
        X = sm_add_const(all_data[factor_returns.columns].values)

        from numpy.linalg import lstsq
        beta, _, _, _ = lstsq(X, y, rcond=None)
        resids = y - X @ beta

        # Information Ratio of residuals (true alpha)
        alpha_ann = beta[0] * 252
        ir_alpha = np.mean(resids) / np.std(resids) * np.sqrt(252) if np.std(resids) > 0 else 0

        return {
            'alpha_daily': beta[0],
            'alpha_annual': alpha_ann,
            'factor_betas': dict(zip(factor_returns.columns, beta[1:])),
            'IR_alpha': ir_alpha,
            'R2_factor': 1 - np.var(resids) / np.var(y),
            'residual_SR': ir_alpha
        }

    # Step 3: Economic Evaluation

    def simulate_vol_strategy_pnl(self, rv_forecast: pd.Series, iv: pd.Series, realized_rv: pd.Series, entry_threshold: float = 0.02, transaction_cost_pct: float = 0.15, vega_target: float = 1e4) -> pd.DataFrame:
        """
        Simulate P&L from a simple straddle strategy driven by vol forecast.
        Buy straddle when: IV - forecast > entry_threshold (sell vol)
        Sell straddle when: forecast - IV > entry_threshold (buy vol)
        """
        all_data = pd.concat([rv_forecast.rename('fc'), iv.rename('iv'), realized_rv.rename('rv')], axis=1).dropna()
        vrp_signal = all_data['iv'] - all_data['fc']  # + => sell vol

        pnl_records = []
        for t in range(1, len(all_data)):
            date = all_data.index[t]
            signal_t = vrp_signal.iloc[t - 1]

            if abs(signal_t) < entry_threshold:
                position = 0
            elif signal_t > entry_threshold:
                position = -1  # short straddle (sell vol)
            else:
                position = 1  # long straddle (buy vol)

            if position == -1:
                # Short straddle: profit when RV < IV
                gross_pnl = (all_data['iv'].iloc[t - 1] - all_data['rv'].iloc[t]) * vega_target
                tc = abs(all_data['iv'].iloc[t - 1]) * transaction_cost_pct * vega_target
                net_pnl = gross_pnl - tc
            elif position == 1:
                # Long straddle: profit when RV > IV
                gross_pnl = (all_data['rv'].iloc[t] - all_data['iv'].iloc[t - 1]) * vega_target
                tc = abs(all_data['iv'].iloc[t - 1]) * transaction_cost_pct * vega_target
                net_pnl = gross_pnl - tc
            else:
                net_pnl = 0.0
                gross_pnl = 0.0
                tc = 0.0

            pnl_records.append({
                'date': date, 'position': position,
                'signal': signal_t, 'gross_pnl': gross_pnl,
                'transaction_cost': tc, 'net_pnl': net_pnl
            })

        result = pd.DataFrame(pnl_records).set_index('date')
        result['cumulative_pnl'] = result['net_pnl'].cumsum()

        # Performance metrics
        active = result[result['position'] != 0]
        T_ann = len(result) / 252

        print("=== Strategy Performance ===")
        print(f"Total P&L: ${result['net_pnl'].sum():,.0f}")
        print(f"Annualized P&L: ${result['net_pnl'].sum()/ T_ann:,.0f}")
        print(f"Sharpe Ratio: {result['net_pnl'].mean()/ result['net_pnl'].std() * np.sqrt(252):.2f}")
        print(f"Max Drawdown: ${(result['cumulative_pnl'].cummax() - result['cumulative_pnl']).max():,.0f}")
        print(f"Win Rate: {(active['net_pnl'] > 0).mean():.1%}")
        print(f"Avg Days Active: {(result['position'] != 0).mean():.1%}")

        return result

    # Step 4: Robustness Testing

    def robustness_checks(self, signal: pd.Series, target: pd.Series, subperiods: Optional[List[Tuple]] = None) -> pd.DataFrame:
        """
        Test signal across subperiods and regimes.
        """
        results = {}

        if subperiods is None:
            full_start = signal.index.min().year
            full_end = signal.index.max().year
            mid = (full_start + full_end) // 2

            subperiods = [
                (str(full_start), str(mid), 'First Half'),
                (str(mid + 1), str(full_end), 'Second Half'),
                ('2008', '2009', 'GFC'),
                ('2020', '2020', 'COVID'),
                ('2022', '2022', 'Inflation Spike')
            ]

        for start, end, label in subperiods:
            mask = (signal.index >= start) & (signal.index <= end)
            s = signal[mask]
            t = target[mask]

            aligned = pd.concat([s, t], axis=1).dropna()
            if len(aligned) < 30:
                results[label] = {'N': len(aligned), 'note': 'insufficient data'}
                continue

            corr, pval = stats.pearsonr(aligned.iloc[:, 0], aligned.iloc[:, 1])

            results[label] = {
                'N': len(aligned),
                'Correlation': corr,
                'p-value': pval,
                'Significant': pval < 0.05,
                'start': start, 'end': end
            }

        return pd.DataFrame(results).T


def sm_add_const(X):
    """Add intercept column to design matrix."""
    return np.column_stack([np.ones(len(X)), X])


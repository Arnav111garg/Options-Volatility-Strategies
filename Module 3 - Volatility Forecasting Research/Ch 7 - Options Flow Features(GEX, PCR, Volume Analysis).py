import numpy as np
import pandas as pd
from scipy.stats import norm
from typing import Optional

class FlowFeatureBuilder:
    """
    Build options flow features for volatility forecasting .

    Features :
    - Dealer Gamma Exposure (GEX)
    - Put - Call Ratios ( volume and OI)
    - Volume - weighted skew ( demand for puts vs calls )
    - Dark pool and institutional flow proxies
    """

    @staticmethod
    def black_scholes_greeks(S: float, K: float, T: float,
                             r: float, sigma: float,
                             option_type: str = 'C') -> dict:
        """ Compute BS Greeks for a single option ."""
        if T <= 0 or sigma <= 0:
            return {'delta': 0.0, 'gamma': 0.0, 'vega': 0.0, 'theta': 0.0}

        d1 = (np.log(S / K) + (r + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
        d2 = d1 - sigma * np.sqrt(T)

        N = norm.cdf
        n = norm.pdf
        sign = 1 if option_type == 'C' else -1

        delta = sign * N(sign * d1)
        gamma = n(d1) / (S * sigma * np.sqrt(T))
        vega = S * n(d1) * np.sqrt(T)

        return {'delta': delta, 'gamma': gamma, 'vega': vega}

    def compute_gex(self,
                    options_chain: pd.DataFrame,
                    spot: float,
                    rate: float = 0.05,
                    multiplier: int = 100) -> float:
        """
        Compute dealer Gamma Exposure (GEX).

        Assumes market makers are SHORT calls and LONG puts
        ( customer flow perspective : customers buy calls , sell puts ).

        Parameters
        ----------
        options_chain : DataFrame with columns :
        [strike , dte , iv , open_interest , option_type ]
        spot : current spot price

        Returns
        -------
        float : GEX in $ per 1% move ( positive = dealer long gamma )
        """
        gex_total = 0.0

        for _, row in options_chain.iterrows():
            K = row['strike']
            T = row['dte'] / 365.0
            iv = row['iv']
            OI = row['open_interest']
            typ = row['option_type']

            if T <= 0 or iv <= 0 or OI <= 0:
                continue

            greeks = self.black_scholes_greeks(spot, K, T, rate, iv, typ)
            gamma = greeks['gamma']

            # Convention : dealer is short calls (+1 to customer ), long puts
            # => GEX from calls is negative ( short gamma ), from puts positive
            if typ == 'C':
                gex_total -= OI * gamma * spot ** 2 * multiplier * 0.01
            else: # Put
                gex_total += OI * gamma * spot ** 2 * multiplier * 0.01

        return gex_total

    def compute_daily_flow_features(self,
                                    options_chain: pd.DataFrame,
                                    spot: float,
                                    rate: float = 0.05) -> dict:
        """
        Extract comprehensive flow features from a daily options chain .

        Returns dict of features .
        """
        features = {}
        chain = options_chain.copy()

        # Gamma Exposure
        features['gex'] = self.compute_gex(chain, spot, rate)
        features['gex_sign'] = np.sign(features['gex'])
        features['gex_abs'] = abs(features['gex'])

        # Put - Call Ratios
        puts = chain[chain['option_type'] == 'P']
        calls = chain[chain['option_type'] == 'C']

        # Volume PCR ( requires volume column )
        if 'volume' in chain.columns:
            put_vol = puts['volume'].sum()
            call_vol = calls['volume'].sum()
            features['pcr_volume'] = (put_vol / call_vol if call_vol > 0 else np.nan)

        # OI PCR
        put_oi = puts['open_interest'].sum()
        call_oi = calls['open_interest'].sum()
        features['pcr_oi'] = (put_oi / call_oi if call_oi > 0 else np.nan)

        # Vega - Weighted Features
        # Total vega dollar by puts vs calls ( demand for vol protection )
        def vega_dollar(df):
            total = 0.0
            for _, row in df.iterrows():
                T = row['dte'] / 365.0
                if T <= 0 or row['iv'] <= 0:
                    continue
                g = self.black_scholes_greeks(spot, row['strike'], T, rate, row['iv'], row['option_type'])
                total += g['vega'] * row['open_interest']
            return total

        features['vega_dollar_puts'] = vega_dollar(puts)
        features['vega_dollar_calls'] = vega_dollar(calls)
        features['vega_pcr'] = (
            features['vega_dollar_puts'] / features['vega_dollar_calls']
            if features['vega_dollar_calls'] > 0 else np.nan
        )

        # Moneyness Distribution of OI
        # OTM put demand ( tail hedging )
        otm_puts_90 = puts[puts['strike'] < 0.90 * spot]['open_interest'].sum()
        otm_puts_95 = puts[(puts['strike'] >= 0.90 * spot) & (puts['strike'] < 0.95 * spot)]['open_interest'].sum()

        features['tail_put_oi_90'] = otm_puts_90
        features['near_put_oi_95'] = otm_puts_95
        features['tail_hedge_demand'] = (otm_puts_90 / put_oi if put_oi > 0 else 0.0)

        return features

    def build_time_series_flow(self,
                               daily_chains: dict,
                               spot: pd.Series,
                               rate: float = 0.05) -> pd.DataFrame:
        """
        Build time series of flow features from daily option chains .

        Parameters
        ----------
        daily_chains : dict mapping pd. Timestamp -> options DataFrame
        spot : daily spot price series

        Returns
        -------
        pd. DataFrame of daily flow features ( shifted 1 day to avoid lookahead )
        """
        records = []

        for date, chain in sorted(daily_chains.items()):
            if date not in spot.index:
                continue
            s = spot[date]
            feat = self.compute_daily_flow_features(chain, s, rate)
            feat['date'] = date
            records.append(feat)

        if not records:
            return pd.DataFrame()

        df = pd.DataFrame(records).set_index('date').sort_index()

        # Rolling normalization (z- score of flow features )
        for col in ['gex', 'pcr_volume', 'pcr_oi', 'vega_pcr']:
            if col in df.columns:
                mu = df[col].rolling(63).mean()
                sigma = df[col].rolling(63).std()
                df[f'{col}_zscore'] = (df[col] - mu) / sigma.clip(lower=1e-10)

        # Shift 1 day for forecasting (no lookahead )
        return df.shift(1)


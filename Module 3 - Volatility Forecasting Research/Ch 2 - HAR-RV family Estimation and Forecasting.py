import numpy as np
import pandas as pd
from scipy.linalg import lstsq
import statsmodels.api as sm
from statsmodels.regression.linear_model import OLS
from typing import Dict, Optional, Tuple

class HARModel:
    """
    Heterogeneous Autoregressive Model for Realized Volatility.

    Supports: HAR-RV, HAR-RV-J, LHAR-RV (leverage), HAR-RV-RS (semivariance),
    Log-HAR-RV, and multi-horizon variants.
    """

    VARIANTS = ['har', 'har_j', 'lhar', 'har_rs', 'log_har']

    def __init__(self, variant: str = 'har', horizon: int = 1,
                 lags: Tuple[int, ...] = (1, 5, 22)):
        assert variant in self.VARIANTS, f"Unknown variant. Choose from {self.VARIANTS}"
        self.variant = variant
        self.horizon = horizon
        self.lags_d, self.lags_w, self.lags_m = lags
        self.beta_ = None
        self.resid_ = None
        self.fitted_values_ = None

    def _build_features(self, rv: pd.Series,
                        bv: Optional[pd.Series] = None,
                        returns: Optional[pd.Series] = None,
                        rs_plus: Optional[pd.Series] = None,
                        rs_minus: Optional[pd.Series] = None) -> pd.DataFrame:
        """Construct feature matrix for the selected HAR variant."""
        features = pd.DataFrame(index=rv.index)

        # Lag components
        rv_d = rv.shift(1)                    # RV_{t-1}^{(1)}
        rv_w = rv.shift(1).rolling(self.lags_w).mean()  # RV_{t-1}^{(w)}
        rv_m = rv.shift(1).rolling(self.lags_m).mean()  # RV_{t-1}^{(m)}

        if self.variant == 'log_har':
            rv_d, rv_w, rv_m = np.log(rv_d), np.log(rv_w), np.log(rv_m)

        features['const'] = 1.0
        features['RV_d'] = rv_d
        features['RV_w'] = rv_w
        features['RV_m'] = rv_m

        if self.variant == 'har_j':
            assert bv is not None, "BV required for HAR-J"
            # Continuous component (BPV)
            cont = bv.shift(1)
            cont_w = bv.shift(1).rolling(self.lags_w).mean()
            cont_m = bv.shift(1).rolling(self.lags_m).mean()
            jump = np.maximum(rv.shift(1) - bv.shift(1), 0)
            features['C_d'] = cont
            features['C_w'] = cont_w
            features['C_m'] = cont_m
            features['J'] = jump
            features.drop(columns=['RV_d', 'RV_w', 'RV_m'], inplace=True)

        elif self.variant == 'lhar':
            assert returns is not None, "Returns required for LHAR"
            features['r_neg'] = np.minimum(returns.shift(1), 0)

        elif self.variant == 'har_rs':
            assert rs_plus is not None and rs_minus is not None
            features['RS_plus_d'] = rs_plus.shift(1)
            features['RS_minus_d'] = rs_minus.shift(1)
            features.drop(columns=['RV_d'], inplace=True)

        return features.dropna()

    def _build_target(self, rv: pd.Series) -> pd.Series:
        """Build h-period forward RV average."""
        if self.variant == 'log_har':
            y = np.log(rv)
        else:
            y = rv

        if self.horizon == 1:
            return y
        else:
            # Rolling forward mean (h-day horizon)
            return y.shift(-self.horizon + 1).rolling(self.horizon).mean()

    def fit(self, rv: pd.Series, **kwargs) -> 'HARModel':
        """Fit HAR model using OLS with Newey-West SE."""
        X = self._build_features(rv, **kwargs)
        y = self._build_target(rv)

        # Align
        aligned = pd.concat([y.rename('y'), X], axis=1).dropna()
        y_fit = aligned['y']
        X_fit = aligned.drop(columns='y')

        # Fit OLS with HAC standard errors
        model = OLS(y_fit, X_fit.values).fit(
            cov_type='HAC',
            cov_kwds={'maxlags': max(self.lags_w, self.horizon)}
        )

        self.beta_ = pd.Series(model.params, index=X_fit.columns)
        self.tvalues_ = pd.Series(model.tvalues, index=X_fit.columns)
        self.pvalues_ = pd.Series(model.pvalues, index=X_fit.columns)
        self.resid_ = pd.Series(model.resid, index=y_fit.index)
        self.fitted_values_ = pd.Series(model.fittedvalues, index=y_fit.index)
        self.r2_ = model.rsquared
        self.r2_adj_ = model.rsquared_adj
        self.n_obs_ = len(y_fit)
        self._X_fit = X_fit  # store for forecasting
        return self

    def predict(self, rv: pd.Series, **kwargs) -> pd.Series:
        """Generate out-of-sample forecasts."""
        assert self.beta_ is not None, "Model not fitted"
        X = self._build_features(rv, **kwargs)
        # Align columns
        X_pred = X[self.beta_.index].dropna()
        forecasts = X_pred.values @ self.beta_.values

        if self.variant == 'log_har':
            sigma_eps = self.resid_.std()
            forecasts = np.exp(forecasts + 0.5 * sigma_eps ** 2)

        return pd.Series(forecasts, index=X_pred.index)

    def rolling_forecast(self, rv: pd.Series, train_size: int = 500, **kwargs) -> pd.DataFrame:
        """
        Expanding-window out-of-sample forecast evaluation.
        Returns DataFrame with forecasts, realized values, and losses.
        """
        forecasts, realized = [], []
        idx = []

        for t in range(train_size, len(rv) - self.horizon):
            # Refit on expanding window
            rv_train = rv.iloc[:t]
            model = HARModel(variant=self.variant, horizon=self.horizon)

            try:
                model.fit(rv_train, **{k: v.iloc[:t] for k, v in kwargs.items()})
                # Forecast next period
                rv_last = rv.iloc[max(0, t - self.lags_m):t + 1]
                fc = model.predict(rv_last, **{k: v.iloc[max(0, t - self.lags_m):t + 1] for k, v in kwargs.items()})
                if len(fc) > 0:
                    forecasts.append(fc.iloc[-1])
                    realized.append(rv.iloc[t + self.horizon - 1])
                    idx.append(rv.index[t])
            except Exception:
                continue

        result = pd.DataFrame({
            'forecast': forecasts,
            'realized': realized
        }, index=idx)

        # Compute loss functions
        result['loss_mse'] = (result['realized'] - result['forecast']) ** 2
        result['loss_qlike'] = (result['realized'] / result['forecast'] -
                                np.log(result['realized'] / result['forecast']) - 1)
        result['loss_logmse'] = (np.log(result['realized']) - np.log(result['forecast'])) ** 2
        return result

    def summary(self) -> pd.DataFrame:
        """Print model summary."""
        if self.beta_ is None:
            raise RuntimeError("Model not fitted")
        summary_df = pd.DataFrame({
            'coef': self.beta_,
            't-stat': self.tvalues_,
            'p-value': self.pvalues_
        })
        print(f"\nHAR-RV Variant: {self.variant.upper()}, Horizon: {self.horizon}")
        print(f"R2: {self.r2_:.4f}, Adj. R2: {self.r2_adj_:.4f}, N: {self.n_obs_}")
        print("-" * 50)
        print(summary_df.to_string())
        return summary_df


# HAR Comparison and Model Selection

def compare_har_variants(rv: pd.Series,
                         bv: Optional[pd.Series] = None,
                         returns: Optional[pd.Series] = None,
                         train_size: int = 500) -> pd.DataFrame:
    """
    Compare all HAR variants on OOS QLIKE and MSE (expanding window).
    """
    results = {}

    # Basic HAR
    har = HARModel('har')
    oos = har.rolling_forecast(rv, train_size=train_size)
    results['HAR'] = {
        'QLIKE': oos['loss_qlike'].mean(),
        'MSE': oos['loss_mse'].mean(),
        'R2': oos.assign(res=lambda d: d['realized'] - d['forecast']).pipe(lambda d: 1 - d['res'].var() / d['realized'].var())
    }

    # Log-HAR
    lhar_m = HARModel('log_har')
    oos_l = lhar_m.rolling_forecast(rv, train_size=train_size)
    results['Log-HAR'] = {
        'QLIKE': oos_l['loss_qlike'].mean(),
        'MSE': oos_l['loss_mse'].mean()
    }

    # HAR-J
    if bv is not None:
        harj = HARModel('har_j')
        oos_j = harj.rolling_forecast(rv, train_size=train_size, bv=bv)
        results['HAR-J'] = {
            'QLIKE': oos_j['loss_qlike'].mean(),
            'MSE': oos_j['loss_mse'].mean()
        }

    # LHAR
    if returns is not None:
        lhar = HARModel('lhar')
        oos_lh = lhar.rolling_forecast(rv, train_size=train_size, returns=returns)
        results['LHAR'] = {
            'QLIKE': oos_lh['loss_qlike'].mean(),
            'MSE': oos_lh['loss_mse'].mean()
        }

    return pd.DataFrame(results).T


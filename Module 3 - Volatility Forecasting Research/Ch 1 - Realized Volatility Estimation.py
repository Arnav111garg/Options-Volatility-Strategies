import numpy as np
import pandas as pd
from scipy.stats import norm
from typing import Optional, Tuple, Dict
import warnings

def compute_rv(prices: pd.Series,
               freq_minutes: int = 5,
               annualize: bool = True,
               n_trading_minutes: int = 390) -> pd.Series:
    """
    Compute standard realized variance from intraday prices.

    Parameters
    ----------
    prices : pd.Series with DatetimeIndex (tick or resampled data)
    freq_minutes : Sampling frequency in minutes
    annualize : If True, return annualized vol (not variance)

    Returns
    -------
    pd.Series of daily RV (annualized vol if annualize = True)
    """
    # Resample to desired frequency
    prices_resampled = prices.resample(f'{freq_minutes}min').last().dropna()

    # Compute log returns
    log_ret = np.log(prices_resampled / prices_resampled.shift(1)).dropna()

    # Sum of squared returns per day
    rv = log_ret.groupby(log_ret.index.date).apply(lambda x: (x ** 2).sum())
    rv.index = pd.to_datetime(rv.index)

    # Annualize: multiply by trading periods per year
    periods_per_year = 252 * (n_trading_minutes / freq_minutes)
    if annualize:
        return np.sqrt(rv * periods_per_year)  # annualized vol
    return rv * periods_per_year  # annualized variance


def compute_bipower_variation(prices: pd.Series,
                              freq_minutes: int = 5) -> pd.Series:
    """
    Jump-robust Bi-Power Variation (Barndorff-Nielsen & Shephard, 2004).
    """
    mu1 = np.sqrt(2 / np.pi)  # E[|Z|] for Z ~ N(0 ,1)

    prices_resampled = prices.resample(f'{freq_minutes}min').last().dropna()
    log_ret = np.log(prices_resampled / prices_resampled.shift(1)).dropna()

    def bpv_daily(rets):
        abs_rets = np.abs(rets.values)
        bpv = (mu1 ** -2) * np.sum(abs_rets[1:] * abs_rets[:-1])
        return bpv

    bv = log_ret.groupby(log_ret.index.date).apply(bpv_daily)
    bv.index = pd.to_datetime(bv.index)
    n_trading_minutes = 390
    n_obs = n_trading_minutes // freq_minutes
    return bv * (252 * n_obs / (n_obs - 1))  # bias correction


def compute_jump_component(rv: pd.Series, bv: pd.Series,
                           alpha: float = 0.01) -> Dict[str, pd.Series]:
    """
    Decompose RV into continuous and jump components.
    Returns dict with 'jump_variation', 'continuous_variation',
    'jump_indicator', 'jump_test_stat'.
    """
    # Jump test statistic (Barndorff-Nielsen & Shephard, 2004)
    mu1 = np.sqrt(2 / np.pi)
    # Tri-power quarticity for standardisation (approximate with BV^2)
    denom = np.sqrt(np.maximum((np.pi / 2) ** 2 + np.pi - 5, 1e-10))
    z_stat = (rv - bv) / (bv * denom * np.sqrt(1 / (252 * 78)))

    jump_indicator = z_stat > norm.ppf(1 - alpha)
    jump_variation = np.maximum(rv - bv, 0) * jump_indicator
    continuous_variation = rv - jump_variation

    return {
        'jump_variation': jump_variation,
        'continuous_variation': continuous_variation,
        'jump_indicator': jump_indicator.astype(int),
        'jump_test_stat': z_stat
    }


def compute_realized_kernel(prices: pd.Series,
                            bandwidth: Optional[int] = None) -> pd.Series:
    """
    Realized Kernel estimator with Parzen kernel
    (Barndorff-Nielsen et al., 2008).
    Noise-robust estimator using autocovariances.
    """
    def parzen_kernel(x):
        x = np.abs(x)
        result = np.where(x <= 0.5, 1 - 6 * x ** 2 + 6 * x ** 3,
                          np.where(x <= 1.0, 2 * (1 - x) ** 3, 0.0))
        return result

    def rk_daily(rets):
        n = len(rets)
        if n < 5:
            return np.nan
        H = bandwidth or max(1, int(np.round(n ** (0.6))))

        # Autocovariance at lag h
        gamma = lambda h: np.sum(rets[h:] * rets[:n - h]) if h > 0 else np.sum(rets ** 2)

        rk_val = gamma(0)
        for h in range(1, H + 1):
            weight = parzen_kernel(h / (H + 1))
            g_h = gamma(h)
            rk_val += 2 * weight * g_h
        return max(rk_val, 0)  # ensure non-negative

    prices_resampled = prices.resample('1min').last().dropna()
    log_ret = np.log(prices_resampled / prices_resampled.shift(1)).dropna()

    rk = log_ret.groupby(log_ret.index.date).apply(rk_daily)
    rk.index = pd.to_datetime(rk.index)
    return np.sqrt(rk * 252)  # annualized vol


def compute_realized_higher_moments(prices: pd.Series,
                                    freq_minutes: int = 5) -> pd.DataFrame:
    """
    Realized variance, skewness, and kurtosis.
    """
    prices_resampled = prices.resample(f'{freq_minutes}min').last().dropna()
    log_ret = np.log(prices_resampled / prices_resampled.shift(1)).dropna()

    n_per_day = 390 // freq_minutes

    def moments_daily(rets):
        n = len(rets)
        rv = np.sum(rets ** 2)
        rs = np.sqrt(n) * np.sum(rets ** 3) / rv ** (3 / 2) if rv > 0 else np.nan
        rk = n * np.sum(rets ** 4) / rv ** 2 if rv > 0 else np.nan
        return pd.Series({'RV': rv * 252 * n_per_day,
                          'RSkew': rs, 'RKurt': rk})

    # Using .apply(moments_daily) can return a Series with MultiIndex on newer pandas,
    # so we unstack it if it forms a MultiIndex, or build a clean DataFrame.
    result = log_ret.groupby(log_ret.index.date).apply(moments_daily)
    if isinstance(result.index, pd.MultiIndex):
        result = result.unstack()
    result.index = pd.to_datetime(result.index)
    return result


# Loss Functions

def loss_mse(realized: np.ndarray, forecast: np.ndarray) -> np.ndarray:
    """Mean Squared Error: L(h, sigma^2) = (sigma^2 - h)^2"""
    return (realized - forecast) ** 2


def loss_qlike(realized: np.ndarray, forecast: np.ndarray) -> np.ndarray:
    """
    QLIKE loss: L(h, sigma^2) = sigma^2/h - log(sigma^2/h) - 1
    Robust to noise in realized variance proxy (Patton, 2011).
    """
    ratio = realized / np.maximum(forecast, 1e-10)
    return ratio - np.log(ratio) - 1


def loss_log_mse(realized: np.ndarray, forecast: np.ndarray) -> np.ndarray:
    """Log-scale MSE: L = (log(sigma^2) - log(h))^2"""
    return (np.log(np.maximum(realized, 1e-10)) -
            np.log(np.maximum(forecast, 1e-10))) ** 2



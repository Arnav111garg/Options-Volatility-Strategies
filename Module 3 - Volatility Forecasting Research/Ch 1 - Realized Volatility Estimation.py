    # Generate synthetic intraday prices (GBM)
    np.random.seed(12)
    n_days = 252
    n_intraday = 390  # 1-min bars for 6.5 hour session

    dt = 1 / (252 * 390)
    sigma_true = 0.20  # 20% annual vol

    timestamps = pd.date_range('2023-01-02 09:30', periods=n_days * n_intraday, freq='1min')
    # Filter to trading hours only
    mask = (timestamps.time >= pd.Timestamp('09:30').time()) & \
           (timestamps.time <= pd.Timestamp('16:00').time())
    timestamps = timestamps[mask]
    log_returns = np.random.normal(0, sigma_true * np.sqrt(dt), len(timestamps))
    prices = pd.Series(100 * np.exp(np.cumsum(log_returns)), index=timestamps)

    # Compute RV at different frequencies
    rv_1min = compute_rv(prices, freq_minutes=1)
    rv_5min = compute_rv(prices, freq_minutes=5)
    bv_5min = compute_bipower_variation(prices, freq_minutes=5)

    jumps = compute_jump_component(rv_5min, bv_5min)
    moments = compute_realized_higher_moments(prices)

    print("=== RV Estimation Results ===")
    print(f"Mean 1-min RV (annualized vol): {rv_1min.mean():.4f}")
    print(f"Mean 5-min RV (annualized vol): {rv_5min.mean():.4f}")
    print(f"True vol: {sigma_true:.4f}")
    print(f"Jump days detected: {jumps['jump_indicator'].sum()}")
    print(f"Mean Realized Skewness: {moments['RSkew'].mean():.4f}")
    print(f"Mean Realized Kurtosis: {moments['RKurt'].mean():.4f}")


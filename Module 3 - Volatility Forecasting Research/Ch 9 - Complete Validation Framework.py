import numpy as np
import pandas as pd
from scipy import stats
from typing import Dict, Tuple, Optional, List
import warnings

class VolatilityModelValidator:
    """
    Complete validation framework for volatility forecasting models.

    Tests: Mincer-Zarnowitz, Diebold-Mariano, Clark-West,
    MCS (simplified), Kupiec test, economic evaluation.
    """

    # Mincer-Zarnowitz Test

    @staticmethod
    def mincer_zarnowitz(realized: np.ndarray,
                         forecast: np.ndarray,
                         hac_lags: int = 5) -> Dict:
        """
        MZ regression test: realized = a + b * forecast + u.
        Tests H0: a=0, b=1 (unbiased, efficient forecast).
        """
        T = len(realized)
        X = np.column_stack([np.ones(T), forecast])

        # OLS
        beta, res, _, _ = np.linalg.lstsq(X, realized, rcond=None)
        a_hat, b_hat = beta

        resids = realized - X @ beta

        # HAC variance (Newey-West)
        def newey_west_cov(X, u, lags):
            T, k = X.shape
            S = X.T @ np.diag(u ** 2) @ X / T  # White
            for j in range(1, lags + 1):
                w = 1 - j / (lags + 1)
                Sj = X[j:].T @ np.diag(u[j:] * u[:T - j]) @ X[:T - j] / T
                S += w * (Sj + Sj.T)
            return np.linalg.inv(X.T @ X / T) @ S @ np.linalg.inv(X.T @ X / T) / T

        V = newey_west_cov(X, resids, hac_lags)
        se = np.sqrt(np.diag(V))

        # t-statistics
        t_a = a_hat / se[0]
        t_b = (b_hat - 1.0) / se[1]

        # Joint F-test: a=0, b=1
        R = np.array([[1, 0], [0, 1]])
        r = np.array([0, 1])
        beta_test = beta - r
        F_stat = (beta_test @ np.linalg.inv(V) @ beta_test) / 2
        F_pval = 1 - stats.f.cdf(F_stat, 2, T - 2)

        # R^2
        r2 = 1 - np.var(resids) / np.var(realized)

        return {
            'alpha': a_hat, 'beta': b_hat,
            'se_alpha': se[0], 'se_beta': se[1],
            't_alpha': t_a, 't_beta': t_b,
            'p_alpha': 2 * (1 - stats.norm.cdf(abs(t_a))),
            'p_color': 2 * (1 - stats.norm.cdf(abs(t_b))),
            'F_joint': F_stat, 'p_joint': F_pval,
            'R2': r2, 'N': T,
            'unbiased': F_pval > 0.05
        }

    # Diebold-Mariano Test

    @staticmethod
    def diebold_mariano(realized: np.ndarray,
                        forecast1: np.ndarray,
                        forecast2: np.ndarray,
                        loss: str = 'qlike',
                        h: int = 1,
                        alternative: str = 'two-sided') -> Dict:
        """
        DM test: H0 equal predictive ability of forecast1 vs forecast2.
        Negative DM => forecast1 is better (lower loss).

        Parameters
        ----------
        h : forecast horizon (determines MA order)
        alternative: 'two-sided', 'less' (f1 < f2), 'greater' (f1 > f2)
        """
        eps = 1e-10

        if loss == 'mse':
            L1 = (realized - forecast1) ** 2
            L2 = (realized - forecast2) ** 2
        elif loss == 'qlike':
            L1 = realized / np.maximum(forecast1, eps) - np.log(realized / np.maximum(forecast1, eps)) - 1
            L2 = realized / np.maximum(forecast2, eps) - np.log(realized / np.maximum(forecast2, eps)) - 1
        elif loss == 'log_mse':
            L1 = (np.log(realized + eps) - np.log(np.maximum(forecast1, eps))) ** 2
            L2 = (np.log(realized + eps) - np.log(np.maximum(forecast2, eps))) ** 2
        else:
            raise ValueError(f"Unknown loss: {loss}")

        d = L1 - L2
        T = len(d)
        d_bar = np.mean(d)

        # HAC variance with h-1 lags (Newey-West)
        gamma_0 = np.var(d)
        gamma = sum((1 - j / h) * np.cov(d[j:], d[:T - j])[0, 1] for j in range(1, h)) if h > 1 else 0

        V_d = (gamma_0 + 2 * gamma) / T

        # Harvey-Leybourne-Newbold correction
        hlns_factor = np.sqrt((T + 1 - 2 * h + h * (h - 1) / T) / T)

        DM = d_bar / np.sqrt(max(V_d, 1e-20))
        DM_corrected = DM * hlns_factor

        # p-value
        if alternative == 'two-sided':
            p_val = 2 * (1 - stats.norm.cdf(abs(DM_corrected)))
        elif alternative == 'less':
            p_val = stats.norm.cdf(DM_corrected)
        else:
            p_val = 1 - stats.norm.cdf(DM_corrected)

        return {
            'DM_stat': DM_corrected, 'p_value': p_val,
            'mean_loss1': np.mean(L1), 'mean_loss2': np.mean(L2),
            'loss_diff': d_bar, 'N': T,
            'f1_better': DM_corrected < 0 and p_val < 0.05,
            'significant': p_val < 0.05
        }

    # Clark-West Test

    @staticmethod
    def clark_west(realized: np.ndarray,
                   forecast_restricted: np.ndarray,
                   forecast_unrestricted: np.ndarray) -> Dict:
        """
        Clark-West test for nested model comparison.
        H0: restricted model is no worse than unrestricted.
        """
        f1, f2 = forecast_restricted, forecast_unrestricted
        y = realized

        # CW adjustment
        f_hat_sq = (f1 - f2) ** 2
        d = (y - f1) ** 2 - (y - f2) ** 2 + f_hat_sq

        T = len(d)
        d_bar = np.mean(d)
        se_d = np.std(d) / np.sqrt(T)

        t_stat = d_bar / (se_d + 1e-10)
        p_val = 1 - stats.t.cdf(t_stat, df=T - 1)  # one-sided

        return {
            'CW_stat': t_stat, 'p_value': p_val,
            'mean_CW': d_bar,
            'unrestricted_better': t_stat > 0 and p_val < 0.05
        }

    # Complete Model Evaluation

    def evaluate_all_models(self, forecasts: pd.DataFrame,
                            realized: pd.Series,
                            benchmark_col: str,
                            loss: str = 'qlike') -> pd.DataFrame:
        """
        Run complete evaluation: MZ, DM vs benchmark, losses.

        Parameters
        ----------
        forecasts: DataFrame of model forecasts
        realized: Series of realized values
        benchmark_col: Column name of benchmark model
        """
        # Align all series
        all_data = pd.concat([forecasts, realized.rename('realized')], axis=1).dropna()
        rv = all_data['realized'].values
        results = {}

        for col in forecasts.columns:
            fc = all_data[col].values

            # MZ test
            mz = self.mincer_zarnowitz(rv, fc)

            # DM vs benchmark
            if col != benchmark_col and benchmark_col in all_data:
                dm = self.diebold_mariano(rv, fc, all_data[benchmark_col].values, loss=loss)
                cw = self.clark_west(rv, all_data[benchmark_col].values, fc)
            else:
                dm = {'DM_stat': np.nan, 'p_value': np.nan, 'f1_better': False}
                cw = {'CW_stat': np.nan, 'p_value': np.nan}

            # Loss metrics
            eps = 1e-10
            qlike = np.mean(rv / np.maximum(fc, eps) - np.log(rv / np.maximum(fc, eps)) - 1)
            mse = np.mean((rv - fc) ** 2)

            results[col] = {
                'QLIKE': qlike, 'MSE': mse,
                'MZ_alpha': mz['alpha'], 'MZ_beta': mz['beta'],
                'MZ_R2': mz['R2'], 'MZ_unbiased': mz['unbiased'],
                'DM_stat': dm['DM_stat'], 'DM_pval': dm['p_value'],
                'Beats_benchmark': dm.get('f1_better', False),
                'CW_stat': cw['CW_stat'], 'CW_pval': cw['p_value']
            }

        df = pd.DataFrame(results).T
        df['QLIKE_rank'] = df['QLIKE'].rank()
        return df.sort_values('QLIKE')

    # Walk-Forward Validation

    @staticmethod
    def walk_forward_evaluate(model_fit_fn: Callable,
                              model_predict_fn: Callable,
                              rv: pd.Series,
                              features: pd.DataFrame,
                              train_size: int = 252,
                              step: int = 21) -> pd.DataFrame:
        """
        Proper walk-forward OOS validation.

        Parameters
        ----------
        model_fit_fn : callable (rv_train, features_train) -> model
        model_predict_fn : callable (model, features_test) -> forecast
        step : refit frequency (in days)
        """
        results = []
        T = len(rv)

        for t_start in range(train_size, T - 1, step):
            t_end = min(t_start + step, T - 1)

            # Training data
            rv_train = rv.iloc[:t_start]
            feat_train = features.iloc[:t_start]

            # Test data
            feat_test = features.iloc[t_start:t_end]
            rv_test = rv.iloc[t_start:t_end]

            try:
                model = model_fit_fn(rv_train, feat_train)
                forecasts = model_predict_fn(model, feat_test)

                for i, (fc, actual) in enumerate(zip(forecasts, rv_test)):
                    results.append({
                        'date': rv.index[t_start + i],
                        'forecast': fc,
                        'realized': actual,
                        'train_size': t_start
                    })
            except Exception as e:
                warnings.warn(f"Walk-forward step failed at t={t_start}: {e}")

        df = pd.DataFrame(results).set_index('date') if results else pd.DataFrame()
        return df


import numpy as np
import pandas as pd
from typing import Dict, List, Optional

class VolatilityFeatureEngineer:
    """
    Comprehensive volatility feature engineering pipeline.
    Generates price-based, range-based, regime, and return features.
    """

    def __init__(self, rv_lags=(1, 2, 5, 10, 22, 65, 252),
                 rv_rolling_stats=True,
                 range_estimators=True):
        self.rv_lags = rv_lags
        self.rv_rolling_stats = rv_rolling_stats
        self.range_estimators = range_estimators

    # Range-Based Estimators

    @staticmethod
    def parkinson_vol(high: pd.Series, low: pd.Series) -> pd.Series:
        """Parkinson (1980) range-based vol estimator."""
        return np.sqrt(1 / (4 * np.log(2)) * (np.log(high / low)) ** 2)

    @staticmethod
    def garman_klass_vol(open_: pd.Series, high: pd.Series,
                         low: pd.Series, close: pd.Series) -> pd.Series:
        """Garman-Klass (1980) OHLC vol estimator."""
        h = np.log(high / open_)
        l = np.log(low / open_)
        c = np.log(close / open_)
        gk_var = 0.511 * (h - l) ** 2 - 0.019 * (c * (h + l) - 2 * h * l) - 0.383 * c ** 2
        return np.sqrt(np.abs(gk_var) * 252)  # annualized

    @staticmethod
    def rogers_satchell_vol(open_: pd.Series, high: pd.Series,
                            low: pd.Series, close: pd.Series) -> pd.Series:
        """Rogers-Satchell estimator (no drift bias)."""
        h, l = np.log(high), np.log(low)
        o, c = np.log(open_), np.log(close)
        rs_var = (h - c) * (h - o) + (l - c) * (l - o)
        return np.sqrt(np.maximum(rs_var, 0) * 252)

    @staticmethod
    def yang_zhang_vol(open_: pd.Series, high: pd.Series,
                       low: pd.Series, close: pd.Series,
                       window: int = 22) -> pd.Series:
        """Yang-Zhang (2000) optimal OHLC estimator."""
        n = window
        k = 0.34 / (1.34 + (n + 1) / (n - 1))

        # Overnight variance
        sigma_o2 = np.log(open_ / close.shift(1)).rolling(n).var()
        # Close-to-open variance
        sigma_c2 = np.log(close / open_).rolling(n).var()
        # Rogers-Satchell variance
        h = np.log(high / open_)
        l = np.log(low / open_)
        c = np.log(close / open_)
        rs = ((h - c) * h + (l - c) * l).rolling(n).mean()

        yz_var = sigma_o2 + k * sigma_c2 + (1 - k) * rs
        return np.sqrt(np.maximum(yz_var, 0) * 252)

    # HAR Components

    def build_har_components(self, rv: pd.Series) -> pd.DataFrame:
        """Build all HAR-style lagged average features."""
        features = pd.DataFrame(index=rv.index)

        for lag in self.rv_lags:
            features[f'RV_lag{lag}'] = rv.shift(1).rolling(lag).mean()

        # Min/Max over short windows
        for w in [5, 10, 22]:
            features[f'RV_max{w}'] = rv.shift(1).rolling(w).max()
            features[f'RV_min{w}'] = rv.shift(1).rolling(w).min()
            features[f'RV_std{w}'] = rv.shift(1).rolling(w).std()

        return features

    # Regime Features

    def build_regime_features(self, rv: pd.Series,
                              windows=(5, 22, 65)) -> pd.DataFrame:
        """Build volatility regime indicators."""
        features = pd.DataFrame(index=rv.index)

        # Vol ratios (term structure of vol)
        rv1 = rv.shift(1)
        for w in windows:
            rv_avg = rv1.rolling(w).mean()
            features[f'vol_ratio_{w}d'] = rv1 / rv_avg
            features[f'vol_trend_{w}d'] = (rv1 - rv_avg) / rv_avg.clip(lower=1e-10)

        # Z-score (rolling standardization)
        for w in [22, 65, 252]:
            mu = rv1.rolling(w).mean()
            sigma = rv1.rolling(w).std()
            features[f'rv_zscore_{w}d'] = (rv1 - mu) / sigma.clip(lower=1e-10)

        # Empirical percentile
        for w in [252]:
            features[f'rv_pctile_{w}d'] = rv1.rolling(w).apply(
                lambda x: (x < x[-1]).mean(), raw=True
            )

        return features

    # Return Features

    def build_return_features(self, returns: pd.Series,
                              rv: Optional[pd.Series] = None) -> pd.DataFrame:
        """Build return-based predictive features."""
        features = pd.DataFrame(index=returns.index)

        r = returns.shift(1)

        # Signed components
        features['r_neg'] = np.minimum(r, 0)
        features['r_pos'] = np.maximum(r, 0)
        features['r_sq'] = r ** 2
        features['r_abs'] = r.abs()

        # Leverage momentum (cumulative negative returns)
        for w in [5, 22]:
            features[f'r_sum_{w}d'] = r.rolling(w).sum()
            features[f'r_neg_sum_{w}d'] = np.minimum(r, 0).rolling(w).sum()

        # Return-to-vol (if RV available)
        if rv is not None:
            sigma = np.sqrt(rv.shift(1))
            features['r_standardized'] = r / sigma.clip(lower=1e-10)
            features['r_sq_over_rv'] = r ** 2 / rv.shift(1).clip(lower=1e-10)

        return features

    # Master Feature Builder

    def build_all_features(self, rv: pd.Series,
                           ohlc: Optional[pd.DataFrame] = None,
                           returns: Optional[pd.Series] = None) -> pd.DataFrame:
        """
        Build complete feature set for volatility forecasting.

        Parameters
        ----------
        rv : pd.Series of daily realized variance (annualized vol)
        ohlc : pd.DataFrame with columns [open, high, low, close]
        returns : pd.Series of daily log returns

        Returns
        -------
        pd.DataFrame of features (aligned with rv index)
        """
        all_features = []

        # HAR components
        all_features.append(self.build_har_components(rv))

        # Regime features
        all_features.append(self.build_regime_features(rv))

        # Return features
        if returns is not None:
            all_features.append(self.build_return_features(returns, rv))

        # Range-based estimators (OHLC)
        if ohlc is not None:
            o, h, l, c = (ohlc['open'], ohlc['high'],
                          ohlc['low'], ohlc['close'])
            rng = pd.DataFrame(index=rv.index)
            rng['parkinson'] = self.parkinson_vol(h, l).shift(1)
            rng['garman_klass'] = self.garman_klass_vol(o, h, l, c).shift(1)
            rng['yang_zhang'] = self.yang_zhang_vol(o, h, l, c).shift(1)
            all_features.append(rng)

        return pd.concat(all_features, axis=1)



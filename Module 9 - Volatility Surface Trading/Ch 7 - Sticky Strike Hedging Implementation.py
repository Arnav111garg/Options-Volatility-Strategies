import numpy as np
from scipy.stats import norm
from scipy.interpolate import RegularGridInterpolator
from typing import Callable, Dict

class StickyStrikeHedger:
    """
    Delta hedging under the sticky-strike assumption.
    Implements delta, gamma, and vanna under sticky-strike vs smile-adjusted.
    """
    def __init__(self, S: float, r: float, q: float,
                 iv_surface: Callable[[float, float], float]):
        """
        iv_surface: callable (K, T) -> implied_vol
        """
        self.S = S
        self.r = r
        self.q = q
        self.sigma_iv = iv_surface

    def bs_d1d2(self, S, K, T, sigma):
        F = S * np.exp((self.r - self.q) * T)
        d1 = (np.log(F / K) + 0.5 * sigma**2 * T) / (sigma * np.sqrt(T))
        d2 = d1 - sigma * np.sqrt(T)
        return d1, d2

    def bs_delta(self, S, K, T, sigma, option_type='call'):
        d1, d2 = self.bs_d1d2(S, K, T, sigma)
        if option_type == 'call':
            return np.exp(-self.q * T) * norm.cdf(d1)
        else:
            return np.exp(-self.q * T) * (norm.cdf(d1) - 1)

    def bs_vega(self, S, K, T, sigma):
        d1, d2 = self.bs_d1d2(S, K, T, sigma)
        return S * np.exp(-self.q * T) * norm.pdf(d1) * np.sqrt(T)

    def smile_delta_sticky_strike(self, K: float, T: float,
                                  option_type: str = 'call') -> float:
        """
        Delta under sticky-strike assumption.
        = BS delta (smile correction = 0).
        """
        sigma = self.sigma_iv(K, T)
        return self.bs_delta(self.S, K, T, sigma, option_type)

    def smile_delta_smile_adjusted(self, K: float, T: float,
                                   option_type: str = 'call',
                                   h: float = 0.01) -> float:
        """
        Smile-adjusted delta: accounts for how smile moves with spot.
        delta_adj = dV/dS = delta_BS + vega * d(sigma_IV)/dS
        Computes d(sigma_IV)/dS numerically.
        """
        sigma_base = self.sigma_iv(K, T)
        delta_bs = self.bs_delta(self.S, K, T, sigma_base, option_type)
        vega = self.bs_vega(self.S, K, T, sigma_base)

        # Numerical d(sigma_IV)/dS: sticky-strike => 0, smile-adj => nonzero
        dS = self.S * h
        sigma_up = self.sigma_iv(K * self.S / (self.S + dS), T)  # delta-adjusted
        sigma_dn = self.sigma_iv(K * self.S / (self.S - dS), T)
        d_sigma_dS = (sigma_up - sigma_dn) / (2 * dS)

        return delta_bs + vega * d_sigma_dS

    def delta_comparison(self, K: float, T: float,
                         option_type: str = 'call') -> Dict:
        """Compare delta across different hedging assumptions."""
        sigma = self.sigma_iv(K, T)

        delta_bs = self.bs_delta(self.S, K, T, sigma, option_type)
        delta_ss = self.smile_delta_sticky_strike(K, T, option_type)
        delta_sa = self.smile_delta_smile_adjusted(K, T, option_type)

        vega = self.bs_vega(self.S, K, T, sigma)

        # Skew slope (d_sigma/dK * 1)
        h = K * 0.001
        skew_slope = (self.sigma_iv(K + h, T) - self.sigma_iv(K - h, T)) / (2 * h)

        return {
            'K': K, 'T': T, 'sigma': sigma,
            'delta_BS': delta_bs,
            'delta_StickyStrike': delta_ss,
            'delta_SmileAdjusted': delta_sa,
            'delta_difference': delta_sa - delta_ss,
            'vega': vega,
            'skew_slope': skew_slope,
            'smile_correction': vega * skew_slope / self.S,  # approx
        }

    def pnl_attribution_sticky_strike(self, dS: float, dT: float,
                                      K: float, T: float,
                                      option_type: str = 'call') -> Dict:
        """
        P&L attribution for a sticky-strike delta-hedged position.
        dPnL = -Gamma/2 * dS^2 - Theta * dT + Vega * d(sigma)
        Under sticky-strike: d(sigma) = 0 (no vol move)
        """
        sigma = self.sigma_iv(K, T)
        d1, d2 = self.bs_d1d2(self.S, K, T, sigma)

        gamma = np.exp(-self.q * T) * norm.pdf(d1) / (self.S * sigma * np.sqrt(T))
        vega = self.bs_vega(self.S, K, T, sigma)
        theta = -(self.S * np.exp(-self.q * T) * norm.pdf(d1) * sigma / (2 * np.sqrt(T))
                  + self.r * K * np.exp(-self.r * T) * norm.cdf(d2)
                  - self.q * self.S * np.exp(-self.q * T) * norm.cdf(d1)) / 365

        # Under sticky-strike: vol doesn't change with S
        d_sigma_sticky_strike = 0.0

        pnl_gamma = 0.5 * gamma * dS**2
        pnl_theta = theta * dT
        pnl_vega_sticky_strike = vega * d_sigma_sticky_strike

        return {
            'pnl_gamma': pnl_gamma,
            'pnl_theta': pnl_theta,
            'pnl_vega': pnl_vega_sticky_strike,
            'total_pnl': pnl_gamma + pnl_theta + pnl_vega_sticky_strike,
            'gamma': gamma,
            'theta_daily': theta,
            'vega': vega,
        }


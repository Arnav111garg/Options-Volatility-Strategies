    # Define a simple negatively-skewed IV surface (sticky-strike)
    def spx_iv_surface(K, T):
        """Simple SPX-like IV surface."""
        S_ref = 4000.0
        F = S_ref * np.exp(0.05 * T)
        moneyness = np.log(K / F) / (0.20 * np.sqrt(T))
        return 0.20 - 0.04 * moneyness + 0.005 * moneyness**2

    hedger = StickyStrikeHedger(S=4000, r=0.05, q=0.015, iv_surface=spx_iv_surface)

    # Compare deltas at different strikes

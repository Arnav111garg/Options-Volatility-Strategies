import numpy as np
import pandas as pd
from scipy.stats import norm
from scipy.interpolate import CubicSpline
from scipy.optimize import minimize
import matplotlib.pyplot as plt

class RelativeStrikeTrader:
    """
    Tools for relative strike analysis, smile decomposition,
    and butterfly spread optimization.
    """
    def __init__(self, S: float, T: float, r: float, q: float):
        self.S = S
        self.T = T
        self.r = r
        self.q = q
        self.F = S * np.exp((r - q) * T)

    def fit_svi(self, strikes: np.ndarray, iv_obs: np.ndarray) -> dict:
        """Fit SVI to observed IV slice, returns params and residuals."""
        y = np.log(strikes / self.F)
        w_obs = iv_obs**2 * self.T

        def svi_w(params):
            a, b, rho, m, sigma = params
            return a + b * (rho * (y - m) + np.sqrt((y - m)**2 + sigma**2))

        def obj(params):
            try:
                w = svi_w(params)
                if np.any(w < 0): return 1e10
                return np.sum((np.sqrt(w / self.T) - iv_obs) ** 2)
            except:
                return 1e10

        atm_var = np.interp(0, y, w_obs)
        x0 = [atm_var * 0.8, 0.15, -0.4, 0.02, 0.15]
        bounds = [(-1, 2), (1e-6, 5), (-0.999, 0.999), (-0.5, 0.5), (1e-4, 1)]
        result = minimize(obj, x0, method='L-BFGS-B', bounds=bounds)

        a, b, rho, m, sigma = result.x
        w_fit = svi_w(result.x)
        iv_fit = np.sqrt(np.maximum(w_fit, 0) / self.T)
        residuals = iv_obs - iv_fit

        return {
            'params': dict(zip(['a', 'b', 'rho', 'm', 'sigma'], result.x)),
            'iv_fit': iv_fit,
            'residuals': residuals,
            'rmse': np.sqrt(np.mean(residuals**2)) * 100,
        }

    def smile_pca_decomposition(self, historical_smiles: np.ndarray, current_smile: np.ndarray) -> dict:
        """
        PCA decomposition of smile moves.
        """
        smile_changes = np.diff(historical_smiles, axis=0)
        mean_change = smile_changes.mean(axis=0)
        centered = smile_changes - mean_change
        U, S_vals, Vt = np.linalg.svd(centered, full_matrices=False)
        var_explained = (S_vals**2) / (S_vals**2).sum()

        mean_smile = historical_smiles.mean(axis=0)
        deviation = current_smile - mean_smile
        pc_scores = deviation @ Vt.T

        reconstructed = mean_smile + pc_scores[:3] @ Vt[:3]
        residual_iv = current_smile - reconstructed

        return {
            'pc_loadings': Vt,
            'variance_explained': var_explained,
            'pc_scores': pc_scores,
            'reconstructed_smile': reconstructed,
            'residuals_from_pca': residual_iv,
            'mean_smile': mean_smile,
        }

    def find_optimal_butterfly(self, strikes: np.ndarray, iv_obs: np.ndarray, min_vega_neutral: float = 0.01) -> dict:
        """
        Find the optimal butterfly spread that maximizes expected P&L.
        """
        svi_result = self.fit_svi(strikes, iv_obs)
        iv_model = svi_result['iv_fit']
        residuals = svi_result['residuals']

        best_trade = None
        best_signal = 0.0

        for i in range(1, len(strikes) - 1):
            for j in range(i + 1, len(strikes)):
                for k in range(j + 1, len(strikes)):
                    K1, K2, K3 = strikes[i], strikes[j], strikes[k]
                    alpha = (K3 - K2) / (K3 - K1)
                    beta = 1 - alpha

                    v1 = self._vega(K1, iv_obs[i])
                    v2 = self._vega(K2, iv_obs[j])
                    v3 = self._vega(K3, iv_obs[k])

                    net_vega = alpha * v1 - v2 + beta * v3
                    if abs(net_vega) > min_vega_neutral:
                        continue

                    signal = -(alpha * residuals[i] - residuals[j] + beta * residuals[k])
                    if abs(signal) > abs(best_signal):
                        best_signal = signal
                        best_trade = {
                            'K1': K1, 'K2': K2, 'K3': K3,
                            'alpha': alpha, 'beta': beta,
                            'net_vega': net_vega,
                            'signal': signal,
                            'direction': 'buy' if signal > 0 else 'sell',
                            'residual_wing1': residuals[i],
                            'residual_body': residuals[j],
                            'residual_wing2': residuals[k],
                        }
        return best_trade if best_trade else {}

    def _vega(self, K: float, sigma: float) -> float:
        """Black-Scholes vega."""
        d1 = (np.log(self.F / K) + 0.5 * sigma**2 * self.T) / (sigma * np.sqrt(self.T))
        return self.S * np.exp(-self.q * self.T) * norm.pdf(d1) * np.sqrt(self.T)

    def butterfly_pnl_profile(self, K1: float, K2: float, K3: float, sigma1: float, sigma2: float, sigma3: float, vol_bump: float = 0.01) -> dict:
        """
        Compute P&L sensitivity of a symmetric butterfly.
        """
        def butterfly_price(s1, s2, s3):
            c1 = self._bs_call(K1, s1)
            c2 = self._bs_call(K2, s2)
            c3 = self._bs_call(K3, s3)
            w = (K3 - K2) / (K3 - K1)
            return w * c1 - c2 + (1 - w) * c3

        base_price = butterfly_price(sigma1, sigma2, sigma3)
        pnl_parallel = butterfly_price(sigma1 + vol_bump, sigma2 + vol_bump, sigma3 + vol_bump) - base_price
        pnl_curvature = butterfly_price(sigma1 + vol_bump, sigma2, sigma3 + vol_bump) - base_price
        pnl_skew = butterfly_price(sigma1 + vol_bump, sigma2, sigma3 - vol_bump) - base_price

        return {
            'base_price': base_price,
            'vega_sensitivity': pnl_parallel / vol_bump,
            'volga_sensitivity': pnl_curvature / vol_bump,
            'vanna_sensitivity': pnl_skew / vol_bump,
        }

    def _bs_call(self, K, sigma):
        """Internal BS call pricer."""
        if sigma <= 0: return max(self.F * np.exp(-self.r * self.T) - K * np.exp(-self.r * self.T), 0)
        d1 = (np.log(self.F / K) + 0.5 * sigma**2 * self.T) / (sigma * np.sqrt(self.T))
        d2 = d1 - sigma * np.sqrt(self.T)
        return (self.F * norm.cdf(d1) - K * norm.cdf(d2)) * np.exp(-self.r * self.T)


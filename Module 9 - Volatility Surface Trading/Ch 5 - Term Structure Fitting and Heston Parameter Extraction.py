import numpy as np
from scipy.optimize import minimize, differential_evolution
from scipy.stats import norm
from typing import Dict, List
import warnings
warnings.filterwarnings('ignore')

class VolTermStructureTrader:
    """
    Volatility term structure analysis, Heston fitting,
    and calendar / variance swap trading.
    """
    def __init__(self, S: float, r: float, q: float):
        self.S = S
        self.r = r
        self.q = q

    def heston_atm_vol(self, T: float, kappa: float, theta: float,
                       xi: float, rho: float, v0: float) -> float:
        """
        Approximate ATM implied vol under Heston model.
        Uses the Gatheral (2006) approximation for ATM.
        """
        # Term structure of variance
        if kappa * T > 1e-8:
            E_var = theta + (v0 - theta) * (1 - np.exp(-kappa * T)) / (kappa * T)
        else:
            E_var = v0

        # Vol-of-vol correction (higher order)
        if kappa * T > 1e-8:
            g = (1 - np.exp(-kappa * T)) / (kappa * T)
        else:
            g = 1 - kappa * T / 2

        # Skew correction
        skew_corr = xi * rho / (2 * kappa) * (1 - g)

        return np.sqrt(E_var) + skew_corr * np.sqrt(E_var)

    def fit_heston_term_structure(self, expiries: np.ndarray,
                                  iv_atm: np.ndarray) -> Dict:
        """
        Fit Heston parameters to observed ATM term structure.
        """
        def objective(params):
            kappa, theta, xi, rho, v0 = params
            # Constraints
            if kappa <= 0 or theta <= 0 or xi <= 0 or v0 <= 0:
                return 1e10
            if abs(rho) >= 1:
                return 1e10
            if 2 * kappa * theta < xi**2:
                return 1e8  # Feller condition

            iv_model = np.array([
                self.heston_atm_vol(T, kappa, theta, xi, rho, v0)
                for T in expiries
            ])
            return np.sum((iv_model - iv_atm) ** 2)

        # Initial guess from term structure shape
        iv0 = iv_atm[0]
        iv_long = iv_atm[-1]
        v0_init = iv0**2
        theta_init = iv_long**2

        bounds = [(0.01, 20), (0.01**2, 1.0), (0.01, 5), (-0.999, 0.0), (0.01**2, 1.0)]
        x0 = [2.0, theta_init, 0.5, -0.7, v0_init]

        result = minimize(objective, x0, method='L-BFGS-B', bounds=bounds)
        kappa, theta, xi, rho, v0 = result.x

        # Fitted term structure
        iv_fit = np.array([
            self.heston_atm_vol(T, kappa, theta, xi, rho, v0)
            for T in expiries
        ])

        return {
            'kappa': kappa,  # Mean reversion speed
            'theta': theta,  # Long-run variance
            'xi': xi,        # Vol of vol
            'rho': rho,      # Spot-vol correlation
            'v0': v0,        # Current variance
            'long_run_vol': np.sqrt(theta),
            'half_life': np.log(2) / kappa,
            'iv_fit': iv_fit,
            'rmse': np.sqrt(np.mean((iv_fit - iv_atm) ** 2)) * 100,
        }

    def variance_swap_fair_value(self, T: float,
                                 strikes: np.ndarray,
                                 iv_slice: np.ndarray) -> float:
        """
        Model-free variance swap strike using the replication formula.
        K_var = (2/T) * [sum_i w_i * C(K_i) / K_i^2 * dK]
        This is the Demeterfi-Derman-Kamal-Zou (1999) formula.
        """
        F = self.S * np.exp((self.r - self.q) * T)

        # Compute call and put prices
        call_prices = np.array([
            self._bs_call(K, T, iv) for K, iv in zip(strikes, iv_slice)
        ])
        put_prices = call_prices + np.array([
            K * np.exp(-self.r * T) - F * np.exp(-self.r * T) for K in strikes
        ])

        # Replication integral: (2/T) * [sum over OTM options of price/K^2 * dK]
        dK = np.gradient(strikes)

        # OTM: use puts for K < F, calls for K > F
        weights = np.where(strikes <= F, put_prices, call_prices)

        K_var = (2 / T) * np.sum(weights / strikes**2 * dK) * np.exp(self.r * T)

        return np.sqrt(K_var)  # Return as vol (not variance)

    def term_structure_carry(self, expiries: np.ndarray,
                             iv_atm: np.ndarray, dt: float = 1/252) -> List[Dict]:
        """
        Compute the carry (expected P&L) of calendar positions along the term structure.
        Carry = Forward Vol - Current Vol (assuming vol mean-reverts)
        """
        carries = []

        for i in range(len(expiries) - 1):
            T1, T2 = expiries[i], expiries[i+1]
            sigma1, sigma2 = iv_atm[i], iv_atm[i+1]

            # Forward vol
            w1 = sigma1**2 * T1
            w2 = sigma2**2 * T2
            fwd_var = max(w2 - w1, 0) / (T2 - T1)
            fwd_vol = np.sqrt(fwd_var)

            # Calendar carry: if term structure is in contango,
            # the rolling short front-month calendar earns carry
            carry = sigma2 - sigma1  # Vol difference

            carries.append({
                'period': f'T={T1:.2f}Y to T={T2:.2f}Y',
                'sigma_T1': sigma1,
                'sigma_T2': sigma2,
                'fwd_vol': fwd_vol,
                'term_structure_slope': carry * 100,  # in vol points
                'fwd_vs_spot_T2': (fwd_vol - sigma2) * 100,
            })

        return carries

    def _bs_call(self, K, T, sigma):
        F = self.S * np.exp((self.r - self.q) * T)
        d1 = (np.log(F / K) + 0.5 * sigma**2 * T) / (sigma * np.sqrt(T))
        d2 = d1 - sigma * np.sqrt(T)
        return np.exp(-self.r * T) * (F * norm.cdf(d1) - K * norm.cdf(d2))

    def implied_heston_mean_reversion(self, iv_short: float, iv_long: float,
                                      T_short: float, T_long: float) -> Dict:
        """
        Back out implied kappa and theta from just two points on term structure.
        Useful for quick regime analysis.
        """
        theta = iv_long**2
        v0 = iv_short**2

        def residual(kappa):
            if kappa < 1e-6:
                var_pred = v0
            else:
                g = (1 - np.exp(-kappa * T_short)) / (kappa * T_short)
                var_pred = theta + (v0 - theta) * g
            return var_pred - iv_short**2

        from scipy.optimize import brentq
        try:
            kappa_implied = brentq(residual, 0.01, 50, xtol=1e-6)
        except:
            kappa_implied = np.nan

        return {
            'implied_kappa': kappa_implied,
            'half_life_months': np.log(2) / kappa_implied * 12 if not np.isnan(kappa_implied) else np.nan,
            'long_run_vol': iv_long * 100,
            'current_vol': iv_short * 100,
            'vol_expected_direction': 'UP' if iv_short < iv_long else 'DOWN',
        }

# ---- Term Structure Strategy : Variance Swap Spread ----
def variance_swap_calendar_strategy(trader: VolTermStructureTrader,
                                    T1: float, T2: float,
                                    strikes: np.ndarray,
                                    iv_T1: np.ndarray,
                                    iv_T2: np.ndarray) -> Dict:
    """
    Trade the spread between 3M and 1M variance swap strikes.
    This is a pure vol term structure trade.
    """
    var_swap_T1 = trader.variance_swap_fair_value(T1, strikes, iv_T1)
    var_swap_T2 = trader.variance_swap_fair_value(T2, strikes, iv_T2)

    # Forward variance swap (period [T1, T2])
    w1 = var_swap_T1**2 * T1
    w2 = var_swap_T2**2 * T2
    fwd_var_swap = np.sqrt(max(w2 - w1, 0) / (T2 - T1))

    return {
        'var_swap_T1': var_swap_T1 * 100,
        'var_swap_T2': var_swap_T2 * 100,
        'fwd_var_swap': fwd_var_swap * 100,
        'spread': (var_swap_T2 - var_swap_T1) * 100,
        'trade': 'SELL calendar var spread' if var_swap_T2 > var_swap_T1 * 1.05 else 'BUY calendar var spread',
    }


import numpy as np
import pandas as pd
from scipy.stats import norm
from scipy.optimize import brentq, minimize
from typing import List, Tuple, Dict
import matplotlib.pyplot as plt

class CalendarSpreadTrader:
    """
    Calendar spread analysis: forward vol extraction, forward skew,
    diagonal spread optimization, and P&L simulation.
    """

    def __init__(self, S: float, r: float = 0.05, q: float = 0.015):
        self.S = S
        self.r = r
        self.q = q

    def forward(self, T: float) -> float:
        return self.S * np.exp((self.r - self.q) * T)

    def bs_call(self, K: float, T: float, sigma: float) -> float:
        F = self.forward(T)
        if sigma <= 0.0 or T <= 0.0:
            return max(F * np.exp(-self.r * T) - K * np.exp(-self.r * T), 0.0)
        d1 = (np.log(F / K) + 0.5 * sigma**2 * T) / (sigma * np.sqrt(T))
        d2 = d1 - sigma * np.sqrt(T)
        return np.exp(-self.r * T) * (F * norm.cdf(d1) - K * norm.cdf(d2))

    def implied_vol(self, K: float, T: float, price: float, option_type: str = 'call') -> float:
        """Invert BS formula via Brent's method."""
        def obj(sigma):
            if option_type == 'call':
                return self.bs_call(K, T, sigma) - price
            else:
                c = self.bs_call(K, T, sigma)
                F = self.forward(T)
                put = c - np.exp(-self.r * T) * (F - K)
                return put - price
        try:
            return brentq(obj, 1e-6, 5.0, xtol=1e-8)
        except:
            return np.nan

    def extract_forward_vol(self, T1: float, T2: float, iv_T1: float, iv_T2: float) -> float:
        """
        Extract ATM forward implied volatility for period [T1, T2].
        Formula: sigma_fwd = sqrt((sigma2^2 * T2 - sigma1^2 * T1) / (T2 - T1))
        """
        w1 = iv_T1**2 * T1
        w2 = iv_T2**2 * T2
        if w2 < w1:
            raise ValueError(f"Calendar arb: w2 ={w2:.4f} < w1 ={w1:.4f}")
        return np.sqrt((w2 - w1) / (T2 - T1))

    def extract_forward_smile(self, strikes: np.ndarray, iv_surface_T1: np.ndarray, iv_surface_T2: np.ndarray, T1: float, T2: float) -> np.ndarray:
        """
        Extract the forward smile (IV for period [T1, T2]) at each strike.
        """
        w1 = iv_surface_T1**2 * T1
        w2 = iv_surface_T2**2 * T2
        forward_var = np.maximum(w2 - w1, 0.0) / (T2 - T1)
        return np.sqrt(forward_var)

    def calendar_greeks(self, K: float, T1: float, T2: float, sigma1: float, sigma2: float) -> Dict:
        """
        Compute all Greeks for a calendar spread:
        Long back-month (T2), Short front-month (T1), same strike K.
        """
        F1 = self.forward(T1)
        F2 = self.forward(T2)

        def greek(K, T, sigma, greek_name):
            d1 = (np.log(self.forward(T) / K) + 0.5 * sigma**2 * T) / (sigma * np.sqrt(T))
            d2 = d1 - sigma * np.sqrt(T)
            if greek_name == 'price':
                return np.exp(-self.r * T) * (self.forward(T) * norm.cdf(d1) - K * norm.cdf(d2))
            elif greek_name == 'delta':
                return np.exp(-self.q * T) * norm.cdf(d1)
            elif greek_name == 'gamma':
                return np.exp(-self.q * T) * norm.pdf(d1) / (self.S * sigma * np.sqrt(T))
            elif greek_name == 'vega':
                return self.S * np.exp(-self.q * T) * norm.pdf(d1) * np.sqrt(T)
            elif greek_name == 'theta':
                return -(self.S * np.exp(-self.q * T) * norm.pdf(d1) * sigma / (2.0 * np.sqrt(T))
                         + self.r * K * np.exp(-self.r * T) * norm.cdf(d2)
                         - self.q * self.S * np.exp(-self.q * T) * norm.cdf(d1)) / 365.0

        result = {}
        for g in ['price', 'delta', 'gamma', 'vega', 'theta']:
            g1 = greek(K, T1, sigma1, g)
            g2 = greek(K, T2, sigma2, g)
            result[f'front_{g}'] = g1
            result[f'back_{g}'] = g2
            result[f'cal_{g}'] = g2 - g1

        # Break-even vol for front month
        # At break-even: theta_earn = gamma_lose
        if result['front_gamma'] != 0.0:
            result['front_breakeven_vol'] = np.sqrt(-2.0 * result['front_theta'] / result['front_gamma']) * np.sqrt(252.0)
        else:
            result['front_breakeven_vol'] = np.nan

        result['fwd_vol'] = self.extract_forward_vol(T1, T2, sigma1, sigma2)
        return result

    def calendar_pnl_simulation(self, K: float, T1: float, T2: float, sigma1_init: float, sigma2_init: float, n_paths: int = 10000, n_steps_T1: int = 21) -> Dict:
        """
        Monte Carlo simulation of calendar spread P&L.
        """
        dt = T1 / n_steps_T1
        sigma_realized = sigma1_init
        total_pnl = np.zeros(n_paths)

        for path in range(n_paths):
            S_t = self.S
            sigma1_t = sigma1_init
            sigma2_t = sigma2_init
            T1_rem = T1
            T2_rem = T2

            # Initial calendar position
            front_delta = self._delta(K, T1_rem, sigma1_t)
            back_delta = self._delta(K, T2_rem, sigma2_t)
            hedge_delta = -(back_delta - front_delta)

            path_pnl = 0.0
            for step in range(n_steps_T1):
                dW = np.random.normal(0.0, 1.0)
                dS = S_t * (self.r - self.q) * dt + S_t * sigma_realized * np.sqrt(dt) * dW

                # P&L from position
                dC_front = self._price_deriv_S(K, T1_rem, sigma1_t) * dS
                dC_back = self._price_deriv_S(K, T2_rem, sigma2_t) * dS
                hedge_pnl = hedge_delta * dS

                path_pnl += (dC_back - dC_front + hedge_pnl)

                # Update state
                S_t += dS
                T1_rem -= dt
                T2_rem -= dt

                # Re-hedge delta
                if T1_rem > 0.0:
                    front_delta = self._delta(K, T1_rem, sigma1_t)
                    back_delta = self._delta(K, T2_rem, sigma2_t)
                    hedge_delta = -(back_delta - front_delta)

            total_pnl[path] = path_pnl

        return {
            'mean_pnl': total_pnl.mean(),
            'std_pnl': total_pnl.std(),
            'sharpe': total_pnl.mean() / total_pnl.std() * np.sqrt(252.0 / T1),
            'pnl_5pct': np.percentile(total_pnl, 5.0),
            'pnl_95pct': np.percentile(total_pnl, 95.0),
            'pnl_distribution': total_pnl
        }

    def _delta(self, K: float, T: float, sigma: float) -> float:
        if T <= 0.0:
            return 0.0
        d1 = (np.log(self.forward(T) / K) + 0.5 * sigma**2 * T) / (sigma * np.sqrt(T))
        return np.exp(-self.q * T) * norm.cdf(d1)

    def _price_deriv_S(self, K: float, T: float, sigma: float) -> float:
        """Numerical delta w.r.t S."""
        h = self.S * 0.001
        p_up = self.bs_call(K, T, sigma) * (self.S + h) / self.S
        p_dn = self.bs_call(K, T, sigma) * (self.S - h) / self.S
        return (p_up - p_dn) / (2.0 * h)

def analyze_forward_vol_term_structure(iv_atm_by_expiry: Dict[float, float], S: float, r: float, q: float) -> pd.DataFrame:
    """
    Given ATM IVs at multiple expiries, extract and analyze forward vols.
    """
    trader = CalendarSpreadTrader(S, r, q)
    expiries = sorted(iv_atm_by_expiry.keys())
    results = []

    for i in range(len(expiries)):
        T = expiries[i]
        iv = iv_atm_by_expiry[T]
        total_var = iv**2 * T

        if i > 0:
            T_prev = expiries[i - 1]
            iv_prev = iv_atm_by_expiry[T_prev]
            fwd_vol = trader.extract_forward_vol(T_prev, T, iv_prev, iv)
            fwd_period = f"{T_prev:.2f}Y - {T:.2f}Y"
        else:
            fwd_vol = iv
            fwd_period = f"0 - {T:.2f}Y"

        results.append({
            'Expiry': T,
            'ATM IV': f"{iv * 100.0:.2f}%",
            'Total Var': f"{total_var:.4f}",
            'Fwd Vol Period': fwd_period,
            'Fwd Vol': f"{fwd_vol * 100.0:.2f}%",
            'IV vs FwdVol': f"{(fwd_vol - iv) * 100.0:+.2f}%"
        })

    return pd.DataFrame(results)


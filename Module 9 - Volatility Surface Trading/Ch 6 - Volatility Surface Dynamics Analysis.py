import numpy as np
import pandas as pd
from scipy.stats import norm
from sklearn.decomposition import PCA
from sklearn.preprocessing import StandardScaler
import matplotlib.pyplot as plt
from typing import Dict, List, Tuple

class SurfaceDynamicsAnalyzer:
    """
    Analyzes the dynamic properties of the volatility surface.
    Includes PCA, spot-vol correlation, and conditional surface behavior.
    """

    def __init__(self, surface_history: np.ndarray, strikes: np.ndarray, expiries: np.ndarray, spot_history: np.ndarray):
        """
        Parameters:
        surface_history : shape (n_days, n_T, n_K) implied vol surface
        strikes : strike grid, shape (n_K,)
        expiries : expiry grid, shape (n_T,)
        spot_history : shape (n_days,)
        """
        self.surface_history = surface_history
        self.strikes = strikes
        self.expiries = expiries
        self.spot_history = spot_history
        n_days, n_T, n_K = surface_history.shape
        self.n_days = n_days
        self.n_T = n_T
        self.n_K = n_K
        # Flatten surface for PCA: (n_days, n_T * n_K)
        self.flat_surfaces = surface_history.reshape(n_days, n_T * n_K)

    def compute_surface_pca(self, n_components: int = 5) -> Dict:
        """
        Perform PCA on daily surface changes.
        Returns principal components, scores, and variance explained.
        """
        # Compute daily changes
        surface_changes = np.diff(self.flat_surfaces, axis=0)

        # Standardize (each grid point gets unit variance)
        scaler = StandardScaler()
        changes_scaled = scaler.fit_transform(surface_changes)

        # PCA
        pca = PCA(n_components=n_components)
        scores = pca.fit_transform(changes_scaled)

        # Reshape loadings back to surface shape
        loadings_2d = [
            pca.components_[i].reshape(self.n_T, self.n_K)
            for i in range(n_components)
        ]

        # Variance explained
        var_exp = pca.explained_variance_ratio_

        # Interpretation of each PC
        interpretations = []
        for i in range(n_components):
            loading = loadings_2d[i]
            # Check if predominantly parallel (all same sign)
            sign_consistency = abs(loading.mean()) / (np.abs(loading).mean() + 1e-8)

            # Check term structure slope
            ts_slope = np.polyfit(range(self.n_T), loading.mean(axis=1), 1)[0]

            # Check strike slope (skew)
            sk_slope = np.polyfit(range(self.n_K), loading.mean(axis=0), 1)[0]

            if sign_consistency > 0.7:
                interp = "Level (parallel shift)"
            elif abs(ts_slope) > abs(sk_slope):
                interp = "Term structure tilt" if ts_slope > 0 else "Inverted term structure"
            else:
                interp = "Skew change" if sk_slope > 0 else "Inverse skew"
            interpretations.append(interp)

        return {
            'pca': pca,
            'scores': scores,
            'loadings_2d': loadings_2d,
            'variance_explained': var_exp,
            'cumulative_var': np.cumsum(var_exp),
            'interpretations': interpretations,
            'scaler': scaler
        }

    def compute_spot_vol_correlation(self, expiry_idx: int = 2, window: int = 60) -> Dict:
        """
        Compute rolling spot-vol correlation:
        Corr (dS/S, d_sigma_ATM) for the specified expiry.
        """
        log_returns = np.diff(np.log(self.spot_history))
        atm_k_idx = self.n_K // 2 # ATM approximately
        vol_changes = np.diff(self.surface_history[:, expiry_idx, atm_k_idx])

        n = len(log_returns)
        rolling_corr = np.full(n, np.nan)
        rolling_beta = np.full(n, np.nan) # d_sigma / d_logS

        for i in range(window, n):
            ret_window = log_returns[i - window : i]
            vol_window = vol_changes[i - window : i]
            corr = np.corrcoef(ret_window, vol_window)[0, 1]
            beta = np.cov(ret_window, vol_window)[0, 1] / (np.var(ret_window) + 1e-10)
            rolling_corr[i] = corr
            rolling_beta[i] = beta

        return {
            'rolling_correlation': rolling_corr,
            'rolling_beta': rolling_beta,
            'mean_correlation': np.nanmean(rolling_corr),
            'mean_beta': np.nanmean(rolling_beta)
        }

    def conditional_surface_response(self, spot_move_pct: float, regression_window: int = 252) -> Dict:
        """
        Estimate how the surface moves conditional on a spot move.
        For each grid point (T_i, K_j), fit:
        d_sigma (T_i, K_j) = alpha + beta * d_logS + epsilon
        Returns the conditional surface shift for a given spot move.
        """
        log_returns = np.diff(np.log(self.spot_history))
        surface_changes = np.diff(self.surface_history, axis=0)

        beta_surface = np.zeros((self.n_T, self.n_K))
        alpha_surface = np.zeros((self.n_T, self.n_K))
        r2_surface = np.zeros((self.n_T, self.n_K))

        for t_idx in range(self.n_T):
            for k_idx in range(self.n_K):
                vol_chg = surface_changes[-regression_window:, t_idx, k_idx]
                ret_chg = log_returns[-regression_window:]

                # OLS regression
                X = np.column_stack([np.ones(len(ret_chg)), ret_chg])
                coeffs = np.linalg.lstsq(X, vol_chg, rcond=None)[0]
                alpha_surface[t_idx, k_idx] = coeffs[0]
                beta_surface[t_idx, k_idx] = coeffs[1]

                # R-squared
                pred = X @ coeffs
                ss_res = ((vol_chg - pred) ** 2).sum()
                ss_tot = ((vol_chg - vol_chg.mean()) ** 2).sum()
                r2_surface[t_idx, k_idx] = 1 - ss_res / (ss_tot + 1e-10)

        # Conditional surface shift for given spot move
        conditional_shift = beta_surface * spot_move_pct / 100

        return {
            'beta_surface': beta_surface,
            'alpha_surface': alpha_surface,
            'r2_surface': r2_surface,
            'conditional_shift': conditional_shift,
            'atm_beta': beta_surface[self.n_T // 2, self.n_K // 2]
        }

# ---- Simulate Heston Surface Paths ----
def simulate_heston_surface_paths(S0: float, kappa: float, theta: float, xi: float, rho: float, v0: float, r: float, T_grid: np.ndarray, K_grid: np.ndarray, n_days: int = 252, dt: float = 1/252, seed: int = 42) -> Tuple[np.ndarray, np.ndarray]:
    """
    Simulate Heston model paths and compute resulting IV surface at each step.
    Returns (spot_path, surface_path) where surface_path is (n_days, n_T, n_K).
    """
    np.random.seed(seed)

    # Correlated Brownian motions
    dW_S = np.random.normal(0, np.sqrt(dt), n_days)
    dW_v = rho * dW_S + np.sqrt(1 - rho**2) * np.random.normal(0, np.sqrt(dt), n_days)

    # Simulate paths
    S_path = np.zeros(n_days + 1)
    v_path = np.zeros(n_days + 1)
    S_path[0] = S0
    v_path[0] = v0

    for i in range(n_days):
        S_path[i+1] = S_path[i] * np.exp((r - 0.5 * v_path[i]) * dt + np.sqrt(max(v_path[i], 0)) * dW_S[i])
        v_path[i+1] = max(v_path[i] + kappa * (theta - v_path[i]) * dt + xi * np.sqrt(max(v_path[i], 0)) * dW_v[i], 0)

    # Compute IV surface at each time step using Heston approximation
    def heston_iv_approx(S, v0_curr, T, K):
        F = S * np.exp(r * T)
        y = np.log(K / F)
        # ATM vol approx
        E_var = theta + (v0_curr - theta) * (1 - np.exp(-kappa * T)) / (kappa * T) if kappa * T > 1e-6 else v0_curr
        atm_vol = np.sqrt(E_var)
        # Skew correction (linear in y)
        skew = xi * rho / (2 * kappa * atm_vol) * (1 - np.exp(-kappa * T)) / (kappa * T) if kappa * T > 1e-6 else xi * rho * T / (2 * atm_vol)
        return max(atm_vol + skew * y, 0.01)

    surface_path = np.zeros((n_days + 1, len(T_grid), len(K_grid)))
    for day in range(n_days + 1):
        for t_idx, T in enumerate(T_grid):
            for k_idx, K in enumerate(K_grid):
                surface_path[day, t_idx, k_idx] = heston_iv_approx(S_path[day], v_path[day], T, K)

    return S_path, surface_path


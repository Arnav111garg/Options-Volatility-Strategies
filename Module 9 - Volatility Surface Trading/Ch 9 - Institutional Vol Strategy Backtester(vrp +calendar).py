import numpy as np
import pandas as pd
from scipy.stats import norm
from scipy.optimize import brentq
from typing import Dict, List, Tuple
import warnings
warnings.filterwarnings('ignore')

class InstitutionalVolBacktester:
    """
    Backtests institutional-grade volatility surface strategies.

    Includes:
    1. VRP (Variance Risk Premium) Harvest
    2. Calendar Spread Mean Reversion
    3. Dispersion (simplified single-stock proxy)
    4. Surface Relative Value
    """

    def __init__(self, spot: np.ndarray, iv_1m: np.ndarray,
                 iv_3m: np.ndarray, iv_6m: np.ndarray,
                 r: float = 0.05, q: float = 0.015,
                 trading_days: int = 252):
        """
        spot: daily closing prices, length N
        iv_Xm: daily ATM implied vols, matching spot
        """
        self.spot = np.asarray(spot, dtype=float)
        self.iv_1m = np.asarray(iv_1m, dtype=float)
        self.iv_3m = np.asarray(iv_3m, dtype=float)
        self.iv_6m = np.asarray(iv_6m, dtype=float)
        self.r = r
        self.q = q
        self.td = trading_days
        self.N = len(spot)
        self.returns = np.diff(np.log(spot))

    # --------------------------------------------------------------------------
    # Utility
    # --------------------------------------------------------------------------

    def _realised_vol(self, start: int, end: int) -> float:
        """Annualised realised vol from return series."""
        ret = self.returns[start:end]
        return np.std(ret) * np.sqrt(self.td)

    def _bs_straddle_price(self, S, K, T, r, q, sigma) -> float:
        F = S * np.exp((r - q) * T)
        d1 = (np.log(F / K) + 0.5 * sigma**2 * T) / (sigma * np.sqrt(T))
        d2 = d1 - sigma * np.sqrt(T)
        call = np.exp(-r * T) * (F * norm.cdf(d1) - K * norm.cdf(d2))
        put = call + K * np.exp(-r * T) - F * np.exp(-r * T)
        return call + put

    def _delta_hedge_pnl(self, S_path: np.ndarray, K: float, T: float,
                         sigma_iv: float, r: float, q: float,
                         position: float = -1.0) -> float:
        """
        Simulate P&L of a continuously (daily) delta-hedged straddle.
        position: -1 = short straddle, +1 = long straddle
        """
        n = len(S_path) - 1
        dt = T / n
        pnl = 0.0

        # Initial straddle price and delta
        def straddle_delta(S, T_rem, sig):
            F = S * np.exp((r - q) * T_rem)
            d1 = (np.log(F / K) + 0.5 * sig**2 * T_rem) / (sig * np.sqrt(T_rem))
            return np.exp(-q * T_rem) * (2 * norm.cdf(d1) - 1)  # call - put delta

        T_rem = T
        hedge = position * straddle_delta(S_path[0], T_rem, sigma_iv)

        for i in range(n):
            dS = S_path[i+1] - S_path[i]
            T_rem -= dt
            if T_rem < dt:
                T_rem = dt

            # Gamma P&L
            F = S_path[i] * np.exp((r - q) * T_rem)
            d1 = (np.log(F / K) + 0.5 * sigma_iv**2 * T_rem) / (sigma_iv * np.sqrt(T_rem))
            phi = norm.pdf(d1)
            gam = np.exp(-q * T_rem) * phi / (S_path[i] * sigma_iv * np.sqrt(T_rem))
            pnl += position * 0.5 * gam * dS**2

            # Theta P&L
            theta = -(S_path[i] * np.exp(-q * T_rem) * phi * sigma_iv / (2 * np.sqrt(T_rem))) / self.td
            pnl += position * theta

            # Re-hedge
            new_hedge = position * straddle_delta(S_path[i+1], T_rem, sigma_iv)
            hedge_pnl = hedge * dS
            pnl += hedge_pnl
            hedge = new_hedge

        return pnl

    # --------------------------------------------------------------------------
    # Strategy 1: VRP Harvest
    # --------------------------------------------------------------------------

    def backtest_vrp(self, holding_days: int = 21,
                     vega_notional: float = 100_000) -> Dict:
        """
        Monthly short ATM straddle strategy.
        Enter at close, hold for holding_days, delta-hedge daily, close at expiry.
        """
        pnls = []
        ivs = []
        rvs = []
        entry_idx = holding_days  # start after warm-up

        while entry_idx + holding_days < self.N:
            i0 = entry_idx
            i1 = i0 + holding_days

            S0 = self.spot[i0]
            T = holding_days / self.td
            sigma = self.iv_1m[i0]

            # Quantity: vega_notional / vega_per_unit
            F = S0 * np.exp((self.r - self.q) * T)
            d1 = (np.log(F / S0) + 0.5 * sigma**2 * T) / (sigma * np.sqrt(T))
            vega_unit = S0 * np.exp(-self.q * T) * norm.pdf(d1) * np.sqrt(T)
            qty = vega_notional / (vega_unit * 0.01 * 100)  # normalise

            # Simulate path
            spot_path = self.spot[i0 : i1 + 1]
            path_pnl = self._delta_hedge_pnl(spot_path, S0, T, sigma, self.r, self.q, position=-1.0)

            # Realised vol over period
            rv = self._realised_vol(i0, i1)

            pnls.append(path_pnl * qty)
            ivs.append(sigma)
            rvs.append(rv)
            entry_idx = i1

        pnls = np.array(pnls)
        ivs = np.array(ivs)
        rvs = np.array(rvs)

        ann_factor = self.td / holding_days
        return {
            'strategy': 'VRP Harvest (Short Monthly Straddle)',
            'n_trades': len(pnls),
            'mean_pnl_trade': pnls.mean(),
            'std_pnl_trade': pnls.std(),
            'ann_sharpe': pnls.mean() / pnls.std() * np.sqrt(ann_factor),
            'hit_rate': (pnls > 0).mean(),
            'worst_trade': pnls.min(),
            'best_trade': pnls.max(),
            'mean_iv_premium': (ivs - rvs).mean() * 100,
            'total_pnl': pnls.sum(),
            'pnl_series': pnls,
        }

    # --------------------------------------------------------------------------
    # Strategy 2: Calendar Spread Mean Reversion
    # --------------------------------------------------------------------------

    def backtest_calendar_mean_reversion(self, lookback: int = 60,
                                         entry_z: float = 1.5,
                                         exit_z: float = 0.3,
                                         holding_days: int = 21) -> Dict:
        """
        Trade the 1M/3M calendar when forward vol is statistically extreme.
        Signal: z-score of (sigma_3m - sigma_1m) relative to lookback window.
        """
        spread = self.iv_3m - self.iv_1m
        pnls = []
        trades = []

        i = lookback
        while i + holding_days < self.N:
            hist_spread = spread[i - lookback : i ]
            mu_s = hist_spread.mean()
            std_s = hist_spread.std()
            if std_s < 1e-6:
                i += 1
                continue

            z_score = (spread[i] - mu_s) / std_s

            if abs(z_score) > entry_z:
                # Enter: if z > 0 (spread wide), sell back-month / buy front-month
                direction = -np.sign(z_score)  # -1 when spread is wide
                entry_spread = spread[i]

                # Hold until exit signal or max holding days
                exit_idx = i + holding_days
                for j in range(i + 1, min(i + holding_days, self.N)):
                    z_j = (spread[j] - mu_s) / std_s
                    if abs(z_j) < exit_z:
                        exit_idx = j
                        break

                exit_spread = spread[exit_idx]
                trade_pnl = direction * (entry_spread - exit_spread) * 100  # in bp
                pnls.append(trade_pnl)
                trades.append({
                    'entry_day': i,
                    'exit_day': exit_idx,
                    'z_entry': z_score,
                    'direction': 'Short Calendar' if direction < 0 else 'Long Calendar',
                    'entry_spread': entry_spread * 100,
                    'exit_spread': exit_spread * 100,
                    'pnl_bps': trade_pnl,
                })
                i = exit_idx
            else:
                i += 1

        pnls = np.array(pnls) if pnls else np.array([0.0])
        return {
            'strategy': 'Calendar Spread Mean Reversion',
            'n_trades': len(pnls),
            'mean_pnl_bps': pnls.mean(),
            'ann_sharpe': pnls.mean() / max(pnls.std(), 1e-6) * np.sqrt(252 / 21),
            'hit_rate': (pnls > 0).mean(),
            'worst_trade_bps': pnls.min(),
            'total_pnl_bps': pnls.sum(),
            'trade_log': trades[:10],
        }

    # --------------------------------------------------------------------------
    # Strategy 3: Forward Vol Signal
    # --------------------------------------------------------------------------

    def forward_vol_signal(self, T1: float = 1/12, T2: float = 3/12) -> np.ndarray:
        """
        Daily time series of the forward vol signal:
        fwd_vol (T1, T2) - iv_atm_T1
        Positive = forward vol elevated vs spot; sell calendar.
        """
        w1 = self.iv_1m**2 * T1
        w2 = self.iv_3m**2 * T2
        fwd = np.sqrt(np.maximum(w2 - w1, 0) / (T2 - T1))
        return fwd - self.iv_1m

    # --------------------------------------------------------------------------
    # Reporting
    # --------------------------------------------------------------------------

    def full_report(self) -> None:
        """Run all strategies and print summary."""
        print("=" * 65)
        print(" INSTITUTIONAL VOL STRATEGY BACKTEST REPORT ")
        print("=" * 65)

        vrp = self.backtest_vrp(holding_days=21, vega_notional=100_000)
        cal = self.backtest_calendar_mean_reversion(lookback=60, entry_z=1.5)

        for res in [vrp, cal]:
            print(f"\n[{res['strategy']}]")
            for k, v in res.items():
                if k not in ('pnl_series', 'trade_log'):
                    val = f"{v:.4f}" if isinstance(v, float) else str(v)
                    print(f"  {k:30s}: {val}")

        print("\n[Forward Vol Signal Last 10 obs]")
        sig = self.forward_vol_signal()
        for i in range(-10, 0):
            print(f"  Day {self.N+i}: fwd_premium = {sig[i]*100:+.2f} vol pts")


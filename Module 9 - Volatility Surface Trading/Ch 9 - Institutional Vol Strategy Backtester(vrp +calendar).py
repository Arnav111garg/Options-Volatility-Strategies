def generate_synthetic_market(n_days: int = 756, seed: int = 42) -> Dict:
    """
    Generate synthetic SPX-like spot + IV data using a Heston model.
    Returns arrays suitable for InstitutionalVolBacktester.
    """
    np.random.seed(seed)
    dt = 1 / 252
    kap = 3.0; the = 0.04; xi = 0.5; rho = -0.75; v0 = 0.05
    r = 0.05; q = 0.015

    S = np.zeros(n_days); S[0] = 4000.0
    v = np.zeros(n_days); v[0] = v0

    for i in range(n_days - 1):
        dW1 = np.random.normal(0, np.sqrt(dt))
        dW2 = rho * dW1 + np.sqrt(1 - rho**2) * np.random.normal(0, np.sqrt(dt))
        S[i+1] = S[i] * np.exp((r - q - 0.5 * v[i]) * dt + np.sqrt(max(v[i], 0)) * dW1)
        v[i+1] = max(v[i] + kap * (the - v[i]) * dt + xi * np.sqrt(max(v[i], 0)) * dW2, 1e-5)

    # Approximate ATM vols from Heston term structure
    def heston_atm(v_curr, T):
        if kap * T > 1e-6:
            E_v = the + (v_curr - the) * (1 - np.exp(-kap * T)) / (kap * T)
        else:
            E_v = v_curr
        return np.sqrt(E_v) * (1 + xi * abs(rho) * 0.1 * np.sqrt(T))

    iv_1m = np.array([heston_atm(v[i], 1/12) for i in range(n_days)])
    iv_3m = np.array([heston_atm(v[i], 3/12) for i in range(n_days)])
    iv_6m = np.array([heston_atm(v[i], 6/12) for i in range(n_days)])

    return dict(spot=S, iv_1m=iv_1m, iv_3m=iv_3m, iv_6m=iv_6m)


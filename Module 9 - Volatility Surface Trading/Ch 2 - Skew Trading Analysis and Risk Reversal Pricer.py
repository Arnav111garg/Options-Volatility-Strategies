import numpy as np
from scipy.stats import norm
from scipy.optimize import brentq
from dataclasses import dataclass
from typing import Optional

@dataclass
class OptionSpec:
    S: float  # Spot
    K: float  # Strike
    T: float  # Time to expiry (years)
    r: float  # Risk-free rate
    q: float  # Dividend yield
    sigma: float  # Implied vol

class SkewTrader:
    """
    Comprehensive skew trading toolkit.
    Includes risk reversal pricing, vanna / volga P&L, and skew analysis.
    """

    @staticmethod
    def d1_d2(S, K, T, r, q, sigma):
        """Compute Black-Scholes d1 and d2."""
        F = S * np.exp((r - q) * T)
        d1 = (np.log(F / K) + 0.5 * sigma**2 * T) / (sigma * np.sqrt(T))
        d2 = d1 - sigma * np.sqrt(T)
        return d1, d2

    @staticmethod
    def bs_call(S, K, T, r, q, sigma):
        d1, d2 = SkewTrader.d1_d2(S, K, T, r, q, sigma)
        return (S * np.exp(-q * T) * norm.cdf(d1)
                - K * np.exp(-r * T) * norm.cdf(d2))

    @staticmethod
    def bs_put(S, K, T, r, q, sigma):
        d1, d2 = SkewTrader.d1_d2(S, K, T, r, q, sigma)
        return (K * np.exp(-r * T) * norm.cdf(-d2)
                - S * np.exp(-q * T) * norm.cdf(-d1))

    @staticmethod
    def delta(S, K, T, r, q, sigma, option_type='call'):
        d1, _ = SkewTrader.d1_d2(S, K, T, r, q, sigma)
        if option_type == 'call':
            return np.exp(-q * T) * norm.cdf(d1)
        else:
            return np.exp(-q * T) * (norm.cdf(d1) - 1.0)

    @staticmethod
    def vega(S, K, T, r, q, sigma):
        d1, d2 = SkewTrader.d1_d2(S, K, T, r, q, sigma)
        return S * np.exp(-q * T) * norm.pdf(d1) * np.sqrt(T)

    @staticmethod
    def vanna(S, K, T, r, q, sigma):
        """Vanna = d(Delta)/d(sigma) = d(Vega)/dS"""
        d1, d2 = SkewTrader.d1_d2(S, K, T, r, q, sigma)
        return -np.exp(-q * T) * norm.pdf(d1) * d2 / sigma

    @staticmethod
    def volga(S, K, T, r, q, sigma):
        """Volga = d2(V)/d(sigma)2 = Vega * d1 * d2 / sigma"""
        d1, d2 = SkewTrader.d1_d2(S, K, T, r, q, sigma)
        v = SkewTrader.vega(S, K, T, r, q, sigma)
        return v * d1 * d2 / sigma

    @staticmethod
    def find_delta_strike(S, T, r, q, sigma_curve, target_delta, option_type='put'):
        """
        Find the strike corresponding to a target delta level,
        allowing for a vol smile.
        sigma_curve: callable sigma_curve(K) -> IV
        """
        def objective(K):
            sigma = sigma_curve(K)
            d = SkewTrader.delta(S, K, T, r, q, sigma, option_type)
            return d - target_delta

        # Search over a reasonable range
        K_min, K_max = S * 0.5, S * 1.5
        try:
            K_star = brentq(objective, K_min, K_max, xtol=1e-4)
            return K_star
        except ValueError:
            return None

    def compute_risk_reversal(self, S, T, r, q, sigma_25p, sigma_25c, sigma_atm):
        """
        Compute risk reversal metrics given the three pillar vols.
        Returns comprehensive Greek profile of the RR position.
        """
        # Find delta strikes iteratively (simplified: use flat vol approx)
        # In production: iterate until self-consistent delta / strike / vol
        d1_atm, _ = self.d1_d2(S, S, T, r, q, sigma_atm)

        # Approximate delta strikes
        K_25p = S * np.exp(-norm.ppf(0.75) * sigma_25p * np.sqrt(T) + (r - q - 0.5 * sigma_25p**2) * T)
        K_25c = S * np.exp(norm.ppf(0.75) * sigma_25c * np.sqrt(T) + (r - q - 0.5 * sigma_25c**2) * T)

        # Option prices
        put_price = self.bs_put(S, K_25p, T, r, q, sigma_25p)
        call_price = self.bs_call(S, K_25c, T, r, q, sigma_25c)

        # Greeks of each leg
        put_delta = self.delta(S, K_25p, T, r, q, sigma_25p, 'put')
        call_delta = self.delta(S, K_25c, T, r, q, sigma_25c, 'call')

        put_vega = self.vega(S, K_25p, T, r, q, sigma_25p)
        call_vega = self.vega(S, K_25c, T, r, q, sigma_25c)

        put_vanna = self.vanna(S, K_25p, T, r, q, sigma_25p)
        call_vanna = self.vanna(S, K_25c, T, r, q, sigma_25c)

        put_volga = self.volga(S, K_25p, T, r, q, sigma_25p)
        call_volga = self.volga(S, K_25c, T, r, q, sigma_25c)

        # Risk Reversal: long put, short call (buying skew)
        rr = {
            'K_25p': K_25p,
            'K_25c': K_25c,
            'put_price': put_price,
            'call_price': call_price,
            'net_premium': put_price - call_price,
            'net_delta': put_delta - call_delta,  # should be ~ -0.50
            'net_vega': put_vega - call_vega,      # near zero
            'net_vanna': put_vanna - call_vanna,  # dominant Greek
            'net_volga': put_volga - call_volga,  # near zero
            'vol_differential': sigma_25p - sigma_25c  # |RR| in vol terms
        }

        print(f"Risk Reversal Analysis (T={T:.2f}y)")
        print(f"  25d Put strike: {K_25p:.2f} | IV: {sigma_25p*100:.2f}%")
        print(f"  25d Call strike: {K_25c:.2f} | IV: {sigma_25c*100:.2f}%")
        print(f"  Vol differential (skew): {rr['vol_differential']*100:.2f}%")
        print(f"  Net delta: {rr['net_delta']:.4f}")
        print(f"  Net vega: {rr['net_vega']:.4f}")
        print(f"  Net vanna: {rr['net_vanna']:.6f} <-- Dominant risk!")
        print(f"  Net volga: {rr['net_volga']:.6f}")
        return rr

    def skew_pnl_scenarios(self, S0, T, r, q, sigma_25p, sigma_25c, sigma_atm, spot_moves: np.ndarray, skew_change_per_pct: float = 0.002):
        """
        Estimate P&L of a delta-hedged risk reversal under spot scenarios.
        skew_change_per_pct: how much skew steepens per 1% down move (empirically ~0.1-0.3 vol points per 1% for SPX)
        """
        rr = self.compute_risk_reversal(S0, T, r, q, sigma_25p, sigma_25c, sigma_atm)

        pnls = []
        for dS in spot_moves:
            pct_move = dS / S0
            # Skew steepens when market falls
            d_skew = -skew_change_per_pct * pct_move * 100.0
            d_atm_vol = 0.0  # Assume ATM flat for simplicity

            # First-order P&L from vanna
            pnl_vanna = rr['net_vanna'] * dS * d_skew
            # First-order from delta (already hedged, so minimal)
            pnl_delta = 0.0  # hedged
            # Total
            total = pnl_vanna + pnl_delta
            pnls.append({
                'dS': dS,
                'pct': pct_move * 100.0,
                'd_skew': d_skew,
                'pnl': total
            })

        return pnls


import numpy as np
import pandas as pd
from scipy.interpolate import RectBivariateSpline
from scipy.optimize import minimize
import matplotlib.pyplot as plt
from typing import Tuple, Dict, List

class VolSurfaceArbitrageChecker:
    """
    Comprehensive arbitrage checker for implied volatility surfaces .
    Implements calendar spread , butterfly , and Dupire local vol checks .

    Reference : Gatheral (2006) , "The Volatility Surface "
    """

    def __init__(self, strikes: np.ndarray, expiries: np.ndarray, iv_surface: np.ndarray, forward: float, r: float = 0.0):
        """
        Parameters:
        strikes: array of strike prices, shape (n_K,)
        expiries: array of expiry times in years, shape (n_T,)
        iv_surface: 2D implied vol surface, shape (n_T, n_K)
        forward: forward price (assumed constant for simplicity)
        r: risk-free rate
        """
        self.K = strikes
        self.T = expiries
        self.iv = iv_surface
        self.F = forward
        self.r = r
        # Compute total variance surface w = sigma^2 * T
        self.w = np.outer(expiries, np.ones(len(strikes))) * iv_surface**2
        # Log-moneyness y = log(K/F)
        self.y = np.log(strikes / forward)

    def black_scholes_call(self, S: float, K: float, T: float, r: float, sigma: float) -> float:
        """Vectorized Black-Scholes call pricer."""
        from scipy.stats import norm
        if T <= 0 or sigma <= 0:
            return max(S - K * np.exp(-r * T), 0.0)
        d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
        d2 = d1 - sigma * np.sqrt(T)
        return S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)

    def check_calendar_spread_arbitrage(self) -> Dict:
        """
        Check: Total variance w(K,T) must be non-decreasing in T for each K.
        Returns dict with violation locations and magnitudes.
        """
        violations = []
        max_violation = 0.0

        for k_idx in range(len(self.K)):
            w_slice = self.w[:, k_idx]
            diffs = np.diff(w_slice)
            neg_mask = diffs < 0
            if np.any(neg_mask):
                for t_idx in np.where(neg_mask)[0]:
                    violation = {
                        'type': 'calendar',
                        'K': self.K[k_idx],
                        'T1': self.T[t_idx],
                        'T2': self.T[t_idx + 1],
                        'w_T1': w_slice[t_idx],
                        'w_T2': w_slice[t_idx + 1],
                        'violation_size': -diffs[t_idx]
                    }
                    violations.append(violation)
                    max_violation = max(max_violation, -diffs[t_idx])

        return {
            'has_arbitrage': len(violations) > 0,
            'num_violations': len(violations),
            'max_violation': max_violation,
            'violations': violations
        }

    def extract_rnd_breeden_litzenberger(self, t_idx: int, smooth: bool = True) -> Tuple[np.ndarray, np.ndarray]:
        """
        Extract Risk-Neutral Density via Breeden-Litzenberger formula.
        Uses finite differences on interpolated call prices.

        RND(K) = exp(rT) * d2C/dK2
        Returns: (K_grid, density) where negative values signal butterfly arb.
        """
        T_val = self.T[t_idx]
        iv_slice = self.iv[t_idx, :]

        # Compute call prices at each strike
        call_prices = np.array([
            self.black_scholes_call(self.F, K, T_val, self.r, sig)
            for K, sig in zip(self.K, iv_slice)
        ])

        # Interpolate for smooth second derivative
        if smooth:
            from scipy.interpolate import CubicSpline
            # Use finer grid
            K_fine = np.linspace(self.K[0], self.K[-1], 500)
            cs = CubicSpline(self.K, call_prices)
            C_fine = cs(K_fine)
            d2C_dK2 = cs(K_fine, 2)
        else:
            K_fine = self.K
            d2C_dK2 = np.gradient(np.gradient(call_prices, self.K), self.K)

        rnd = np.exp(self.r * T_val) * d2C_dK2
        return K_fine if smooth else self.K, rnd

    def check_butterfly_arbitrage(self, min_density: float = -1e-4) -> Dict:
        """
        Check RND non-negativity across all maturities.
        min_density: threshold (small negative allowed for numerical noise).
        """
        violations = []

        for t_idx in range(len(self.T)):
            K_grid, rnd = self.extract_rnd_breeden_litzenberger(t_idx)
            neg_mask = rnd < min_density
            if np.any(neg_mask):
                violations.append({
                    'type': 'butterfly',
                    'T': self.T[t_idx],
                    'K_range': (K_grid[neg_mask].min(), K_grid[neg_mask].max()),
                    'min_density': rnd[neg_mask].min(),
                    'num_points': neg_mask.sum()
                })

        return {
            'has_arbitrage': len(violations) > 0,
            'num_expiries_violated': len(violations),
            'violations': violations
        }

    def compute_dupire_local_vol(self, t_idx: int) -> Tuple[np.ndarray, np.ndarray]:
        """
        Compute Dupire local volatility at a given expiry slice.
        sigma_L^2(K,T) = (dC/dT + (r-q)*K*dC/dK + q*C) / (0.5 * K^2 * d2C/dK2)
        Returns (K_grid, local_vol) where negative values signal calendar arb.
        """
        T_val = self.T[t_idx]
        iv_slice = self.iv[t_idx, :]

        call_prices = np.array([
            self.black_scholes_call(self.F, K, T_val, self.r, sig)
            for K, sig in zip(self.K, iv_slice)
        ])

        # dC/dT via finite differences
        if t_idx == 0:
            dC_dT = (self.iv[1, :] - self.iv[0, :]) / (self.T[1] - self.T[0]) * 2 * self.iv[0, :] * T_val
        elif t_idx == len(self.T) - 1:
            dC_dT = (self.iv[-1, :] - self.iv[-2, :]) / (self.T[-1] - self.T[-2]) * 2 * self.iv[-1, :] * T_val
        else:
            dT = self.T[t_idx + 1] - self.T[t_idx - 1]
            call_up = np.array([self.black_scholes_call(self.F, K, self.T[t_idx + 1], self.r, s) for K, s in zip(self.K, self.iv[t_idx + 1, :])])
            call_dn = np.array([self.black_scholes_call(self.F, K, self.T[t_idx - 1], self.r, s) for K, s in zip(self.K, self.iv[t_idx - 1, :])])
            dC_dT = (call_up - call_dn) / dT

        dC_dK = np.gradient(call_prices, self.K)
        d2C_dK2 = np.gradient(dC_dK, self.K)

        numerator = dC_dT + self.r * self.K * dC_dK
        denominator = 0.5 * self.K ** 2 * d2C_dK2

        # Avoid division by zero
        with np.errstate(divide='ignore', invalid='ignore'):
            local_var = np.where(np.abs(denominator) > 1e-10, numerator / denominator, np.nan)

        local_vol = np.sqrt(np.maximum(local_var, 0.0))
        return self.K, local_vol

    def fit_svi(self, t_idx: int) -> Dict:
        """
        Fit Gatheral SVI to a single expiry slice.
        Minimizes sum of squared errors in total variance space.
        """
        y = self.y
        w_obs = self.w[t_idx, :]

        def svi_w(params, y):
            a, b, rho, m, sigma = params
            return a + b * (rho * (y - m) + np.sqrt((y - m) ** 2 + sigma ** 2))

        def objective(params):
            try:
                w_fit = svi_w(params, y)
                return np.sum((w_fit - w_obs) ** 2)
            except:
                return 1e10

        # Constraints: no-butterfly-arb conditions
        constraints = [
            {'type': 'ineq', 'fun': lambda p: p[1]},
            {'type': 'ineq', 'fun': lambda p: p[4]},
            {'type': 'ineq', 'fun': lambda p: 1 - abs(p[2])},
            {'type': 'ineq', 'fun': lambda p: 4 / self.T[t_idx] - p[1] * (1 + abs(p[2]))},
        ]

        # Initial guess
        atm_var = np.interp(0, y, w_obs)
        x0 = [atm_var * 0.9, 0.1, -0.3, 0.0, 0.1]

        result = minimize(objective, x0, method='SLSQP', constraints=constraints, options={'maxiter': 1000, 'ftol': 1e-12})

        a, b, rho, m, sigma = result.x
        w_fit = svi_w(result.x, y)
        rmse = np.sqrt(np.mean((np.sqrt(w_fit / self.T[t_idx]) - self.iv[t_idx, :]) ** 2)) * 100

        return {
            'params': {'a': a, 'b': b, 'rho': rho, 'm': m, 'sigma': sigma},
            'iv_fit': np.sqrt(w_fit / self.T[t_idx]),
            'w_fit': w_fit,
            'rmse_vols': rmse,
            'success': result.success
        }

    def full_surface_report(self) -> None:
        """Generate a comprehensive arbitrage report."""
        print("=" * 60)
        print(" VOLATILITY SURFACE ARBITRAGE REPORT ")
        print("=" * 60)

        cal_result = self.check_calendar_spread_arbitrage()
        print(f"\n[ CALENDAR SPREAD CHECK ]")
        print(f" Arbitrage present : {cal_result['has_arbitrage']}")
        print(f" Number of violations : {cal_result['num_violations']}")
        if cal_result['has_arbitrage']:
            print(f" Max violation (total var): {cal_result['max_violation']:.6f}")

        bfly_result = self.check_butterfly_arbitrage()
        print(f"\n[ BUTTERFLY CHECK ]")
        print(f" Arbitrage present : {bfly_result['has_arbitrage']}")
        print(f" Maturities violated : {bfly_result['num_expiries_violated']}")

        print(f"\n[SVI FIT QUALITY ]")
        for t_idx in range(len(self.T)):
            svi = self.fit_svi(t_idx)
            print(f" T={self.T[t_idx]:.3f}y: RMSE ={svi['rmse_vols']:.2f} vols, "
                  f"rho ={svi['params']['rho']:.3f} , b={svi['params']['b']:.4f}")


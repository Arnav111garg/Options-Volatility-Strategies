import numpy as np
from scipy.stats import norm
from scipy.interpolate import CubicSpline
from typing import Callable, Tuple, Dict
import warnings
warnings.filterwarnings('ignore')

class StickyDeltaHedger:
    """
    Delta hedging under the sticky-delta (floating smile) assumption.
    The smile is parameterised by delta (or log-moneyness normalised by ATM vol),
    so it translates rigidly with spot.
    """
    def __init__(self, S: float, r: float, q: float, deltas: np.ndarray, iv_smile: np.ndarray, T: float):
        self.S = S
        self.r = r
        self.q = q
        self.T = T
        self.F = S * np.exp((r - q) * T)
        self._delta_grid = deltas
        self._iv_smile = iv_smile
        self._smile_interp = CubicSpline(deltas, iv_smile, extrapolate=True)

    def iv_from_delta(self, delta: float) -> float:
        return float(np.clip(self._smile_interp(delta), 0.01, 5.0))

    def delta_to_strike(self, delta: float, S: float = None) -> float:
        S = S if S is not None else self.S
        F = S * np.exp((self.r - self.q) * self.T)

        def residual(K):
            iv = self.iv_from_delta(delta)
            d1 = (np.log(F / K) + 0.5 * iv**2 * self.T) / (iv * np.sqrt(self.T))
            return np.exp(-self.q * self.T) * norm.cdf(d1) - delta

        from scipy.optimize import brentq
        try:
            return brentq(residual, S * 0.3, S * 2.5, xtol=1e-4)
        except ValueError:
            iv_approx = self.iv_from_delta(delta)
            d1_approx = norm.ppf(delta * np.exp(self.q * self.T))
            return F * np.exp(-d1_approx * iv_approx * np.sqrt(self.T) + 0.5 * iv_approx**2 * self.T)

    def strike_to_delta(self, K: float, S: float = None) -> float:
        S = S if S is not None else self.S
        F = S * np.exp((self.r - self.q) * self.T)
        delta_guess = 0.5
        for _ in range(50):
            iv = self.iv_from_delta(delta_guess)
            d1 = (np.log(F / K) + 0.5 * iv**2 * self.T) / (iv * np.sqrt(self.T))
            delta_new = np.exp(-self.q * self.T) * norm.cdf(d1)
            if abs(delta_new - delta_guess) < 1e-8:
                break
            delta_guess = 0.5 * delta_guess + 0.5 * delta_new
        return delta_guess

    def _bs_greeks(self, S, K, T, sigma) -> Dict:
        F = S * np.exp((self.r - self.q) * T)
        d1 = (np.log(F / K) + 0.5 * sigma**2 * T) / (sigma * np.sqrt(T))
        d2 = d1 - sigma * np.sqrt(T)
        delta = np.exp(-self.q * T) * norm.cdf(d1)
        gamma = np.exp(-self.q * T) * norm.pdf(d1) / (S * sigma * np.sqrt(T))
        vega = S * np.exp(-self.q * T) * norm.pdf(d1) * np.sqrt(T)
        vanna = -np.exp(-self.q * T) * norm.pdf(d1) * d2 / sigma
        volga = vega * d1 * d2 / sigma
        theta = -(S * np.exp(-self.q * T) * norm.pdf(d1) * sigma / (2 * np.sqrt(T)) +
                  self.r * K * np.exp(-self.r * T) * norm.cdf(d2) -
                  self.q * S * np.exp(-self.q * T) * norm.cdf(d1)) / 365
        price = np.exp(-self.r * T) * (F * norm.cdf(d1) - K * norm.cdf(d2))
        return dict(d1=d1, d2=d2, delta=delta, gamma=gamma, vega=vega, vanna=vanna, volga=volga, theta=theta, price=price)

    def smile_adjusted_delta(self, K: float) -> float:
        delta_call = self.strike_to_delta(K)
        sigma = self.iv_from_delta(delta_call)
        g = self._bs_greeks(self.S, K, self.T, sigma)
        dsigma_ddelta = float(self._smile_interp(delta_call, 1))
        ddelta_dK = -np.exp(-self.q * self.T) * norm.pdf(g['d1']) / (sigma * np.sqrt(self.T) * K)
        dsigma_dK_sticky_delta = dsigma_ddelta * ddelta_dK
        delta_sa = g['delta'] + g['vega'] * dsigma_dK_sticky_delta
        return delta_sa

    def delta_hedge_comparison(self, strikes: np.ndarray) -> Dict:
        rows = []
        for K in strikes:
            delta_val = self.strike_to_delta(K)
            sigma = self.iv_from_delta(delta_val)
            g = self._bs_greeks(self.S, K, self.T, sigma)
            delta_ss = g['delta']
            delta_sd = self.smile_adjusted_delta(K)
            rows.append({
                'K': K,
                'delta': round(delta_val, 4),
                'IV': round(sigma * 100, 2),
                'BS_delta': round(delta_ss, 4),
                'SD_delta': round(delta_sd, 4),
                'correction': round(delta_sd - delta_ss, 6),
                'vega': round(g['vega'], 3),
                'vanna': round(g['vanna'], 5),
            })
        return rows

    def pnl_attribution(self, K: float, dS: float, dt: float, realized_vol: float = None) -> Dict:
        delta_val = self.strike_to_delta(K)
        sigma = self.iv_from_delta(delta_val)
        g = self._bs_greeks(self.S, K, self.T, sigma)
        h = K * 1e-4
        skew_slope = (self.iv_from_delta(self.strike_to_delta(K + h)) - self.iv_from_delta(self.strike_to_delta(K - h))) / (2 * h)
        d_sigma = -skew_slope * (K / self.S) * dS

        rv_component = 0.0
        if realized_vol is not None:
            d_sigma_rv = realized_vol - sigma
            rv_component = g['vega'] * d_sigma_rv * dt * 252

        pnl_gamma = 0.5 * g['gamma'] * dS**2
        pnl_theta = g['theta'] * dt
        pnl_vanna = g['vanna'] * dS * d_sigma
        pnl_volga = 0.5 * g['volga'] * d_sigma**2
        pnl_total = pnl_gamma + pnl_theta + pnl_vanna + pnl_volga + rv_component

        return {
            'K': K, 'sigma': sigma, 'dS': dS, 'd_sigma': d_sigma,
            'pnl_gamma': round(pnl_gamma, 6),
            'pnl_theta': round(pnl_theta, 6),
            'pnl_vanna': round(pnl_vanna, 6),
            'pnl_volga': round(pnl_volga, 6),
            'pnl_rv': round(rv_component, 6),
            'pnl_total': round(pnl_total, 6),
        }

class SABRModel:
    """
    SABR stochastic vol model (Hagan et al., 2002).
    Produces a sticky-delta smile naturally.
    """
    def __init__(self, F: float, T: float, alpha: float, beta: float, rho: float, nu: float):
        self.F = F
        self.T = T
        self.alpha = alpha
        self.beta = beta
        self.rho = rho
        self.nu = nu

    def hagan_iv(self, K: float) -> float:
        F, T = self.F, self.T
        alpha, beta, rho, nu = self.alpha, self.beta, self.rho, self.nu

        if abs(K - F) < 1e-8:
            term1 = (alpha / (F**(1 - beta) * (1 + ((1 - beta)**2 / 24) * alpha**2 / F**(2 - 2 * beta) * T + (rho * beta * nu * alpha) / (4 * F**(1 - beta)) * T + (2 - 3 * rho**2) / 24 * nu**2 * T)))
            return term1

        log_FK = np.log(F / K)
        FK_mid = (F * K)**((1 - beta) / 2)
        z = nu / alpha * FK_mid * log_FK
        chi_z = np.log((np.sqrt(1 - 2 * rho * z + z**2) + z - rho) / (1 - rho))

        prefac = alpha / (FK_mid * (1 + (1 - beta)**2 / 24 * log_FK**2 + (1 - beta)**4 / 1920 * log_FK**4))
        zchi = 1.0 if abs(chi_z) < 1e-10 else z / chi_z
        corr = (1 + ((1 - beta)**2 / 24 * alpha**2 / FK_mid**(2 - 2 * beta) + rho * beta * nu * alpha / (4 * FK_mid**(1 - beta)) + (2 - 3 * rho**2) / 24 * nu**2) * T)
        return prefac * zchi * corr

    def smile(self, strikes: np.ndarray) -> np.ndarray:
        return np.array([self.hagan_iv(K) for K in strikes])

    def fit(self, strikes: np.ndarray, iv_obs: np.ndarray, beta: float = 0.5) -> Dict:
        from scipy.optimize import minimize
        self.beta = beta

        def obj(params):
            a, r, n = params
            if a <= 0 or n <= 0 or abs(r) >= 1: return 1e10
            old_alpha, old_rho, old_nu = self.alpha, self.rho, self.nu
            self.alpha, self.rho, self.nu = a, r, n
            try:
                iv_fit = self.smile(strikes)
                res = np.sum((iv_fit - iv_obs)**2)
            except Exception:
                res = 1e10
            self.alpha, self.rho, self.nu = old_alpha, old_rho, old_nu
            return res

        x0 = [self.alpha, self.rho, self.nu]
        bounds = [(1e-4, 5.0), (-0.999, 0.999), (1e-4, 10.0)]
        result = minimize(obj, x0, method='L-BFGS-B', bounds=bounds)
        self.alpha, self.rho, self.nu = result.x
        iv_fit = self.smile(strikes)
        return {
            'alpha': self.alpha, 'rho': self.rho, 'nu': self.nu,
            'beta': beta,
            'iv_fit': iv_fit,
            'rmse': np.sqrt(np.mean((iv_fit - iv_obs)**2)) * 100,
        }

    def sabr_delta(self, K: float, S: float, T: float, r: float, q: float) -> float:
        F = S * np.exp((r - q) * T)
        old_F = self.F
        self.F = F
        sigma = self.hagan_iv(K)
        self.F = old_F
        d1 = (np.log(F / K) + 0.5 * sigma**2 * T) / (sigma * np.sqrt(T))
        return np.exp(-q * T) * norm.cdf(d1)

def backtest_sticky_vs_sticky_delta(S0: float, K: float, T: float, r: float, q: float, sigma_sabr_params: Dict, n_paths: int = 2000, n_steps: int = 63, seed: int = 0) -> Dict:
    np.random.seed(seed)
    dt = T / n_steps
    pnl_ss = np.zeros(n_paths)
    pnl_sd = np.zeros(n_paths)

    alpha = sigma_sabr_params['alpha']
    beta = sigma_sabr_params['beta']
    rho = sigma_sabr_params['rho']
    nu = sigma_sabr_params['nu']

    for p in range(n_paths):
        S_t = S0
        sig_t = alpha
        pos_ss = 0.0
        pos_sd = 0.0
        cash_ss = 0.0
        cash_sd = 0.0

        for step in range(n_steps):
            T_rem = T - step * dt
            dW1 = np.random.normal(0, np.sqrt(dt))
            dW2 = rho * dW1 + np.sqrt(max(1 - rho**2, 0)) * np.random.normal(0, np.sqrt(dt))

            dS = S_t * (r - q) * dt + sig_t * S_t**beta * dW1
            dsig = nu * sig_t * dW2
            S_t += dS
            sig_t = max(sig_t + dsig, 1e-4)

            if T_rem <= dt:
                break

            F_t = S_t * np.exp((r - q) * T_rem)
            sabr = SABRModel(F_t, T_rem, sig_t, beta, rho, nu)
            iv_ss = sabr.hagan_iv(K)
            d1_ss = (np.log(F_t / K) + 0.5 * iv_ss**2 * T_rem) / (iv_ss * np.sqrt(T_rem))
            delta_ss = np.exp(-q * T_rem) * norm.cdf(d1_ss)

            h = K * 0.005
            iv_up = sabr.hagan_iv(K + h)
            iv_dn = sabr.hagan_iv(K - h)
            dIV_dK = (iv_up - iv_dn) / (2 * h)
            vega_t = S_t * np.exp(-q * T_rem) * norm.pdf(d1_ss) * np.sqrt(T_rem)
            delta_sd = delta_ss + vega_t * dIV_dK * (-K / S_t)

            cash_ss += (pos_ss - delta_ss) * S_t
            cash_sd += (pos_sd - delta_sd) * S_t
            pos_ss = delta_ss
            pos_sd = delta_sd

        payoff = max(S_t - K, 0.0)
        pnl_ss[p] = payoff + cash_ss * np.exp(r * dt) + pos_ss * S_t
        pnl_sd[p] = payoff + cash_sd * np.exp(r * dt) + pos_sd * S_t

    return {
        'ss_mean_pnl': pnl_ss.mean(),
        'ss_std_pnl': pnl_ss.std(),
        'ss_rmse': np.sqrt(np.mean(pnl_ss**2)),
        'sd_mean_pnl': pnl_sd.mean(),
        'sd_std_pnl': pnl_sd.std(),
        'sd_rmse': np.sqrt(np.mean(pnl_sd**2)),
        'rmse_improvement': (np.sqrt(np.mean(pnl_ss**2)) - np.sqrt(np.mean(pnl_sd**2))) / np.sqrt(np.mean(pnl_ss**2)) * 100,
    }


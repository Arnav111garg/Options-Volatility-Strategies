import numpy as np
import pandas as pd
from arch import arch_model
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches
from scipy import stats
import yfinance as yf

def garch_forecast_with_ci(returns, h=63, n_sim=10000, quantiles=(0.05, 0.25, 0.75, 0.95)):
    """
    GARCH(1,1) h-step forecast with Monte Carlo confidence intervals.

    Parameters
    ----------
    returns : array of returns (in %)
    h : forecast horizon (days)
    n_sim : Monte Carlo simulations
    quantiles : tuple of quantiles for CI bands

    Returns
    -------
    dict with forecast paths and quantiles
    """
    # Fit GARCH(1,1) with t-innovations
    am = arch_model(returns, vol='GARCH', p=1, q=1, dist='t')
    res = am.fit(disp='off', show_warning=False)

    omega = res.params['omega']
    alpha = res.params['alpha[1]']
    beta = res.params['beta[1]']
    nu = res.params['nu'] # degrees of freedom for t-dist

    # FIXED: Use index [-1] to support both NumPy arrays and Pandas Series
    sigma2_0 = res.conditional_volatility[-1]**2
    long_run_var = omega / (1 - alpha - beta)
    persistence = alpha + beta

    # --- Closed-form h-step forecast ---
    horizons = np.arange(1, h + 1)
    cf_forecast = long_run_var + persistence**horizons * (sigma2_0 - long_run_var)
    cf_ann_vol = np.sqrt(cf_forecast * 252) * 100

    # --- Monte Carlo simulation of forecast paths ---
    np.random.seed(42)
    sigma2_paths = np.zeros((n_sim, h))

    # Innovations: draw from Student-t
    innovations = stats.t.rvs(df=nu, size=(n_sim, h))
    # Scale to unit variance: t(nu) has variance nu / (nu - 2)
    innovations = innovations / np.sqrt(nu / (nu - 2))

    for sim_idx in range(n_sim):
        s2 = sigma2_0
        for k in range(h):
            eps_k = innovations[sim_idx, k] * np.sqrt(s2)
            s2 = omega + alpha * eps_k**2 + beta * s2
            sigma2_paths[sim_idx, k] = s2

    # Annualized volatility paths
    vol_paths = np.sqrt(sigma2_paths * 252) * 100

    # Quantile bands
    vol_quantiles = {q: np.quantile(vol_paths, q, axis=0) for q in quantiles}
    vol_mean = np.mean(vol_paths, axis=0)
    vol_median = np.median(vol_paths, axis=0)

    # Integrated vol paths (average variance over 1..k)
    int_vol_paths = np.zeros((n_sim, h))
    for k in range(1, h + 1):
        int_vol_paths[:, k - 1] = np.sqrt(
            np.mean(sigma2_paths[:, :k], axis=1) * 252
        ) * 100
    int_vol_quantiles = {q: np.quantile(int_vol_paths, q, axis=0) for q in quantiles}

    return {
        'horizons': horizons,
        'cf_forecast': cf_ann_vol,
        'vol_mean': vol_mean,
        'vol_median': vol_median,
        'vol_quantiles': vol_quantiles,
        'int_vol_quantiles': int_vol_quantiles,
        'params': {'omega': omega, 'alpha': alpha, 'beta': beta, 'nu': nu},
        'sigma2_0': sigma2_0,
        'long_run_var': long_run_var,
        'persistence': persistence
    }

# ============================================================
# Run forecasts for multiple market regimes
# ============================================================
spy = yf.download('^GSPC', start='2000-01-01', end='2023-12-31', auto_adjust=True, progress=False)
rets_full = np.log(spy['Close']).diff().dropna() * 100

# Three epochs
epochs = {
    'Full Sample (2000-2023)': rets_full.values,
    'Pre-Crisis (2004-2007)': rets_full['2004':'2007'].values,
    'Post-COVID (2020-2023)': rets_full['2020':'2023'].values,
}

fig, axes = plt.subplots(1, 3, figsize=(18, 6))
fig.suptitle('GARCH(1,1) Volatility Forecasts: 63-Day Horizon with MC Confidence Intervals\n'
             'Point forecast (closed-form) + 90%/50% simulation bands',
             fontsize=12, fontweight='bold')

for ax, (epoch_name, epoch_rets) in zip(axes, epochs.items()):
    result = garch_forecast_with_ci(epoch_rets, h=63, n_sim=5000)

    h_ax = result['horizons']
    lr_vol = np.sqrt(result['long_run_var'] * 252) * 100
    cur_vol = np.sqrt(result['sigma2_0'] * 252) * 100

    # 90% band
    ax.fill_between(h_ax, result['vol_quantiles'][0.05], result['vol_quantiles'][0.95],
                    alpha=0.20, color='navy', label='90% Simulation Band')
    # 50% band
    ax.fill_between(h_ax, result['vol_quantiles'][0.25], result['vol_quantiles'][0.75],
                    alpha=0.35, color='navy', label='50% Simulation Band')
    # Closed-form forecast
    ax.plot(h_ax, result['cf_forecast'], color='darkred', linewidth=2.5, label='Closed-Form Forecast')
    # Median simulation
    ax.plot(h_ax, result['vol_median'], color='red', linewidth=1.5, linestyle=':', label='Simulation Median')
    # Long-run level
    ax.axhline(lr_vol, color='black', linewidth=1.5, linestyle='--', alpha=0.7, label=f'Long-run: {lr_vol:.1f}%')
    # Current
    ax.axhline(cur_vol, color='darkgreen', linewidth=1.0, linestyle=':', alpha=0.7, label=f'Current: {cur_vol:.1f}%')

    p = result['params']
    ax.set_title(f'{epoch_name}\n'
                 f'$\alpha$={p["alpha"]:.3f}, $\beta$={p["beta"]:.3f}, $\nu$={p["nu"]:.1f}\n'
                 f'Persistence={result["persistence"]:.4f}',
                 fontsize=9, fontweight='bold')
    ax.set_xlabel('Forecast Horizon (Days)', fontsize=9)
    ax.set_ylabel('Annualized Volatility (%)', fontsize=9)
    ax.legend(fontsize=7, loc='upper right')
    ax.grid(True, alpha=0.3)

    # Mark option maturities
    for mat, name in [(21, '1M'), (63, '3M')]:
        if mat <= 63:
            ax.axvline(mat, color='orange', linestyle=':', alpha=0.5)
            ax.text(mat + 0.5, ax.get_ylim()[1] * 0.97, name, fontsize=8, color='orange')

plt.tight_layout()
plt.savefig('garch_forecasts.png', dpi=150, bbox_inches='tight')
plt.show()


import numpy as np
import pandas as pd
from scipy.optimize import minimize
from scipy import stats
import matplotlib.pyplot as plt
import matplotlib.gridspec as gridspec
import warnings
warnings.filterwarnings('ignore')

# ============================================================
# GARCH (1 ,1) Class : Manual MLE
# ============================================================
class GARCH11:
    """
    GARCH (1 ,1) model with Gaussian QMLE .

    Model :
    r_t = mu + eps_t
    eps_t = sigma_t * z_t , z_t ~ N(0 ,1)
    sigma_t ^2 = omega + alpha * eps_ {t -1}^2 + beta * sigma_ {t -1}^2
    """

    def __init__(self):
        self.params_ = None
        self.sigma2_ = None
        self.residuals_ = None
        self.loglik_ = None

    def _compute_variance(self, params, returns):
        """ Recursively compute conditional variance sequence ."""
        mu, omega, alpha, beta = params
        T = len(returns)
        eps = returns - mu
        sigma2 = np.zeros(T)

        # Initialize with sample variance
        sigma2[0] = np.var(eps)

        for t in range(1, T):
            sigma2[t] = omega + alpha * eps[t-1]**2 + beta * sigma2[t-1]

        return sigma2, eps

    def _neg_loglikelihood(self, params, returns):
        """ Negative Gaussian quasi -log - likelihood ."""
        mu, omega, alpha, beta = params

        # Parameter constraints ( interior penalty )
        if omega <= 0 or alpha < 0 or beta < 0 or alpha + beta >= 1:
            return 1e10

        sigma2, eps = self._compute_variance(params, returns)

        # Avoid numerical issues
        sigma2 = np.maximum(sigma2, 1e-8)

        # Log - likelihood ( Gaussian )
        ll = -0.5 * np.sum(np.log(2 * np.pi * sigma2) + eps**2 / sigma2)
        return -ll # Return negative for minimization

    def fit(self, returns, verbose=True):
        """ Fit GARCH (1 ,1) via numerical MLE ."""
        returns = np.asarray(returns).flatten()
        T = len(returns)

        # Initial parameters : [mu , omega , alpha , beta ]
        mu0 = np.mean(returns)
        var0 = np.var(returns)

        # Bounds : omega > 0 , alpha >= 0 , beta >= 0
        bounds = [
            (None, None),     # mu: unconstrained
            (1e-8, None),     # omega > 0
            (1e-6, 0.999),    # 0 <= alpha < 1
            (1e-6, 0.999),    # 0 <= beta < 1
        ]

        # Multiple starting points for robustness
        best_result = None
        best_ll = np.inf

        start_points = [
            [mu0, var0 * 0.05, 0.08, 0.88],
            [mu0, var0 * 0.10, 0.10, 0.85],
            [mu0, var0 * 0.02, 0.05, 0.90],
        ]

        for x0 in start_points:
            result = minimize(
                self._neg_loglikelihood, x0, args=(returns,),
                method='L-BFGS-B', bounds=bounds,
                options={'maxiter': 5000, 'ftol': 1e-12}
            )
            if result.fun < best_ll:
                best_ll = result.fun
                best_result = result

        self.params_ = best_result.x
        self.loglik_ = -best_ll
        self.sigma2_, self.residuals_ = self._compute_variance(
            self.params_, returns
        )

        # Compute standard errors via Hessian ( numerical )
        from scipy.optimize import approx_fprime
        eps_h = 1e-5
        hess = np.zeros((4, 4))
        grad = lambda p: approx_fprime(
            p, self._neg_loglikelihood, eps_h, returns
        )
        for i in range(4):
            e_i = np.zeros(4)
            e_i[i] = eps_h
            hess[i] = (grad(self.params_ + e_i) - grad(self.params_ - e_i)) / (2 * eps_h)

        try:
            cov_matrix = np.linalg.inv(hess) / T
            self.std_errors_ = np.sqrt(np.diag(cov_matrix))
        except np.linalg.LinAlgError:
            self.std_errors_ = np.full(4, np.nan)

        if verbose:
            self._print_results(T)

        return self

    def _print_results(self, T):
        """ Print formatted results table ."""
        mu, omega, alpha, beta = self.params_
        se = self.std_errors_
        names = ['mu', 'omega', 'alpha', 'beta']

        print("=" * 65)
        print(f"{' GARCH (1 ,1) Estimation Results ':^65}")
        print("=" * 65)
        print(f"{' Observations ': >25}: {T}")
        print(f"{'Log - Likelihood ': >25}: {self.loglik_:.4f}")
        print(f"{'AIC ': >25}: {-2*self.loglik_ + 2*4:.4f}")
        print(f"{'BIC ': >25}: {-2*self.loglik_ + np.log(T) * 4:.4f}")
        print("-" * 65)
        print(f"{' Parameter ': >12} {' Estimate ': >12} {'Std .Err ': >12} "
              f"{'t- stat ': >10} {'p- value ': >10}")
        print("-" * 65)
        for name, est, se_val in zip(names, self.params_, se):
            t_stat = est / se_val if se_val > 0 else np.nan
            p_val = 2 * (1 - stats.norm.cdf(abs(t_stat)))
            stars = ('***' if p_val < 0.001 else '**' if p_val < 0.01
                     else '*' if p_val < 0.05 else '')
            print(f"{name: >12} {est: >12.6f} {se_val: >12.6f} "
                  f"{t_stat: >10.3f} {p_val: >10.4f} {stars}")
        print("=" * 65)
        print(f"{' alpha + beta ': >25}: {alpha + beta:.6f} ( persistence )")
        uncond_var = omega / (1 - alpha - beta)
        uncond_vol_ann = np.sqrt(uncond_var * 252) * 100
        print(f"{'Long -run variance ( daily ) ': >25}: {uncond_var:.6f}")
        print(f"{'Long -run vol ( annualized ) ': >25}: {uncond_vol_ann:.2f}%")
        print("=" * 65)

    def forecast(self, h=22):
        """
        h- step ahead variance forecast from current time T.
        Returns array of shape (h ,): sigma ^2_{T+1} , ... , sigma ^2_{T+h}.
        """
        mu, omega, alpha, beta = self.params_
        persistence = alpha + beta
        long_run_var = omega / (1 - persistence)

        sigma2_T = self.sigma2_[-1]
        forecasts = np.zeros(h)

        for k in range(1, h + 1):
            # E[ sigma ^2_{T+k} | F_T ] = long_run_var + persistence ^k * ( sigma ^2 _T - long_run_var )
            forecasts[k - 1] = (long_run_var + (persistence ** k) * (sigma2_T - long_run_var))

        return forecasts

    def annualized_vol(self):
        """ Return annualized conditional volatility series ."""
        return np.sqrt(self.sigma2_ * 252) * 100


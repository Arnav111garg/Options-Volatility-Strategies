# EXAMPLE : Fit GARCH (1 ,1) to S&P 500
# ============================================================
import yfinance as yf

spy = yf.download('^GSPC', start='2010-01-01', end='2023-12-31',
                  auto_adjust=True, progress=False)
# Squeeze the series to make it 1-dimensional
returns = np.log(spy['Close']).diff().dropna().squeeze().values * 100

model = GARCH11()
model.fit(returns)

# ============================================================
# COMPREHENSIVE DIAGNOSTIC PLOTS
# ============================================================
fig = plt.figure(figsize=(16, 12))
gs = gridspec.GridSpec(3, 2, figure=fig, hspace=0.4, wspace=0.35)
fig.suptitle('GARCH (1 ,1) Model Diagnostics S&P 500',
             fontsize=14, fontweight='bold', color='navy')

dates = spy.index[1:]

# 1. Returns and Conditional Volatility
ax1 = fig.add_subplot(gs[0, :])
ax1_twin = ax1.twinx()
ax1.fill_between(dates, returns, 0, alpha=0.3, color='navy', label='Returns')
ax1_twin.plot(dates, model.annualized_vol(), color='darkred',
              linewidth=1.0, label='GARCH Vol (Ann .)', alpha=0.8)
ax1.set_ylabel('Return (%)', color='navy')
ax1.tick_params(axis='y', colors='navy')
ax1_twin.set_ylabel('Annualized Vol (%)', color='darkred')
ax1_twin.tick_params(axis='y', colors='darkred')
ax1.set_title('S&P 500 Returns vs. GARCH (1 ,1) Conditional Volatility',
              fontweight='bold')
lines1, labels1 = ax1.get_legend_handles_labels()
lines2, labels2 = ax1_twin.get_legend_handles_labels()
ax1.legend(lines1 + lines2, labels1 + labels2, loc='upper right')

# 2. Standardized residuals
std_resid = model.residuals_ / np.sqrt(model.sigma2_)
ax2 = fig.add_subplot(gs[1, 0])
ax2.plot(dates, std_resid, color='navy', linewidth=0.4, alpha=0.7)
ax2.axhline(0, color='red', linestyle='--')
ax2.axhline(3, color='orange', linestyle=':', label='+/- 3 sigma')
ax2.axhline(-3, color='orange', linestyle=':')
ax2.set_title('Standardized Residuals', fontweight='bold')
ax2.set_ylabel('$\\hat{z}_t = \\hat{\\epsilon}_t / \\hat{\\sigma}_t$')
ax2.legend()

# 3. QQ - plot of standardized residuals
ax3 = fig.add_subplot(gs[1, 1])
stats.probplot(std_resid, dist="norm", plot=ax3)
ax3.set_title('Q-Q Plot of Standardized Residuals', fontweight='bold')
ax3.get_lines()[0].set(markersize=1.5, alpha=0.5, color='navy')

# 4. ACF of standardized residuals
from statsmodels.graphics.tsaplots import plot_acf
ax4 = fig.add_subplot(gs[2, 0])
plot_acf(std_resid**2, lags=30, ax=ax4, color='darkred', alpha=0.05)
ax4.set_title('ACF of Squared Standardized Residuals', fontweight='bold')

# 5. Volatility forecast
ax5 = fig.add_subplot(gs[2, 1])
h = 66 # 3 months
fcast = model.forecast(h=h)
fcast_vol = np.sqrt(fcast * 252) * 100
mu, omega, alpha, beta = model.params_
long_run_vol = np.sqrt(omega / (1 - alpha - beta) * 252) * 100
current_vol = model.annualized_vol()[-1]

ax5.plot(range(1, h + 1), fcast_vol, color='darkblue', linewidth=2,
         label='GARCH Forecast')
ax5.axhline(long_run_vol, color='red', linestyle='--', linewidth=1.5,
            label=f'Long -run : {long_run_vol:.1f}%')
ax5.axhline(current_vol, color='green', linestyle=':', linewidth=1.5,
            label=f'Current : {current_vol:.1f}%')
ax5.set_xlabel('Days ahead')
ax5.set_ylabel('Forecast Vol (%)')
ax5.set_title('66 - Day GARCH (1 ,1) Volatility Forecast', fontweight='bold')
ax5.legend()

plt.savefig('garch11_diagnostics.png', dpi=150, bbox_inches='tight')
plt.show()


import numpy as np
import pandas as pd
from arch import arch_model
import matplotlib.pyplot as plt
import yfinance as yf
import warnings
warnings.filterwarnings('ignore')

# 1. Download S&P 500 Data
spy = yf.download('^GSPC', start='2000-01-01', end='2023-12-31', auto_adjust=True, progress=False)
rets = np.log(spy['Close']).diff().dropna().squeeze() * 100

# 2. Rolling GARCH(1,1) Estimation
window = 252  # 1-year rolling window
dates = rets.index[window:]
persistence_list = []
alpha_list, beta_list = [], []

for i in range(len(dates)):
    sub = rets.iloc[i : i + window].values
    try:
        am = arch_model(sub, vol='GARCH', p=1, q=1, dist='Normal', rescale=False)
        res = am.fit(disp='off', show_warning=False)
        a = res.params['alpha[1]']
        b = res.params['beta[1]']
        persistence_list.append(a + b)
        alpha_list.append(a)
        beta_list.append(b)
    except Exception:
        persistence_list.append(np.nan)
        alpha_list.append(np.nan)
        beta_list.append(np.nan)

persistence_series = pd.Series(persistence_list, index=dates)
alpha_series = pd.Series(alpha_list, index=dates)
beta_series = pd.Series(beta_list, index=dates)

# 3. Create Diagnostic Plots
fig, axes = plt.subplots(3, 1, figsize=(14, 10), sharex=True)
fig.suptitle('Rolling GARCH(1,1) Parameter Estimates S&P 500\n(252-Day Rolling Window)', fontsize=12, fontweight='bold')

for ax, series, name, color in zip(
    axes,
    [persistence_series, alpha_series, beta_series],
    ['Persistence (alpha + beta)', 'Alpha (ARCH)', 'Beta (GARCH)'],
    ['navy', 'darkred', 'darkgreen']
):
    ax.plot(series, color=color, linewidth=0.8, alpha=0.9)
    ax.axhline(series.median(), color=color, linestyle='--', linewidth=1.2, alpha=0.6, label=f'Median: {series.median():.3f}')
    ax.set_ylabel(name, fontsize=10)
    ax.legend(loc='lower right', fontsize=9)
    ax.grid(True, alpha=0.3)

    # Add recession shading (2008 Financial Crisis, 2020 COVID crash)
    ax.axvspan(pd.Timestamp('2008-01-01'), pd.Timestamp('2009-06-30'), alpha=0.1, color='red')
    ax.axvspan(pd.Timestamp('2020-02-01'), pd.Timestamp('2020-06-30'), alpha=0.1, color='orange')

plt.tight_layout()
plt.savefig('rolling_persistence.png', dpi=150, bbox_inches='tight')
plt.show()

# 4. Print Summary Statistics
print("\nPersistence Summary Statistics:")
print(persistence_series.describe().round(4))
print(f"\nCorr(alpha, beta): {alpha_series.corr(beta_series):.3f}")


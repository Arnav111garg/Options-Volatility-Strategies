# ============================================================
# Simulate RV from OHLC (Rogers - Satchell estimator )
# (In production , use actual 5 -min data from Bloomberg / Refinitiv )
# ============================================================
def rogers_satchell_rv ( open_p , high_p , low_p , close_p ) :
    """
    Rogers - Satchell (1991) volatility estimator from OHLC prices .
    More efficient than squared close -to - close returns .

    RV_RS = ln(H/C) * ln(H/O) + ln(L/C) * ln(L/O)
    """
    h_c = np.log ( high_p / close_p )
    h_o = np.log ( high_p / open_p )
    l_c = np.log ( low_p / close_p )
    l_o = np.log ( low_p / open_p )
    return h_c * h_o + l_c * l_o # Daily variance estimate

spy_ohlc = yf.download ('^GSPC', start='2000-01-01', end='2023-12-31', auto_adjust=True, progress=False)

rv_daily = rogers_satchell_rv (
    spy_ohlc['Open'].values ,
    spy_ohlc['High'].values ,
    spy_ohlc['Low'].values ,
    spy_ohlc['Close'].values
) * 252 # Annualized

log_rets = np.log ( spy_ohlc['Close']) . diff () . dropna () . values * 100
dates = spy_ohlc.index [1:]

# Align
rv_daily = rv_daily [1:] # Align with returns ( skip first day )
T = len( log_rets )

# ============================================================
# HAR -RV Model
# ============================================================
def build_har_features ( rv , d =1 , w =5 , m =22) :
    """ Build HAR -RV feature matrix ."""
    T = len( rv )
    max_lag = m
    n = T - max_lag

    X = np.ones (( n , 4) ) # [1 , RV_d , RV_w , RV_m ]
    y = np.zeros ( n )

    for i in range ( n ) :
        t = i + max_lag
        X [i , 1] = rv [t - d ] # Daily
        X [i , 2] = np.mean ( rv [t - w : t ]) # Weekly
        X [i , 3] = np.mean ( rv [t - m : t ]) # Monthly
        y [ i ] = rv [ t ] # Target : next -day RV

    return X , y

X_har , y_har = build_har_features ( rv_daily )
n = len( y_har )

# Train - test split ( last 20% = test )
split = int (0.8 * n )
X_train , X_test = X_har [: split ] , X_har [ split :]
y_train , y_test = y_har [: split ] , y_har [ split :]

# Fit HAR -RV by OLS
beta_har = np.linalg.lstsq ( X_train , y_train , rcond = None ) [0]
har_fcast = X_test @ beta_har

print ("HAR -RV Coefficients :")
for name , val in zip ([ 'const', 'phi_D', 'phi_W', 'phi_M' ] , beta_har ) :
    print ( f" { name }: {val :.4f}")

# ============================================================
# GARCH (1 ,1) rolling 1 - step forecasts
# ============================================================
def rolling_garch_forecast ( returns , test_start_idx , dist ='t') :
    """ Rolling window GARCH 1 - step ahead forecasts ."""
    forecasts = []
    train_rets = returns [: test_start_idx ]

    am = arch_model ( train_rets , vol ='GARCH', p =1 , q =1 , dist = dist )
    res = am.fit ( disp ='off', show_warning = False )

    for t in range ( test_start_idx , len ( returns ) ) :
        # Re - fit every 21 days , otherwise just update
        if ( t - test_start_idx ) % 21 == 0:
            am = arch_model ( returns [: t ] , vol ='GARCH', p =1 , q =1 , dist = dist )
            res = am.fit ( disp ='off', show_warning = False )

        fcast = res.forecast ( horizon =1 , reindex = False )
        var_fcast = fcast.variance.iloc [ -1 , 0]
        forecasts.append ( var_fcast )

    return np.array ( forecasts ) * 252 # Annualized

# Only run on subset for speed
test_start = int (0.8 * T )
garch_fcast_ann = rolling_garch_forecast ( log_rets , test_start , dist ='t') [: len ( y_test ) ]

# ============================================================
# Evaluation : MSE , QLIKE , R- squared
# ============================================================
def qlike ( actual , forecast ) :
    """ QLIKE loss : preferred for vol model comparison ( Patton 2011) ."""
    ratio = actual / forecast
    return np.mean ( ratio - np.log ( ratio ) - 1)

y_test_aligned = y_test [: len ( garch_fcast_ann ) ]
har_aligned = har_fcast [: len ( garch_fcast_ann ) ]

results = {}
for name , fcast in [('GARCH(1,1)', garch_fcast_ann ) , ('HAR-RV', har_aligned ) ]:
    mse = np.mean (( y_test_aligned - fcast ) **2)
    ql = qlike ( np.maximum ( y_test_aligned , 1e-8) , np.maximum ( fcast , 1e-8) )
    # Mincer - Zarnowitz regression
    mz_X = np.column_stack ([ np.ones (len ( fcast ) ) , fcast ])
    mz_beta = np.linalg.lstsq ( mz_X , y_test_aligned , rcond = None ) [0]
    ss_res = np.sum (( y_test_aligned - mz_X @ mz_beta ) **2)
    ss_tot = np.sum (( y_test_aligned - np.mean ( y_test_aligned ) ) **2)
    R2_mz = 1 - ss_res / ss_tot

    results [ name ] = {'MSE': mse , 'QLIKE': ql , 'R2_MZ': R2_mz , 'alpha_MZ': mz_beta [0] , 'beta_MZ': mz_beta [1]}

print ("\n" + "=" * 65)
print ( f"{'Volatility Forecast Model Comparison':^65} ")
print ("=" * 65)
print ( f"{'Model':>15} {'MSE':>10} {'QLIKE':>10} {'R2 (MZ)':>10} {'alpha':>8} {'beta':>8}")
print ("-" * 65)
for name , m in results.items () :
    print ( f"{name:>15} {m['MSE']:>10.4f} {m['QLIKE']:>10.4f} {m['R2_MZ']:>10.4f} {m['alpha_MZ']:>8.3f} {m['beta_MZ']:>8.3f}")

print ("=" * 65)
print ("MZ test : unbiased forecast => alpha=0, beta=1 (Mincer-Zarnowitz)")


import numpy as np
import pandas as pd
from arch import arch_model
import matplotlib.pyplot as plt
import yfinance as yf
import warnings
warnings.filterwarnings('ignore')

spy = yf.download('^GSPC', start='2005-01-01', end='2023-12-31', auto_adjust=True, progress=False)
rets = np.log(spy['Close']).diff().dropna().squeeze() * 100

# Fit GARCH(1,1)
garch_model = arch_model(rets, vol='GARCH', p=1, q=1, dist='t')
garch_res = garch_model.fit(disp='off', show_warning=False)

# Fit IGARCH(1,1) (equivalent to an EWMA style GARCH with fixed persistence = 1.0)
# To cleanly model IGARCH without using unsupported fit constraints, we fit GARCH and simulate the unit-root
# or represent it directly using EWMA (where persistence is constrained to 1).
igarch_model = arch_model(rets, vol='GARCH', p=1, q=1, dist='t')
igarch_res = igarch_model.fit(disp='off', show_warning=False)

# Compare parameters
params_df = pd.DataFrame({
    'GARCH(1,1)': garch_res.params,
    'IGARCH(1,1) (Unconstrained)': igarch_res.params
}).round(6)
print("Parameter Comparison:")
print(params_df)

alpha_g = garch_res.params['alpha[1]']
beta_g = garch_res.params['beta[1]']
omega_g = garch_res.params['omega']

# Compare 1-year forecasts: GARCH vs IGARCH (where alpha + beta = 1)
h = 252
sigma2_T = garch_res.conditional_volatility.iloc[-1]**2
long_run_var = omega_g / (1 - alpha_g - beta_g)

garch_fcast = np.array([
    long_run_var + (alpha_g + beta_g) ** k * (sigma2_T - long_run_var)
    for k in range(1, h + 1)
])

# IGARCH forecast: alpha + beta is set to 1.0, meaning volatility has a permanent unit-root step.
# We set omega_i close to zero and sum alpha_i + beta_i = 1.
alpha_i = 0.06
beta_i = 0.94
omega_i = 0.00
igarch_fcast = np.array([
    sigma2_T + k * omega_i
    for k in range(1, h + 1)
])

fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(13, 5))
fig.suptitle('GARCH(1,1) vs IGARCH(1,1): Forecast Comparison', fontsize=12, fontweight='bold')

horizons = np.arange(1, h + 1)
ax1.plot(horizons, np.sqrt(garch_fcast * 252), color='navy', linewidth=2, label='GARCH(1,1)')
ax1.plot(horizons, np.sqrt(igarch_fcast * 252), color='darkred', linewidth=2, linestyle='--', label='IGARCH(1,1)')
ax1.axhline(np.sqrt(long_run_var * 252), color='navy', linestyle=':', alpha=0.7, label='GARCH long-run')
ax1.set_xlabel('Horizon (Days)')
ax1.set_ylabel('Forecast Vol (%)')
ax1.set_title('Volatility Forecasts')
ax1.legend()
ax1.grid(True, alpha=0.3)

# Conditional volatility comparison
ax2.plot(garch_res.conditional_volatility[-500:] * np.sqrt(252), color='navy', linewidth=1, alpha=0.8, label='GARCH(1,1)')
ax2.plot(igarch_res.conditional_volatility[-500:] * np.sqrt(252), color='darkred', linewidth=1, alpha=0.6, linestyle='--', label='IGARCH(1,1) proxy')
ax2.set_xlabel('Trading Days (Last 500)')
ax2.set_ylabel('Annualized Vol (%)')
ax2.set_title('Conditional Volatility (Last 500 Days)')
ax2.legend()
ax2.grid(True, alpha=0.3)

plt.tight_layout()
plt.savefig('igarch_comparison.png', dpi=150, bbox_inches='tight')
plt.show()


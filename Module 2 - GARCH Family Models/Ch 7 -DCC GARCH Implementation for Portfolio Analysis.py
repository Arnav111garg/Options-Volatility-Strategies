# DCC - GARCH Implementation
# ============================================================
class DCC_GARCH:
    """
    Two-asset DCC-GARCH (1,1) implementation.
    Reference: Engle (2002), J. Business & Economic Statistics.
    """

    def __init__(self):
        self.garch_results = []
        self.std_resids = None
        self.Q_bar = None
        self.dcc_params = None
        self.R_t = None
        self.H_t = None

    def fit_individual_garch(self, returns_df, dist='t'):
        """ Step 1: Fit univariate GARCH to each asset using a Pandas DataFrame."""
        N = returns_df.shape[1]
        self.garch_results = []
        std_resids_list = []
        cond_vols = []

        for i in range(N):
            r = returns_df.iloc[:, i]
            am = arch_model(r, vol='GARCH', p=1, q=1, dist=dist)
            res = am.fit(disp='off', show_warning=False)
            self.garch_results.append(res)
            std_resids_list.append((res.resid / res.conditional_volatility).values)
            cond_vols.append(res.conditional_volatility.values)

        self.std_resids = np.column_stack(std_resids_list)
        self.cond_vols = np.column_stack(cond_vols)
        self.Q_bar = np.cov(self.std_resids.T)
        return self

    def _dcc_neg_loglik(self, params, std_resids, Q_bar):
        """ DCC negative log-likelihood ."""
        a, b = params
        if a < 0 or b < 0 or a + b >= 1:
            return 1e10

        T, N = std_resids.shape
        Q_t = Q_bar.copy()
        ll = 0.0

        for t in range(1, T):
            z = std_resids[t-1]
            Q_t = ((1 - a - b) * Q_bar
                   + a * np.outer(z, z)
                   + b * Q_t)
            # Normalize to correlation matrix
            d = np.sqrt(np.diag(Q_t))
            R_t = Q_t / np.outer(d, d)
            R_t = np.clip(R_t, -0.9999, 0.9999)
            np.fill_diagonal(R_t, 1.0)

            # DCC log-likelihood contribution
            sign, logdet = np.linalg.slogdet(R_t)
            if sign <= 0:
                return 1e10
            z_t = std_resids[t]
            try:
                R_inv = np.linalg.inv(R_t)
                ll += -0.5 * (logdet + z_t @ R_inv @ z_t - z_t @ z_t)
            except np.linalg.LinAlgError:
                return 1e10
        return -ll

    def fit_dcc(self):
        """ Step 2: Estimate DCC parameters ."""
        result = minimize(
            self._dcc_neg_loglik,
            x0=[0.05, 0.90],
            args=(self.std_resids, self.Q_bar),
            method='L-BFGS-B',
            bounds=[(1e-6, 0.499), (1e-6, 0.999)]
        )
        self.dcc_params = result.x
        a, b = self.dcc_params
        print(f"DCC parameters: a={a:.4f}, b={b:.4f} (a+b={a+b:.4f})")
        self._compute_dynamic_correlations()
        return self

    def _compute_dynamic_correlations(self):
        """ Compute full time series of dynamic correlations ."""
        a, b = self.dcc_params
        T, N = self.std_resids.shape
        Q_t = self.Q_bar.copy()

        self.R_t = np.zeros((T, N, N))
        self.corr_t = np.zeros(T)

        for t in range(T):
            if t > 0:
                z = self.std_resids[t-1]
                Q_t = ((1 - a - b) * self.Q_bar
                       + a * np.outer(z, z)
                       + b * Q_t)
            d = np.sqrt(np.diag(Q_t))
            R_t = Q_t / np.outer(d, d)
            np.fill_diagonal(R_t, 1.0)
            self.R_t[t] = R_t
            # Store off-diagonal (for 2-asset case)
            if N == 2:
                self.corr_t[t] = R_t[0, 1]

        return self

    def portfolio_risk(self, weights):
        """
        Compute time-varying portfolio variance for given weights.

        Parameters
        ----------
        weights : array of shape (N,)

        Returns
        -------
        port_var : array of shape (T,) conditional portfolio variance
        """
        T = len(self.corr_t)
        N = len(weights)
        port_var = np.zeros(T)

        for t in range(T):
            # Conditional covariance matrix
            D_t = np.diag(self.cond_vols[t])
            H_t = D_t @ self.R_t[t] @ D_t
            port_var[t] = weights @ H_t @ weights

        return port_var


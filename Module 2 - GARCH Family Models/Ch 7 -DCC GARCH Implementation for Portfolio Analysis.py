T = len(log_rets)
dates = log_rets.index

fig, axes = plt.subplots(3, 1, figsize=(14, 11), sharex=True)
fig.suptitle('DCC-GARCH (1,1): SPY & TLT Dynamic Correlation\nEngle (2002) Two-Stage MLE', fontsize=12, fontweight='bold')

# 1. Dynamic correlation
ax1 = axes[0]
ax1.plot(dates, dcc.corr_t, color='navy', linewidth=1.0, alpha=0.85, label='DCC Correlation')

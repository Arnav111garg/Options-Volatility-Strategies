tickers = ['^GSPC', 'TLT']
data = yf.download(tickers, start='2010-01-01', end='2023-12-31', auto_adjust=True, progress=False)['Close']
log_rets = np.log(data).diff().dropna() * 100
log_rets.columns = ['SPY', 'TLT']

print("DCC-GARCH Estimation: SPY + TLT")
print("=" * 50)

dcc = DCC_GARCH()
dcc.fit_individual_garch(log_rets)
dcc.fit_dcc()


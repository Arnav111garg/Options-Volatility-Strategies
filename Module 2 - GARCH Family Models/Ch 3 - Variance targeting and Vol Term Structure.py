import numpy as np
import pandas as pd
from arch import arch_model
import matplotlib.pyplot as plt
import yfinance as yf
import warnings
warnings.filterwarnings('ignore')

def garch_variance_term_structure(alpha, beta, sigma2_0, omega, max_horizon=252):
    """
    Compute GARCH(1,1) variance term structure correctly scaled.
    Returns annualized vol term structure for horizons 1..max_horizon days.
    """
    persistence = alpha + beta
    long_run_var = omega / (1 - persistence)
    horizons = np.arange(1, max_horizon + 1)

    # h-step ahead forecast: variance
    var_h = long_run_var + (persistence ** horizons) * (sigma2_0 - long_run_var)

    # Annualized vol (single-period forward vol at each horizon)
    # Correct scaling: since returns are in %, variance is already %^2. Just multiply by 252 and take sqrt.
    vol_h_annualized = np.sqrt(var_h * 252)

    # Cumulative / average vol (relevant for options pricing)
    cumulative_var = np.array([
        long_run_var * h + (sigma2_0 - long_run_var) * (1 - persistence ** h) / (1 - persistence)
        for h in horizons
    ])
    avg_var_h = cumulative_var / horizons
    vol_avg_annualized = np.sqrt(avg_var_h * 252)

    return horizons, vol_h_annualized, vol_avg_annualized, long_run_var

# Fit model
spy = yf.download('^GSPC', start='2018-01-01', end='2023-12-31', auto_adjust=True, progress=False)
rets = np.log(spy['Close']).diff().dropna().squeeze() * 100

am = arch_model(rets, vol='GARCH', p=1, q=1, dist='t', rescale=False)
res = am.fit(disp='off', show_warning=False)
print(res.summary())

alpha = res.params['alpha[1]']
beta = res.params['beta[1]']
omega = res.params['omega']
sigma2_0 = res.conditional_volatility.iloc[-1]**2

# Three scenarios: current vol above / below / at long-run
long_run_var = omega / (1 - alpha - beta)
long_run_vol_ann = np.sqrt(long_run_var * 252)
current_vol_ann = np.sqrt(sigma2_0 * 252)

print(f"\nLong-run volatility: {long_run_vol_ann:.2f}% (annualized)")
print(f"Current volatility: {current_vol_ann:.2f}% (annualized)")
print(f"Persistence: {alpha + beta:.4f}")
print(f"Half-life: {np.log(0.5) / np.log(alpha + beta):.1f} days")

scenarios = {
    f'High vol (2x LR): {2*long_run_vol_ann:.1f}%': 4 * long_run_var,
    f'Current vol: {current_vol_ann:.1f}%': sigma2_0,
    f'Low vol (0.5x LR): {0.5*long_run_vol_ann:.1f}%': 0.25 * long_run_var,
}

fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 6))
fig.suptitle(f'GARCH(1,1) Volatility Term Structure S&P 500\n'
             f'\\alpha={alpha:.3f}, \\beta={beta:.3f}, \\alpha+\\beta={alpha+beta:.4f}',
             fontsize=12, fontweight='bold')

colors = ['darkred', 'navy', 'darkgreen']
for (label, s2), color in zip(scenarios.items(), colors):
    hs, fwd_vol, avg_vol, _ = garch_variance_term_structure(alpha, beta, s2, omega, max_horizon=252)
    ax1.plot(hs, fwd_vol, color=color, linewidth=2, label=label)
    ax2.plot(hs, avg_vol, color=color, linewidth=2, label=label)

ax1.axhline(long_run_vol_ann, color='black', linestyle='--', linewidth=1.5, alpha=0.7, label=f'Long-run: {long_run_vol_ann:.1f}%')
ax2.axhline(long_run_vol_ann, color='black', linestyle='--', linewidth=1.5, alpha=0.7, label=f'Long-run: {long_run_vol_ann:.1f}%')

for ax, title in zip([ax1, ax2],
                     ['Forward Variance (Instantaneous)',
                      'Average Variance (Relevant for Options)']):
    ax.set_xlabel('Horizon (Days)', fontsize=10)
    ax.set_ylabel('Annualized Volatility (%)', fontsize=10)
    ax.set_title(title, fontweight='bold')
    ax.legend(fontsize=8)
    ax.grid(True, alpha=0.3)

    # Mark standard option maturities
    for mat, name in [(21, '1M'), (63, '3M'), (126, '6M'), (252, '1Y')]:
        ax.axvline(mat, color='gray', linestyle=':', alpha=0.5)
        ax.text(mat, ax.get_ylim()[1] * 0.95, name, ha='center', fontsize=8, color='gray')

plt.tight_layout()
plt.savefig('garch_term_structure.png', dpi=150, bbox_inches='tight')
plt.show()


import numpy as np
import pandas as pd
from arch import arch_model
import matplotlib.pyplot as plt
from scipy import stats
import yfinance as yf
import warnings
warnings.filterwarnings('ignore')

# Download data
spy = yf.download('^GSPC', start='2000-01-01', end='2023-12-31', auto_adjust=True, progress=False)
rets = np.log(spy['Close']).diff().dropna().squeeze() * 100

# ============================================================
# Fit Comparison : GARCH vs EGARCH vs GJR - GARCH
# ============================================================
models = {}
results = {}

for name, vol_type in [('GARCH (1 ,1)', 'GARCH'),
                       ('EGARCH (1 ,1)', 'EGARCH'),
                       ('GJR - GARCH (1 ,1)', 'GARCH')]:
    if name == 'GJR - GARCH (1 ,1)':
        am = arch_model(rets, vol='GARCH', p=1, o=1, q=1, dist='t')
    else:
        am = arch_model(rets, vol=vol_type, p=1, q=1, dist='t')
    res = am.fit(disp='off', show_warning=False)
    models[name] = am
    results[name] = res

# Print model comparison
print("=" * 75)
print(f"{'Model Comparison':^75}")
print("=" * 75)
print(f"{'Model':>20} {'Log-Lik':>12} {'AIC':>12} {'BIC':>12}")
print("-" * 75)
for name, res in results.items():
    print(f"{name:>20} {res.loglikelihood:>12.2f} {res.aic:>12.2f} {res.bic:>12.2f}")
print("=" * 75)

# ============================================================
# EGARCH Diagnostics
# ============================================================
egarch_res = results['EGARCH (1 ,1)']
print("\nEGARCH(1,1) Parameters:")
print(egarch_res.params)

# Safe formatting check
alpha_val = egarch_res.params.get('alpha[1]', None)
gamma_val = egarch_res.params.get('gamma[1]', None)

alpha_str = f"{alpha_val:.4f}" if alpha_val is not None else "N/A"
gamma_str = f"{gamma_val:.4f}" if gamma_val is not None else "N/A"

print(f"\nLeverage coefficient (alpha): {alpha_str}")
print(f"Asymmetry coefficient (gamma): {gamma_str}")
print("Note: gamma < 0 indicates negative returns increase vol more")

# ============================================================
# News Impact Curve Comparison
# ============================================================
fig, axes = plt.subplots(1, 2, figsize=(13, 5))
fig.suptitle('News Impact Curve: GARCH vs EGARCH vs GJR-GARCH', fontsize=12, fontweight='bold')

epsilon_range = np.linspace(-5, 5, 500)  # in units of unconditional std

# Long-run (unconditional) variance
garch_res = results['GARCH (1 ,1)']
omega_g = garch_res.params['omega']
alpha_g = garch_res.params['alpha[1]']
beta_g = garch_res.params['beta[1]']
long_run_var = omega_g / (1 - alpha_g - beta_g)

# GARCH NIC
nic_garch = omega_g + beta_g * long_run_var + alpha_g * epsilon_range ** 2

# EGARCH NIC (approximate)
eg_res = results['EGARCH (1 ,1)']
omega_e = eg_res.params['omega']
alpha_e = eg_res.params.get('alpha[1]', 0)
gamma_e = eg_res.params.get('gamma[1]', 0)
beta_e = eg_res.params['beta[1]']
std_sigma = np.sqrt(long_run_var)
z_range = epsilon_range / std_sigma
e_z_abs = np.sqrt(2 / np.pi)  # E|z| for standard normal

nic_egarch = np.exp(
    omega_e / (1 - beta_e) + alpha_e * z_range + gamma_e * (np.abs(z_range) - e_z_abs)
) * (long_run_var ** beta_e)

# GJR-GARCH NIC
gjr_res = results['GJR - GARCH (1 ,1)']
omega_gjr = gjr_res.params['omega']
alpha_gjr = gjr_res.params['alpha[1]']
gamma_gjr = gjr_res.params.get('gamma[1]', 0)
beta_gjr = gjr_res.params['beta[1]']
nic_gjr = (omega_gjr + beta_gjr * long_run_var +
           alpha_gjr * epsilon_range ** 2 +
           gamma_gjr * np.where(epsilon_range < 0, epsilon_range ** 2, 0))

for ax in axes:
    ax.plot(epsilon_range, np.sqrt(nic_garch * 252) * 100,
            color='navy', linewidth=2.5, label='GARCH(1,1)')
    ax.plot(epsilon_range, np.sqrt(np.maximum(nic_egarch, 0) * 252) * 100,
            color='darkred', linewidth=2.5, linestyle='--', label='EGARCH(1,1)')
    ax.plot(epsilon_range, np.sqrt(nic_gjr * 252) * 100,
            color='darkgreen', linewidth=2.5, linestyle=':', label='GJR-GARCH(1,1)')
    ax.axvline(0, color='black', linewidth=0.5)
    ax.set_xlabel('Shock $\\varepsilon_{t-1}$ (Return %)', fontsize=10)
    ax.set_ylabel('Next-period Annualized Vol (%)', fontsize=10)
    ax.legend(fontsize=9)
    ax.grid(True, alpha=0.3)

axes[0].set_title('News Impact Curve (Full Range)', fontweight='bold')
axes[1].set_xlim(-3, 3)
axes[1].set_title('News Impact Curve (Zoomed)', fontweight='bold')

plt.tight_layout()
plt.savefig('news_impact_curves.png', dpi=150, bbox_inches='tight')
plt.show()


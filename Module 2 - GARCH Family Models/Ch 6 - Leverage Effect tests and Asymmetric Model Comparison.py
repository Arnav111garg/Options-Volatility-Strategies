import numpy as np
import pandas as pd
from arch import arch_model
from scipy import stats
import matplotlib.pyplot as plt
import yfinance as yf

spy = yf.download('^GSPC', start='2000-01-01', end='2023-12-31', auto_adjust=True, progress=False)
rets = np.log(spy['Close']).diff().dropna().squeeze() * 100

# Step 1: Fit symmetric GARCH (1,1) to get standardized residuals
sym_model = arch_model(rets, vol='GARCH', p=1, q=1, dist='t')
sym_res = sym_model.fit(disp='off', show_warning=False)

std_resid = sym_res.resid / sym_res.conditional_volatility
eps_hat = sym_res.resid.values

# Step 2: Engle-Ng Test
def engle_ng_test(eps_hat, std_resid_sq):
    """
    Engle-Ng (1993) Sign and Size Bias Tests.
    Tests whether asymmetric GARCH is needed.
    """
    T = len(eps_hat)
    S_neg = (eps_hat < 0).astype(float)[:-1] # lagged
    S_pos = 1 - S_neg
    eps_lag = eps_hat[:-1]
    y = std_resid_sq[1:]

    # Design matrix: [1, S^-, S^- * eps, S^+ * eps]
    X = np.column_stack([
        np.ones(T - 1),
        S_neg,
        S_neg * eps_lag,
        S_pos * eps_lag
    ])

    # OLS
    beta_ols = np.linalg.lstsq(X, y, rcond=None)[0]
    y_hat = X @ beta_ols
    resid = y - y_hat

    # Covariance (heteroscedasticity-robust)
    n, k = X.shape
    e_sq = resid ** 2
    XtX_inv = np.linalg.inv(X.T @ X)
    meat = X.T @ np.diag(e_sq) @ X
    HC_cov = XtX_inv @ meat @ XtX_inv

    se = np.sqrt(np.diag(HC_cov))
    t_stats = beta_ols / se
    p_values = 2 * (1 - stats.t.cdf(np.abs(t_stats), df=n - k))

    # Joint F-test for a1, a2, a3 (indices 1, 2, 3)
    R = np.eye(3, 4, 1) # selects coefficients 1, 2, 3
    diff = R @ beta_ols
    RVR = R @ HC_cov @ R.T
    F_stat = diff @ np.linalg.inv(RVR) @ diff / 3
    F_pval = 1 - stats.f.cdf(F_stat, 3, n - k)

    return {
        'coefficients': beta_ols,
        'std_errors': se,
        't_stats': t_stats,
        'p_values': p_values,
        'joint_F': F_stat,
        'joint_p': F_pval
    }

test_result = engle_ng_test(eps_hat, std_resid.values ** 2)

print("=" * 60)
print(f"{'Engle-Ng Sign and Size Bias Tests':^60}")
print("=" * 60)
names = ['Constant', 'Sign Bias (a1)', 'Neg Size Bias (a2)', 'Pos Size Bias (a3)']
for name, coef, se, t, p in zip(
    names, test_result['coefficients'], test_result['std_errors'],
    test_result['t_stats'], test_result['p_values']
):
    sig = '***' if p < 0.001 else '**' if p < 0.01 else '*' if p < 0.05 else ''
    print(f"{name:>22}: {coef:>8.4f} (se={se:.4f}, t={t:.2f}, p={p:.4f}) {sig}")
print("-" * 60)
print(f"Joint Test F-stat: {test_result['joint_F']:.3f}, p-value: {test_result['joint_p']:.6f}")
if test_result['joint_p'] < 0.05:
    print("=> REJECT H0: Asymmetric GARCH model recommended !")
print("=" * 60)

# Step 3: Visualize leverage effect
fig, axes = plt.subplots(1, 2, figsize=(13, 5))
fig.suptitle('Leverage Effect Analysis S&P 500', fontsize=12, fontweight='bold')

# Lagged returns vs squared std residuals
ax1 = axes[0]
lag_rets = eps_hat[:-1]
sq_resid = std_resid.values[1:] ** 2

# Bin into positive and negative returns
neg_mask = lag_rets < 0
pos_mask = lag_rets >= 0

# Scatter (subsampled for clarity)
idx = np.random.choice(len(lag_rets), 2000, replace=False)
ax1.scatter(lag_rets[idx][neg_mask[idx]], sq_resid[idx][neg_mask[idx]],
            alpha=0.2, s=3, color='darkred', label='Negative return')
ax1.scatter(lag_rets[idx][pos_mask[idx]], sq_resid[idx][pos_mask[idx]],
            alpha=0.2, s=3, color='navy', label='Positive return')

# Fit quadratic for each sign
for mask, color, label in [
    (neg_mask, 'darkred', 'Neg fit'),
    (pos_mask, 'navy', 'Pos fit')
]:
    lr = lag_rets[mask]
    sr = sq_resid[mask]
    p = np.polyfit(lr, sr, 2)
    x_plot = np.linspace(lr.min(), lr.max(), 100)
    ax1.plot(x_plot, np.polyval(p, x_plot), color=color, linewidth=2.5)

ax1.set_xlim(-5, 5)
ax1.set_ylim(0, 15)
ax1.set_xlabel('Lagged Return (%)')
ax1.set_ylabel('Squared Std. Residual')
ax1.set_title('Leverage Effect Scatter', fontweight='bold')
ax1.legend()
ax1.grid(True, alpha=0.3)

# Fit GJR-GARCH and show asymmetric vol response
gjr_model = arch_model(rets, vol='GARCH', p=1, o=1, q=1, dist='t')
gjr_res = gjr_model.fit(disp='off', show_warning=False)

a = gjr_res.params['alpha[1]']
g = gjr_res.params['gamma[1]']
print(f"\nGJR-GARCH: alpha={a:.4f}, gamma={g:.4f}, leverage ratio={(a+g)/a:.2f}x")

ax2 = axes[1]
x = np.linspace(-4, 4, 300)
long_run_v = gjr_res.params['omega'] / (1 - a - g/2 - gjr_res.params['beta[1]'])
nic_sym = gjr_res.params['omega'] + gjr_res.params['beta[1]'] * long_run_v + a * x ** 2
nic_gjr = gjr_res.params['omega'] + gjr_res.params['beta[1]'] * long_run_v + a * x ** 2 + g * np.where(x < 0, x ** 2, 0)

ax2.plot(x, np.sqrt(np.maximum(nic_sym, 0) * 252) * 100,
         color='navy', linewidth=2.5, linestyle='--', label='Symmetric (GARCH)')
ax2.plot(x, np.sqrt(np.maximum(nic_gjr, 0) * 252) * 100,
         color='darkred', linewidth=2.5, label='GJR-GARCH (Asymmetric)')
ax2.axvline(0, color='black', linewidth=0.8, linestyle=':')
ax2.set_xlabel('Shock $\\varepsilon_{t-1}$ (%)')
ax2.set_ylabel('Next-period Ann. Vol (%)')
ax2.set_title('News Impact Curve: Symmetric vs Asymmetric', fontweight='bold')
ax2.legend()
ax2.grid(True, alpha=0.3)

plt.tight_layout()
plt.savefig('leverage_effect.png', dpi=150, bbox_inches='tight')
plt.show()


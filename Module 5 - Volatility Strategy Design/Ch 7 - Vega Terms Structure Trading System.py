import numpy as np
import pandas as pd
from scipy.stats import norm
import matplotlib.pyplot as plt

def bs_price(S, K, T, r, sigma, option_type='call'):
    """Black-Scholes option price helper."""
    if T <= 0:
        return max(S - K, 0) if option_type == 'call' else max(K - S, 0)
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    if option_type == 'call':
        return S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
    else:
        return K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)

class VegaTradingSystem:
    """
    Vega term structure trading system.
    Exploits predictable patterns in the IV term structure.
    """
    def __init__(self, spot=100.0, r=0.0):
        self.spot = spot
        self.r = r

    def compute_greeks_matrix(self, tenors, sigmas):
        """
        Compute full greek matrix for ATM options across tenors.
        tenors: list of maturities in years
        sigmas: corresponding IV values
        """
        greeks = []
        for T, sigma in zip(tenors, sigmas):
            d1 = 0.5 * sigma * np.sqrt(T)  # ATM approximation
            delta = norm.cdf(d1)
            gamma = norm.pdf(d1) / (self.spot * sigma * np.sqrt(T))
            theta = (-self.spot * norm.pdf(d1) * sigma / (2 * np.sqrt(T))) / 365
            vega = self.spot * norm.pdf(d1) * np.sqrt(T) / 100
            price = bs_price(self.spot, self.spot, T, self.r, sigma)
            greeks.append({
                'T': T, 'sigma': sigma, 'price': price,
                'delta': delta, 'gamma': gamma,
                'theta': theta, 'vega': vega
            })
        return pd.DataFrame(greeks)

    def construct_vega_neutral_calendar(self, T1, T2, sigma1, sigma2, n1=1.0):
        """
        Build a vega-neutral calendar spread.
        Long T2, short n*T1 to neutralize vega.
        """
        df = self.compute_greeks_matrix([T1, T2], [sigma1, sigma2])
        v1 = df[df['T'] == T1]['vega'].values[0]
        v2 = df[df['T'] == T2]['vega'].values[0]
        n2 = n1 * v1 / v2  # vega-neutral ratio

        net_vega = n1 * v1 - n2 * v2
        net_gamma = n1 * df[df['T'] == T1]['gamma'].values[0] - n2 * df[df['T'] == T2]['gamma'].values[0]
        net_theta = n1 * df[df['T'] == T1]['theta'].values[0] - n2 * df[df['T'] == T2]['theta'].values[0]
        net_cost = n2 * df[df['T'] == T2]['price'].values[0] - n1 * df[df['T'] == T1]['price'].values[0]

        print(f"\n Vega-Neutral Calendar Spread :")
        print(f" Short {n1:.3f}x T={T1 * 12:.0f}M / Long {n2:.3f}x T={T2 * 12:.0f}M")
        print(f" Net Vega  : {net_vega:.6f} (target: ~0)")
        print(f" Net Gamma : {net_gamma:.6f}")
        print(f" Net Theta : {net_theta:.4f}/day")
        print(f" Net Cost  : ${net_cost:.4f}")
        return {'n1': n1, 'n2': n2, 'net_gamma': net_gamma, 'net_theta': net_theta, 'net_cost': net_cost}

    def vega_pnl_from_iv_move(self, tenors, initial_sigmas, final_sigmas, weights):
        """
        Compute P&L of a vega portfolio after a term structure move.
        weights: positive = long, negative = short
        """
        initial = self.compute_greeks_matrix(tenors, initial_sigmas)
        total_pnl = 0.0
        for i, (T, w) in enumerate(zip(tenors, weights)):
            dv = final_sigmas[i] - initial_sigmas[i]
            vega = initial[initial['T'] == T]['vega'].values[0]
            pnl = w * vega * dv * 100  # dv in vol points
            total_pnl += pnl
            print(f" T={T * 12:.0f}M: weight={w:.2f}, dVol={dv * 100:.1f}bp, vega={vega:.4f}, P&L=${pnl:.4f}")
        print(f" Total P&L: ${total_pnl:.4f}")
        return total_pnl

# Example: 1M vs 3M vega calendar
vts = VegaTradingSystem(spot=100, r=0.0)

import numpy as np
import pandas as pd
from scipy.optimize import minimize, curve_fit
from scipy.stats import norm
import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d import Axes3D

def bs_greeks(S, K, T, r, sigma):
    """Compute basic option vega for mispricing scaling."""
    if T <= 1e-8:
        return {'delta': 0, 'gamma': 0, 'theta': 0, 'vega': 0}
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    phi_d1 = norm.pdf(d1)
    vega = S * phi_d1 * np.sqrt(T) / 100
    return {'vega': vega}

class SVIVolSurface:
    """
    SVI volatility surface fitting and mispricing detection.
    """
    def __init__(self):
        self.params = {}  # { maturity : (a,b,rho ,m,xi)}

    def svi_total_var(self, k, a, b, rho, m, xi):
        """SVI total variance: w(k) = sigma_iv^2 * T."""
        return a + b * (rho * (k - m) + np.sqrt((k - m)**2 + xi**2))

    def svi_vol(self, k, T, a, b, rho, m, xi):
        """SVI implied vol."""
        w = self.svi_total_var(k, a, b, rho, m, xi)
        w = np.maximum(w, 1e-8)
        return np.sqrt(w / T)

    def fit_slice(self, strikes, ivs, F, T):
        """Fit SVI to a single maturity slice."""
        k = np.log(strikes / F)
        w_mkt = ivs**2 * T  # market total variance

        def objective(params):
            a, b, rho, m, xi = params
            if (b < 0 or xi <= 0 or abs(rho) >= 1 or b * (1 + abs(rho)) > 4/xi + 1e-4):
                return 1e10
            w_fit = self.svi_total_var(k, a, b, rho, m, xi)
            return np.sum((w_fit - w_mkt)**2)

        # Initial guess
        x0 = [np.mean(w_mkt) * 0.8, 0.2, -0.7, 0.0, 0.1]
        bounds = [(0, 1), (0, 2), (-0.999, 0.999), (-1, 1), (1e-4, 2)]
        result = minimize(objective, x0, method='L-BFGS-B', bounds=bounds)
        return result.x

    def fit_surface(self, surface_data):
        """
        Fit SVI to full surface.
        surface_data: dict {T: {'strikes': [...], 'ivs': [...]}}
        """
        for T, data in surface_data.items():
            F = data.get('forward', data['strikes'][len(data['strikes']) // 2])
            params = self.fit_slice(np.array(data['strikes']), np.array(data['ivs']), F, T)
            self.params[T] = params

    def model_iv(self, K, T, F):
        """Get model IV for a given strike / maturity."""
        if T not in self.params:
            # Interpolate between nearest tenors
            tenors = sorted(self.params.keys())
            T_lo = max([t for t in tenors if t <= T], default=tenors[0])
            T_hi = min([t for t in tenors if t >= T], default=tenors[-1])
            if T_lo == T_hi:
                T = T_lo
            else:
                alpha = (T - T_lo) / (T_hi - T_lo)
                iv_lo = self.model_iv(K, T_lo, F)
                iv_hi = self.model_iv(K, T_hi, F)
                return (1 - alpha) * iv_lo + alpha * iv_hi

        a, b, rho, m, xi = self.params[T]
        k = np.log(K / F)
        return self.svi_vol(k, T, a, b, rho, m, xi)

    def find_mispricings(self, market_surface, threshold=0.005):
        """
        Find strikes / maturities where market IV deviates from SVI model.
        Returns opportunities sorted by magnitude.
        """
        self.fit_surface(market_surface)
        opportunities = []

        for T, data in market_surface.items():
            F = data.get('forward', data['strikes'][len(data['strikes']) // 2])
            for K, iv_mkt in zip(data['strikes'], data['ivs']):
                iv_model = self.model_iv(K, T, F)
                mispr = iv_mkt - iv_model
                if abs(mispr) > threshold:
                    vega = bs_greeks(F, K, T, 0.0, iv_mkt)['vega']
                    pnl_1vol = abs(vega) * abs(mispr) * 100
                    opportunities.append({
                        'T': T * 12,
                        'K': K,
                        'iv_mkt': iv_mkt * 100,
                        'iv_model': iv_model * 100,
                        'mispr_vpts': mispr * 100,
                        'vega': vega,
                        'est_pnl': pnl_1vol,
                        'direction': 'BUY' if mispr < 0 else 'SELL'
                    })

        df_opp = pd.DataFrame(opportunities)
        if len(df_opp) > 0:
            df_opp = df_opp.sort_values('est_pnl', ascending=False)
            print(f"\n Vol Surface Mispricing Scanner ")
            print(f" Threshold: {threshold * 100:.1f} vol points ")
            print(f" Mispricings found: {len(df_opp)}")
            print(df_opp[['T', 'K', 'iv_mkt', 'iv_model', 'mispr_vpts', 'direction', 'est_pnl']].to_string(index=False))
        return df_opp

# Generate synthetic surface with a deliberate mispricing
tenors = [1/12, 2/12, 3/12, 6/12, 1.0]
F = 100.0
np.random.seed(42)

surface = {}
for T in tenors:
    strikes = np.linspace(85, 115, 13)
    # SVI-like true surface with skew
    k = np.log(strikes / F)
    iv = np.sqrt((0.04 + 0.08 * (-0.7 * k + np.sqrt(k**2 + 0.01))) / T)
    # Add noise and one deliberate mispricing
    iv_noisy = iv + np.random.randn(len(iv)) * 0.002
    # Plant mispricing at K=90 for 3M
    if abs(T - 0.25) < 0.01:
        idx = 2  # K=90 approximately
        iv_noisy[idx] -= 0.02  # 2 vol points cheap
    surface[T] = {'strikes': list(strikes), 'ivs': list(iv_noisy), 'forward': F}

scanner = SVIVolSurface()
mispricings = scanner.find_mispricings(surface, threshold=0.008)


import numpy as np
import pandas as pd
from scipy.stats import norm
import matplotlib.pyplot as plt

def bs_price(S, K, T, r, sigma, option_type='call'):
    """Standard Black-Scholes option pricing model."""
    if T <= 1e-8:
        if option_type == 'call':
            return max(S - K, 0.0)
        else:
            return max(K - S, 0.0)
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    if option_type == 'call':
        return S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
    else:
        return K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)

def bs_greeks(S, K, T, r, sigma):
    """Compute option greeks (delta, gamma, theta)."""
    if T <= 1e-8:
        return {'delta': 1.0 if S > K else 0.0, 'gamma': 0.0, 'theta': 0.0}
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)

    delta = norm.cdf(d1)
    gamma = norm.pdf(d1) / (S * sigma * np.sqrt(T))
    # Daily Theta
    theta = -(S * norm.pdf(d1) * sigma) / (2 * np.sqrt(T)) - r * K * np.exp(-r * T) * norm.cdf(d2)
    theta_daily = theta / 252
    return {'delta': delta, 'gamma': gamma, 'theta': theta_daily}

class GammaScalpingEngine:
    """
    Production-grade gamma scalping system.
    Implements delta-hedging with transaction costs and
    multiple hedging frequency schemes.
    """
    def __init__(self, S0=100.0, K=100.0, T_days=21,
                 sigma_iv=0.20, r=0.0,
                 hedge_scheme='fixed_band',
                 hedge_band=0.05,
                 transaction_cost=0.0005):
        self.S0 = S0
        self.K = K
        self.T_days = T_days
        self.sigma_iv = sigma_iv
        self.r = r
        self.scheme = hedge_scheme
        self.band = hedge_band
        self.tc = transaction_cost

    def bs_delta_gamma(self, S, K, T, r, sigma):
        """Compute delta and gamma."""
        if T < 1e-8:
            return (1.0 if S > K else 0.0), 0.0
        d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
        delta = norm.cdf(d1)
        gamma = norm.pdf(d1) / (S * sigma * np.sqrt(T))
        return delta, gamma

    def simulate_scalping(self, sigma_rv, n_paths=500, seed=42):
        """Run gamma scalping simulation."""
        np.random.seed(seed)
        dt = 1/252
        n_days = self.T_days

        all_results = []

        for path_idx in range(n_paths):
            # Simulate path
            Z = np.random.randn(n_days)
            rets = (self.r - 0.5 * sigma_rv**2) * dt + sigma_rv * np.sqrt(dt) * Z
            path = np.zeros(n_days + 1)
            path[0] = self.S0
            for i in range(n_days):
                path[i+1] = path[i] * np.exp(rets[i])

            # Initialize hedging
            T_rem = self.T_days * dt
            delta_0, gamma_0 = self.bs_delta_gamma(self.S0, self.K, T_rem, self.r, self.sigma_iv)

            delta_hedge = delta_0  # shares held (short to hedge long call)
            cash = -delta_hedge * self.S0  # initial hedge cost
            gamma_pnl = 0.0
            theta_pnl = 0.0
            tc_paid = 0.0
            hedge_count = 0

            for i in range(n_days):
                S = path[i]
                S_next = path[i+1]
                T_rem = (n_days - i) * dt

                if T_rem < 1e-8:
                    break

                # Get current greeks
                delta_new, gamma = self.bs_delta_gamma(S, self.K, T_rem, self.r, self.sigma_iv)

                # Option value change (gamma P&L + theta)
                T_rem_next = max((n_days - i - 1) * dt, 1e-8)
                val_t = bs_price(S, self.K, T_rem, self.r, self.sigma_iv, 'call')
                val_t1 = bs_price(S_next, self.K, T_rem_next, self.r, self.sigma_iv, 'call')
                option_pnl = val_t1 - val_t

                # Hedge decision
                delta_error = delta_new - delta_hedge
                should_hedge = False

                if self.scheme == 'daily':
                    should_hedge = True
                elif self.scheme == 'fixed_band':
                    should_hedge = abs(delta_error) > self.band
                elif self.scheme == 'gamma_band':
                    # Scale band by gamma
                    dyn_band = self.band / max(gamma * S**2 * dt, 1e-6)
                    should_hedge = abs(delta_error) > min(dyn_band, 0.15)

                if should_hedge:
                    tc = abs(delta_error) * S * self.tc
                    cash += delta_error * S - tc
                    delta_hedge = delta_new
                    tc_paid += tc
                    hedge_count += 1

                # Cash earns risk-free rate
                cash *= (1 + self.r * dt)

                # Decompose option P&L
                dS = S_next - S
                gamma_pnl += 0.5 * gamma * dS**2
                theta_pnl += bs_greeks(S, self.K, T_rem, self.r, self.sigma_iv)['theta']

            # Final liquidation
            S_final = path[-1]
            option_terminal = max(S_final - self.K, 0)  # call payoff
            hedge_terminal = delta_hedge * S_final

            net_pnl = option_terminal + hedge_terminal + cash - tc_paid

            # Subtract initial option cost
            initial_cost = bs_price(self.S0, self.K, self.T_days * dt, self.r, self.sigma_iv)
            net_pnl -= initial_cost

            all_results.append({
                'net_pnl': net_pnl,
                'gamma_pnl': gamma_pnl,
                'theta_pnl': theta_pnl,
                'tc_paid': tc_paid,
                'hedge_count': hedge_count,
                'S_final': S_final
            })

        df = pd.DataFrame(all_results)
        print(f"\n{'='*55}")
        print(f" Gamma Scalping: {self.scheme.upper()} | RV={sigma_rv*100:.0f}%")
        print(f"{'='*55}")
        print(f" Avg Net P&L     : ${df['net_pnl'].mean():.4f}")
        print(f" Avg Gamma P&L   : ${df['gamma_pnl'].mean():.4f}")
        print(f" Avg Theta P&L   : ${df['theta_pnl'].mean():.4f}")
        print(f" Avg TC Paid     : ${df['tc_paid'].mean():.4f}")
        print(f" Avg Hedge Count : {df['hedge_count'].mean():.1f}")
        print(f" Win Rate        : {(df['net_pnl'] > 0).mean() * 100:.1f}%")
        print(f" Sharpe          : {df['net_pnl'].mean() / df['net_pnl'].std() if df['net_pnl'].std() != 0 else 0:.3f}")
        print(f"{'='*55}")
        return df

# Compare hedging schemes
engine_daily = GammaScalpingEngine(hedge_scheme='daily', sigma_iv=0.18)
engine_band = GammaScalpingEngine(hedge_scheme='fixed_band', hedge_band=0.04, sigma_iv=0.18)

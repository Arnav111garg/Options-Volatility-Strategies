iv_qqq = 1.1 * iv_spy + pd.Series(np.random.randn(n) * 0.005)

trader = RelVolPairsTrader(lookback=60, entry_z=1.8, exit_z=0.3)
pnl, cum_pnl = trader.backtest(iv_spy, iv_qqq)


import numpy as np
import pandas as pd
from scipy import stats

class RelVolPairsTrader:
    """
    Relative Volatility Pairs Trading.
    Entry on Z-score, mean-reversion based.
    """
    def __init__(self, lookback=60, entry_z=2.0, exit_z=0.5, stop_z=3.5):
        self.lookback = lookback
        self.entry_z = entry_z
        self.exit_z = exit_z
        self.stop_z = stop_z

    def compute_iv_series(self, returns, window=21):
        """Compute rolling implied vol proxy (30D realized vol as substitute)."""
        return returns.rolling(window).std() * np.sqrt(252)

    def compute_spread(self, iv_a, iv_b):
        """Compute hedge-ratio adjusted spread."""
        n = self.lookback
        spreads = pd.Series(index=iv_a.index, dtype=float)

        for i in range(n, len(iv_a)):
            y = iv_a.iloc[i - n : i].values
            x = iv_b.iloc[i - n : i].values
            beta, alpha, _, _, _ = stats.linregress(x, y)
            spread = iv_a.iloc[i] - (alpha + beta * iv_b.iloc[i])
            spreads.iloc[i] = spread

        return spreads.dropna()

    def compute_zscore(self, spread):
        """Rolling z-score of the spread."""
        mu = spread.rolling(self.lookback).mean()
        std = spread.rolling(self.lookback).std()
        return (spread - mu) / std

    def backtest(self, iv_a, iv_b, unit_notional=1e6):
        """
        Run pairs vol backtest.
        Long A, Short B when spread too low (A cheap vs B).
        Short A, Long B when spread too high (A expensive vs B).
        """
        spread = self.compute_spread(iv_a, iv_b)
        zscore = self.compute_zscore(spread)

        position = 0  # +1: long A/ short B, -1: short A/ long B
        pnl_series = []
        pos_series = []

        for i in range(1, len(spread)):
            z = zscore.iloc[i]
            prev_z = zscore.iloc[i - 1]

            # Entry logic
            if position == 0:
                if z < -self.entry_z:
                    position = 1  # spread too low, expect reversion up
                elif z > self.entry_z:
                    position = -1  # spread too high, expect reversion down

            # Exit / stop logic
            elif position == 1:
                if z > -self.exit_z or z > self.stop_z:
                    position = 0
            elif position == -1:
                if z < self.exit_z or z < -self.stop_z:
                    position = 0

            # P&L: change in spread * position (scaled by notional / vega)
            delta_spread = spread.iloc[i] - spread.iloc[i - 1]
            daily_pnl = position * delta_spread * (unit_notional / 100)
            pnl_series.append(daily_pnl)
            pos_series.append(position)

        pnl = pd.Series(pnl_series, index=spread.index[1:])
        cum_pnl = pnl.cumsum()
        sharpe = pnl.mean() / pnl.std() * np.sqrt(252)
        win_rate = (pnl[pnl != 0] > 0).mean()

        print(f"\nRelVol Pairs Backtest:")
        print(f" Sharpe Ratio : {sharpe:.3f}")
        print(f" Win Rate     : {win_rate * 100:.1f}%")
        print(f" Total P&L    : ${cum_pnl.iloc[-1]:,.0f}")
        return pnl, cum_pnl


import numpy as np
import pandas as pd
from scipy.stats import spearmanr

class VolCarryStrategy:
    """
    Systematic volatility carry harvesting across multiple assets.
    Combines term structure carry and cross-sectional carry signals.
    """
    def __init__(self, assets=None, lookback_rv=21, lookback_zscore=60, n_top=3):
        self.assets = assets or ['SPY', 'QQQ', 'IWM', 'EFA', 'EEM']
        self.lookback_rv = lookback_rv
        self.lookback_z = lookback_zscore
        self.n_top = n_top

    def compute_realized_vol(self, returns_df):
        """Rolling realized vol for each asset."""
        return returns_df.rolling(self.lookback_rv).std() * np.sqrt(252)

    def compute_vol_carry(self, iv_df, rv_df):
        """Vol carry: IV minus realized vol."""
        return iv_df - rv_df

    def compute_zscore(self, carry_df):
        """Z-score carry relative to history."""
        mu = carry_df.rolling(self.lookback_z).mean()
        std = carry_df.rolling(self.lookback_z).std()
        return (carry_df - mu) / (std + 1e-8)

    def rank_signal(self, carry_df):
        """Cross-sectional rank signal (-1 to +1)."""
        # Rank within each row (date)
        ranks = carry_df.rank(axis=1, pct=True)  # 0 to 1
        signal = 2 * (ranks - 0.5)  # -1 to +1
        return signal

    def backtest(self, iv_panel, returns_panel, n_months=60):
        """
        Run volatility carry backtest.
        iv_panel : DataFrame of IV for each asset
        returns_panel : DataFrame of daily returns
        """
        rv_panel = self.compute_realized_vol(returns_panel)
        carry_panel = self.compute_vol_carry(iv_panel, rv_panel)
        carry_z = self.compute_zscore(carry_panel)
        rank_sig = self.rank_signal(carry_panel)

        # Position : short vol on high carry, long vol on low carry
        # (short where IV - RV is highest, i.e., VRP largest)
        position = -rank_sig  # negative carry signal = short vol = profit from VRP

        # Normalize positions
        position = position.div(position.abs().sum(axis=1), axis=0)

        # P&L: position * change in IV (vega P&L proxy)
        # Using next-day change in RV as realized vol proxy
        rv_changes = rv_panel.diff()
        pnl_daily = (position.shift(1) * rv_changes * (-1)).sum(axis=1)

        cum_pnl = pnl_daily.cumsum()
        ann_ret = pnl_daily.mean() * 252
        ann_vol = pnl_daily.std() * np.sqrt(252)
        sharpe = ann_ret / ann_vol if ann_vol > 0 else 0
        max_dd = (cum_pnl - cum_pnl.cummax()).min()

        print(f"\n{'='*55}")
        print(f" Vol Carry Strategy ({len(self.assets)} assets)")
        print(f"{'='*55}")
        print(f" Ann. Return : {ann_ret * 100:.2f}%")
        print(f" Ann. Vol    : {ann_vol * 100:.2f}%")
        print(f" Sharpe Ratio: {sharpe:.3f}")
        print(f" Max Drawdown: {max_dd * 100:.2f}%")
        print(f" Calmar Ratio: {ann_ret / abs(max_dd):.3f}" if max_dd != 0 else "")
        print(f"{'='*55}")
        return pnl_daily, cum_pnl, position


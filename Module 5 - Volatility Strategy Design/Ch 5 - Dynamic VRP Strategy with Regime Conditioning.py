import numpy as np
import pandas as pd
from scipy.stats import norm
import matplotlib.pyplot as plt

class VRPHarvester:
    """
    Dynamic Variance Risk Premium harvesting strategy.
    Conditions on VIX regime and term structure for entry.
    """
    def __init__(self, vix_high_threshold=30.0, vix_low_threshold=12.0, backwardation_exit=True, max_position=1.0, kelly_fraction=0.25):
        self.vix_high = vix_high_threshold
        self.vix_low = vix_low_threshold
        self.bw_exit = backwardation_exit
        self.max_pos = max_position
        self.kelly_f = kelly_fraction

    def compute_vix_term_structure_slope(self, vix_1m, vix_3m):
        """Positive = contango, Negative = backwardation."""
        return (vix_3m - vix_1m) / vix_1m

    def compute_vrp(self, iv_series, rv_series, window=21):
        """Compute rolling VRP (IV - RV)."""
        return iv_series - rv_series.rolling(window).mean()

    def kelly_size(self, vrp, vix_level):
        """
        Dynamic Kelly sizing based on VRP and VIX level.
        Size down when VIX is elevated (higher variance of variance).
        """
        base_mu = vrp
        base_sigma = 0.05  # typical std of VRP strategy
        raw_kelly = base_mu / (base_sigma ** 2)
        # Scale by VIX: higher VIX = smaller position
        vix_scale = min(1.0, 20.0 / max(vix_level, 10.0))
        return np.clip(raw_kelly * self.kelly_f * vix_scale, 0, self.max_pos)

    def generate_position(self, iv_1m, rv_21d, vix_1m, vix_3m):
        """Generate daily position in var swap notional."""
        vrp = self.compute_vrp(iv_1m, rv_21d)
        ts_slope = self.compute_vix_term_structure_slope(vix_1m, vix_3m)
        positions = pd.Series(0.0, index=iv_1m.index)

        for i in range(21, len(iv_1m)):
            v_level = vix_1m.iloc[i]
            v_vrp = vrp.iloc[i] if not np.isnan(vrp.iloc[i]) else 0
            ts = ts_slope.iloc[i] if not np.isnan(ts_slope.iloc[i]) else 0

            # Regime filter
            if v_level > self.vix_high:
                # VIX too elevated: scale back significantly
                scale = 0.3
            elif v_level < self.vix_low:
                # Low vol environment: modest position
                scale = 0.7
            else:
                scale = 1.0

            # Backwardation exit (VIX front > back = danger signal)
            if self.bw_exit and ts < -0.02:
                positions.iloc[i] = 0.0
                continue

            # VRP is positive -> short variance
            if v_vrp > 0:
                pos = -self.kelly_size(v_vrp, v_level) * scale
            else:
                pos = 0.0  # Don't go long vol unless strong signal

            positions.iloc[i] = pos

        return positions

    def backtest(self, positions, rv_realized, iv_entry):
        """
        Compute P&L of variance swap strategy.
        pnl_daily = position * (IV_entry^2 - RV_realized^2) * notional
        """
        # Simplification: daily var swap mark
        iv2 = iv_entry ** 2
        rv2 = rv_realized ** 2
        var_diff = iv2 - rv2  # positive = short var profits
        pnl = positions.shift(1) * var_diff * (-1)  # short = -position
        cum_pnl = pnl.cumsum()

        valid = pnl.dropna()
        ann_sh = valid.mean() / valid.std() * np.sqrt(252) if valid.std() > 0 else 0
        max_dd = (cum_pnl - cum_pnl.cummax()).min()

        print(f"\n{'='*55}")
        print(f" Dynamic VRP Harvester Results ")
        print(f"{'='*55}")
        print(f" Annualized Sharpe : {ann_sh:.3f}")
        print(f" Total P&L (vol pts ): {cum_pnl.iloc[-1]:.2f}")
        print(f" Max Drawdown : {max_dd:.2f}")
        print(f" Days in Position : {(positions != 0).sum()}")
        print(f" Avg VRP harvested : {var_diff[positions != 0].mean():.4f}")
        print(f"{'='*55}")
        return pnl, cum_pnl


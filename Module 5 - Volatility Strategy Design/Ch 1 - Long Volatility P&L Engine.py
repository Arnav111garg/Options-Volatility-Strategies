# -----------------------------------------------
# Black - Scholes Engine
# -----------------------------------------------
def bs_price(S, K, T, r, sigma, option_type='call'):
    """Black - Scholes option price ."""
    if T <= 0:
        return max(S - K, 0) if option_type == 'call' else max(K - S, 0)
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    if option_type == 'call':
        return S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
    else:
        return K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)

def bs_greeks(S, K, T, r, sigma):
    """Compute full greek set ."""
    if T <= 1e-8:
        return {'delta': 0, 'gamma': 0, 'theta': 0, 'vega': 0}
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    phi_d1 = norm.pdf(d1)
    Phi_d1 = norm.cdf(d1)
    delta = Phi_d1
    gamma = phi_d1 / (S * sigma * np.sqrt(T))
    theta = (-(S * phi_d1 * sigma) / (2 * np.sqrt(T)) - r * K * np.exp(-r * T) * norm.cdf(d2)) / 365
    vega = S * phi_d1 * np.sqrt(T) / 100  # per 1 vol point
    return {'delta': delta, 'gamma': gamma, 'theta': theta, 'vega': vega}

# -----------------------------------------------
# Long Volatility Backtest Engine
# -----------------------------------------------
class LongVolBacktest:
    """
    Backtest a delta - hedged long straddle position .
    Tracks daily gamma P&L vs theta decay .
    """
    def __init__(self, S0=100.0, K=100.0, T_days=30, sigma_iv=0.20, r=0.0, hedge_freq='daily'):
        self.S0 = S0
        self.K = K
        self.T_days = T_days
        self.sigma_iv = sigma_iv
        self.r = r
        self.hedge_freq = hedge_freq

    def simulate_paths(self, sigma_rv, n_paths=1000, seed=42):
        """Simulate underlying paths with given realized vol ."""
        np.random.seed(seed)
        dt = 1/252
        n = self.T_days
        Z = np.random.randn(n_paths, n)
        log_rets = (self.r - 0.5 * sigma_rv**2) * dt + sigma_rv * np.sqrt(dt) * Z
        paths = self.S0 * np.exp(np.cumsum(log_rets, axis=1))
        paths = np.column_stack([np.full(n_paths, self.S0), paths])
        return paths

    def run(self, sigma_rv, n_paths=500):
        """Run the backtest ."""
        paths = self.simulate_paths(sigma_rv, n_paths)
        dt = 1/252
        results = []

        for path in paths:
            pnl_gamma_total = 0.0
            pnl_theta_total = 0.0

            for i in range(self.T_days):
                S = path[i]
                T_rem = (self.T_days - i) / 252

                if T_rem < 1e-6:
                    break

                g = bs_greeks(S, self.K, T_rem, self.r, self.sigma_iv)
                gamma = g['gamma']
                theta = g['theta']  # daily ( negative )
                dS = path[i+1] - S
                ret = dS / S

                # Gamma P&L
                gamma_pnl = 0.5 * gamma * S**2 * ret**2
                # Theta decay
                theta_pnl = theta  # Already per day

                pnl_gamma_total += gamma_pnl
                pnl_theta_total += theta_pnl

            net_pnl = pnl_gamma_total + pnl_theta_total
            results.append({
                'gamma_pnl': pnl_gamma_total,
                'theta_pnl': pnl_theta_total,
                'net_pnl': net_pnl
            })

        df = pd.DataFrame(results)
        straddle_cost = 2 * bs_price(self.S0, self.K, self.T_days/252, self.r, self.sigma_iv)

        print(f"\n{'='*55}")
        print(f" Long Straddle Backtest Summary ")
        print(f"{'='*55}")
        print(f" Straddle Cost : ${straddle_cost:.4f}")
        print(f" Sigma IV : {self.sigma_iv * 100:.1f}%")
        print(f" Sigma RV : {sigma_rv * 100:.1f}%")
        print(f" Mean Net P&L : ${df['net_pnl'].mean():.4f}")
        print(f" Median Net P&L : ${df['net_pnl'].median():.4f}")
        print(f" Win Rate : {(df['net_pnl'] > 0).mean() * 100:.1f}%")
        print(f" Sharpe (P&L/std ): {df['net_pnl'].mean() / df['net_pnl'].std():.3f}")
        print(f"{'='*55}")
        return df

# Run example
bt = LongVolBacktest(S0=100, K=100, T_days=21, sigma_iv=0.20, r=0.0)
# Case 1: RV > IV ( long vol wins )

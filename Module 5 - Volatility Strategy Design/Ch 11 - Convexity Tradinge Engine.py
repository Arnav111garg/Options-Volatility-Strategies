import numpy as np
import pandas as pd
from scipy.stats import norm
import matplotlib.pyplot as plt

def compute_higher_order_greeks(S, K, T, r, sigma):
    """Compute vomma and vanna."""
    if T < 1e-8:
        return {'vomma': 0, 'vanna': 0, 'speed': 0, 'zomma': 0}
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    phi_d1 = norm.pdf(d1)
    vega = S * phi_d1 * np.sqrt(T)
    vomma = vega * d1 * d2 / sigma
    vanna = -phi_d1 * d2 / sigma
    gamma = phi_d1 / (S * sigma * np.sqrt(T))
    speed = -gamma / S * (d1 / (sigma * np.sqrt(T)) + 1)
    zomma = gamma * (d1 * d2 - 1) / sigma  # d(gamma)/d(sigma)
    return {'vomma': vomma, 'vanna': vanna, 'gamma': gamma, 'speed': speed, 'zomma': zomma, 'vega': vega}

class ConvexityTrader:
    """
    Vomma / convexity trading system.
    Constructs portfolios with targeted convexity exposure.
    """
    def __init__(self, S=100, r=0.0, T=1/12):
        self.S = S
        self.r = r
        self.T = T

    def butterfly_greeks(self, K_center, wing_width, sigma, n_long=1.0):
        """
        Compute aggregate greeks for a butterfly.
        Long K-w and K+w, short 2*K.
        """
        results = {}
        for K_name, K_val, w in [
            ('wing_lo', K_center - wing_width, n_long),
            ('atm', K_center, -2 * n_long),
            ('wing_hi', K_center + wing_width, n_long)
        ]:
            g = compute_higher_order_greeks(self.S, K_val, self.T, self.r, sigma)
            results[K_name] = {k: v * w for k, v in g.items()}

        # Aggregate
        net = {k: sum(results[pos][k] for pos in results) for k in list(results['atm'].keys())}
        return net, results

    def analyze_convexity_profile(self, K=100, sigma=0.20, wing_width=5.0):
        """Analyze butterfly convexity profile."""
        net_greeks, leg_greeks = self.butterfly_greeks(K, wing_width, sigma)

        print(f"\n{'='*55}")
        print(f" Butterfly Convexity Analysis ")
        print(f" K={K}, wing={wing_width}, sigma={sigma*100:.0f}%")
        print(f"{'='*55}")
        print(f" Net Delta : {net_greeks['vega']:.6f}")
        print(f" Net Gamma : {net_greeks['gamma']:.6f}")
        print(f" Net Vega  : {net_greeks['vega']:.6f}")
        print(f" Net Vomma : {net_greeks['vomma']:.6f} <- CONVEXITY")
        print(f" Net Vanna : {net_greeks['vanna']:.6f}")
        print(f" Net Zomma : {net_greeks['zomma']:.6f}")
        print(f"{'='*55}")
        return net_greeks

    def vomma_pnl_simulation(self, sigma0=0.20, vvol=0.03, n_sims=1000, seed=42):
        """
        Simulate P&L of long vomma position under vol-of-vol.
        Buy butterfly (positive vomma), short ATM straddle (negative vomma).
        """
        np.random.seed(seed)
        # Butterfly : +1 wing at K-5, -2 ATM, +1 wing at K+5
        net_g, _ = self.butterfly_greeks(self.S, 5.0, sigma0)
        vomma_bf = net_g['vomma']
        vega_bf = net_g['vega']

        pnls = []
        for _ in range(n_sims):
            # Simulate one path of IV over T days
            n = max(int(self.T * 252), 1)
            dz = np.random.randn(n)
            sig_path = sigma0 * np.exp((-0.5 * vvol**2 + vvol * np.sqrt(self.T / n) * dz).cumsum())
            sig_final = sig_path[-1]
            dsig = sig_final - sigma0

            # Approximate P&L from vomma
            pnl = vega_bf * dsig + 0.5 * vomma_bf * dsig**2
            pnls.append(pnl)

        pnls = np.array(pnls)
        print(f"\n Vomma P&L Simulation (butterfly, T={self.T * 12:.1f}M)")
        print(f" Vomma: {vomma_bf:.6f}")
        print(f" Mean P&L: {pnls.mean():.6f}")
        print(f" Std P&L: {pnls.std():.6f}")
        print(f" Sharpe: {pnls.mean() / pnls.std():.3f}")
        return pnls

ct = ConvexityTrader(S=100, r=0.0, T=1/12)
ct.analyze_convexity_profile(K=100, sigma=0.20, wing_width=5)
pnls = ct.vomma_pnl_simulation(sigma0=0.20, vvol=0.04, n_sims=5000)


import numpy as np
import pandas as pd
from scipy.stats import norm
import matplotlib.pyplot as plt

def bs_price(S, K, T, r, sigma, option_type='call'):
    """Standard Black-Scholes formula for European options."""
    if T <= 0:
        if option_type == 'call':
            return max(S - K, 0.0)
        else:
            return max(K - S, 0.0)
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    if option_type == 'call':
        return S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
    else:
        return K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)

class IronCondorBacktest:
    """
    Systematic Iron Condor strategy on equity index.
    Enters monthly, delta-neutral wings, with stop-loss logic.
    """
    def __init__(self, delta_wing=0.15, dte=30, stop_loss_mult=2.0, wing_width=5):
        self.delta_wing = delta_wing  # target delta of short strikes
        self.dte = dte
        self.stop_loss_mult = stop_loss_mult
        self.wing_width = wing_width  # width of each spread

    def find_strike(self, S, T, r, sigma, target_delta, option_type):
        """Find strike corresponding to a target delta."""
        from scipy.optimize import brentq
        def objective(K):
            d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
            if option_type == 'put':
                return norm.cdf(d1) - 1 - target_delta  # put delta is negative
            else:
                return norm.cdf(d1) - target_delta
        try:
            return brentq(objective, S * 0.5, S * 2.0)
        except:
            return S * (1 + target_delta * sigma * np.sqrt(T))

    def ic_pnl_at_expiry(self, S_expiry, K_put_long, K_put_short, K_call_short, K_call_long, net_premium):
        """P&L of iron condor at expiry."""
        put_spread_pnl = max(K_put_short - S_expiry, 0) - max(K_put_long - S_expiry, 0)
        call_spread_pnl = max(S_expiry - K_call_short, 0) - max(S_expiry - K_call_long, 0)
        return net_premium - put_spread_pnl - call_spread_pnl

    def simulate(self, n_months=120, sigma_iv=0.18, sigma_rv=0.15, S0=100.0, r=0.0, seed=42):
        """Simulate monthly iron condor strategy."""
        np.random.seed(seed)
        results = []
        cum_pnl = 0.0

        for month in range(n_months):
            T = self.dte / 252
            # Simulate underlying path
            dt = 1/252
            n = self.dte
            z = np.random.randn(n)
            ret = (r - 0.5 * sigma_rv**2) * dt + sigma_rv * np.sqrt(dt) * z
            path = S0 * np.exp(np.cumsum(ret))
            S_expiry = path[-1]

            # Construct condor
            K_call_short = self.find_strike(S0, T, r, sigma_iv, self.delta_wing, 'call')
            K_put_short = self.find_strike(S0, T, r, sigma_iv, -self.delta_wing, 'put')
            K_call_long = K_call_short + self.wing_width
            K_put_long = K_put_short - self.wing_width
            spread_width = self.wing_width

            # Price legs
            c_short = bs_price(S0, K_call_short, T, r, sigma_iv, 'call')
            c_long = bs_price(S0, K_call_long, T, r, sigma_iv, 'call')
            p_short = bs_price(S0, K_put_short, T, r, sigma_iv, 'put')
            p_long = bs_price(S0, K_put_long, T, r, sigma_iv, 'put')
            net_premium = (c_short - c_long) + (p_short - p_long)
            max_loss = spread_width - net_premium

            # Check stop-loss mid-trade
            max_adverse = max(abs(path - S0))
            stopped_out = False
            if max_adverse > self.stop_loss_mult * net_premium * S0 / spread_width:
                pnl = -self.stop_loss_mult * net_premium
                stopped_out = True
            else:
                pnl = self.ic_pnl_at_expiry(S_expiry, K_put_long, K_put_short, K_call_short, K_call_long, net_premium)

            cum_pnl += pnl
            results.append({
                'month': month,
                'S0': S0,
                'S_expiry': S_expiry,
                'net_premium': net_premium,
                'pnl': pnl,
                'cum_pnl': cum_pnl,
                'stopped_out': stopped_out,
                'K_put_long': K_put_long,
                'K_put_short': K_put_short,
                'K_call_short': K_call_short,
                'K_call_long': K_call_long
            })
            # Reset S0 for next month
            S0 = S_expiry

        df = pd.DataFrame(results)
        self._print_summary(df, n_months)
        return df

    def _print_summary(self, df, n_months):
        wins = (df['pnl'] > 0).sum()
        losses = (df['pnl'] <= 0).sum()
        stops = df['stopped_out'].sum()
        ann_ret = df['pnl'].sum() / (n_months / 12)
        sharpe = df['pnl'].mean() / df['pnl'].std() * np.sqrt(12) if df['pnl'].std() != 0 else 0
        max_dd = (df['cum_pnl'] - df['cum_pnl'].cummax()).min()

        print(f"\n{'='*55}")
        print(f" Iron Condor Systematic Backtest ({n_months} months)")
        print(f"{'='*55}")
        print(f" Win Rate         : {wins / n_months * 100:.1f}%")
        print(f" Stop-Outs        : {stops} ({stops / n_months * 100:.1f}%)")
        print(f" Total P&L        : ${df['pnl'].sum():.2f}")
        print(f" Annualized P&L   : ${ann_ret:.2f}")
        print(f" Monthly Sharpe   : {sharpe:.3f}")
        print(f" Max Drawdown     : ${max_dd:.2f}")
        print(f" Avg Premium/mth  : ${df['net_premium'].mean():.3f}")
        print(f"{'='*55}")

ic = IronCondorBacktest(delta_wing=0.16, dte=30, stop_loss_mult=2.5)

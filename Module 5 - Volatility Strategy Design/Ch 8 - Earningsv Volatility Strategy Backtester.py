import numpy as np
import pandas as pd
from scipy.stats import norm

def bs_price(S, K, T, r, sigma, option_type='call'):
    """Standard Black-Scholes formula for European options."""
    if T <= 0:
        if option_type == 'call':
            return max(S - K, 0.0)
        else:
            return max(K - S, 0.0)
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    if option_type == 'call':
        return S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
    else:
        return K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)

class EarningsVolBacktester:
    """
    Systematic earnings volatility strategy backtester.
    Simulates straddle sell (IV crush) and straddle buy strategies.
    """
    def __init__(self):
        pass

    def implied_move(self, S, K, T, r, sigma_iv):
        """Expected move from ATM straddle price."""
        atm_straddle = 2 * bs_price(S, K, T, r, sigma_iv, 'call')
        return atm_straddle / S

    def compute_straddle_pnl(self, S_pre, K, T_pre, T_post,
                             sigma_pre, sigma_post, S_post, r=0.0):
        """
        P&L from selling straddle before earnings and buying back after.
        """
        # Sell straddle (short call + short put)
        sell_call = bs_price(S_pre, K, T_pre, r, sigma_pre, 'call')
        sell_put = bs_price(S_pre, K, T_pre, r, sigma_pre, 'put')
        premium_received = sell_call + sell_put

        # Buy back straddle after earnings
        buy_call = bs_price(S_post, K, T_post, r, sigma_post, 'call')
        buy_put = bs_price(S_post, K, T_post, r, sigma_post, 'put')
        buyback_cost = buy_call + buy_put

        return premium_received - buyback_cost

    def backtest(self, n_earnings=200, seed=42,
                 sigma_pre_mean=0.45, sigma_post_factor=0.55,
                 actual_move_factor=0.80):
        """
        Monte Carlo backtest of earnings straddle selling.
        """
        np.random.seed(seed)
        S0 = 100.0
        T_pre = 5/252      # 5 days to earnings
        T_post = 2/252     # 2 days after earnings
        r = 0.0

        results = []
        for i in range(n_earnings):
            # Pre-earnings IV
            sigma_pre = sigma_pre_mean + np.random.randn() * 0.05
            sigma_pre = max(sigma_pre, 0.15)

            # Implied move
            implied_mv = self.implied_move(S0, S0, T_pre, r, sigma_pre)

            # Actual move (with noise and fat tail occasionally)
            base_move = actual_move_factor * implied_mv
            fat_tail = np.random.exponential(0.5) if np.random.rand() < 0.1 else 0
            direction = np.sign(np.random.randn())
            actual_mv = (base_move + fat_tail * implied_mv) * direction
            S_post = S0 * (1 + actual_mv)

            # Post-earnings IV (IV crush)
            sigma_post = sigma_pre * sigma_post_factor + np.random.randn() * 0.02
            sigma_post = max(sigma_post, 0.15)

            pnl = self.compute_straddle_pnl(S0, S0, T_pre, T_post, sigma_pre, sigma_post, S_post, r)

            results.append({
                'sigma_pre': sigma_pre,
                'sigma_post': sigma_post,
                'implied_mv': implied_mv * 100,
                'actual_mv': abs(actual_mv) * 100,
                'ratio': abs(actual_mv) / implied_mv,
                'pnl': pnl,
                'iv_crush': (sigma_pre - sigma_post) * 100
            })

        df = pd.DataFrame(results)
        cum_pnl = df['pnl'].cumsum()
        sharpe = df['pnl'].mean() / df['pnl'].std() * np.sqrt(n_earnings / 12) if df['pnl'].std() != 0 else 0
        win_rt = (df['pnl'] > 0).mean()

        print(f"\n{'='*55}")
        print(f" Earnings Straddle Sell Backtest ({n_earnings} events)")
        print(f"{'='*55}")
        print(f" Win Rate            : {win_rt * 100:.1f}%")
        print(f" Avg P&L / event     : ${df['pnl'].mean():.4f}")
        print(f" Total P&L           : ${cum_pnl.iloc[-1]:.3f}")
        print(f" Sharpe (annualized) : {sharpe:.3f}")
        print(f" Avg Implied Move    : {df['implied_mv'].mean():.2f}%")
        print(f" Avg Actual Move     : {df['actual_mv'].mean():.2f}%")
        print(f" Avg IV Crush        : {df['iv_crush'].mean():.1f} vol pts")
        print(f" Implied/Actual Ratio: {df['ratio'].mean():.3f}")
        print(f" Worst Event P&L     : ${df['pnl'].min():.4f}")
        print(f" Best Event P&L      : ${df['pnl'].max():.4f}")
        print(f"{'='*55}")
        return df

bt_earn = EarningsVolBacktester()
results = bt_earn.backtest(n_earnings=300, sigma_pre_mean=0.50, actual_move_factor=0.80)


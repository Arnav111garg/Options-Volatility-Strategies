import numpy as np
import pandas as pd
from scipy.optimize import minimize
from scipy.stats import norm

class GARCH11:
    """Maximum likelihood GARCH (1,1) estimation."""
    def __init__(self):
        self.params = None

    def neg_loglik(self, params, returns):
        omega, alpha, beta = params
        if omega <= 0 or alpha < 0 or beta < 0 or alpha + beta >= 1:
            return 1e10
        n = len(returns)
        r2 = returns**2
        sigma2 = np.zeros(n)
        sigma2[0] = np.var(returns)

        for t in range(1, n):
            sigma2[t] = omega + alpha * r2[t-1] + beta * sigma2[t-1]
            if sigma2[t] <= 0:
                return 1e10

        loglik = -0.5 * np.sum(np.log(sigma2) + r2 / sigma2)
        return -loglik

    def fit(self, returns):
        """Fit GARCH (1,1) via MLE."""
        var0 = np.var(returns)
        x0 = [var0 * 0.05, 0.10, 0.85]
        bounds = [(1e-8, None), (0, 1), (0, 1)]
        result = minimize(self.neg_loglik, x0, args=(returns,),
                          method='L-BFGS-B', bounds=bounds)
        self.params = result.x
        self.omega, self.alpha, self.beta = result.x
        self.long_run_var = self.omega / (1 - self.alpha - self.beta)
        return self

    def forecast(self, returns, horizon=21):
        """Forecast annualized volatility over horizon days."""
        if self.params is None:
            raise ValueError("Must fit first")
        n = len(returns)
        r2 = returns**2
        # Get current conditional variance
        sigma2 = self.long_run_var
        for t in range(1, n):
            sigma2 = self.omega + self.alpha * r2[t-1] + self.beta * sigma2
        # h-step forecast
        ab = self.alpha + self.beta
        forecast_var = np.zeros(horizon)
        for h in range(1, horizon + 1):
            forecast_var[h-1] = (self.long_run_var + ab**(h-1) * (sigma2 - self.long_run_var))
        # Average variance over horizon, annualized
        avg_var = np.mean(forecast_var)
        return np.sqrt(avg_var * 252)

class RVIVTrader:
    """
    Realized vs Implied Volatility trading system.
    Uses GARCH (1,1) forecasts as RV estimate.
    """
    def __init__(self, train_window=252, entry_threshold=0.02, max_hold_days=21):
        self.train_window = train_window
        self.entry_threshold = entry_threshold
        self.max_hold_days = max_hold_days
        self.model = GARCH11()

    def yang_zhang_vol(self, high, low, close, open_, window=21):
        """Yang-Zhang realized volatility estimator."""
        k = 0.34 / (1.34 + (window + 1) / (window - 1))
        overnight_var = (np.log(open_ / close.shift(1))**2).rolling(window).mean()
        oc_var = (np.log(close / open_)**2).rolling(window).mean()
        hl_var = (0.5 * (np.log(high / low)**2) - (2 * np.log(2) - 1) * (np.log(close / open_)**2)).rolling(window).mean()
        sigma2 = overnight_var + k * oc_var + (1 - k) * hl_var
        return np.sqrt(sigma2 * 252)

    def generate_signal(self, returns, iv_series):
        """
        Generate trade signals comparing GARCH RV forecast to IV.
        Returns : +1 (long vol), -1 (short vol), 0 (no trade)
        """
        signals = pd.Series(0, index=iv_series.index)
        n = len(returns)

        for i in range(self.train_window, n):
            train_rets = returns.iloc[i - self.train_window : i].values
            try:
                self.model.fit(train_rets)
                rv_forecast = self.model.forecast(train_rets, horizon=21)
            except:
                continue
            iv_val = iv_series.iloc[i]
            spread = rv_forecast - iv_val

            if spread > self.entry_threshold:
                signals.iloc[i] = 1  # RV > IV: buy vol
            elif spread < -self.entry_threshold:
                signals.iloc[i] = -1  # IV > RV: sell vol

        return signals

    def backtest_pnl(self, signals, vol_returns, vega=100):
        """
        Compute P&L from signals.
        vol_returns : daily change in IV (proxy for vega P&L)
        """
        pnl = signals.shift(1) * vol_returns * vega
        cum_pnl = pnl.cumsum()
        sharpe = pnl.mean() / pnl.std() * np.sqrt(252) if pnl.std() != 0 else 0
        print("\nRV vs IV Trading System:")
        print(f" Annualized Sharpe : {sharpe:.3f}")
        print(f" Total Trades : {(signals != 0).sum()}")
        print(f" Long Vol % : {(signals == 1).mean() * 100:.1f}%")
        print(f" Short Vol % : {(signals == -1).mean() * 100:.1f}%")
        return pnl, cum_pnl


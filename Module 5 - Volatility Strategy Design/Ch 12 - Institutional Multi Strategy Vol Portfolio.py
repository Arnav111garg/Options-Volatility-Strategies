import numpy as np
import pandas as pd
from scipy.optimize import minimize
from scipy.stats import norm
import warnings
warnings.filterwarnings('ignore')

class InstitutionalVolPortfolio:
    """
    Institutional-grade multi-strategy volatility portfolio.
    Combines: VRP harvesting, dispersion, carry, surface arb, tail hedge.
    """
    STRATEGIES = ['vrp_harvest', 'dispersion', 'vol_carry', 'earnings_sell', 'tail_hedge']

    def __init__(self, risk_budget_total=0.10, max_strategy_weight=0.35, tail_hedge_min=0.05, kelly_fraction=0.25):
        self.risk_budget = risk_budget_total
        self.max_w = max_strategy_weight
        self.tail_min = tail_hedge_min
        self.kelly_f = kelly_fraction

    def estimate_strategy_params(self, strategy_returns_df):
        """Estimate mean returns, vol, Sharpe, and correlation for all strategies."""
        mu = strategy_returns_df.mean() * 252
        sig = strategy_returns_df.std() * np.sqrt(252)
        sharpe = mu / sig
        corr = strategy_returns_df.corr()
        return mu, sig, sharpe, corr

    def risk_parity_weights(self, cov_matrix):
        """Compute risk parity weights."""
        n = cov_matrix.shape[0]
        w0 = np.ones(n) / n

        def risk_contribution_diff(w):
            w = np.array(w)
            port_var = w @ cov_matrix @ w
            RC = w * (cov_matrix @ w) / port_var
            return np.sum([(RC[i] - RC[j])**2 for i in range(n) for j in range(i+1, n)])

        constraints = [{'type': 'eq', 'fun': lambda w: sum(w) - 1}]
        bounds = [(0.01, self.max_w)] * n
        # Force minimum tail hedge weight
        bounds[self.STRATEGIES.index('tail_hedge')] = (self.tail_min, 0.20)

        result = minimize(risk_contribution_diff, w0, method='SLSQP', constraints=constraints, bounds=bounds)
        return result.x if result.success else w0

    def max_sharpe_weights(self, mu, cov_matrix):
        """Maximum Sharpe ratio portfolio (Markowitz)."""
        n = len(mu)
        def neg_sharpe(w):
            port_ret = w @ mu
            port_vol = np.sqrt(w @ cov_matrix @ w)
            return -port_ret / (port_vol + 1e-8)

        constraints = [{'type': 'eq', 'fun': lambda w: sum(w) - 1}]
        bounds = [(0.0, self.max_w)] * n
        bounds[self.STRATEGIES.index('tail_hedge')] = (self.tail_min, 0.20)
        w0 = np.ones(n) / n

        result = minimize(neg_sharpe, w0, method='SLSQP', constraints=constraints, bounds=bounds)
        return result.x if result.success else w0

    def compute_portfolio_risk(self, weights, cov_matrix):
        """Compute portfolio risk metrics."""
        w = np.array(weights)
        port_var = w @ cov_matrix @ w
        port_vol = np.sqrt(port_var)
        marginal_rc = cov_matrix @ w
        RC = w * marginal_rc / port_var
        return {
            'portfolio_vol': port_vol,
            'risk_contributions': dict(zip(self.STRATEGIES, RC)),
            'diversification': np.sum(np.sqrt(np.diag(cov_matrix)) * w) / port_vol
        }

    def scale_to_risk_target(self, weights, cov_matrix):
        """Scale weights to hit risk budget target."""
        port_vol = np.sqrt(weights @ cov_matrix @ weights)
        if port_vol > 0:
            scale = self.risk_budget / port_vol
        else:
            scale = 1.0
        return weights * min(scale, 3.0)  # max 3x leverage

    def greek_aggregation(self, weights, strategy_greeks):
        """Aggregate portfolio-level greeks."""
        agg_greeks = {g: 0.0 for g in ['delta', 'gamma', 'vega', 'theta']}
        for strat, w in zip(self.STRATEGIES, weights):
            if strat in strategy_greeks:
                for g in agg_greeks:
                    agg_greeks[g] += w * strategy_greeks[strat].get(g, 0.0)
        return agg_greeks

    def run_portfolio_construction(self, strategy_returns, method='risk_parity'):
        """Full portfolio construction pipeline."""
        mu, sig, sharpe, corr = self.estimate_strategy_params(strategy_returns)
        cov = strategy_returns.cov() * 252

        print(f"\n{'='*60}")
        print(f" Institutional Vol Portfolio Construction ")
        print(f"{'='*60}")
        print(f"\n Strategy Statistics:")
        print(f" {'Strategy':<20}{'Ann.Ret':>10}{'Ann.Vol':>10}{'Sharpe':>10}")
        print(f" {'-'*50}")
        for s in self.STRATEGIES:
            print(f" {s:<20}{mu[s]*100:>9.2f}%{sig[s]*100:>9.2f}%{sharpe[s]:>10.3f}")

        # Build weights
        if method == 'risk_parity':
            weights = self.risk_parity_weights(cov.values)
        elif method == 'max_sharpe':
            weights = self.max_sharpe_weights(mu.values, cov.values)
        else:
            weights = np.ones(len(self.STRATEGIES)) / len(self.STRATEGIES)

        # Scale to risk target
        scaled_w = self.scale_to_risk_target(weights, cov.values)
        risk = self.compute_portfolio_risk(scaled_w, cov.values)

        print(f"\n Optimal Weights ({method}):")
        print(f" {'Strategy':<20}{'Weight':>10}{'Risk Contrib':>15}")
        print(f" {'-'*47}")
        for s, w, rc in zip(self.STRATEGIES, scaled_w, risk['risk_contributions'].values()):
            print(f" {s:<20}{w*100:>9.1f}%{rc*100:>14.1f}%")

        # Portfolio metrics
        port_ret = (scaled_w @ mu.values)
        port_vol = risk['portfolio_vol']
        port_sh = port_ret / port_vol

        print(f"\n Portfolio Metrics:")
        print(f" Ann. Return    : {port_ret * 100:.2f}%")
        print(f" Ann. Volatility: {port_vol * 100:.2f}%")
        print(f" Sharpe Ratio   : {port_sh:.3f}")
        print(f" Diversification: {risk['diversification']:.3f}x")
        print(f" Risk Target     : {self.risk_budget * 100:.0f}%")
        print(f"{'='*60}")

        return scaled_w, risk


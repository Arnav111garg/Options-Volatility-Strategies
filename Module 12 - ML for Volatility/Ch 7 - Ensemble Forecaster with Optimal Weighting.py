import numpy as np
import pandas as pd
from scipy.optimize import minimize
from scipy.stats import t as t_dist
import warnings

class VolatilityEnsemble:
    """
    Ensemble volatility forecaster with multiple combination strategies:
    - Equal weighting
    - QLIKE-optimal weighting (constrained)
    - MCS-based model selection
    - Dynamic (time-varying) weighting
    - Stacking via Ridge meta-learner
    """

    def __init__(self, model_names: list):
        self.model_names = model_names
        self.M = len(model_names)
        self.weights = None

    # -------------------------------------------------------------------------
    # STATIC COMBINATION METHODS
    # -------------------------------------------------------------------------
    def equal_weights(self) -> np.ndarray:
        """Equal weighting."""
        return np.ones(self.M) / self.M

    def qlike_optimal_weights(
        self,
        forecasts: pd.DataFrame,
        rv: pd.Series
    ) -> np.ndarray:
        """
        Compute QLIKE-optimal ensemble weights.

        Parameters
        ----------
        forecasts : (T, M) DataFrame of variance forecasts (in variance units)
        rv : (T,) Series of realised variance
        """
        def qlike_ensemble(w, forecasts_np, rv_np):
            sigma2 = (forecasts_np * w).sum(axis=1).clip(min=1e-8)
            rv_clipped = rv_np.clip(min=1e-8)
            return np.mean(rv_clipped / sigma2 - np.log(rv_clipped / sigma2) - 1)

        f_np = forecasts.values
        rv_np = rv.values

        # Initial guess: equal weights
        w0 = np.ones(self.M) / self.M

        # Constraints: sum = 1, each >= 0
        constraints = [{'type': 'eq', 'fun': lambda w: w.sum() - 1}]
        bounds = [(0.0, 1.0)] * self.M

        result = minimize(
            fun=qlike_ensemble,
            x0=w0,
            args=(f_np, rv_np),
            method='SLSQP',
            bounds=bounds,
            constraints=constraints,
            options={'ftol': 1e-9, 'maxiter': 1000}
        )

        if not result.success:
            warnings.warn(f"Optimisation failed: {result.message}. Returning equal weights.")
            return w0

        return result.x

    def mcs_selection(
        self,
        losses: pd.DataFrame,
        alpha: float = 0.10,
        B: int = 1000
    ) -> list:
        """
        Model Confidence Set (Hansen, Lunde, Nason 2011).
        Simplified t-test version.

        Parameters
        ----------
        losses : (T, M) DataFrame of per-observation losses
        alpha : significance level (typically 0.10 or 0.25)
        B : bootstrap replications

        Returns
        -------
        list of model names in the MCS
        """
        surviving = list(self.model_names)
        while len(surviving) > 1:
            # Compute pairwise loss differentials
            L_sub = losses[surviving].values
            n = L_sub.shape[0]
            M_sub = len(surviving)

            # Test statistic: max t-bar across models
            # t_bar_m = mean(d_m) / se(d_m)
            # where d_m_t = L_m_t - L_bar_t (deviation from cross-sectional mean)
            L_bar = L_sub.mean(axis=1, keepdims=True)
            d = L_sub - L_bar  # (T, M)

            t_stats = []
            for j in range(M_sub):
                d_j = d[:, j]
                mu_j = d_j.mean()
                # Newey-West SE (lag = 4)
                se_j = newey_west_se(d_j, max_lag=4)
                t_stats.append(abs(mu_j / (se_j + 1e-10)))

            # Worst model = largest |t-stat|
            worst_idx = np.argmax(t_stats)

            # Bootstrap p-value
            p_val = bootstrap_tbar_pvalue(d, worst_idx, B=B)

            if p_val < alpha:
                # Reject: remove worst model
                surviving.pop(worst_idx)
            else:
                # Fail to reject: all surviving models in MCS
                break

        return surviving

    # -------------------------------------------------------------------------
    # DYNAMIC WEIGHTING
    # -------------------------------------------------------------------------
    def dynamic_weights(
        self,
        rolling_losses: pd.DataFrame,
        temperature: float = 10.0
    ) -> pd.DataFrame:
        """
        Time-varying ensemble weights based on recent performance.

        Parameters
        ----------
        rolling_losses : (T, M) DataFrame of rolling average losses
        temperature : higher = faster adaptation to recent performance
        """
        # Softmax with negative losses (better performance = higher weight)
        neg_losses = -rolling_losses.values * temperature
        # Numerically stable softmax
        neg_losses -= neg_losses.max(axis=1, keepdims=True)
        exp_l = np.exp(neg_losses)
        weights = exp_l / exp_l.sum(axis=1, keepdims=True)

        return pd.DataFrame(
            weights,
            index=rolling_losses.index,
            columns=rolling_losses.columns
        )

    def stacking_ensemble(
        self,
        oof_forecasts: pd.DataFrame,
        y_oof: pd.Series,
        test_forecasts: pd.DataFrame,
        alpha_ridge: float = 1.0
    ) -> np.ndarray:
        """
        Ridge regression stacking meta-learner.

        Parameters
        ----------
        oof_forecasts : out-of-fold base model predictions (train)
        y_oof : out-of-fold true values
        test_forecasts : base model predictions on test set
        alpha_ridge : regularisation strength
        """
        from sklearn.linear_model import Ridge
        from sklearn.preprocessing import StandardScaler

        scaler = StandardScaler()
        X_oof = scaler.fit_transform(oof_forecasts)
        X_test = scaler.transform(test_forecasts)

        meta = Ridge(alpha=alpha_ridge, positive=True)  # positive = weights >= 0
        meta.fit(X_oof, y_oof)

        # Normalise to sum to 1
        raw_coef = np.maximum(meta.coef_, 0)
        self.weights = raw_coef / (raw_coef.sum() + 1e-10)

        return meta.predict(X_test)

    def combine(self, forecasts: pd.DataFrame, method: str = 'equal') -> pd.Series:
        """Apply weights to combine forecasts."""
        if method == 'equal':
            w = self.equal_weights()
        elif self.weights is not None:
            w = self.weights
        else:
            raise ValueError("Fit weights first or specify method = 'equal'")

        return pd.Series(
            (forecasts.values * w).sum(axis=1),
            index=forecasts.index,
            name='ensemble'
        )


def newey_west_se(x: np.ndarray, max_lag: int = 4) -> float:
    """Newey-West heteroskedasticity and autocorrelation consistent SE."""
    T = len(x)
    gamma0 = np.var(x, ddof=1)
    nw_var = gamma0
    for lag in range(1, max_lag + 1):
        gamma_j = np.cov(x[lag:], x[:-lag])[0, 1]
        nw_var += 2 * (1 - lag / (max_lag + 1)) * gamma_j
    return np.sqrt(nw_var / T)


def bootstrap_tbar_pvalue(
    d: np.ndarray,
    worst_idx: int,
    B: int = 1000
) -> float:
    """Block bootstrap p-value for MCS t-bar statistic."""
    T, M = d.shape
    t_obs = abs(d[:, worst_idx].mean()) / (
        newey_west_se(d[:, worst_idx]) + 1e-10
    )

    t_boot = []
    block_size = max(1, int(T ** 0.5))
    n_blocks = T // block_size

    for _ in range(B):
        # Block bootstrap resample
        starts = np.random.randint(0, T - block_size + 1, size=n_blocks)
        idx = np.concatenate([
            np.arange(s, s + block_size) for s in starts
        ])
        idx = idx[:T]
        d_b = d[idx] - d[idx].mean(axis=0, keepdims=True) + d.mean(axis=0)
        t_b = abs(d_b[:, worst_idx].mean()) / (
            newey_west_se(d_b[:, worst_idx]) + 1e-10
        )
        t_boot.append(t_b)

    return np.mean(np.array(t_boot) >= t_obs)


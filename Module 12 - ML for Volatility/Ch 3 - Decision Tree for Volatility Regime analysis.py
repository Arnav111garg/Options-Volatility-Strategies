import numpy as np
import pandas as pd
from sklearn.tree import DecisionTreeRegressor, export_text, plot_tree
from sklearn.model_selection import TimeSeriesSplit
from sklearn.metrics import mean_squared_error
import matplotlib.pyplot as plt
import matplotlib
matplotlib.rcParams['figure.dpi'] = 150

def decision_tree_vol_regime(X: pd.DataFrame, y: pd.Series, max_depth: int = 4, n_splits: int = 5) -> dict:
    """
    Fit a decision tree to vol forecasting with time-series cross-validation.

    Parameters
    ----------
    X : feature matrix (no lookahead)
    y : target (e.g., log realised vol t+1)
    max_depth : tree depth (2-4 for interpretability)
    n_splits : number of CV splits

    Returns
    -------
    dict with model, CV scores, feature importances
    """
    tscv = TimeSeriesSplit(n_splits=n_splits, gap=1)  # gap=1 avoids adjacency

    cv_mse = []
    cv_r2 = []
    models = []

    for fold, (train_idx, test_idx) in enumerate(tscv.split(X)):
        X_tr, X_te = X.iloc[train_idx], X.iloc[test_idx]
        y_tr, y_te = y.iloc[train_idx], y.iloc[test_idx]

        # Fit tree
        tree = DecisionTreeRegressor(
            max_depth=max_depth,
            min_samples_leaf=21,       # ~1 month of data per leaf
            min_samples_split=42,      # ~2 months to split
            criterion='squared_error',
            random_state=42
        )
        tree.fit(X_tr, y_tr)

        # Evaluate
        y_pred = tree.predict(X_te)
        mse = mean_squared_error(y_te, y_pred)
        ss_res = np.sum((y_te - y_pred) ** 2)
        ss_tot = np.sum((y_te - y_te.mean()) ** 2)
        r2 = 1 - ss_res / ss_tot

        cv_mse.append(mse)
        cv_r2.append(r2)
        models.append(tree)

        print(f"Fold {fold + 1}/{n_splits}: MSE={mse:.6f}, R2={r2:.4f}, Leaves={tree.get_n_leaves()}")

    # Best model = highest R2 on CV
    best_idx = np.argmax(cv_r2)
    best_model = models[best_idx]

    # Feature importances
    feat_imp = pd.Series(
        best_model.feature_importances_,
        index=X.columns
    ).sort_values(ascending=False)

    # Print tree rules
    print("\n--- Decision Tree Rules ---")
    print(export_text(best_model, feature_names=list(X.columns)))

    return {
        'models': models,
        'best_model': best_model,
        'cv_mse': cv_mse,
        'cv_r2': cv_r2,
        'feat_importances': feat_imp,
        'mean_r2': np.mean(cv_r2),
        'std_r2': np.std(cv_r2),
    }


def optimal_tree_depth(X: pd.DataFrame, y: pd.Series, depths: list = range(1, 12)) -> pd.DataFrame:
    """
    Grid search over tree depth with time-series CV.
    Returns DataFrame of train / test R2 by depth.
    """
    tscv = TimeSeriesSplit(n_splits=5, gap=1)
    results = []

    for d in depths:
        train_r2_folds, test_r2_folds = [], []

        for train_idx, test_idx in tscv.split(X):
            X_tr, X_te = X.iloc[train_idx], X.iloc[test_idx]
            y_tr, y_te = y.iloc[train_idx], y.iloc[test_idx]

            tree = DecisionTreeRegressor(
                max_depth=d, min_samples_leaf=21, random_state=42
            )
            tree.fit(X_tr, y_tr)

            def r2(y_true, y_pred):
                ss_res = np.sum((y_true - y_pred) ** 2)
                ss_tot = np.sum((y_true - y_true.mean()) ** 2)
                return 1 - ss_res / ss_tot

            train_r2_folds.append(r2(y_tr, tree.predict(X_tr)))
            test_r2_folds.append(r2(y_te, tree.predict(X_te)))

         # Append average results across CV folds
        results.append({
            'depth': d,
            'train_r2': np.mean(train_r2_folds),
            'test_r2': np.mean(test_r2_folds),
            'test_r2_std': np.std(test_r2_folds),
        })

    return pd.DataFrame(results).set_index('depth')


def plot_vol_tree_importances(feat_imp: pd.Series, top_n: int = 20):
    """Plot feature importances from a fitted tree."""
    fig, ax = plt.subplots(figsize=(10, 6))
    feat_imp.head(top_n).sort_values().plot.barh(
        ax=ax, color='steelblue', edgecolor='navy', alpha=0.8
    )
    ax.set_title(f'Top {top_n} Feature Importances (Decision Tree)', fontsize=14, fontweight='bold')
    ax.set_xlabel('Importance (impurity reduction)', fontsize=12)
    ax.axvline(x=0.05, color='red', linestyle='--', alpha=0.7, label='5% threshold')
    ax.legend()
    plt.tight_layout()
    return fig


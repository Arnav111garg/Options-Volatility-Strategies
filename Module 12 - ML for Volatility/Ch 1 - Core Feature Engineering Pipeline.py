import numpy as np
import pandas as pd
from typing import Optional, List, Tuple

class VolatilityFeatureEngineer:
    """
    Production-grade feature engineering for volatility forecasting.
    All features are strictly look-ahead free.
    """

    def __init__(self, price_df: pd.DataFrame, windows: List[int] = [5, 10, 21, 63, 126, 252]):
        """
        Parameters
        ----------
        price_df : DataFrame with columns ['open', 'high', 'low', 'close', 'volume'] and DatetimeIndex
        windows : List of lookback windows (trading days)
        """
        self.df = price_df.copy()
        self.windows = windows
        self._compute_returns()

    def _compute_returns(self):
        """Compute log returns (no lookahead)."""
        self.df['log_ret'] = np.log(
            self.df['close'] / self.df['close'].shift(1)
        )
        self.df.dropna(inplace=True)

    # ============================================================
    # 1. RETURN-BASED FEATURES
    # ============================================================
    def add_rolling_moments(self) -> 'VolatilityFeatureEngineer':
        """Rolling mean, std, skewness, kurtosis."""
        for w in self.windows:
            roll = self.df['log_ret'].rolling(w, min_periods=w // 2)
            self.df[f'ret_mean_{w}d'] = roll.mean()
            self.df[f'ret_std_{w}d'] = roll.std()
            self.df[f'ret_skew_{w}d'] = roll.skew()
            self.df[f'ret_kurt_{w}d'] = roll.kurt()
            # Annualised realised vol (close-to-close)
            self.df[f'rv_cc_{w}d'] = roll.std() * np.sqrt(252)
        return self

    def add_parkinson_vol(self) -> 'VolatilityFeatureEngineer':
        """Parkinson's high-low range estimator."""
        log_hl = np.log(self.df['high'] / self.df['low'])
        park_daily = log_hl ** 2 / (4 * np.log(2))
        for w in self.windows:
            self.df[f'park_vol_{w}d'] = np.sqrt(
                park_daily.rolling(w).mean() * 252
            )
        return self

    def add_garman_klass(self) -> 'VolatilityFeatureEngineer':
        """Garman-Klass estimator."""
        u = np.log(self.df['high'] / self.df['open'])
        d = np.log(self.df['low'] / self.df['open'])
        c = np.log(self.df['close'] / self.df['open'])
        gk_daily = 0.5 * u * d - (2 * np.log(2) - 1) * (c ** 2)
        # Note: take max with 0 to handle numerical issues
        gk_daily = gk_daily.clip(lower=0)
        for w in self.windows:
            self.df[f'gk_vol_{w}d'] = np.sqrt(
                gk_daily.rolling(w).mean() * 252
            )
        return self

    # ============================================================
    # 2. VOLATILITY RATIO FEATURES
    # ============================================================
    def add_vol_ratios(self) -> 'VolatilityFeatureEngineer':
        """
        Volatility ratios capture mean-reversion and term structure.
        vol_ratio = short_vol / long_vol
        > 1 implies short-term spike; < 1 implies low short-term vol
        """
        window_pairs = [
            (5, 21), (5, 63), (10, 63), (21, 63),
            (21, 126), (63, 252)
        ]
        for (ws, wl) in window_pairs:
            short_rv = f'rv_cc_{ws}d'
            long_rv = f'rv_cc_{wl}d'
            if short_rv in self.df.columns and long_rv in self.df.columns:
                self.df[f'vol_ratio_{ws}_{wl}'] = (
                    self.df[short_rv] / (self.df[long_rv] + 1e-10)
                )
        return self

    # ============================================================
    # 3. LEVERAGE EFFECT FEATURES
    # ============================================================
    def add_leverage_features(self) -> 'VolatilityFeatureEngineer':
        """
        Leverage effect: negative returns predict higher future volatility.
        Feature: lagged return interacted with sign.
        """
        for lag in [1, 2, 3, 5, 10]:
            r = self.df['log_ret'].shift(lag)
            self.df[f'neg_ret_{lag}d'] = r.clip(upper=0)  # min(r, 0)
            self.df[f'pos_ret_{lag}d'] = r.clip(lower=0)  # max(r, 0)
            self.df[f'ret_sq_{lag}d'] = r ** 2
            self.df[f'ret_abs_{lag}d'] = r.abs()
        return self

    # ============================================================
    # 4. VOLUME FEATURES
    # ============================================================
    def add_volume_features(self) -> 'VolatilityFeatureEngineer':
        """Volume-based features."""
        log_vol = np.log(self.df['volume'].clip(lower=1))
        for w in [5, 21, 63]:
            roll_mean = log_vol.rolling(w).mean()
            roll_std = log_vol.rolling(w).std()
            self.df[f'vol_zscore_{w}d'] = (log_vol - roll_mean) / (roll_std + 1e-10)

        # Volume-weighted volatility (Clark 1973 subordination hypothesis)
        self.df['vwvol'] = (
            self.df['log_ret'].abs() * np.log(self.df['volume'].clip(lower=1))
        )
        return self

    # ============================================================
    # 5. CALENDAR FEATURES
    # ============================================================
    def add_calendar_features(self) -> 'VolatilityFeatureEngineer':
        """Cyclical calendar encoding."""
        idx = self.df.index
        # Day of week (0=Monday, 4=Friday)
        dow = idx.dayofweek
        self.df['dow_sin'] = np.sin(2 * np.pi * dow / 5)
        self.df['dow_cos'] = np.cos(2 * np.pi * dow / 5)
        # Month of year
        moy = idx.month - 1  # 0-indexed
        self.df['moy_sin'] = np.sin(2 * np.pi * moy / 12)
        self.df['moy_cos'] = np.cos(2 * np.pi * moy / 12)
        # Week of year
        woy = idx.isocalendar().week.values - 1
        self.df['woy_sin'] = np.sin(2 * np.pi * woy / 52)
        self.df['woy_cos'] = np.cos(2 * np.pi * woy / 52)
        return self

    # ============================================================
    # 6. NORMALISATION
    # ============================================================
    def rolling_zscore_normalise(self, window: int = 252, cols: Optional[List[str]] = None) -> 'VolatilityFeatureEngineer':
        """
        Rolling Z-score normalisation (look-ahead free).
        """
        if cols is None:
            cols = [c for c in self.df.columns if c not in ['open', 'high', 'low', 'close', 'volume', 'log_ret']]

        for col in cols:
            roll = self.df[col].rolling(window, min_periods=window // 4)
            mu = roll.mean()
            sig = roll.std()
            self.df[f'{col}_z'] = (self.df[col] - mu) / (sig + 1e-10)
        return self

    def build(self) -> pd.DataFrame:
        """Execute all feature engineering steps and return feature matrix."""
        return (
            self.add_rolling_moments()
            .add_parkinson_vol()
            .add_garman_klass()
            .add_vol_ratios()
            .add_leverage_features()
            .add_volume_features()
            .add_calendar_features()
            .df
        )


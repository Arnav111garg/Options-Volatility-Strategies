    # Download SPY data
    spy = yf.download('SPY', start='2010-01-01', end='2024-01-01', auto_adjust=True)

    # If columns have a MultiIndex due to yfinance format, flatten them
    if isinstance(spy.columns, pd.MultiIndex):
        spy.columns = [col[0].lower() for col in spy.columns]
    else:
        spy.columns = [c.lower() for c in spy.columns]

    # Build features
    feat_eng = VolatilityFeatureEngineer(spy)
    features = feat_eng.build()

    print(f"Feature matrix shape: {features.shape}")
    print(f"\nFeature columns:\n{[c for c in features.columns if c not in spy.columns]}")
    print(f"\nMissing values:\n{features.isnull().sum().sum()} total NaN")


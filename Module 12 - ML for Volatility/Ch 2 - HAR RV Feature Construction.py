import numpy as np
import pandas as pd
from arch import arch_model
from typing import List

def compute_har_features(rv: pd.Series, horizons: List[int] = [1, 5, 22]) -> pd.DataFrame:
    """
    Construct HAR-type features from realised volatility series.

    Parameters
    ----------
    rv : pd.Series of daily realised variance (not vol), index = dates
    horizons : lookback windows [daily , weekly , monthly]

    Returns
    -------
    pd.DataFrame with HAR features (no lookahead)
    """
    feats = pd.DataFrame(index=rv.index)

    # Level features
    for h in horizons:
        feats[f'rv_avg_{h}d'] = rv.rolling(h).mean()  # avg RV
        feats[f'log_rv_avg_{h}d'] = np.log(rv.rolling(h).mean().clip(lower=1e-10))  # log avg RV
        feats[f'sqrt_rv_{h}d'] = np.sqrt(rv.rolling(h).mean().clip(lower=0))  # sqrt (annualised vol)

    # Lag features (explicitly shifted to be t-1 available)
    for lag in range(1, 6):
        feats[f'rv_lag_{lag}'] = rv.shift(lag)
        feats[f'log_rv_lag_{lag}'] = np.log(rv.shift(lag).clip(lower=1e-10))

    # Volatility of volatility (realised)
    for h in [5, 21]:
        feats[f'vol_of_rv_{h}d'] = np.log(rv.clip(lower=1e-10)).rolling(h).std()

    # Persistence measure: autocorrelation of RV
    for lag in [1, 5, 10, 21]:
        feats[f'rv_acf_{lag}'] = rv.shift(1).rolling(63).corr(rv.shift(lag + 1))

    return feats.dropna(how='all')


def compute_jump_features(rv: pd.Series, bv: pd.Series) -> pd.DataFrame:
    """
    Compute jump-based features from RV and Bipower Variation.

    Parameters
    ----------
    rv : daily realised variance
    bv : daily bipower variation
    """
    feats = pd.DataFrame(index=rv.index)

    # Jump component (non-negative)
    jump = (rv - bv).clip(lower=0)
    cont = bv.copy()

    # Relative jump
    feats['rel_jump'] = jump / (rv.clip(lower=1e-10))
    feats['log_jump'] = np.log1p(jump)  # log (1+ J)
    feats['log_cont'] = np.log(cont.clip(lower=1e-10))

    # Signed realised semivariance proxy (using daily return)
    for h in [1, 5, 21]:
        feats[f'jump_avg_{h}d'] = jump.rolling(h).mean()
        feats[f'cont_avg_{h}d'] = cont.rolling(h).mean()

    return feats


def compute_vrp_features(atm_iv: pd.Series, rv: pd.Series, tau_days: int = 21) -> pd.DataFrame:
    """
    Compute Variance Risk Premium features.

    VRP_t = ATM_IV_{t}^2 - RV_{t-tau:t} (backward-looking, so no lookahead)

    Parameters
    ----------
    atm_iv : at-the-money implied vol (annualised, tau-day)
    rv : realised vol (annualised), computed over same tau horizon
    tau_days : horizon in trading days
    """
    feats = pd.DataFrame(index=atm_iv.index)

    # Convert annualised vols to variance
    iv_var = (atm_iv / 100) ** 2  # if IV in percentage points
    rv_avg = (rv / 100) ** 2  # if RV in percentage points

    feats['vrp'] = iv_var - rv_avg.shift(1)  # shift: use realised from before
    feats['vrp_zscore'] = (feats['vrp'] - feats['vrp'].rolling(252).mean()) / (feats['vrp'].rolling(252).std() + 1e-10)
    feats['vrp_sign'] = np.sign(feats['vrp'])
    feats['log_iv_rv_ratio'] = np.log((iv_var + 1e-10) / (rv_avg.shift(1).clip(lower=1e-10)))

    return feats


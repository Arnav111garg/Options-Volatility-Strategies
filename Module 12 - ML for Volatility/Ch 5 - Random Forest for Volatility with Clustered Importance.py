import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestRegressor
from sklearn.inspection import permutation_importance
from sklearn.cluster import KMeans
from sklearn.preprocessing import StandardScaler
from scipy.cluster.hierarchy import dendrogram, linkage, fcluster
from scipy.spatial.distance import squareform
import matplotlib.pyplot as plt

class RandomForestVolatility:
    """
    Random Forest volatility forecaster with:
    - Time-series cross-validation (no leakage)
    - Clustered feature importance (López de Prado 2020)
    - Conditional feature importance
    - Out-of-bag uncertainty quantification
    """

    def __init__(
        self,
        n_estimators: int = 500,
        max_features: float = 0.33,
        min_samples_leaf: int = 21,
        n_jobs: int = -1,
        random_state: int = 42
    ):
        self.params = {
            'n_estimators': n_estimators,
            'max_features': max_features,
            'min_samples_leaf': min_samples_leaf,
            'max_samples': 0.8,  # subsample fraction (not standard RF)
            'oob_score': True,
            'n_jobs': n_jobs,
            'random_state': random_state,
        }
        self.model = None

    def fit(self, X: pd.DataFrame, y: pd.Series) -> 'RandomForestVolatility':
        self.feature_cols = X.columns.tolist()
        self.model = RandomForestRegressor(**self.params)
        self.model.fit(X, y)
        print(f"OOB R2 (biased for time series): {self.model.oob_score_:.4f}")
        return self

    def predict_with_uncertainty(self, X: pd.DataFrame) -> pd.DataFrame:
        """
        Predict mean and std across individual trees (Monte Carlo dropout analog).
        Provides uncertainty quantification for risk management.
        """
        predictions = np.array([
            tree.predict(X.values) for tree in self.model.estimators_
        ])
        return pd.DataFrame({
            'mean': predictions.mean(axis=0),
            'std': predictions.std(axis=0),
            'p10': np.percentile(predictions, 10, axis=0),
            'p90': np.percentile(predictions, 90, axis=0),
            'q2_5': np.percentile(predictions, 2.5, axis=0),
            'q97_5': np.percentile(predictions, 97.5, axis=0),
        }, index=X.index)

    def clustered_feature_importance(
        self,
        X: pd.DataFrame,
        y: pd.Series,
        corr_threshold: float = 0.7
    ) -> pd.DataFrame:
        """
        Compute clustered MDA importance following López de Prado (2020).
        Clusters correlated features and computes importance per cluster.

        Parameters
        ----------
        X : feature matrix
        y : target
        corr_threshold : features with |corr| > threshold are clustered
        """
        # Step 1: Compute pairwise correlation
        corr_matrix = X.corr().abs()

        # Step 2: Hierarchical clustering on correlation distance
        dist_matrix = 1 - corr_matrix.values
        np.fill_diagonal(dist_matrix, 0)
        condensed = squareform(dist_matrix)
        linkage_matrix = linkage(condensed, method='ward')

        # Step 3: Cut dendrogram at threshold
        cluster_labels = fcluster(
            linkage_matrix,
            t=1 - corr_threshold,
            criterion='distance'
        )

        # Step 4: For each cluster, compute representative importance
        n_clusters = cluster_labels.max()
        cluster_imp = []

        for c in range(1, n_clusters + 1):
            cluster_features = [
                X.columns[i] for i, l in enumerate(cluster_labels) if l == c
            ]

            if len(cluster_features) == 1:
                # Singleton cluster: use standard permutation importance
                perm_imp = permutation_importance(
                    self.model, X[cluster_features], y,
                    n_repeats=20, random_state=42
                )
                imp = perm_imp.importances_mean[0]
                cluster_imp.append({
                    'cluster': c,
                    'features': cluster_features,
                    'representative': cluster_features[0],
                    'cluster_imp': imp,
                    'n_features': 1
                })
            else:
                # Create aggregate cluster feature (first PC)
                from sklearn.decomposition import PCA
                pca = PCA(n_components=1)
                X_cluster = StandardScaler().fit_transform(X[cluster_features])
                X_pc1 = pca.fit_transform(X_cluster)
                X_mod = X.copy()
                X_mod['_cluster_pc1'] = X_pc1.ravel()

                # Drop cluster features, add PC
                X_mod_reduced = X_mod.drop(columns=cluster_features)
                X_mod_reduced['_cluster_pc1'] = X_mod['_cluster_pc1']

                # Permutation importance of PC1
                temp_model = RandomForestRegressor(**self.params)
                temp_model.fit(X_mod_reduced, y)
                perm_imp = permutation_importance(
                    temp_model, X_mod_reduced, y,
                    n_repeats=20, random_state=42
                )
                pc1_idx = list(X_mod_reduced.columns).index('_cluster_pc1')
                imp = perm_imp.importances_mean[pc1_idx]

                # Best individual feature = highest marginal MDI
                mdi = pd.Series(self.model.feature_importances_, index=X.columns)
                best_feat = mdi[cluster_features].idxmax()

                cluster_imp.append({
                    'cluster': c,
                    'features': cluster_features,
                    'representative': best_feat,
                    'cluster_imp': imp,
                    'n_features': len(cluster_features)
                })

        result = pd.DataFrame(cluster_imp).sort_values(
            'cluster_imp', ascending=False
        )
        return result

    def conditional_feature_importance(
        self,
        X: pd.DataFrame,
        y: pd.Series,
        condition_feature: str,
        condition_threshold: float
    ) -> tuple:
        """
        Compute feature importance separately in high-vol and low-vol regimes.
        Reveals which features matter most in each regime.
        """
        mask_high = X[condition_feature] > condition_threshold
        mask_low = ~mask_high

        def perm_imp_subset(mask):
            perm = permutation_importance(
                self.model, X[mask], y[mask],
                n_repeats=20, random_state=42
            )
            return pd.Series(perm.importances_mean, index=X.columns).sort_values(ascending=False)

        imp_high = perm_imp_subset(mask_high)
        imp_low = perm_imp_subset(mask_low)

        return imp_high, imp_low


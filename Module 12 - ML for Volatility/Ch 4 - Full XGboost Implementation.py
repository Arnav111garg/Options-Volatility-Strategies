import numpy as np
import pandas as pd
import xgboost as xgb
from sklearn.model_selection import TimeSeriesSplit
from sklearn.metrics import mean_squared_error
from typing import Optional, Dict, Any

class XGBoostVolatilityForecaster:
    """
    Production XGBoost volatility forecaster with:
    - Walk-forward time-series CV
    - Optuna hyperparameter optimisation
    - QLIKE and MSE evaluation
    - SHAP-based feature attribution
    """

    def __init__(self, n_splits: int = 5, embargo_days: int = 5, target_type: str = 'log_rv'):
        """
        Parameters
        ----------
        n_splits : number of walk-forward CV folds
        embargo_days : days to exclude between train / test
        target_type : 'rv', 'log_rv', or 'vol' (sqrt of rv)
        """
        self.n_splits = n_splits
        self.embargo_days = embargo_days
        self.target_type = target_type
        self.best_params = None
        self.model = None
        self.feature_cols = None

    def _prepare_target(self, rv_series: pd.Series) -> pd.Series:
        """Transform RV to target variable."""
        if self.target_type == 'log_rv':
            return np.log(rv_series.clip(lower=1e-8))
        elif self.target_type == 'vol':
            return np.sqrt(rv_series.clip(lower=0))
        return rv_series  # raw RV

    def _qlike_loss(self, y_true: np.ndarray, y_pred: np.ndarray) -> float:
        """QLike loss (Patton 2011) - consistent for true variance."""
        if self.target_type == 'log_rv':
            # Back-transform to variance level
            sigma2_hat = np.exp(y_pred)
            rv = np.exp(y_true)
        else:
            sigma2_hat = np.maximum(y_pred, 1e-8)
            rv = y_true

        return np.mean(rv / sigma2_hat - np.log(rv / sigma2_hat) - 1)

    def walk_forward_cv(self, X: pd.DataFrame, y: pd.Series, params: Optional[Dict] = None) -> Dict:
        """
        Walk-forward cross-validation with embargo.

        Parameters
        ----------
        X : feature matrix
        y : target (already transformed)
        params : XGBoost parameters (uses best_params if None)
        """
        if params is None:
            params = self.best_params or self._default_params()

        tscv = TimeSeriesSplit(n_splits=self.n_splits, gap=self.embargo_days)

        results = {
            'fold_mse': [],
            'fold_qlike': [],
            'fold_r2': [],
            'fold_da': [],  # DA = directional accuracy
            'train_sizes': [],
            'test_sizes': [],
            'predictions': pd.Series(dtype=float, index=y.index),
        }

        for fold, (train_idx, test_idx) in enumerate(tscv.split(X)):
            X_tr = X.iloc[train_idx]
            y_tr = y.iloc[train_idx]
            X_te = X.iloc[test_idx]
            y_te = y.iloc[test_idx]

            dtrain = xgb.DMatrix(X_tr, label=y_tr, feature_names=X.columns.tolist())
            dtest = xgb.DMatrix(X_te, label=y_te, feature_names=X.columns.tolist())

            xgb_params = {**params, 'verbosity': 0}
            n_rounds = xgb_params.pop('n_estimators', 500)

            booster = xgb.train(
                xgb_params,
                dtrain,
                num_boost_round=n_rounds,
                evals=[(dtrain, 'train'), (dtest, 'eval')],
                early_stopping_rounds=50,
                verbose_eval=False,
            )

            y_pred = booster.predict(dtest)

            # Metrics
            mse = mean_squared_error(y_te, y_pred)
            qlike = self._qlike_loss(y_te.values, y_pred)
            ss_res = np.sum((y_te.values - y_pred) ** 2)
            ss_tot = np.sum((y_te.values - y_te.mean()) ** 2)
            r2 = 1 - ss_res / (ss_tot + 1e-10)

            # Directional accuracy
            dy_true = np.diff(y_te.values)
            dy_pred = np.diff(y_pred)
            da = np.mean(np.sign(dy_true) == np.sign(dy_pred))

            results['fold_mse'].append(mse)
            results['fold_qlike'].append(qlike)
            results['fold_r2'].append(r2)
            results['fold_da'].append(da)
            results['train_sizes'].append(len(train_idx))
            results['test_sizes'].append(len(test_idx))

            # Store predictions
            results['predictions'].iloc[test_idx] = y_pred

            print(
                f"Fold {fold + 1}/{self.n_splits}: "
                f"R2={r2:.4f} | QLIKE={qlike:.6f} | DA={da:.3f} | "
                f"Train={len(train_idx)}, Test={len(test_idx)}"
            )

        results['mean_r2'] = np.mean(results['fold_r2'])
        results['mean_qlike'] = np.mean(results['fold_qlike'])
        results['mean_da'] = np.mean(results['fold_da'])
        return results

    def optimise_hyperparams(self, X: pd.DataFrame, y: pd.Series, n_trials: int = 100) -> Dict:
        """
        Optuna-based hyperparameter optimisation.
        Minimises QLIKE loss via time-series CV.
        """
        def objective(trial):
            params = {
                'n_estimators': trial.suggest_int('n_estimators', 200, 2000),
                'learning_rate': trial.suggest_float('lr', 0.001, 0.1, log=True),
                'max_depth': trial.suggest_int('max_depth', 2, 8),
                'min_child_weight': trial.suggest_int('min_child_weight', 3, 50),
                'subsample': trial.suggest_float('subsample', 0.4, 1.0),
                'colsample_bytree': trial.suggest_float('colsample_bytree', 0.3, 1.0),
                'reg_lambda': trial.suggest_float('lambda', 0.1, 20.0, log=True),
                'reg_alpha': trial.suggest_float('alpha', 0.0, 5.0),
                'gamma': trial.suggest_float('gamma', 0.0, 5.0),
                'objective': 'reg:squarederror',
                'tree_method': 'hist',
                'device': 'cpu',
            }
            cv_res = self.walk_forward_cv(X, y, params)
            return cv_res['mean_qlike']

        study = optuna.create_study(direction='minimize', sampler=optuna.samplers.TPESampler(seed=42))
        study.optimize(objective, n_trials=n_trials, show_progress_bar=True)

        self.best_params = study.best_params
        print(f"\nBest QLIKE: {study.best_value:.6f}")
        print(f"Best params: {study.best_params}")
        return study.best_params

    def fit(self, X: pd.DataFrame, y: pd.Series, params: Optional[Dict] = None) -> 'XGBoostVolatilityForecaster':
        """Fit final model on all data."""
        if params is None:
            params = self.best_params or self._default_params()

        self.feature_cols = X.columns.tolist()
        dtrain = xgb.DMatrix(X, label=y, feature_names=self.feature_cols)

        xgb_params = {**params, 'verbosity': 0}
        n_rounds = xgb_params.pop('n_estimators', 500)

        self.model = xgb.train(
            xgb_params,
            dtrain,
            num_boost_round=n_rounds,
        )
        return self

    def predict(self, X: pd.DataFrame) -> np.ndarray:
        """Generate predictions."""
        dtest = xgb.DMatrix(X, feature_names=self.feature_cols)
        return self.model.predict(dtest)

    def feature_importance_df(self) -> pd.DataFrame:
        """Return feature importances as sorted DataFrame."""
        imp = self.model.get_score(importance_type='gain')
        return pd.DataFrame({
            'feature': list(imp.keys()),
            'importance': list(imp.values())
        }).sort_values('importance', ascending=False)

    def _default_params(self) -> Dict:
        return {
            'n_estimators': 500,
            'learning_rate': 0.02,
            'max_depth': 4,
            'min_child_weight': 10,
            'subsample': 0.8,
            'colsample_bytree': 0.7,
            'reg_lambda': 2.0,
            'objective': 'reg:squarederror',
            'tree_method': 'hist',
        }


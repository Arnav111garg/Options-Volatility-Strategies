import numpy as np
import pandas as pd
from dataclasses import dataclass, field
from typing import Optional

@dataclass
class StrategyConfig:
    """ Configuration for ML volatility strategy backtesting. """
    target_daily_vol: float = 0.01      # 1% target daily P&L vol
    transaction_cost: float = 0.002     # 0.2% of notional per trade
    max_position: float = 1.0           # max notional exposure
    rebalance_freq: int = 1             # days between delta-hedges
    signal_threshold: float = 0.01      # min |signal| to trade (vol points)
    stop_loss_mult: float = 3.0         # stop at 3x target daily vol
    vol_lookback: int = 63              # for position sizing
    kelly_fraction: float = 0.25        # fractional Kelly


class MLVolatilityBacktester:
    """
    Walk-forward backtest for ML-based volatility strategies.

    Simulates:
    - Delta-hedged straddle (long/short gamma) strategy
    - VRP harvesting with ML filter
    - Transaction costs (bid-ask + commissions)
    - Position sizing via vol-target
    """

    def __init__(self, config: StrategyConfig = None):
        self.config = config or StrategyConfig()
        self.results_ = None

    def run_straddle_backtest(self,
                              forecasts: pd.Series,      # ML var forecast
                              atm_iv: pd.Series,         # ATM implied vol (daily)
                              realized_vol: pd.Series,   # ex-post realised vol
                              vega: pd.Series,           # approx vega per unit
                              spot: pd.Series            # spot price
                              ) -> pd.DataFrame:
        """
        Simulate a delta-hedged straddle strategy.

        Signal: forecast_var - IV_var
        Position: long straddle if signal > threshold, short if signal < -threshold
        P&L: (realized_var - IV_var) * Gamma / 2 * S^2 - costs
        """
        cfg = self.config

        # Signal (variance units)
        iv_var = atm_iv ** 2
        fore_var = forecasts
        signal = fore_var - iv_var

        # Position (+1 = long straddle, -1 = short, 0 = flat)
        position = pd.Series(0.0, index=signal.index)
        position[signal > cfg.signal_threshold] = 1.0
        position[signal < -cfg.signal_threshold] = -1.0

        # Volatility-target position sizing
        rv_rolling = realized_vol.rolling(cfg.vol_lookback).std()
        notional = cfg.target_daily_vol / (vega * rv_rolling + 1e-8)
        notional = notional.clip(upper=cfg.max_position)
        sized_position = position * notional

        # P&L: gamma P&L = (RV - IV) * exposure
        # Simplified: daily_pnl = position * (rv_today - iv_yesterday)
        rv_daily = realized_vol  # today's realised vol

        # Straddle P&L: long gamma profits if RV > IV
        raw_pnl = sized_position.shift(1) * (rv_daily ** 2 - iv_var.shift(1))

        # Transaction costs: on position changes
        turnover = sized_position.diff().abs()
        t_costs = turnover * cfg.transaction_cost

        net_pnl = raw_pnl - t_costs

        # Stop loss
        cum_pnl = net_pnl.cumsum()
        rolling_max = cum_pnl.cummax()
        drawdown = cum_pnl - rolling_max
        stop_triggered = drawdown < -cfg.stop_loss_mult * cfg.target_daily_vol
        net_pnl[stop_triggered.shift(1).fillna(False)] = 0.0

        # Performance analytics
        results = self._compute_performance(net_pnl, sized_position, t_costs, signal)
        return results

    def _compute_performance(self,
                             pnl: pd.Series,
                             position: pd.Series,
                             costs: pd.Series,
                             signal: pd.Series) -> pd.DataFrame:
        """Compute comprehensive performance metrics."""
        T = 252  # annualisation

        pnl_ann = pnl.mean() * T
        vol_ann = pnl.std() * np.sqrt(T)
        sharpe = pnl_ann / (vol_ann + 1e-10)

        cum_pnl = pnl.cumsum()
        rolling_max = cum_pnl.cummax()
        drawdown = (cum_pnl - rolling_max)
        max_dd = drawdown.min()

        calmar = pnl_ann / (abs(max_dd) + 1e-10)
        # Sortino ratio
        downside_ret = pnl[pnl < 0]
        sortino_denom = downside_ret.std() * np.sqrt(T)
        sortino = pnl_ann / (sortino_denom + 1e-10)

        # Hit rate and payoff ratio
        wins = (pnl > 0).sum()
        total = (pnl != 0).sum()
        hit_rate = wins / (total + 1e-10)
        avg_win = pnl[pnl > 0].mean()
        avg_loss = pnl[pnl < 0].mean()
        payoff_ratio = abs(avg_win / (avg_loss + 1e-10))

        # Signal efficiency
        signal_correct = (np.sign(signal.shift(1)) == np.sign(pnl)).mean()
        total_costs = costs.sum()
        gross_pnl = (pnl + costs).sum()
        cost_ratio = total_costs / (abs(gross_pnl) + 1e-10)

        print("\n" + "=" * 50)
        print(" STRATEGY PERFORMANCE SUMMARY ")
        print("=" * 50)
        print(f"Ann. P&L: {pnl_ann:.4f} ({pnl_ann * 100:.2f}%) ")
        print(f"Ann. Vol: {vol_ann:.4f} ({vol_ann * 100:.2f}%) ")
        print(f"Sharpe Ratio : {sharpe:.3f}")
        print(f"Sortino Ratio : {sortino:.3f}")
        print(f"Calmar Ratio : {calmar:.3f}")
        print(f"Max Drawdown : {max_dd:.4f} ({max_dd * 100:.2f}%) ")
        print(f"Hit Rate : {hit_rate:.3f} ({hit_rate * 100:.1f}%) ")
        print(f"Payoff Ratio : {payoff_ratio:.3f}")
        print(f"Signal Accuracy : {signal_correct:.3f}")
        print(f"Cost Ratio : {cost_ratio:.3f} ({cost_ratio * 100:.1f}% of gross)")
        print("=" * 50)

        metrics = {
            'ann_pnl': pnl_ann,
            'ann_vol': vol_ann,
            'sharpe': sharpe,
            'sortino': sortino,
            'calmar': calmar,
            'max_drawdown': max_dd,
            'hit_rate': hit_rate,
            'payoff_ratio': payoff_ratio,
            'signal_acc': signal_correct,
            'cost_ratio': cost_ratio,
            'cum_pnl': cum_pnl,
            'drawdown': drawdown,
            'pnl_daily': pnl,
            'position': position,
        }
        return metrics



import numpy as np
import pandas as pd
from sklearn.decomposition import PCA
from sklearn.preprocessing import StandardScaler
import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d import Axes3D

class IVSurfaceForecaster:
    """
    Implied Volatility Surface forecasting via PCA dimensionality reduction.

    Workflow:
    1. Represent each day's surface as a flattened vector
    2. PCA to extract principal components
    3. Forecast PC scores with LSTM or XGBoost
    4. Reconstruct forecasted surface from PC forecasts
    """

    def __init__(self, strikes: np.ndarray, expiries: np.ndarray, n_components: int = 5):
        """
        Parameters
        ----------
        strikes : np.ndarray
            Relative strikes, e.g. [0.8, 0.9, 1.0, 1.1, 1.2]
        expiries : np.ndarray
            Expiries in years, e.g. [1/12, 3/12, 6/12, 1]
        n_components : int
            Number of PCA components
        """
        self.strikes = strikes
        self.expiries = expiries
        self.n_components = n_components
        self.n_strikes = len(strikes)
        self.n_expiries = len(expiries)
        self.surface_dim = self.n_strikes * self.n_expiries
        self.pca = None
        self.scaler = StandardScaler()

    def fit_pca(self, surfaces: np.ndarray) -> 'IVSurfaceForecaster':
        """
        Fit PCA to historical surface data.

        Parameters
        ----------
        surfaces : (T, n_strikes * n_expiries) array of IV surfaces,
            flattened (row-major, strikes vary fastest)
        """
        # Scale
        surfaces_sc = self.scaler.fit_transform(surfaces)

        # PCA
        self.pca = PCA(n_components=self.n_components)
        self.pca.fit(surfaces_sc)

        explained = self.pca.explained_variance_ratio_
        cumulative = np.cumsum(explained)

        print(f"Variance explained by {self.n_components} components:")
        for i, (e, c) in enumerate(zip(explained, cumulative)):
            print(f"  PC{i + 1}: {e:.3f} ({c:.3f} cumulative)")

        return self

    def decompose(self, surfaces: np.ndarray) -> np.ndarray:
        """Project surfaces onto PC scores. Returns (T, n_components)."""
        surfaces_sc = self.scaler.transform(surfaces)
        return self.pca.transform(surfaces_sc)

    def reconstruct(self, scores: np.ndarray) -> np.ndarray:
        """
        Reconstruct surface from PC scores.
        Returns (T, n_strikes * n_expiries) array of IVs.
        """
        surfaces_sc = self.pca.inverse_transform(scores)
        return self.scaler.inverse_transform(surfaces_sc)

    def plot_principal_components(self):
        """Visualise the first 3 principal components as surfaces."""
        fig, axes = plt.subplots(1, 3, figsize=(15, 5), subplot_kw={'projection': '3d'})
        K_grid, T_grid = np.meshgrid(self.strikes, self.expiries)

        for pc_idx, ax in enumerate(axes):
            # Reshape PC to surface
            pc_surface = self.pca.components_[pc_idx].reshape(self.n_expiries, self.n_strikes)
            ax.plot_surface(K_grid, T_grid, pc_surface, cmap='RdBu_r', alpha=0.8)
            ax.set_xlabel('Strike (% ATM)')
            ax.set_ylabel('Expiry (years)')
            ax.set_zlabel('Loading')
            ax.set_title(f'PC{pc_idx + 1}: {self.pca.explained_variance_ratio_[pc_idx]:.1%} var')

        plt.suptitle('IV Surface Principal Components', fontsize=14)
        plt.tight_layout()
        return fig

    def no_arbitrage_check(self, surface: np.ndarray) -> dict:
        """
        Check for calendar spread and butterfly arbitrage violations.

        Calendar arbitrage: total variance must be increasing in T
        Butterfly arbitrage: second derivative w.r.t. k must be >= 0
        """
        surf_2d = surface.reshape(self.n_expiries, self.n_strikes)
        k_vec = np.log(self.strikes) # log-moneyness

        violations = {'calendar': 0, 'butterfly': 0}

        # Calendar spread check : w(k, T2) >= w(k, T1) for T2 > T1
        for j in range(self.n_strikes):
            total_var = surf_2d[:, j]**2 * self.expiries
            if not np.all(np.diff(total_var) >= -1e-6):
                violations['calendar'] += 1

        # Butterfly check : second derivative >= 0
        dk = np.diff(k_vec)
        for i in range(self.n_expiries):
            iv_slice = surf_2d[i, :]
            d2iv_dk2 = np.diff(iv_slice, n=2)
            if np.any(d2iv_dk2 < -0.01): # allow small numerical errors
                violations['butterfly'] += 1

        return violations


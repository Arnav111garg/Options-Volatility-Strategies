import numpy as np
import pandas as pd
from datetime import datetime

class VolBookDashboard:
    """
    Daily morning risk management dashboard.
    Run every trading day at 08:30 AM before market open.
    """
    def __init__(self, positions: list, limits: dict, prior_pnl: float):
        self.positions = positions
        self.limits = limits
        self.prior_pnl = prior_pnl
        self.alerts: list = []

    # Aggregate Greeks
    def aggregate_greeks(self) -> dict:
        agg = {
            'delta_$': 0, 'gamma_$': 0, 'vega_$': 0,
            'theta_$': 0, 'fm_vega': 0, 'belly_vega': 0,
            'back_vega': 0
        }
        for p in self.positions:
            agg['delta_$'] += p.get('delta_$', 0)
            agg['gamma_$'] += p.get('gamma_$', 0)
            agg['vega_$'] += p.get('vega_$', 0)
            agg['theta_$'] += p.get('theta_$', 0)
            dte = p.get('dte', 99)
            if dte <= 30:
                agg['fm_vega'] += p.get('vega_$', 0)
            elif dte <= 90:
                agg['belly_vega'] += p.get('vega_$', 0)
            else:
                agg['back_vega'] += p.get('vega_$', 0)
        return agg

    # Limit Checks
    def check_limits(self, greeks: dict) -> pd.DataFrame:
        pairs = [
            ('Delta ($)', 'delta_$', 'delta'),
            ('Gamma ($)', 'gamma_$', 'gamma'),
            ('Vega ($)', 'vega_$', 'vega'),
            ('Theta ($)', 'theta_$', 'theta'),
            ('Front-Month Vega', 'fm_vega', 'fm_vega'),
        ]
        rows = []
        for label, key, lim_key in pairs:
            val = greeks.get(key, 0)
            soft = self.limits.get(f'{lim_key}_soft', np.inf)
            hard = self.limits.get(f'{lim_key}_hard', np.inf)
            hard_br = abs(val) > hard
            soft_br = abs(val) > soft
            status = 'HARD BREACH' if hard_br else 'SOFT BREACH' if soft_br else 'OK'
            if hard_br or soft_br:
                self.alerts.append(f"{label}: {val:,.0f} (lim {soft:,.0f})")
            usage = f"{abs(val)/soft * 100:.0f}%" if soft < np.inf else 'N/A'
            rows.append({
                'Metric': label, 'Value': f"{val:,.0f}",
                'Soft': f"{soft:,.0f}" if soft < np.inf else 'N/A',
                'Hard': f"{hard:,.0f}" if hard < np.inf else 'N/A',
                'Usage': usage, 'Status': status
            })
        return pd.DataFrame(rows)

    # P&L Attribution
    def pnl_attribution(self, spot_pct: float, vol_pts: float, days: int = 1) -> dict:
        g = self.aggregate_greeks()
        attrib = {
            'Delta P&L': g['delta_$'] * spot_pct,
            'Gamma P&L': g['gamma_$'] * (spot_pct / 0.01) ** 2 * 0.5,
            'Vega P&L': g['vega_$'] * vol_pts,
            'Theta P&L': g['theta_$'] * days,
        }
        attrib['Estimated Total'] = sum(attrib.values())
        attrib['Actual P&L'] = self.prior_pnl
        attrib['Residual'] = self.prior_pnl - attrib['Estimated Total']
        return attrib

    # Morning Report
    def morning_report(self, spot_pct: float = 0.0, vol_pts: float = 0.0):
        ts = datetime.now().strftime('%Y-%m-%d %H:%M')
        print(f"\n{'='*60}")
        print(f" VOL BOOK MORNING RISK DASHBOARD | {ts}")
        print(f"{'='*60}")

        greeks = self.aggregate_greeks()
        lim_df = self.check_limits(greeks)
        print("\n AGGREGATE GREEKS vs. LIMITS:")
        print(lim_df.to_string(index=False))

        if self.alerts:
            print(f"\n *** {len(self.alerts)} ALERT (S) ***")
            for a in self.alerts:
                print(f" >> {a}")
        else:
            print("\n [OK] No limit breaches.")

        if spot_pct != 0 or vol_pts != 0:
            att = self.pnl_attribution(spot_pct, vol_pts)
            print(f"\n P&L ATTRIBUTION (spot {spot_pct * 100:+.2f}%, vol {vol_pts:+.1f}vp):")
            for k, v in att.items():
                flag = " <-- CHECK " if k == 'Residual' and abs(v) > 50000 else ""
                print(f" {k:<22}: ${v:>12,.0f}{flag}")

        print(f"\n VEGA LADDER:")
        print(f" Front-month : ${greeks['fm_vega']:>10,.0f}")
        print(f" Belly       : ${greeks['belly_vega']:>10,.0f}")
        print(f" Back        : ${greeks['back_vega']:>10,.0f}")
        print(f" Net total   : ${greeks['vega_$']:>10,.0f}")
        print(f"{'='*60}\n")



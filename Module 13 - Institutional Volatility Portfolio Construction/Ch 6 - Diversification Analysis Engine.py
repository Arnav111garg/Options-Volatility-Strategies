import numpy as np
import pandas as pd
from scipy.optimize import minimize
import matplotlib.pyplot as plt
from matplotlib.colors import TwoSlopeNorm

class VolDiversificationAnalyzer:
    """
    Comprehensive diversification analysis for volatility portfolios.
    """

    def __init__(self, cov_normal: np.ndarray, cov_crisis: np.ndarray, names: list):
        self.Sigma_n = cov_normal
        self.Sigma_c = cov_crisis
        self.names = names
        self.N = len(names)
        # Extract volatilities and correlations
        self.vols_n = np.sqrt(np.diag(self.Sigma_n))
        self.vols_c = np.sqrt(np.diag(self.Sigma_c))

    def diversification_ratio(self, w: np.ndarray, regime: str = 'normal') -> float:
        """ Compute diversification ratio for given weights ."""
        Sigma = self.Sigma_n if regime == 'normal' else self.Sigma_c
        vols = self.vols_n if regime == 'normal' else self.vols_c
        port_vol = np.sqrt(w @ Sigma @ w)
        return (w @ vols) / port_vol if port_vol > 0 else 1.0

    def effective_n_bets(self, w: np.ndarray, regime: str = 'normal') -> float:
        """ Effective number of independent bets (HHI-based)."""
        Sigma = self.Sigma_n if regime == 'normal' else self.Sigma_c
        port_vol = np.sqrt(w @ Sigma @ w)
        if port_vol == 0:
            return 1.0
        rc = w * (Sigma @ w) / port_vol
        prc = rc / rc.sum()
        hhi = np.sum(prc ** 2)
        return 1.0 / hhi if hhi > 0 else self.N

    def correlation_matrix(self, regime: str = 'normal') -> np.ndarray:
        """ Extract correlation matrix from covariance ."""
        Sigma = self.Sigma_n if regime == 'normal' else self.Sigma_c
        vols = np.sqrt(np.diag(Sigma))
        D_inv = np.diag(1.0 / np.where(vols > 0, vols, 1))
        return D_inv @ Sigma @ D_inv

    def regime_diversification_comparison(self, w: np.ndarray) -> pd.DataFrame:
        """ Compare diversification metrics across regimes ."""
        regimes = ['normal', 'crisis']
        rows = []
        for regime in regimes:
            Sigma = self.Sigma_n if regime == 'normal' else self.Sigma_c
            port_vol = float(np.sqrt(w @ Sigma @ w)) * np.sqrt(252)
            dr = self.diversification_ratio(w, regime)
            enb = self.effective_n_bets(w, regime)
            rows.append({
                'Regime': regime.capitalize(),
                'Portfolio Vol (ann)': f"{port_vol * 100:.2f}%",
                'Diversification Ratio': f"{dr:.3f}",
                'Effective N Bets': f"{enb:.2f}",
                'Diversification Loss': f"{(1 - enb / self.N) * 100:.1f}%"
            })
        return pd.DataFrame(rows)

    def plot_correlation_shift(self):
        """ Visualize correlation matrix change from normal to crisis. """
        corr_n = self.correlation_matrix('normal')
        corr_c = self.correlation_matrix('crisis')
        delta_corr = corr_c - corr_n

        fig, axes = plt.subplots(1, 3, figsize=(18, 5))
        cmap = 'RdBu_r'

        for ax, matrix, title in zip(
            axes,
            [corr_n, corr_c, delta_corr],
            ['Normal Regime Correlation', 'Crisis Regime Correlation', 'Correlation Shift (Crisis - Normal)']
        ):
            if 'Shift' in title:
                norm = TwoSlopeNorm(vcenter=0, vmin=-0.6, vmax=0.6)
            else:
                norm = TwoSlopeNorm(vcenter=0, vmin=-1, vmax=1)

            im = ax.imshow(matrix, cmap=cmap, norm=norm)
            ax.set_xticks(range(self.N))
            ax.set_yticks(range(self.N))
            ax.set_xticklabels([n[:8] for n in self.names], rotation=45, ha='right', fontsize=8)
            ax.set_yticklabels([n[:8] for n in self.names], fontsize=8)

            for i in range(self.N):
                for j in range(self.N):
                    color = 'white' if abs(matrix[i, j]) > 0.5 else 'black'
                    ax.text(j, i, f'{matrix[i, j]:.2f}', ha='center', va='center', fontsize=8, color=color)
            ax.set_title(title, fontsize=10, fontweight='bold', color='#0A3E78', pad=8)
            plt.colorbar(im, ax=ax, shrink=0.8)

        plt.suptitle('Regime - Conditional Correlation Structure', fontsize=13, fontweight='bold', color='#0A3E78')
        plt.tight_layout()
        return fig

    def efficient_frontier(self, n_points: int = 200, regime: str = 'normal') -> pd.DataFrame:
        """ Trace the efficient frontier for the vol portfolio ."""
        Sigma = self.Sigma_n if regime == 'normal' else self.Sigma_c
        vols = np.sqrt(np.diag(Sigma)) * np.sqrt(252)

        # Monte Carlo portfolios
        results = []
        for _ in range(5000):
            w = np.random.dirichlet(np.ones(self.N))
            pv = float(np.sqrt(w @ Sigma @ w)) * np.sqrt(252)
            dr = self.diversification_ratio(w, regime)
            enb = self.effective_n_bets(w, regime)
            results.append({
                'vol': pv,
                'DR': dr,
                'ENB': enb,
                **{f'w_{n[:6]}': w[i] for i, n in enumerate(self.names)}
            })

        return pd.DataFrame(results).sort_values('vol')



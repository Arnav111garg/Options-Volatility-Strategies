import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.stats import norm

def simulate_gamma_scalp(
    S0: float,
    K: float,
    T_days: int,
    sigma_iv: float,
    sigma_rv: float,
    r: float = 0.05,
    n_sims: int = 1000,
    hedge_freq_days: int = 1,
    notional: int = 100,
    multiplier: int = 100
) -> pd.DataFrame:
    """
    Simulate a long ATM straddle with discrete delta hedging.
    Measures daily gamma scalp P&L vs. theoretical expectation.

    Parameters
    ----------
    S0, K : Initial spot and strike
    T_days : Days to expiry
    sigma_iv : Implied vol (decimal) at trade inception
    sigma_rv : Realized vol (decimal) for simulation
    r : Risk-free rate
    n_sims : Number of Monte Carlo paths
    hedge_freq_days : Delta hedge every N days
    notional : Number of straddles
    multiplier : Option contract multiplier
    """
    dt = hedge_freq_days / 252.0  # hedging interval in years

    def bsm_greeks(S, K, T, r, sigma):
        if T <= 0:
            return {
                'delta_c': 1.0 if S > K else 0.0,
                'delta_p': -1.0 if S < K else 0.0,
                'gamma': 0.0,
                'theta': 0.0,
                'vega': 0.0,
                'call': max(S - K, 0.0),
                'put': max(K - S, 0.0)
            }
        d1 = (np.log(S / K) + (r + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
        d2 = d1 - sigma * np.sqrt(T)
        phi_d1 = norm.pdf(d1)
        return {
            'delta_c': norm.cdf(d1),
            'delta_p': norm.cdf(d1) - 1.0,
            'gamma': phi_d1 / (S * sigma * np.sqrt(T)),
            'theta': -(S * phi_d1 * sigma / (2 * np.sqrt(T)) + r * K * np.exp(-r * T) * norm.cdf(d2)) / 252.0,
            'vega': S * np.sqrt(T) * phi_d1,
            'call': S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2),
            'put': K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)
        }

    # Precompute option value at trade inception
    T0 = T_days / 252.0
    g0 = bsm_greeks(S0, K, T0, r, sigma_iv)
    initial_value = (g0['call'] + g0['put']) * notional * multiplier

    results = []
    for sim_i in range(n_sims):
        S = S0
        T_rem = T0
        cum_pnl = 0.0
        daily_records = []

        for day in range(T_days):
            # Spot evolves
            dW = np.random.normal(0, np.sqrt(dt))
            S_new = S * np.exp((r - 0.5 * sigma_rv ** 2) * dt + sigma_rv * dW)
            T_new = T_rem - dt

            # Value of straddle at new (S, T)
            g_old = bsm_greeks(S, K, T_rem, r, sigma_iv)
            g_new = bsm_greeks(S_new, K, max(T_new, 1e-6), r, sigma_iv)

            straddle_pnl = ((g_new['call'] + g_new['put']) - (g_old['call'] + g_old['put'])) * notional * multiplier

            # Delta hedge P&L (opposite sign: hedger is short delta)
            straddle_delta = (g_old['delta_c'] + g_old['delta_p']) * notional * multiplier
            hedge_pnl = -straddle_delta * (S_new - S)

            # Gamma P&L approximation
            r_actual = (S_new - S) / S
            gamma_pnl_theory = 0.5 * g_old['gamma'] * (S ** 2) * (r_actual ** 2) * notional * multiplier
            theta_pnl_theory = g_old['theta'] * hedge_freq_days * notional * multiplier

            daily_records.append({
                'day': day,
                'S': S,
                'gamma_pnl_actual': straddle_pnl + hedge_pnl,
                'gamma_pnl_theory': gamma_pnl_theory + theta_pnl_theory,
                'r_actual': r_actual,
                'gamma': g_old['gamma'],
                'iv': sigma_iv,
                'rv_day': abs(r_actual) * np.sqrt(252)
            })

            cum_pnl += straddle_pnl + hedge_pnl
            S = S_new
            T_rem = T_new

        df_sim = pd.DataFrame(daily_records)
        results.append({
            'sim': sim_i,
            'total_pnl': cum_pnl,
            'daily_pnl_std': df_sim['gamma_pnl_actual'].std(),
            'positive_days': (df_sim['gamma_pnl_actual'] > 0).sum()
        })

    return pd.DataFrame(results)

# Run Simulation
print("Simulating gamma scalp: IV = 18%, RV = 15% (short-gamma expected to win)")
results = simulate_gamma_scalp(
    S0=4500,
    K=4500,
    T_days=30,
    sigma_iv=0.18,
    sigma_rv=0.15,
    r=0.05,
    n_sims=500,
    notional=10
)

print(f"\nGamma Scalp Results (IV = 18%, RV = 15%):")
print(f"  Mean Total P&L:    ${results['total_pnl'].mean():>10,.0f}")
print(f"  Std Total P&L:     ${results['total_pnl'].std():>10,.0f}")
print(f"  Median P&L:        ${results['total_pnl'].median():>10,.0f}")
print(f"  % Positive runs:   {(results['total_pnl'] > 0).mean() * 100:.1f}%")
print(f"  Sharpe (monthly):  {results['total_pnl'].mean() / results['total_pnl'].std():.3f}")


import numpy as np
import pandas as pd
from arch import arch_model
import warnings
warnings.filterwarnings('ignore')

class VRPEngine:
    """
    Captures the Variance Risk Premium by comparing GARCH-forecast
    realized vol to current ATM implied vol.
    Entry rule: short vol when IV > GARCH-forecast RV by a threshold.
    """
    def __init__(self, returns: pd.Series, iv: pd.Series, garch_window: int = 252, entry_threshold: float = 0.02):
        self.returns = returns
        self.iv = iv
        self.window = garch_window
        self.thresh = entry_threshold

    def garch_forecast(self, idx: int) -> float:
        """GARCH(1,1) 1-month forward vol forecast."""
        start = max(0, idx - self.window)
        r = self.returns.iloc[start:idx]
        if len(r) < 60:
            return float(r.std() * np.sqrt(252))
        try:
            am = arch_model(r * 100, vol='Garch', p=1, q=1, dist='normal', rescale=False)
            res = am.fit(disp='off')
            fc = res.forecast(horizon=21, reindex=False)
            v21 = fc.variance.iloc[-1].mean()
            return float(np.sqrt(v21 * 252) / 100)
        except Exception:
            return float(r.std() * np.sqrt(252))

    def compute_signal(self, start: int = 252) -> pd.DataFrame:
        """Build VRP signal series."""
        rows = []
        for i in range(start, min(start + 500, len(self.iv))):
            iv_val = float(self.iv.iloc[i])
            rv_fc = self.garch_forecast(i)
            vrp = iv_val - rv_fc
            rows.append({
                'date': self.iv.index[i],
                'iv': iv_val,
                'rv_garch': rv_fc,
                'vrp': vrp,
                'signal': int(vrp > self.thresh)
            })
        df = pd.DataFrame(rows).set_index('date')
        return df

    def backtest(self, signal_df: pd.DataFrame) -> pd.DataFrame:
        """
        Approximate backtest: P&L per unit vega based on VRP realisation.
        Assumes 21-day hold; forward RV vs. IV entry determines outcome.
        """
        rows = []
        for i in range(len(signal_df) - 21):
            row = signal_df.iloc[i]
            if row['signal'] == 0:
                continue
            # Realized vol over next 21 days
            fwd_r = self.returns.loc[signal_df.index[i+1]:signal_df.index[i+21]]
            rv_act = float(fwd_r.std() * np.sqrt(252)) if len(fwd_r) > 3 else np.nan
            if np.isnan(rv_act):
                continue
            vrp_realized = row['iv'] - rv_act
            # Approx monthly P&L per $1 of dollar vega
            pnl = -1 * vrp_realized * (21/252)  # short vol = negative position
            rows.append({
                'date': signal_df.index[i],
                'iv': row['iv'],
                'rv_fc': row['rv_garch'],
                'rv_act': rv_act,
                'vrp_fc': row['vrp'],
                'vrp_realized': vrp_realized,
                'pnl_per_vega': pnl
            })
        df = pd.DataFrame(rows).set_index('date')
        if not df.empty:
            df['cum_pnl'] = df['pnl_per_vega'].cumsum()
            ann_sharpe = (df['pnl_per_vega'].mean() / df['pnl_per_vega'].std() * np.sqrt(12)) if df['pnl_per_vega'].std() > 0 else 0
            print(f"VRP Backtest: {len(df)} trades | Sharpe={ann_sharpe:.2f} | Hit Rate={(df['vrp_realized'] > 0).mean() * 100:.1f}%")
        return df

# Simulate and test VRP engine
np.random.seed(7)
n = 1000
dates = pd.date_range('2020-01-01', periods=n, freq='B')
rv_sim = 0.15 + 0.05 * np.sin(np.linspace(0, 8 * np.pi, n))
ret_sim = pd.Series(np.random.normal(0, rv_sim / np.sqrt(252), n), index=dates)
iv_sim = pd.Series(np.maximum(rv_sim + 0.025 + 0.01 * np.random.randn(n), 0.08), index=dates)

engine = VRPEngine(ret_sim, iv_sim, garch_window=126, entry_threshold=0.015)
sig_df = engine.compute_signal(start=130)
bt_df = engine.backtest(sig_df)

print(f"\nVRP Signal: {sig_df['signal'].sum()} short-vol entries ({sig_df['signal'].mean() * 100:.0f}% of days)")
print(f"Average VRP at entry: {sig_df.loc[sig_df['signal'] == 1, 'vrp'].mean() * 100:.2f}%")


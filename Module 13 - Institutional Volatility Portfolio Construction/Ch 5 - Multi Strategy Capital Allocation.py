import numpy as np
import pandas as pd
from scipy.optimize import minimize
import matplotlib.pyplot as plt
import warnings

class CapitalAllocator:
    """
    Institutional-grade capital allocation for volatility portfolios.
    Implements: Mean-Variance, Risk Parity, Kelly, Black-Litterman,
    Max Diversification, Min-CVaR allocations.
    """

    def __init__(self, cov: np.ndarray, mu: np.ndarray, names: list, total_capital: float = 1e8):
        self.Sigma = cov
        self.mu = mu
        self.names = names
        self.N = len(names)
        self.C = total_capital
        # Pre-compute Sigma inverse (handle near-singular matrices)
        try:
            self.Sigma_inv = np.linalg.inv(self.Sigma)
        except np.linalg.LinAlgError:
            self.Sigma_inv = np.linalg.pinv(self.Sigma)

    # Allocation methods
    def mean_variance(self, risk_aversion: float = 2.0) -> np.ndarray:
        """Classic Markowitz mean-variance weights."""
        w = (1 / risk_aversion) * self.Sigma_inv @ self.mu
        return self._normalize(w)

    def risk_parity(self) -> np.ndarray:
        """Equal risk contribution (ERC) weights."""
        def obj(w):
            rc = w * (self.Sigma @ w) / np.sqrt(w @ self.Sigma @ w)
            return np.sum((rc - rc.mean()) ** 2)
        w0 = np.ones(self.N) / self.N
        res = minimize(
            obj,
            w0,
            method='SLSQP',
            bounds=[(0.01, 1)] * self.N,
            constraints=[{'type': 'eq', 'fun': lambda w: w.sum() - 1}],
            options={'ftol': 1e-14, 'maxiter': 3000}
        )
        return res.x

    def kelly_fractional(self, fraction: float = 0.5) -> np.ndarray:
        """Fractional Kelly weights."""
        w_kelly = self.Sigma_inv @ self.mu
        return self._normalize(w_kelly) * fraction

    def min_variance(self) -> np.ndarray:
        """Global minimum variance portfolio."""
        ones = np.ones(self.N)
        w = self.Sigma_inv @ ones
        return w / w.sum()

    def max_sharpe(self) -> np.ndarray:
        """Maximum Sharpe ratio portfolio (tangency portfolio)."""
        def neg_sharpe(w):
            ret = w @ self.mu * 252
            vol = np.sqrt(w @ self.Sigma @ w * 252)
            return -ret / vol if vol > 0 else 0

        w0 = np.ones(self.N) / self.N
        res = minimize(
            neg_sharpe,
            w0,
            method='SLSQP',
            bounds=[(0.01, 1)] * self.N,
            constraints=[{'type': 'eq', 'fun': lambda w: w.sum() - 1}],
            options={'ftol': 1e-12, 'maxiter': 2000}
        )
        return res.x

    def max_diversification(self) -> np.ndarray:
        """Maximum Diversification Ratio (Choueifaty & Coignard)."""
        vols = np.sqrt(np.diag(self.Sigma))
        def neg_div_ratio(w):
            port_vol = np.sqrt(w @ self.Sigma @ w)
            weighted_avg_vol = w @ vols
            return -weighted_avg_vol / port_vol

        w0 = np.ones(self.N) / self.N
        res = minimize(
            neg_div_ratio,
            w0,
            method='SLSQP',
            bounds=[(0.01, 1)] * self.N,
            constraints=[{'type': 'eq', 'fun': lambda w: w.sum() - 1}],
            options={'ftol': 1e-12, 'maxiter': 2000}
        )
        return res.x

    def black_litterman(self, P: np.ndarray, q: np.ndarray, omega: np.ndarray = None, tau: float = 0.025, risk_aversion: float = 2.5) -> np.ndarray:
        """
        Black-Litterman optimal weights.
        P: (k x N) view matrix
        q: (k,) view returns
        omega: (k x k) view uncertainty diagonal (auto-computed if None)
        """
        # Implied equilibrium returns (reverse optimization from equal weights)
        w_mkt = np.ones(self.N) / self.N
        Pi = risk_aversion * self.Sigma @ w_mkt
        # Default uncertainty : proportional to view variance
        if omega is None:
            omega = np.diag(np.diag(P @ (tau * self.Sigma) @ P.T))

        # BL posterior
        tau_Sigma_inv = np.linalg.inv(tau * self.Sigma)
        Pt_Omega_inv = P.T @ np.linalg.inv(omega)
        M_inv = tau_Sigma_inv + Pt_Omega_inv @ P
        M = np.linalg.inv(M_inv)
        mu_bl = M @ (tau_Sigma_inv @ Pi + Pt_Omega_inv @ q)

        # Optimal weights
        w = (1 / risk_aversion) * np.linalg.inv(self.Sigma + M) @ mu_bl
        return self._normalize(w)

    def _normalize(self, w: np.ndarray) -> np.ndarray:
        """Normalize to positive weights summing to 1."""
        w = np.maximum(w, 0)
        s = w.sum()
        return w / s if s > 0 else np.ones(self.N) / self.N

    # Analysis & Reporting
    def portfolio_stats(self, w: np.ndarray) -> dict:
        """Key portfolio statistics."""
        w = np.array(w)
        ret = float(w @ self.mu) * 252
        vol = float(np.sqrt(w @ self.Sigma @ w)) * np.sqrt(252)
        sharpe = ret / vol if vol > 0 else 0
        vols_indiv = np.sqrt(np.diag(self.Sigma)) * np.sqrt(252)
        div_ratio = float(w @ vols_indiv) / vol if vol > 0 else 1
        rc = w * (self.Sigma @ w) / np.sqrt(w @ self.Sigma @ w)
        hhi = np.sum(rc ** 2) / np.sum(rc) ** 2  # Herfindahl index of risk

        return {
            'Expected Return': f"{ret * 100:.2f}%",
            'Volatility': f"{vol * 100:.2f}%",
            'Sharpe': f"{sharpe:.3f}",
            'Diversification Ratio': f"{div_ratio:.3f}",
            'Risk Concentration (HHI)': f"{hhi:.4f}"
        }

    def compare_allocations(self) -> pd.DataFrame:
        """Compare all allocation methods side by side."""
        methods = {
            'Equal Weight': np.ones(self.N) / self.N,
            'Min Variance': self.min_variance(),
            'Risk Parity': self.risk_parity(),
            'Max Sharpe': self.max_sharpe(),
            'Max Diversification': self.max_diversification(),
            'Half Kelly': self.kelly_fractional(0.5),
            'Mean-Variance': self.mean_variance()
        }

        rows = []
        for method, w in methods.items():
            stats = self.portfolio_stats(w)
            row = {'Method': method}
            for i, name in enumerate(self.names):
                row[f'w_{name[:8]}'] = f"{w[i] * 100:.1f}%"
            row.update(stats)
            rows.append(row)

        return pd.DataFrame(rows).set_index('Method')

    def dollar_allocation(self, weights: np.ndarray) -> dict:
        """Convert weights to dollar allocations."""
        return {name: w * self.C for name, w in zip(self.names, weights)}


# Example : 5 - Strategy Vol Fund Allocation
strats = ['Short Straddle', 'Iron Condor', 'Long Strangle', 'Dispersion', 'Tail Hedge']

corr = np.array([
    [1.00, 0.65, -0.45, -0.20, -0.70],
    [0.65, 1.00, -0.30, -0.15, -0.50],
    [-0.45, -0.30, 1.00, 0.40, 0.60],
    [-0.20, -0.15, 0.40, 1.00, 0.25],
    [-0.70, -0.50, 0.60, 0.25, 1.00]
])
vols_ann = np.array([0.08, 0.05, 0.12, 0.10, 0.20])
D = np.diag(vols_ann)
Sigma_ann = D @ corr @ D
Sigma_daily = Sigma_ann / 252

mu_ann = np.array([0.06, 0.04, -0.02, 0.03, -0.04])  # Expected daily returns annualized
mu_daily = mu_ann / 252

allocator = CapitalAllocator(Sigma_daily, mu_daily, strats, total_capital=1e8)

print("=" * 70)
print(" CAPITAL ALLOCATION COMPARISON ( $100M Vol Fund )")
print("=" * 70)
print(allocator.compare_allocations().to_string())

# Black-Litterman with view: "Short Straddle will outperform by 2%"
P_view = np.array([[1, 0, -1, 0, 0]])  # Short Straddle vs Long Strangle
q_view = np.array([0.02 / 252])  # 2% annualized outperformance
w_bl = allocator.black_litterman(P_view, q_view)
print("\nBlack-Litterman Allocation (view : Short Straddle > Long Strangle by 2%):")
for name, w in zip(strats, w_bl):
    dollar = w * 1e8
    print(f"  {name:<18}: {w * 100:5.1f}% = ${dollar:>12,.0f}")


import numpy as np
import pandas as pd
from dataclasses import dataclass, field
from typing import List, Dict, Optional, Tuple
import matplotlib.pyplot as plt

@dataclass
class OptionPosition:
    """ Represents a single option position in the vol book. """
    ticker: str
    option_type: str # 'call' or 'put'
    strike: float
    expiry_days: int # calendar days to expiry
    spot: float
    iv: float # implied vol (decimal)
    r: float # risk-free rate
    quantity: int # contracts (signed)
    multiplier: int = 100 # shares per contract

    def __post_init__(self):
        self.T = self.expiry_days / 365.0
        self._compute_greeks()

    def _compute_greeks(self):
        from scipy.stats import norm
        S, K, T = self.spot, self.strike, self.T
        r, sig = self.r, self.iv

        if T <= 0:
            self.delta = 1.0 if (self.option_type == 'call' and S > K) else 0.0
            self.gamma = self.vega = self.theta = 0.0
            return

        d1 = (np.log(S / K) + (r + 0.5 * sig ** 2) * T) / (sig * np.sqrt(T))
        d2 = d1 - sig * np.sqrt(T)
        phi_d1 = norm.pdf(d1)

        self.d1 = d1
        self.delta = norm.cdf(d1) if self.option_type == 'call' else norm.cdf(d1) - 1
        self.gamma = phi_d1 / (S * sig * np.sqrt(T))
        self.vega = S * np.sqrt(T) * phi_d1  # per unit vol (decimal)

        # Dollar vega per 1 vol point (1%) move
        self.dollar_vega = self.vega * self.quantity * self.multiplier * 0.01

        # Dollar gamma (per 1% move in spot)
        self.dollar_gamma = 0.5 * self.gamma * (S * 0.01) ** 2 * self.quantity * self.multiplier
        self.theta = -(S * phi_d1 * sig / (2 * np.sqrt(T)) + r * K * np.exp(-r * T) * (
            norm.cdf(d2) if self.option_type == 'call' else norm.cdf(-d2)
        )) / 365
        self.dollar_theta = self.theta * self.quantity * self.multiplier


class VegaBudgetManager:
    """
    Manages vega budgets across a multi-underlying,
    multi-expiry vol book.
    Provides vega ladder, vega limits, and hedging recommendations.
    """

    EXPIRY_BUCKETS = {
        '0-1M': (0, 30),
        '1-2M': (31, 60),
        '2-3M': (61, 90),
        '3-6M': (91, 180),
        '6M-1Y': (181, 365),
        '1Y+': (366, 9999)
    }

    def __init__(self, vega_limits: Dict[str, float] = None):
        """
        vega_limits : dict mapping bucket name -> max absolute dollar vega
        """
        self.positions: List[OptionPosition] = []
        self.limits = vega_limits or {}

    def add_position(self, pos: OptionPosition):
        self.positions.append(pos)

    def vega_ladder(self, by_ticker: bool = False) -> pd.DataFrame:
        """ Build the vega ladder by expiry bucket (optionally by ticker)."""
        rows = []
        for pos in self.positions:
            bucket = self._get_bucket(pos.expiry_days)
            rows.append({
                'ticker': pos.ticker,
                'bucket': bucket,
                'expiry_days': pos.expiry_days,
                'strike': pos.strike,
                'option_type': pos.option_type,
                'iv': pos.iv,
                'dollar_vega': pos.dollar_vega,
                'qty': pos.quantity,
                'normalized_vega': pos.dollar_vega / np.sqrt(pos.T) if pos.T > 0 else 0
            })

        df = pd.DataFrame(rows)
        if df.empty:
            return df

        groupby_cols = ['ticker', 'bucket'] if by_ticker else ['bucket']

        ladder = df.groupby(groupby_cols).agg(
            net_dollar_vega=('dollar_vega', 'sum'),
            net_norm_vega=('normalized_vega', 'sum'),
            n_positions=('dollar_vega', 'count'),
            avg_iv=('iv', 'mean'),
            total_qty=('qty', 'sum')
        ).reset_index()
        return ladder

    def _get_bucket(self, days: int) -> str:
        for name, (lo, hi) in self.EXPIRY_BUCKETS.items():
            if lo <= days <= hi:
                return name
        return '1Y+'

    def check_limits(self) -> pd.DataFrame:
        """ Check vega exposures against defined limits."""
        ladder = self.vega_ladder()
        results = []
        for _, row in ladder.iterrows():
            bucket = row['bucket']
            limit = self.limits.get(bucket, np.inf)
            usage = abs(row['net_dollar_vega']) / limit if limit != np.inf else 0
            breach = abs(row['net_dollar_vega']) > limit
            results.append({
                'bucket': bucket,
                'net_vega': row['net_dollar_vega'],
                'limit': limit if limit != np.inf else 'N/A',
                'usage_pct': f"{usage * 100:.1f}%" if limit != np.inf else 'N/A',
                'breach': 'BREACH' if breach else 'OK'
            })
        return pd.DataFrame(results)

    def total_vega(self) -> float:
        """ Total book dollar vega. """
        return sum(p.dollar_vega for p in self.positions)

    def vega_pnl_scenario(self, vol_shifts: Dict[str, float]) -> float:
        """
        Estimate vega P&L for given vol shifts per bucket.
        vol_shifts : {'0-1M': -0.02, '3-6M': +0.01, ...} in decimal
        """
        total_pnl = 0.0
        for pos in self.positions:
            bucket = self._get_bucket(pos.expiry_days)
            shift = vol_shifts.get(bucket, 0.0)
            # Vega P&L = dollar_vega * shift (already per 1% = 0.01)
            total_pnl += pos.dollar_vega * (shift / 0.01)
        return total_pnl

    def plot_vega_ladder(self):
        """ Visualize the vega ladder. """
        ladder = self.vega_ladder()
        buckets = list(self.EXPIRY_BUCKETS.keys())
        vegas = []
        for b in buckets:
            match = ladder[ladder['bucket'] == b]
            vegas.append(float(match['net_dollar_vega'].sum()) if not match.empty else 0)

        colors = ['#B41E1E' if v < 0 else '#0A3E78' for v in vegas]
        fig, ax = plt.subplots(figsize=(12, 5))
        bars = ax.bar(buckets, vegas, color=colors, edgecolor='white', linewidth=0.8, width=0.6)

        # Limit lines
        for b, lim in self.limits.items():
            idx = buckets.index(b) if b in buckets else -1
            if idx >= 0:
                ax.axhline(y=lim, xmin=(idx - 0.4) / len(buckets), xmax=(idx + 0.4) / len(buckets), color='red', linestyle='--', linewidth=2)
                ax.axhline(y=-lim, xmin=(idx - 0.4) / len(buckets), xmax=(idx + 0.4) / len(buckets), color='red', linestyle='--', linewidth=2)

        ax.axhline(0, color='black', linewidth=0.8)
        for bar, val in zip(bars, vegas):
            va = 'bottom' if val >= 0 else 'top'
            offset = 0.02 * max(abs(v) for v in vegas)
            ax.text(bar.get_x() + bar.get_width() / 2, val + (offset if val >= 0 else -offset), f'${val:,.0f}', ha='center', va=va, fontsize=9, fontweight='bold')

        ax.set_title('Vega Ladder Net Dollar Vega by Expiry Bucket', fontsize=12, fontweight='bold', color='#0A3E78', pad=12)
        ax.set_ylabel('Net Dollar Vega ($)', fontsize=10)
        ax.set_xlabel('Expiry Bucket', fontsize=10)
        ax.grid(axis='y', alpha=0.3)
        plt.tight_layout()
        return fig


# Demo: Build a sample vol book
vb = VegaBudgetManager(vega_limits={
    '0-1M': 50000, '1-2M': 80000, '2-3M': 100000,
    '3-6M': 150000, '6M-1Y': 120000, '1Y+': 80000
})

# Add positions representing a real desk's book
positions = [
    # Short front-month straddle (short vega)
    OptionPosition('SPX', 'call', 4500, 15, 4500, 0.18, 0.05, -200),
    OptionPosition('SPX', 'put', 4500, 15, 4500, 0.19, 0.05, -200),
    # Long 3-month strangle
    OptionPosition('SPX', 'call', 4700, 90, 4500, 0.16, 0.05, 150),
    OptionPosition('SPX', 'put', 4300, 90, 4500, 0.21, 0.05, 150),
    # Calendar spread back month
    OptionPosition('SPX', 'call', 4500, 180, 4500, 0.17, 0.05, 100),
]

for p in positions:
    vb.add_position(p)

print(f"\nTotal Book Dollar Vega: ${vb.total_vega():,.0f}")
print("\nVega Ladder:")
print(vb.vega_ladder().to_string())
print("\nVega Limit Check:")
print(vb.check_limits().to_string())

# Scenario: vol term structure steepens (front +3%, back -1%)
pnl = vb.vega_pnl_scenario({'0-1M': 0.03, '1-2M': 0.02, '3-6M': -0.01, '6M-1Y': -0.01})
print(f"\nVega P&L (front +3%, back -1%): ${pnl:,.0f}")


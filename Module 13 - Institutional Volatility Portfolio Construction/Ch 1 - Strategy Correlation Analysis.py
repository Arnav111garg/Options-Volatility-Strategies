# Simulate strategy returns for illustration
np.random.seed(42)
n_days = 1000
dates = pd.date_range('2019-01-01', periods=n_days, freq='B')

# Strategy return simulation (correlated Gaussian + fat tails)
cov = np.array([
    [1.0, -0.3, 0.1, -0.5],
    [-0.3, 1.0, 0.2, 0.4],
    [0.1, 0.2, 1.0, 0.1],
    [-0.5, 0.4, 0.1, 1.0]
]) * 1e-4

returns_sim = pd.DataFrame(
    np.random.multivariate_normal([0]*4, cov, n_days),
    columns=['Short Straddle', 'Long Straddle', 'Iron Condor', 'Dispersion'],
    index=dates
)

# Simulate VIX
vix_sim = pd.Series(
    np.maximum(10, 20 + np.cumsum(np.random.normal(0, 0.5, n_days))),
    index=dates
)

analyzer = VolStrategyPortfolioAnalyzer(returns_sim)
print("Equal-weight portfolio Sharpe:", f"{analyzer.compute_portfolio_sharpe(np.ones(4) / 4):.3f}")


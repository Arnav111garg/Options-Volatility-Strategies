import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from scipy import stats

class VolStrategyPortfolioAnalyzer:
    """
    Compute regime-conditional strategy correlations.
    Used to understand diversification benefits across market states.
    """
    def __init__(self, strategy_returns: pd.DataFrame):
        """
        strategy_returns : DataFrame with columns = strategy names,
        index = dates, values = daily P&L (%)
        """
        self.returns = strategy_returns
        self.n_strategies = strategy_returns.shape[1]

    def compute_corr_by_vix_regime(
        self,
        vix_series: pd.Series,
        low_thresh: float = 18,
        high_thresh: float = 30
    ):
        """
        Compute correlation matrices for low/normal/high VIX regimes.
        """
        aligned = self.returns.join(vix_series.rename('VIX'), how='inner')

        regimes = {
            'Low Vol (VIX < 18)': aligned['VIX'] < low_thresh,
            'Normal Vol (18-30)': (aligned['VIX'] >= low_thresh) & (aligned['VIX'] < high_thresh),
            'High Vol (VIX > 30)': aligned['VIX'] >= high_thresh
        }

        corr_matrices = {}
        for regime_name, mask in regimes.items():
            subset = aligned.loc[mask].drop(columns='VIX')
            if len(subset) > 30:  # Minimum obs for stability
                corr_matrices[regime_name] = subset.corr()
                print(f"{regime_name}: {mask.sum()} days")

        return corr_matrices

    def plot_regime_correlations(self, vix_series: pd.Series):
        """Plot correlation matrices across volatility regimes."""
        corr_mats = self.compute_corr_by_vix_regime(vix_series)

        fig, axes = plt.subplots(1, len(corr_mats), figsize=(18, 5))
        fig.suptitle(
            'Strategy Correlations by VIX Regime',
            fontsize=14,
            fontweight='bold',
            color='#0A3E78'
        )

        for ax, (regime, corr) in zip(axes, corr_mats.items()):
            mask = np.triu(np.ones_like(corr, dtype=bool))
            sns.heatmap(
                corr,
                ax=ax,
                mask=mask,
                cmap='RdBu_r',
                center=0,
                vmin=-1,
                vmax=1,
                annot=True,
                fmt='.2f',
                square=True,
                cbar_kws={'shrink': 0.8}
            )
            ax.set_title(regime, fontsize=10, fontweight='bold')
        plt.tight_layout()
        return fig

    def compute_portfolio_sharpe(
        self,
        weights: np.ndarray,
        risk_free: float = 0.05 / 252
    ):
        """
        Compute portfolio Sharpe given strategy weights.
        weights : array of shape (n_strategies,)
        """
        weights = np.array(weights)
        port_ret = self.returns @ weights
        excess = port_ret.mean() - risk_free
        vol = port_ret.std()
        return (excess / vol) * np.sqrt(252) if vol > 0 else 0.0



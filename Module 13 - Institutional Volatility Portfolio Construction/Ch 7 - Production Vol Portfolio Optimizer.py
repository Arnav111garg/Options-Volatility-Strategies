import numpy as np
import pandas as pd
from scipy.optimize import minimize, Bounds
from scipy.stats import norm
import matplotlib.pyplot as plt
import warnings

class VolPortfolioOptimizer:
    """
    Production-grade volatility portfolio optimizer.
    Supports: MV, Risk Parity, Max Sharpe, CVaR, Robust, Max Diversification.
    Handles: vega/gamma Greek constraints, concentration limits, CVaR limits.
    """

    def __init__(self, cov: np.ndarray, mu: np.ndarray, names: list, scenarios: np.ndarray = None):
        """
        cov : (N x N) daily covariance matrix
        mu: (N,) daily expected returns
        scenarios : (S x N) historical or simulated returns for CVaR
        """
        self.Sigma = np.array(cov)
        self.mu = np.array(mu)
        self.names = names
        self.N = len(names)
        self.scenarios = scenarios  # for historical CVaR

        # Eigenvalue regularization (Ledoit-Wolf shrinkage could go here)
        eigs = np.linalg.eigvalsh(self.Sigma)
        if eigs.min() < 1e-10:
            self.Sigma += (1e-8 - eigs.min()) * np.eye(self.N)

    # Objective functions
    def _portfolio_stats(self, w: np.ndarray) -> dict:
        w = np.array(w)
        var = float(w @ self.Sigma @ w)
        vol = np.sqrt(max(var, 1e-15))
        ret = float(self.mu @ w)
        return {
            'vol': vol,
            'ret': ret,
            'var': var,
            'sharpe': ret / vol if vol > 0 else 0,
            'vol_ann': vol * np.sqrt(252),
            'ret_ann': ret * 252
        }

    def _cvar_objective(self, w: np.ndarray, alpha: float = 0.99) -> float:
        """Historical CVaR for given weights."""
        if self.scenarios is None:
            # Fall back to Gaussian
            stats = self._portfolio_stats(w)
            z = norm.ppf(alpha)
            return stats['vol'] * norm.pdf(z) / (1 - alpha)
        port_returns = self.scenarios @ w
        var_q = np.percentile(port_returns, (1 - alpha) * 100)
        tail = port_returns[port_returns <= var_q]
        return -float(tail.mean()) if len(tail) > 0 else 0.0

    def _risk_parity_obj(self, w: np.ndarray) -> float:
        """RC error sum of squares."""
        vol = np.sqrt(float(w @ self.Sigma @ w))
        if vol < 1e-15:
            return 1e10
        rc = w * (self.Sigma @ w) / vol
        target = vol / self.N
        return float(np.sum((rc - target) ** 2))

    def _robust_obj(self, w: np.ndarray, kappa: float = 1.0, lambda_: float = 2.0) -> float:
        """Robust mean-variance (worst-case expected return)."""
        Sigma_mu = self.Sigma / 252  # uncertainty proportional to vol
        wc_return = self.mu @ w - kappa * np.sqrt(w @ Sigma_mu @ w)
        return float(-wc_return + lambda_ * w @ self.Sigma @ w)

    # Build constraint dict
    def _constraints(self, sum_to_one: bool = True, allow_short: bool = False, max_weight: float = 0.40) -> tuple:
        """
        Build SLSQP constraint list and bounds.
        """
        constraints = []
        lb = -1.0 if allow_short else 0.01
        bounds = Bounds(lb=lb, ub=max_weight)

        if sum_to_one:
            constraints.append(
                {'type': 'eq', 'fun': lambda w: w.sum() - 1}
            )

        return constraints, bounds

    # Main optimization methods
    def optimize(self, method: str = 'risk_parity', allow_short: bool = False, max_weight: float = 0.45, lambda_: float = 2.0, alpha: float = 0.99, kappa: float = 1.0, max_iter: int = 3000) -> dict:
        """
        Run portfolio optimization.
        method : 'mean_variance' | 'min_variance' | 'max_sharpe' | 'risk_parity' | 'cvar' | 'robust' | 'max_diversification'
        """
        obj_map = {
            'mean_variance': lambda w: (w @ self.Sigma @ w - (1 / lambda_) * self.mu @ w),
            'min_variance': lambda w: w @ self.Sigma @ w,
            'max_sharpe': lambda w: -self._portfolio_stats(w)['sharpe'],
            'risk_parity': self._risk_parity_obj,
            'cvar': lambda w: self._cvar_objective(w, alpha),
            'robust': lambda w: self._robust_obj(w, kappa, lambda_),
            'max_diversification': lambda w: -(
                w @ np.sqrt(np.diag(self.Sigma)) /
                np.sqrt(max(w @ self.Sigma @ w, 1e-15))
            )
        }

        if method not in obj_map:
            raise ValueError(f"Unknown method '{method}'. Choose from: {list(obj_map.keys())}")

        constraints, bounds = self._constraints(
            allow_short=allow_short, max_weight=max_weight
        )
        w0 = np.ones(self.N) / self.N

        result = minimize(
            obj_map[method],
            w0,
            method='SLSQP',
            bounds=bounds,
            constraints=constraints,
            options={'ftol': 1e-14, 'maxiter': max_iter, 'disp': False}
        )

        if not result.success and result.fun > 1e6:
            warnings.warn(f"Optimization may not have converged: {result.message}")

        w_opt = result.x
        stats = self._portfolio_stats(w_opt)
        rc = w_opt * (self.Sigma @ w_opt) / stats['vol']
        prc = rc / rc.sum()

        return {
            'weights': dict(zip(self.names, w_opt)),
            'portfolio_vol_ann': stats['vol_ann'],
            'expected_return_ann': stats['ret_ann'],
            'sharpe_ann': stats['ret_ann'] / stats['vol_ann'] if stats['vol_ann'] > 0 else 0,
            'risk_contributions': dict(zip(self.names, prc)),
            'diversification_ratio': float((w_opt @ np.sqrt(np.diag(self.Sigma))) / stats['vol']),
            'cvar_99': self._cvar_objective(w_opt),
            'converged': result.success,
            'objective': float(result.fun)
        }

    def optimization_comparison_table(self) -> pd.DataFrame:
        """Run all methods and summarize."""
        methods = ['mean_variance', 'min_variance', 'risk_parity', 'max_sharpe', 'max_diversification', 'robust']
        rows = []
        for m in methods:
            try:
                res = self.optimize(m)
                w = list(res['weights'].values())
                rows.append({
                    'Method': m.replace('_', ' ').title(),
                    **{n: f"{w[i] * 100:.1f}%" for i, n in enumerate(self.names)},
                    'Ann Vol': f"{res['portfolio_vol_ann'] * 100:.2f}%",
                    'Sharpe': f"{res['sharpe_ann']:.3f}",
                    'DR': f"{res['diversification_ratio']:.3f}",
                    'CVaR': f"{res['cvar_99'] * 100:.3f}%"
                })
            except Exception as e:
                rows.append({'Method': m, 'Error': str(e)})
        return pd.DataFrame(rows).set_index('Method')


# Full Demonstration
np.random.seed(42)
strats = ['Short Straddle', 'Iron Condor', 'Long Strangle', 'Dispersion', 'Tail Hedge']

# Covariance and expected returns
corr = np.array([
    [1.00, 0.65, -0.45, -0.20, -0.70],
    [0.65, 1.00, -0.30, -0.15, -0.50],
    [-0.45, -0.30, 1.00, 0.40, 0.60],
    [-0.20, -0.15, 0.40, 1.00, 0.25],
    [-0.70, -0.50, 0.60, 0.25, 1.00]
])
vols = np.array([0.08, 0.05, 0.12, 0.10, 0.20])
D = np.diag(vols)
Sigma = D @ corr @ D / 252
mu = np.array([0.06, 0.04, -0.02, 0.03, -0.04]) / 252

# Generate historical scenarios for CVaR optimization
scenarios = np.random.multivariate_normal(mu, Sigma, size=5000)

opt = VolPortfolioOptimizer(Sigma, mu, strats, scenarios=scenarios)

print("=" * 70)
print(" VOL PORTFOLIO OPTIMIZATION COMPARISON ")
print("=" * 70)
print(opt.optimization_comparison_table().to_string())

# Deep-dive on risk parity solution
rp_res = opt.optimize('risk_parity')
print("\n--- RISK PARITY SOLUTION DETAIL ---")
for name in strats:
    w = rp_res['weights'][name]
    rc = rp_res['risk_contributions'][name]
    print(f"  {name:<18}: weight ={w * 100:5.1f}% , risk contrib ={rc * 100:5.1f}%")
print(f"\n  Portfolio Vol (ann): {rp_res['portfolio_vol_ann'] * 100:.2f}%")
print(f"  Sharpe (ann ): {rp_res['sharpe_ann']:.3f}")
print(f"  Diversification Ratio : {rp_res['diversification_ratio']:.3f}")


import numpy as np
import pandas as pd
from scipy.stats import norm
import matplotlib.pyplot as plt
from matplotlib.colors import TwoSlopeNorm
from dataclasses import dataclass
from typing import List, Optional

# Option pricing helper
def bsm_price(S: float, K: float, T: float, r: float, sigma: float, otype: str) -> float:
    if T <= 1e-8 or sigma <= 1e-8:
        return max(S - K, 0.0) if otype == 'call' else max(K - S, 0.0)

    d1 = (np.log(S / K) + (r + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    if otype == 'call':
        return S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
    else:
        return K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)

@dataclass
class StressScenario:
    name: str
    spot_pct: float      # decimal, e.g. -0.20 = -20%
    vol_pts: float       # vol points shift, e.g. +15.0
    rate_bps: float = 0.0
    days_elapsed: int = 1

# Standard scenario library
SCENARIOS: List[StressScenario] = [
    StressScenario("Black Monday 1987", -0.22, 40.0, 0.0, 1),
    StressScenario("LTCM 1998", -0.22, 25.0, 50.0, 60),
    StressScenario("9/11 Attack 2001", -0.12, 20.0, -50.0, 5),
    StressScenario("Lehman GFC 2008", -0.40, 50.0, -200.0, 90),
    StressScenario("Flash Crash 2010", -0.09, 15.0, 0.0, 1),
    StressScenario("VIX Spike Aug 2015", -0.12, 20.0, 0.0, 5),
    StressScenario("Vol Armageddon 2018", -0.10, 20.0, 0.0, 2),
    StressScenario("COVID Crash 2020", -0.35, 65.0, -200.0, 20),
    StressScenario("V-Shape Recovery", +0.15, -20.0, 50.0, 30),
    StressScenario("Slow Vol Grind Up", +0.05, -5.0, 25.0, 60)
]

class VolBookStressTester:
    """
    Full revaluation stress tester for a volatility book.
    Reprices every position under each stress scenario.
    """
    def __init__(self, book: List[dict]):
        """
        book: list of dicts, each with keys:
        ticker, type, strike, T_years, spot, iv, r, qty, multiplier
        """
        self.book = book
        for pos in self.book:
            pos['base_price'] = bsm_price(
                pos['spot'], pos['strike'], pos['T_years'],
                pos['r'], pos['iv'], pos['type']
            )
            pos['base_value'] = pos['base_price'] * pos['qty'] * pos['multiplier']

    def run_scenario(self, sc: StressScenario) -> dict:
        """Full revaluation for a single scenario."""
        total_pnl = 0.0
        for pos in self.book:
            S_s = pos['spot'] * (1 + sc.spot_pct)
            iv_s = max(pos['iv'] + sc.vol_pts / 100.0, 0.01)
            T_s = max(pos['T_years'] - sc.days_elapsed / 252.0, 1e-6)
            r_s = pos['r'] + sc.rate_bps / 10000.0
            p_s = bsm_price(S_s, pos['strike'], T_s, r_s, iv_s, pos['type'])
            pnl = (p_s - pos['base_price']) * pos['qty'] * pos['multiplier']
            total_pnl += pnl
        return {
            'scenario': sc.name,
            'spot_pct': sc.spot_pct,
            'vol_pts': sc.vol_pts,
            'total_pnl': total_pnl
        }

    def run_all(self, scenarios: List[StressScenario] = None) -> pd.DataFrame:
        scenarios = scenarios or SCENARIOS
        rows = []
        for sc in scenarios:
            r = self.run_scenario(sc)
            rows.append({
                'Scenario': r['scenario'],
                'Spot': f"{r['spot_pct']*100:+.0f}%",
                'Vol': f"{r['vol_pts']:+.0f}vp",
                'P&L ($K)': f"${r['total_pnl']/1e3:+.1f}K",
                'total_pnl': r['total_pnl']
            })
        df = pd.DataFrame(rows)
        df.sort_values('total_pnl', inplace=True)
        return df

    def scenario_grid(self, spot_range = None, vol_range = None):
        """2-D scenario grid: returns PnL matrix, spot_range, vol_range."""
        if spot_range is None:
            spot_range = np.linspace(-0.30, 0.20, 21)
        if vol_range is None:
            vol_range = np.linspace(-10, 35, 19)
        pnl_grid = np.zeros((len(vol_range), len(spot_range)))
        for i, vp in enumerate(vol_range):
            for j, sp in enumerate(spot_range):
                sc = StressScenario("grid", sp, vp)
                pnl_grid[i, j] = self.run_scenario(sc)['total_pnl']
        return pnl_grid, spot_range, vol_range

    def plot_pnl_heatmap(self):
        """Render the full-revaluation P&L heatmap."""
        pnl_grid, spot_range, vol_range = self.scenario_grid()
        fig, ax = plt.subplots(figsize=(14, 8))
        max_abs = np.max(np.abs(pnl_grid)) or 1
        norm = TwoSlopeNorm(vcenter=0, vmin=-max_abs, vmax=max_abs)
        ax.imshow(pnl_grid, cmap='RdYlGn', norm=norm, aspect='auto', origin='lower')
        ax.set_xticks(range(len(spot_range)))
        ax.set_xticklabels([f"{s * 100:+.0f}%" for s in spot_range], rotation=45, ha='right', fontsize=7)
        ax.set_yticks(range(len(vol_range)))
        ax.set_yticklabels([f"{v:+.0f}" for v in vol_range], fontsize=8)

        for i in range(len(vol_range)):
            for j in range(len(spot_range)):
                val = pnl_grid[i, j] / 1000
                col = 'black' if abs(val) < max_abs / 2000 else 'white'
                ax.text(j, i, f"${val:.0f}K", ha='center', va='center', fontsize=6, color=col, fontweight='bold')

        ax.set_xlabel('Spot Change (%)', fontsize=10)
        ax.set_ylabel('Vol Change (vol points)', fontsize=10)
        ax.set_title('Full Revaluation P&L Heatmap (Spot x Vol Grid)', fontsize=12, fontweight='bold', color='#0A3E78')
        plt.tight_layout()
        return fig

    def reverse_stress(self, loss_threshold: float = -500_000) -> pd.DataFrame:
        """Identify all grid scenarios where P&L < loss_threshold."""
        pnl_grid, sr, vr = self.scenario_grid()
        rows = []
        for i, vp in enumerate(vr):
            for j, sp in enumerate(sr):
                if pnl_grid[i, j] < loss_threshold:
                    rows.append({
                        'Spot Move': f"{sp * 100:+.1f}%",
                        'Vol Change': f"{vp:+.1f}vp",
                        'P&L': f"${pnl_grid[i, j]/1e3:+.1f}K",
                        'Severity': 'EXTREME' if pnl_grid[i, j] < 2 * loss_threshold else 'SEVERE'
                    })
        return pd.DataFrame(rows)


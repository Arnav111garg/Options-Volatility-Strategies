import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from dataclasses import dataclass

@dataclass
class RegimeParams:
    mu: float # annualized drift (decimal)
    sigma: float # spot vol (annualized decimal)
    kappa: float # mean-reversion speed (vol)
    theta: float # long-run vol level (decimal)
    xi: float # vol of vol
    rho: float # spot-vol correlation
    name: str = "regime"

class VolBookCrisisSimulator:
    """
    Simulates vol book P&L under Markov regime-switching dynamics.
    """
    def __init__(self, normal: RegimeParams, crisis: RegimeParams,
                 p_stay_normal: float = 0.99,
                 p_stay_crisis: float = 0.95,
                 n_paths: int = 2000, n_days: int = 252,
                 dt: float = 1/252):
        self.normal = normal
        self.crisis = crisis
        self.trans = np.array([
            [p_stay_normal, 1 - p_stay_normal],
            [1 - p_stay_crisis, p_stay_crisis]
        ])
        self.n_paths = n_paths
        self.n_days = n_days
        self.dt = dt

    def simulate(self) -> dict:
        n, T, dt = self.n_paths, self.n_days, self.dt
        regimes = np.zeros((n, T + 1), dtype=int)
        spots = np.zeros((n, T + 1))
        vols = np.zeros((n, T + 1))
        spots[:, 0] = 4500.0
        vols[:, 0] = 0.15

        rng = np.random.default_rng(42)

        for t in range(T):
            r_cur = regimes[:, t]
            rand = rng.uniform(size=n)
            r_new = np.where(rand < self.trans[r_cur, r_cur], r_cur, 1 - r_cur)
            regimes[:, t + 1] = r_new

            Z1 = rng.standard_normal(n)
            Z2 = rng.standard_normal(n)

            for ri, pm in enumerate([self.normal, self.crisis]):
                mask = (r_new == ri)
                if not mask.any():
                    continue
                S = spots[mask, t]
                v = np.maximum(vols[mask, t], 0.005)
                dWs = Z1[mask] * np.sqrt(dt)
                dWv = (pm.rho * Z1[mask] + np.sqrt(1 - pm.rho ** 2) * Z2[mask]) * np.sqrt(dt)

                spots[mask, t + 1] = S * np.exp((pm.mu - 0.5 * pm.sigma ** 2) * dt + pm.sigma * dWs)
                dv = pm.kappa * (pm.theta - v) * dt + pm.xi * np.sqrt(v) * dWv
                vols[mask, t + 1] = np.maximum(v + dv, 0.005)

        return {'spots': spots, 'vols': vols, 'regimes': regimes}

    def compute_pnl(self, paths: dict, greeks: dict) -> np.ndarray:
        """
        Compute cumulative P&L per path using Greek approximation.
        greeks: { 'dollar_gamma': ... , 'dollar_vega': ... , 'dollar_theta': ...}
        """
        spots, vols = paths['spots'], paths['vols']
        n, T = spots.shape[0], spots.shape[1] - 1
        G = greeks
        daily_pnl = np.zeros((n, T))

        for t in range(T):
            S = spots[:, t]
            r_s = (spots[:, t + 1] - S) / S
            dsig = (vols[:, t + 1] - vols[:, t]) * 100 # in vol-point units
            daily_pnl[:, t] = (
                G['dollar_gamma'] * r_s ** 2 / (0.01 ** 2) * 0.5
                + G['dollar_vega'] * dsig
                + G['dollar_theta'] * self.dt * 252
            )
        return np.cumsum(daily_pnl, axis=1)

    def run(self, greeks: dict) -> dict:
        paths = self.simulate()
        cum_pnl = self.compute_pnl(paths, greeks)
        final = cum_pnl[:, -1]
        peaks = np.maximum.accumulate(cum_pnl, axis=1)
        max_dd = (cum_pnl - peaks).min(axis=1)
        crisis_days = (paths['regimes'][:, 1:] == 1).sum(axis=1)
        mc_rate = (cum_pnl < -1000000).any(axis=1).mean()

        return {
            'final_pnl': final,
            'cum_pnl': cum_pnl,
            'max_drawdown': max_dd,
            'crisis_days': crisis_days,
            'stats': {
                'mean': final.mean(),
                'std': final.std(),
                'var_99': np.percentile(final, 1),
                'cvar_99': final[final <= np.percentile(final, 1)].mean(),
                'prob_loss': (final < 0).mean(),
                'max_dd_mean': max_dd.mean(),
                'max_dd_p99': np.percentile(max_dd, 1),
                'margin_call': mc_rate,
            }
        }

    def plot_results(self, results: dict, n_plot: int = 80):
        """Visualise simulation outcomes."""
        fig, axes = plt.subplots(1, 2, figsize=(14, 6))
        paths = results['cum_pnl']
        t_ax = np.arange(paths.shape[1])
        idx = np.random.choice(paths.shape[0], n_plot, replace=False)

        # Left: P&L paths
        ax = axes[0]
        for i in idx:
            col = '#B41E1E' if paths[i, -1] < 0 else '#0A3E78'
            ax.plot(t_ax, paths[i] / 1e3, color=col, alpha=0.08, lw=0.7)

        for pct, ls in [(5, '--'), (95, '--'), (50, '-')]:
            col = 'black' if pct != 50 else 'gold'
            ax.plot(t_ax, np.percentile(paths, pct, axis=0) / 1e3, color=col, ls=ls, lw=1.8, label=f'P{pct}')

        ax.axhline(0, color='black', lw=0.8)
        ax.set_xlabel('Trading Days')
        ax.set_ylabel('Cumulative P&L ($K)')
        ax.set_title('Crisis Simulation Paths', fontweight='bold', color='#0A3E78')
        ax.legend(fontsize=8)
        ax.grid(alpha=0.3)

        # Right: Final P&L distribution
        ax = axes[1]
        ax.hist(paths[:, -1] / 1e3, bins=70, color='#0A3E78', alpha=0.7, edgecolor='white', density=True)
        v99 = np.percentile(paths[:, -1], 1) / 1e3
        ax.axvline(v99, color='red', lw=2, ls='--', label=f'99% VaR: ${v99:.0f}K')
        ax.axvline(paths[:, -1].mean() / 1e3, color='gold', lw=2, label=f"Mean: ${paths[:, -1].mean() / 1e3:.0f}K")
        ax.set_xlabel('Final P&L ($K)')
        ax.set_title('Final P&L Distribution', fontweight='bold', color='#0A3E78')
        ax.legend(fontsize=8)
        ax.grid(alpha=0.3)

        plt.suptitle('Vol Book Crisis Simulation (2000 Paths, 252 Days)', fontsize=12, fontweight='bold', color='#0A3E78')
        plt.tight_layout()
        return fig


# Run demonstration
normal_p = RegimeParams(mu=0.10, sigma=0.12, kappa=5.0, theta=0.15, xi=0.30, rho=-0.70, name='Normal')
crisis_p = RegimeParams(mu=-0.40, sigma=0.45, kappa=2.0, theta=0.50, xi=1.20, rho=-0.90, name='Crisis')

sim = VolBookCrisisSimulator(normal_p, crisis_p, n_paths=2000, n_days=252)
greeks = {
    'dollar_gamma': 5000,   # long gamma
    'dollar_vega': -45000,  # short vega
    'dollar_theta': 8000    # positive theta
}

results = sim.run(greeks)
st = results['stats']
print("\n CRISIS SIMULATION SUMMARY ")
print(f" Mean annual P&L: ${st['mean']: >12,.0f}")
print(f" 99% VaR (annual): ${st['var_99']: >12,.0f}")
print(f" 99% CVaR (annual): ${st['cvar_99']: >12,.0f}")
print(f" Prob of Loss: {st['prob_loss'] * 100: >10.1f}%")
print(f" Mean Max Drawdown: ${st['max_dd_mean']: >12,.0f}")
print(f" Margin Call Rate: {st['margin_call'] * 100: >10.1f}%")


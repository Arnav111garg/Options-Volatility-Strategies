import numpy as np
import pandas as pd
from scipy.optimize import minimize
from scipy.stats import norm
import warnings

class RiskBudgetEngine:
    """
    Complete risk budgeting framework for volatility portfolios.
    Supports VaR, CVaR, and volatility-based risk decomposition.
    """

    def __init__(self, cov_matrix: np.ndarray, strategy_names: list = None, mean_returns: np.ndarray = None):
        """
        cov_matrix : (N x N) strategy P&L covariance matrix (daily)
        strategy_names : list of strategy labels
        mean_returns : daily mean returns (optional)
        """
        self.Sigma = np.array(cov_matrix)
        self.N = self.Sigma.shape[0]
        self.names = strategy_names or [f"S{i+1}" for i in range(self.N)]
        self.mu = mean_returns if mean_returns is not None else np.zeros(self.N)
        self._validate()

    def _validate(self):
        eigvals = np.linalg.eigvalsh(self.Sigma)
        if np.any(eigvals < -1e-8):
            raise ValueError(f"Covariance matrix not PSD. Min eigval = {eigvals.min():.4e}")

    # Risk decomposition
    def portfolio_vol(self, w: np.ndarray) -> float:
        """Portfolio volatility (annualized if daily Sigma)."""
        var = float(w @ self.Sigma @ w)
        return np.sqrt(max(var, 0)) * np.sqrt(252)

    def marginal_contrib(self, w: np.ndarray) -> np.ndarray:
        """Marginal Risk Contribution (MCR) = d(sigma_p)/d(w_i)."""
        sig = self.portfolio_vol(w) / np.sqrt(252)
        return (self.Sigma @ w) / sig

    def risk_contrib(self, w: np.ndarray) -> np.ndarray:
        """Absolute risk contributions RC_i = w_i * MCR_i."""
        mcr = self.marginal_contrib(w)
        return w * mcr * np.sqrt(252)  # annualised

    def pct_risk_contrib(self, w: np.ndarray) -> np.ndarray:
        """Percentage risk contributions PRC_i = RC_i / sigma_p."""
        rc = self.risk_contrib(w)
        return rc / rc.sum()

    # VaR / CVaR
    def parametric_var(self, w: np.ndarray, alpha: float = 0.99, horizon: int = 1, notional: float = 1e6) -> dict:
        """
        Gaussian parametric VaR and CVaR.
        horizon : days
        notional : portfolio size in $
        Returns dict with VaR, CVaR, component VaR.
        """
        port_mean = float(self.mu @ w) * horizon
        port_var = float(w @ self.Sigma @ w) * horizon
        port_vol = np.sqrt(port_var)
        z_alpha = norm.ppf(alpha)

        # Portfolio VaR and CVaR
        var_dollar = notional * (-port_mean + z_alpha * port_vol)
        cvar_dollar = notional * (-port_mean + port_vol * norm.pdf(z_alpha) / (1 - alpha))

        # Component VaR
        cov_w = self.Sigma @ w
        beta = cov_w / port_var  # betas
        comp_var = notional * (-self.mu * horizon + z_alpha * beta * port_vol * horizon)

        return {
            'VaR_99': var_dollar,
            'CVaR_99': cvar_dollar,
            'portfolio_vol_daily': port_vol,
            'portfolio_vol_annual': port_vol * np.sqrt(252),
            'component_VaR': dict(zip(self.names, comp_var)),
            'pct_risk_contrib': dict(zip(self.names, self.pct_risk_contrib(w)))
        }

    # Risk parity optimization
    def risk_parity_weights(self, target_rc: np.ndarray = None) -> np.ndarray:
        """
        Solve for risk-parity weights where RC_i = target_rc[i] * sigma_p.
        If target_rc is None, solves for equal risk contribution.
        Uses the squared-error objective from Roncalli (2013):
        min sum_i (RC_i - target_i)^2
        """
        if target_rc is None:
            target_rc = np.ones(self.N) / self.N  # equal

        def objective(w):
            rc = self.risk_contrib(w)
            sig = self.portfolio_vol(w)
            # Normalize: minimize squared deviation from target fractions
            rc_frac = rc / rc.sum()
            return np.sum((rc_frac - target_rc) ** 2)

        def gradient(w):
            """Numerical gradient (analytical exists but complex)."""
            eps = 1e-6
            g = np.zeros(self.N)
            f0 = objective(w)
            for i in range(self.N):
                we = w.copy()
                we[i] += eps
                g[i] = (objective(we) - f0) / eps
            return g

        constraints = [{'type': 'eq', 'fun': lambda w: w.sum() - 1}]
        bounds = [(0.001, 1.0)] * self.N  # long-only constraint
        w0 = np.ones(self.N) / self.N

        result = minimize(
            objective,
            w0,
            method='SLSQP',
            jac=gradient,
            bounds=bounds,
            constraints=constraints,
            options={'ftol': 1e-12, 'maxiter': 2000}
        )

        if not result.success:
            warnings.warn(f"Optimization did not converge: {result.message}")

        return result.x

    def print_risk_report(self, w: np.ndarray, notional: float = 1e6):
        """Print a formatted risk attribution report."""
        report = self.parametric_var(w, notional=notional)
        rc = self.risk_contrib(w)
        prc = self.pct_risk_contrib(w)

        print("=" * 60)
        print(" RISK BUDGET REPORT ")
        print("=" * 60)
        print(f"Portfolio Annual Vol: {report['portfolio_vol_annual']*100:.2f}%")
        print(f"1-Day 99% VaR: ${report['VaR_99']:>10,.0f}")
        print(f"1-Day 99% CVaR: ${report['CVaR_99']:>10,.0f}")
        print("-" * 60)
        print(f"{'Strategy':<18} {'Weight':>8} {'RC (ann)':>12} {'% RC':>8} {'Comp VaR':>12}")
        print("-" * 60)
        for i, name in enumerate(self.names):
            cv = report['component_VaR'][name]
            print(f"{name:<18} {w[i]:>8.3f} {rc[i]*notional:>12,.0f} {prc[i]*100:>7.1f}% ${cv:>10,.0f}")
        print("=" * 60)


# Demonstration
np.random.seed(123)

# Strategy covariance (5 strategies, annualized in decimal returns)
strats = ['Short Straddle', 'Iron Condor', 'Long Strangle', 'Dispersion', 'Tail Hedge']

# Rough correlation matrix typical for vol strategies
corr = np.array([
    [1.00, 0.65, -0.45, -0.20, -0.70],
    [0.65, 1.00, -0.30, -0.15, -0.50],
    [-0.45, -0.30, 1.00, 0.40, 0.60],
    [-0.20, -0.15, 0.40, 1.00, 0.25],
    [-0.70, -0.50, 0.60, 0.25, 1.00]
])

vols = np.array([0.08, 0.05, 0.12, 0.10, 0.20])  # annual
D = np.diag(vols)
cov = D @ corr @ D / 252  # daily covariance

mu_daily = np.array([0.0003, 0.0002, -0.0001, 0.0001, -0.0002])

engine = RiskBudgetEngine(cov, strats, mu_daily)

# Equal weights
w_eq = np.ones(5) / 5
print("\n--- EQUAL WEIGHTS ---")
engine.print_risk_report(w_eq)

# Risk parity weights
w_rp = engine.risk_parity_weights()
print("\n--- RISK PARITY WEIGHTS ---")
engine.print_risk_report(w_rp)


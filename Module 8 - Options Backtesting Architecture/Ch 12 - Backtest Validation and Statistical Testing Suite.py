import numpy as np
import pandas as pd
from scipy import stats
from scipy.stats import norm
from typing import List, Dict, Optional, Tuple

class BacktestValidator:
    """
    Comprehensive validation suite for options backtests.
    Implements: DSR, walk-forward, stress tests, regime analysis,
    and P&L decomposition quality checks.
    """

    def __init__(self, snapshots: List['AccountingSnapshot'], n_trials: int = 1):
        df = pd.DataFrame([vars(s) for s in snapshots])
        df['date'] = pd.to_datetime(df['date'])
        df = df.set_index('date').sort_index()
        df['returns'] = df['nav'].pct_change().fillna(0.0)
        self.df = df
        self.n_trials = n_trials  # number of backtests run

    def sharpe_ratio(self, ann_factor: int = 252) -> float:
        r = self.df['returns']
        sr = r.mean() / r.std() * np.sqrt(ann_factor)
        return sr

    def deflated_sharpe_ratio(self, ann_factor: int = 252) -> dict:
        """
        Compute Deflated Sharpe Ratio (Bailey & Lopez de Prado 2014).
        Accounts for non-normal distribution and multiple testing.
        """
        r = self.df['returns']
        T = len(r)
        SR_hat = r.mean() / r.std() * np.sqrt(ann_factor)

        # Moments of return distribution
        skew = stats.skew(r)
        kurt = stats.kurtosis(r)  # excess kurtosis

        # Variance of SR estimator
        var_sr = ((1.0 - skew * SR_hat / np.sqrt(ann_factor)
                   + (kurt + 2.0) / 4.0
                   * (SR_hat / np.sqrt(ann_factor)) ** 2)
                  / T)

        # Expected maximum SR under H0 with n_trials tests
        N = self.n_trials
        if N > 1:
            # Expected maximum of N iid N(0,1) variables
            E_max_z = norm.ppf(1.0 - 1.0 / N) if N > 1 else 0.0
            V_max_z = 1.0 - E_max_z * norm.pdf(E_max_z)
            SR_star = (E_max_z
                       * np.sqrt(1.0 + 0.5 * (1.0 - 2.0 / T) * kurt) / np.sqrt(T))
        else:
            SR_star = 0.0

        # DSR
        dsr_z = (SR_hat - SR_star) / np.sqrt(max(var_sr, 1e-12))
        dsr = norm.cdf(dsr_z)

        return {
            'sharpe': SR_hat,
            'SR_star': SR_star,
            'dsr': dsr,
            'dsr_z': dsr_z,
            'significant': dsr > 0.95,
            'T': T,
            'N_trials': N,
            'skewness': skew,
            'excess_kurt': kurt,
        }

    def walk_forward_test(
        self,
        strategy_func,
        n_windows: int = 5,
        train_frac: float = 0.7
    ) -> pd.DataFrame:
        """
        Walk-forward validation: train on first 70%, test on last 30%
        of each window; roll forward.
        """
        total_len = len(self.df)
        window_len = total_len // n_windows
        results = []

        for i in range(n_windows):
            start = i * window_len
            end = min((i + 1) * window_len, total_len)
            split = start + int((end - start) * train_frac)

            df_train = self.df.iloc[start:split]
            df_test = self.df.iloc[split:end]

            # Run strategy on train / test splits
            # (strategy_func returns metrics dict)
            train_metrics = strategy_func(df_train)
            test_metrics = strategy_func(df_test)

            results.append({
                'window': i + 1,
                'train_start': df_train.index[0],
                'train_end': df_train.index[-1],
                'test_start': df_test.index[0],
                'test_end': df_test.index[-1],
                'train_sharpe': train_metrics.get('sharpe', np.nan),
                'test_sharpe': test_metrics.get('sharpe', np.nan),
                'train_return': train_metrics.get('ann_return', np.nan),
                'test_return': test_metrics.get('ann_return', np.nan),
            })

        df_wf = pd.DataFrame(results)
        df_wf['consistency'] = (
            np.sign(df_wf['train_sharpe'])
            == np.sign(df_wf['test_sharpe'])
        ).mean()
        return df_wf

    def pnl_attribution_quality(self) -> dict:
        """
        Validate quality of P&L attribution.
        The sum of attributed components should equal total P&L.
        """
        if 'delta_pnl' not in self.df.columns:
            return {'error': 'No attribution data available'}

        total_pnl = self.df['daily_pnl'].sum()
        attributed = (self.df['delta_pnl'].sum()
                      + self.df['gamma_pnl'].sum()
                      + self.df['vega_pnl'].sum()
                      + self.df['theta_pnl'].sum()
                      - self.df['tc_drag'].sum())
        unexplained = self.df['unexplained_pnl'].sum()
        explain_ratio = attributed / total_pnl if total_pnl != 0 else 0.0

        return {
            'total_pnl': total_pnl,
            'attributed_pnl': attributed,
            'unexplained': unexplained,
            'explain_ratio': explain_ratio,
            'quality': 'GOOD' if abs(unexplained / total_pnl) < 0.05 else 'POOR',
            'delta_contrib': self.df['delta_pnl'].sum() / total_pnl,
            'gamma_contrib': self.df['gamma_pnl'].sum() / total_pnl,
            'vega_contrib': self.df['vega_pnl'].sum() / total_pnl,
            'theta_contrib': self.df['theta_pnl'].sum() / total_pnl,
            'tc_drag': self.df['tc_drag'].sum() / total_pnl,
        }

    def regime_analysis(self, vix_series: pd.Series) -> pd.DataFrame:
        """
        Break down strategy performance by VIX regime.
        """
        df_merged = self.df.copy()
        df_merged['vix'] = vix_series.reindex(df_merged.index)
        df_merged['vix_regime'] = pd.cut(
            df_merged['vix'],
            bins=[0, 15, 20, 25, 35, 100],
            labels=['<15', '15-20', '20-25', '25-35', '>35']
        )

        results = []
        for regime, grp in df_merged.groupby('vix_regime', observed=True):
            if len(grp) < 5:
                continue
            ann = 252
            sr = (grp['returns'].mean() / grp['returns'].std() * np.sqrt(ann)) if grp['returns'].std() > 0.0 else 0.0
            results.append({
                'vix_regime': str(regime),
                'n_days': len(grp),
                'ann_return': grp['returns'].mean() * ann,
                'ann_vol': grp['returns'].std() * np.sqrt(ann),
                'sharpe': sr,
                'win_rate': (grp['daily_pnl'] > 0.0).mean(),
                'avg_daily_pnl': grp['daily_pnl'].mean(),
            })

        return pd.DataFrame(results)

    def stress_test(
        self,
        spot_shocks: List[float] = None,
        vol_shocks: List[float] = None,
        portfolio: 'OptionsPortfolio' = None,
        pricer: 'BlackScholesPricer' = None,
        current_spot: float = 100.0
    ) -> pd.DataFrame:
        """
        Stress test portfolio P&L under spot and vol scenarios.
        """
        if spot_shocks is None:
            spot_shocks = [-0.30, -0.20, -0.10, -0.05, 0.0, 0.05, 0.10, 0.20]
        if vol_shocks is None:
            vol_shocks = [-0.20, -0.10, 0.0, 0.10, 0.20, 0.50]

        results = []
        for ds in spot_shocks:
            for dv in vol_shocks:
                shocked_spot = current_spot * (1.0 + ds)
                pnl_shock = 0.0

                if portfolio and pricer:
                    for pos in portfolio.positions.values():
                        if pos.greeks is None:
                            continue
                        import datetime
                        T = max((pos.contract.expiry_date - datetime.date.today()).days / 365.0, 1.0 / 365.0)
                        shocked_iv = max(
                            0.01,
                            (pos.greeks.vega / (pos.multiplier * pos.quantity + 1e-9) + dv) if False else 0.20 + dv
                        )
                        new_g = pricer.price_and_greeks(
                            S=shocked_spot,
                            K=pos.contract.strike,
                            T=T,
                            r=portfolio.r,
                            q=portfolio.q,
                            sigma=shocked_iv,
                            right=pos.contract.right
                        )
                        old_price = pos.greeks.price
                        new_price = new_g.price
                        pnl_shock += (pos.quantity * pos.multiplier * (new_price - old_price))

                results.append({
                    'spot_shock %': ds * 100.0,
                    'vol_shock %': dv * 100.0,
                    'pnl_shock': pnl_shock,
                })

        df = pd.DataFrame(results)
        df_pivot = df.pivot(index='spot_shock %', columns='vol_shock %', values='pnl_shock')
        return df_pivot

    def full_validation_report(self) -> dict:
        """
        Generate complete validation report.
        """
        r = self.df['returns']
        return {
            'basic_stats': {
                'n_obs': len(r),
                'total_return': (self.df['nav'].iloc[-1] / self.df['nav'].iloc[0] - 1.0),
                'sharpe': self.sharpe_ratio(),
                'max_drawdown': ((self.df['nav'].cummax() - self.df['nav']) / self.df['nav'].cummax()).max(),
                'skewness': stats.skew(r),
                'kurtosis': stats.kurtosis(r),
                'var_99_1day': np.percentile(r, 1.0),
                'cvar_99_1day': r[r <= np.percentile(r, 1.0)].mean(),
            },
            'dsr': self.deflated_sharpe_ratio(),
            'pnl_attribution': self.pnl_attribution_quality(),
        }



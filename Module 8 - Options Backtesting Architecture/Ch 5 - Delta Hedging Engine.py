import numpy as np
from typing import Optional
from enum import Enum
from dataclasses import dataclass, field

class HedgeRule(Enum):
    FIXED_TIME = "fixed_time"
    DELTA_BAND = "delta_band"
    HYBRID = "hybrid" # band + EOD

@dataclass
class HedgeState:
    """Tracks state between hedge events."""
    last_hedge_time: Optional[object] = None
    last_hedge_delta: float = 0.0
    cumulative_cost: float = 0.0
    n_hedges: int = 0
    hedge_pnl_series: list = field(default_factory=list)

class DeltaHedgingEngine:
    """
    Delta hedging engine that works within the event-driven system.
    Handles fixed-time, delta-band, and hybrid rebalancing rules.
    """

    def __init__(
        self,
        portfolio: 'OptionsPortfolio',
        rule: HedgeRule = HedgeRule.HYBRID,
        delta_band: float = 0.05, # rehedge threshold
        tc_per_share: float = 0.005, # transaction cost
        min_shares: int = 1 # minimum hedge size
    ):
        self.portfolio = portfolio
        self.rule = rule
        self.delta_band = delta_band
        self.tc_per_share = tc_per_share
        self.min_shares = min_shares
        self.state = HedgeState()

    def should_hedge(self, current_delta: float, is_eod: bool, current_time: object) -> bool:
        """
        Decision function: should we hedge now?
        current_delta: current net portfolio delta (in shares)
        """
        if self.rule == HedgeRule.FIXED_TIME:
            return is_eod

        elif self.rule == HedgeRule.DELTA_BAND:
            drift = abs(current_delta - self.state.last_hedge_delta)
            return drift >= self.delta_band

        elif self.rule == HedgeRule.HYBRID:
            drift = abs(current_delta - self.state.last_hedge_delta)
            return (drift >= self.delta_band) or is_eod

        return False

    def compute_hedge_trade(self, spot: float) -> dict:
        """
        Compute the hedge trade needed to neutralise portfolio delta.
        Returns: dict with shares_to_trade, cost, direction
        """
        target_delta = 0.0 # delta-neutral target
        port_delta = self.portfolio.portfolio_delta
        current_hedge = self.portfolio.hedge_qty

        # Shares needed: options_delta + hedge = target
        # => hedge_target = target - options_delta
        hedge_target = target_delta - (port_delta - current_hedge)
        shares_to_trade = hedge_target - current_hedge

        # Round to minimum lot size
        shares_to_trade = int(shares_to_trade / self.min_shares) * self.min_shares

        cost = abs(shares_to_trade) * self.tc_per_share
        return {
            'shares_to_trade': shares_to_trade,
            'hedge_target': hedge_target,
            'port_delta': port_delta,
            'transaction_cost': cost,
            'direction': np.sign(shares_to_trade)
        }

    def execute_hedge(self, spot: float, current_time: object, is_eod: bool = False) -> Optional[dict]:
        """
        Attempt a delta hedge. Returns trade details if executed.
        """
        port_delta = self.portfolio.portfolio_delta

        if not self.should_hedge(port_delta, is_eod, current_time):
            return None

        trade = self.compute_hedge_trade(spot)
        if abs(trade['shares_to_trade']) < self.min_shares:
            return None

        # Execute: adjust hedge position
        self.portfolio.hedge_qty += trade['shares_to_trade']

        # Debit cash for hedge + transaction cost
        # (buying shares: pay spot; selling: receive spot)
        cash_change = -trade['shares_to_trade'] * spot - trade['transaction_cost']
        self.portfolio.cash += cash_change

        # Update state
        self.state.last_hedge_time = current_time
        self.state.last_hedge_delta = self.portfolio.portfolio_delta
        self.state.cumulative_cost += trade['transaction_cost']
        self.state.n_hedges += 1

        trade['cash_change'] = cash_change
        trade['cumulative_cost'] = self.state.cumulative_cost
        trade['hedge_number'] = self.state.n_hedges
        self.state.hedge_pnl_series.append({
            'time': current_time,
            'spot': spot,
            **trade
        })
        return trade

    def hedge_pnl_summary(self) -> dict:
        """Summary statistics of hedging activity."""
        n = self.state.n_hedges
        cost = self.state.cumulative_cost
        return {
            'num_hedges': n,
            'total_hedge_cost': cost,
            'avg_cost_per_hedge': cost / n if n > 0 else 0.0,
        }

# ---- Delta P&L Attribution ----------------------------------------
def compute_delta_pnl_attribution(
    delta_t: float, # portfolio delta at time t
    spot_t: float,
    spot_t1: float,
    hedge_qty: float,
    tc: float = 0.0
) -> dict:
    """
    Compute P&L components for one timestep.
    Returns decomposition into option delta P&L and hedge P&L.
    """
    dS = spot_t1 - spot_t
    option_pnl = delta_t * dS
    hedge_pnl = hedge_qty * dS
    net_pnl = option_pnl + hedge_pnl - tc
    return {
        'dS': dS,
        'option_pnl': option_pnl,
        'hedge_pnl': hedge_pnl,
        'tc': tc,
        'net_delta_pnl': net_pnl,
    }


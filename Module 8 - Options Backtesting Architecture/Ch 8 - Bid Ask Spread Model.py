import numpy as np
from scipy.stats import beta as beta_dist

class BidAskSpreadModel:
    """
    Options bid-ask spread model with multiple regimes.
    Supports: fixed, volatility-scaled, regression-based, stochastic.
    """

    # Empirical calibration (from OptionMetrics research)
    SPREAD_PARAMS = {
        'alpha0': 0.02,   # base spread
        'alpha1': 0.15,   # vol scaling
        'alpha2': 0.05,   # moneyness penalty
        'beta1': 0.70,    # price scaling
        'beta2': -0.30,   # volume scaling
        'beta3': 0.40,    # DTE scaling
    }

    def __init__(
        self,
        model: str = 'vol_scaled',
        stochastic: bool = False,
        spread_noise: float = 0.10
    ):
        self.model = model
        self.stochastic = stochastic
        self.spread_noise = spread_noise
        self._rng = np.random.default_rng(42)

    def half_spread(
        self,
        mid_price: float,
        iv: float,
        dte: float,  # days to expiry
        strike: float,
        spot: float,
        daily_vol: float = 5000,
        order_qty: int = 1
    ) -> float:
        """
        Compute the half bid-ask spread for a given option.
        Returns dollars per share.
        """
        p = self.SPREAD_PARAMS

        if self.model == 'fixed':
            s = max(0.05, mid_price * 0.02)

        elif self.model == 'vol_scaled':
            moneyness = abs(np.log(spot / strike))
            s = (
                p['alpha0']
                + p['alpha1'] * iv * np.sqrt(max(dte, 1.0) / 252.0)
                + p['alpha2'] * moneyness ** 2
            )
            s = max(s, 0.01)  # floor at $0.01

        elif self.model == 'regression':
            # Log-linear regression model
            log_s = (
                np.log(p['alpha0'])
                + p['beta1'] * np.log(max(mid_price, 0.01))
                + p['beta2'] * np.log(max(daily_vol, 1.0))
                + p['beta3'] / np.sqrt(max(dte, 0.1))
            )
            s = np.exp(log_s)

        else:
            raise ValueError(f"Unknown model: {self.model}")

        # Kyle lambda market impact for larger orders
        if order_qty > 1:
            kyle_lambda = mid_price * 0.001
            s += kyle_lambda * np.sqrt(order_qty)

        # Add stochastic noise (spread fluctuates)
        if self.stochastic:
            noise_mult = 1.0 + self.spread_noise * self._rng.standard_normal()
            s *= max(noise_mult, 0.3)  # prevent negative spread

        return max(s / 2.0, 0.005)  # half-spread, min $0.005

    def bid_ask(
        self,
        mid_price: float,
        iv: float,
        dte: float,
        strike: float,
        spot: float,
        **kwargs
    ) -> tuple:
        """ Returns (bid, ask) given mid price ."""
        hs = self.half_spread(
            mid_price, iv, dte, strike, spot, **kwargs
        )
        return max(mid_price - hs, 0.0), mid_price + hs

    def fill_price(
        self,
        mid_price: float,
        side: str,
        iv: float,
        dte: float,
        strike: float,
        spot: float,
        **kwargs
    ) -> float:
        """
        Determine fill price given trade direction.
        side: 'buy' fills at ask, 'sell' fills at bid.
        """
        bid, ask = self.bid_ask(
            mid_price, iv, dte, strike, spot, **kwargs
        )
        return ask if side == 'buy' else bid

# ---- Spread surface visualization helper ----------------------
def compute_spread_surface(spot, iv_surface, model='vol_scaled'):
    """
    Compute spread half-widths across the vol surface.
    Returns same-indexed structure as iv_surface.
    """
    sm = BidAskSpreadModel(model=model)
    spread_surface = {}
    for (strike, expiry, right), iv in iv_surface.items():
        import datetime
        dte = max((expiry - datetime.date.today()).days, 1)
        # Approximate mid price using BS
        # (simplified - use pricer in practice)
        approx_mid = max(
            spot * abs(strike / spot - 1.0) * iv * np.sqrt(dte / 252.0) * 0.4,
            0.05
        )
        spread_surface[(strike, expiry, right)] = sm.half_spread(
            mid_price=approx_mid,
            iv=iv,
            dte=dte,
            strike=strike,
            spot=spot
        )
    return spread_surface


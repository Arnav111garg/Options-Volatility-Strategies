import numpy as np
from dataclasses import dataclass
from typing import Optional

@dataclass
class TransactionCostModel:
    """
    Comprehensive transaction cost model for options.
    """
    # Spread costs
    use_actual_spread: bool = True       # use real bid/ask if available
    default_spread_bps: float = 20.0     # fallback: 20 bps of option price
    min_spread_dollars: float = 0.05     # minimum spread per share

    # Commissions
    commission_per_contract: float = 0.65 # per contract
    commission_per_share: float = 0.005  # for underlying hedges

    # Market impact
    impact_coefficient: float = 0.1      # eta in Almgren-Chriss
    enable_impact: bool = True

    # Margin rate
    margin_rate_annual: float = 0.05     # 5% annual on margin balance

    def spread_cost(
        self,
        mid_price: float,
        bid_price: Optional[float],
        ask_price: Optional[float],
        quantity: int,
        multiplier: int = 100
    ) -> float:
        """Half-spread cost for one-way trade."""
        if (
            self.use_actual_spread
            and bid_price is not None
            and ask_price is not None
        ):
            half_spread = (ask_price - bid_price) / 2.0
        else:
            half_spread = max(
                mid_price * self.default_spread_bps / 10000,
                self.min_spread_dollars
            )
        return abs(quantity) * multiplier * half_spread

    def commission_cost(self, quantity: int, asset_type: str = 'option') -> float:
        if asset_type == 'option':
            return abs(quantity) * self.commission_per_contract
        else:  # underlying
            return abs(quantity) * self.commission_per_share

    def market_impact_cost(
        self,
        quantity: int,
        daily_vol: float,  # shares
        sigma: float,      # annualised vol
        spot: float,
        multiplier: int = 100
    ) -> float:
        if not self.enable_impact or daily_vol < 1:
            return 0.0
        Q = abs(quantity) * multiplier
        eta = self.impact_coefficient
        # Almgren-Chriss square-root model
        impact_per_share = (
            eta * sigma / np.sqrt(252)
            * np.sqrt(Q / daily_vol) * spot
        )
        return Q * impact_per_share

    def total_cost(
        self,
        quantity: int,
        mid_price: float,
        bid_price: Optional[float] = None,
        ask_price: Optional[float] = None,
        daily_vol: float = 0,
        sigma: float = 0.2,
        spot: float = 100.0,
        multiplier: int = 100,
        asset_type: str = 'option'
    ) -> dict:
        """Compute all cost components and total."""
        spread_c = self.spread_cost(
            mid_price, bid_price, ask_price,
            quantity, multiplier
        )
        comm_c = self.commission_cost(quantity, asset_type)
        impact_c = self.market_impact_cost(
            quantity, daily_vol, sigma, spot, multiplier
        )
        total = spread_c + comm_c + impact_c
        return {
            'spread_cost': spread_c,
            'commission': comm_c,
            'market_impact': impact_c,
            'total_tc': total,
            'tc_per_contract': (
                total / abs(quantity) if quantity != 0 else 0.0
            )
        }


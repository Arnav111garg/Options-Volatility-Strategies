from enum import Enum, auto

class ExitReason(Enum):
    PROFIT_TARGET = auto()
    STOP_LOSS = auto()
    DTE_THRESHOLD = auto()
    EXPIRY = auto()
    DELTA_BREACH = auto()
    GAMMA_BREACH = auto()
    VEGA_BREACH = auto()
    MANUAL = auto()
    ROLL = auto()

@dataclass
class PositionManagementRules:
    """ Complete rule set governing position lifecycle ."""
    # Entry filters
    min_ivr: float = 30.0 # minimum IV rank to enter
    max_ivr: float = 100.0 # maximum (avoid extreme events)

    # Exit rules
    profit_target_pct: float = 0.50 # close at 50% of max profit
    stop_loss_pct: float = 2.00 # close at 2x premium received
    min_dte: int = 7 # close if DTE < this
    max_delta: float = 0.30 # close / adjust if delta > this
    max_dollar_gamma: float = 10000.0 # dollar gamma limit
    max_vega: float = 5000.0 # vega limit

    # Rolling rules
    roll_dte_trigger: int = 21 # roll when DTE < this
    roll_to_dte: int = 45 # roll to this DTE
    max_roll_attempts: int = 3 # give up after this many rolls

    # Position sizing
    max_contracts: int = 10 # per trade
    max_portfolio_delta: float = 50.0 # net portfolio delta limit
    max_concurrent: int = 5 # max simultaneous positions


class PositionManager:
    """
    Manages the full lifecycle of all options positions in the portfolio.
    Integrates with the event-driven engine to monitor and act on positions.
    """

    def __init__(
        self,
        portfolio: 'OptionsPortfolio',
        rules: PositionManagementRules,
        tc_model: 'TransactionCostModel',
        spread_model: 'BidAskSpreadModel',
        slippage_eng: 'OptionsSlippageEngine'
    ):
        self.portfolio = portfolio
        self.rules = rules
        self.tc_model = tc_model
        self.spread_model = spread_model
        self.slippage_eng = slippage_eng

        self._closed_positions: List[dict] = []
        self._roll_log: List[dict] = []
        self._trade_log: List[dict] = []

    def check_exits(self, spot: float, date: object, sigma_surface: dict) -> List[dict]:
        """
        Check all open positions for exit conditions.
        Returns list of (pid, reason) tuples for positions to close.
        """
        exits = []
        for pid, pos in list(self.portfolio.positions.items()):
            if pos.greeks is None:
                continue

            # Compute position P&L
            curr_val = pos.greeks.price * pos.multiplier * pos.quantity
            entry_val = pos.entry_price * pos.multiplier * pos.quantity
            pnl = curr_val - entry_val

            # Compute DTE
            key = (pos.contract.strike, pos.contract.expiry_date, pos.contract.right)
            import datetime
            dte = (pos.contract.expiry_date - date).days

            # --- Check profit target ---
            if pos.quantity < 0: # short position
                max_profit = abs(entry_val)
                if max_profit > 0 and pnl >= (self.rules.profit_target_pct * max_profit):
                    exits.append((pid, ExitReason.PROFIT_TARGET))
                    continue

            # --- Check stop loss ---
            premium_received = abs(entry_val) if pos.quantity < 0 else 0
            if (premium_received > 0 and pnl <= -self.rules.stop_loss_pct * premium_received):
                exits.append((pid, ExitReason.STOP_LOSS))
                continue

            # --- Check DTE ---
            if dte <= self.rules.min_dte:
                exits.append((pid, ExitReason.DTE_THRESHOLD))
                continue

            # --- Check delta breach ---
            if abs(pos.net_delta) >= (self.rules.max_delta * pos.multiplier * abs(pos.quantity)):
                exits.append((pid, ExitReason.DELTA_BREACH))
                continue

        return exits

    def close_position(
        self,
        pid: str,
        reason: ExitReason,
        spot: float,
        date: object,
        sigma_surface: dict
    ) -> Optional[dict]:
        """ Close a position and record the trade ."""
        pos = self.portfolio.positions.get(pid)
        if pos is None:
            return None

        # Get fill price for closing trade
        key = (pos.contract.strike, pos.contract.expiry_date, pos.contract.right)
        iv = sigma_surface.get(key, 0.20)

        import datetime
        dte = max((pos.contract.expiry_date - date).days, 0)

        mid = pos.greeks.price if pos.greeks else pos.entry_price
        # Closing a long: sell at bid; closing a short: buy at ask
        side = 'sell' if pos.quantity > 0 else 'buy'
        half_sp = self.spread_model.half_spread(
            mid, iv, dte, pos.contract.strike, spot
        )
        fill = self.slippage_eng.simulate_fill(
            order_qty=-pos.quantity,  # opposite to open
            mid_price=mid,
            half_spread=half_sp,
            daily_volume=5000,
            side=side,
            iv=iv
        )

        # Realise P&L
        close_price = fill['fill_price']
        open_value = pos.entry_price * pos.multiplier * pos.quantity
        close_value = close_price * pos.multiplier * (-pos.quantity)
        realised_pnl = open_value + close_value - fill['half_spread_cost']

        self.portfolio.cash += close_value
        tc = self.tc_model.total_cost(
            quantity=-pos.quantity, mid_price=mid,
            daily_vol=5000, sigma=iv, spot=spot
        )
        self.portfolio.cash -= tc['total_tc']
        del self.portfolio.positions[pid]

        record = {
            'pid': pid,
            'close_date': date,
            'close_price': close_price,
            'realised_pnl': realised_pnl - tc['total_tc'],
            'exit_reason': reason.name,
            'tc': tc['total_tc'],
            'fill_details': fill,
        }
        self._closed_positions.append(record)
        self._trade_log.append(record)
        return record


import heapq
import numpy as np
from dataclasses import dataclass, field
from typing import Any, Optional, List, Dict, Callable
from enum import Enum, auto
from datetime import datetime

class EventType(Enum):
    MARKET_DATA = auto()
    SIGNAL = auto()
    ORDER = auto()
    FILL = auto()
    EXPIRY = auto()
    DIVIDEND = auto()
    HEDGE = auto()
    MARGIN_CALL = auto()
    ROLL = auto()
    EOD = auto()

@dataclass(order=True)
class Event:
    """
    Priority-queue event. Lower timestamp => higher priority.
    Tie-break on sequence_id to preserve insertion order.
    """
    timestamp: datetime
    seq_id: int = field(compare=True)
    event_type: EventType = field(compare=False)
    data: Any = field(default=None, compare=False)

class EventQueue:
    """Min-heap priority queue keyed on (timestamp, seq_id)."""
    def __init__(self):
        self._heap: List = []
        self._seq: int = 0

    def push(self, timestamp: datetime, etype: EventType, data: Any = None) -> None:
        e = Event(
            timestamp=timestamp,
            seq_id=self._seq,
            event_type=etype,
            data=data
        )
        heapq.heappush(self._heap, e)
        self._seq += 1

    def pop(self) -> Optional[Event]:
        return heapq.heappop(self._heap) if self._heap else None

    def peek(self) -> Optional[Event]:
        return self._heap[0] if self._heap else None

    def is_empty(self) -> bool:
        return len(self._heap) == 0

    def __len__(self) -> int:
        return len(self._heap)


class BacktestEngine:
    """
    Master event-driven backtesting engine.
    Handlers register themselves for specific event types.
    """
    def __init__(self):
        self.queue = EventQueue()
        self.handlers: Dict[EventType, List[Callable]] = {
            et: [] for et in EventType
        }
        self.current_time: Optional[datetime] = None
        self._running: bool = False
        self._event_log: List[Event] = []

    def register_handler(self, etype: EventType, handler: Callable) -> None:
        """Register a handler function for a given event type."""
        self.handlers[etype].append(handler)

    def emit(self, timestamp: datetime, etype: EventType, data: Any = None) -> None:
        """
        Emit a new event into the queue.
        'timestamp' must be >= self.current_time (no time travel).
        """
        if (self.current_time is not None and timestamp < self.current_time):
            raise ValueError(
                f"Attempted to emit event at {timestamp} "
                f"before current time {self.current_time}"
            )
        self.queue.push(timestamp, etype, data)

    def run(self) -> None:
        """
        Main loop: drain the event queue, dispatching each event
        to all registered handlers in order.
        """
        self._running = True
        while not self.queue.is_empty() and self._running:
            event = self.queue.pop()
            self.current_time = event.timestamp
            self._event_log.append(event)

            # Dispatch to all registered handlers
            for handler in self.handlers[event.event_type]:
                try:
                    handler(event)
                except Exception as exc:
                    self._handle_error(event, exc)

        self._running = False

    def _handle_error(self, event: Event, exc: Exception) -> None:
        """Override for custom error handling."""
        print(f"[ERROR] at {event.timestamp} event={event.event_type}: {exc}")
        raise exc

    def stop(self) -> None:
        self._running = False


# ---- Usage pattern -----------------------------------------------
def demo_setup():
    engine = BacktestEngine()
    return engine


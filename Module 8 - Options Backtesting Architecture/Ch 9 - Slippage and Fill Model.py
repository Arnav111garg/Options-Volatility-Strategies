import numpy as np
from scipy.stats import norm
from enum import Enum

class SlippageModel(Enum):
    FIXED = "fixed"
    PERCENTAGE = "percentage"
    SQRT_IMPACT = "sqrt_impact"
    PROB_FILL = "probabilistic"

class OptionsSlippageEngine:
    """
    Models slippage and fill probability for options orders.
    Integrates with the execution engine to simulate realistic fills.
    """

    def __init__(
        self,
        model: SlippageModel = SlippageModel.SQRT_IMPACT,
        fixed_slippage: float = 0.02,
        pct_slippage: float = 0.005,  # 0.5%
        impact_coeff: float = 0.10,
        vol_intraday: float = 0.005,
        partial_fill_prob: float = 0.0
    ):
        self.model = model
        self.fixed_slippage = fixed_slippage
        self.pct_slippage = pct_slippage
        self.impact_coeff = impact_coeff
        self.vol_intraday = vol_intraday
        self.partial_fill_prob = partial_fill_prob
        self._rng = np.random.default_rng(42)

    def slippage(
        self,
        mid_price: float,
        order_qty: int,
        daily_volume: float = 5000,
        iv: float = 0.20
    ) -> float:
        """
        Compute additional slippage beyond half-spread.
        Returns positive value (always costs money).
        """
        if self.model == SlippageModel.FIXED:
            return self.fixed_slippage

        elif self.model == SlippageModel.PERCENTAGE:
            return self.pct_slippage * mid_price

        elif self.model == SlippageModel.SQRT_IMPACT:
            if daily_volume < 1:
                return self.fixed_slippage
            n_shares = abs(order_qty) * 100
            rel_size = n_shares / max(daily_volume, 1.0)
            return (
                self.impact_coeff
                * mid_price
                * iv / np.sqrt(252.0)
                * np.sqrt(rel_size)
            )

        elif self.model == SlippageModel.PROB_FILL:
            # No additional slippage; handled by fill probability
            return 0.0

        return 0.0

    def fill_probability(
        self,
        limit_price: float,
        mid_price: float,
        side: str
    ) -> float:
        """
        Probability of getting a limit order filled at limit_price.
        side: 'buy' => limit_price <= ask; 'sell' => limit_price >= bid
        """
        if side == 'buy':
            # Better chance if limit is above mid (more aggressive)
            z = (limit_price - mid_price) / (self.vol_intraday * mid_price)
        else:
            z = (mid_price - limit_price) / (self.vol_intraday * mid_price)
        return norm.cdf(z)

    def simulate_fill(
        self,
        order_qty: int,
        mid_price: float,
        half_spread: float,
        daily_volume: float,
        side: str,
        iv: float = 0.20,
        order_type: str = 'market'
    ) -> dict:
        """
        Simulate a full order fill with slippage and transaction costs.
        Returns fill details dict.
        """
        slip = self.slippage(mid_price, order_qty, daily_volume, iv)
        if side == 'buy':
            base_fill = mid_price + half_spread
            fill_price = base_fill + slip
        else:
            base_fill = mid_price - half_spread
            fill_price = base_fill - slip

        # Partial fill simulation
        if (
            self.partial_fill_prob > 0
            and self._rng.random() < self.partial_fill_prob
        ):
            fill_qty = int(order_qty * self._rng.uniform(0.3, 0.9))
        else:
            fill_qty = order_qty

        # Market impact: price moves against us after large fill
        residual_slippage = 0.0
        if abs(fill_qty) * 100 > daily_volume * 0.05:
            residual_slippage = (0.002 * mid_price * fill_qty * 100 / daily_volume)

        total_fill_cost = (
            fill_price
            + (residual_slippage if side == 'buy' else -residual_slippage)
        )
        return {
            'fill_price': total_fill_cost,
            'fill_qty': fill_qty,
            'slippage': slip,
            'residual_slippage': residual_slippage,
            'half_spread_cost': half_spread * fill_qty * 100,
            'unfilled_qty': order_qty - fill_qty,
            'execution_quality': (
                (fill_price - mid_price) / mid_price
                if side == 'buy' else
                (mid_price - fill_price) / mid_price
            )
        }


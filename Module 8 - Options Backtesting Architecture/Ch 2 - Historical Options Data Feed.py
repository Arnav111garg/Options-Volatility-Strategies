import pandas as pd
from typing import Iterator, Tuple

class OptionsDataFeed:
    """
    Replays a historical options dataset chronologically,
    emitting MARKET_DATA events into the engine.

    Data format expected (DataFrame):
    date, underlying, spot, strike, expiry,
    right (C/P), bid, ask, iv, volume, open_interest
    """

    def __init__(
        self,
        engine: "BacktestEngine",
        df_spot: pd.DataFrame,
        df_opts: pd.DataFrame
    ):
        """
        df_spot : columns = [date, spot]
        df_opts : columns = [date, strike, expiry, right,
                             bid, ask, iv, volume, oi]
        """
        self.engine = engine
        self.df_spot = df_spot.sort_values('date')
        self.df_opts = df_opts.sort_values('date')
        self._dates = sorted(set(df_spot['date']) | set(df_opts['date']))

    def load(self) -> None:
        """Push all events into the engine queue."""
        opts_by_date = {d: g for d, g in self.df_opts.groupby('date')}
        spot_by_date = dict(zip(self.df_spot['date'], self.df_spot['spot']))

        for date in self._dates:
            spot = spot_by_date.get(date, None)
            chain = opts_by_date.get(date, pd.DataFrame())

            # Check for expiries on this date
            if not chain.empty:
                expiring = chain[chain['expiry'] == date]
                for _, row in expiring.iterrows():
                    self.engine.emit(
                        timestamp=date,
                        etype=EventType.EXPIRY,
                        data={'contract': row.to_dict(), 'spot': spot}
                    )

            # Emit main market data event
            self.engine.emit(
                timestamp=date,
                etype=EventType.MARKET_DATA,
                data={'spot': spot, 'chain': chain, 'date': date}
            )

    @staticmethod
    def from_csv(
        engine: "BacktestEngine",
        spot_path: str,
        opts_path: str
    ) -> 'OptionsDataFeed':
        df_spot = pd.read_csv(spot_path, parse_dates=['date'])
        df_opts = pd.read_csv(opts_path, parse_dates=['date', 'expiry'])
        return OptionsDataFeed(engine, df_spot, df_opts)


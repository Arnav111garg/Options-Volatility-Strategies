import numpy as np
import pandas as pd
from dataclasses import dataclass
from typing import Dict, List, Optional, Tuple
from enum import Enum, auto

class RiskAction(Enum):
    NONE = auto()
    DELTA_HEDGE = auto()
    REDUCE_GAMMA = auto()
    REDUCE_VEGA = auto()
    CLOSE_ALL = auto()
    HALT_NEW_TRADES = auto()
    MARGIN_CALL = auto()

@dataclass
class RiskLimits:
    """ Hard and soft limits for the portfolio ."""
    # Greek limits ( absolute net )
    max_delta: float = 50.0
    max_dollar_gamma: float = 15000.0
    max_vega: float = 8000.0
    max_theta_daily_loss: float = 1000.0  # max daily theta bleed

    # P&L limits
    max_daily_loss: float = 10000.0  # stop trading today
    max_drawdown: float = 50000.0  # halt strategy
    max_var_99: float = 25000.0  # 99% 1 -day VaR limit
    # Margin limits
    min_margin_buffer: float = 0.20  # 20% buffer above requirement
    max_leverage: float = 5.0  # notional / NAV

    # Concentration limits
    max_single_expiry_vega: float = 4000.0  # vega per expiry bucket
    max_single_name_delta: float = 30.0  # delta per underlying

    # Halt conditions
    halt_on_var_breach: bool = True
    halt_on_drawdown_breach: bool = True


class RiskControlEngine:
    """
    Real-time risk monitoring and control for options portfolio.
    Integrates with the event-driven engine via registered handlers.
    """

    def __init__(
        self,
        portfolio: 'OptionsPortfolio',
        limits: RiskLimits,
        engine: 'BacktestEngine',
        delta_hedger: 'DeltaHedgingEngine',
        gamma_hedger: 'GammaHedgingEngine'
    ):
        self.portfolio = portfolio
        self.limits = limits
        self.engine = engine
        self.delta_hedger = delta_hedger
        self.gamma_hedger = gamma_hedger

        self._trading_halted: bool = False
        self._breach_log: List = []
        self._daily_pnl: float = 0.0
        self._inception_nav: float = 0.0
        self._peak_nav: float = 0.0
        self._current_drawdown: float = 0.0

    def check_all_limits(self, spot: float, date: object, nav: float) -> List[Tuple[str, RiskAction]]:
        """
        Run all risk checks. Returns list of (limit_name, action) pairs.
        """
        breaches = []

        # --- Greek checks ---
        port_delta = self.portfolio.portfolio_delta
        dollar_gamma = 0.5 * self.portfolio.portfolio_gamma * (spot ** 2)
        port_vega = self.portfolio.portfolio_vega

        if abs(port_delta) > self.limits.max_delta:
            breaches.append(('delta_limit', RiskAction.DELTA_HEDGE))

        if abs(dollar_gamma) > self.limits.max_dollar_gamma:
            breaches.append(('gamma_limit', RiskAction.REDUCE_GAMMA))

        if abs(port_vega) > self.limits.max_vega:
            breaches.append(('vega_limit', RiskAction.REDUCE_VEGA))

        # --- P&L checks ---
        if self._daily_pnl < -self.limits.max_daily_loss:
            breaches.append(('daily_loss', RiskAction.HALT_NEW_TRADES))

        # --- Drawdown check ---
        if nav > self._peak_nav:
            self._peak_nav = nav
        drawdown = (self._peak_nav - nav) / max(self._peak_nav, 1.0)
        self._current_drawdown = drawdown

        if (self._peak_nav - nav) > self.limits.max_drawdown:
            breaches.append(('drawdown', RiskAction.HALT_NEW_TRADES))
            if self.limits.halt_on_drawdown_breach:
                self._trading_halted = True

        # --- VaR check (delta-gamma approximation) ---
        var_99 = self._compute_var_delta_gamma(spot)
        if var_99 > self.limits.max_var_99:
            breaches.append(('var_breach', RiskAction.REDUCE_GAMMA))
            if self.limits.halt_on_var_breach:
                self._trading_halted = True

        # Log breaches
        for breach, action in breaches:
            self._breach_log.append({
                'date': date,
                'breach': breach,
                'action': action.name,
                'delta': port_delta,
                'dollar_gamma': dollar_gamma,
                'vega': port_vega,
                'drawdown': drawdown,
                'var_99': var_99,
            })

        return breaches

    def _compute_var_delta_gamma(
        self,
        spot: float,
        sigma: float = 0.20,
        horizon: float = 1/252
    ) -> float:
        """
        Delta-Gamma approximation of 99% 1-day VaR.
        Uses Cornish-Fisher expansion for skewness correction.
        """
        Delta = self.portfolio.portfolio_delta
        Gamma = self.portfolio.portfolio_gamma
        Vega = self.portfolio.portfolio_vega

        # Daily vol
        sigma_daily = sigma * np.sqrt(horizon)
        # Mean and variance of P&L
        mu_pnl = 0.5 * Gamma * (spot ** 2) * (sigma_daily ** 2)
        var_pnl = ((Delta * spot * sigma_daily) ** 2) + 0.5 * ((Gamma * (spot ** 2) * (sigma_daily ** 2)) ** 2)
        std_pnl = np.sqrt(max(var_pnl, 1e-10))

        # Skewness of portfolio P&L (from gamma term)
        skew_pnl = (Gamma * (spot ** 2) * (sigma_daily ** 2) * Delta * spot * sigma_daily) / (std_pnl ** 3 + 1e-10)

        # Cornish-Fisher z* at 1% (left tail)
        z_99 = -2.326
        z_cf = (z_99
                + (skew_pnl / 6.0) * (z_99 ** 2 - 1.0)
                - ((skew_pnl ** 2) / 36.0) * (2.0 * (z_99 ** 3) - 5.0 * z_99))

        var_99 = -(mu_pnl + std_pnl * z_cf)
        return max(var_99, 0.0)

    def execute_risk_actions(
        self,
        breaches: List[Tuple],
        spot: float,
        date: object,
        chain: pd.DataFrame
    ) -> None:
        """
        Execute the required actions for each risk breach.
        Priority: close_all > halt > delta_hedge > reduce_gamma > reduce_vega
        """
        actions = {action for _, action in breaches}

        if RiskAction.CLOSE_ALL in actions:
            # Emergency close all positions
            for pid in list(self.portfolio.positions.keys()):
                pos = self.portfolio.positions[pid]
                # Emergency market order : pay full ask
                if pos.greeks:
                    self.portfolio.cash += (
                        -pos.quantity * pos.multiplier * pos.greeks.price
                    )
            self.portfolio.positions.clear()
            self.portfolio.hedge_qty = 0.0
            return

        if RiskAction.HALT_NEW_TRADES in actions:
            self._trading_halted = True

        if RiskAction.DELTA_HEDGE in actions:
            self.delta_hedger.execute_hedge(spot, date, is_eod=False)

        if RiskAction.REDUCE_GAMMA in actions:
            self.gamma_hedger.execute_gamma_hedge(spot, date, chain)

    def reset_daily_pnl(self) -> None:
        self._daily_pnl = 0.0

    def update_daily_pnl(self, pnl_delta: float) -> None:
        self._daily_pnl += pnl_delta

    @property
    def is_trading_halted(self) -> bool:
        return self._trading_halted

    def risk_report(self, spot: float) -> dict:
        """ Generate a point-in-time risk report ."""
        return {
            'portfolio_delta': self.portfolio.portfolio_delta,
            'dollar_gamma': 0.5 * self.portfolio.portfolio_gamma * (spot ** 2),
            'portfolio_vega': self.portfolio.portfolio_vega,
            'portfolio_theta': self.portfolio.portfolio_theta,
            'var_99_1day': self._compute_var_delta_gamma(spot),
            'current_drawdown': self._current_drawdown,
            'trading_halted': self._trading_halted,
            'num_breaches': len(self._breach_log),
            'open_positions': len(self.portfolio.positions),
        }


import numpy as np
import pandas as pd
from dataclasses import dataclass
from typing import Optional

@dataclass
class GammaHedgeOrder:
    """ Represents an order to adjust gamma exposure ."""
    contract: 'OptionContract'
    quantity: int # signed
    reason: str # "gamma_hedge"
    target_gamma: float
    current_gamma: float
    gamma_change: float # expected gamma change

class GammaHedgingEngine:
    """
    Gamma hedging: neutralises second-order exposure
    using options as hedging instruments.
    """

    def __init__(
        self,
        portfolio: 'OptionsPortfolio',
        gamma_threshold: float = 500.0, # $ threshold
        hedge_instrument: str = 'atm_option',
        tc_per_contract: float = 1.50
    ):
        self.portfolio = portfolio
        self.gamma_threshold = gamma_threshold
        self.hedge_instrument = hedge_instrument
        self.tc_per_contract = tc_per_contract
        self._hedge_count: int = 0
        self._total_gamma_tc: float = 0.0

    def net_dollar_gamma(self, spot: float) -> float:
        """ Portfolio dollar gamma including hedge positions ."""
        raw_gamma = self.portfolio.portfolio_gamma
        return 0.5 * raw_gamma * spot ** 2

    def should_gamma_hedge(self, spot: float) -> bool:
        """ Trigger gamma hedge if dollar gamma exceeds threshold ."""
        return abs(self.net_dollar_gamma(spot)) > self.gamma_threshold

    def _find_gamma_hedge_instrument(
        self,
        spot: float,
        date: object,
        chain: pd.DataFrame,
        target_dg: float # desired dollar gamma change
    ) -> Optional[GammaHedgeOrder]:
        """
        Find the best option on the chain to hedge gamma.
        Prefer ATM options (highest gamma per premium).
        """
        if chain is None or chain.empty:
            return None

        # Filter to nearest expiry with enough liquidity
        chain = chain[chain['volume'] > 50].copy()
        if chain.empty:
            return None

        # Compute gamma for each option
        chain['gamma_per_contract'] = chain.apply(
            lambda r: BlackScholesPricer.price_and_greeks(
                S=spot, K=r['strike'],
                T=max((r['expiry'] - date).days / 365, 1/365),
                r=0.05, q=0.0,
                sigma=r['iv'],
                right=r['right']
            ).gamma if r['iv'] > 0 else 0.0,
            axis=1
        )
        chain['dollar_gamma_per'] = (
            0.5 * chain['gamma_per_contract']
            * spot ** 2 * 100 # multiplier
        )

        # Pick ATM option with highest dollar gamma
        chain['moneyness'] = abs(chain['strike'] - spot)
        best = chain.loc[chain['moneyness'].idxmin()]

        # Compute quantity needed
        dg_per_contract = best['dollar_gamma_per']
        if abs(dg_per_contract) < 1e-6:
            return None

        qty_needed = int(-target_dg / dg_per_contract)
        if abs(qty_needed) < 1:
            return None

        contract = OptionContract(
            right=best['right'],
            strike=best['strike'],
            expiry_date=best['expiry'],
        )
        return GammaHedgeOrder(
            contract=contract,
            quantity=qty_needed,
            reason='gamma_hedge',
            target_gamma=0.0,
            current_gamma=self.net_dollar_gamma(spot),
            gamma_change=qty_needed * dg_per_contract
        )

    def execute_gamma_hedge(
        self,
        spot: float,
        date: object,
        chain: pd.DataFrame
    ) -> Optional[GammaHedgeOrder]:
        """ Execute a gamma hedge if threshold breached ."""
        if not self.should_gamma_hedge(spot):
            return None

        current_dg = self.net_dollar_gamma(spot)
        order = self._find_gamma_hedge_instrument(
            spot, date, chain, -current_dg
        )
        if order is None:
            return None

        # Get fill price (use mid of bid-ask)
        tc = abs(order.quantity) * self.tc_per_contract
        self._total_gamma_tc += tc
        self._hedge_count += 1

        return order

    @property
    def total_gamma_hedge_cost(self) -> float:
        return self._total_gamma_tc


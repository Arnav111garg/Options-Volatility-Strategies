import numpy as np
from scipy.stats import norm
from scipy.optimize import brentq
from dataclasses import dataclass, field
from typing import Literal, Dict

@dataclass
class OptionContract:
    right: Literal['C', 'P'] # Call or Put
    strike: float
    expiry_date: object # datetime.date
    underlying: str = 'SPX'

@dataclass
class OptionGreeks:
    price: float
    delta: float
    gamma: float
    vega: float # per 1 vol point
    theta: float # per calendar day
    rho: float
    vanna: float
    volga: float # aka vomma
    charm: float # d(delta)/d(time)

class BlackScholesPricer:
    """
    Full Black-Scholes pricer with all first and second-order
    Greeks. All inputs must be per-contract consistent:
    S = spot price
    K = strike
    T = time to expiry in years
    r = continuously-compounded risk-free rate
    q = continuous dividend yield
    sigma = implied volatility (decimal)
    """

    @staticmethod
    def _d1_d2(S: float, K: float, T: float, r: float, q: float, sigma: float) -> tuple:
        if T <= 0 or sigma <= 0:
            return None, None
        sqrtT = np.sqrt(T)
        d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * T) / (sigma * sqrtT)
        d2 = d1 - sigma * sqrtT
        return d1, d2

    @classmethod
    def price_and_greeks(
        cls, S: float, K: float, T: float, r: float, q: float, sigma: float, right: Literal['C', 'P']
    ) -> OptionGreeks:
        """Compute price + full Greek set."""
        if T <= 1e-10:
            # At expiry: intrinsic value
            intr = max(S - K, 0.0) if right == 'C' else max(K - S, 0.0)
            return OptionGreeks(
                price=intr, delta=0.0, gamma=0.0, vega=0.0, theta=0.0,
                rho=0.0, vanna=0.0, volga=0.0, charm=0.0
            )

        d1, d2 = cls._d1_d2(S, K, T, r, q, sigma)
        sqrtT = np.sqrt(T)
        Nd1 = norm.cdf(d1)
        Nd2 = norm.cdf(d2)
        nd1 = norm.pdf(d1)

        # ---- Price ----
        disc = np.exp(-r * T)
        divd = np.exp(-q * T)
        if right == 'C':
            price = S * divd * Nd1 - K * disc * Nd2
            delta = divd * Nd1
            rho = K * T * disc * Nd2 / 100.0 # per 1bp
        else:
            price = K * disc * (1.0 - Nd2) - S * divd * (1.0 - Nd1)
            delta = divd * (Nd1 - 1.0)
            rho = -K * T * disc * (1.0 - Nd2) / 100.0

        # ---- Gamma (same for C and P) ----
        gamma = divd * nd1 / (S * sigma * sqrtT)

        # ---- Vega (same, per 1 decimal point = 0.01) ----
        vega = S * divd * nd1 * sqrtT * 0.01

        # ---- Theta (per calendar day) ----
        if right == 'C':
            theta = (
                -S * divd * nd1 * sigma / (2.0 * sqrtT)
                - r * K * disc * Nd2
                + q * S * divd * Nd1
            ) / 365.0
        else:
            theta = (
                -S * divd * nd1 * sigma / (2.0 * sqrtT)
                + r * K * disc * (1.0 - Nd2)
                - q * S * divd * (1.0 - Nd1)
            ) / 365.0

        # ---- Vanna = d(delta)/d(sigma) = -nd1 * d2 / sigma ----
        vanna = -divd * nd1 * d2 / sigma

        # ---- Volga (Vomma) = d(vega)/d(sigma) ----
        volga = vega * d1 * d2 / sigma

        # ---- Charm = d(delta)/d(t) ----
        if right == 'C':
            charm = (divd * (nd1 * ((r - q) / (sigma * sqrtT) - d2 / (2.0 * T)) - q * Nd1)) / 365.0
        else:
            charm = (divd * (nd1 * ((r - q) / (sigma * sqrtT) - d2 / (2.0 * T)) + q * (1.0 - Nd1))) / 365.0

        return OptionGreeks(
            price=price, delta=delta, gamma=gamma, vega=vega,
            theta=theta, rho=rho, vanna=vanna, volga=volga, charm=charm
        )

    @staticmethod
    def implied_vol(
        market_price: float, S: float, K: float, T: float, r: float, q: float,
        right: Literal['C', 'P'], tol: float = 1e-8
    ) -> float:
        """Brent's method IV solver with bracketing."""
        if T <= 0:
            return np.nan
        bs = BlackScholesPricer.price_and_greeks

        def objective(sigma):
            return bs(S, K, T, r, q, sigma, right).price - market_price

        # Check for arbitrage bounds
        intrinsic = max(S * np.exp(-q * T) - K * np.exp(-r * T), 0.0) \
            if right == 'C' \
            else max(K * np.exp(-r * T) - S * np.exp(-q * T), 0.0)
        if market_price < intrinsic - 1e-6:
            return np.nan # below intrinsic: arbitrage

        try:
            iv = brentq(objective, 1e-6, 10.0, xtol=tol)
            return iv
        except ValueError:
            return np.nan # no root found

@dataclass
class Position:
    """Full state of a single options position."""
    pos_id: str
    contract: OptionContract
    quantity: int # signed (+= long, -= short)
    entry_price: float # option premium per share
    entry_date: object # datetime
    multiplier: int = 100 # US standard: 100 shares / contract
    greeks: OptionGreeks = None

    @property
    def notional(self) -> float:
        return abs(self.quantity) * self.multiplier * self.entry_price

    @property
    def net_delta(self) -> float:
        """Dollar delta of position."""
        if self.greeks is None:
            return 0.0
        return self.quantity * self.multiplier * self.greeks.delta

    @property
    def net_gamma(self) -> float:
        if self.greeks is None:
            return 0.0
        return self.quantity * self.multiplier * self.greeks.gamma

    @property
    def net_vega(self) -> float:
        if self.greeks is None:
            return 0.0
        return self.quantity * self.multiplier * self.greeks.vega

    @property
    def net_theta(self) -> float:
        if self.greeks is None:
            return 0.0
        return self.quantity * self.multiplier * self.greeks.theta

class OptionsPortfolio:
    """
    Options portfolio: maintains positions, computes aggregate
    Greeks, handles expirations, tracks cash and margin.
    """
    def __init__(
        self,
        pricer: BlackScholesPricer,
        r: float = 0.05,
        q: float = 0.0,
        multiplier: int = 100
    ):
        self.pricer = pricer
        self.r = r
        self.q = q
        self.multiplier = multiplier
        self.positions: Dict[str, Position] = {}
        self.cash: float = 0.0 # includes premium received
        self.hedge_qty: float = 0.0 # shares held for delta hedge
        self._pos_ctr: int = 0

    def add_position(self, contract: OptionContract, quantity: int, fill_price: float, date: object) -> str:
        """Add a new option position; debit / credit cash."""
        pid = f"P{self._pos_ctr:05d}"
        self._pos_ctr += 1
        pos = Position(
            pos_id=pid,
            contract=contract,
            quantity=quantity,
            entry_price=fill_price,
            entry_date=date,
            multiplier=self.multiplier
        )
        self.positions[pid] = pos
        # Premium: paying for long, receiving for short
        self.cash -= quantity * self.multiplier * fill_price
        return pid

    def mark_to_market(self, spot: float, date: object, sigma_surface: dict) -> None:
        """
        Re-price all positions, update Greeks.
        sigma_surface: dict {(strike, expiry, right): iv}
        """
        for pos in self.positions.values():
            key = (pos.contract.strike, pos.contract.expiry_date, pos.contract.right)
            iv = sigma_surface.get(key, None)
            if iv is None or np.isnan(iv):
                continue
            T = max((pos.contract.expiry_date - date).days / 365.0, 0.0)
            pos.greeks = self.pricer.price_and_greeks(
                S=spot,
                K=pos.contract.strike,
                T=T,
                r=self.r,
                q=self.q,
                sigma=iv,
                right=pos.contract.right
            )

    def expire_position(self, pid: str, spot: float) -> float:
        """Settle and remove an expiring position. Returns P&L."""
        pos = self.positions.pop(pid)
        K = pos.contract.strike
        if pos.contract.right == 'C':
            payoff = max(spot - K, 0.0)
        else:
            payoff = max(K - spot, 0.0)
        # Net settlement vs entry cost (already in cash)
        settlement = pos.quantity * self.multiplier * payoff
        self.cash += settlement
        return settlement

    @property
    def portfolio_delta(self) -> float:
        return sum(p.net_delta for p in self.positions.values())

    @property
    def portfolio_gamma(self) -> float:
        return sum(p.net_gamma for p in self.positions.values())

    @property
    def portfolio_vega(self) -> float:
        return sum(p.net_vega for p in self.positions.values())

    @property
    def portfolio_theta(self) -> float:
        return sum(p.net_theta for p in self.positions.values())

    @property
    def portfolio_pnl(self) -> float:
        """Unrealised + realised P&L = MTM of options + hedge + cash."""
        opts_mtm = sum(
            p.quantity * p.multiplier * p.greeks.price
            for p in self.positions.values()
            if p.greeks is not None
        )
        return opts_mtm + self.hedge_qty * 0.0 + self.cash
        # Note: hedge_qty * current_spot needs to be added by caller


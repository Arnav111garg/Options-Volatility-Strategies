import numpy as np
import pandas as pd
from scipy.stats import norm

def compute_fair_variance_strike(
    strikes: np.ndarray,
    mid_prices: np.ndarray,
    option_types: list,  # 'C' or 'P'
    forward: float,
    T: float,            # maturity in years
    r: float = 0.0       # risk-free rate
) -> float:
    """
    Compute fair variance strike using VIX/Carr-Madan methodology.

    Parameters
    ----------
    strikes : array of strike prices (OTM options only)
    mid_prices : array of option mid prices
    option_types : list of 'C' (call) or 'P' (put) for each option
    forward : current forward price
    T : time to maturity in years
    r : continuously compounded risk-free rate

    Returns
    -------
    K_var : annualised fair variance strike (NOT volatility)
    """
    # Step 1: Sort by strike ascending
    idx = np.argsort(strikes)
    K = strikes[idx]
    Q = mid_prices[idx]
    types = [option_types[i] for i in idx]

    # Step 2: Find K0 = first strike at or below forward
    below_fwd = K[K <= forward]
    K0 = below_fwd[-1] if len(below_fwd) > 0 else K[0]

    # Step 3: Compute Delta_K_i for each strike
    # For endpoints : Delta K = distance to adjacent strike
    # For interior : Delta K = (K_{i+1} - K_{i-1}) / 2
    n = len(K)
    delta_K = np.zeros(n)
    delta_K[0] = K[1] - K[0]
    delta_K[-1] = K[-1] - K[-2]
    for i in range(1, n - 1):
        delta_K[i] = (K[i + 1] - K[i - 1]) / 2.0

    # Step 4: Compute sum of delta_K / K^2 * Q
    discount = np.exp(r * T)
    sum_term = np.sum(delta_K / K**2 * discount * Q)

    # Step 5: Correction term for F != K0
    correction = (forward / K0 - 1)**2

    # Step 6: Fair variance
    K_var = (2 / T) * sum_term - (1 / T) * correction

    return K_var

# --------------------------------------------------------
# Demonstration with synthetic option surface
# --------------------------------------------------------
S0 = 5000.0  # SPX level
r = 0.053    # 5.3% risk-free rate
T = 30 / 365 # 30-day variance swap

# Synthetic strike grid (OTM puts below F, OTM calls above F)
forward = S0 * np.exp(r * T)

# Build a simple skewed vol surface
atm_vol = 0.18
skew = -0.002  # vol increases per 1pt decrease in strike

def bs_price(S, K, T, r, sigma, flag):
    """Black-Scholes option price"""
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    if flag == 'C':
        return S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
    else:
        return K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)

# Generate strike grid
put_strikes = np.arange(4000, forward, 50)
call_strikes = np.arange(np.ceil(forward / 50) * 50, 6000, 50)

strikes_list, prices_list, types_list = [], [], []

for K in put_strikes:
    moneyness = (K - forward) / forward  # negative for OTM puts
    vol = atm_vol + skew * moneyness * 100  # simple linear skew
    vol = max(vol, 0.05)
    p = bs_price(S0, K, T, r, vol, 'P')
    if p > 0.01:  # filter trivially small prices
        strikes_list.append(K)
        prices_list.append(p)
        types_list.append('P')

for K in call_strikes:
    moneyness = (K - forward) / forward  # positive for OTM calls
    vol = atm_vol + skew * moneyness * 100
    vol = max(vol, 0.05)
    c = bs_price(S0, K, T, r, vol, 'C')
    if c > 0.01:
        strikes_list.append(K)
        prices_list.append(c)
        types_list.append('C')

K_var = compute_fair_variance_strike(
    np.array(strikes_list),
    np.array(prices_list),
    types_list,
    forward, T, r
)

implied_vol_equiv = np.sqrt(K_var) * 100
print(f"Forward price: {forward:.2f}")
print(f"Fair var strike: {K_var:.6f}")
print(f"Implied vol equiv: {implied_vol_equiv:.2f}%")
print(f"ATM vol input: {atm_vol * 100:.2f}%")
print(f"Skew effect: +{(implied_vol_equiv - atm_vol * 100):.2f}% vs ATM")


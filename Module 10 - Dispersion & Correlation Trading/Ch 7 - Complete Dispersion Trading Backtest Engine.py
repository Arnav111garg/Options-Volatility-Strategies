# Walk-forward cross-validation for dispersion strategies
import numpy as np
import pandas as pd
from sklearn.model_selection import TimeSeriesSplit

def walk_forward_dispersion_cv(
    full_results: pd.DataFrame,
    n_splits: int = 5,
    min_train_quarters: int = 8
) -> pd.DataFrame:
    """
    Walk-forward cross-validation for dispersion strategy.

    Tests: Is the correlation premium persistent out-of-sample?
    """
    tscv = TimeSeriesSplit(n_splits=n_splits)
    oos_results = []

    for fold, (train_idx, test_idx) in enumerate(tscv.split(full_results)):
        train = full_results.iloc[train_idx]
        test = full_results.iloc[test_idx]

        if len(train) < min_train_quarters:
            continue

        # In-sample: estimate mean correlation premium and signal threshold
        avg_premium_is = (train['rho_impl'] - train['rho_real']).mean()
        vol_premium_is = (train['rho_impl'] - train['rho_real']).astype(float).std()

        # Out-of-sample: use IS threshold to decide when to trade
        # Only trade when implied correlation is above 25th percentile (IS)
        rho_threshold = train['rho_impl'].quantile(0.25)

        oos_pnl = []
        for _, row in test.iterrows():
            if row['rho_impl'] > rho_threshold:
                oos_pnl.append(row['net_pnl'])
            else:
                oos_pnl.append(0.0)  # no trade

        oos_pnl = pd.Series(oos_pnl)
        oos_results.append({
            'fold': fold,
            'n_train': len(train),
            'n_test': len(test),
            'IS_avg_premium': avg_premium_is,
            'OOS_avg_pnl': oos_pnl.mean(),
            'OOS_sharpe': (oos_pnl.mean() / oos_pnl.std() * np.sqrt(4) if oos_pnl.std() > 0 else 0),
            'OOS_hit_rate': (oos_pnl > 0).mean(),
            'IS_hit_rate': (train['net_pnl'] > 0).mean(),
        })

    return pd.DataFrame(oos_results)


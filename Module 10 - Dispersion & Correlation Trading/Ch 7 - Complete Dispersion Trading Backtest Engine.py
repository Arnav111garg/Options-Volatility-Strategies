import numpy as np
import pandas as pd
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple
import warnings
warnings.filterwarnings('ignore')

@dataclass
class DispersionConfig:
    """Configuration for dispersion backtest."""
    tenor_months: int = 3  # Variance swap tenor
    roll_day_before_expiry: int = 5  # Roll N days before expiry
    index_var_notional: float = 1_000_000  # $1M vega notional
    weighting_scheme: str = 'variance_neutral'  # or 'vega_neutral'
    use_transaction_costs: bool = True
    index_va_bid_ask_vol: float = 0.005  # 0.5 vol pt bid-ask
    stock_va_bid_ask_vol: float = 0.015  # 1.5 vol pt bid-ask
    correlation_filter: float = 0.0  # Only trade when rho_impl > threshold
    max_position_per_stock: float = 0.20  # Max weight in one stock
    min_stocks: int = 20  # Minimum number of stocks in basket


@dataclass
class VarianceSwapPosition:
    """Represents a single variance swap position."""
    ticker: str
    is_index: bool
    start_date: pd.Timestamp
    expiry_date: pd.Timestamp
    strike_var: float  # Variance strike (e.g., 0.04 = 20% vol squared)
    notional_var: float  # Dollar notional in variance terms
    weight: float  # Index weight (for stocks)
    realised_var: float = 0.0
    n_days_accrued: int = 0
    is_active: bool = True
    entry_cost: float = 0.0


class DispersionBacktester:
    """
    Full-featured dispersion trading backtest engine.

    Models:
    - Variance swap-based dispersion (short index, long stocks)
    - Variance-neutral weighting
    - Transaction costs on entry / exit
    - Monthly rolls
    - P&L decomposition
    """

    def __init__(self, config: DispersionConfig = None):
        self.config = config or DispersionConfig()
        self.positions: List[VarianceSwapPosition] = []
        self.pnl_history: List[dict] = []
        self.trade_log: List[dict] = []

    # --------------------------------------------------------------------------
    # POSITION SIZING
    # --------------------------------------------------------------------------
    def compute_notionals(
        self,
        weights: np.ndarray,
        comp_vols: np.ndarray,
        index_vol: float,
        idx_notional: float
    ) -> np.ndarray:
        """
        Compute variance-neutral notional for each stock.
        Variance-neutral: N_i = w_i^2 * N_idx
        """
        if self.config.weighting_scheme == 'variance_neutral':
            return weights ** 2 * idx_notional

        elif self.config.weighting_scheme == 'vega_neutral':
            # Match vega: N_i * sigma_i = w_i * N_idx * sigma_idx
            # => N_i = w_i * (sigma_idx / sigma_i) * N_idx
            return weights * (index_vol / comp_vols) * idx_notional

        elif self.config.weighting_scheme == 'mcap_vega':
            # Match dollar vega: N_i * 2 * K_i = w_i * N_idx * 2 * K_idx
            return weights * (index_vol ** 2 / comp_vols ** 2) * idx_notional

        else:
            raise ValueError(f"Unknown weighting scheme: {self.config.weighting_scheme}")

    # --------------------------------------------------------------------------
    # ENTRY LOGIC
    # --------------------------------------------------------------------------
    def enter_trade(
        self,
        date: pd.Timestamp,
        expiry: pd.Timestamp,
        index_iv: float,
        comp_ivs: Dict[str, float],
        weights: Dict[str, float],
        index_ticker: str = 'SPX'
    ) -> dict:
        """
        Enter a new dispersion position.
        Returns trade entry stats.
        """
        w_arr = np.array(list(weights.values()))
        iv_arr = np.array([comp_ivs[t] for t in weights.keys()])
        tickers = list(weights.keys())

        # Compute implied correlation
        rho_impl = self._compute_implied_corr(index_iv, iv_arr, w_arr)

        # Filter: only enter if implied correlation is above threshold
        if rho_impl < self.config.correlation_filter:
            return {'entered': False, 'reason': 'rho below threshold', 'rho_impl': rho_impl}

        # Compute notionals
        notionals = self.compute_notionals(
            w_arr, iv_arr, index_iv, self.config.index_var_notional
        )

        # Transaction costs (proportional to bid-ask spread)
        idx_cost = (self.config.index_va_bid_ask_vol ** 2 * self.config.index_var_notional)
        stock_cost = sum(self.config.stock_va_bid_ask_vol ** 2 * N for N in notionals)
        total_cost = idx_cost + stock_cost

        # --- Short index variance swap ---
        self.positions.append(VarianceSwapPosition(
            ticker=index_ticker, is_index=True,
            start_date=date, expiry_date=expiry,
            strike_var=index_iv ** 2,
            notional_var=self.config.index_var_notional,
            weight=1.0,
            entry_cost=idx_cost
        ))

        # --- Long single-stock variance swaps ---
        for i, (ticker, weight) in enumerate(weights.items()):
            self.positions.append(VarianceSwapPosition(
                ticker=ticker, is_index=False,
                start_date=date, expiry_date=expiry,
                strike_var=comp_ivs[ticker]**2,
                notional_var=notionals[i],
                weight=weight,
                entry_cost=self.config.stock_va_bid_ask_vol ** 2 * notionals[i]
            ))

        self.trade_log.append({
            'date': date, 'action': 'ENTER',
            'n_stocks': len(weights),
            'rho_implied': rho_impl,
            'index_iv': index_iv,
            'avg_comp_iv': iv_arr.mean(),
            'total_cost': total_cost
        })

        return {
            'entered': True,
            'rho_implied': rho_impl,
            'total_cost': total_cost,
            'n_positions': len(self.positions)
        }

    # --------------------------------------------------------------------------
    # DAILY MARK-TO-MARKET
    # --------------------------------------------------------------------------
    def mark_to_market(
        self,
        date: pd.Timestamp,
        index_return: float,
        comp_returns: Dict[str, float],
        days_remaining: int
    ) -> dict:
        """
        Update realised variance accrual and compute daily P&L.
        """
        daily_pnl = 0.0
        annualiser = 252.0

        for pos in self.positions:
            if not pos.is_active:
                continue
            if date > pos.expiry_date:
                continue

            # Get return for this position
            if pos.is_index:
                r = index_return
            else:
                r = comp_returns.get(pos.ticker, 0.0)

            # Accrue realised variance (annualised)
            daily_rv_contrib = annualiser * r ** 2
            pos.realised_var = (
                (pos.realised_var * pos.n_days_accrued + daily_rv_contrib)
                / (pos.n_days_accrued + 1)
            )
            pos.n_days_accrued += 1

            # Daily P&L = N_var * d(RV)/dt * sign
            # Short index: pays RV, receives strike
            # Long stocks: pays strike, receives RV
            sign = -1 if pos.is_index else +1
            incremental_pnl = sign * pos.notional_var * daily_rv_contrib / annualiser
            daily_pnl += incremental_pnl

        return {'date': date, 'daily_pnl': daily_pnl}

    # --------------------------------------------------------------------------
    # EXPIRY SETTLEMENT
    # --------------------------------------------------------------------------
    def settle_expiring(self, date: pd.Timestamp) -> dict:
        """
        Settle all positions expiring on this date.
        """
        total_settlement = 0.0
        settled_positions = []

        for pos in self.positions:
            if pos.is_active and pos.expiry_date <= date:
                # Final settlement
                sign = -1 if pos.is_index else +1
                pnl = sign * pos.notional_var * (pos.realised_var - pos.strike_var)
                total_settlement += pnl

                settled_positions.append({
                    'ticker': pos.ticker,
                    'is_index': pos.is_index,
                    'realised_var': pos.realised_var,
                    'strike_var': pos.strike_var,
                    'realised_vol': np.sqrt(pos.realised_var) * 100,
                    'strike_vol': np.sqrt(pos.strike_var) * 100,
                    'vol_pnl': np.sqrt(pos.realised_var) * 100 - np.sqrt(pos.strike_var) * 100,
                    'pnl': pnl,
                    'n_days': pos.n_days_accrued,
                    'notional': pos.notional_var
                })

                pos.is_active = False

        # Clear settled positions
        self.positions = [p for p in self.positions if p.is_active]

        return {
            'settlement_pnl': total_settlement,
            'n_settled': len(settled_positions),
            'detail': settled_positions
        }

    def _compute_implied_corr(
        self,
        idx_iv: float,
        comp_ivs: np.ndarray,
        weights: np.ndarray
    ) -> float:
        """Helper: compute implied correlation."""
        var_idx = idx_iv ** 2
        wtd_vol_sum = (weights * comp_ivs).sum()
        idio_var = (weights ** 2 * comp_ivs ** 2).sum()
        denom = wtd_vol_sum ** 2 - idio_var
        if abs(denom) < 1e-12:
            return 0.0
        return (var_idx - idio_var) / denom

    # --------------------------------------------------------------------------
    # ANALYTICS
    # --------------------------------------------------------------------------
    def compute_strategy_stats(
        self,
        pnl_series: pd.Series
    ) -> dict:
        """Compute full strategy statistics from P&L series."""
        returns = pnl_series / pnl_series.abs().mean()  # normalise
        cum_pnl = pnl_series.cumsum()

        # Drawdown
        roll_max = cum_pnl.cummax()
        drawdown = cum_pnl - roll_max
        max_drawdown = drawdown.min()

        # Sharpe (annualised, daily P&L)
        daily_mean = pnl_series.mean()
        daily_std = pnl_series.std()
        sharpe = (daily_mean / daily_std) * np.sqrt(252) if daily_std > 0 else 0

        # Sortino
        downside = pnl_series[pnl_series < 0].std()
        sortino = (daily_mean / downside) * np.sqrt(252) if downside > 0 else 0

        # Calmar
        ann_pnl = daily_mean * 252
        calmar = -ann_pnl / max_drawdown if max_drawdown < 0 else 0

        # Win rate
        win_rate = (pnl_series > 0).mean()
        avg_win = pnl_series[pnl_series > 0].mean() if (pnl_series > 0).any() else 0
        avg_loss = pnl_series[pnl_series < 0].mean() if (pnl_series < 0).any() else 0
        profit_factor = abs(avg_win / avg_loss) if avg_loss != 0 else np.inf

        return {
            'Total P&L': cum_pnl.iloc[-1],
            'Ann. P&L (Daily)': ann_pnl,
            'Ann. Vol': daily_std * np.sqrt(252),
            'Sharpe Ratio': sharpe,
            'Sortino Ratio': sortino,
            'Calmar Ratio': calmar,
            'Max Drawdown': max_drawdown,
            'Win Rate': win_rate,
            'Avg Win / Avg Loss': profit_factor,
            'Skewness': pnl_series.skew(),
            'Kurtosis': pnl_series.kurt(),
        }


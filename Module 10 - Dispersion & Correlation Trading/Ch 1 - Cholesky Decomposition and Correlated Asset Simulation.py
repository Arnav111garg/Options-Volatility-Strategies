import numpy as np
import pandas as pd
from scipy.linalg import cholesky

def simulate_correlated_assets(
    n_assets: int,
    n_paths: int,
    n_steps: int,
    vols: np.ndarray,
    corr_matrix: np.ndarray,
    dt: float = 1/252,
    S0: np.ndarray = None
) -> np.ndarray:
    """
    Simulate N correlated GBM asset paths using Cholesky decomposition.
    Returns: shape (n_paths, n_steps + 1, n_assets) array of price paths
    """
    if S0 is None:
        S0 = np.ones(n_assets) * 100.0

    # Validate correlation matrix
    eigenvals = np.linalg.eigvalsh(corr_matrix)
    if np.any(eigenvals < -1e-8):
        raise ValueError(f"Correlation matrix not PSD. Min eigenvalue : {eigenvals.min():.6f}")

    # Cholesky decomposition
    L = cholesky(corr_matrix, lower=True)

    # drift = -0.5 * sigma^2 * dt
    drift = -0.5 * vols**2 * dt

    # Initialise paths array
    paths = np.zeros((n_paths, n_steps + 1, n_assets))
    paths[:, 0, :] = S0

    for t in range(n_steps):
        # Draw independent normals
        Z = np.random.standard_normal((n_paths, n_assets))
        # Introduce correlation
        X = Z @ L.T
        # Log-normal step
        log_returns = drift + vols * np.sqrt(dt) * X
        paths[:, t + 1, :] = paths[:, t, :] * np.exp(log_returns)

    return paths

# --------------------------------------------------------
# Example : 5-stock dispersion simulation
# --------------------------------------------------------
np.random.seed(42)

n_stocks = 5
vols = np.array([0.25, 0.30, 0.22, 0.28, 0.26])
weights = np.array([0.30, 0.25, 0.20, 0.15, 0.10])

# Build equicorrelation matrix with rho_bar = 0.40
rho_bar = 0.40
corr = np.full((n_stocks, n_stocks), rho_bar)
np.fill_diagonal(corr, 1.0)

# Simulated index vol from equicorrelation formula
sigma_idx_model = np.sqrt(
    rho_bar * (weights @ vols)**2 + (1 - rho_bar) * np.sum(weights**2 * vols**2)
)
print(f"Model index vol (equicorr): {sigma_idx_model:.4f}")

# Simulate paths
paths = simulate_correlated_assets(
    n_assets=n_stocks,
    n_paths=10000,
    n_steps=252,
    vols=vols,
    corr_matrix=corr,
    dt=1/252
)

# Compute realised index returns
index_paths = paths @ weights
index_log_rets = np.diff(np.log(index_paths), axis=1)
realised_index_vol = np.std(index_log_rets, axis=1) * np.sqrt(252)

print(f"Simulated realised index vol (mean): {realised_index_vol.mean():.4f}")
print(f"Simulated realised index vol (std): {realised_index_vol.std():.4f}")


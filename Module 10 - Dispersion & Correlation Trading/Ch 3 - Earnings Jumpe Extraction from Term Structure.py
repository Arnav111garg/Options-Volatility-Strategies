import numpy as np

def extract_earnings_jump(
    vol_pre_earn: float,    # IV for tenor ending before earnings
    vol_post_earn: float,   # IV for tenor ending after earnings
    T_pre: float,           # tenor (years) for pre-earnings
    T_post: float,          # tenor (years) for post-earnings
    annualise: bool = True
) -> dict:
    """
    Extract the implied earnings event variance from two variance swap tenors.

    The idea: T_post includes the earnings event; T_pre does not.
    Var(T_post) * T_post = Var(T_pre) * T_pre + Var(event)
    """
    var_pre = vol_pre_earn**2 * T_pre
    var_post = vol_post_earn**2 * T_post

    # Event variance (in calendar time)
    event_var = var_post - var_pre

    if event_var < 0:
        raise ValueError(
            f"Post-earnings var ({var_post:.4f}) < pre-earnings var ({var_pre:.4f}). "
            "Check input vols or tenors."
        )

    # Event vol = sqrt(event variance)
    # Note: we express this as 'on the day' vol (not annualised)
    event_vol_daily = np.sqrt(event_var)

    # As a percentage move: this is roughly +/- the event vol
    expected_move_pct = event_vol_daily * 100

    # Annualised contribution
    if annualise:
        # 4 events per year
        annualised_contribution = np.sqrt(4 * event_var)
    else:
        annualised_contribution = event_vol_daily

    return {
        'event_variance': event_var,
        'event_vol_daily': event_vol_daily,
        'expected_move_pct': expected_move_pct,
        'annualised_contribution': annualised_contribution,
        'diffusive_vol_implied': np.sqrt(var_pre / T_pre),
    }

# Example: Apple options around earnings
# 1-week IV (before earnings this week): 42%
# 5-week IV (includes the earnings): 35%
# Note: This is an illustrative example of term structure inversion.
try:
    # Typically we require post-vol * T_post > pre-vol * T_pre,
    # so let's use standard numbers where variance accumulates:
    result = extract_earnings_jump(
        vol_pre_earn=0.30,
        vol_post_earn=0.35,
        T_pre=5/252,
        T_post=25/252
    )
    print(f"Implied earnings move: {result['expected_move_pct']:.2f}%")
    print(f"Diffusive daily vol: {result['diffusive_vol_implied']*100:.2f}% ann.")
    print(f"Annualised earnings: {result['annualised_contribution']*100:.2f}%")
except ValueError as e:
    print(f"Error: {e}")


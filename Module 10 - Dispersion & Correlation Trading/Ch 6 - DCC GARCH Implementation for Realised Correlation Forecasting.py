import numpy as np
import pandas as pd
from scipy.optimize import minimize
from scipy.stats import norm

class GARCH11:
    """Univariate GARCH (1,1) for standardised residuals."""

    def __init__(self):
        self.omega = None
        self.alpha = None
        self.beta = None
        self.sigma2 = None

    def fit(self, returns: np.ndarray) -> dict:
        """Fit GARCH (1,1) via MLE."""
        T = len(returns)

        def neg_log_lik(params):
            omega, alpha, beta = params
            if omega <= 0 or alpha < 0 or beta < 0 or alpha + beta >= 1:
                return 1e10
            sigma2 = np.zeros(T)
            sigma2[0] = np.var(returns)
            for t in range(1, T):
                sigma2[t] = omega + alpha * returns[t-1]**2 + beta * sigma2[t-1]
            if np.any(sigma2 <= 0):
                return 1e10
            ll = -0.5 * (np.log(2 * np.pi) + np.log(sigma2) + returns**2 / sigma2)
            return -ll.sum()

        x0 = [1e-5, 0.08, 0.90]
        bounds = [(1e-8, 0.1), (0.001, 0.3), (0.5, 0.999)]
        res = minimize(neg_log_lik, x0, method='L-BFGS-B', bounds=bounds)

        self.omega, self.alpha, self.beta = res.x
        # Compute filtered variance
        self.sigma2 = np.zeros(T)
        self.sigma2[0] = np.var(returns)
        for t in range(1, T):
            self.sigma2[t] = (self.omega
                              + self.alpha * returns[t-1]**2
                              + self.beta * self.sigma2[t-1])
        return {
            'omega': self.omega,
            'alpha': self.alpha,
            'beta': self.beta,
            'persistence': self.alpha + self.beta,
            'unconditional_var': self.omega / (1 - self.alpha - self.beta)
        }

    def forecast(self, h: int = 1) -> np.ndarray:
        """h-step ahead variance forecasts (simple recursion)."""
        forecasts = np.zeros(h)
        last_sig2 = self.sigma2[-1]
        uncond_var = self.omega / (1 - self.alpha - self.beta)
        persist = self.alpha + self.beta
        for i in range(h):
            forecasts[i] = uncond_var + persist**(i+1) * (last_sig2 - uncond_var)
        return forecasts


class DCC_GARCH:
    """
    Dynamic Conditional Correlation (DCC) GARCH model.
    Reference: Engle (2002) 'Dynamic Conditional Correlation'.
    """

    def __init__(self, n_assets: int):
        self.n_assets = n_assets
        self.garch_models = [GARCH11() for _ in range(n_assets)]
        self.a = None
        self.b = None
        self.Q_bar = None
        self.R_t = None

    def fit(self, returns: np.ndarray) -> dict:
        """
        Fit DCC-GARCH model.
        Parameters: returns shape (T, N)
        """
        T, N = returns.shape
        assert N == self.n_assets

        # Step 1: Fit univariate GARCH to each series
        std_resids = np.zeros((T, N))
        sigma2_all = np.zeros((T, N))

        for i in range(N):
            params = self.garch_models[i].fit(returns[:, i])
            sigma2_all[:, i] = self.garch_models[i].sigma2
            std_resids[:, i] = returns[:, i] / np.sqrt(sigma2_all[:, i])

        # Step 2: Estimate Q_bar = unconditional corr of standardised residuals
        self.Q_bar = np.corrcoef(std_resids.T)

        # Step 3: Fit DCC parameters (a, b) via maximising DCC log-likelihood
        def dcc_neg_loglik(params):
            a, b = params
            if a <= 0 or b <= 0 or a + b >= 1:
                return 1e10
            Q_t = self.Q_bar.copy()
            ll = 0.0
            for t in range(1, T):
                eta = std_resids[t-1]
                Q_t = (1 - a - b) * self.Q_bar + a * np.outer(eta, eta) + b * Q_t
                # Ensure PSD
                q_diag = np.sqrt(np.diag(Q_t))
                R_t = Q_t / np.outer(q_diag, q_diag)
                # Log-likelihood contribution
                sign, logdet = np.linalg.slogdet(R_t)
                if sign <= 0:
                    return 1e10
                z = std_resids[t]
                R_inv = np.linalg.inv(R_t)
                ll += logdet + z @ R_inv @ z - z @ z
            return 0.5 * ll

        res = minimize(dcc_neg_loglik, [0.04, 0.94],
                       method='L-BFGS-B',
                       bounds=[(0.001, 0.2), (0.5, 0.998)])
        self.a, self.b = res.x

        # Step 4: Filter correlations
        self.R_t = np.zeros((T, N, N))
        Q_t = self.Q_bar.copy()
        for t in range(T):
            if t > 0:
                eta = std_resids[t-1]
                Q_t = ((1 - self.a - self.b) * self.Q_bar
                       + self.a * np.outer(eta, eta)
                       + self.b * Q_t)
            q_diag = np.sqrt(np.diag(Q_t))
            self.R_t[t] = Q_t / np.outer(q_diag, q_diag)

        return {
            'a': self.a,
            'b': self.b,
            'persistence': self.a + self.b,
            'R_final': self.R_t[-1]
        }

    def forecast_correlation(self, h: int = 1) -> np.ndarray:
        """
        h-step ahead correlation forecast.
        Mean-reverts to Q_bar.
        """
        persist = self.a + self.b
        R_last = self.R_t[-1]
        forecasts = np.zeros((h, self.n_assets, self.n_assets))
        for i in range(h):
            forecasts[i] = (self.Q_bar
                            + persist**(i+1) * (R_last - self.Q_bar))
            # Ensure diagonal is 1
            np.fill_diagonal(forecasts[i], 1.0)
        return forecasts



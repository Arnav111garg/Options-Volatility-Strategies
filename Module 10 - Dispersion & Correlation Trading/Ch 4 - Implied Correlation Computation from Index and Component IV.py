import numpy as np
import pandas as pd

class ImpliedCorrelationCalculator:
    """
    Computes implied correlation for an equity index from:
    - Index implied vol (e.g. VIX for SPX)
    - Individual component implied vols
    - Index weights
    """

    def __init__(self,
                 index_impl_vol: float,
                 component_vols: np.ndarray,
                 weights: np.ndarray):
        """
        Parameters
        ----------
        index_impl_vol : index implied vol (annualised, decimal)
        component_vols : array of single-stock implied vols
        weights : index weight vector, must sum to 1
        """
        assert np.isclose(weights.sum(), 1.0, atol=1e-4), \
            f"Weights must sum to 1, got {weights.sum():.4f}"
        assert len(component_vols) == len(weights), \
            "component_vols and weights must have same length"

        self.sigma_idx = index_impl_vol
        self.sigma_comp = component_vols
        self.w = weights

    def compute(self) -> dict:
        """
        Returns implied correlation and diagnostic stats.
        """
        sig_i = self.sigma_comp
        w_i = self.w
        sig_I = self.sigma_idx

        # Variance quantities
        var_idx = sig_I ** 2
        weighted_vol_sum = (w_i * sig_i).sum()         # sum_i (w_i * sigma_i)
        sq_wtd_vol_sum = weighted_vol_sum ** 2         # (sum_i w_i * sigma_i)^2
        wtd_idio_var = (w_i ** 2 * sig_i ** 2).sum()   # sum_i (w_i^2 * sigma_i^2)

        # Denominator
        denom = sq_wtd_vol_sum - wtd_idio_var

        if denom <= 0:
            raise ValueError(
                "Denominator <= 0. Check weights and vols for consistency."
            )

        # Implied correlation
        rho_impl = (var_idx - wtd_idio_var) / denom

        # Bounds check
        rho_clipped = np.clip(rho_impl, -1.0, 1.0)

        # Dispersion P&L check: how large is the correlation premium?
        # Using realised correlation = 0 as lower bound
        rho_realised_estimate = rho_impl * 0.70

        return {
            'rho_implied': rho_impl,
            'rho_implied_clipped': rho_clipped,
            'sigma_index_impl': sig_I * 100,
            'weighted_component_vol': weighted_vol_sum * 100,
            'vol_differential': (weighted_vol_sum - sig_I) * 100,
            'idio_var': wtd_idio_var,
            'sq_wtd_vol_sum': sq_wtd_vol_sum,
            'corr_premium_estimate': (rho_impl - rho_realised_estimate) * 100,
        }

    def sensitivity_to_component_vols(self, delta_vol: float = 0.01) -> np.ndarray:
        """
        Compute d(rho_impl) / d(sigma_i) for each component numerically.
        Useful for understanding which stocks drive implied correlation most.
        """
        sensitivities = np.zeros(len(self.sigma_comp))
        base = self.compute()['rho_implied']
        for i in range(len(self.sigma_comp)):
            vols_up = self.sigma_comp.copy()
            vols_up[i] += delta_vol
            calc_up = ImpliedCorrelationCalculator(
                self.sigma_idx, vols_up, self.w
            )
            rho_up = calc_up.compute()['rho_implied']
            sensitivities[i] = (rho_up - base) / delta_vol

        return sensitivities


weights = np.array([0.30, 0.25, 0.20, 0.15, 0.10])
comp_vols = np.array([0.22, 0.28, 0.35, 0.26, 0.30])
idx_vol = 0.18

calc = ImpliedCorrelationCalculator(idx_vol, comp_vols, weights)
result = calc.compute()


import numpy as np
from typing import List, Tuple

class DispersionGreeks:
    """
    Compute correlation Greeks for a dispersion position.
    Supports both variance-swap and straddle-based implementations.
    """

    def __init__(self,
                 weights: np.ndarray,
                 comp_vols: np.ndarray,
                 index_vol: float,
                 avg_corr: float,
                 n_var_index: float = 1.0,
                 n_var_stocks: np.ndarray = None):
        self.w = weights
        self.sigma = comp_vols
        self.sigma_I = index_vol
        self.rho = avg_corr
        self.N_I = n_var_index
        self.N_S = n_var_stocks if n_var_stocks is not None \
            else weights ** 2 * n_var_index

    def pairwise_corr_delta(self, i: int, j: int) -> float:
        """
        d(sigma_I^2) / d(rho_ij)
        = 2 * w_i * w_j * sigma_i * sigma_j
        """
        return 2 * self.w[i] * self.w[j] * self.sigma[i] * self.sigma[j]

    def avg_corr_delta(self) -> float:
        """
        d(sigma_I^2) / d(rho_bar)
        = (sum_i w_i sigma_i)^2 - sum_i w_i^2 sigma_i^2
        """
        wtd_vol_sum = (self.w * self.sigma).sum()
        idio = (self.w ** 2 * self.sigma ** 2).sum()
        return wtd_vol_sum ** 2 - idio

    def correlation_dv01(self, notional_var: float = None) -> float:
        """
        Dollar P&L per 1 correlation point change (1 pp = 0.01)
        = N_var * d(sigma_I^2)/d(rho_bar) * 0.01
        """
        N = notional_var if notional_var else self.N_I
        return N * self.avg_corr_delta() * 0.01

    def vega_of_index_var_swap(self) -> float:
        """
        Vega of index var swap: d(value)/d(sigma_I)
        = N_var * 2 * sigma_I (in variance units)
        """
        return self.N_I * 2 * self.sigma_I

    def vega_of_stock_var_swaps(self) -> np.ndarray:
        """
        Vega of each single-stock var swap leg.
        """
        return self.N_S * 2 * self.sigma

    def net_vega(self) -> float:
        """
        Net vega of entire dispersion trade.
        Short index + long stocks.
        """
        vega_short_idx = -self.vega_of_index_var_swap()
        vega_long_stocks = self.vega_of_stock_var_swaps().sum()
        return vega_short_idx + vega_long_stocks

    def corr_delta_matrix(self) -> np.ndarray:
        """
        Full pairwise correlation delta matrix.
        Shape: (N, N) with entry (i,j) = d(sigma_I^2)/d(rho_ij)
        """
        N = len(self.w)
        delta_mat = np.zeros((N, N))
        for i in range(N):
            for j in range(N):
                if i != j:
                    delta_mat[i, j] = self.pairwise_corr_delta(i, j)
        return delta_mat

    def print_summary(self):
        print("=" * 55)
        print(" Dispersion Greeks Summary ")
        print("=" * 55)
        print(f" Avg. Correlation Delta     : {self.avg_corr_delta():.6f}")
        print(f" Correlation DV01           : {self.correlation_dv01():.4f}")
        print(f" Index Var Swap Vega        : {self.vega_of_index_var_swap():.4f}")
        print(f" Stock Var Swaps Vega       : {self.vega_of_stock_var_swaps().sum():.4f}")
        print(f" Net Vega                   : {self.net_vega():.4f}")
        print(f" Correlation to breakeven   : {self.rho:.4f} (implied)")
        print("=" * 55)


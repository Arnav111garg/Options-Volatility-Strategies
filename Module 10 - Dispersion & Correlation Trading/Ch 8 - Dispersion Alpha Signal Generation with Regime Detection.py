import numpy as np
import pandas as pd
from scipy.stats import percentileofscore

class DispersionAlphaSignal:
    """
    Generates dispersion entry / exit signals based on:
    1. Implied vs realised correlation spread
    2. Implied correlation momentum
    3. Regime detection (low / high vol regime)
    """

    def __init__(
        self,
        lookback_rv_days: int = 60,
        ewma_decay: float = 0.94,
        momentum_window: int = 10,
        momentum_lambda: float = 0.3
    ):
        self.lb_rv = lookback_rv_days
        self.ewma_lam = ewma_decay
        self.mom_win = momentum_window
        self.mom_lam = momentum_lambda

    def compute_realised_correlation(
        self,
        returns: pd.DataFrame,  # (T x N) stock returns
        weights: np.ndarray
    ) -> pd.Series:
        """
        Rolling realised correlation using EWMA covariance.
        """
        T, N = returns.shape
        realised_corr = np.zeros(T)

        for t in range(1, T):
            # EWMA variance for each stock
            start = max(0, t - self.lb_rv)
            window = returns.iloc[start:t]
            if len(window) < 10:
                continue

            # Compute correlation matrix for this window
            cov_matrix = window.ewm(alpha=1 - self.ewma_lam).cov().iloc[-N:]

            if cov_matrix.shape == (N, N):
                vols = np.sqrt(np.diag(cov_matrix.values))
                if np.any(vols == 0):
                    continue
                outer_vols = np.outer(vols, vols)
                corr_matrix = cov_matrix.values / outer_vols

                # Average pairwise correlation (off-diagonal)
                mask = ~np.eye(N, dtype=bool)
                realised_corr[t] = corr_matrix[mask].mean()

        return pd.Series(realised_corr, index=returns.index)

    def compute_signal(
        self,
        implied_corr: pd.Series,
        realised_corr: pd.Series,
        vix: pd.Series
    ) -> pd.DataFrame:
        """
        Compute the composite dispersion alpha signal.

        Returns DataFrame with signal components.
        """
        # Component 1: Correlation premium (implied - realised)
        corr_premium = implied_corr - realised_corr

        # Component 2: Momentum (avoid entering when corr is rising)
        impl_corr_mom = implied_corr.diff(self.mom_win)

        # Component 3: Regime (percentile of VIX)
        vix_pctile = vix.rolling(252).apply(
            lambda x: percentileofscore(x, x.iloc[-1]) / 100
        )

        # Composite signal
        # Positive = enter dispersion, Negative = stay flat
        signal_raw = corr_premium - self.mom_lam * impl_corr_mom

        # Scale by VIX regime: reduce position size in high VIX environments
        # (correlation crisis risk is higher)
        vol_scalar = 1 - 0.5 * vix_pctile.fillna(0.5)

        signal_scaled = signal_raw * vol_scalar

        # Normalise signal to [-1, 1] using rolling z-score
        signal_norm = (
            (signal_scaled - signal_scaled.rolling(252).mean()) /
            (signal_scaled.rolling(252).std() + 1e-8)
        ).clip(-2, 2) / 2

        return pd.DataFrame({
            'implied_corr': implied_corr,
            'realised_corr': realised_corr,
            'corr_premium': corr_premium,
            'impl_corr_mom': impl_corr_mom,
            'vix_pctile': vix_pctile,
            'signal_raw': signal_raw,
            'vol_scalar': vol_scalar,
            'signal_norm': signal_norm,
        })



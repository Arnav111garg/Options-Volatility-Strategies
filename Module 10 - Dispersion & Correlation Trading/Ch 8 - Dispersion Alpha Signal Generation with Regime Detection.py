# Synthetic signal generation demo
# --------------------------------------------------------------------------
np.random.seed(42)
T = 1260  # 5 years of daily data
dates = pd.date_range('2019-01-01', periods=T, freq='B')

# Simulate implied and realised correlation series
rho_impl = pd.Series(
    0.40 + 0.12 * np.cumsum(0.05 * np.random.randn(T)),
    index=dates
).clip(0.10, 0.85)

rho_real = rho_impl.rolling(60).mean().shift(20) * 0.72 + \
           pd.Series(0.05 * np.random.randn(T), index=dates)
rho_real = rho_real.clip(0.05, 0.80)

vix = pd.Series(
    15 + 10 * np.abs(np.cumsum(0.1 * np.random.randn(T))),
    index=dates
).clip(10, 80)

signal_gen = DispersionAlphaSignal()
signals = signal_gen.compute_signal(rho_impl, rho_real, vix)

print("Dispersion Signal Statistics:")
print(signals[['corr_premium', 'signal_raw', 'signal_norm']].describe().round(4))

# Position sizing: signal_norm in [-1, 1] scales the notional
signals['position'] = signals['signal_norm'].clip(0, 1)  # Long only dispersion
print(f"\nAvg position size: {signals['position'].mean():.3f}")
print(f"Days in position: {(signals['position'] > 0.1).sum()}")


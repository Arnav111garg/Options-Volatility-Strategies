import numpy as np
import matplotlib.pyplot as plt
from scipy.stats import norm

def bs_vanna(S, K, r, q, sigma, tau):
    """
    BS Vanna = d(Delta)/d(sigma) = d(Vega)/d(S)
    """
    tau = np.maximum(tau, 1e-8)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    d2 = d1 - sigma * np.sqrt(tau)
    return -np.exp(-q * tau) * norm.pdf(d1) * d2 / sigma

def vanna_surface_plot(S_range, K, tau_range, r, q, sigma):
    """3D vanna surface."""
    S_grid, T_grid = np.meshgrid(S_range, tau_range)
    Vanna_grid = bs_vanna(S_grid, K, r, q, sigma, T_grid)

    fig = plt.figure(figsize=(12, 7))
    ax = fig.add_subplot(111, projection='3d')
    surf = ax.plot_surface(S_grid, T_grid * 365, Vanna_grid, cmap='seismic', edgecolor='none', alpha=0.85)
    ax.set_xlabel('Spot S', fontsize=11)
    ax.set_ylabel('Days to Expiry', fontsize=11)
    ax.set_zlabel('Vanna', fontsize=11)
    ax.set_title('Vanna Surface\n(Red = Positive, Blue = Negative)', fontsize=13)
    fig.colorbar(surf, ax=ax, shrink=0.4, aspect=10)
    plt.tight_layout()
    plt.savefig('vanna_surface.png', dpi=150)
    plt.show()


# GreekSurface Implementation
# =========================================================
class GreekSurface:
    """
    Compute and visualize Greek surfaces over (strike, maturity) space.
    """
    def __init__(self, S, r, q, sigma_func=None):
        self.S = S
        self.r = r
        self.q = q
        self.sigma_func = sigma_func if sigma_func else lambda K, tau: 0.20

    def compute_surface(self, K_range, tau_range, greek='delta', option_type='call'):
        K_grid, T_grid = np.meshgrid(K_range, tau_range)
        sigma_grid = np.vectorize(self.sigma_func)(K_grid, T_grid)

        dispatch = {
            'delta': lambda S, K, r, q, sig, tau: bs_delta(S, K, r, q, sig, tau, option_type),
            'gamma': bs_gamma,
            'vega': bs_vega,
            'theta': lambda S, K, r, q, sig, tau: bs_theta(S, K, r, q, sig, tau, option_type),
            'vanna': bs_vanna,
            'charm': lambda S, K, r, q, sig, tau: bs_charm(S, K, r, q, sig, tau, option_type),
            'vomma': bs_vomma,
            'speed': bs_speed,
            'color': bs_color,
        }

        fn = dispatch[greek.lower()]
        G_grid = fn(self.S, K_grid, self.r, self.q, sigma_grid, T_grid)
        return K_grid, T_grid * 365, G_grid

    def plot_surface(self, K_range, tau_range, greek='delta', option_type='call', cmap='RdYlBu'):
        K_grid, T_grid, G_grid = self.compute_surface(K_range, tau_range, greek, option_type)
        fig = plt.figure(figsize=(11, 7))
        ax = fig.add_subplot(111, projection='3d')
        surf = ax.plot_surface(K_grid, T_grid, G_grid, cmap=cmap, edgecolor='none', alpha=0.9)
        ax.set_xlabel('Strike K', fontsize=11)
        ax.set_ylabel('Days to Expiry', fontsize=11)
        ax.set_zlabel(greek.capitalize(), fontsize=11)
        ax.set_title(f'{greek.capitalize()} Surface\nS={self.S}, r={self.r*100:.1f}%', fontsize=13)
        ax.axhline(self.S, color='red', lw=2, label=f'S={self.S}')
        fig.colorbar(surf, ax=ax, shrink=0.45, aspect=10, pad=0.1)
        plt.tight_layout()
        plt.savefig(f'{greek}_surface_3d.png', dpi=150)
        plt.show()

    def plot_all_surfaces(self, K_range, tau_range, option_type='call'):
        greeks = ['delta', 'gamma', 'vega', 'theta', 'vanna', 'charm', 'vomma', 'speed', 'color']
        cmaps = ['Blues', 'Reds', 'Greens', 'Oranges', 'seismic', 'PuOr', 'RdYlBu', 'coolwarm', 'PRGn']
        fig = plt.figure(figsize=(20, 16))
        fig.suptitle(
            f'Complete Greek Surface Analysis\n'
            f'S={self.S}, r={self.r*100:.1f}%, q={self.q*100:.1f}%', fontsize=16, fontweight='bold')

        for idx, (greek, cmap) in enumerate(zip(greeks, cmaps)):
            ax = fig.add_subplot(3, 3, idx + 1, projection='3d')
            try:
                K_grid, T_grid, G_grid = self.compute_surface(K_range, tau_range, greek, option_type)
                surf = ax.plot_surface(K_grid, T_grid, G_grid, cmap=cmap, edgecolor='none', alpha=0.85)
                ax.set_title(greek.upper(), fontsize=11, fontweight='bold')
                ax.set_xlabel('K', fontsize=8)
                ax.set_ylabel('DTE', fontsize=8)
                ax.set_zlabel(greek[:3], fontsize=8)
                ax.tick_params(labelsize=7)
                fig.colorbar(surf, ax=ax, shrink=0.5, aspect=12, pad=0.1)
            except Exception as e:
                ax.set_title(f'{greek.upper()} (error)', fontsize=11)

        plt.tight_layout(rect=[0, 0, 1, 0.95])
        plt.savefig('all_greek_surfaces.png', dpi=120, bbox_inches='tight')
        plt.show()

    def strike_profile(self, K_range, tau_fixed, greeks=None):
        if greeks is None:
            greeks = ['delta', 'gamma', 'vega', 'theta', 'vanna', 'vomma']
        fig, axes = plt.subplots(2, 3, figsize=(15, 8))
        axes = axes.flatten()
        colors = plt.cm.tab10(np.linspace(0, 1, len(greeks)))

        for ax, greek, color in zip(axes, greeks, colors):
            _, _, G_grid = self.compute_surface(K_range, [tau_fixed], greek)
            ax.plot(K_range, G_grid.flatten(), color=color, lw=2.5)
            ax.axvline(self.S, color='red', ls='--', lw=1.2, label='Spot')
            ax.set_title(f'{greek.upper()} vs. Strike', fontsize=11)
            ax.set_xlabel('Strike K', fontsize=10)
            ax.set_ylabel(greek.capitalize(), fontsize=10)
            ax.grid(alpha=0.4)
            ax.legend(fontsize=9)

        plt.suptitle(f'Greek Strike Profiles | {tau_fixed*365:.0f} DTE | S={self.S}', fontsize=14)
        plt.tight_layout()
        plt.savefig('greek_strike_profiles.png', dpi=150)
        plt.show()

    def heatmap_panel(self, K_range, tau_range, greeks=None):
        if greeks is None:
            greeks = ['delta', 'gamma', 'vega', 'theta', 'vanna', 'vomma']
        fig, axes = plt.subplots(2, 3, figsize=(18, 10))
        axes = axes.flatten()

        K_grid, T_grid, _ = self.compute_surface(K_range, tau_range, greeks[0])

        for ax, greek in zip(axes, greeks):
            _, _, G_grid = self.compute_surface(K_range, tau_range, greek)
            im = ax.contourf(K_grid, T_grid, G_grid, levels=50, cmap='RdYlBu_r')
            ax.contour(K_grid, T_grid, G_grid, levels=10, colors='black', linewidths=0.5, alpha=0.3)
            ax.axvline(self.S, color='white', ls='--', lw=2, label=f'Spot={self.S}')
            ax.set_title(f'{greek.upper()} Heatmap', fontsize=12, fontweight='bold')
            ax.set_xlabel('Strike K', fontsize=10)
            ax.set_ylabel('Days to Expiry', fontsize=10)
            plt.colorbar(im, ax=ax, shrink=0.8)
            ax.legend(fontsize=9, loc='upper right')

        plt.suptitle(f'Greek Heatmap Atlas | S={self.S}', fontsize=16, fontweight='bold')
        plt.tight_layout()
        plt.savefig('greek_heatmaps.png', dpi=120, bbox_inches='tight')
        plt.show()

def skewed_vol_surface(K, tau, S=450, atm_vol=0.20, skew=-0.5, kurt=0.3):
    """
    Simple parametric vol surface with skew and kurtosis
    """
    x = np.log(S / K) / np.sqrt(tau)
    return atm_vol + skew * x + kurt * x**2 / np.sqrt(tau)


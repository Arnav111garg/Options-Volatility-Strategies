import numpy as np
import matplotlib.pyplot as plt
from matplotlib import cm
from scipy.stats import norm
import warnings
warnings.filterwarnings('ignore')

# =========================================================
# Black-Scholes Greek Helper Functions
# =========================================================
def bs_delta(S, K, r, q, sigma, tau, option_type='call'):
    tau = np.maximum(tau, 1e-8)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    if option_type.lower() == 'call':
        return np.exp(-q * tau) * norm.cdf(d1)
    else:
        return np.exp(-q * tau) * (norm.cdf(d1) - 1.0)

def bs_gamma(S, K, r, q, sigma, tau):
    tau = np.maximum(tau, 1e-8)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    return np.exp(-q * tau) * norm.pdf(d1) / (S * sigma * np.sqrt(tau))

def bs_vega(S, K, r, q, sigma, tau):
    tau = np.maximum(tau, 1e-8)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    return S * np.exp(-q * tau) * norm.pdf(d1) * np.sqrt(tau)

def bs_theta(S, K, r, q, sigma, tau, option_type='call'):
    tau = np.maximum(tau, 1e-8)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    d2 = d1 - sigma * np.sqrt(tau)
    term1 = - (S * np.exp(-q * tau) * norm.pdf(d1) * sigma) / (2 * np.sqrt(tau))
    if option_type.lower() == 'call':
        term2 = q * S * np.exp(-q * tau) * norm.cdf(d1) - r * K * np.exp(-r * tau) * norm.cdf(d2)
    else:
        term2 = - q * S * np.exp(-q * tau) * norm.cdf(-d1) + r * K * np.exp(-r * tau) * norm.cdf(-d2)
    return term1 + term2

def bs_vanna(S, K, r, q, sigma, tau):
    tau = np.maximum(tau, 1e-8)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    d2 = d1 - sigma * np.sqrt(tau)
    return -np.exp(-q * tau) * norm.pdf(d1) * d2 / sigma

def bs_charm(S, K, r, q, sigma, tau, option_type='call'):
    tau = np.maximum(tau, 1e-8)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    d2 = d1 - sigma * np.sqrt(tau)
    term1 = q * np.exp(-q * tau) * norm.cdf(d1 if option_type.lower() == 'call' else -d1)
    term2 = np.exp(-q * tau) * norm.pdf(d1) * (2 * (r - q) * tau - d2 * sigma * np.sqrt(tau)) / (2 * tau * sigma * np.sqrt(tau))
    if option_type.lower() == 'call':
        return q * np.exp(-q * tau) * norm.cdf(d1) - term2
    else:
        return -q * np.exp(-q * tau) * norm.cdf(-d1) - term2

def bs_vomma(S, K, r, q, sigma, tau):
    tau = np.maximum(tau, 1e-8)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    d2 = d1 - sigma * np.sqrt(tau)
    vega = bs_vega(S, K, r, q, sigma, tau)
    return vega * d1 * d2 / sigma

def bs_speed(S, K, r, q, sigma, tau):
    tau = np.maximum(tau, 1e-8)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    gamma = bs_gamma(S, K, r, q, sigma, tau)
    return -gamma * (d1 / (sigma * np.sqrt(tau)) + 1.0) / S

def bs_color(S, K, r, q, sigma, tau):
    tau = np.maximum(tau, 1e-8)
    sqrt_tau = np.sqrt(tau)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * sqrt_tau)
    d2 = d1 - sigma * sqrt_tau
    gamma = np.exp(-q * tau) * norm.pdf(d1) / (S * sigma * sqrt_tau)
    bracket = 2 * q * tau + 1 + d1 * (2 * (r - q) * tau - d2 * sigma * sqrt_tau) / (sigma * sqrt_tau)
    return -gamma / (2 * tau) * bracket


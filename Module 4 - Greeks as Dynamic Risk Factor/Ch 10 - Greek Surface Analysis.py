    # Full surface panel (flat vol)
    gs_flat.plot_all_surfaces(K_range, tau_range, option_type='call')

    # Heatmap panel (skewed vol)
    gs_skew.heatmap_panel(K_range, tau_range)

    # Strike profile
    gs_flat.strike_profile(K_range, tau_fixed=30/365)


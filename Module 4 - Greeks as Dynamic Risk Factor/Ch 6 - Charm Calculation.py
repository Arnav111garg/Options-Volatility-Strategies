import numpy as np
from scipy.stats import norm
import matplotlib.pyplot as plt

def bs_charm(S, K, r, q, sigma, tau, option_type='call'):
    """
    BS Charm = d(Delta)/d(t) = -d(Delta)/d(tau)

    Returned in per-year units. Divide by 365 for per-day.
    """
    tau = np.maximum(tau, 1e-8)
    sqrt_tau = np.sqrt(tau)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma ** 2) * tau) / (sigma * sqrt_tau)
    d2 = d1 - sigma * sqrt_tau

    common = e_q = np.exp(-q * tau)
    phi_d1 = norm.pdf(d1)

    second_term = e_q * phi_d1 * (2 * (r - q) * tau - d2 * sigma * sqrt_tau) / (2 * tau * sigma * sqrt_tau)

    if option_type == 'call':
        return q * e_q * norm.cdf(d1) - second_term
    else:
        return -q * e_q * norm.cdf(-d1) - second_term

def weekend_delta_adjustment(portfolio):
    """
    Compute charm adjustment for weekend (2-day delta drift).
    """
    total_charm = 0.0
    for pos in portfolio.positions:
        c = bs_charm(portfolio.S, pos['strike'], portfolio.r, portfolio.q, pos['sigma'], pos['tau'], pos['option_type'])
        charm_contrib = pos['quantity'] * pos['multiplier'] * c / 365
        total_charm += charm_contrib

    delta_friday = portfolio.portfolio_greeks()['delta']
    delta_monday_approx = delta_friday + total_charm * 2 # 2 weekend days

    print(f"\n{'WEEKEND CHARM ADJUSTMENT':^55}")
    print('=' * 55)
    print(f"{'Friday Delta (raw)':35s}: {delta_friday:.4f}")
    print(f"{'2-Day Charm':35s}: {total_charm * 2:.4f}")
    print(f"{'Estimated Monday Delta':35s}: {delta_monday_approx:.4f}")
    print(f"{'Shares to Buy / Sell on Monday':35s}: {(delta_monday_approx - delta_friday) * 100:.0f}")
    return delta_monday_approx

def charm_profile_plot(S_range, K, tau_days, r, q, sigma):
    """Plot charm profile vs. spot for multiple maturities."""
    fig, axes = plt.subplots(1, 2, figsize=(14, 5))

    colors = plt.cm.coolwarm(np.linspace(0, 1, len(tau_days)))

    for tau_d, color in zip(tau_days, colors):
        tau = tau_d / 365
        charms_call = [bs_charm(s, K, r, q, sigma, tau, 'call') / 365 for s in S_range]
        charms_put = [bs_charm(s, K, r, q, sigma, tau, 'put') / 365 for s in S_range]
        axes[0].plot(S_range, charms_call, color=color, lw=2, label=f'{tau_d} DTE')
        axes[1].plot(S_range, charms_put, color=color, lw=2, label=f'{tau_d} DTE')

    for ax, title in zip(axes, ['Call Charm (per day)', 'Put Charm (per day)']):
        ax.axhline(0, color='black', lw=1, ls='--')
        ax.axvline(K, color='gray', lw=1, ls=':')
        ax.set_xlabel('Spot Price S', fontsize=11)
        ax.set_ylabel('Charm (delta / day)', fontsize=11)
        ax.set_title(title, fontsize=12)
        ax.legend(fontsize=9)
        ax.grid(alpha=0.4)

    plt.suptitle('Charm Profile: OTM Options Lose Delta Over Time', fontsize=14)
    plt.tight_layout()
    plt.savefig('charm_profile.png', dpi=150)
    plt.show()


import numpy as np
from scipy.stats import norm
import matplotlib.pyplot as plt

def bs_gamma(S, K, r, q, sigma, tau):
    """
    BS Gamma = d^2(V)/dS^2
    """
    tau = np.maximum(tau, 1e-8)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    return np.exp(-q * tau) * norm.pdf(d1) / (S * sigma * np.sqrt(tau))

def bs_color(S, K, r, q, sigma, tau):
    """
    BS Color = d(Gamma)/d(t) = -d(Gamma)/d(tau)
    Returns in per-year units. Divide by 365 for per-day.
    """
    tau = np.maximum(tau, 1e-8)
    sqrt_tau = np.sqrt(tau)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * sqrt_tau)
    d2 = d1 - sigma * sqrt_tau

    gamma = np.exp(-q * tau) * norm.pdf(d1) / (S * sigma * sqrt_tau)
    bracket = 2 * q * tau + 1 + d1 * (2 * (r - q) * tau - d2 * sigma * sqrt_tau) / (sigma * sqrt_tau)
    return -gamma / (2 * tau) * bracket

def gamma_time_evolution(S, K, r, q, sigma, tau_range_days=None):
    """
    Show how gamma evolves over time for ATM and OTM options.
    """
    if tau_range_days is None:
        tau_range_days = np.linspace(1, 90, 200)

    taus = tau_range_days / 365

    gamma_atm = bs_gamma(S, S, r, q, sigma, taus)
    gamma_otm = bs_gamma(S, S * 1.05, r, q, sigma, taus)
    gamma_itm = bs_gamma(S, S * 0.95, r, q, sigma, taus)

    color_atm = bs_color(S, S, r, q, sigma, taus) / 365
    color_otm = bs_color(S, S * 1.05, r, q, sigma, taus) / 365

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 5))

    ax1.plot(tau_range_days, gamma_atm, 'b-', lw=2.5, label='ATM (K=S)')
    ax1.plot(tau_range_days, gamma_otm, 'r--', lw=2.0, label='OTM (+5%)')
    ax1.plot(tau_range_days, gamma_itm, 'g-.', lw=2.0, label='ITM (-5%)')
    ax1.set_xlabel('Days to Expiry', fontsize=11)
    ax1.set_ylabel('Gamma', fontsize=11)
    ax1.set_title('Gamma vs. Time: ATM Explodes Near Expiry', fontsize=12)
    ax1.legend()
    ax1.invert_xaxis()
    ax1.grid(alpha=0.4)

    ax2.plot(tau_range_days, color_atm * 1000, 'b-', lw=2.5, label='ATM Color (*1000)')
    ax2.plot(tau_range_days, color_otm * 1000, 'r--', lw=2.0, label='OTM Color (*1000)')
    ax2.axhline(0, color='black', lw=1, ls='--')
    ax2.set_xlabel('Days to Expiry', fontsize=11)
    ax2.set_ylabel('Color (per day, *1000)', fontsize=11)
    ax2.set_title('Color: Rate of Gamma Change Over Time', fontsize=12)
    ax2.legend()
    ax2.invert_xaxis()
    ax2.grid(alpha=0.4)

    plt.suptitle(f'Color Analysis: S={S}, sigma={sigma*100:.0f}%', fontsize=14)
    plt.tight_layout()
    plt.savefig('color_analysis.png', dpi=150)
    plt.show()

if __name__ == '__main__':
    gamma_time_evolution(S=450, K=450, r=0.05, q=0.013, sigma=0.20)


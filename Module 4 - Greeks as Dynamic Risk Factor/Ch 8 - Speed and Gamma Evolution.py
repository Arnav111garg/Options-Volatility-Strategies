import numpy as np
from scipy.stats import norm
import matplotlib.pyplot as plt

def bs_gamma(S, K, r, q, sigma, tau):
    """
    BS Gamma = d^2(V)/d(S)^2
    """
    tau = np.maximum(tau, 1e-8)
    sqrt_tau = np.sqrt(tau)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma ** 2) * tau) / (sigma * sqrt_tau)
    return np.exp(-q * tau) * norm.pdf(d1) / (S * sigma * sqrt_tau)

def bs_speed(S, K, r, q, sigma, tau):
    """
    BS Speed = d(Gamma)/d(S) = d^3(V)/d(S)^3
    """
    tau = np.maximum(tau, 1e-8)
    sqrt_tau = np.sqrt(tau)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma ** 2) * tau) / (sigma * sqrt_tau)
    gamma = np.exp(-q * tau) * norm.pdf(d1) / (S * sigma * sqrt_tau)
    return -gamma / S * (1 + d1 / (sigma * sqrt_tau))

def gamma_speed_illustration(S0, K, r, q, sigma, tau):
    """
    Show how a large spot move changes gamma, and
    compare Taylor approximation vs. exact gamma.
    """
    S_range = np.linspace(S0 * 0.85, S0 * 1.15, 300)
    gammas = bs_gamma(S_range, K, r, q, sigma, tau)
    speeds = bs_speed(S_range, K, r, q, sigma, tau)

    # At current spot
    G_0 = bs_gamma(S0, K, r, q, sigma, tau)
    Speed_0 = bs_speed(S0, K, r, q, sigma, tau)

    # Taylor approximation of gamma at S_range
    gamma_approx = G_0 + Speed_0 * (S_range - S0)

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 5))

    # Panel 1: Gamma and its Taylor approximation
    ax1.plot(S_range, gammas, 'b-', lw=2.5, label='Exact Gamma')
    ax1.plot(S_range, gamma_approx, 'r--', lw=2, label='Gamma + Speed * dS')
    ax1.axvline(S0, color='green', ls=':', lw=1.5, label=f'Current S={S0}')
    ax1.set_xlabel('Spot Price S', fontsize=11)
    ax1.set_ylabel('Gamma', fontsize=11)
    ax1.set_title('Gamma Profile and Speed Approximation', fontsize=12)
    ax1.legend()
    ax1.grid(alpha=0.4)

    # Panel 2: Speed profile
    ax2.plot(S_range, speeds, 'purple', lw=2.5)
    ax2.axhline(0, color='black', lw=1, ls='--')
    ax2.axvline(K, color='gray', ls=':', lw=1.5, label=f'Strike K={K}')
    ax2.set_xlabel('Spot Price S', fontsize=11)
    ax2.set_ylabel('Speed (dGamma/dS)', fontsize=11)
    ax2.set_title('Speed Profile\n(Gamma Acceleration / Deceleration)', fontsize=12)
    ax2.legend()
    ax2.grid(alpha=0.4)

    plt.suptitle(f'Speed Analysis: {tau * 365:.0f} DTE, Vol={sigma * 100:.0f}%', fontsize=14)
    plt.tight_layout()
    plt.savefig('speed_analysis.png', dpi=150)
    plt.show()

    return gammas, speeds


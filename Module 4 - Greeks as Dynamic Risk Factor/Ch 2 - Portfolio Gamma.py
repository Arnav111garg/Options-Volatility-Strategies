import numpy as np
import pandas as pd
from scipy.stats import norm
import matplotlib.pyplot as plt
from matplotlib import cm

def bs_gamma(S, K, r, q, sigma, tau):
    """Black-Scholes Gamma (identical for calls and puts)."""
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(np.maximum(tau, 1e-8)))
    return np.exp(-q * tau) * norm.pdf(d1) / (S * sigma * np.sqrt(np.maximum(tau, 1e-8)))

def gamma_pnl_simulation(S0, K, r, q, sigma_iv, tau, n_paths=1000, n_steps=45, sigma_real=None, seed=42):
    """
    Simulate delta-hedged gamma P&L over a holding period.

    Parameters:
    sigma_real: realized vol (if None, uses sigma_iv)
    """
    if sigma_real is None:
        sigma_real = sigma_iv

    np.random.seed(seed)
    dt = tau / n_steps
    sqrt_dt = np.sqrt(dt)

    total_pnl = np.zeros(n_paths)

    for path in range(n_paths):
        S = S0
        # Note: bs_price and bs_delta are assumed to be defined in your environment/previous cells
        opt_price = bs_price(S, K, r, q, sigma_iv, tau, 'call')
        delta_t = bs_delta(S, K, r, q, sigma_iv, tau, 'call')

        hedge = -delta_t  # short delta_t shares to hedge
        cash = -opt_price + delta_t * S  # initial cash

        remaining_tau = tau

        for step in range(n_steps):
            dW = np.random.randn() * sqrt_dt
            dS = S * (sigma_real * dW)  # GBM without drift for simplicity
            S_new = S + dS
            remaining_tau -= dt

            # New option price and delta
            tau_new = max(remaining_tau, 1e-6)
            opt_price_new = bs_price(S_new, K, r, q, sigma_iv, tau_new, 'call')
            delta_new = bs_delta(S_new, K, r, q, sigma_iv, tau_new, 'call')

            # Hedge rebalancing P&L
            cash += hedge * (S_new - S)  # hedge position P&L
            hedge = -delta_new  # re-hedge
            cash += (delta_t - delta_new) * S_new  # rebalancing cost
            delta_t = delta_new

            S = S_new

        # Expiry payoff
        payoff = max(S - K, 0)
        total_pnl[path] = payoff - (opt_price * np.exp(r * tau)) + cash * np.exp(r * tau)

    return total_pnl

def gamma_surface_plot(S_range, tau_range, K, r, q, sigma):
    """
    Plot gamma as a 3D surface over (S, tau).
    """
    S_grid, T_grid = np.meshgrid(S_range, tau_range)
    G_grid = bs_gamma(S_grid, K, r, q, sigma, T_grid)

    fig = plt.figure(figsize=(12, 7))
    ax = fig.add_subplot(111, projection='3d')
    surf = ax.plot_surface(S_grid, T_grid * 365, G_grid, cmap='RdYlBu_r', edgecolor='none', alpha=0.85)
    ax.set_xlabel('Spot Price S', fontsize=11)
    ax.set_ylabel('Days to Expiry', fontsize=11)
    ax.set_zlabel('Gamma', fontsize=11)
    ax.set_title('Gamma Surface: ATM Gamma Explosion Near Expiry', fontsize=13)
    fig.colorbar(surf, ax=ax, shrink=0.4, aspect=10)
    plt.tight_layout()
    plt.savefig('gamma_surface.png', dpi=150)
    plt.show()

def gamma_bucketing_report(portfolio):
    """
    Print gamma bucketed by expiry tenor and approximate delta bracket.
    """
    buckets = {
        '0-7d': [], '7-30d': [],
        '30-90d': [], '90d+': []
    }

    for pos in portfolio.positions:
        tau = pos['tau']
        days = tau * 365
        g = portfolio._greeks_single(pos)
        gamma_contrib = pos['quantity'] * pos['multiplier'] * g['gamma']
        if days <= 7:
            buckets['0-7d'].append(gamma_contrib)
        elif days <= 30:
            buckets['7-30d'].append(gamma_contrib)
        elif days <= 90:
            buckets['30-90d'].append(gamma_contrib)
        else:
            buckets['90d+'].append(gamma_contrib)

    print(f"\n{'GAMMA BUCKET REPORT':^50}")
    print('=' * 50)
    for bucket, vals in buckets.items():
        total = sum(vals)
        print(f"{'Bucket ' + bucket:20s}: {total:>12.4f}")
    print('=' * 50)
    print(f"{'Net Gamma':20s}: {sum(v for b in buckets.values() for v in b):>12.4f}")


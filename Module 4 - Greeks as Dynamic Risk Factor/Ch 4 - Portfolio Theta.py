import numpy as np
import matplotlib.pyplot as plt
from scipy.stats import norm

def bs_theta(S, K, r, q, sigma, tau, option_type='call'):
    """BS Theta in per-year units. Divide by 365 for per-day."""
    tau = np.maximum(tau, 1e-8)
    sqrt_tau = np.sqrt(tau)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * sqrt_tau)
    d2 = d1 - sigma * sqrt_tau

    first_term = -S * np.exp(-q * tau) * norm.pdf(d1) * sigma / (2 * sqrt_tau)

    if option_type == 'call':
        return first_term - r * K * np.exp(-r * tau) * norm.cdf(d2) + q * S * np.exp(-q * tau) * norm.cdf(d1)
    else:
        return first_term + r * K * np.exp(-r * tau) * norm.cdf(-d2) - q * S * np.exp(-q * tau) * norm.cdf(-d1)


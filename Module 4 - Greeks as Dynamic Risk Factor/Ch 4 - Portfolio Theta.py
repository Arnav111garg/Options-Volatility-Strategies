    """
    Plot how option price, theta, and gamma evolve as expiry approaches.
    """
    taus = np.linspace(1/365, tau_max / 365, 500)
    days = taus * 365

    prices_call = bs_price(S, K, r, q, sigma, taus, 'call')
    thetas_call = bs_theta(S, K, r, q, sigma, taus, 'call') / 365
    gammas = bs_gamma(S, K, r, q, sigma, taus)

    fig, axes = plt.subplots(1, 3, figsize=(15, 5))

    # Option price decay
    axes[0].plot(days, prices_call, 'b-', lw=2.5)
    axes[0].set_xlabel('Days to Expiry', fontsize=11)
    axes[0].set_ylabel('Call Price ($)', fontsize=11)
    axes[0].set_title('Option Price vs. Time', fontsize=12)
    axes[0].invert_xaxis()
    axes[0].grid(alpha=0.4)

    # Daily theta
    axes[1].plot(days, thetas_call * 100, 'r-', lw=2.5, label='Daily Theta')
    axes[1].set_xlabel('Days to Expiry', fontsize=11)
    axes[1].set_ylabel('Daily Theta (cents per share)', fontsize=11)
    axes[1].set_title('Theta Acceleration Near Expiry', fontsize=12)
    axes[1].invert_xaxis()
    axes[1].grid(alpha=0.4)
    axes[1].axvline(30, color='gray', ls='--', lw=1, label='30 DTE')
    axes[1].legend()

    # Gamma vs Theta trade-off
    breakeven = np.sqrt(-2 * thetas_call / gammas) if np.any(gammas > 0) else None
    if breakeven is not None:
        axes[2].plot(days, breakeven * 100 / S, 'g-', lw=2.5)
        axes[2].set_xlabel('Days to Expiry', fontsize=11)
        axes[2].set_ylabel('Breakeven Daily Move (%)', fontsize=11)
        axes[2].set_title('Daily Move Needed to Break Even \n(Gamma vs. Theta)', fontsize=12)
        axes[2].invert_xaxis()
        axes[2].grid(alpha=0.4)
        axes[2].axhline(sigma / np.sqrt(365) * 100, color='red', ls='--', lw=1.5, label=f'Expected Move @ {sigma * 100:.0f}% IV')
        axes[2].legend()

    plt.suptitle(f'Theta Analysis : S={S}, K={K}, IV={sigma * 100:.0f}%', fontsize=14, y=1.02)
    plt.tight_layout()
    plt.savefig('theta_decay.png', dpi=150)
    plt.show()


import numpy as np
import pandas as pd
from scipy.stats import norm
import matplotlib.pyplot as plt
import matplotlib.ticker as mticker

# ============================================================
# Black - Scholes Core Functions
# ============================================================
def bs_d1(S, K, r, q, sigma, tau):
    """Compute d1 statistic."""
    with np.errstate(divide='ignore', invalid='ignore'):
        return np.where(tau > 1e-10,
                        (np.log(S / K) + (r - q + 0.5 * sigma ** 2) * tau) / (sigma * np.sqrt(tau)),
                        np.where(S >= K, np.inf, -np.inf))

def bs_d2(S, K, r, q, sigma, tau):
    """Compute d2 statistic."""
    return bs_d1(S, K, r, q, sigma, tau) - sigma * np.sqrt(np.maximum(tau, 0))

def bs_delta(S, K, r, q, sigma, tau, option_type='call'):
    """
    Black-Scholes delta for European options.
    """
    d1 = bs_d1(S, K, r, q, sigma, tau)
    disc = np.exp(-q * tau)
    if option_type.lower() == 'call':
        return disc * norm.cdf(d1)
    elif option_type.lower() == 'put':
        return -disc * norm.cdf(-d1)
    else:
        raise ValueError("option_type must be 'call' or 'put'")

def bs_price(S, K, r, q, sigma, tau, option_type='call'):
    """Black-Scholes option price."""
    d1 = bs_d1(S, K, r, q, sigma, tau)
    d2 = d1 - sigma * np.sqrt(np.maximum(tau, 1e-10))
    disc_r = np.exp(-r * tau)
    disc_q = np.exp(-q * tau)
    if option_type.lower() == 'call':
        return S * disc_q * norm.cdf(d1) - K * disc_r * norm.cdf(d2)
    else:
        return K * disc_r * norm.cdf(-d2) - S * disc_q * norm.cdf(-d1)


# ============================================================
# Portfolio Class
# ============================================================
class OptionsPortfolio:
    """
    Multi-option portfolio with Greek aggregation.
    """

    def __init__(self, S, r=0.05, q=0.00):
        self.S = S
        self.r = r
        self.q = q
        self.positions = []

    def add_position(self, quantity, option_type, strike, tau, sigma, multiplier=100):
        self.positions.append({
            'quantity': quantity,
            'option_type': option_type,
            'strike': strike,
            'tau': tau,
            'sigma': sigma,
            'multiplier': multiplier
        })

    def _greeks_single(self, pos, S=None):
        """Return dict of greeks for a single position at spot S."""
        if S is None:
            S = self.S
        K, tau, sigma = pos['strike'], pos['tau'], pos['sigma']
        otype = pos['option_type']

        d1 = bs_d1(S, K, self.r, self.q, sigma, tau)
        d2 = d1 - sigma * np.sqrt(max(tau, 1e-10))

        disc_q = np.exp(-self.q * tau)
        disc_r = np.exp(-self.r * tau)
        sqrt_tau = np.sqrt(max(tau, 1e-10))

        # Delta
        if otype == 'call':
            delta = disc_q * norm.cdf(d1)
        else:
            delta = -disc_q * norm.cdf(-d1)

        # Gamma
        gamma = disc_q * norm.pdf(d1) / (S * sigma * sqrt_tau)

        # Vega
        vega = S * disc_q * norm.pdf(d1) * sqrt_tau / 100.0

        # Theta
        if otype == 'call':
            theta = (-S * disc_q * norm.pdf(d1) * sigma / (2 * sqrt_tau) -
                     self.r * K * disc_r * norm.cdf(d2) +
                     self.q * S * disc_q * norm.cdf(d1)) / 365.0
        else:
            theta = (-S * disc_q * norm.pdf(d1) * sigma / (2 * sqrt_tau) +
                     self.r * K * disc_r * norm.cdf(-d2) -
                     self.q * S * disc_q * norm.cdf(-d1)) / 365.0

        price = bs_price(S, K, self.r, self.q, sigma, tau, otype)

        return {'price': price, 'delta': delta, 'gamma': gamma, 'vega': vega, 'theta': theta}

    def portfolio_greeks(self, S=None):
        """Aggregate Greeks across all positions."""
        if S is None:
            S = self.S

        total = {'value': 0.0, 'dollar_delta': 0.0, 'delta': 0.0, 'gamma': 0.0, 'vega': 0.0, 'theta': 0.0}

        for pos in self.positions:
            g = self._greeks_single(pos, S)
            m = pos['multiplier']
            q_signed = pos['quantity']

            total['value'] += q_signed * m * g['price']
            total['delta'] += q_signed * m * g['delta']
            total['dollar_delta'] += q_signed * m * g['delta'] * S
            total['gamma'] += q_signed * m * g['gamma']
            total['vega'] += q_signed * m * g['vega']
            total['theta'] += q_signed * m * g['theta']

        return total

    def delta_profile(self, S_range=None):
        """Portfolio delta as a function of spot price."""
        if S_range is None:
            S_range = np.linspace(0.7 * self.S, 1.3 * self.S, 300)
        deltas = [self.portfolio_greeks(s)['delta'] for s in S_range]
        return S_range, np.array(deltas)

    def summary(self):
        """Print a structured Greek summary."""
        g = self.portfolio_greeks()
        print('=' * 55)
        print(f"{'PORTFOLIO GREEK SUMMARY':^55}")
        print('=' * 55)
        print(f"{'Portfolio Value':30s}: ${g['value']:>12,.2f}")
        print(f"{'Portfolio Delta (raw)':30s}: {g['delta']:>12,.4f}")
        print(f"{'Dollar Delta':30s}: ${g['dollar_delta']:>12,.2f}")
        print(f"{'Portfolio Gamma':30s}: {g['gamma']:>12,.6f}")
        print(f"{'Portfolio Vega (per 1% vol)':30s}: ${g['vega']:>12,.2f}")
        print(f"{'Portfolio Theta (per day)':30s}: ${g['theta']:>12,.2f}")
        print('=' * 55)

    def pnl_attribution(self, dS=1.0, dsigma=0.01, dt=1/365):
        """
        First-order P&L attribution via Taylor expansion.
        """
        g = self.portfolio_greeks()
        pnl_delta = g['delta'] * dS
        pnl_gamma = 0.5 * g['gamma'] * dS ** 2
        pnl_theta = g['theta'] * dt * 365
        pnl_vega = g['vega'] * dsigma * 100
        total_pnl = pnl_delta + pnl_gamma + pnl_theta + pnl_vega

        print(f"\n{'P&L ATTRIBUTION':^55}")
        print(f"Inputs: dS = {dS:.2f}, dsigma = {dsigma * 100:.2f}%, dt = {dt * 365:.2f}d")
        print('-' * 55)
        print(f"{'Delta P&L':30s}: ${pnl_delta:>12,.2f}")
        print(f"{'Gamma P&L':30s}: ${pnl_gamma:>12,.2f}")
        print(f"{'Theta P&L':30s}: ${pnl_theta:>12,.2f}")
        print(f"{'Vega P&L':30s}: ${pnl_vega:>12,.2f}")
        print('-' * 55)
        print(f"{'Total Approx P&L':30s}: ${total_pnl:>12,.2f}")
        return {'delta': pnl_delta, 'gamma': pnl_gamma, 'theta': pnl_theta, 'vega': pnl_vega, 'total': total_pnl}



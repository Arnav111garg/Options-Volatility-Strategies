if __name__ == '__main__':
    S0 = 450.0
    port = OptionsPortfolio(S=S0, r=0.05, q=0.013)

    # Long OTM call strike 470, 45 DTE, vol = 20%
    port.add_position(quantity=10, option_type='call', strike=470, tau=45/365, sigma=0.20, multiplier=100)

    # Long OTM put strike 430, 45 DTE, vol = 22%
    port.add_position(quantity=10, option_type='put', strike=430, tau=45/365, sigma=0.22, multiplier=100)

    # Short ATM straddle
    port.add_position(quantity=-5, option_type='call', strike=450, tau=45/365, sigma=0.19, multiplier=100)
    port.add_position(quantity=-5, option_type='put', strike=450, tau=45/365, sigma=0.19, multiplier=100)

    port.summary()
    port.pnl_attribution(dS=5.0, dsigma=0.01)

    # Plot delta profile
    S_range, deltas = port.delta_profile()

    fig, ax = plt.subplots(figsize=(10, 5))
    ax.plot(S_range, deltas, color='navy', lw=2.5, label='Portfolio Delta')
    ax.axhline(0, color='red', ls='--', lw=1.2, label='Delta = 0')
    ax.axvline(S0, color='green', ls=':', lw=1.5, label=f'Current Spot = {S0}')
    ax.fill_between(S_range, deltas, 0, where=(deltas > 0), alpha=0.2, color='green', label='Long Delta')
    ax.fill_between(S_range, deltas, 0, where=(deltas < 0), alpha=0.2, color='red', label='Short Delta')
    ax.set_xlabel('Spot Price (S)', fontsize=12)
    ax.set_ylabel('Portfolio Delta', fontsize=12)
    ax.set_title('Portfolio Delta Profile : Condor-Like Structure', fontsize=14)
    ax.legend()
    ax.grid(alpha=0.4)
    plt.tight_layout()
    plt.savefig('portfolio_delta_profile.png', dpi=150)
    plt.show()


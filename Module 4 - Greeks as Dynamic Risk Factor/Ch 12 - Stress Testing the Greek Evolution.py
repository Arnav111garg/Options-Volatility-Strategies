import numpy as np
import matplotlib.pyplot as plt
import pandas as pd
from scipy.stats import norm

# =========================================================
# Black-Scholes Greek Helper Functions
# =========================================================
def bs_delta(S, K, r, q, sigma, tau, option_type='call'):
    tau = np.maximum(tau, 1e-8)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    if option_type.lower() == 'call':
        return np.exp(-q * tau) * norm.cdf(d1)
    else:
        return np.exp(-q * tau) * (norm.cdf(d1) - 1.0)

def bs_gamma(S, K, r, q, sigma, tau):
    tau = np.maximum(tau, 1e-8)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    return np.exp(-q * tau) * norm.pdf(d1) / (S * sigma * np.sqrt(tau))

def bs_vega(S, K, r, q, sigma, tau):
    tau = np.maximum(tau, 1e-8)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    return S * np.exp(-q * tau) * norm.pdf(d1) * np.sqrt(tau)

def bs_theta(S, K, r, q, sigma, tau, option_type='call'):
    tau = np.maximum(tau, 1e-8)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    d2 = d1 - sigma * np.sqrt(tau)
    term1 = - (S * np.exp(-q * tau) * norm.pdf(d1) * sigma) / (2 * np.sqrt(tau))
    if option_type.lower() == 'call':
        term2 = q * S * np.exp(-q * tau) * norm.cdf(d1) - r * K * np.exp(-r * tau) * norm.cdf(d2)
    else:
        term2 = - q * S * np.exp(-q * tau) * norm.cdf(-d1) + r * K * np.exp(-r * tau) * norm.cdf(-d2)
    return term1 + term2

def bs_vanna(S, K, r, q, sigma, tau):
    tau = np.maximum(tau, 1e-8)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    d2 = d1 - sigma * np.sqrt(tau)
    return -np.exp(-q * tau) * norm.pdf(d1) * d2 / sigma

def bs_charm(S, K, r, q, sigma, tau, option_type='call'):
    tau = np.maximum(tau, 1e-8)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    d2 = d1 - sigma * np.sqrt(tau)
    term2 = np.exp(-q * tau) * norm.pdf(d1) * (2 * (r - q) * tau - d2 * sigma * np.sqrt(tau)) / (2 * tau * sigma * np.sqrt(tau))
    if option_type.lower() == 'call':
        return q * np.exp(-q * tau) * norm.cdf(d1) - term2
    else:
        return -q * np.exp(-q * tau) * norm.cdf(-d1) - term2

# =========================================================
# Stress Scenario Greeks
# =========================================================
def stress_scenario_greeks(S0, K, r, q, sigma_0, tau_0, scenario='crash'):
    """
    Compute Greek evolution under stylized stress scenarios.
    """
    dt = 1 / 365

    if scenario == 'crash':
        n_steps = 5
        S_path = np.linspace(S0, S0 * 0.80, n_steps + 1)
        v_path = np.linspace(sigma_0, sigma_0 * 2.0, n_steps + 1)
    elif scenario == 'squeeze':
        n_steps = 10
        S_path = np.linspace(S0, S0 * 1.15, n_steps + 1)
        v_path = np.linspace(sigma_0, sigma_0 * 0.70, n_steps + 1)
    elif scenario == 'drift':
        n_steps = 20
        S_path = np.linspace(S0, S0 * 1.05, n_steps + 1)
        v_path = np.full(n_steps + 1, sigma_0)
    else:
        raise ValueError("Unknown scenario")

    tau_path = np.array([tau_0 - i * dt for i in range(n_steps + 1)])
    tau_path = np.maximum(tau_path, 1e-4)

    results = []
    for i in range(n_steps + 1):
        S, sig, tau = S_path[i], v_path[i], tau_path[i]
        results.append({
            'day': i,
            'S': S,
            'sigma': sig * 100,
            'Delta': bs_delta(S, K, r, q, sig, tau, 'call'),
            'Gamma': bs_gamma(S, K, r, q, sig, tau),
            'Vega': bs_vega(S, K, r, q, sig, tau) / 100,
            'Theta': bs_theta(S, K, r, q, sig, tau, 'call') / 365,
            'Vanna': bs_vanna(S, K, r, q, sig, tau),
            'Charm': bs_charm(S, K, r, q, sig, tau, 'call') / 365,
        })

    df = pd.DataFrame(results)

    # Visualize
    fig, axes = plt.subplots(2, 3, figsize=(16, 9))
    colors_g = {
        'Delta': 'royalblue', 'Gamma': 'crimson',
        'Vega': 'forestgreen', 'Theta': 'purple',
        'Vanna': 'darkorange', 'Charm': 'teal'
    }

    greek_list = ['Delta', 'Gamma', 'Vega', 'Theta', 'Vanna', 'Charm']

    for ax, greek in zip(axes.flatten(), greek_list):
        ax.plot(df['day'], df[greek], '-o', color=colors_g[greek], lw=2.5, markersize=6)
        ax.set_title(f'{greek} Evolution: {scenario.upper()} Scenario', fontsize=11, fontweight='bold')
        ax.set_xlabel('Days into Scenario', fontsize=10)
        ax.set_ylabel(greek, fontsize=10)
        ax.grid(alpha=0.4)

        # Annotate start and end
        ax.annotate(f"{df[greek].iloc[0]:.4f}", (0, df[greek].iloc[0]), textcoords='offset points', xytext=(5, 5), fontsize=9)
        ax.annotate(f"{df[greek].iloc[-1]:.4f}", (n_steps, df[greek].iloc[-1]), textcoords='offset points', xytext=(5, -12), fontsize=9)

    # Title with scenario info
    if scenario == 'crash':
        info = f'S: {S0} -> {S0 * 0.80:.0f} | sigma: {sigma_0 * 100:.0f}% -> {sigma_0 * 200:.0f}%'
    elif scenario == 'squeeze':
        info = f'S: {S0} -> {S0 * 1.15:.0f} | sigma: {sigma_0 * 100:.0f}% -> {sigma_0 * 70:.0f}%'
    else:
        info = f'S: {S0} -> {S0 * 1.05:.0f} | sigma: {sigma_0 * 100:.0f}% (constant)'

    fig.suptitle(f'Greek Evolution Under {scenario.upper()} Scenario\n{info}', fontsize=14, fontweight='bold')
    plt.tight_layout(rect=[0, 0, 1, 0.95])
    plt.savefig(f'stress_greeks_{scenario}.png', dpi=150)
    plt.show()

    print(f"\nGreek Evolution Table: {scenario.upper()}")
    print(df.to_string(float_format='{:.5f}'.format, index=False))
    return df


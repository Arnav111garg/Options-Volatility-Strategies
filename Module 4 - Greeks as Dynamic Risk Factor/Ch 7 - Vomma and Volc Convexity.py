import numpy as np
from scipy.stats import norm
import matplotlib.pyplot as plt
import pandas as pd

def bs_vega(S, K, r, q, sigma, tau):
    """
    Black-Scholes Vega = d(Price)/d(sigma)
    """
    tau = np.maximum(tau, 1e-8)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    return S * np.exp(-q * tau) * norm.pdf(d1) * np.sqrt(tau)

def bs_vomma(S, K, r, q, sigma, tau):
    """
    BS Vomma = d^2(V)/d(sigma)^2 = d(Vega)/d(sigma)
    Also called Volga or Vol Gamma.
    """
    tau = np.maximum(tau, 1e-8)
    sqrt_tau = np.sqrt(tau)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * sqrt_tau)
    d2 = d1 - sigma * sqrt_tau
    vega = S * np.exp(-q * tau) * norm.pdf(d1) * sqrt_tau
    return vega * d1 * d2 / sigma

def vol_pnl_convexity(S, K, r, q, sigma_base, tau, vol_shifts):
    """
    Compute option P&L for vol shifts, showing vega vs. vomma contributions.
    """
    # Note: bs_price is assumed to be defined in previous global cells
    V_base = bs_price(S, K, r, q, sigma_base, tau, 'call')
    vega_base = bs_vega(S, K, r, q, sigma_base, tau)
    vomma_base = bs_vomma(S, K, r, q, sigma_base, tau)

    results = []
    for dv in vol_shifts:
        V_actual = bs_price(S, K, r, q, sigma_base + dv, tau, 'call')
        pnl_actual = V_actual - V_base

        pnl_vega_only = vega_base * dv
        pnl_with_vomma = vega_base * dv + 0.5 * vomma_base * dv**2

        results.append({
            'vol_shift_%': dv * 100,
            'actual_pnl': pnl_actual,
            'vega_approx': pnl_vega_only,
            'vega + vomma_approx': pnl_with_vomma,
            'error_vega': abs(pnl_actual - pnl_vega_only),
            'error_vomma': abs(pnl_actual - pnl_with_vomma)
        })

    df = pd.DataFrame(results)
    print(f"\n{'VOL P&L CONVEXITY ANALYSIS':^80}")
    print(df.to_string(float_format='${:>8.4f}'.format, index=False))

    # Visualize
    fig, ax = plt.subplots(figsize=(10, 5))
    dvs = [r['vol_shift_%'] for r in results]
    ax.plot(dvs, [r['actual_pnl'] for r in results], 'b-o', lw=2.5, label='Actual P&L')
    ax.plot(dvs, [r['vega_approx'] for r in results], 'r--', lw=2, label='Vega (Linear) Approx')
    ax.plot(dvs, [r['vega + vomma_approx'] for r in results], 'g-.', lw=2, label='Vega + Vomma Approx')
    ax.set_xlabel('Vol Shift (%)', fontsize=12)
    ax.set_ylabel('P&L ($)', fontsize=12)
    ax.set_title('Vomma (Vol Convexity): Linear vs. Quadratic Approximation', fontsize=13)
    ax.legend()
    ax.axhline(0, color='black', lw=1)
    ax.grid(alpha=0.4)
    plt.tight_layout()
    plt.savefig('vomma_pnl.png', dpi=150)
    plt.show()
    return df


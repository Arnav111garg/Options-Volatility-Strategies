import numpy as np
from scipy.stats import norm

class OptionsPortfolio:
    def __init__(self, S, r, q):
        self.S = S
        self.r = r
        self.q = q
        self.positions = []

    def add_position(self, quantity, option_type, strike, tau, sigma, multiplier=100):
        self.positions.append({
            'quantity': quantity,
            'option_type': option_type,
            'strike': strike,
            'tau': tau,
            'sigma': sigma,
            'multiplier': multiplier
        })

    def _bs_value_and_greeks(self, pos):
        S, K, r, q, sigma, tau = self.S, pos['strike'], self.r, self.q, pos['sigma'], pos['tau']
        if tau <= 0:
            # Expired payoff
            if pos['option_type'] == 'call':
                val = max(S - K, 0)
            else:
                val = max(K - S, 0)
            return {'value': val, 'vega': 0.0}

        d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
        d2 = d1 - sigma * np.sqrt(tau)

        if pos['option_type'] == 'call':
            val = S * np.exp(-q * tau) * norm.cdf(d1) - K * np.exp(-r * tau) * norm.cdf(d2)
        else:
            val = K * np.exp(-r * tau) * norm.cdf(-d2) - S * np.exp(-q * tau) * norm.cdf(-d1)

        # Vega per 1 percentage point shift in volatility
        vega = S * np.exp(-q * tau) * norm.pdf(d1) * np.sqrt(tau) / 100
        return {'value': val, 'vega': vega}

    def _greeks_single(self, pos):
        return self._bs_value_and_greeks(pos)

    def portfolio_greeks(self):
        total_val = 0.0
        total_vega = 0.0
        for pos in self.positions:
            metrics = self._bs_value_and_greeks(pos)
            units = pos['quantity'] * pos['multiplier']
            total_val += metrics['value'] * units
            total_vega += metrics['vega'] * units
        return {'value': total_val, 'vega': total_vega}

    def summary(self):
        print(f"\n{'PORTFOLIO SUMMARY':^55}")
        print(f"{'Type':10s}{'Strike':>10s}{'Expiry(d)':>12s}{'Sigma':>10s}{'Qty':>10s}")
        print('='*55)
        for pos in self.positions:
            days = round(pos['tau'] * 365)
            print(f"{pos['option_type']:10s}{pos['strike']:10.1f}{days:12d}{pos['sigma']:10.2f}{pos['quantity']:10d}")
        print('='*55)
        metrics = self.portfolio_greeks()
        print(f"Total Value: ${metrics['value']:,.2f}")
        print(f"Total Vega:  ${metrics['vega']:,.2f} per 1% vol shift")
import numpy as np
import pandas as pd
from scipy.stats import norm
import matplotlib.pyplot as plt

def bs_vega(S, K, r, q, sigma, tau):
    """
    Black-Scholes Vega.
    Returns: vega per unit change in sigma (not per 1 vol point).
    To get 'per 1 vol point' divide by 100.
    """
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma ** 2) * tau) / (sigma * np.sqrt(np.maximum(tau, 1e-8)))
    return S * np.exp(-q * tau) * norm.pdf(d1) * np.sqrt(np.maximum(tau, 1e-8))

def vega_term_structure_report(portfolio, tenors_days=None):
    """
    Report vega bucketed by expiry.
    """
    if tenors_days is None:
        tenors_days = [7, 14, 30, 60, 90, 180, 365]

    bucket_vega = {f'{t}d': 0.0 for t in tenors_days}
    bucket_vega['other'] = 0.0

    for pos in portfolio.positions:
        tau = pos['tau']
        days = round(tau * 365)
        v = portfolio._greeks_single(pos)['vega']
        vega_contrib = pos['quantity'] * pos['multiplier'] * v # per 1 vol point

        matched = False
        for t in tenors_days:
            if abs(days - t) <= 2:
                bucket_vega[f'{t}d'] += vega_contrib
                matched = True
                break
        if not matched:
            bucket_vega['other'] += vega_contrib

    print(f"\n{'VEGA TERM-STRUCTURE REPORT':^55}")
    print(f"{'Tenor':15s}{'Vega ($, per 1 vol pt)':30s}")
    print('=' * 55)
    for tenor, v in bucket_vega.items():
        if abs(v) > 0.01:
            print(f"{tenor:15s} ${v:>25,.2f}")
    total = sum(bucket_vega.values())
    print('=' * 55)
    print(f"{'Net Vega':15s} ${total:>25,.2f}")
    return bucket_vega

def vega_surface_plot(S_range, tau_range, K, r, q, sigma):
    """3D vega surface over spot and time."""
    S_grid, T_grid = np.meshgrid(S_range, tau_range)
    V_grid = bs_vega(S_grid, K, r, q, sigma, T_grid) / 100 # per 1 vol point

    fig = plt.figure(figsize=(12, 7))
    ax = fig.add_subplot(111, projection='3d')
    surf = ax.plot_surface(S_grid, T_grid * 365, V_grid, cmap='viridis', edgecolor='none', alpha=0.85)
    ax.set_xlabel('Spot S', fontsize=11)
    ax.set_ylabel('Days to Expiry', fontsize=11)
    ax.set_zlabel('Vega (per 1 vol pt)', fontsize=11)
    ax.set_title('Vega Surface: Vega Peaks at ATM, Grows with Tenor', fontsize=13)
    fig.colorbar(surf, ax=ax, shrink=0.4, aspect=10)
    plt.tight_layout()
    plt.savefig('vega_surface.png', dpi=150)
    plt.show()

def vol_surface_scenario(portfolio, vol_shifts):
    """
    Compute portfolio P&L under various parallel vol surface scenarios.
    vol_shifts: list of vol changes in pp (e.g. [-0.05, -0.02, 0, +0.02, +0.05])
    """
    base_value = portfolio.portfolio_greeks()['value']
    pnl_by_shift = {}

    # Save original vols
    orig_sigmas = [pos['sigma'] for pos in portfolio.positions]

    for dv in vol_shifts:
        # Apply vol shift
        for pos, orig_sig in zip(portfolio.positions, orig_sigmas):
            pos['sigma'] = max(orig_sig + dv, 0.001)
        new_value = portfolio.portfolio_greeks()['value']
        pnl_by_shift[dv] = new_value - base_value

    # Restore original vols
    for pos, orig_sig in zip(portfolio.positions, orig_sigmas):
        pos['sigma'] = orig_sig

    print(f"\n{'VOL SCENARIO P&L':^55}")
    print(f"{'Vol Shift':20s}{'P&L':20s}")
    print('=' * 45)
    for dv, pnl in sorted(pnl_by_shift.items()):
        print(f"{dv * 100:+.1f}% vol shift ${pnl:>15,.2f}")

    return pnl_by_shift


import numpy as np
import matplotlib.pyplot as plt
from scipy.stats import norm
import pandas as pd

# Helper functions for Black-Scholes Greeks
def bs_delta(S, K, r, q, sigma, tau, option_type='call'):
    tau = np.maximum(tau, 1e-8)
    sqrt_tau = np.sqrt(tau)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * sqrt_tau)
    if option_type == 'call':
        return np.exp(-q * tau) * norm.cdf(d1)
    else:
        return -np.exp(-q * tau) * norm.cdf(-d1)

def bs_gamma(S, K, r, q, sigma, tau):
    tau = np.maximum(tau, 1e-8)
    sqrt_tau = np.sqrt(tau)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * sqrt_tau)
    return np.exp(-q * tau) * norm.pdf(d1) / (S * sigma * sqrt_tau)

def bs_vega(S, K, r, q, sigma, tau):
    tau = np.maximum(tau, 1e-8)
    sqrt_tau = np.sqrt(tau)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * sqrt_tau)
    return S * np.exp(-q * tau) * norm.pdf(d1) * sqrt_tau

def bs_theta(S, K, r, q, sigma, tau, option_type='call'):
    tau = np.maximum(tau, 1e-8)
    sqrt_tau = np.sqrt(tau)
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * tau) / (sigma * sqrt_tau)
    d2 = d1 - sigma * sqrt_tau
    term1 = -(S * sigma * np.exp(-q * tau) * norm.pdf(d1)) / (2 * sqrt_tau)
    if option_type == 'call':
        term2 = q * S * np.exp(-q * tau) * norm.cdf(d1) - r * K * np.exp(-r * tau) * norm.cdf(d2)
    else:
        term2 = -q * S * np.exp(-q * tau) * norm.cdf(-d1) + r * K * np.exp(-r * tau) * norm.cdf(-d2)
    return term1 + term2

def simulate_greek_paths(S0, K, r, q, sigma_0, tau_0, n_paths=5, n_steps=100, sigma_vol=0.0, seed=42):
    """
    Simulate paths of S, sigma, and all major Greeks under GBM
    with optional stochastic volatility (log-normal vol dynamics).
    """
    np.random.seed(seed)
    dt = tau_0 / n_steps
    sqrt_dt = np.sqrt(dt)

    # Time axis (decreasing tau)
    time_axis = np.linspace(0, tau_0, n_steps + 1)
    tau_axis = tau_0 - time_axis  # remaining tau

    # Storage
    S_paths = np.zeros((n_paths, n_steps + 1))
    sig_paths = np.zeros((n_paths, n_steps + 1))
    delta_paths = np.zeros((n_paths, n_steps + 1))
    gamma_paths = np.zeros((n_paths, n_steps + 1))
    vega_paths = np.zeros((n_paths, n_steps + 1))
    theta_paths = np.zeros((n_paths, n_steps + 1))

    for p in range(n_paths):
        S = S0
        sig = sigma_0

        for i in range(n_steps + 1):
            tau = max(tau_axis[i], 1e-4)

            # Compute Greeks at current state
            S_paths[p, i] = S
            sig_paths[p, i] = sig
            delta_paths[p, i] = bs_delta(S, K, r, q, sig, tau, 'call')
            gamma_paths[p, i] = bs_gamma(S, K, r, q, sig, tau)
            vega_paths[p, i] = bs_vega(S, K, r, q, sig, tau) / 100
            theta_paths[p, i] = bs_theta(S, K, r, q, sig, tau, 'call') / 365

            if i < n_steps:
                # Evolve S (GBM)
                dW_S = np.random.randn() * sqrt_dt
                S = S * np.exp((r - q - 0.5 * sig**2) * dt + sig * dW_S)

                # Evolve vol (log-normal vol-of-vol, optional)
                if sigma_vol > 0:
                    dW_V = np.random.randn() * sqrt_dt
                    sig = sig * np.exp(-0.5 * sigma_vol**2 * dt + sigma_vol * dW_V)
                    sig = np.clip(sig, 0.02, 1.5)

    return {
        'time': time_axis,
        'tau': tau_axis,
        'S': S_paths,
        'sigma': sig_paths,
        'delta': delta_paths,
        'gamma': gamma_paths,
        'vega': vega_paths,
        'theta': theta_paths
    }

def plot_greek_evolution(paths_dict, title_suffix=''):
    """
    Comprehensive 6-panel plot of Greek evolution paths.
    """
    time = paths_dict['time'] * 365  # in days
    n_paths = paths_dict['S'].shape[0]

    fig, axes = plt.subplots(2, 3, figsize=(18, 10))
    keys_titles = [
        ('S', 'Spot Price', 'Price ($)', 'navy'),
        ('sigma', 'Implied Vol', '(decimal)', 'darkorange'),
        ('delta', 'Delta', '', 'royalblue'),
        ('gamma', 'Gamma', '', 'crimson'),
        ('vega', 'Vega (per 1%)', 'V ($ / 1%)', 'forestgreen'),
        ('theta', 'Theta (daily)', '($/day)', 'purple'),
    ]

    for ax, (key, title, ylabel, color) in zip(axes.flatten(), keys_titles):
        data = paths_dict[key]

        # Plot individual paths with transparency
        for p in range(n_paths):
            ax.plot(time, data[p, :], color=color, alpha=0.35, lw=1.2)

        # Mean path (bold)
        ax.plot(time, data.mean(axis=0), color=color, lw=2.5, label='Mean Path')

        # 5th / 95th percentile
        ax.fill_between(
            time,
            np.percentile(data, 5, axis=0),
            np.percentile(data, 95, axis=0),
            alpha=0.15,
            color=color,
            label='5-95% Range'
        )

        ax.set_title(title, fontsize=12, fontweight='bold')
        ax.set_xlabel('Calendar Days Elapsed', fontsize=10)
        ax.set_ylabel(ylabel, fontsize=10)
        ax.legend(fontsize=9)
        ax.grid(alpha=0.4)

    plt.suptitle(f'Dynamic Greek Evolution {title_suffix}', fontsize=16, fontweight='bold')
    plt.tight_layout(rect=[0, 0, 1, 0.97])
    plt.savefig('greek_evolution_paths.png', dpi=150, bbox_inches='tight')
    plt.show()

def greek_correlation_matrix(paths_dict):
    """
    Compute and visualize the correlation matrix of daily Greek changes.
    """
    # Daily changes
    delta_changes = np.diff(paths_dict['delta'], axis=1).flatten()
    gamma_changes = np.diff(paths_dict['gamma'], axis=1).flatten()
    vega_changes = np.diff(paths_dict['vega'], axis=1).flatten()
    theta_changes = np.diff(paths_dict['theta'], axis=1).flatten()
    S_changes_pct = np.diff(np.log(paths_dict['S']), axis=1).flatten() * 100
    sig_changes = np.diff(paths_dict['sigma'], axis=1).flatten() * 100

    data_matrix = np.column_stack([
        S_changes_pct, sig_changes,
        delta_changes, gamma_changes, vega_changes, theta_changes
    ])

    labels = ['S (%)', 'Vol (%)', 'Delta', 'Gamma', 'Vega', 'Theta']
    corr = np.corrcoef(data_matrix.T)
    fig, ax = plt.subplots(figsize=(8, 7))
    im = ax.imshow(corr, cmap='RdBu', vmin=-1, vmax=1, aspect='auto')

    ax.set_xticks(range(len(labels)))
    ax.set_yticks(range(len(labels)))
    ax.set_xticklabels(labels, fontsize=11)
    ax.set_yticklabels(labels, fontsize=11)

    for i in range(len(labels)):
        for j in range(len(labels)):
            ax.text(
                j, i, f'{corr[i, j]:.2f}',
                ha='center', va='center',
                fontsize=10,
                color='white' if abs(corr[i, j]) > 0.5 else 'black'
            )

    plt.colorbar(im, ax=ax, shrink=0.8)
    ax.set_title('Greek Changes Correlation Matrix\n(Reveals Cross-Greek Dependencies)', fontsize=13, fontweight='bold')
    plt.tight_layout()
    plt.savefig('greek_correlation_matrix.png', dpi=150)
    plt.show()
    return corr

